def картинка(ширина_пікс, висота_пікс, колір=(120, 160, 90)):
    """PNG заданої форми — тим самим писарем, що малює карти у звіті."""
    полотно = np.zeros((висота_пікс, ширина_пікс, 3), dtype="uint8")
    полотно[:, :] = колір
    return report_norm._png(полотно)


def поле(стовпців, рядків, крок=10.0):
    """Синтетичне поле заданої ФОРМИ. Форма тут і є предметом перевірки."""
    import geopandas as gpd
    from shapely.geometry import Point, box

    с, р = np.meshgrid(np.arange(стовпців), np.arange(рядків))
    с = с.ravel().astype("float64")
    р = р.ravel().astype("float64")
    x = 400000.0 + с * крок
    y = 5400000.0 - р * крок
    вегетація = 0.55 + 0.18 * (1.0 - р / max(рядків, 1)) + 0.05 * np.sin(с / 7.0)
    врожай = 6000.0 + 9000.0 * (вегетація - 0.55) + 40.0 * np.sin(с / 5.0)
    пляма = (с > стовпців * 0.2) & (с < стовпців * 0.5) & (р > рядків * 0.25) & (р < рядків * 0.6)
    врожай = np.where(пляма, врожай * 0.72, врожай)

    точки = gpd.GeoDataFrame({
        "YLD_KGHA": врожай,
        "YLD_SM": врожай,
        "SRC_TYPE": np.where(np.arange(len(врожай)) % 37 == 0, "INTERP", "MEAS"),
        "MOIST": np.full(len(врожай), 14.0),
        "VEG_IDX": вегетація,
        "VEG_YEARS": вегетація * 0.95,
        "BSI_IDX": 0.3 + 0.1 * (с / max(стовпців, 1)),
        "ELEV_M": 120.0 + (р / max(рядків, 1)) * 6.0,
    }, geometry=[Point(а, б) for а, б in zip(x, y)], crs="EPSG:32635")
    контур = gpd.GeoDataFrame(
        geometry=[box(x.min() - крок / 2, y.min() - крок / 2,
                      x.max() + крок / 2, y.max() + крок / 2)], crs="EPSG:32635")
    return точки, контур


