def шкала_налізла(межі):
    """Міряє ТЕ, ЩО ШКАЛА НАМАЛЮВАЛА, а не те, що вона могла б намалювати.

    Перша версія цієї перевірки рахувала всі межі підряд і показала два
    провали там, де механізм працював правильно: шкала проріджує підписи,
    і мірило дивилось на інший набір. Тому `шкала` тепер повертає намальоване.
    """
    д = report_norm._Аркуш("тест")
    д.аркуш()
    p = д.pdf
    ширина = (д.ш - 5) / 2
    кольори = ["#8c3a22"] * (len(межі) - 1)
    видимі = д.шкала(д.ПОЛЕ, ширина, кольори, межі)

    p.set_font("ф", "", 6.6)
    зазор = p.get_string_width(" ")
    крок = ширина / max(len(кольори), 1)
    підписи = [report_norm._ч(м) for м in межі]
    межі_праворуч = ширина - p.get_string_width(підписи[-1])
    for місце, і in enumerate(видимі):
        кінець = і * крок + p.get_string_width(підписи[і])
        далі = (видимі[місце + 1] * крок if місце + 1 < len(видимі)
                else межі_праворуч)
        if кінець + зазор > далі:
            return True, підписи[і], (підписи[видимі[місце + 1]]
                                      if місце + 1 < len(видимі) else підписи[-1]), видимі
    return False, None, None, видимі


