# -*- coding: utf-8 -*-
"""ВОРОТА МАЙСТЕР-ТАБЛИЦІ. Читач історії полів із таблиці господарства.

Перевіряється те, на чому цей читач уже спіткнувся під час написання —
обидві помилки коштували б мовчазної втрати даних:

* «т/га» впізнавалось як ПЛОЩА, бо містить «га». Урожай зникав з усіх
  років, а таблиця виглядала прочитаною;
* двохрядкова шапка зсувала початок даних на рядок, і перше поле в
  таблиці мовчки не потрапляло в передпоказ.

Плюс те, що має триматись завжди: порожня клітинка лишається порожньою,
рік береться з шапки навіть коли він написаний як «2024 результати»,
а закладення без збігу назви не заводить поле наосліп.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\майстер_таблиця.py"
"""

import os
import shutil
import sys
import tempfile

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if БАЗА not in sys.path:
    sys.path.insert(0, БАЗА)

from app.core import master_table                    # noqa: E402
from app.core.catalog import Картотека               # noqa: E402

збої = []


def перевірити(що, умова, пояснення=""):
    print("  {}  {}{}".format("OK  " if умова else "ЗБІЙ", що,
                              "" if умова else " — " + пояснення))
    if not умова:
        збої.append(що)


def таблиця(шлях, рядки, назва_аркуша="Master table"):
    from openpyxl import Workbook

    книга = Workbook()
    лист = книга.active
    лист.title = назва_аркуша
    for рядок in рядки:
        лист.append(рядок)
    книга.save(шлях)


print("═" * 60)
print("МАЙСТЕР-ТАБЛИЦЯ ГОСПОДАРСТВА")
print("═" * 60)

тимчасове = tempfile.mkdtemp(prefix="ff_майстер_")
try:
    # ── двохрядкова шапка: рік згори, підписи знизу
    двохрядкова = os.path.join(тимчасове, "двохрядкова.xlsx")
    таблиця(двохрядкова, [
        ["поле", "площа", "Рейтинг", 2024, None, None, 2025, None, None],
        [None, None, None, "культура", "гібрид", "т/га", "культура", "гібрид", "т/га"],
        ["Високе 01", 143.49, 4.0, "Кукурудза", "КМ 2170", 5.14, "Соняшник", "Цейлон", 1.96],
        ["Високе 06", 16.75, 1.0, "Кукурудза", "ДКС 3730", 5.85, None, None, None],
    ])
    р = master_table.розібрати(двохрядкова)
    перевірити("двохрядкова шапка прочиталась", р.get("гаразд"), str(р.get("повідомлення")))
    назви = [п["поле"] for п in р["поля"]]
    перевірити("ПЕРШЕ поле не загубилось", назви == ["Високе 01", "Високе 06"],
               "маємо {}".format(назви))

    перше = р["поля"][0]["роки"]
    перевірити("урожай не став площею", перше["2024"].get("урожай") == 5.14,
               "у 2024 маємо {}".format(перше["2024"]))
    перевірити("площа поля прочиталась окремо", р["поля"][0]["площа_га"] == 143.49)
    перевірити("рейтинг прочитався", р["поля"][0]["рейтинг"] == 4.0)
    перевірити("гібрид на місці", перше["2025"].get("гібрид") == "Цейлон")

    друге = р["поля"][1]["роки"]
    перевірити("порожній рік лишився порожнім", "2025" not in друге,
               "зʼявився зайвий рік: {}".format(друге.get("2025")))

    # ── однорядкова шапка з роками в підписах
    однорядкова = os.path.join(тимчасове, "однорядкова.xlsx")
    таблиця(однорядкова, [
        ["Поле №", "Площа, га", "2020 результати", "т/га", "2021 результати", "т/га"],
        ["Поле 1-60", 60.0, "кукурудза", 6.8, "соняшник", 2.9],
    ])
    р2 = master_table.розібрати(однорядкова)
    перевірити("рік із підпису «2020 результати» впізнано",
               "2020" in (р2["поля"][0]["роки"] if р2["поля"] else {}),
               "роки: {}".format(р2.get("роки")))
    перевірити("урожай при однорядковій шапці теж на місці",
               р2["поля"][0]["роки"]["2021"].get("урожай") == 2.9)

    # ── рік живе в РЯДКАХ, а не в шапці (АТП, Альянс, Маяк).
    # Разом із пасткою, на якій це стояло: у шапці Альянса й Маяка є
    # колонки «2020 результати … 2025 результати», і остання з них
    # ставила рік усім колонкам праворуч. Уся історія поля злипалась
    # у 2025 — а лічильник років при цьому показував успіх.
    рядковий = os.path.join(тимчасове, "рік_у_рядку.xlsx")
    таблиця(рядковий, [
        ["поле", "площа", "2020 результати", "2025 результати",
         "рік", "культура", "т/га", "рік", "культура", "т/га"],
        ["Високе 03-1", 11.63, None, None,
         2018, "Соняшник", 2.8, 2023, "Кукурудза", 8.67],
        ["Високе 02", 30.47, None, None,
         2019, "Ячмінь ярий", 3.79, 2024, "Пшениця озима", 5.5],
    ])
    р3 = master_table.розібрати(рядковий)
    роки3 = {п["поле"]: п["роки"] for п in р3["поля"]}
    перевірити("рік узято з клітинки рядка, а не з шапки",
               sorted(роки3.get("Високе 03-1", {})) == ["2018", "2023"],
               "маємо {}".format(sorted(роки3.get("Високе 03-1", {}))))
    перевірити("у різних полів у тій самій колонці різні роки",
               sorted(роки3.get("Високе 02", {})) == ["2019", "2024"],
               "маємо {}".format(sorted(роки3.get("Високе 02", {}))))
    перевірити("шапкове «2025 результати» не отруює колонки праворуч",
               "2025" not in роки3.get("Високе 03-1", {}),
               "усе злиплось у 2025 — це та сама помилка, що й була")
    перевірити("урожай не приліпився до чужого року",
               (роки3.get("Високе 03-1", {}).get("2023") or {}).get("урожай") == 8.67,
               "маємо {}".format(роки3.get("Високе 03-1", {}).get("2023")))

    # ── закладення в картотеку
    корінь = os.path.join(тимчасове, "робота")
    os.makedirs(корінь)
    к = Картотека(корінь)
    г = к.завести_господарство("Тест")
    к.завести_поле(г, "Високе 01")
    наслідок = master_table.закласти(к, г, р)
    перевірити("поле зі збігом назви заклалось", наслідок["полів"] == 1,
               "закладено {}".format(наслідок["полів"]))
    перевірити("поле без збігу НЕ заведено наосліп",
               наслідок["не_знайдено"] == 1 and "Високе 06" in наслідок["не_знайшлось"],
               "не знайшлось: {}".format(наслідок["не_знайшлось"]))

    from app.core import history
    тека = к.тека_поля(г, "Високе_01")
    зведення = {з["рік"]: з for з in history.зведення(тека)}
    перевірити("рік ліг у історію з культурою й урожаєм",
               зведення.get("2024", {}).get("культура") == "Кукурудза"
               and зведення.get("2024", {}).get("урожай_т_га") == 5.14,
               "маємо {}".format(зведення.get("2024")))
    перевірити("джерело записано на роках",
               "майстер-таблиця" in (history.рік(тека, 2024).get("загальне") or {}).get("джерело", ""),
               "джерело: {}".format((history.рік(тека, 2024).get("загальне") or {}).get("джерело")))
    перевірити("рейтинг поля перенесено в паспорт",
               к.паспорт_поля(г, "Високе_01").get("рейтинг") == 4.0)
finally:
    shutil.rmtree(тимчасове, ignore_errors=True)

print()
if збої:
    print("ЗБОЇ: {}".format(len(збої)))
    for з in збої:
        print("  · {}".format(з))
    sys.exit(1)
print("УСІ ПЕРЕВІРКИ ПРОЙДЕНІ")
