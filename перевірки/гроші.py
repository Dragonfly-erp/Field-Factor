каже(після["пальне_л_га"] > до["пальне_л_га"] * 1.3,
     "поміняли трактор — робота перерахувалась сама: {:.2f} → {:.2f} л/га"
     .format(до["пальне_л_га"], після["пальне_л_га"]))
каже(до["звідки"] == "з техніки", "робота знає, що взяла числа з техніки")

print("\n=== ЧЕРВОНЕ: техніка без потрібних чисел ===")
каже(money.виробіток(dict(назва="Жатка", ширина_м=6.0)) is None,
     "ширина є, швидкості немає — виробітку НЕМАЄ, а не нуль")
каже(money.пальне_на_гектар(dict(назва="Трактор"), борона) is None,
     "витрати пального не названо — числа немає")
