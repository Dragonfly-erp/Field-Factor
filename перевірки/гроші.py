# -*- coding: utf-8 -*-
r"""Гроші: бюджет підприємства, розкид постійних витрат, матрьошка.

Зелене перевіряє щасливий шлях, червоне перевіряє перевірку.

Головне червоне тут — **середнє з питомих чисел**. Скласти грн/га по полях
і поділити на кількість полів здається природним і дає неправильну відповідь:
поле на 5 га важить стільки ж, скільки поле на 200. Перевірка показує обидва
числа поруч, щоб цю пастку було видно.

Запуск:  runtime\python.exe -X utf8 "перевірки\гроші.py"
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import money

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


def близько(а, б, допуск=1e-6):
    return а is not None and б is not None and abs(а - б) <= допуск * max(1.0, abs(б))


# ═══════════════════════════════════════════════════════════════════════
print("\n=== ЗЕЛЕНЕ: канонічна форма сходиться сама з собою ===")

б = money.бюджет({
    "площа_га": 177.80,
    "врожайність_т_га": 12.105,
    "ціна_т": 8450.0,
    "змінні": {"насіння": 4950, "добрива": 19400, "ЗЗР": 3323, "пальне": 3105,
               "роботи": 4123, "сушіння": 2645, "перевезення": 1000},
    "постійні": [{"назва": "Оренда паїв", "грн_га": 8200},
                 {"назва": "Земельний податок", "грн_га": 360},
                 {"назва": "Зарплата", "грн_га": 4004},
                 {"назва": "Амортизація", "грн_га": 4505},
                 {"назва": "Ремонти", "грн_га": 2002},
                 {"назва": "Страхування", "грн_га": 400},
                 {"назва": "Адміністративні", "грн_га": 3003},
                 {"назва": "Відсотки", "грн_га": 1602}],
})

каже(близько(б["дохід"]["разом"], 12.105 * 8450.0),
     "дохід = врожайність × ціна: {:.0f} грн/га".format(б["дохід"]["разом"]))
каже(близько(б["маржинальний"], б["дохід"]["разом"] - б["змінні"]["разом"]),
     "маржинальний = дохід − змінні: {:.0f} грн/га".format(б["маржинальний"]))
каже(близько(б["чистий"], б["маржинальний"] - б["постійні"]["разом"]),
     "чистий = маржинальний − постійні: {:.0f} грн/га".format(б["чистий"]))
каже(близько(б["повні_витрати"], б["змінні"]["разом"] + б["постійні"]["разом"]),
     "повні витрати = змінні + постійні: {:.0f} грн/га".format(б["повні_витрати"]))

print("\n=== ЗЕЛЕНЕ: точка беззбитковості вертається сама в себе ===")
бз = б["беззбитковість"]
каже(близько(бз["ціна_т"] * 12.105, б["повні_витрати"]),
     "беззбиткова ціна × врожайність = повні витрати ({:.0f} грн/т)".format(бз["ціна_т"]))
каже(близько(бз["врожайність_т_га"] * 8450.0, б["повні_витрати"]),
     "беззбиткова врожайність × ціна = повні витрати ({:.2f} т/га)"
     .format(бз["врожайність_т_га"]))
каже(близько(б["собівартість_т"], б["повні_витрати"] / 12.105),
     "собівартість тонни: {:.0f} грн".format(б["собівартість_т"]))

print("\n=== ЧЕРВОНЕ: поле, з якого нічого не взяли ===")
порожнє = money.бюджет({"площа_га": 50, "врожайність_т_га": 0.0, "ціна_т": 8450,
                        "змінні": {"насіння": 4950}, "постійні": []})
каже(порожнє["беззбитковість"]["ціна_т"] is None,
     "врожайність нуль — беззбиткової ціни НЕМАЄ, а не нескінченність")
каже(порожнє["чистий"] < 0, "чистий результат відʼємний, як і має бути")

нульова_ціна = money.бюджет({"площа_га": 50, "врожайність_т_га": 8, "ціна_т": 0.0,
                             "змінні": {}, "постійні": []})
каже(нульова_ціна["беззбитковість"]["врожайність_т_га"] is None,
     "ціни немає — беззбиткової врожайності немає")

# ═══════════════════════════════════════════════════════════════════════
print("\n=== ЗЕЛЕНЕ: розкид постійних за статтею ===")
витрати = [
    dict(назва="Оренда паїв", група="земля", розкид="поле", ставка_га=8200),
    dict(назва="Амортизація", група="техніка", розкид="години", сума_рік=4095000),
    dict(назва="Адміністративні", група="адмін", розкид="площа", сума_рік=2730000),
]
дороге = money.постійні_на_гектар(витрати, 909.0,
                                  поле=dict(площа_га=177.8, оренда_грн_га=12000,
                                            частка_годин=177.8 / 909.0))
дешеве = money.постійні_на_гектар(витрати, 909.0,
                                  поле=dict(площа_га=177.8, оренда_грн_га=3000,
                                            частка_годин=177.8 / 909.0))
о_дороге = [р for р in дороге if р["група"] == "земля"][0]["грн_га"]
о_дешеве = [р for р in дешеве if р["група"] == "земля"][0]["грн_га"]
каже(близько(о_дороге, 12000) and близько(о_дешеве, 3000),
     "земля бере ставку САМОГО поля: {:.0f} проти {:.0f} грн/га".format(о_дороге, о_дешеве))

адмін = [р for р in дороге if р["група"] == "адмін"][0]["грн_га"]
каже(близько(адмін, 2730000 / 909.0),
     "адміністративні лягли за площею: {:.0f} грн/га".format(адмін))

техніка = [р for р in дороге if р["група"] == "техніка"][0]["грн_га"]
каже(близько(техніка, 4095000 * (177.8 / 909.0) / 177.8),
     "техніка лягла за годинами: {:.0f} грн/га".format(техніка))

print("\n=== ЧЕРВОНЕ: годин не названо — не мовчимо, а падаємо на площу ===")
без_годин = money.постійні_на_гектар(витрати, 909.0, поле=dict(площа_га=177.8))
т = [р for р in без_годин if р["група"] == "техніка"][0]
каже("за площею" in т["чому"],
     "техніка без годин: розкид підмінено й СКАЗАНО про це — «{}»".format(т["чому"]))

# ═══════════════════════════════════════════════════════════════════════
print("\n=== ЧЕРВОНЕ: матрьошка не має рахувати середнє з питомих ===")
мале = money.бюджет({"площа_га": 5.0, "врожайність_т_га": 4.0, "ціна_т": 8450,
                     "змінні": {"насіння": 4950}, "постійні": []})
велике = money.бюджет({"площа_га": 200.0, "врожайність_т_га": 12.0, "ціна_т": 8450,
                       "змінні": {"насіння": 4950}, "постійні": []})
зведено = money.звести([мале, велике], "господарство")

наївне = (мале["чистий"] + велике["чистий"]) / 2.0
чесне = зведено["грн_га"]["чистий"]
каже(abs(наївне - чесне) > 1000,
     "середнє з питомих бреше: {:.0f} проти чесних {:.0f} грн/га — різниця {:.0f}"
     .format(наївне, чесне, наївне - чесне))
каже(близько(зведено["грн"]["чистий"],
             мале["на_поле"]["чистий"] + велике["на_поле"]["чистий"]),
     "у гривнях сума збігається до копійки")
каже(близько(зведено["площа_га"], 205.0), "площа склалась: 205,0 га")
каже(близько(чесне, зведено["грн"]["чистий"] / 205.0),
     "питоме дістається діленням суми на суму площ, а не усередненням")

# ═══════════════════════════════════════════════════════════════════════
print("\n=== ЗЕЛЕНЕ: ПДВ ===")
каже(близько(money.без_ПДВ(24000, з_ПДВ=True), 20000.0),
     "24 000 з ПДВ 20 % — це 20 000 без: {:.0f}".format(money.без_ПДВ(24000, True)))
каже(близько(money.без_ПДВ(20000, з_ПДВ=False), 20000.0),
     "ціна без ПДВ не чіпається")
каже(money.без_ПДВ(None) is None, "порожня ціна лишається порожньою, а не нулем")

# ═══════════════════════════════════════════════════════════════════════
print("\n=== ЧЕРВОНЕ: картка без дати ціни не приймається ===")
з = money.перевірити(dict(назва="Селітра", вид="добриво", одиниця="т", ціна=21400,
                          джерело_ціни="накладна"), money.ПОЛЯ_МАТЕРІАЛУ)
каже(any("Ціна від" in х for х in з),
     "ціна без дати — ворота кричать: {}".format("; ".join(з)))

добра = money.перевірити(dict(назва="Селітра", вид="добриво", одиниця="т", ціна=21400,
                              дата_ціни="2026-02-12", джерело_ціни="накладна", норма=0.2),
                         money.ПОЛЯ_МАТЕРІАЛУ)
каже(not добра, "повна картка проходить чисто")

print("\n=== ЧЕРВОНЕ: решта пасток картки ===")
для = money.ПОЛЯ_МАТЕРІАЛУ
каже(any("відʼємне" in х for х in money.перевірити(
    dict(назва="X", вид="добриво", одиниця="т", ціна=-5, дата_ціни="2026-01-01",
         джерело_ціни="оцінка"), для)), "відʼємна ціна не проходить")
каже(any("невідоме значення" in х for х in money.перевірити(
    dict(назва="X", вид="паливо", одиниця="т", ціна=5, дата_ціни="2026-01-01",
         джерело_ціни="оцінка"), для)), "невідомий вид товару не проходить")
каже(any("нижню межу" in х for х in money.перевірити(
    dict(назва="X", вид="добриво", одиниця="т", ціна=5, дата_ціни="2026-01-01",
         джерело_ціни="оцінка", норма=0.1, норма_від=0.2), для)),
     "норма нижча за власну межу не проходить")

з_обома = money.перевірити(dict(назва="Оренда", група="земля", розкид="поле",
                                сума_рік=100000, ставка_га=8200), money.ПОЛЯ_ВИТРАТИ)
каже(any("лишіть щось одне" in х for х in з_обома),
     "і річна сума, і ставка разом — ворота кричать")
ні_того_ні_того = money.перевірити(dict(назва="Оренда", група="земля", розкид="поле"),
                                   money.ПОЛЯ_ВИТРАТИ)
каже(any("ні річної суми" in х for х in ні_того_ні_того),
     "стаття без жодного числа не проходить")

