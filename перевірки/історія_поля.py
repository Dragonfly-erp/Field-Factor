# -*- coding: utf-8 -*-
"""ВОРОТА ІСТОРІЇ ПОЛЯ.

Історія поділена блоками саме для того, щоб правки не заважали одна одній.
Перевіряється те, чим цей поділ може мовчки збрехати:

* запис одного блоку затер сусідній або сусідній рік;
* рік записаний числом і рядком дав два різні сезони;
* порожнє в зведенні перетворилось на нуль — «не вносили» замість «не знаємо»;
* провенанс ліг на файл, а не на рік, і роки з різних джерел стали
  підписані однаково;
* видалення року прибрало його не з усіх блоків;
* невідомий блок записався мовчки.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\історія_поля.py"
"""

import json
import os
import shutil
import sys
import tempfile

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if БАЗА not in sys.path:
    sys.path.insert(0, БАЗА)

from app.core import history      # noqa: E402

збої = []


def перевірити(що, умова, пояснення=""):
    print("  {}  {}{}".format("OK  " if умова else "ЗБІЙ", що,
                              "" if умова else " — " + пояснення))
    if not умова:
        збої.append(що)


print("═" * 60)
print("ІСТОРІЯ ПОЛЯ")
print("═" * 60)

тека = tempfile.mkdtemp(prefix="ff_історія_")
try:
    # ── два блоки одного року
    history.записати(тека, "загальне", 2025,
                     {"культура": "Ріпак озимий", "урожай_т_га": 3.5},
                     джерело="таблиця господарства")
    history.записати(тека, "живлення", 2025, {"N": 191, "P": 62, "K": 76},
                     джерело="накладні")

    рік = history.рік(тека, 2025)
    перевірити("два блоки одного року лежать поруч",
               set(рік) == {"загальне", "живлення"}, "маємо {}".format(set(рік)))
    перевірити("провенанс у кожного блоку СВІЙ",
               рік["загальне"]["джерело"] != рік["живлення"]["джерело"],
               "джерела злиплись: {}".format(рік["загальне"]["джерело"]))

    # ── запис іншого року не чіпає попередній
    history.записати(тека, "живлення", 2024, {"N": 164}, джерело="накладні")
    перевірити("новий рік не зачепив старий",
               history.рік(тека, 2025)["живлення"]["N"] == 191,
               "стало {}".format(history.рік(тека, 2025)["живлення"].get("N")))
    перевірити("новий блок не зачепив сусідній блок",
               history.рік(тека, 2025)["загальне"]["культура"] == "Ріпак озимий")

    # ── рік числом і рядком — це один сезон, а не два.
    #
    # Чесно про силу цієї перевірки: поки сховище — JSON, її тримає не наш
    # код, а сам формат: `json.dump` перетворює числовий ключ на рядок, і
    # роки зійшлися б навіть без `_рік_ключем`. Перевірка лишається як
    # сторожа на майбутнє — на день, коли сховище перестане бути JSON.
    history.записати(тека, "економіка", "2025", {"витрати_на_га": 323})
    history.записати(тека, "економіка", 2025, {"витрати_на_га": 330})
    вміст = history.блок(тека, "економіка")
    перевірити("рік числом і рядком — один сезон",
               list(вміст["роки"].keys()) == ["2025"],
               "роки: {}".format(list(вміст["роки"].keys())))
    перевірити("другий запис перекрив перший, а не додав другий",
               вміст["роки"]["2025"]["витрати_на_га"] == 330)

    # ── порожнє лишається порожнім
    зведення = {р["рік"]: р for р in history.зведення(тека)}
    перевірити("рік без блоку дає порожнє, а не нуль",
               зведення["2024"]["культура"] is None
               and зведення["2024"]["вапнування_т_га"] is None,
               "маємо {}".format(зведення["2024"]))
    перевірити("нуль у зведенні не з'являється сам",
               not any(v == 0 for v in зведення["2024"].values()),
               "знайшовся нуль: {}".format(зведення["2024"]))

    # ── роки й підсумок
    перевірити("роки перелічені свіжим першим",
               history.роки(тека) == ["2025", "2024"],
               "роки: {}".format(history.роки(тека)))
    підсумок = history.підсумок(тека)
    перевірити("підсумок рахує лише те, що є",
               підсумок["років"] == 2 and підсумок["середній_урожай"] == 3.5,
               "підсумок: {}".format(підсумок))

    # ── невідомий блок не записується мовчки
    мовчки = False
    try:
        history.записати(тека, "вигаданий_блок", 2025, {"щось": 1})
        мовчки = True
    except ValueError:
        pass
    перевірити("невідомий блок спиняє, а не пишеться", not мовчки,
               "записався блок, якого немає в переліку")

    # ── видалення року прибирає його з УСІХ блоків
    прибрано = history.видалити_рік(тека, 2025)
    перевірити("видалення року пройшло всі блоки",
               set(прибрано) == {"загальне", "живлення", "економіка"},
               "прибрано з {}".format(прибрано))
    перевірити("після видалення року в ньому нічого не лишилось",
               history.рік(тека, 2025) == {},
               "лишилось {}".format(history.рік(тека, 2025)))
    перевірити("сусідній рік уцілів", history.рік(тека, 2024)["живлення"]["N"] == 164)

    # ── файли справді окремі: правка одного не переписує інший
    шлях_живлення = os.path.join(тека, history.ТЕКА, "живлення.json")
    шлях_загального = os.path.join(тека, history.ТЕКА, "загальне.json")
    перевірити("блок — це окремий файл",
               os.path.isfile(шлях_живлення) and os.path.isfile(шлях_загального))
    було = os.path.getmtime(шлях_загального)
    with open(шлях_загального, encoding="utf-8") as ф:
        зміст_до = json.load(ф)
    history.записати(тека, "живлення", 2023, {"N": 78})
    with open(шлях_загального, encoding="utf-8") as ф:
        зміст_після = json.load(ф)
    перевірити("запис у живлення не переписав файл загального",
               зміст_до == зміст_після, "файл загального змінився")
    del було
finally:
    shutil.rmtree(тека, ignore_errors=True)

print()
if збої:
    print("ЗБОЇ: {}".format(len(збої)))
    for з in збої:
        print("  · {}".format(з))
    sys.exit(1)
print("УСІ ПЕРЕВІРКИ ПРОЙДЕНІ")
