# -*- coding: utf-8 -*-
"""Вирівнювання проходів: чи знаходить воно підкладений зсув і чи не псує поле.

Це найнебезпечніший модуль у конвеєрі: він **міняє виміряні числа**. Тому
перевірка тут сувора з обох боків.

Зелене: на полі з підкладеними множниками проходів вони мусять знайтись і
зникнути, а сам малюнок поля — лишитись на місці.

Червоне — і воно тут головне: **на чистому полі без смугастості вирівнювання
не має права нічого поміняти**. Механізм, який завжди щось «покращує»,
покращує власний слід, а не карту. І другий червоний випадок: рівень поля
не має зрушитись ані на кілограм, бо його задають інші кроки.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\вирівнювання.py"
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import leveling

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


ШИРИНА = 5.0
ПРОХОДІВ = 60
ДОВЖИНА = 600.0
КРОК_УЗДОВЖ = 5.0


def поле(сід=1):
    """Поле з плавним справжнім малюнком: два горби й улоговина.

    Проходи навмисно НЕ ідеально прямі. Перша версія цієї перевірки будувала
    їх по лінійці, і мірило смугастості на ній мовчало: коли комірка сітки
    точно збігається з проходом, «той самий прохід» і «той самий напрямок»
    стають одним і тим самим, і порівнювати нема чого. Справжній комбайн
    рискає — і саме тому на живому полі мірило працює, а на ідеальному ні.
    """
    r = np.random.default_rng(сід)
    сx, сy, прохід = [], [], []
    ряд = np.arange(0.0, ДОВЖИНА, КРОК_УЗДОВЖ)
    for п in range(ПРОХОДІВ):
        # рискання: плавний відхил осі проходу на кілька десятків сантиметрів
        відхил = 0.8 * np.sin(2.0 * np.pi * ряд / 220.0 + п * 0.7)
        сx.extend(п * ШИРИНА + відхил + r.normal(0, 0.25, len(ряд)))
        сy.extend(ряд + r.normal(0, 0.4, len(ряд)))
        прохід.extend(np.full(len(ряд), п))
    x = np.array(сx, float); y = np.array(сy, float)
    прохід = np.array(прохід)

    X = x / (ПРОХОДІВ * ШИРИНА); Y = y / ДОВЖИНА
    правда = (9000.0
              + 2500.0 * np.sin(3.0 * np.pi * X) * np.cos(2.0 * np.pi * Y)
              + 1500.0 * np.exp(-((X - 0.7) ** 2 + (Y - 0.3) ** 2) / 0.02))
    шум = r.normal(0, 350.0, len(x))
    return x, y, прохід, правда, правда + шум


def надлишок(x, y, з, п):
    м = leveling.смугастість(x, y, з, п, ширина_захвату=ШИРИНА)
    return м["надлишок"] if м else float("nan")


print("\n=== ЗЕЛЕНЕ: підкладені множники проходів мусять знайтись ===")
x, y, п, правда, чисте = поле()
r = np.random.default_rng(7)
підкладені = r.normal(1.0, 0.09, ПРОХОДІВ)      # ±9 % зміщення сенсора
підкладені /= підкладені.mean()
смугасте = чисте * підкладені[п]

до = надлишок(x, y, смугасте, п)
знайдені, хід = leveling.множники(x, y, смугасте, п, ШИРИНА)
оцінка = np.array([знайдені.get(і, 1.0) for і in range(ПРОХОДІВ)])
оцінка /= оцінка.mean()

# Міряємо те, що метод МАЄ відновити, а не суміш усього підряд.
#
# Зсув між СУСІДНІМИ проходами — це і є смугастість, і її треба знімати
# повністю. А плавний хід поперек поля метод чіпати не має права: пологий
# градієнт через поле неможливо відрізнити від самого поля, і стерти його
# означало б стерти те, за що клієнт платить.
#
# Перший поріг я поставив був на сирі множники — і він мішав обидві частини
# в одну купу. Число виходило 0,92 і виглядало як недопрацювання, тоді як
# насправді смугастість відновлювалась із r = 0,997.
від_сусіда = np.diff(підкладені)
від_сусіда_оц = np.diff(оцінка)
r_смуг = np.corrcoef(від_сусіда, від_сусіда_оц)[0, 1]
нахил_смуг = np.polyfit(від_сусіда, від_сусіда_оц, 1)[0]
каже(r_смуг > 0.95 and 0.85 < нахил_смуг < 1.15,
     "смугастість між сусідніми проходами відновлено: r = %.3f, нахил %.3f"
     % (r_смуг, нахил_смуг))

from scipy.ndimage import uniform_filter1d
плавно_п = uniform_filter1d(підкладені, 9, mode="nearest")
плавно_о = uniform_filter1d(оцінка, 9, mode="nearest")
нахил_плавно = np.polyfit(плавно_п - 1, плавно_о - 1, 1)[0]
каже(нахил_плавно < 0.4,
     "плавний хід поперек поля НЕ знято (нахил %.3f) — інакше метод стирав "
     "би саме поле" % нахил_плавно)
print("      збіжність (медіана правки): "
      + " → ".join("%.1f %%" % (100 * к["медіана"]) for к in хід))

вирівняне = смугасте / оцінка[п]
після = надлишок(x, y, вирівняне, п)
каже(після < до / 2.0,
     "смугастість упала: %.0f %% → %.0f %%" % (до, після))

print("\n=== ЗЕЛЕНЕ: поле лишилось на місці ===")
каже(np.corrcoef(вирівняне, правда)[0, 1] > np.corrcoef(смугасте, правда)[0, 1],
     "згода з правдою зросла: r %.3f → %.3f"
     % (np.corrcoef(смугасте, правда)[0, 1], np.corrcoef(вирівняне, правда)[0, 1]))
похибка_до = np.median(np.abs(смугасте - правда))
похибка_після = np.median(np.abs(вирівняне - правда))
каже(похибка_після < похибка_до,
     "похибка проти правди впала: %.0f → %.0f кг/га" % (похибка_до, похибка_після))

print("\n=== ЧЕРВОНЕ: рівень не має зрушитись ===")
каже(abs(вирівняне.mean() / смугасте.mean() - 1) < 0.01,
     "середнє збереглось: %.0f → %.0f кг/га (%.2f %%)"
     % (смугасте.mean(), вирівняне.mean(),
        100 * (вирівняне.mean() / смугасте.mean() - 1)))

print("\n=== ЧЕРВОНЕ: на чистому полі вирівнювання не має чіпати нічого ===")
знайдені_ч, _ = leveling.множники(x, y, чисте, п, ШИРИНА)
оцінка_ч = np.array([знайдені_ч.get(і, 1.0) for і in range(ПРОХОДІВ)])
оцінка_ч /= оцінка_ч.mean()
каже(оцінка_ч.std() < 0.035,
     "множники на чистому полі лишились біля одиниці: розкид %.3f "
     "(на смугастому було %.3f)" % (оцінка_ч.std(), оцінка.std()))
вирівняне_ч = чисте / оцінка_ч[п]
каже(np.median(np.abs(вирівняне_ч - чисте)) < 0.03 * чисте.mean(),
     "числа майже не змінились: медіана правки %.0f кг/га з %.0f"
     % (np.median(np.abs(вирівняне_ч - чисте)), чисте.mean()))
каже(np.median(np.abs(вирівняне_ч - правда)) <= похибка_до * 1.05,
     "і поле від цього не постраждало")

print("\n=== ЧЕРВОНЕ: один зіпсований прохід не має тягти за собою сусідів ===")
зіпсоване = чисте.copy()
зіпсоване[п == 30] *= 2.4                       # прохід поза межами калібрування
знайдені_з, _ = leveling.множники(x, y, зіпсоване, п, ШИРИНА)
м30 = знайдені_з.get(30, 1.0)
сусіди = np.array([знайдені_з.get(і, 1.0) for і in (28, 29, 31, 32)])
сусіди /= np.mean([знайдені_з.get(і, 1.0) for і in знайдені_з])
каже(м30 > 1.5, "зіпсований прохід видно: множник %.2f" % м30)
каже(np.all(np.abs(сусіди - 1.0) < 0.12),
     "сусідні проходи не поїхали за ним: %s"
     % ", ".join("%.2f" % с for с in сусіди))

print("")
print("=== ЧЕРВОНЕ: те, що зламалось на живому полі ===")
# На Г-03 сталось дві речі, яких синтетика не показувала, бо там усі проходи
# рівні й довгі: ітерації закрутились (56 → 23 → 23 → 39 → 8 %), а рівень
# з'їхав на 2,3 %. Відтворюємо обидві причини: багато КОРОТКИХ проходів,
# частина з них дика, і множники скошені в один бік.
import geopandas as gpd
from shapely.geometry import Point

r2 = np.random.default_rng(11)
скошені = 1.0 + np.abs(r2.normal(0, 0.13, ПРОХОДІВ))     # усі в один бік
скошені[::9] *= 2.2                                       # кожен девятий дикий
нерівне = чисте * скошені[п]
уривок = п * 1000 + (np.arange(len(п)) % 2)               # короткі уривки

т = gpd.GeoDataFrame(
    {"ПРОХІД": уривок, "ВРОЖАЙ_БАЗ": нерівне, "QC": "OK"},
    geometry=[Point(а, б) for а, б in zip(x, y)], crs=32635)
було_середнє = float(т["ВРОЖАЙ_БАЗ"].mean())
т, звіт = leveling.вирівняти(т, ШИРИНА, поле_значень="ВРОЖАЙ_БАЗ")
стало_середнє = float(т["ВРОЖАЙ_БАЗ"].mean())

каже(abs(стало_середнє / було_середнє - 1) < 0.002,
     "рівень збережено точно: %.0f → %.0f кг/га (%.3f %%)"
     % (було_середнє, стало_середнє, 100 * (стало_середнє / було_середнє - 1)))

каже(звіт.get("зроблено"), "вирівнювання відпрацювало: %s"
     % (звіт.get("чому") or "проходів %d, вирівняно %d, відхилено %d"
        % (звіт.get("проходів_усього", 0), звіт.get("вирівняно", 0),
           звіт.get("відхилено", 0))))
# Збіжність міряємо медіаною правки, а не максимумом: максимум смикає
# жменя найкоротших проходів, і на Г-03 він виглядав як гойдалка там, де
# метод насправді сходився чисто.
хід = [к["медіана"] for к in звіт["збіжність"]]
монотонно = all(хід[к + 1] <= хід[к] * 1.2 + 0.002 for к in range(len(хід) - 1))
каже(монотонно,
     "ітерації сходяться, а не коливаються: %s"
     % " → ".join("%.1f %%" % (100 * з_) for з_ in хід))
каже(хід[-1] < 0.02,
     "остання ітерація майже нічого не міняє: %.1f %%" % (100 * хід[-1]))
максимуми = [к["максимум"] for к in звіт["збіжність"]]
print("      максимум по проходах (він смикається, і це нормально): %s"
      % " → ".join("%.0f %%" % (100 * м) for м in максимуми))
print("      не вгамувалось проходів: %d із %d"
      % (звіт["невгамовних"], звіт["проходів_усього"]))
print("")
print("\n=== ЧЕРВОНЕ: мірило смугастості саме по собі ===")
каже(надлишок(x, y, чисте, п) < 12,
     "на чистому полі надлишок через шов малий: %.0f %%" % надлишок(x, y, чисте, п))
каже(до > 25, "на підкладеній смугастості мірило її бачить: %.0f %%" % до)

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п_ in провал:
        print("  · " + п_)
    sys.exit(1)
print("УСЕ ЧИСТО")
