# -*- coding: utf-8 -*-
"""Просторові викиди: чи ловить фільтр огріх і чи не з'їдає справжнє поле.

Це третій крок стандартного протоколу очистки карт врожайності (Vega та ін.,
2019). Він прибирає точки, що сперечаються зі своїми сусідами.

Червоне тут головніше за зелене, бо фільтр **прибирає виміряні числа**.
Найгірше, що він може зробити, — з'їсти справжню низину. Різниця між низиною
й огріхом одна: низина плавна, і її сусіди теж низькі; огріх різкий, і
довкола нього нормальне поле.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\просторові_викиди.py"
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import moran

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


КРОК = 5.0
ШИРИНА, ВИСОТА = 100, 80
ЖАТКА = 6.0


def поле(сід=1, шум=250.0):
    r = np.random.default_rng(сід)
    рр, сс = np.mgrid[0:ВИСОТА, 0:ШИРИНА]
    x = (сс * КРОК).ravel().astype(float)
    y = (рр * КРОК).ravel().astype(float)
    X, Y = сс.ravel() / ШИРИНА, рр.ravel() / ВИСОТА
    # плавне поле: горб і улоговина
    правда = (10000.0 + 2200.0 * np.sin(2.0 * np.pi * X)
              - 1500.0 * np.exp(-((X - 0.3) ** 2 + (Y - 0.6) ** 2) / 0.03))
    return x, y, правда + r.normal(0, шум, len(правда)), правда, рр.ravel(), сс.ravel()


print("\n=== ЗЕЛЕНЕ: чисте поле майже не чіпається ===")
x, y, врожай, правда, рр, сс = поле()
маска, звіт = moran.знайти(x, y, врожай, ЖАТКА)
каже(звіт["частка"] < 3.0,
     "на чистому полі прибрано %.2f %% (норма протоколу ~4,5 %%, тут менше)"
     % звіт["частка"])

print("\n=== ЧЕРВОНЕ: підкладений огріх — низьке серед високого ===")
# Огріх завширшки з ОДИН прохід. Перша версія підкладала смугу 20 м —
# ширшу за оточення, у якому фільтр шукає сусідів. Сусіди такої точки
# самі всередині огріху, і сперечатися нема з ким. Це не вада фільтра,
# а його межа: він бачить те, що вужче за оточення. Справжній огріх —
# це один прохід, шість метрів.
огріх = (сс == 62) & (рр >= 20) & (рр < 60)
врожай_о = врожай.copy()
врожай_о[огріх] *= 0.55
маска_о, звіт_о = moran.знайти(x, y, врожай_о, ЖАТКА)
спіймано = маска_о[огріх].mean()
хибно = маска_о[~огріх].mean()
каже(спіймано > 0.6, "спіймано %.0f %% комірок огріху" % (100 * спіймано))
каже(хибно < 0.04, "поза огріхом зачеплено %.2f %%" % (100 * хибно))
напрям_о = звіт_о["напрям"][огріх & маска_о]
каже((напрям_о < 0).mean() > 0.9,
     "самі комірки огріху класифіковано як «нижча за сусідів»: %.0f %%"
     % (100 * (напрям_о < 0).mean()))

print("\n=== ЧЕРВОНЕ: подвійний облік — високе серед низького ===")
подвійно = (сс == 22) & (рр >= 30) & (рр < 70)
врожай_п = врожай.copy()
врожай_п[подвійно] *= 1.8
маска_п, звіт_п = moran.знайти(x, y, врожай_п, ЖАТКА)
каже(маска_п[подвійно].mean() > 0.6,
     "спіймано %.0f %% комірок подвійного обліку" % (100 * маска_п[подвійно].mean()))
напрям_п = звіт_п["напрям"][подвійно & маска_п]
каже((напрям_п > 0).mean() > 0.9,
     "самі комірки подвійного обліку класифіковано як «вища за сусідів»: %.0f %%" % (100 * (напрям_п > 0).mean()))
print("      по всьому полю класи змішані: сусіди високої смуги виглядають")
print("      низькими за контрастом — це очікувано, а не збій")

print("\n=== ЧЕРВОНЕ, І ЦЕ ГОЛОВНЕ: справжня низина НЕ з'їдається ===")
# улоговина вже є в полі за побудовою: -1500 кг/га, плавна
низина = np.exp(-(((сс.ravel() / ШИРИНА) - 0.3) ** 2
                  + ((рр.ravel() / ВИСОТА) - 0.6) ** 2) / 0.03) > 0.5
каже(низина.sum() > 100, "низина в тесті є: %d комірок" % низина.sum())
з_низини = маска[низина].mean()
каже(з_низини < 0.05,
     "з низини прибрано лише %.2f %% — плавна різниця поля лишається"
     % (100 * з_низини))

print("\n=== ЧЕРВОНЕ: широка пляма поля теж не з'їдається ===")
# велика плавна пляма 30 х 30 комірок = 150 х 150 м, на 20 % нижча
пляма = (сс >= 30) & (сс < 60) & (рр >= 30) & (рр < 60)
врожай_пл = врожай.copy()
згасання = np.ones(len(врожай))
згасання[пляма] = 0.8
врожай_пл = врожай * згасання
маска_пл, звіт_пл = moran.знайти(x, y, врожай_пл, ЖАТКА)
всередині = пляма & ~((сс >= 33) & (сс < 57) & (рр >= 33) & (рр < 57) == False)
серцевина = (сс >= 36) & (сс < 54) & (рр >= 36) & (рр < 54)
каже(маска_пл[серцевина].mean() < 0.05,
     "серцевина широкої плями не чіпається: %.2f %%"
     % (100 * маска_пл[серцевина].mean()))

print("\n=== ЧЕРВОНЕ: без сусідів ніхто не судить ===")
x_р, y_р = x[::37], y[::37]          # рідкі точки: сусідів немає
маска_р, звіт_р = moran.знайти(x_р, y_р, врожай[::37], ЖАТКА)
каже(звіт_р.get("прибрано", 0) == 0 or звіт_р.get("без_сусідів", 0) > 0,
     "на рідких точках або нічого не прибрано, або сказано про брак сусідів "
     "(прибрано %d, без сусідів %d)"
     % (звіт_р.get("прибрано", 0), звіт_р.get("без_сусідів", 0)))

print("\n=== СКІЛЬКИ ПРИБИРАЄ НА ПОЛІ З ОГРІХОМ ===")
print("      усього %d точок, прибрано %d (%.2f %%)"
      % (звіт_о["усього"], звіт_о["прибрано"], звіт_о["частка"]))
каже(звіт_о["частка"] < 8.0,
     "прибрано %.2f %% — у межах того, що дає протокол (~4,5 %%)"
     % звіт_о["частка"])

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п in провал:
        print("  · " + п)
    sys.exit(1)
print("УСЕ ЧИСТО")
