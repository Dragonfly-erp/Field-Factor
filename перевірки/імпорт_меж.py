# -*- coding: utf-8 -*-
"""ВОРОТА ІМПОРТУ МЕЖ. Що саме заходить у дерево з чужого файлу.

Перевіряється не «чи не впало», а те, чим цей імпорт може мовчки збрехати:

* площа порахована в градусах замість метрів — поле «на 8000 га»;
* розрізане поле зайшло двома полями замість одного;
* ферма загубилась, бо GDAL стер кириличне імʼя колонки в KML;
* точки й лінії з того самого файлу стали «полями»;
* повторний імпорт затер контур, який уже лежав у полі;
* службова тека прийому вилізла в дерево як поле.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\імпорт_меж.py"
"""

import os
import shutil
import sys
import tempfile

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if БАЗА not in sys.path:
    sys.path.insert(0, БАЗА)

from app.core import intake                      # noqa: E402
from app.core.catalog import Картотека           # noqa: E402

збої = []


def перевірити(що, умова, пояснення=""):
    print("  {}  {}{}".format("OK  " if умова else "ЗБІЙ", що,
                              "" if умова else " — " + пояснення))
    if not умова:
        збої.append(що)


def _мітка(назва, ферма, кути, імʼя_колонки="Відділок"):
    коорд = " ".join("{},{},0".format(x, y) for x, y in кути)
    додаток = ("<ExtendedData><Data name=\"{}\"><value>{}</value></Data></ExtendedData>"
               .format(імʼя_колонки, ферма)) if ферма else ""
    return ("<Placemark><name>{}</name>{}<Polygon><outerBoundaryIs><LinearRing>"
            "<coordinates>{}</coordinates></LinearRing></outerBoundaryIs></Polygon>"
            "</Placemark>".format(назва, додаток, коорд))


def _точка(назва, x, y):
    return ("<Placemark><name>{}</name><Point><coordinates>{},{},0</coordinates>"
            "</Point></Placemark>".format(назва, x, y))


def _прямокутник(x0, y0, ш, в):
    return [(x0, y0), (x0 + ш, y0), (x0 + ш, y0 + в), (x0, y0 + в), (x0, y0)]


def _записати_kml(тека, частини):
    тіло = ("<?xml version=\"1.0\" encoding=\"UTF-8\"?>"
            "<kml xmlns=\"http://www.opengis.net/kml/2.2\"><Document>{}</Document></kml>"
            .format("".join(частини)))
    with open(os.path.join(тека, "поля.kml"), "w", encoding="utf-8") as ф:
        ф.write(тіло)


print("═" * 60)
print("ІМПОРТ МЕЖ У ДЕРЕВО")
print("═" * 60)

тимчасове = tempfile.mkdtemp(prefix="ff_ворота_імпорту_")
try:
    прийом = os.path.join(тимчасове, "прийом")
    os.makedirs(прийом)
    _записати_kml(прийом, [
        # ~192 га на широті 49,85 — рахунок у метрах дасть саме стільки,
        # рахунок у градусах дасть 0,00024
        _мітка("Північне", "Відділок 1", _прямокутник(24.10, 49.85, 0.02, 0.012)),
        _мітка("Південне", "Відділок 2", _прямокутник(24.10, 49.80, 0.018, 0.006)),
        _мітка("Південне", "Відділок 2", _прямокутник(24.10, 49.807, 0.018, 0.005)),
        _точка("Свердловина", 24.11, 49.83),
    ])

    звіт = intake.розвідати(прийом)
    перевірити("файл прочитано", звіт.get("гаразд"), звіт.get("повідомлення", ""))

    назви = {д["назва"]: д for д in звіт["ділянки"]}
    перевірити("розрізане поле зайшло одним, а не двома",
               len(звіт["ділянки"]) == 2 and назви["Південне"]["шматків"] == 2,
               "ділянок {}".format(len(звіт["ділянки"])))
    перевірити("точка полем не стала", "Свердловина" not in назви)

    га = назви["Північне"]["площа_га"]
    перевірити("площа в гектарах, а не в градусах", 150 < га < 250,
               "порахувало {} га — схоже на градуси".format(га))

    перевірити("ферму видно, хоч GDAL і стер імʼя колонки",
               sorted(звіт["ферми"]) == ["Відділок 1", "Відділок 2"],
               "ферми: {}".format(звіт["ферми"]))
    перевірити("сказано, що ферму взято за вмістом",
               any("за вмістом" in п for п in звіт["попередження"]),
               "мовчазне вгадування — найгірший вид вгадування")

    # ── закладення в картотеку
    корінь = os.path.join(тимчасове, "робота")
    os.makedirs(корінь)
    картотека = Картотека(корінь)
    господарство = картотека.завести_господарство("Ворота")
    наслідок = intake.закласти(картотека, господарство, прийом)

    перевірити("закладено рівно два поля", наслідок["полів"] == 2,
               "закладено {}".format(наслідок["полів"]))
    перевірити("ферма записалась у паспорт поля",
               all(з["ферма"] for з in наслідок["закладено"]),
               "поля без ферми: {}".format([з["назва"] for з in наслідок["закладено"] if not з["ферма"]]))
    перевірити("площа з контуру збіглася з розвідкою",
               abs(наслідок["площа_га"] - звіт["площа_га"]) < 1.0,
               "{} проти {}".format(наслідок["площа_га"], звіт["площа_га"]))

    # передпоказ не має розходитись із тим, що лягло: інакше людина
    # погоджується на одне, а в дереві опиняється інше
    у_дереві = {п["назва"]: п for п in картотека.поля(господарство)}
    перевірити("у дереві ті самі назви, що показали",
               set(у_дереві) == set(назви), "{} проти {}".format(set(у_дереві), set(назви)))
    перевірити("службова тека прийому в дерево не потрапила",
               all(not к.startswith("_") for к in у_дереві))

    # ── повторний імпорт не чіпає вже покладений контур
    повтор = intake.закласти(картотека, господарство, прийом)
    перевірити("повторний імпорт контур не затер", повтор["полів"] == 0,
               "перезаписав {} полів".format(повтор["полів"]))
    перевірити("і сказав, чому пропустив", len(повтор["пропущено"]) == 2)

    силою = intake.закласти(картотека, господарство, прийом, перезаписувати=True)
    перевірити("свідомий перезапис усе ж можливий", силою["полів"] == 2,
               "перезаписало {}".format(силою["полів"]))

    # ── файл без назв полів: поля мають зайти, але з чесними іменами
    другий = os.path.join(тимчасове, "прийом2")
    os.makedirs(другий)
    _записати_kml(другий, [_мітка("", "", _прямокутник(24.30, 49.90, 0.01, 0.01))])
    без_назв = intake.розвідати(другий)
    перевірити("поле без назви не втрачається",
               без_назв.get("гаразд") and len(без_назв["ділянки"]) == 1,
               "ділянок: {}".format(len(без_назв.get("ділянки") or [])))

    # ── файл без жодного полігона: чесна відмова, а не порожній успіх
    третій = os.path.join(тимчасове, "прийом3")
    os.makedirs(третій)
    _записати_kml(третій, [_точка("Тільки точка", 24.5, 49.5)])
    порожньо = intake.розвідати(третій)
    перевірити("файл без меж — відмова, а не тихий успіх",
               not порожньо.get("гаразд") and порожньо.get("повідомлення"),
               "повернуло {}".format(порожньо))
finally:
    shutil.rmtree(тимчасове, ignore_errors=True)

print()
if збої:
    print("ЗБОЇ: {}".format(len(збої)))
    for з in збої:
        print("  · {}".format(з))
    sys.exit(1)
print("УСІ ПЕРЕВІРКИ ПРОЙДЕНІ")
