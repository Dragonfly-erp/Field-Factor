# -*- coding: utf-8 -*-
"""Ворота на зупинки: чи відрізняють вони «стояв» від «швидкість не записана».

Причина, з якої ця перевірка існує. На Г-03 монітор у чотирьох суцільних
сесіях лишив колонку швидкості порожньою — рівний нуль на 98 185 записів із
222 760, тоді як координати тих самих записів дають робочі 6,4 км/год. Стара
умова «швидкість < 1 км/год → стояв» відкидала їх усі, і половина поля
лишалась без виміру: 77,6 га з 177,8.

Правило стало таким: нулю віримо лише тоді, коли місце з ним згодне.

Зелене тут перевіряє, що робочі записи не викидаються. Червоне перевіряє
саму перевірку: справжня зупинка — це запис, який стоїть на місці, і його
ворота мусять ловити далі. Інакше ми просто зняли фільтр і назвали це
виправленням.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\зупинки.py"
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import qc

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


class Журнал:
    def __init__(self):
        self.рядки = []

    def сказати(self, текст, *решта, **інше):
        self.рядки.append(текст)


def поле(швидкість, крок, тривалість=None):
    """Найменша таблиця, якої вистачає воротам кінематики."""
    n = len(швидкість)
    т = pd.DataFrame({
        "ШВИДКІСТЬ": np.asarray(швидкість, dtype=float),
        "КРОК": np.asarray(крок, dtype=float),
        "ТРИВАЛІСТЬ": (np.full(n, np.nan) if тривалість is None
                       else np.asarray(тривалість, dtype=float)),
        "ШВИДКІСТЬ_ГЕО": np.full(n, np.nan),
        "ВИСОТА": np.full(n, 235.0),
        "ПРОХІД": np.zeros(n, dtype=int),
        "QC": np.full(n, qc.ЧИСТО),
    })
    return т


ГЕОМЕТРІЯ = {"крок_уздовж_м": 1.6, "крок_поперек_м": 2.4}


def прогнати(швидкість, крок, тривалість=None):
    т = поле(швидкість, крок, тривалість)
    ж = Журнал()
    т, відкинуто = qc.кінематика(т, ГЕОМЕТРІЯ, ж)
    зупинених = (т["QC"] == "STOP").to_numpy()
    return зупинених, ж.рядки


N = 400
робочий_крок = np.full(N, 1.79)

print("\n=== ЗЕЛЕНЕ: звичайна робота ===")
з, _ = прогнати(np.full(N, 6.4), робочий_крок)
каже(з.sum() == 0, "монітор пише швидкість, машина їде — зупинок нема")

print("\n=== ЗЕЛЕНЕ: колонка швидкості не заповнена ===")
з, рядки = прогнати(np.zeros(N), робочий_крок)
каже(з.sum() == 0,
     "рівний нуль у швидкості при робочому кроці 1,79 м — не зупинка "
     "(відкинуто %d із %d)" % (з.sum(), N))
каже(any("координатами рухались" in р for р in рядки),
     "програма сказала про це вголос, а не мовчки виправила")
for р in рядки:
    if "координатами" in р:
        print("      " + р.strip())

print("\n=== ЧЕРВОНЕ: справжня зупинка мусить ловитись далі ===")
# Комбайн став: координати не міняються, зерно ще йде через сенсор.
швидкість = np.full(N, 6.4)
крок = робочий_крок.copy()
стоянка = slice(150, 200)
швидкість[стоянка] = 0.0
крок[стоянка] = 0.01
з, _ = прогнати(швидкість, крок)
каже(з[стоянка].all(), "усі 50 записів стоянки позначено STOP")
каже(з.sum() == 50, "і нічого зайвого не зачеплено (позначено %d)" % з.sum())

print("\n=== ЧЕРВОНЕ: стоянка всередині сесії без записаної швидкості ===")
# Найгірший випадок: колонка швидкості порожня ВСЮДИ, а машина посеред
# сесії справді стала. Свідком лишаються тільки координати.
швидкість = np.zeros(N)
крок = робочий_крок.copy()
крок[стоянка] = 0.02
з, _ = прогнати(швидкість, крок)
каже(з[стоянка].all(),
     "стоянку впіймано самими координатами, без допомоги швидкості")
каже(з.sum() == 50, "решта сесії лишилась робочою (позначено %d)" % з.sum())

print("\n=== ЧЕРВОНЕ: повзе поволі — це теж не робота ===")
швидкість = np.full(N, 6.4)
крок = робочий_крок.copy()
швидкість[стоянка] = 0.4      # 0,4 км/год — сповзання, не хід
крок[стоянка] = 0.11          # 0,11 м за запис: нижче порога руху
з, _ = прогнати(швидкість, крок)
каже(з[стоянка].all(), "повзання ловиться: і швидкість, і крок кажуть одне")

print("\n=== ГОЛОВНЕ: дві частоти запису на тій самій швидкості ===")
# Монітор Г-03 пише то раз на секунду, то п'ять разів. При тих самих
# 6,5 км/год робочий крок виходить 1,79 м або 0,365 м. Поріг у метрах,
# підібраний під один режим, у другому ріже роботу.
for гц, тривал in [("1 Гц", 1.0), ("5 Гц", 0.2)]:
    for хід in (6.5, 5.0, 4.0):
        крок_м = хід / 3.6 * тривал
        з, _ = прогнати(np.zeros(N), np.full(N, крок_м), np.full(N, тривал))
        каже(з.sum() == 0,
             "%s, хід %.1f км/год (крок %.3f м) — робота, не зупинка "
             "(відкинуто %d)" % (гц, хід, крок_м, з.sum()))

print("\n=== МЕЖА ПО ШВИДКОСТІ, а не по метрах ===")
for гц, тривал in [("1 Гц", 1.0), ("5 Гц", 0.2)]:
    for хід, чекаємо in [(0.5, True), (0.9, True), (1.1, False), (3.0, False)]:
        крок_м = хід / 3.6 * тривал
        з, _ = прогнати(np.zeros(N), np.full(N, крок_м), np.full(N, тривал))
        усі = bool(з.all())
        каже(усі == чекаємо,
             "%s, хід %.1f км/год → %s"
             % (гц, хід, "зупинка" if усі else "робота"))

print("\n=== БЕЗ ТРИВАЛОСТІ: свідком стає типовий крок проходу ===")
for гц, робочий in [("1 Гц", 1.79), ("5 Гц", 0.365)]:
    крок = np.full(N, робочий)
    крок[стоянка] = робочий * 0.05      # 5 % ходи — це стояння
    з, _ = прогнати(np.zeros(N), крок)
    каже(з[стоянка].all() and з.sum() == 50,
         "%s (робочий крок %.3f м): стоянку видно й без тривалості "
         "(позначено %d)" % (гц, робочий, з.sum()))
    з, _ = прогнати(np.zeros(N), np.full(N, робочий))
    каже(з.sum() == 0,
         "%s: рівний робочий хід зупинкою не стає (відкинуто %d)"
         % (гц, з.sum()))

print("\n=== МЕЖА: крок невідомий зовсім ===")
# Два різні випадки, і плутати їх не можна.
з, _ = прогнати(np.zeros(N), np.full(N, np.nan))
каже(з.sum() == 0,
     "колонка з самих нулів і кроку немає — свідка нема взагалі, весь файл "
     "не викидаємо (відкинуто %d)" % з.sum())

швидкість = np.full(N, 6.4)     # колонка заповнена й жива
швидкість[стоянка] = 0.0
крок = робочий_крок.copy()
крок[стоянка] = np.nan          # координат саме тут немає
з, _ = прогнати(швидкість, крок)
каже(з[стоянка].all() and з.sum() == 50,
     "а коли колонка жива — її нулю віримо й без координат (позначено %d)"
     % з.sum())

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п in провал:
        print("  · " + п)
    sys.exit(1)
print("УСЕ ЧИСТО")
