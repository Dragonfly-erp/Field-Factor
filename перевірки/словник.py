# -*- coding: utf-8 -*-
"""Перевірка словника атрибутів: зелене й червоне.

Зелене перевіряє щасливий шлях, червоне перевіряє саму перевірку. Тому тут
половина випадків — навмисно биті картки: якщо ворота на них мовчать, вони
не ворота, а напис.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\словник.py"
"""
import io
import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import attrs

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


print("\n=== ЗЕЛЕНЕ: заготовка ===")
с = attrs.словник()
print("  карток: %d, канонічних: %d" % (len(с), len(attrs.КАНОНІЧНІ)))
погані = {і: к["зауваги"] for і, к in с.items() if not к["годиться"]}
каже(not погані, "усі картки заготовки проходять перевірку")
if погані:
    print(json.dumps(погані, ensure_ascii=False, indent=2))
каже(not attrs.перевірити_словник(list(с.values())),
     "збігів імен і битих синонімів у заготовці немає")
каже(sorted(attrs.КАНОНІЧНІ) == sorted(
        ["YLD_KGHA", "MOIST", "ELEV_M", "HDR_W_M", "SPD_KMH",
         "DATETIME", "COMB_ID"]),
     "канонічні рівно ті сім, що в плані, розділ 33")
каже(all(len(і) <= 10 for і in с), "жодне імʼя не довше за 10 символів")

print("\n=== ЗЕЛЕНЕ: одиниці ===")
for значення, з_од, в_од, чекаємо in [
        (9.8, "т/га", "кг/га", 9800.0),
        (100.0, "ц/га", "т/га", 10.0),
        (1.0, "фут", "м", 0.3048),
        (10.0, "м/с", "км/год", 36.0),
        (0.15, "частка", "%", 15.0),
        (1.0, "т/год", "кг/с", 0.277778)]:
    число, чому = attrs.перевести(значення, з_од, в_од)
    каже(число is not None and abs(число - чекаємо) < 1e-4,
         "%s %s = %s %s" % (значення, з_од, чекаємо, в_од))

print("\n=== ЧЕРВОНЕ: одиниці, які переводити не можна ===")
число, чому = attrs.перевести(180.0, "bu/ac", "кг/га")
каже(число is None and "натур" in чому, "бушель мовчки в кілограми не йде: " + чому)
число, чому = attrs.перевести(10.0, "км/год", "кг/га")
каже(число is None, "швидкість у врожайність не переводиться: " + чому)
число, чому = attrs.перевести(10.0, "kg/ha", "кг/га")
каже(число is None, "невідома одиниця ловиться: " + чому)

print("\n=== ЧЕРВОНЕ: биті картки ===")
випадки = [
    ("задовге імʼя",
     dict(імʼя="YIELD_MASS_DRY", назва="Врожайність", розмірність="маса/площа",
          одиниця="кг/га", група="врожай", роль="додатковий", тип="дробове"),
     "довше за"),
    ("кирилиця в імені",
     dict(імʼя="ВРОЖАЙ", назва="Врожайність", розмірність="маса/площа",
          одиниця="кг/га", група="врожай", роль="додатковий", тип="дробове"),
     "не годиться для файлу"),
    ("пробіл в імені",
     dict(імʼя="YLD KGHA", назва="Врожайність", розмірність="маса/площа",
          одиниця="кг/га", група="врожай", роль="додатковий", тип="дробове"),
     "не годиться для файлу"),
    ("одиниця не від тієї величини",
     dict(імʼя="TESTA", назва="Проба", розмірність="маса/площа",
          одиниця="км/год", група="врожай", роль="додатковий", тип="дробове"),
     "не від цієї величини"),
    ("величина без одиниці",
     dict(імʼя="TESTB", назва="Проба", розмірність="маса/площа",
          одиниця=None, група="врожай", роль="додатковий", тип="дробове"),
     "Немає одиниці"),
    ("мітка з одиницею",
     dict(імʼя="TESTC", назва="Проба", розмірність="мітка", одиниця="кг/га",
          група="службові", роль="додатковий", тип="текст"),
     "одиниці не буває"),
    ("канонічний без «що без нього»",
     dict(імʼя="TESTD", назва="Проба", розмірність="маса/площа",
          одиниця="кг/га", група="врожай", роль="канонічний", тип="дробове",
          двигун="щось"),
     "без відповіді"),
    ("невідома група",
     dict(імʼя="TESTE", назва="Проба", розмірність="число", одиниця=None,
          група="погода", роль="додатковий", тип="дробове"),
     "Невідома група"),
]
for підпис, картка, слово in випадки:
    з = attrs.перевірити_картку(картка)
    спіймано = [x for x in з if x["вага"] == "помилка" and слово in x["що"]]
    каже(bool(спіймано), "%s → %s" % (підпис, спіймано[0]["що"] if спіймано else "НЕ СПІЙМАНО"))

print("\n=== ЧЕРВОНЕ: збіги імен по всьому словнику ===")
# Справжній випадок із SMS: три колонки Target_Rat злилися в одну.
пара = [dict(імʼя="TARGET_RATE_MASS", назва="а", розмірність="маса/площа",
             одиниця="кг/га", група="врожай", роль="додатковий", тип="дробове"),
        dict(імʼя="TARGET_RATE_VOL", назва="б", розмірність="обʼєм/площа",
             одиниця="л/га", група="врожай", роль="додатковий", тип="дробове")]
з = attrs.перевірити_словник(пара)
каже(any("зливаються" in x["що"] for x in з),
     "два різні імена, що зливаються після обрізання: "
     + (з[0]["що"] if з else "НЕ СПІЙМАНО"))

з = attrs.перевірити_словник([
    dict(імʼя="YLD_THA", назва="а", розмірність="маса/площа", одиниця="т/га",
         група="врожай", роль="додатковий", тип="дробове", синонім_до="YLD_XX")])
каже(any("в словнику немає" in x["що"] for x in з), "битий синонім ловиться")

print("\n=== ВОРОТА НА РОЗКЛАДКУ ===")
повна = {"YLD_KGHA": "Yld Mass Dry", "MOIST": "Moisture", "ELEV_M": "Elevation",
         "HDR_W_M": "Swath Width", "SPD_KMH": "Speed",
         "DATETIME": "Time", "COMB_ID": "Machine"}
з = attrs.перевірити_розкладку(повна)
каже(attrs.розкладка_чиста(з) and not з, "повна розкладка проходить чисто")

часткова = dict(повна)
del часткова["COMB_ID"]
з = attrs.перевірити_розкладку(часткова)
каже(not attrs.розкладка_чиста(з), "пропущений канонічний не пускає далі")
print("      " + з[0]["чому"])

явно = dict(повна)
явно["COMB_ID"] = attrs.НЕМАЄ_У_ФАЙЛІ
з = attrs.перевірити_розкладку(явно)
каже(attrs.розкладка_чиста(з) and len(з) == 1 and з[0]["вага"] == "увага",
     "явне «немає у файлі» пускає, але лишає попередження")
print("      " + з[0]["що"] + " — " + з[0]["чому"])

порожня = {}
з = attrs.перевірити_розкладку(порожня)
каже(len([x for x in з if x["вага"] == "помилка"]) == 7,
     "порожня розкладка дає сім помилок — по одній на кожен канонічний")

print("\n=== СВОЄ ПОВЕРХ ЗАГОТОВКИ ===")
тека = tempfile.mkdtemp()
своє = {
    "GRAIN_T": dict(назва="Температура зерна", розмірність="число",
                    одиниця=None, група="врожай", тип="дробове"),
    "YLD_KGHA": dict(назва="Урожай по-нашому", розмірність="маса/площа",
                     одиниця="т/га", група="врожай", роль="додатковий",
                     тип="дробове"),
}
with io.open(os.path.join(тека, attrs.ФАЙЛ), "w", encoding="utf-8") as ф:
    json.dump(своє, ф, ensure_ascii=False)

с2 = attrs.словник(тека)
каже("GRAIN_T" in с2 and с2["GRAIN_T"]["своє"], "своя картка потрапила в словник")
каже(с2["GRAIN_T"]["роль"] == "додатковий", "своя картка канонічною сама не стає")
каже(с2["YLD_KGHA"]["роль"] == "канонічний",
     "спроба зняти канонічність із врожайності не вдалась — роль зашита в картку")
каже(с2["YLD_KGHA"]["назва"] == "Урожай по-нашому",
     "але свій підпис клієнта прийнято")
каже(с2["YLD_KGHA"]["імʼя"] == "YLD_KGHA",
     "імʼя колонки у файлі лишилось канонічним")
каже(attrs.підпис(с2["YLD_KGHA"]) == "Урожай по-нашому", "у легенду йде підпис клієнта")

print("\n=== ЗА ГРУПАМИ ===")
групи = attrs.за_групами(с)
для_друку = ["%s: %d" % (г["назва"], len(г["картки"])) for г in групи]
print("  " + " · ".join(для_друку))
каже(sum(len(г["картки"]) for г in групи) == len(с), "у групи потрапили всі картки")
каже(групи[0]["картки"][0]["роль"] == "канонічний",
     "канонічні йдуть першими в групі")

print("\n=== ЗВІРКА З ТИМ, ЩО ПРОГРАМА ПИШЕ СЬОГОДНІ ===")
from app.core import rx, catalog

бракує = [к["імʼя"] for к in rx.КОЛОНКИ if к["імʼя"] not in с]
каже(not бракує, "усі колонки карти внесення є у словнику" +
     ("" if not бракує else ": бракує " + ", ".join(бракує)))

# Тип у словнику має збігатись із тим, як колонка пишеться в DBF.
розходження = []
for к in rx.КОЛОНКИ:
    у_словнику = с.get(к["імʼя"], {}).get("тип")
    у_файлі = к["вид"]
    if у_файлі == "текст" and у_словнику not in ("текст", "момент"):
        розходження.append("%s: у файлі текст, у словнику %s"
                           % (к["імʼя"], у_словнику))
    if у_файлі == "ціле" and у_словнику != "ціле":
        розходження.append("%s: у файлі ціле, у словнику %s"
                           % (к["імʼя"], у_словнику))
каже(not розходження, "типи збігаються" +
     ("" if not розходження else ": " + " · ".join(розходження)))

from app.core import export_points
поза = [і for і in export_points.ПОРЯДОК if і not in с]
каже(not поза, "усі колонки нормалізованої карти є у словнику"
     + ("" if not поза else ": бракує " + ", ".join(поза)))

# Зведення на сітку тримає власний перелік імен. 21.08 перейменування
# MOIST_RAW -> MOIST і HDR_W_M -> WORK_W_M мовчки викинуло обидві колонки
# з віддачі: модуль просто не знайшов їх і пропустив.
from app.core import thinning
чужі_у_сітці = [і for і in thinning.СЕРЕДНІ if і not in export_points.ПОРЯДОК]
каже(not чужі_у_сітці,
     "зведення на сітку не знає колонок, яких немає у віддачі"
     + ("" if not чужі_у_сітці else ": " + ", ".join(чужі_у_сітці)))

атрибути_шарів = {т.get("атрибут") for т in catalog.ТИПИ.values() if т.get("атрибут")}
чужі = sorted(а for а in атрибути_шарів if а not in с)
print("  атрибути шарів картотеки поза словником: "
      + (", ".join(чужі) if чужі else "немає"))

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п in провал:
        print("  · " + п)
    sys.exit(1)
print("УСЕ ЧИСТО")
