# -*- coding: utf-8 -*-
"""Машинні аномалії: чи ловить механізм огріх і чи не чіпає бідного ґрунту.

Це найнебезпечніші ворота в конвеєрі: вони **знімають виміряні числа з
обліку**. Тому червоне тут головніше за зелене.

Головна пастка, яку треба виключити: бідна ділянка ґрунту теж дає низьку
врожайність. Різниця одна — там і рослинність низька. Якщо механізм почне
знімати бідний ґрунт, він зітре справжню різницю поля, тобто рівно те, за
що клієнт платить.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\аномалії.py"
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import anomaly

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


КРОК = 10.0
ШИРИНА, ВИСОТА = 120, 90          # комірок: 1200 x 900 м
НАПРЯМОК = 0.0                    # проходи йдуть уздовж рядків сітки


def поле(сід=1):
    r = np.random.default_rng(сід)
    рр, сс = np.mgrid[0:ВИСОТА, 0:ШИРИНА]
    x = (сс * КРОК).ravel().astype(float)
    y = ((ВИСОТА - рр) * КРОК).ravel().astype(float)
    X, Y = сс.ravel() / ШИРИНА, рр.ravel() / ВИСОТА
    правда = 10000.0 + 1800.0 * np.sin(2.5 * np.pi * X) * np.cos(1.5 * np.pi * Y)
    веге = (правда - правда.mean()) / правда.std() + r.normal(0, 0.25, len(правда))
    врожай = правда + r.normal(0, 250.0, len(правда))
    return x, y, врожай, веге, рр.ravel(), сс.ravel()


print("\n=== ЧЕРВОНЕ: підкладений огріх комбайна ===")
x, y, врожай, веге, рр, сс = поле()
# Смуга УЗДОВЖ проходу. При напрямку 0 проходи йдуть з півночі на південь,
# тобто вертикально по сітці. Перша версія цієї перевірки підклала смугу
# впоперек — і механізм чесно її відкинув, бо огріх такої форми не буває.
# Провалився тест, а не код.
огріх = (сс >= 40) & (сс < 45) & (рр >= 20) & (рр < 70)
врожай_огріх = врожай.copy()
врожай_огріх[огріх] *= 0.72                       # зерно не потрапило в бункер
print("      підкладено: %.1f га, %d %% нижче, рослинність не чіпали"
      % (огріх.sum() * 0.01, 28))

маска, перелік = anomaly.знайти(x, y, врожай_огріх, веге, НАПРЯМОК, КРОК)
каже(len(перелік) >= 1, "огріх знайдено: ділянок %d" % len(перелік))
if перелік:
    д = перелік[0]
    print("      %.1f га · нижче на %.0f %% · рослинність %+.2f · витягнутість %.1f"
          % (д["га"], д["нижче_на"], д["рослинність"], д["витягнутість"]))
    каже(abs(д["га"] - огріх.sum() * 0.01) < 1.5,
         "площа збіглася: %.1f га проти підкладених %.1f"
         % (д["га"], огріх.sum() * 0.01))
    спіймано = маска[огріх].mean()
    каже(спіймано > 0.5, "спіймано %.0f %% комірок огріху" % (100 * спіймано))
    хибно = маска[~огріх].mean()
    каже(хибно < 0.02, "поза огріхом зачеплено лише %.2f %%" % (100 * хибно))

print("\n=== ЧЕРВОНЕ: бідний ґрунт НЕ має зніматись ===")
# та сама пляма, але там і рослинність низька — це поле, а не машина
врожай_ґрунт = врожай.copy()
веге_ґрунт = веге.copy()
врожай_ґрунт[огріх] *= 0.72
веге_ґрунт[огріх] -= 1.2
маска_ґ, перелік_ґ = anomaly.знайти(x, y, врожай_ґрунт, веге_ґрунт, НАПРЯМОК, КРОК)
каже(not перелік_ґ,
     "бідний ґрунт аномалією не став (знайдено %d)" % len(перелік_ґ))

print("\n=== ЧЕРВОНЕ: кругла пляма — форма ґрунту, не машини ===")
центр_р, центр_с = 45, 60
кругла = ((рр - центр_р) ** 2 + (сс - центр_с) ** 2) <= 13 ** 2
врожай_кругла = врожай.copy()
врожай_кругла[кругла] *= 0.72
маска_к, перелік_к = anomaly.знайти(x, y, врожай_кругла, веге, НАПРЯМОК, КРОК)
каже(not перелік_к,
     "кругла пляма не пройшла ворота витягнутості (знайдено %d)" % len(перелік_к))

print("\n=== ЧЕРВОНЕ: на чистому полі ловити нема чого ===")
маска_ч, перелік_ч = anomaly.знайти(x, y, врожай, веге, НАПРЯМОК, КРОК)
каже(not перелік_ч, "на чистому полі аномалій нема (знайдено %d)" % len(перелік_ч))

print("\n=== ЧЕРВОНЕ: дрібний огріх не рахується ===")
дрібний = (сс >= 60) & (сс < 62) & (рр >= 30) & (рр < 38)   # 0,16 га
врожай_д = врожай.copy()
врожай_д[дрібний] *= 0.7
маска_д, перелік_д = anomaly.знайти(x, y, врожай_д, веге, НАПРЯМОК, КРОК)
каже(not перелік_д,
     "ділянка %.2f га менша за поріг — не рахується (знайдено %d)"
     % (дрібний.sum() * 0.01, len(перелік_д)))

print("\n=== ЧЕРВОНЕ: без свідка нічого не знімається ===")
маска_б, перелік_б = anomaly.знайти(
    x, y, врожай_огріх, np.full(len(врожай), np.nan), НАПРЯМОК, КРОК)
каже(not перелік_б, "рослинності немає — аномалій не шукаємо")

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п in провал:
        print("  · " + п)
    sys.exit(1)
print("УСЕ ЧИСТО")
