# -*- coding: utf-8 -*-
"""ВОРОТА ПЛАНУ СЕЗОНУ.

Перевіряється те, на чому план може мовчки збрехати:

* обраний варіант ротації затирає культуру, яку агроном поставив рукою;
* поле без площі тихо входить у структуру посівів з нульовою часткою;
* зведення рахує «готових 21 з 21», бо не знає про решту полів;
* порожній крок записується як крок, і «ще не вирішили» стає
  «вирішили нічого»;
* план без жодної культури затверджується й породжує порожній сезон.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\план_сезону.py"
"""

import os
import shutil
import sys
import tempfile

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if БАЗА not in sys.path:
    sys.path.insert(0, БАЗА)

from app.core import plan                             # noqa: E402
from app.core.catalog import Картотека                # noqa: E402

збої = []


def перевірити(що, умова, пояснення=""):
    print("  {}  {}{}".format("OK  " if умова else "ЗБІЙ", що,
                              "" if умова else " — " + пояснення))
    if not умова:
        збої.append(що)


print("═" * 60)
print("ПЛАН СЕЗОНУ")
print("═" * 60)

тимчасове = tempfile.mkdtemp(prefix="ff_план_")
try:
    к = Картотека(тимчасове)
    г = к.завести_господарство("Тест")
    for назва in ("Поле Перше", "Поле Друге", "Поле Третє"):
        к.завести_поле(г, назва)
    за_назвою = {п["назва"]: п["ключ"] for п in к.поля(г)}
    ключі = [за_назвою["Поле Перше"], за_назвою["Поле Друге"],
             за_назвою["Поле Третє"]]

    # ── план не зʼявляється на диску від самого перегляду
    п = plan.прочитати(к, г, 2027)
    перевірити("порожній план не записується сам",
               not os.path.isdir(os.path.join(тимчасове, г, plan.ТЕКА)),
               "тека планів створилась від простого читання")
    перевірити("новий план — чернетка", п["стан"] == "чернетка")
    перевірити("у новому плані немає полів", п["поля"] == {},
               "план на всі поля порожнім не заводиться")

    # ── варіанти ротації
    plan.варіант_додати(п, "а", "Базовий", "як торік",
                        {ключі[0]: "пшениця", ключі[1]: "соя"})
    plan.варіант_додати(п, "б", "Максимум маржі", "більше олійних",
                        {ключі[0]: "соняшник", ключі[1]: "соняшник"})
    перевірити("два варіанти лежать поруч", len(п["варіанти"]) == 2)

    plan.варіант_обрати(п, "а")
    перевірити("обраний варіант розклався по полях",
               plan.крок(п, ключі[0], "ротація")["культура"] == "пшениця")
    перевірити("джерело кроку названо",
               "варіант ротації" in plan.крок(п, ключі[0], "ротація")["джерело"])

    # ── рішення агронома не затирається варіантом
    п["поля"][ключі[0]]["культура"] = "кукурудза"
    plan.варіант_обрати(п, "б")
    перевірити("варіант НЕ затер культуру, обрану рукою",
               п["поля"][ключі[0]]["культура"] == "кукурудза",
               "стало {}".format(п["поля"][ключі[0]]["культура"]))
    р = {з["поле"]: з for з in plan.розбіжності(п)}
    перевірити("розбіжність із варіантом видно на полі, правленому рукою",
               р.get(ключі[0], {}).get("у_варіанті") == "соняшник"
               and р.get(ключі[0], {}).get("у_плані") == "кукурудза",
               "маємо {}".format(р.get(ключі[0])))
    перевірити("розбіжність видно й там, де культура лишилась із першого варіанта",
               р.get(ключі[1], {}).get("у_плані") == "соя",
               "маємо {}".format(р.get(ключі[1])))
    перевірити("поле, якого варіант не торкався, у розбіжності не потрапило",
               ключі[2] not in р)

    # ── кроки
    plan.крок_записати(п, ключі[0], "живлення", {"N": 164, "P": 68, "K": 90},
                       джерело="норми по зонах")
    перевірити("крок записався", plan.крок(п, ключі[0], "живлення")["N"] == 164)
    plan.крок_записати(п, ключі[0], "живлення", {})
    перевірити("порожній крок стирається, а не пишеться порожнім",
               plan.крок(п, ключі[0], "живлення") is None,
               "лишився {}".format(plan.крок(п, ключі[0], "живлення")))

    невідомий = False
    try:
        plan.крок_записати(п, ключі[0], "вигаданий", {"щось": 1})
    except ValueError:
        невідомий = True
    перевірити("невідомий крок не заводиться", невідомий)

    # ── культура прибирається БЕЗ недогризка. Порожній запис поля
    # «{"кроки": {}}» лишався в плані назавжди: поставили культуру,
    # передумали — і поле висить у плані порожнім.
    plan.культуру_поставити(п, ключі[2], "ячмінь")
    перевірити("культура поставилась разом із кроком ротації",
               plan.крок(п, ключі[2], "ротація")["культура"] == "ячмінь")
    plan.культуру_поставити(п, ключі[2], "")
    перевірити("прибрана культура не лишає порожнього запису поля",
               ключі[2] not in (п.get("поля") or {}),
               "лишилось {}".format((п.get("поля") or {}).get(ключі[2])))

    # поле, де є ІНШІ кроки, при прибиранні культури не зникає — там ще
    # лежить робота, і викидати її разом із культурою не можна
    plan.культуру_поставити(п, ключі[2], "ячмінь")
    plan.крок_записати(п, ключі[2], "живлення", {"N": 90})
    plan.культуру_поставити(п, ключі[2], "")
    перевірити("поле з іншими кроками лишається в плані",
               plan.крок(п, ключі[2], "живлення") is not None
               and not (п["поля"][ключі[2]].get("культура")),
               "маємо {}".format((п.get("поля") or {}).get(ключі[2])))
    plan.крок_записати(п, ключі[2], "живлення", {})
    plan.культуру_поставити(п, ключі[2], "")

    # ── наступний крок — той, на якому зупинились
    с = plan.стан_поля(п, ключі[0])
    перевірити("наступний крок — перший незакритий", с["наступний"] == "культура",
               "маємо {}".format(с["наступний"]))
    перевірити("поле не вважається готовим", not с["готове"])

    # ── зведення бачить УСІ поля господарства, а не лише зачеплені планом
    зв = plan.зведення(п, усі_поля=ключі)
    перевірити("зведення рахує всі поля господарства", зв["полів"] == 3,
               "порахувало {}".format(зв["полів"]))
    перевірити("поля без культури названі",
               ключі[2] in зв["без_культури"],
               "без культури: {}".format(зв["без_культури"]))
    зв_без = plan.зведення(п)
    перевірити("без переліку полів видно лише зачеплені планом",
               зв_без["полів"] == 2, "порахувало {}".format(зв_без["полів"]))

    # ── структура посівів: поле без площі не входить нулем
    структура = plan.структура(п, {ключі[0]: 100.0})
    перевірити("поле без площі не потрапило в структуру",
               ключі[1] in структура["без_площі"],
               "без площі: {}".format(структура["без_площі"]))
    перевірити("частка рахується від відомої площі",
               структура["рядки"][0]["частка"] == 100.0,
               "маємо {}".format(структура["рядки"]))
    перевірити("гектари не вигадані", структура["га"] == 100.0)

    # ── затвердження
    порожній = plan.порожній(2028)
    не_дав = False
    try:
        plan.затвердити(порожній)
    except ValueError:
        не_дав = True
    перевірити("план без культур не затверджується", не_дав)
    plan.затвердити(п)
    перевірити("план із культурами затвердився", п["стан"] == "затверджений")

    # ── записане читається з диска, а не з памʼяті
    plan.записати(к, г, п)
    з_диска = plan.прочитати(к, г, 2027)
    перевірити("план прочитався з диска таким, як записаний",
               з_диска["стан"] == "затверджений"
               and з_диска["поля"][ключі[0]]["культура"] == "кукурудза",
               "прочитано {}".format(з_диска.get("стан")))
    перевірити("рік плану знайшовся у переліку",
               plan.роки(к, г) == [2027], "маємо {}".format(plan.роки(к, г)))
finally:
    shutil.rmtree(тимчасове, ignore_errors=True)

print()
if збої:
    print("ЗБОЇ: {}".format(len(збої)))
    for з in збої:
        print("  · {}".format(з))
    sys.exit(1)
print("УСІ ПЕРЕВІРКИ ПРОЙДЕНІ")
