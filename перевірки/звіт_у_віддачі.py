def синтетичне_поле(стовпців=64, рядків=44, крок=10.0):
    """Рівне поле з градієнтом і плямою — рівно стільки, скільки треба звіту."""
    import geopandas as gpd
    from shapely.geometry import Point, box

    с, р = np.meshgrid(np.arange(стовпців), np.arange(рядків))
    с = с.ravel().astype("float64")
    р = р.ravel().astype("float64")
    x = 400000.0 + с * крок
    y = 5400000.0 - р * крок

    рельєф = 120.0 + (р / рядків) * 6.0
    вегетація = 0.55 + 0.18 * (1.0 - р / рядків) + 0.05 * np.sin(с / 7.0)
    врожай = 6000.0 + 9000.0 * (вегетація - 0.55) + 40.0 * np.sin(с / 5.0)
    # пляма недобору: щоб сторінка «втрачених можливостей» мала що показати
    пляма = (с > 12) & (с < 30) & (р > 10) & (р < 26)
    врожай = np.where(пляма, врожай * 0.72, врожай)

    поле = gpd.GeoDataFrame({
        "YLD_KGHA": врожай,
        "YLD_SM": врожай,
        "SRC_TYPE": np.where(np.arange(len(врожай)) % 37 == 0, "INTERP", "MEAS"),
        "MOIST": np.full(len(врожай), 14.0),
        "VEG_IDX": вегетація,
        "VEG_YEARS": вегетація * 0.95,
        "BSI_IDX": 0.3 + 0.1 * (с / стовпців),
        "ELEV_M": рельєф,
    }, geometry=[Point(а, б) for а, б in zip(x, y)], crs="EPSG:32635")

    контур = gpd.GeoDataFrame(
        geometry=[box(x.min() - крок / 2, y.min() - крок / 2,
                      x.max() + крок / 2, y.max() + крок / 2)], crs="EPSG:32635")
    return поле, контур


