def мертві_аргументи(функція):
    """Аргументи, які функція приймає й жодного разу не читає.

    Дивимось у байт-код, а не в текст: назва аргументу може трапитись у
    коментарі чи в рядку, і пошук по тексту сказав би «використовується».
    """
    прочитані = set()
    for крок in dis.get_instructions(функція.__code__):
        if крок.opname.startswith("LOAD_FAST"):
            if isinstance(крок.argval, tuple):
                прочитані.update(крок.argval)
            else:
                прочитані.add(крок.argval)
    return [і for і in inspect.signature(функція).parameters if і not in прочитані]


