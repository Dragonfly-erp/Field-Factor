# -*- coding: utf-8 -*-
r"""Ворота видачі читають ФАЙЛ, а не таблицю в памʼяті.

Між таблицею й файлом стоять округлення, опис поля, його довжина й
кодування. 21.08 округлення при стисканні DBF обнулило 789 значень потоку:
таблиця лишалась бездоганною, ворота казали «чисто», а сім чисел SMS у
файлі між собою не сходились.

Головне тут червоне: **та сама помилка, відтворена навмисно.** Механізм
тривоги, якого не бачили в стані тривоги, — це напис.

Запуск:  runtime\python.exe -X utf8 "перевірки\віддане_проти_памяті.py"
"""
import os
import shutil
import sys
import tempfile

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import export_points, validation

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


def кричить(дія):
    try:
        дія()
    except Exception as помилка:                       # noqa: BLE001
        return str(помилка)
    return None


class Тиша:
    def сказати(self, *_а, **_к):
        pass


def таблиця(рядків=400):
    """Маленька віддача з тими самими колонками, що й справжня."""
    import geopandas as gpd
    from shapely.geometry import Point

    н = np.arange(рядків)
    x = 400000.0 + (н % 20) * 10.0
    y = 5400000.0 - (н // 20) * 10.0
    return gpd.GeoDataFrame({
        "PT_ID": (н + 1).astype("int64"),
        "ORIG_ID": (н + 1000).astype("float64"),
        "YLD_KGHA": 9000.0 + (н % 37) * 51.7,
        "MOIST": 14.0 + (н % 11) * 0.13,
        # медіана потоку тут така сама мала, як на живому полі: саме через
        # цей порядок величини три знаки після коми й обнулили 789 комірок
        "FLOW_TH": 0.07 + (н % 13) * 0.004,
        "DUR_S": 0.2 + (н % 7) * 0.05,
        "CELL_HA": np.full(рядків, 0.01),
        "VEG_IDX": 0.4 + (н % 23) * 0.012,
    }, geometry=[Point(а, б) for а, б in zip(x, y)], crs="EPSG:32635")


тека = tempfile.mkdtemp(prefix="ff_віддане_")


def записати(таб, імʼя="віддача.shp"):
    шлях = os.path.join(тека, імʼя)
    export_points.записати_шейп(таб, шлях)
    return шлях


# ═══════════════════════════════════════════════════════════════════════
print("\n=== ЗЕЛЕНЕ: чесний запис ===")
таб = таблиця()
шлях = записати(таб)
слово = кричить(lambda: validation.звірити_віддане(шлях, таб, Тиша()))
каже(слово is None, "файл збігається з тим, що віддавали{}".format(
    "" if слово is None else " — АЛЕ: " + слово))

print("\n=== ЧЕРВОНЕ: та сама помилка 21.08 — округлення зʼїло потік ===")
# Відтворюємо дослівно: DBF стискається з ТРЬОМА знаками на FLOW_TH замість
# шести. Медіана 0,07 т/год — три знаки лишають два значущих розряди.
таб2 = таблиця()
шлях2 = записати(таб2, "обнулений.shp")
зіпсовані = dict(export_points.ЗНАКІВ)
зіпсовані["FLOW_TH"] = 3
export_points.стиснути_dbf(шлях2.replace(".shp", ".dbf"),
                           export_points.ШИРИНИ, знаків=зіпсовані)
слово = кричить(lambda: validation.звірити_віддане(шлях2, таб2, Тиша()))
каже(слово is not None and "FLOW_TH" in слово,
     "потік округлено до трьох знаків — ворота спиняють: {}".format(
         (слово or "МОВЧАТЬ")[:150]))

print("\n=== ЧЕРВОНЕ: значення змінилось при записі ===")
таб3 = таблиця()
шлях3 = записати(таб3, "змінене.shp")
підроблена = таб3.copy()
підроблена.loc[7, "YLD_KGHA"] = 1234.5          # у памʼяті було інше
слово = кричить(lambda: validation.звірити_віддане(шлях3, підроблена, Тиша()))
каже(слово is not None and "YLD_KGHA" in слово,
     "одна комірка розійшлась — ворота спиняють")

print("\n=== ЧЕРВОНЕ: колонка не доїхала до файлу ===")
таб4 = таблиця()
шлях4 = записати(таб4.drop(columns=["VEG_IDX"]), "без_колонки.shp")
слово = кричить(lambda: validation.звірити_віддане(шлях4, таб4, Тиша()))
каже(слово is not None and "VEG_IDX" in слово,
     "зникла колонка — ворота спиняють")

print("\n=== ЧЕРВОНЕ: у файлі не стільки рядків ===")
таб5 = таблиця()
шлях5 = записати(таб5.iloc[:-10], "коротший.shp")
слово = кричить(lambda: validation.звірити_віддане(шлях5, таб5, Тиша()))
каже(слово is not None and "рядк" in слово, "зникли рядки — ворота спиняють")

print("\n=== ЧЕРВОНЕ: дробова колонка без оголошеної точності ===")
# Саме так VEG_IDX, VEG_YEARS і BSI_IDX проїхали клієнту сімнадцятибайтовими
# полями з пʼятнадцятьма знаками: незакритий коментар зʼїв їх із таблиці
# точності, і ніхто не крикнув.
таб6 = таблиця()
# назва латиницею: у шейпфайла імʼя поля не довше за 10 БАЙТІВ,
# і кирилиця там обрізається вдвічі швидше
таб6["NEW_COL"] = 0.123456789
шлях6 = записати(таб6, "без_точності.shp")
слово = кричить(lambda: validation.звірити_віддане(шлях6, таб6, Тиша()))
каже(слово is not None and "точност" in слово,
     "нова дробова колонка без запису в ЗНАКІВ — ворота спиняють")

print("\n=== ЗЕЛЕНЕ: кожна дробова колонка віддачі має оголошену точність ===")
# Ловить ту саму діру на рівні коду, не чекаючи прогону: 21.08 незакритий
# коментар зʼїв чотири колонки прямо з таблиці точності.
каже(len(export_points.ЗНАКІВ) >= 24,
     "у таблиці точності {} колонок".format(len(export_points.ЗНАКІВ)))
for обовʼязкова in ("VEG_IDX", "VEG_YEARS", "BSI_IDX", "ORIG_ID", "FLOW_TH"):
    каже(обовʼязкова in export_points.ЗНАКІВ,
         "{} має оголошену точність".format(обовʼязкова))

print("\n=== ЧЕРВОНЕ: файлу немає взагалі ===")
слово = кричить(lambda: validation.звірити_віддане(
    os.path.join(тека, "якого-немає.shp"), таблиця(), Тиша()))
каже(слово is not None, "файлу немає — ворота спиняють, а не мовчать")

shutil.rmtree(тека, ignore_errors=True)
print("\n" + ("ПРОВАЛІВ: %d" % len(провал) if провал else "УСІ ПЕРЕВІРКИ ПРОЙДЕНІ"))
for р in провал:
    print("  · " + р)
sys.exit(1 if провал else 0)
