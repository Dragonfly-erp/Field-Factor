# -*- coding: utf-8 -*-
"""Робоча ширина з геометрії: чи справді вона міряє те, що обіцяє.

Причина, з якої це існує. Монітор Г-03 записав жатку 6,00 м і чесно ділив на
неї масу. Земля під смугами дала 5,26 м: комбайнер ішов із нахлистом, друга
половина жатки місцями йшла по вже зібраному, зерна звідти немає. Площа
виходила завищена на 12 %, а врожайність — занижена рівно настільки ж.

Тут вимір годують **підкладеним перекриттям відомої величини**. Якщо він на
ньому не спрацює, то на живому полі він і поготів нічого не покаже — просто
ніхто не помітить.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\ширина.py"
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import passes

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


def поле(крок_між_проходами, проходів=14, довжина=400.0, крок_уздовж=1.0):
    """Прямі паралельні проходи із заданою відстанню між ними."""
    import geopandas as gpd
    import pandas as pd
    from shapely.geometry import Point

    x, y, прохід, крок = [], [], [], []
    для_кожного = np.arange(0.0, довжина, крок_уздовж)
    for п in range(проходів):
        x.extend(np.full(len(для_кожного), п * крок_між_проходами))
        y.extend(для_кожного)
        прохід.extend(np.full(len(для_кожного), п))
        крок.extend([крок_уздовж] * len(для_кожного))
    т = gpd.GeoDataFrame(
        {"ПРОХІД": прохід, "КРОК": крок},
        geometry=[Point(а, б) for а, б in zip(x, y)], crs=32635)
    return т


ЖАТКА = 6.0

print("\n=== ЗЕЛЕНЕ: проходи впритул, перекриття нема ===")
т = поле(ЖАТКА)
з = passes.виміряти_ширину(т, ЖАТКА)
каже(з is not None and abs(з["ширина_м"] - ЖАТКА) < 0.25,
     "проходи через %.2f м → виміряно %.2f м (записано %.2f)"
     % (ЖАТКА, з["ширина_м"], ЖАТКА))
каже(з["перекриття_відсотків"] < 5,
     "перекриття близьке до нуля: %.1f %%" % з["перекриття_відсотків"])

print("\n=== ЧЕРВОНЕ: підкладене перекриття відомої величини ===")
for нахлист, чекаємо in [(0.5, 8.3), (1.0, 16.7), (1.5, 25.0), (2.0, 33.3)]:
    крок = ЖАТКА - нахлист
    з = passes.виміряти_ширину(поле(крок), ЖАТКА)
    похибка = abs(з["ширина_м"] - крок)
    каже(похибка < 0.3,
         "нахлист %.1f м → проходи через %.1f м, виміряно %.2f м "
         "(перекриття %.0f %%, чекали %.0f %%)"
         % (нахлист, крок, з["ширина_м"], з["перекриття_відсотків"], чекаємо))

print("\n=== ЧЕРВОНЕ: проходи з розривами — ширина не має роздуватись ===")
# Комбайн пропустив смуги: землі накрито менше, але й ширина проходу та сама.
з = passes.виміряти_ширину(поле(ЖАТКА * 2), ЖАТКА)
каже(abs(з["ширина_м"] - ЖАТКА) < 0.3,
     "проходи через 12 м при жатці 6 м → виміряно %.2f м, а не 12"
     % з["ширина_м"])
каже(з["перекриття_відсотків"] < 5,
     "розрив між проходами перекриттям не рахується: %.1f %%"
     % з["перекриття_відсотків"])

print("\n=== ЧЕРВОНЕ: коли міряти нема на чому ===")
каже(passes.виміряти_ширину(поле(ЖАТКА), 0) is None, "ширина нуль → None")
каже(passes.виміряти_ширину(поле(ЖАТКА), float("nan")) is None, "ширина NaN → None")
куце = поле(ЖАТКА, проходів=1, довжина=20.0)
каже(passes.виміряти_ширину(куце, ЖАТКА) is None,
     "шлях коротший за 100 м → None, а не вигадане число")

print("\n=== ЧИ СХОДИТЬСЯ ПЛОЩА ===")
т = поле(ЖАТКА, проходів=10, довжина=500.0)
з = passes.виміряти_ширину(т, ЖАТКА)
очікувано = 10 * 500.0 * ЖАТКА / 10000.0
каже(abs(з["накрито_га"] - очікувано) / очікувано < 0.06,
     "10 проходів по 500 м жаткою 6 м = %.2f га, виміряно %.2f га"
     % (очікувано, з["накрито_га"]))

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п in провал:
        print("  · " + п)
    sys.exit(1)
print("УСЕ ЧИСТО")
