# ═══════════════════════════════════════ СЦЕНАРІЇ ГОСПОДАРСТВА
print()
ОДНАКОВА = {"2023": "Соя", "2024": "Соняшник",
            "2025": "Пшениця озима", "2026": "Кукурудза"}
# Історія навмисно ОДНАКОВА на всіх полях: тоді «перша допустима»
# культура однакова для всіх, і брак рівномірного розподілу одразу
# виливається в монокультуру. На полях з різною історією цей провал
# не відтворюється, і перевірка була б порожньою.
ПОЛЯ = [{"ключ": "П{}".format(і), "площа_га": га, "історія": dict(ОДНАКОВА)}
        for і, га in enumerate((200.0, 150.0, 100.0, 90.0), 1)]

# ── культури беруться з ГОСПОДАРСТВА, а не зі словника коренів. Без цього
# генератор пропонував просо, гречку й люцерну лише тому, що вони є в
# словнику: сівозміну складають із того, під що є техніка й покупець.
свої = р.культури_господарства(ПОЛЯ)
перевірити("культури беруться з історії господарства",
           set(свої) == {"пшениця", "кукурудза", "соя", "соняшник"},
           "маємо {}".format(свої))

варіанти = р.сценарії(ПОЛЯ, 2027)

# Перевіряємо СТРУКТУРУ готового сценарію, а не функцію окремо: генератор
# міг би брати кандидатів зі словника коренів повз неї, і перевірка самої
# функції цього не побачила б.
чужі = set()
for в in варіанти:
    чужі |= {р2["культура"] for р2 in в["структура"]} - set(свої)
перевірити("у сценаріях немає культур, яких господарство не вирощує",
           not чужі, "з'явились {}".format(sorted(чужі)))
перевірити("сценаріїв чотири", len(варіанти) == 4, "маємо {}".format(len(варіанти)))

# ── ГОЛОВНЕ: жоден сценарій не віддає всю площу одній культурі.
# Саме це сталось у першому прогоні — кукурудза на всіх 21 полі, бо вона
# єдина без обмеження повернення, і всі чотири варіанти вийшли однакові.
for в in варіанти:
    найбільша = max((р2["частка"] or 0) for р2 in в["структура"]) if в["структура"] else 0
    перевірити("«{}» не є монокультурою".format(в["назва"]), найбільша < 100,
               "найбільша частка {} %".format(найбільша))
    перевірити("«{}» має більше однієї культури".format(в["назва"]),
               len(в["структура"]) > 1, "культур {}".format(len(в["структура"])))

# ── МОНОКУЛЬТУРА КУКУРУДЗИ. Саме це сталось на живих даних КОМАГРО:
# кукурудза єдина, чий інтервал повернення — один рік, тож стеля частки
# в неї 100 %, і без рівномірного розподілу вона вигравала на всіх 21
# полі. Решту культур від монокультури стеля рятує сама, тому провал
# відтворюється ЛИШЕ на наборі, де кукурудза чиста.
БЕЗ_КУКУРУДЗИ = {"2023": "Соя", "2024": "Пшениця озима",
                 "2025": "Соя", "2026": "Пшениця озима"}
ПОЛЯ_КУКУРУДЗА = [{"ключ": "К{}".format(і), "площа_га": га,
                   "історія": dict(БЕЗ_КУКУРУДЗИ)}
                  for і, га in enumerate((200.0, 150.0, 100.0, 90.0), 1)]
для_кукурудзи = р.сценарій(ПОЛЯ_КУКУРУДЗА, 2027, р.ПОЛІТИКИ[0],
                           культури=["кукурудза", "соя", "пшениця", "соняшник"])
частки = {р2["культура"]: р2["частка"] for р2 in для_кукурудзи["структура"]}
перевірити("кукурудза не займає все поле господарства",
           (частки.get("кукурудза") or 0) < 100,
           "кукурудза дістала {} % — рівномірний розподіл не спрацював".format(
               частки.get("кукурудза")))
перевірити("у сценарії більше однієї культури навіть там, де кукурудза чиста",
           len(для_кукурудзи["структура"]) > 1,
           "маємо {}".format(для_кукурудзи["структура"]))

# ── обережний не приймає ризиків за побудовою
обережний = [в for в in варіанти if в["ключ"] == "обережний"][0]
наступальний = [в for в in варіанти if в["ключ"] == "наступальний"][0]
перевірити("обережний не приймає жодного ризику", обережний["ризиків"] == 0,
           "прийняв {}".format(обережний["ризиків"]))
перевірити("наступальний приймає ризики свідомо й називає їх",
           all(п.get("пояснення") for п in наступальний["прийняті_ризики"]))

# ── сценарії, що зійшлись в один розклад, позначені збігом
відбитки = {}
for в in варіанти:
    відбиток = tuple(sorted(в["розклад"].items()))
    if відбиток in відбитки:
        перевірити("однаковий сценарій «{}» позначено збігом".format(в["назва"]),
                   в["збігається_з"] == відбитки[відбиток],
                   "маємо {}".format(в["збігається_з"]))
    else:
        відбитки[відбиток] = в["назва"]

# ── поле, для якого політика не знайшла культури, лишається порожнім
вузько = р.сценарій(ПОЛЯ, 2027, р.ПОЛІТИКИ[0], культури=["соняшник"])
перевірити("поле без допустимої культури лишається порожнім, а не заповненим навмання",
           len(вузько["не_закрито"]) + len(вузько["розклад"]) == len(ПОЛЯ))
перевірити("у незакритого поля названа причина",
           all(нз.get("чому") for нз in вузько["не_закрито"]))

print()
if збої:
    print("ЗБОЇ: {}".format(len(збої)))
    for з in збої:
        print("  · {}".format(з))
    sys.exit(1)
print("УСІ ПЕРЕВІРКИ ПРОЙДЕНІ")
