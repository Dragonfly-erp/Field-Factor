def перевірити(що, умова, пояснення=""):
    print("  {}  {}{}".format("OK  " if умова else "ЗБІЙ", що,
                              "" if умова else " — " + пояснення))
    if not умова:
        збої.append(що)


def механізми(оцінка, імʼя):
    return [п for п in оцінка["причини"] if п["механізм"] == імʼя]


