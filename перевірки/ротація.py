перевірити("матриця сумісності прочиталась", len(р.матриця()) >= 60,
           "маємо {}".format(len(р.матриця())))
перевірити("каталог післядії прочитався", len(р.післядія()["рядки"]) >= 300,
           "маємо {}".format(len(р.післядія()["рядки"])))

# ── корені культур
перевірити("«Кукурудза на зерно» і «кукурудза зерно» — одна культура",
           р.корінь("Кукурудза на зерно") == р.корінь("кукурудза зерно") == "кукурудза")
перевірити("«Пшениця озима» зводиться до пшениці", р.корінь("Пшениця озима") == "пшениця")
перевірити("невідома культура лишається собою, а не вгадується",
           р.корінь("Амарант посівний") == "амарант посівний")

ІСТОРІЯ = {"2020": "Кукурудза", "2021": "Соняшник", "2022": "Пшениця озима",
           "2023": "Соя", "2024": "Кукурудза", "2025": "Соняшник",
           "2026": "Пшениця озима"}

# ── КЛЮЧОВЕ: короткий інтервал — це ризик, а не заборона
о = р.оцінити("Соняшник", ІСТОРІЯ, 2027)
перевірити("соняшник через 2 роки — РИЗИК, а не стоп", о["стан"] == р.РИЗИК,
           "стан {}".format(о["стан"]))
інт = механізми(о, "інтервал_повернення")
перевірити("інтервал названий поіменно", len(інт) == 1)
перевірити("клас інтервалу — попередній, не твердий",
           інт[0]["клас"] == р.ПОПЕРЕДНІЙ, "маємо {}".format(інт[0]["клас"]))
перевірити("у поясненні видно ДІАПАЗОН, а не одне число",
           "3–7" in інт[0]["пояснення"], "маємо: {}".format(інт[0]["пояснення"]))
перевірити("джерело названо", "SDSU" in інт[0]["джерело"])

# ── ідентичність культури не дає СТОП навіть у найгіршому разі
підряд = {"2024": "Соняшник", "2025": "Соняшник", "2026": "Соняшник"}
о2 = р.оцінити("Соняшник", підряд, 2027)
перевірити("соняшник четвертий рік підряд — усе одно не СТОП",
           о2["стан"] != р.СТОП,
           "ідентичність культури не є доказовою умовою; маємо {}".format(о2["стан"]))

# ── післядія ЗЗР за фактично внесеною речовиною
внесення = [{"речовина": "імазамокс", "рік": 2026, "дата": "2026-05-12"}]
о3 = р.оцінити("Соняшник", ІСТОРІЯ, 2027, внесення=внесення)
пд = механізми(о3, "післядія_ЗЗР")
перевірити("післядія знайшлась за назвою речовини", len(пд) == 1)
перевірити("післядія — дорадчий доказ, не попереднє правило",
           пд and пд[0]["клас"] == р.ДОКАЗ_ДОРАДЧИЙ,
           "маємо {}".format(пд[0]["клас"] if пд else None))
перевірити("в поясненні названо безпечний інтервал",
           пд and "12–24" in пд[0]["пояснення"])

# ── речовина, що цієї культури не обмежує, мовчить
о4 = р.оцінити("Кукурудза", ІСТОРІЯ, 2027, внесення=внесення)
перевірити("речовина не чіпає культуру, якої немає в її обмеженнях",
           not механізми(о4, "післядія_ЗЗР"),
           "імазамокс кукурудзу не обмежує")

# ── ВНЕСЕННЯ БЕЗ ДАТИ: невідомість, а не чистота
о5 = р.оцінити("Соняшник", ІСТОРІЯ, 2027, внесення=[{"речовина": "імазамокс"}])
пд5 = механізми(о5, "післядія_ЗЗР")
перевірити("внесення без дати не зникає", len(пд5) == 1)
перевірити("внесення без дати — НЕВІДОМО, а не безпечно",
           пд5 and пд5[0]["клас"] == р.НЕВІДОМО,
           "маємо {}".format(пд5[0]["клас"] if пд5 else None))

# ── ґрунт як підсилювач: імідазолінони шкодять за КИСЛОГО ґрунту
кисло = р.оцінити("Соняшник", ІСТОРІЯ, 2027, внесення=внесення, ґрунт={"pH": 5.9})
лужно = р.оцінити("Соняшник", ІСТОРІЯ, 2027, внесення=внесення, ґрунт={"pH": 7.4})
перевірити("на кислому ґрунті післядія імідазолінону підсилена",
           "шкодить сильніше" in механізми(кисло, "післядія_ЗЗР")[0]["пояснення"])
перевірити("на лужному ґрунті тієї примітки немає",
           "шкодить сильніше" not in механізми(лужно, "післядія_ЗЗР")[0]["пояснення"],
           "підсилювач не має спрацьовувати в обидва боки")

# ── коротке вікно історії: не знаємо ≠ чисто
коротке = {"2026": "Пшениця озима"}
о6 = р.оцінити("Соняшник", коротке, 2027)
інт6 = механізми(о6, "інтервал_повернення")
перевірити("коротке вікно історії дає НЕВІДОМО, а не тишу",
           інт6 and інт6[0]["клас"] == р.НЕВІДОМО,
           "маємо {}".format(інт6[0]["клас"] if інт6 else "нічого"))
перевірити("стан при короткому вікні — не_оцінено",
           о6["стан"] in (р.НЕ_ОЦІНЕНО, р.РИЗИК), "маємо {}".format(о6["стан"]))

# ── чиста пара мовчить
