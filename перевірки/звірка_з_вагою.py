# -*- coding: utf-8 -*-
"""Звірка карти з вагою господарства: чи не роздує вона карту на воду.

Причина, з якої ця перевірка існує. Г-03, кукурудза 2025. Господарство
назвало 12 128 кг/га. Карта на заліковій вологості 14 % показує 10 065.
Спокуса очевидна: помножити на 1,205 і сказати «звели з вагою».

Числа однакові, а причин дві, і вони протилежні:

  · число дано бункерною вагою при 27,5 % води — тоді на базисі 14 % воно
    є 10 226 кг/га, і монітор помилявся на 1,6 %, а не на 20 %;
  · число дано заліковою вагою — тоді монітор справді занижує, і причина
    в площі: він ділить масу на 6,00 м жатки, тоді як за прохід реально
    береться близько 5 м, бо проходи перекриваються.

На Г-03 правильною виявилась друга. Але **з самих чисел вони нерозрізненні**,
і саме тому програма не має права вибирати за людину.

Зелене: коли вологість числа названо, приведення робиться правильно.
Червоне: коли не названо — підгін мусить зупинитись, а не спрацювати.

**І окремий урок.** На Г-03 число господарства виявилось таки заліковим, а
збіг із вологою масою був випадковий: рівно таку саму різницю дає монітор,
який ділить на завелику ширину захвату. Тому ворота НЕ ставлять діагноз
«це бункерна вага» — вони кажуть, що двох причин не розрізнити, і питають.

Запуск:  runtime\\python.exe -X utf8 "перевірки\\звірка_з_вагою.py"
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.core import moisture

провал = []


def каже(умова, що):
    print(("  OK   " if умова else "  ПРОВАЛ ") + що)
    if not умова:
        провал.append(що)


class Журнал:
    def __init__(self):
        self.рядки = []

    def сказати(self, текст, *решта, **інше):
        self.рядки.append(текст)


# Справжні числа Г-03: вологість монітора, карта на базисі 14 %.
ВОЛОГІСТЬ_ПОЛЯ = 27.49
КАРТА = 10065.3
ФАКТ_БУНКЕР = 12.128          # т/га, як назвало господарство
N = 2000


def поле():
    return pd.DataFrame({
        "ВРОЖАЙ_БАЗ": np.full(N, КАРТА),
        "ВОЛОГІСТЬ": np.random.default_rng(7).normal(ВОЛОГІСТЬ_ПОЛЯ, 1.5, N),
        "QC": np.full(N, "OK"),
    })


def прогнати(паспорт):
    т = поле()
    ж = Журнал()
    т, звіт = moisture.звірити_з_вагою(т, паспорт, ж, середнє_по_площі=КАРТА)
    return т, звіт, ж.рядки


ОСНОВА = dict(базис=14.0, одиниця_факту="т/га", джерело_факту="вагова")

print("\n=== ЗЕЛЕНЕ: вологість числа названо ===")
т, звіт, _ = прогнати(dict(ОСНОВА, факт=ФАКТ_БУНКЕР, вологість_факту=ВОЛОГІСТЬ_ПОЛЯ))
каже(abs(звіт["ціль_кг_га"] - 10226) < 5,
     "12 128 кг/га при 27,49 %% води приведено до %.0f кг/га на базисі 14 %%"
     % звіт["ціль_кг_га"])
каже(abs(звіт["коефіцієнт"] - 1.016) < 0.005,
     "коефіцієнт ×%.4f — поправка 1,6 %%, а не 20 %%" % звіт["коефіцієнт"])
print("      " + str(звіт["про_ціль"]))

print("\n=== ЗЕЛЕНЕ: число вже на заліковій вологості ===")
т, звіт, _ = прогнати(dict(ОСНОВА, факт=10.226, вологість_факту=14.0))
каже(abs(звіт["ціль_кг_га"] - 10226) < 5, "число взято як є, без переведення")
каже(abs(звіт["коефіцієнт"] - 1.016) < 0.005,
     "той самий коефіцієнт ×%.4f — два шляхи сходяться" % звіт["коефіцієнт"])

print("\n=== ЧЕРВОНЕ: вологість не названо, число бункерне ===")
т, звіт, рядки = прогнати(dict(ОСНОВА, факт=ФАКТ_БУНКЕР))
каже(звіт["коефіцієнт"] == 1.0,
     "підгін НЕ застосовано (коефіцієнт ×%.3f)" % звіт["коефіцієнт"])
каже(float(т["ВРОЖАЙ_БАЗ"].iloc[0]) == КАРТА, "карта лишилась недоторканою")
каже(any("нерозрізненні" in з for з in звіт["застереження"]),
     "програма сказала, що не може розрізнити, і не вирішила за людину")
for з in звіт["застереження"]:
    print("      " + з)

print("\n=== ЧЕРВОНЕ: без цих воріт карту роздуло б ===")
роздуте = ФАКТ_БУНКЕР * 1000 / КАРТА
каже(роздуте > 1.15,
     "сліпий підгін дав би ×%.3f — це %.0f кг/га вигадки на кожному гектарі"
     % (роздуте, ФАКТ_БУНКЕР * 1000 - КАРТА))

print("\n=== ЗЕЛЕНЕ: чесна розбіжність повз ворота не проскакує ===")
# Число на заліковій вологості, монітор справді помилявся на 12 % —
# ворота на бункер не мають спрацювати, підгін мусить пройти.
т, звіт, _ = прогнати(dict(ОСНОВА, факт=11.273, вологість_факту=14.0))
каже(abs(звіт["коефіцієнт"] - 1.12) < 0.01,
     "справжній недооблік монітора підганяється: ×%.3f" % звіт["коефіцієнт"])

print("\n=== ЗЕЛЕНЕ: числа немає зовсім ===")
т, звіт, _ = прогнати(dict(базис=14.0))
каже(звіт["коефіцієнт"] == 1.0 and звіт["ціль_кг_га"] is None,
     "карта лишається відносною, як і було")

print("\n=== ЧЕРВОНЕ: одиниці переплутано ===")
т, звіт, _ = прогнати(dict(ОСНОВА, факт=12128, одиниця_факту="т/га",
                           вологість_факту=ВОЛОГІСТЬ_ПОЛЯ))
каже(звіт["коефіцієнт"] == 1.0,
     "12 128 т/га замість кг/га — підгін відхилено")
каже(any("занадто" in з for з in звіт["застереження"]),
     "і сказано чому")

print("\n" + ("=" * 60))
if провал:
    print("ПРОВАЛІВ: %d" % len(провал))
    for п in провал:
        print("  · " + п)
    sys.exit(1)
print("УСЕ ЧИСТО")
