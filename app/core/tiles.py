# Чому в цьому переліку немає Google. Їхні умови на плитки прямо забороняють
# кешувати й зберігати їх, показувати поза картою Google і використовувати
# для машинного аналізу зображення. Ми робимо все три речі: кладемо тло під
# власні шари на власному полотні, тримаємо плитки в кеші й возимо програму
# в поле без мережі. Питання не в ціні — за ціною Google дешевий.
БЕЗ_GOOGLE = ("плитки Google дозволено лише в їхньому SDK, без кешу й офлайну")

# Чесне представлення. Анонімний качальник — це те, за що OSM банить.
# **Тільки латиниця.** Заголовок HTTP кодується latin-1: кирилиця в
# User-Agent валить запит іще до того, як він вийде з машини. Те саме
# правило, що й для назв файлів, які їдуть на техніку.
ПРЕДСТАВЛЕННЯ = "FieldFactor/1.0 (agronomy consulting; portable desktop app)"

РОЗМІР_ПЛИТКИ = 256
МАКСИМУМ_ПЛИТОК = 96          # більше — це вже не поле, а район
ЧАС_ОЧІКУВАННЯ = 12


# ------------------------------------------------------------ геометрія плиток


def _плитка(довгота, широта, масштаб):
    рад = math.radians(широта)
    n = 2.0 ** масштаб
    x = (довгота + 180.0) / 360.0 * n
    y = (1.0 - math.log(math.tan(рад) + 1.0 / math.cos(рад)) / math.pi) / 2.0 * n
    return x, y


def _межі_плитки_3857(масштаб):
    """Розмір однієї плитки в метрах Web Mercator."""
    обхват = 2 * math.pi * 6378137.0
    return обхват / (2.0 ** масштаб)


def _підібрати_масштаб(межі_град, бажана_ширина_пікселів=1200):
    """Масштаб такий, щоб поле займало приблизно бажану ширину, і не більше."""
    захід, південь, схід, північ = межі_град
    for масштаб in range(19, 8, -1):
        x1, y1 = _плитка(захід, північ, масштаб)
        x2, y2 = _плитка(схід, південь, масштаб)
        плиток = (math.floor(x2) - math.floor(x1) + 1) * (math.floor(y2) - math.floor(y1) + 1)
        пікселів = abs(x2 - x1) * РОЗМІР_ПЛИТКИ
        if плиток <= МАКСИМУМ_ПЛИТОК and пікселів <= бажана_ширина_пікселів * 1.6:
            return масштаб
    return 12


# ------------------------------------------------------------ качання й кеш


def _шлях_кешу(база, джерело, масштаб, x, y):
    тека = os.path.join(база, "кеш_плиток", джерело, str(масштаб), str(x))
    os.makedirs(тека, exist_ok=True)
    return os.path.join(тека, "{}.png".format(y))


def ключі(база):
    """Ключі доступу до платних джерел. Лежать у налаштуваннях програми,
    не в коді: ключ — це рахунок Власника, і в git він не потрапляє."""
    from app.core import settings

    налаштування = settings.прочитати(база) or {}
    карти = налаштування.get("карти") or {}
    return {"mapbox": (карти.get("ключ_mapbox") or "").strip(),
            "maptiler": (карти.get("ключ_maptiler") or "").strip()}


def перелік(база):
    """Джерела для екрана: які є, які доступні, і чому саме це джерело."""
    наявні = ключі(база)
    зібране = []
    for ключ, опис in ДЖЕРЕЛА.items():
        треба = опис.get("ключ")
        зібране.append({
            "ключ": ключ,
            "підпис": опис["підпис_джерела"],
            "чому": опис.get("чому", ""),
            "потрібен_ключ": треба,
            "доступне": (треба is None) or bool(наявні.get(треба)),
        })
    return зібране


def _взяти_плитку(база, джерело, масштаб, x, y):
    шлях = _шлях_кешу(база, джерело, масштаб, x, y)
    if os.path.isfile(шлях) and os.path.getsize(шлях) > 0:
        with open(шлях, "rb") as ф:
            return ф.read()
    опис = ДЖЕРЕЛА[джерело]
    потрібен = опис.get("ключ")
    ключ_доступу = ключі(база).get(потрібен, "") if потрібен else ""
    if потрібен and not ключ_доступу:
        raise RuntimeError("для «{}» потрібен ключ {} — заведіть його в налаштуваннях"
                           .format(опис["підпис_джерела"], потрібен))
    адреса = опис["адреса"].format(z=масштаб, x=x, y=y, ключ=ключ_доступу)
    запит = urllib.request.Request(адреса, headers={"User-Agent": ПРЕДСТАВЛЕННЯ})
    with urllib.request.urlopen(запит, timeout=ЧАС_ОЧІКУВАННЯ) as відповідь:
        дані = відповідь.read()
    with open(шлях, "wb") as ф:
        ф.write(дані)
    return дані


def _розібрати_png(дані):
    """PNG/JPEG → масив RGB. Без Pillow не обійтись, і це не біда: він уже
    стоїть у рантаймі заради звіту."""
    import io
    from PIL import Image

    зображення = Image.open(io.BytesIO(дані)).convert("RGB")
    return np.asarray(зображення, dtype="uint8")


# ------------------------------------------------------------ головне


def підкладка(контур, тека_виводу, база, джерело="супутник", запас=0.12):
    """Плитки під полем, перепроєктовані в метричну CRS поля.

    Повертає той самий вигляд, що й супутникова підкладка зі знімка:
    `{файл, межі, підпис}` — карта на екрані не мусить знати, звідки картинка.
    Не вийшло (немає інтернету, джерело мовчить) — повертає None, і поле
    просто лишається без тла.
    """
    from rasterio.transform import from_origin
    from rasterio.warp import Resampling, reproject

    якщо = ДЖЕРЕЛА.get(джерело)
    if якщо is None:
        return None

    у_градусах = контур.to_crs(4326)
    захід, південь, схід, північ = у_градусах.total_bounds
    ш, в = схід - захід, північ - південь
    захід, схід = захід - ш * запас, схід + ш * запас
    південь, північ = південь - в * запас, північ + в * запас

    масштаб = _підібрати_масштаб((захід, південь, схід, північ))
    x1, y1 = _плитка(захід, північ, масштаб)
    x2, y2 = _плитка(схід, південь, масштаб)
    x_від, x_до = int(math.floor(x1)), int(math.floor(x2))
    y_від, y_до = int(math.floor(y1)), int(math.floor(y2))

    стовпців = x_до - x_від + 1
    рядків = y_до - y_від + 1
    if стовпців * рядків > МАКСИМУМ_ПЛИТОК:
        return None

    полотно = np.zeros((рядків * РОЗМІР_ПЛИТКИ, стовпців * РОЗМІР_ПЛИТКИ, 3), dtype="uint8")
    здобуто = 0
    # Причина першого збою запамʼятовується й доїжджає до екрана. Мовчазне
    # «не вийшло» коштувало тут пів години: качалка падала на кирилиці в
    # заголовку, а програма показувала просто порожнє тло.
    причина = ""
    for сх in range(стовпців):
        for ря in range(рядків):
            try:
                дані = _взяти_плитку(база, джерело, масштаб, x_від + сх, y_від + ря)
                картинка = _розібрати_png(дані)
            except Exception as збій:
                причина = причина or "{}: {}".format(type(збій).__name__, збій)
                continue
            if картинка.shape[0] != РОЗМІР_ПЛИТКИ or картинка.shape[1] != РОЗМІР_ПЛИТКИ:
                continue
            полотно[ря * РОЗМІР_ПЛИТКИ:(ря + 1) * РОЗМІР_ПЛИТКИ,
                    сх * РОЗМІР_ПЛИТКИ:(сх + 1) * РОЗМІР_ПЛИТКИ] = картинка
            здобуто += 1

    # Половина плиток — це вже дірява карта, і краще чесно не показати нічого,
    # ніж показати поле на клаптях.
    if здобуто < стовпців * рядків * 0.5:
        return {"помилка": причина or "джерело плиток не відповідає",
                "здобуто": здобуто, "треба": стовпців * рядків}

    крок = _межі_плитки_3857(масштаб) / РОЗМІР_ПЛИТКИ
    обхват = 2 * math.pi * 6378137.0
    ліво = -обхват / 2 + x_від * _межі_плитки_3857(масштаб)
    верх = обхват / 2 - y_від * _межі_плитки_3857(масштаб)
    джерельне = from_origin(ліво, верх, крок, крок)

    # ── у метричну CRS поля: карта малює в метрах, а не в градусах
    межі = контур.total_bounds
    ш_м, в_м = межі[2] - межі[0], межі[3] - межі[1]
    xmin, ymin = межі[0] - ш_м * запас, межі[1] - в_м * запас
    xmax, ymax = межі[2] + ш_м * запас, межі[3] + в_м * запас
    крок_цілі = max((xmax - xmin) / 1400.0, 0.25)
    ширина = max(1, int(math.ceil((xmax - xmin) / крок_цілі)))
    висота = max(1, int(math.ceil((ymax - ymin) / крок_цілі)))
    ціль_перетворення = from_origin(xmin, ymax, крок_цілі, крок_цілі)

    вихід = np.zeros((висота, ширина, 3), dtype="uint8")
    for смуга in range(3):
        приймач = np.zeros((висота, ширина), dtype="uint8")
        reproject(source=полотно[:, :, смуга], destination=приймач,
                  src_transform=джерельне, src_crs="EPSG:3857",
                  dst_transform=ціль_перетворення, dst_crs=контур.crs,
                  resampling=Resampling.bilinear)
        вихід[:, :, смуга] = приймач

    from app.core import render

    os.makedirs(тека_виводу, exist_ok=True)
    імʼя = "підкладка_{}.png".format(джерело)
    render.записати_png(os.path.join(тека_виводу, імʼя), вихід)
    return {
        "файл": імʼя,
        # float(), а не numpy: json такого типу не знає й падає вже на віддачі
        "межі": [float(xmin), float(ymin), float(xmax), float(ymax)],
        "підпис": якщо["підпис"],
        "джерело": джерело,
        "масштаб": масштаб,
        "плиток": здобуто,
    }


def ключ_кешу(контур, джерело):
    межі = tuple(round(з, 1) for з in контур.total_bounds)
    основа = "{}|{}".format(джерело, межі)
    return hashlib.md5(основа.encode("utf-8")).hexdigest()[:16]
