# -*- coding: utf-8 -*-
"""Очистка електропровідності від слідів техніки.

EC міряє не лише ґрунт. Вона реагує на ущільнення, на колію, на розворотну
смугу, на свіжий обробіток — на все, що зробила машина. Такі сліди лягають
вузькими смугами й плямами, і якщо пустити їх у зонування, поле буде порізане
по маршруту трактора, а не по ґрунту. Потім із цими зонами доведеться щось
робити, і винен буде агроном.

Метод у трьох кроках:

1. **Своя околиця.** Від EC віднімається її ж місцевий фон. Лишається те,
   чим клітинка відрізняється від сусідів — саме там і живуть сліди.

2. **Свідки пояснюють, скільки можуть.** Рельєф і вегетація не «підтверджують»
   аномалію просто тим, що там теж щось коливається. Вони підганяються до
   залишку EC кількісно, і законною вважається лише та його частина, яку вони
   справді пояснюють. Западина має право робити EC вищою; смуга через усе поле,
   якої не видно ні в рельєфі, ні в покриві чотири роки поспіль, — не має.

3. **Вузьке — підозріліше за широке.** Ґрунт не буває смугастим завширшки з
   колію. Те, що зникає від морфологічного відкриття, отримує окремий штраф.

Знята частина не викидається: на її місце стає фон плюс те, що пояснили
свідки. Скільки й де знято — пишеться у звіт.
"""

import numpy as np

ПОРІГ_АНОМАЛІЇ = 3.0          # у робастних розкидах непоясненого залишку
ШИРИНА_СЛІДУ_М = 24.0         # ширше за це вже не схоже на колію


def _медіанний_фон(поверхня, розмір):
    from scipy.ndimage import median_filter

    добрі = np.isfinite(поверхня)
    заповнена = np.where(добрі, поверхня, np.nanmedian(поверхня[добрі]) if добрі.any() else 0.0)
    return median_filter(заповнена, size=int(max(3, розмір)))


def _розкид(значення):
    розкид = float(np.median(np.abs(значення - np.median(значення)))) * 1.4826
    if розкид <= 1e-9:
        розкид = float(np.std(значення)) or 1.0
    return розкид


def _пояснення_свідками(залишок_ec, свідки, поле, розмір):
    """Скільки із залишку EC справді пояснюють рельєф і вегетація.

    Не «чи коливається свідок», а «наскільки його коливання відтворює саме це
    коливання EC». Підганяється звичайним найменшим квадратом по всьому полю.
    """
    стовпці, назви = [], []
    for імʼя, поверхня in (свідки or {}).items():
        if поверхня is None:
            continue
        залишок = поверхня - _медіанний_фон(поверхня, розмір)
        значення = залишок[поле]
        if not np.isfinite(значення).all() or _розкид(значення) <= 1e-9:
            continue
        стовпці.append(залишок)
        назви.append(імʼя)
    if not стовпці:
        return np.zeros_like(залишок_ec), []

    матриця = np.column_stack([с[поле] for с in стовпці])
    матриця = np.column_stack([матриця, np.ones(матриця.shape[0])])
    ціль = залишок_ec[поле]
    коефіцієнти, *_ = np.linalg.lstsq(матриця, ціль, rcond=None)

    пояснене = np.zeros_like(залишок_ec)
    for коефіцієнт, шар in zip(коефіцієнти[:-1], стовпці):
        пояснене += коефіцієнт * шар
    пояснене += коефіцієнти[-1]

    внески = []
    загальна = float(np.var(ціль)) or 1.0
    for і, імʼя in enumerate(назви):
        окремо = коефіцієнти[і] * стовпці[і][поле]
        внески.append({"свідок": імʼя,
                       "пояснив_відсотків": round(
                           max(0.0, float(np.cov(окремо, ціль)[0, 1]) / загальна) * 100, 1)})
    return пояснене, внески


def почистити(ec, поле, крок, свідки=None, ширина_розворотної=18.0, журнал=None,
              назва="EC"):
    """Повертає (очищена поверхня, звіт)."""
    from scipy.ndimage import binary_dilation, distance_transform_edt, grey_opening

    розмір = max(3, int(round(70.0 / крок)))
    ec = np.asarray(ec, dtype="float32")
    фон = _медіанний_фон(ec, розмір)
    залишок = np.where(np.isfinite(ec), ec - фон, 0.0)

    пояснене, внески = _пояснення_свідками(залишок, свідки, поле, розмір)
    непояснене = залишок - пояснене
    розкид = _розкид(непояснене[поле])

    підозрілі = (np.abs(непояснене) > ПОРІГ_АНОМАЛІЇ * розкид) & поле

    # вузьке зникає від відкриття — це слід, а не ґрунтова пляма
    ядро = max(3, int(round(ШИРИНА_СЛІДУ_М / крок)) | 1)
    широке = grey_opening(np.abs(непояснене), size=ядро)
    вузькі = (np.abs(непояснене) - широке > ПОРІГ_АНОМАЛІЇ * розкид * 0.6) & поле

    відстань = distance_transform_edt(поле) * крок
    край = поле & (відстань < ширина_розворотної)

    артефакти = binary_dilation(підозрілі | вузькі, iterations=1) & поле
    артефакти |= край & (np.abs(непояснене) > ПОРІГ_АНОМАЛІЇ * розкид * 0.6)

    очищена = ec.copy()
    очищена[артефакти] = (фон + пояснене)[артефакти]

    площа = float(поле.sum()) or 1.0
    звіт = {
        "шар": назва,
        "підозрілих_відсотків": round(float(підозрілі.sum()) / площа * 100, 1),
        "вузьких_відсотків": round(float(вузькі.sum()) / площа * 100, 1),
        "знято_відсотків": round(float(артефакти.sum()) / площа * 100, 1),
        "край_відсотків": round(float((край & артефакти).sum()) / площа * 100, 1),
        "свідки": внески,
    }

    if журнал:
        журнал.сказати(
            "  {}: знято {:.1f} % площі як слід техніки — з них вузькі смуги "
            "{:.1f} %, розворотна смуга {:.1f} %".format(
                назва, звіт["знято_відсотків"], звіт["вузьких_відсотків"],
                звіт["край_відсотків"]))
        for в in внески:
            журнал.сказати("    {} пояснює {:.0f} % коливань EC".format(
                в["свідок"], в["пояснив_відсотків"]))
        if звіт["знято_відсотків"] > 15:
            журнал.сказати("    УВАГА: знято більше шостої частини поля. Перевірте, "
                           "чи не робилось сканування по свіжому обробітку.")
    return очищена, звіт
