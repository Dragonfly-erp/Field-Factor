"""Фази 9 і 12: чим саме заповнювати пропуски і наскільки цьому вірити.

Перевірка тут навмисне сувора. Випадковий поділ точок на «навчити/перевірити»
для карти врожайності — самообман: сусідні точки одного проходу майже
однакові, тож будь-яка модель покаже блискучий результат. Тому перевіряємо
двома чесними способами: блоками поля і схованими цілими проходами.
"""

import numpy as np


# ------------------------------------------------------------ анізотропія


def _повернути(x, y, напрямок, розтяг):
    """Координати в системі проходу: уздовж — стиснуто, впоперек — ні."""
    к, с = np.cos(-напрямок), np.sin(-напрямок)
    уздовж = x * к - y * с
    впоперек = x * с + y * к
    return np.c_[уздовж / розтяг, впоперек]


class ЛокальнаМодель:
    """Зважене середнє сусідів із урахуванням напрямку проходу."""

    назва = "локальна"

    def __init__(self, напрямок=0.0, розтяг=3.0, сусідів=12, степінь=2.0):
        self.напрямок = напрямок
        self.розтяг = розтяг
        self.сусідів = сусідів
        self.степінь = степінь
        self._дерево = None

    def навчити(self, x, y, z, ознаки=None):
        from scipy.spatial import cKDTree

        self._z = np.asarray(z, dtype="float64")
        self._дерево = cKDTree(_повернути(np.asarray(x), np.asarray(y),
                                          self.напрямок, self.розтяг))
        return self

    def передбачити(self, x, y, ознаки=None):
        к = min(self.сусідів, len(self._z))
        відстані, сусіди = self._дерево.query(
            _повернути(np.asarray(x), np.asarray(y), self.напрямок, self.розтяг), k=к
        )
        if к == 1:
            відстані = відстані[:, None]
            сусіди = сусіди[:, None]
        ваги = 1.0 / np.maximum(відстані, 0.25) ** self.степінь
        значення = np.sum(ваги * self._z[сусіди], axis=1) / np.sum(ваги, axis=1)
        return значення


class МодельЗПредикторами:
    """Ліс по супутнику й рельєфу, а поверх нього — локальна поправка залишків."""

    назва = "супутник+залишок"

    def __init__(self, напрямок=0.0, розтяг=3.0, дерев=180):
        self.напрямок = напрямок
        self.розтяг = розтяг
        self.дерев = дерев
        self._ліс = None
        self._залишки = None

    def навчити(self, x, y, z, ознаки=None):
        from sklearn.ensemble import RandomForestRegressor

        матриця = np.asarray(ознаки, dtype="float64")
        матриця = np.nan_to_num(матриця, nan=0.0, posinf=0.0, neginf=0.0)
        self._ліс = RandomForestRegressor(
            n_estimators=self.дерев, min_samples_leaf=8, max_features="sqrt",
            n_jobs=-1, random_state=17,
        ).fit(матриця, z)
        залишок = np.asarray(z, dtype="float64") - self._ліс.predict(матриця)
        self._залишки = ЛокальнаМодель(self.напрямок, self.розтяг).навчити(x, y, залишок)
        return self

    def передбачити(self, x, y, ознаки=None):
        матриця = np.nan_to_num(np.asarray(ознаки, dtype="float64"),
                                nan=0.0, posinf=0.0, neginf=0.0)
        return self._ліс.predict(матриця) + self._залишки.передбачити(x, y)


class ЛишеПредиктори(МодельЗПредикторами):
    назва = "лише супутник"

    def навчити(self, x, y, z, ознаки=None):
        from sklearn.ensemble import RandomForestRegressor

        матриця = np.nan_to_num(np.asarray(ознаки, dtype="float64"), nan=0.0)
        self._ліс = RandomForestRegressor(
            n_estimators=self.дерев, min_samples_leaf=8, max_features="sqrt",
            n_jobs=-1, random_state=17,
        ).fit(матриця, z)
        self._залишки = None
        return self

    def передбачити(self, x, y, ознаки=None):
        матриця = np.nan_to_num(np.asarray(ознаки, dtype="float64"), nan=0.0)
        return self._ліс.predict(матриця)


# ------------------------------------------------------------ перевірка


def _блоки(x, y, розмір):
    return (np.floor(x / розмір).astype("int64") * 100003
            + np.floor(y / розмір).astype("int64"))


def _похибка(факт, прогноз):
    добрі = np.isfinite(факт) & np.isfinite(прогноз)
    if добрі.sum() < 10:
        return None
    п = прогноз[добрі] - факт[добрі]
    зв = float(np.corrcoef(факт[добрі], прогноз[добрі])[0, 1]) if добрі.sum() > 20 else float("nan")
    return {
        "MAE": float(np.mean(np.abs(п))),
        "RMSE": float(np.sqrt(np.mean(п ** 2))),
        "зсув": float(np.mean(п)),
        "звʼязок": зв,
        "перевірено_точок": int(добрі.sum()),
    }


def перевірити_блоками(модель_фабрика, x, y, z, ознаки, розмір_блоку, частин=5):
    """Ховаємо цілі шматки поля, не окремі точки."""
    блоки = _блоки(x, y, розмір_блоку)
    унікальні = np.unique(блоки)
    if унікальні.size < частин * 2:
        return None
    порядок = np.random.RandomState(11).permutation(унікальні)
    групи = np.array_split(порядок, частин)

    прогноз = np.full(len(z), np.nan)
    for група in групи:
        сховані = np.isin(блоки, група)
        якщо_вчити = ~сховані
        if якщо_вчити.sum() < 100 or сховані.sum() < 20:
            continue
        модель = модель_фабрика()
        модель.навчити(x[якщо_вчити], y[якщо_вчити], z[якщо_вчити],
                       None if ознаки is None else ознаки[якщо_вчити])
        прогноз[сховані] = модель.передбачити(
            x[сховані], y[сховані], None if ознаки is None else ознаки[сховані]
        )
    return _похибка(z, прогноз)


def перевірити_проходами(модель_фабрика, x, y, z, ознаки, проходи, частка=0.2):
    """Ховаємо цілі проходи — це і є справжній пропуск смуги."""
    унікальні = np.unique(проходи)
    if унікальні.size < 8:
        return None
    генератор = np.random.RandomState(23)
    сховані_проходи = генератор.choice(
        унікальні, size=max(2, int(len(унікальні) * частка)), replace=False
    )
    сховані = np.isin(проходи, сховані_проходи)
    if сховані.sum() < 30 or (~сховані).sum() < 100:
        return None

    модель = модель_фабрика()
    модель.навчити(x[~сховані], y[~сховані], z[~сховані],
                   None if ознаки is None else ознаки[~сховані])
    прогноз = модель.передбачити(
        x[сховані], y[сховані], None if ознаки is None else ознаки[сховані]
    )
    return _похибка(z[сховані], прогноз)


def перевірити_дірками(модель_фабрика, x, y, z, ознаки, радіус, дірок=8):
    """Ховаємо суцільні круглі ділянки — саме такі, як реальні пропуски.

    Це не те саме, що сховати прохід. У схованому проході опора лишається
    з обох боків за пів метра, і локальне усереднення виглядає геніальним.
    А в дірці на п'ять гектарів опори немає взагалі, і видно, хто справді
    щось знає про це місце, а хто просто розмазує край.
    """
    from scipy.spatial import cKDTree

    if len(z) < 400:
        return None
    дерево = cKDTree(np.c_[x, y])
    генератор = np.random.RandomState(31)
    центри = генератор.choice(len(z), size=min(дірок * 4, len(z)), replace=False)

    факт, прогноз = [], []
    використано = 0
    for центр in центри:
        if використано >= дірок:
            break
        всередині = np.zeros(len(z), dtype=bool)
        всередині[дерево.query_ball_point([x[центр], y[центр]], r=радіус)] = True
        if всередині.sum() < 25 or (~всередині).sum() < 300:
            continue
        модель = модель_фабрика()
        модель.навчити(x[~всередині], y[~всередині], z[~всередині],
                       None if ознаки is None else ознаки[~всередині])
        значення = модель.передбачити(
            x[всередині], y[всередині], None if ознаки is None else ознаки[всередині]
        )
        факт.append(z[всередині])
        прогноз.append(значення)
        використано += 1

    if використано < 3:
        return None
    підсумок = _похибка(np.concatenate(факт), np.concatenate(прогноз))
    if підсумок:
        підсумок["дірок"] = використано
        підсумок["радіус_м"] = round(float(радіус), 1)
    return підсумок


def _кандидати(ознаки, напрямок):
    список = [
        ("локальна", lambda: ЛокальнаМодель(напрямок, 1.0), None),
        ("локальна витягнута", lambda: ЛокальнаМодель(напрямок, 3.0), None),
    ]
    if ознаки is not None and ознаки.shape[1] > 0:
        список.append(("вегетація + залишок", lambda: МодельЗПредикторами(напрямок, 3.0), ознаки))
        список.append(("лише вегетація", lambda: ЛишеПредиктори(напрямок, 3.0), ознаки))
    return список


def обрати_методи(x, y, z, ознаки, проходи, напрямок, ширина, радіус_дірки, журнал):
    """Фаза 9. Два різні питання — і два різні відповіді.

    Короткий розрив усередині проходу і порожній масив на п'ять гектарів —
    це не одна задача. Для першого сусідні записи знають усе; для другого
    вони не знають нічого, і працює тільки те, що бачило це місце згори.
    Тому метод обирається окремо для кожного випадку.
    """
    розмір_блоку = max(60.0, ширина * 8)
    результати = []

    журнал.сказати("  міряю на близьких розривах і окремо — на дірках "
                   "радіусом {:.0f} м".format(радіус_дірки))
    for назва, фабрика, свої in _кандидати(ознаки, напрямок):
        блоками = перевірити_блоками(фабрика, x, y, z, свої, розмір_блоку)
        проходами = перевірити_проходами(фабрика, x, y, z, свої, проходи)
        дірками = перевірити_дірками(фабрика, x, y, z, свої, радіус_дірки)

        близькі = [р["MAE"] for р in (блоками, проходами) if р]
        результати.append({
            "метод": назва,
            "MAE_близькі": float(np.mean(близькі)) if близькі else None,
            "MAE_дірки": дірками["MAE"] if дірками else None,
            "блоками": блоками, "проходами": проходами, "дірками": дірками,
            "_фабрика": фабрика, "_ознаки": свої,
        })
        журнал.сказати("    {:<22} близькі {:>6}   дірки {:>6}".format(
            назва,
            "{:.0f}".format(результати[-1]["MAE_близькі"]) if близькі else "—",
            "{:.0f}".format(дірками["MAE"]) if дірками else "—"))

    def найкращий(ключ):
        придатні = [р for р in результати if р[ключ] is not None]
        return min(придатні, key=lambda р: р[ключ]) if придатні else результати[0]

    для_близьких = найкращий("MAE_близькі")
    для_великих = найкращий("MAE_дірки")

    висновки = []
    з_вегетацією = [р for р in результати if р["_ознаки"] is not None]
    без_вегетації = [р for р in результати if р["_ознаки"] is None
                     and р["MAE_дірки"] is not None]

    if not з_вегетацією:
        висновки.append(
            "Вегетаційних знімків у роботі не було, тож великі ділянки відновлені "
            "лише за геометрією проходів і сусідніми записами. Це найслабше місце "
            "цієї карти: перевірка на дірках дала {} кг/га проти {} кг/га на "
            "близьких розривах.".format(
                "{:.0f}".format(для_великих["MAE_дірки"]) if для_великих["MAE_дірки"] else "—",
                "{:.0f}".format(для_близьких["MAE_близькі"]) if для_близьких["MAE_близькі"] else "—")
        )
    elif для_великих["_ознаки"] is not None and без_вегетації:
        краще_без = min(без_вегетації, key=lambda р: р["MAE_дірки"])
        виграш = (краще_без["MAE_дірки"] - для_великих["MAE_дірки"]) / краще_без["MAE_дірки"] * 100
        висновки.append(
            "На ділянках без опори вегетація зменшила похибку на {:.0f} % "
            "({:.0f} → {:.0f} кг/га), тому саме нею вони й закриті.".format(
                виграш, краще_без["MAE_дірки"], для_великих["MAE_дірки"])
        )
    elif для_великих["_ознаки"] is None and з_вегетацією:
        висновки.append(
            "Вегетація не дала переваги навіть на дірках, тож великі ділянки "
            "закриті геометрією проходів. Довіра до них лишається зниженою."
        )

    журнал.сказати("  близькі розриви — {}; великі ділянки — {}.".format(
        для_близьких["метод"], для_великих["метод"]))
    for в in висновки:
        журнал.сказати("  " + в)
    return для_близьких, для_великих, результати, висновки


# ------------------------------------------------------------ довіра


def довіра(відстань_до_опори, ширина, клас=None):
    """HIGH / MED / LOW за тим, скільки реальних записів поруч.

    Клас пропуску б'є відстань: точка посеред п'ятигектарної діри не буває
    надійною, навіть якщо випадково опинилась поруч із краєм.
    """
    мітки = np.full(len(відстань_до_опори), "LOW", dtype=object)
    мітки[відстань_до_опори <= ширина * 2.5] = "MED"
    мітки[відстань_до_опори <= ширина * 1.2] = "HIGH"
    if клас is not None:
        клас = np.asarray(клас)
        мітки[np.isin(клас, ("C", "D")) & (мітки == "HIGH")] = "MED"
        мітки[клас == "D"] = "LOW"
    return мітки
