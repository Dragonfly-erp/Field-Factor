import json
import os
import re

БАЗА = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ДОВІДНИКИ = os.path.join(БАЗА, "довідники_ротації")

# ── класи доказовості й що вони мають право робити в runtime
ДОКАЗ_ТВЕРДИЙ = "доказ_твердий"
ДОКАЗ_ДОРАДЧИЙ = "доказ_дорадчий"
ПОПЕРЕДНІЙ = "попередній"
