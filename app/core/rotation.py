def корінь(культура):
    """Культура зведена до кореня. Невідоме лишається як є — вигадувати
    для нього корінь означало б тихо приписати чужі правила."""
    н = re.sub(r"\s+", " ", str(культура or "").strip().lower())
    if not н:
        return None
    for ключ, слова in КОРЕНІ:
        for с in слова:
            if с in н:
                return ключ
    return н


_кеш = {}


def _довідник(імʼя, читач):
    if імʼя not in _кеш:
        шлях = os.path.join(ДОВІДНИКИ, імʼя)
        _кеш[імʼя] = читач(шлях) if os.path.isfile(шлях) else None
    return _кеш[імʼя]


def інтервали():
    """Мінімальний інтервал повернення за курованою таблицею.

    Статус ПОПЕРЕДНІЙ: число підпису не має. Поруч тримаємо зовнішнє
    число з extension — щоб на екрані було видно ДІАПАЗОН, а не одне
    число, яке вдає точність.
    """
    def читач(шлях):
        with open(шлях, encoding="utf-8") as ф:
            таблиця = {}
            for рядок in csv.DictReader(ф):
                к = корінь(рядок.get("crop"))
                if not к:
                    continue
                таблиця[к] = {
                    "років_куровано": _ціле(рядок.get("minReturnYears")),
                    "причина": (рядок.get("reason") or "").strip(),
                    "погані_попередники": [корінь(ч) for ч in
                                           (рядок.get("forbiddenPredecessors") or "").split(";")
                                           if ч.strip()],
                    "добрі_попередники": [корінь(ч) for ч in
                                          (рядок.get("recommendedPredecessors") or "").split(";")
                                          if ч.strip()],
                    "нотатка": (рядок.get("notes") or "").strip(),
                    "N_після": _ціле(рядок.get("nCreditsAfter")),
                }
            return таблиця
    return _довідник("інтервали_повернення.csv", читач) or {}


# Зовнішнє, незалежне від курованої таблиці. Джерела названі у шапці
# модуля. Там, де зовнішнє й куроване розходяться, показуємо обидва:
# розбіжність — це теж знання про те, наскільки число тверде.
ІНТЕРВАЛ_EXTENSION = {
    "соняшник": (3, "SDSU Extension · Sclerotinia Concerns in Sunflower"),
    "ріпак": (3, "Canola Council of Canada · Crop rotation (раз на 2–3 роки)"),
}


def матриця():
    """Пара «попередник → наступник» із вердиктом курованої таблиці."""
    def читач(шлях):
        with open(шлях, encoding="utf-8") as ф:
            таблиця = {}
            for рядок in csv.DictReader(ф):
                п, н = корінь(рядок.get("predecessor")), корінь(рядок.get("successor"))
                if not п or not н:
                    continue
                таблиця[(п, н)] = {"рівень": (рядок.get("level") or "").strip(),
                                   "причина": (рядок.get("reason") or "").strip()}
            return таблиця
    return _довідник("матриця_сумісності.csv", читач) or {}


def післядія():
    """Каталог післядії ЗЗР: діюча речовина → чутливі наступні культури."""
    def читач(шлях):
        with open(шлях, encoding="utf-8") as ф:
            дані = json.load(ф)
        за_речовиною = {}
        for рядок in дані.get("rows") or []:
            назва = (рядок.get("name_ua") or "").strip().lower()
            if назва:
                за_речовиною[назва] = рядок
        return {"рядки": за_речовиною, "джерело": дані.get("source"),
                "примітка": дані.get("note")}
    return _довідник("післядія_ЗЗР.json", читач) or {"рядки": {}}


def _ціле(значення):
    try:
        return int(float(str(значення).strip()))
    except (TypeError, ValueError):
        return None


def причина(механізм, клас, пояснення, джерело, число=None):
    """Один названий механізм. Саме з таких складається відповідь —
    замість бала, який ховає, що саме сталось на полі."""
    return {"механізм": механізм, "клас": клас, "наслідок": НАСЛІДОК[клас],
            "пояснення": пояснення, "джерело": джерело, "число": число}


# ═════════════════════════════════════════════════════════ ОЦІНКА КАНДИДАТА

def _останній_рік(історія):
    роки = [_ціле(р) for р in (історія or {}) if _ціле(р)]
    return max(роки) if роки else None


def інтервал_повернення(культура, історія, рік):
    """Скільки років минуло, відколи ця культура була тут востаннє.

    Повертає (років, рік_коли_була). `None` означає, що у вікні історії
    її немає — але це НЕ те саме, що «давно не було»: вікно може бути
    коротшим за правило, і тоді ми просто не знаємо.
    """
    к = корінь(культура)
    роки = sorted((_ціле(р) for р in (історія or {}) if _ціле(р)), reverse=True)
    for р in роки:
        if р >= рік:
            continue
        if корінь((історія.get(str(р)) or історія.get(р) or {}).get("культура")
                  if isinstance(історія.get(str(р)) or історія.get(р), dict)
                  else (історія.get(str(р)) or історія.get(р))) == к:
            return рік - р, р
    return None, None


def оцінити(культура, історія, рік, внесення=None, ґрунт=None):
    """Що станеться, якщо посіяти цю культуру тут наступного року.

    `історія`  {рік: культура} або {рік: {"культура": ...}} — як віддає сітка;
    `внесення` перелік {"речовина": ..., "рік": ..., "дата": ...} з історії захисту;
    `ґрунт`    {"pH": ..., "орг_речовина": ...} з аналізів поля.

    Повертає стан і ПЕРЕЛІК названих причин. Стан — найсуворіший із
    наслідків: один СТОП робить стоп усьому, скільки б добрих ознак не
    було поруч. Гроші цього не перекривають — так підписано.
    """
    к = корінь(культура)
    причини = []

    # ── 1. Попередник: що стояло тут торік
    попередник = None
    минулий = історія.get(str(рік - 1)) or історія.get(рік - 1)
    if isinstance(минулий, dict):
        минулий = минулий.get("культура")
    попередник = корінь(минулий)

    if попередник:
        пара = матриця().get((попередник, к))
        if пара:
            рівень = пара["рівень"]
            if рівень == "forbidden":
                # Куроване «forbidden» — це НЕ заборона в нашому runtime:
                # підписано, що ідентичність культури сама по собі твердою
                # умовою не є. Показуємо як ризик, названий поіменно.
                причини.append(причина(
                    "попередник", ПОПЕРЕДНІЙ,
                    "після «{}» — {}".format(минулий, пара["причина"] or "погана пара"),
                    "курована матриця сумісності · знімок agroplace-weather"))
            elif рівень == "caution":
                причини.append(причина(
                    "попередник", ПОПЕРЕДНІЙ,
                    "після «{}» — {}".format(минулий, пара["причина"] or "обережно"),
                    "курована матриця сумісності · знімок agroplace-weather"))
        else:
            причини.append(причина(
                "попередник", НЕВІДОМО,
                "пари «{} → {}» у матриці немає".format(попередник, к),
                "межа покриття довідника, а не висновок про поле"))

    # ── 2. Інтервал повернення
    правило = інтервали().get(к) or {}
    треба_куровано = правило.get("років_куровано")
    треба_extension, джерело_ext = ІНТЕРВАЛ_EXTENSION.get(к, (None, None))
    минуло, коли = інтервал_повернення(культура, історія, рік)

    if треба_куровано or треба_extension:
        пороги = [п for п in (треба_куровано, треба_extension) if п]
        найменший, найбільший = min(пороги), max(пороги)
        if минуло is None:
            # Культури у вікні немає. Якщо вікно коротше за правило —
            # це невідомість, а не чистота поля.
            вікно = рік - min(_ціле(р) for р in історія if _ціле(р)) if історія else 0
            if вікно < найбільший:
                причини.append(причина(
                    "інтервал_повернення", НЕВІДОМО,
                    "у видимих {} роках цієї культури немає, але правило говорить "
                    "про {}–{} років — глибша історія невідома".format(
                        вікно, найменший, найбільший),
                    "вікно історії коротше за правило"))
        elif минуло < найменший:
            причини.append(причина(
                "інтервал_повернення", ПОПЕРЕДНІЙ,
                "була тут у {} — минуло {} р., а перерва рекомендується {}–{} р. "
                "({})".format(коли, минуло, найменший, найбільший,
                              правило.get("причина") or "ґрунтовий інокулюм"),
                джерело_ext or "курована таблиця інтервалів", число=минуло))
        elif минуло < найбільший:
            причини.append(причина(
                "інтервал_повернення", ПОПЕРЕДНІЙ,
                "була тут у {} — минуло {} р.; extension вважає це достатнім, "
                "курована таблиця просить {} р.".format(коли, минуло, найбільший),
                "розбіжність джерел: {} проти курованих {}".format(
                    треба_extension, треба_куровано), число=минуло))

    # ── 3. Післядія ЗЗР за ФАКТИЧНО внесеними речовинами
    каталог = післядія()["рядки"]
    for запис in внесення or []:
        назва = str(запис.get("речовина") or "").strip().lower()
        рядок = каталог.get(назва)
        if not рядок:
            continue
        чутливі = [корінь(ч) for ч in
                   str(рядок.get("restricted_next_crops") or "").split(",") if ч.strip()]
        if к not in чутливі:
            continue
        інтервал = рядок.get("safe_interval_months") or "?"
        коли_внесено = запис.get("дата") or запис.get("рік")
        if not коли_внесено:
            # Дати немає — інтервал безпеки порахувати неможливо. Це
            # невідомість, а не відсутність ризику.
            причини.append(причина(
                "післядія_ЗЗР", НЕВІДОМО,
                "«{}» обмежує «{}» ({} міс.), але дати внесення немає".format(
                    рядок.get("name_ua"), культура, інтервал),
                "історія захисту без дати"))
            continue
        пояснення = "«{}» обмежує «{}»: безпечний інтервал {} міс., внесено {}".format(
            рядок.get("name_ua"), культура, інтервал, коли_внесено)
        # Тип ґрунту — підсилювач, названий у самому каталозі. pH тягнеться
        # з аналізів поля: за лугового ґрунту сульфонілсечовини й триазини
        # тримаються довше, за кислого — сильніше шкодять імідазолінони.
        pH = (ґрунт or {}).get("pH")
        напрям = str(рядок.get("ph_direction") or "")
        if pH and напрям and напрям != "ph_independent":
            if "high" in напрям and float(pH) >= 7.0:
                пояснення += " · pH {} — залишок тримається довше".format(pH)
            elif "low" in напрям and float(pH) <= 6.5:
                пояснення += " · pH {} — шкодить сильніше".format(pH)
        причини.append(причина(
            "післядія_ЗЗР", ДОКАЗ_ДОРАДЧИЙ, пояснення,
            "каталог післядії · 309 д.р. · atom_kb + NDSU/Purdue/Iowa/GRDC/PPDB",
            число=рядок.get("risk")))

    # ── стан = найсуворіший наслідок
    порядок = [СТОП, РИЗИК, НЕ_ОЦІНЕНО, БЕЗ_СИГНАЛУ]
    наслідки = [п["наслідок"] for п in причини]
    стан = next((с for с in порядок if с in наслідки), БЕЗ_СИГНАЛУ)
    return {"культура": культура, "корінь": к, "стан": стан,
            "попередник": минулий, "причини": причини,
            "N_після_попередника": (інтервали().get(попередник) or {}).get("N_після")}


def кандидати(історія, рік, культури=None, внесення=None, ґрунт=None):
    """Усі культури з оцінками, від найчистішої до найризикованішої.

    Порядок — за станом і кількістю названих ризиків, а не за балом:
    двом культурам з однаковим станом ми не приписуємо різниці, якої не
    можемо назвати словами.
    """
    перелік = культури or [к for к, _ in КОРЕНІ if к != "пар"]
    оцінки = [оцінити(к, історія, рік, внесення=внесення, ґрунт=ґрунт)
              for к in перелік]
    вага = {БЕЗ_СИГНАЛУ: 0, НЕ_ОЦІНЕНО: 1, РИЗИК: 2, СТОП: 3}
    оцінки.sort(key=lambda о: (вага[о["стан"]], len(о["причини"])))
    return оцінки


