"""РОТАЦІЯ. Що можна сіяти на цьому полі наступного року — і чого це коштує.

**Головне правило, підписане Власником** (перенесено з `agroplace-weather`,
`lib/data/rotationEvidence.ts`, і не переглядається тут):

    Агрономічні ворота визначають ДОПУСТИМІСТЬ. Гроші лише порівнюють
    наслідки серед допустимого. СТОП грішми не компенсується.

**Балів і сум тут немає за побудовою.** Не тому, що важко скласти, а тому
що складене число ховає причину: «ризик 7,4» не каже, чи це склеротинія,
чи залишок гербіциду, і що з ним робити. Модуль повертає ПЕРЕЛІК названих
механізмів, кожен зі своїм класом доказовості й провенансом.

**Чотири класи доказовості й ніякого пʼятого:**

    ДОКАЗ_ТВЕРДИЙ    конкретна доказова умова: заборона реєстрації,
                     доведена післядія за ФАКТИЧНО внесеною речовиною з
                     датою, названий стан патогена. Сама лише
                     ідентичність культури сюди НЕ веде.
    ДОКАЗ_ДОРАДЧИЙ   механізм названий і простежується до даних; ризик,
                     який агроном бачить і може свідомо прийняти.
    ПОПЕРЕДНІЙ       правило існує, але його джерело — курована таблиця
                     без ланцюга доказів. Має право попереджати, не
                     забороняти.
    НЕВІДОМО         оцінити нічим. Це не «безпечно» і не «погано».

**Чому інтервали повернення тут не забороняють.** Біологічна підстава
сильна, а самі числа — ні: курована таблиця каже про соняшник 7 років,
SDSU Extension — про 3, і жодне з двох не має під собою ланцюга доказів
для наших полів. Тому короткий інтервал — це ЗРОСТАЮЧИЙ РИЗИК із
провенансом, а не заборона з фіксованого числа.

Джерела зовнішні, звірені 2026-08-22:

* соняшник — перерва 3 роки, а на полях з історією склеротинії мінімум
  3 роки: SDSU Extension, «Sclerotinia Concerns in Sunflower»;
* склероції живуть у ґрунті 3–7 років, тому сама лише ротація
  склеротинію не знімає: там само;
* ріпак (canola) — не частіше ніж раз на 2–3 роки, і його не садять у
  проміжку між соняшниками, бо обидва — господарі Sclerotinia:
  Canola Council of Canada, «Crop rotation»;
* дрібні зернові й кукурудза — розділові культури між сприйнятливими
  дводольними: SDSU Extension, «Crop Rotation in Farm Management»;
* післядія гербіцидів залежить від pH: триазини й сульфонілсечовини
  тримаються довше за pH вище 7,0–7,5, а імідазолінони шкодять радше за
  pH нижче 6,5: SDSU Extension «Herbicide Rotation Restrictions»,
  UW-Madison Extension «Herbicide Rotational Restrictions».

Довідники лежать знімком у `довідники_ротації/` — з датою, шляхом у
джерелі й контрольною сумою. Живого join із чужим репозиторієм немає.
"""

