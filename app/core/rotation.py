# Чим сценарії різняться, якщо балів немає. Не «рівнем ризику 1–5», а
# ПОЛІТИКОЮ: які класи причин політика згодна прийняти, і скільки площі
# дозволяє віддати одній культурі. Політика — це рішення, яке можна
# переказати словами, а бал переказати неможливо.
#
# Стеля частки культури не вигадана: вона виводиться з інтервалу
# повернення. Якщо культура має повертатись не частіше ніж раз на N
# років, то під нею не може бути більше ніж 1/N площі — інакше на
# частині полів інтервал порушиться вже наступного циклу. Це арифметика
# сівозміни, а не смак.
ПОЛІТИКИ = (
    {
        "ключ": "обережний",
        "назва": "Обережний",
        "суть": "тільки чисті пари, жодного прийнятого ризику",
        "приймає": (БЕЗ_СИГНАЛУ,),
        "запас_стелі": 1.0,
    },
    {
        "ключ": "збалансований",
        "назва": "Збалансований",
        "суть": "чисті пари; невідоме приймається там, де інакше поле лишиться порожнім",
        "приймає": (БЕЗ_СИГНАЛУ, НЕ_ОЦІНЕНО),
        "запас_стелі": 1.0,
    },
    {
        "ключ": "наступальний",
        "назва": "Наступальний",
        "суть": "ризики приймаються свідомо, кожен названий поіменно",
        "приймає": (БЕЗ_СИГНАЛУ, НЕ_ОЦІНЕНО, РИЗИК),
        "запас_стелі": 1.35,
    },
)


def стеля_частки(культура):
    """Скільки площі щонайбільше може бути під цією культурою.

    Виводиться з інтервалу повернення: раз на 4 роки → не більше чверті
    площі. Беремо МʼЯКШИЙ з двох інтервалів (extension проти курованого),
    бо жорсткіший підпису не має і не повинен звужувати господарство
    сильніше, ніж на те є докази.
    """
    правило = інтервали().get(корінь(культура)) or {}
    пороги = [п for п in (правило.get("років_куровано"),
                          ІНТЕРВАЛ_EXTENSION.get(корінь(культура), (None, None))[0]) if п]
    if not пороги:
        return None
    років = min(пороги)
    return 1.0 / років if років > 0 else None


def сценарій(поля, рік, політика, культури=None, перевага=None):
    """Один сценарій на все господарство.

    `поля` — перелік {"ключ", "площа_га", "історія", "внесення", "ґрунт"}.

    Поле, для якого політика не знаходить жодної допустимої культури,
    лишається ПОРОЖНІМ і потрапляє в «не закрито». Підставити туди
    будь-що, аби заповнити, означало б збрехати саме там, де рішення
    найважче.
    """
    усього_га = sum(float(п.get("площа_га") or 0) for п in поля)
    зайнято = {}
    розклад, не_закрито, прийняті_ризики = {}, [], []

    # Поля йдуть від найбільшого: велике поле важче пересунути, і саме
    # воно з'їдає стелю частки. Дрібним потім легше знайти місце.
    for поле in sorted(поля, key=lambda п: -float(п.get("площа_га") or 0)):
        га = float(поле.get("площа_га") or 0)
        оцінки = кандидати(поле.get("історія") or {}, рік, культури=культури,
                           внесення=поле.get("внесення"),
                           ґрунт=поле.get("ґрунт"))
        # Перевага політики — не обхід воріт: вона лише зсуває порядок
        # СЕРЕД допустимих, а недопустиме лишається недопустимим.
        допустимі = []
        for о in оцінки:
            if о["стан"] not in політика["приймає"]:
                continue
            стеля = стеля_частки(о["корінь"])
            if стеля and усього_га:
                межа = стеля * політика["запас_стелі"] * усього_га
                if зайнято.get(о["корінь"], 0) + га > межа:
                    continue
            допустимі.append(о)

        # СЕРЕД ДОПУСТИМИХ розподіляємо рівномірно, а не беремо першу.
        # Без цього сценарій ставив кукурудзу на всі 21 поле: вона єдина
        # без обмеження повернення, тож вигравала скрізь, і всі чотири
        # варіанти виходили однаковими — 100 % однієї культури. Це не
        # сівозміна, а її протилежність: наступного року кожне поле
        # опинилось би в повторенні.
        #
        # «Рівномірно» тут не смак, а те, що переказується словами:
        # береться культура, найменш зайнята ВІДНОСНО власної стелі.
        # Ворота вже відсіяли недопустиме — рівномірність лише вибирає
        # серед того, що пройшло.
        def завантаженість(о):
            стеля = стеля_частки(о["корінь"])
            зайняті_га = зайнято.get(о["корінь"], 0)
            if стеля and усього_га:
                return зайняті_га / (стеля * усього_га)
            return зайняті_га / усього_га if усього_га else 0

        if перевага:
            корені_переваги = [корінь(к) for к in перевага]
            допустимі.sort(key=lambda о: (о["корінь"] not in корені_переваги,
                                          завантаженість(о), len(о["причини"])))
        else:
            допустимі.sort(key=lambda о: (завантаженість(о), len(о["причини"])))
        обрана = допустимі[0] if допустимі else None
        if not обрана:
            не_закрито.append({"поле": поле.get("ключ"), "площа_га": га,
                               "чому": "жодна культура не проходить політику "
                                       "«{}»".format(політика["назва"])})
            continue
        розклад[поле["ключ"]] = обрана["корінь"]
        зайнято[обрана["корінь"]] = зайнято.get(обрана["корінь"], 0) + га
        for п in обрана["причини"]:
            if п["наслідок"] in (РИЗИК, НЕ_ОЦІНЕНО):
                прийняті_ризики.append({"поле": поле.get("ключ"),
                                        "культура": обрана["корінь"], **п})

    структура = [{"культура": к, "га": round(г, 1),
                  "частка": round(100 * г / усього_га, 1) if усього_га else None}
                 for к, г in sorted(зайнято.items(), key=lambda п: -п[1])]
    return {
        "ключ": політика["ключ"],
        "назва": політика["назва"],
        "суть": політика["суть"],
        "приймає": list(політика["приймає"]),
        "розклад": розклад,
        "структура": структура,
        "закрито_полів": len(розклад),
        "усього_полів": len(поля),
        "не_закрито": не_закрито,
        "прийняті_ризики": прийняті_ризики,
        "ризиків": len(прийняті_ризики),
    }


def культури_господарства(поля, щонайменше=2):
    """Що це господарство справді вирощує — з його ж історії.

    Без цього генератор пропонував просо, гречку й люцерну лише тому,
    що вони є в словнику коренів. Сівозміну складають із культур, під
    які в господарства є техніка, насіння й покупець, а не з переліку
    ботанічних видів.

    `щонайменше` відсіює випадковий рядок: культура, що трапилась у
    історії один раз на одному полі, — це не те, на чому будують план.
    """
    скільки = {}
    for поле in поля:
        for культура in (поле.get("історія") or {}).values():
            к = корінь(культура.get("культура") if isinstance(культура, dict) else культура)
            if к and к != "пар":
                скільки[к] = скільки.get(к, 0) + 1
    return [к for к, н in sorted(скільки.items(), key=lambda п: -п[1])
            if н >= щонайменше]


def сценарії(поля, рік, культури=None):
    """Три політики плюс один зсув структури — чотири варіанти.

    Четвертий не «ризикованіший», а ІНАКШИЙ: та сама обережна політика,
    але з перевагою зернових. Господарству потрібен вибір не лише за
    сміливістю, а й за тим, чим воно хоче торгувати.
    """
    культури = культури or культури_господарства(поля)
    варіанти = [сценарій(поля, рік, п, культури=культури) for п in ПОЛІТИКИ]
    зерновий = сценарій(поля, рік, ПОЛІТИКИ[1], культури=культури,
                        перевага=["пшениця", "кукурудза", "ячмінь"])
    зерновий.update({"ключ": "зерновий", "назва": "Зерновий фокус",
                     "суть": "та сама обережність, але перевага зерновим"})
    варіанти.append(зерновий)

    # Політики можуть зійтись в один розклад — так буває, коли в історії
    # немає невідомості й обережному нема від чого відступати. Тоді два
    # варіанти виглядають як вибір, не будучи ним. Позначаємо збіг: чотири
    # картки, з яких дві однакові, — це прихована брехня про вибір.
    бачені = {}
    for в in варіанти:
        відбиток = tuple(sorted(в["розклад"].items()))
        якщо_був = бачені.get(відбиток)
        if якщо_був:
            в["збігається_з"] = якщо_був
        else:
            бачені[відбиток] = в["назва"]
            в["збігається_з"] = None
    return варіанти
