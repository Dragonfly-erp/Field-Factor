# -*- coding: utf-8 -*-
"""Фаза 6: зведення кількох комбайнів.

Два комбайни на одному полі майже завжди відкалібровані по-різному. Але якщо
вони працювали на різних кінцях поля, різниця між ними може бути не збоєм
приладу, а справжньою різницею ґрунту. Тому поправка береться ТІЛЬКИ там, де
машини реально працювали поруч — у спільних клітинках.
"""

import numpy as np

МІНІМУМ_КЛІТИНОК = 15
МІНІМАЛЬНА_РІЗНИЦЯ = 0.03      # менше 3 % не чіпаємо
МЕЖА_ПОПРАВКИ = (0.70, 1.45)   # поза цим — це не калібрування, це щось інше


def _клітинки(таблиця, розмір):
    x = таблиця.geometry.x.to_numpy()
    y = таблиця.geometry.y.to_numpy()
    return (np.floor(x / розмір).astype("int64") * 1000003
            + np.floor(y / розмір).astype("int64"))


def звести(таблиця, журнал, розмір_клітинки=25.0):
    """Повертає (таблиця з ВРОЖАЙ_ЗВЕД, звіт)."""
    import pandas as pd

    таблиця["ВРОЖАЙ_ЗВЕД"] = таблиця["ВРОЖАЙ_КГГА"]
    машини = sorted(таблиця["МАШИНА"].dropna().unique())
    звіт = {"машин": len(машини), "поправки": {}, "підстава": "", "рядки": []}

    if len(машини) < 2:
        звіт["підстава"] = "комбайн один — зводити нема з чим"
        return таблиця, звіт

    чисті = таблиця[(таблиця["QC"] == "OK") & np.isfinite(таблиця["ВРОЖАЙ_КГГА"])]
    if len(чисті) < 500:
        звіт["підстава"] = "чистих записів замало, поправку не рахували"
        return таблиця, звіт

    робоча = чисті.copy()
    робоча["_КЛІТИНКА"] = _клітинки(робоча, розмір_клітинки)
    зведення = (
        робоча.groupby(["_КЛІТИНКА", "МАШИНА"])["ВРОЖАЙ_КГГА"]
        .agg(["median", "size"])
        .reset_index()
    )
    зведення = зведення[зведення["size"] >= 3]
    широко = зведення.pivot(index="_КЛІТИНКА", columns="МАШИНА", values="median")

    опорна = робоча["МАШИНА"].value_counts().idxmax()
    звіт["опорна"] = опорна
    поправки = {опорна: 1.0}
    рядки = []

    for машина in машини:
        if машина == опорна:
            рядки.append({
                "машина": машина, "поправка": 1.0, "спільних_клітинок": "—",
                "рішення": "опорна машина",
            })
            continue
        if машина not in широко.columns or опорна not in широко.columns:
            поправки[машина] = 1.0
            рядки.append({"машина": машина, "поправка": 1.0, "спільних_клітинок": 0,
                          "рішення": "спільних ділянок немає — не чіпаємо"})
            continue

        пара = широко[[опорна, машина]].dropna()
        спільних = int(len(пара))
        if спільних < МІНІМУМ_КЛІТИНОК:
            поправки[машина] = 1.0
            рядки.append({
                "машина": машина, "поправка": 1.0, "спільних_клітинок": спільних,
                "рішення": "працювали в різних місцях — різницю списуємо на поле, "
                           "а не на прилад",
            })
            continue

        відношення = float(np.median(пара[опорна].to_numpy() / пара[машина].to_numpy()))
        if not np.isfinite(відношення) or відношення <= 0:
            поправки[машина] = 1.0
            рядки.append({"машина": машина, "поправка": 1.0, "спільних_клітинок": спільних,
                          "рішення": "відношення не порахувалось"})
            continue

        if abs(відношення - 1.0) < МІНІМАЛЬНА_РІЗНИЦЯ:
            поправки[машина] = 1.0
            рішення = "різниця менша за 3 % — у межах шуму, не чіпаємо"
        elif not (МЕЖА_ПОПРАВКИ[0] <= відношення <= МЕЖА_ПОПРАВКИ[1]):
            поправки[машина] = 1.0
            рішення = ("різниця завелика ({:.2f}) — це не калібрування. "
                       "Перевірте одиниці й налаштування монітора".format(відношення))
        else:
            поправки[машина] = відношення
            рішення = "поправка застосована"

        рядки.append({
            "машина": машина, "поправка": round(поправки[машина], 4),
            "спільних_клітинок": спільних, "рішення": рішення,
        })

    множник = таблиця["МАШИНА"].map(поправки).fillna(1.0).to_numpy(dtype="float64")
    таблиця["ВРОЖАЙ_ЗВЕД"] = таблиця["ВРОЖАЙ_КГГА"] * множник

    звіт["поправки"] = {к: round(в, 4) for к, в in поправки.items()}
    звіт["рядки"] = рядки
    звіт["підстава"] = (
        "порівняння медіан у клітинках {:.0f}×{:.0f} м, де працювали обидві "
        "машини".format(розмір_клітинки, розмір_клітинки)
    )

    журнал.сказати("Комбайнів: {}. Опорний — {}.".format(len(машини), опорна))
    for рядок in рядки:
        журнал.сказати("  {}: ×{} — {}".format(
            рядок["машина"], рядок["поправка"], рядок["рішення"]))
    return таблиця, звіт
