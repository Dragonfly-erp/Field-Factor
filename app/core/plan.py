# -*- coding: utf-8 -*-
"""ПЛАН СЕЗОНУ. Те, що господарство збирається зробити наступного року.

**План — це запис, а не тека з файлами.** Взято з моделі farmOS, де план
звʼязує поля й операції навколо однієї мети й має власний стан. Через це
план живе ПОРУЧ із фактом, а не замість нього: історія поля каже, що вже
сталося, план каже, що збираємось зробити, і жодне з двох не переписує
іншого. Затвердили план — з нього народжуються операції, і аж тоді вони
стають фактом.

**Де лежить.** У теці господарства, бо план — про все господарство одразу:

    <господарство>/_плани/2027.json

Не в теці поля, як історія. Ротація, структура посівів і бюджет культури
не належать жодному окремому полю: соняшник на одному полі має сенс лише
разом із тим, що стоїть на решті.

**Варіанти ротації всередині плану.** Господарство робить кілька варіантів
і порівнює їх лоб у лоб; обраний стає планом сезону. Варіанти лишаються
після вибору — рік по тому корисно бачити, що саме відкинули й чому.

**Шість кроків на кожному полі**, і порядок тут — це порядок роботи:

    ротація → культура й гібрид → живлення → захист → обробіток → бюджет

Крок, якого немає, лишається порожнім і **каже про себе порожнім**. Нуль у
нормі означає «не вносимо», відсутність кроку означає «ще не вирішили», і
плутати їх не можна — це та сама межа, що між «не вносили» й «не знаємо»
в історії поля.
"""

import json
import os
from datetime import datetime

# Підкреслення — не прикраса: картотека вважає полем КОЖНУ підтеку
# господарства, крім тих, що починаються з «_». Тека «плани» без нього
# ставала двадцять другим полем КОМАГРО, і рейка чесно рахувала його
# як поле без культури.
ТЕКА = "_плани"

# Порядок кроків — порядок роботи, а не абетка. Кожен крок бачить те, що
# вирішено на попередніх: норма живлення не рахується, доки не обрано
# культуру, а бюджет не сходиться, доки не закрито обробіток.
КРОКИ = (
    ("ротація", "Ротація"),
    ("культура", "Культура й гібрид"),
    ("живлення", "Живлення"),
    ("захист", "Захист"),
    ("обробіток", "Обробіток"),
    ("бюджет", "Бюджет поля"),
)

# Стан плану. «Чернетку» можна правити як завгодно; «затверджений» — той,
# з якого вже народжуються операції, і правка в ньому має бути свідомою.
СТАНИ = ("чернетка", "затверджений", "архів")


def _тека(картотека, господарство):
    return os.path.join(картотека.корінь, господарство, ТЕКА)


def _шлях(картотека, господарство, рік):
    return os.path.join(_тека(картотека, господарство), "{}.json".format(рік))


def _прочитати(шлях, замовчування):
    try:
        with open(шлях, encoding="utf-8") as ф:
            return json.load(ф)
    except (OSError, ValueError):
        return замовчування


def _записати(шлях, дані):
    os.makedirs(os.path.dirname(шлях), exist_ok=True)
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(дані, ф, ensure_ascii=False, indent=2)


def порожній(рік):
    """Скелет плану. Полів у ньому ще немає — вони заводяться, коли на
    поле щось ставлять. План на 300 полів, де все порожнє, нічим не
    відрізняється від відсутнього плану, тільки займає місце."""
    return {
        "рік": int(рік),
        "стан": "чернетка",
        "створено": datetime.now().strftime("%Y-%m-%d"),
        "варіанти": [],
        "обраний_варіант": None,
        "поля": {},
    }


def прочитати(картотека, господарство, рік):
    """План року. Немає — повертається порожній, але НЕ записується на
    диск: відкрити екран і подивитись ще не означає почати планувати."""
    план = _прочитати(_шлях(картотека, господарство, рік), None)
    return план if план else порожній(рік)


def записати(картотека, господарство, план):
    план["змінено"] = datetime.now().strftime("%Y-%m-%d")
    _записати(_шлях(картотека, господарство, план["рік"]), план)
    return план


def роки(картотека, господарство):
    """Роки, на які в цього господарства вже є план."""
    тека = _тека(картотека, господарство)
    знайдені = []
    for імʼя in sorted(os.listdir(тека)) if os.path.isdir(тека) else []:
        корінь, розширення = os.path.splitext(імʼя)
        if розширення == ".json" and корінь.isdigit():
            знайдені.append(int(корінь))
    return знайдені


# ─────────────────────────────────────────────────────────── варіанти ротації

def варіант_додати(план, ключ, назва, суть="", поля=None):
    """Ще один варіант ротації. Варіант — це лише «яка культура на якому
    полі»; гібриди, норми й захист належать уже обраному плану, бо їх
    немає сенсу підбирати для ротації, яку відкинуть."""
    варіант = {"ключ": ключ, "назва": назва, "суть": суть,
               "поля": dict(поля or {}),
               "створено": datetime.now().strftime("%Y-%m-%d")}
    план["варіанти"] = [в for в in план.get("варіанти") or []
                        if в.get("ключ") != ключ] + [варіант]
    return варіант


def варіант(план, ключ):
    for в in план.get("варіанти") or []:
        if в.get("ключ") == ключ:
            return в
    return None


def варіант_обрати(план, ключ):
    """Обраний варіант розкладається по полях як крок «ротація».

    Культура з варіанта НЕ затирає культуру, обрану на полі руками: якщо
    на полі вже стоїть інша, вона лишається, а розбіжність видно в
    `розбіжності()`. Мовчки перезаписати рішення агронома — гірше, ніж
    показати, що воно розійшлося з варіантом.
    """
    обраний = варіант(план, ключ)
    if not обраний:
        raise ValueError("Немає варіанта «{}»".format(ключ))
    план["обраний_варіант"] = ключ
    for поле, культура in (обраний.get("поля") or {}).items():
        запис = план.setdefault("поля", {}).setdefault(поле, {})
        запис.setdefault("культура", культура)
        запис.setdefault("кроки", {})["ротація"] = {
            "культура": культура,
            "джерело": "варіант ротації · {}".format(обраний.get("назва") or ключ),
        }
    return обраний


def розбіжності(план):
    """Поля, де культура плану розійшлася з обраним варіантом ротації.

    Це не помилка — агроном міг свідомо змінити поле після вибору
    сценарію. Але воно має бути видно, інакше структура посівів на екрані
    перестане збігатися з тим, що справді заплановано.
    """
    обраний = варіант(план, план.get("обраний_варіант"))
    якщо_немає = []
    if not обраний:
        return якщо_немає
    for поле, культура in (обраний.get("поля") or {}).items():
        своя = (план.get("поля") or {}).get(поле, {}).get("культура")
        if своя and своя != культура:
            якщо_немає.append({"поле": поле, "у_варіанті": культура, "у_плані": своя})
    return якщо_немає


# ─────────────────────────────────────────────────────────────── кроки поля

def крок_записати(план, поле, крок, дані, джерело=""):
    """Крок на полі. Порожній словник стирає крок, а не пише порожнечу:
    «немає кроку» і «крок є, але в ньому нічого» — різні речі, і другого
    в плані бути не повинно."""
    if крок not in dict(КРОКИ):
        raise ValueError("Невідомий крок «{}»".format(крок))
    запис = план.setdefault("поля", {}).setdefault(поле, {})
    кроки = запис.setdefault("кроки", {})
    if not дані:
        кроки.pop(крок, None)
        return None
    значення = dict(дані)
    if джерело:
        значення["джерело"] = джерело
    значення["записано"] = datetime.now().strftime("%Y-%m-%d")
    кроки[крок] = значення
    return значення


def культуру_поставити(план, поле, культура, джерело="поставлено рукою"):
    """Культура на полі — разом із кроком ротації, який на ній тримається.

    Порожня культура прибирає поле з плану **цілком**, а не лишає запис
    `{"кроки": {}}`. Порожній запис — це сміття, яке накопичується мовчки:
    поставили культуру, передумали, і поле лишається в плані назавжди.
    План на триста порожніх полів нічим не кращий за відсутній.
    """
    культура = (культура or "").strip()
    запис = план.setdefault("поля", {}).setdefault(поле, {})
    if культура:
        запис["культура"] = культура
        крок_записати(план, поле, "ротація", {"культура": культура}, джерело=джерело)
        return культура
    запис.pop("культура", None)
    крок_записати(план, поле, "ротація", {})
    if not запис.get("культура") and not (запис.get("кроки") or {}):
        план["поля"].pop(поле, None)
    return None


def крок(план, поле, крок_):
    return ((план.get("поля") or {}).get(поле, {}).get("кроки") or {}).get(крок_)


def стан_поля(план, поле):
    """Які кроки на полі закрито, а який наступний.

    `наступний` — це перший незакритий крок у порядку роботи. Саме він
    стоїть на кнопці внизу екрана: людині не треба самій згадувати, де
    вона зупинилась.
    """
    кроки = (план.get("поля") or {}).get(поле, {}).get("кроки") or {}
    закриті = [к for к, _ in КРОКИ if кроки.get(к)]
    наступний = next((к for к, _ in КРОКИ if not кроки.get(к)), None)
    return {"поле": поле, "закрито": закриті, "усього": len(КРОКИ),
            "наступний": наступний,
            "готове": наступний is None}


def зведення(план, усі_поля=None):
    """Скільки полів у плані, скільки готових, де діри.

    `усі_поля` — перелік ключів полів господарства. Без нього видно лише
    ті поля, яких план уже торкнувся, і «21 з 21 готове» означало б, що
    ми забули про решту двохсот.
    """
    поля = list(усі_поля) if усі_поля is not None else list((план.get("поля") or {}))
    стани = [стан_поля(план, п) for п in поля]
    без_культури = [с["поле"] for с in стани if "культура" not in с["закрито"]]
    по_кроках = {}
    for ключ, підпис in КРОКИ:
        по_кроках[ключ] = {
            "підпис": підпис,
            "закрито": sum(1 for с in стани if ключ in с["закрито"]),
        }
    return {
        "рік": план.get("рік"),
        "стан": план.get("стан"),
        "полів": len(поля),
        "готових": sum(1 for с in стани if с["готове"]),
        "без_культури": без_культури,
        "по_кроках": по_кроках,
        "варіантів": len(план.get("варіанти") or []),
        "обраний_варіант": план.get("обраний_варіант"),
        "розбіжностей": len(розбіжності(план)),
    }


def структура(план, площі):
    """Структура посівів: скільки гектарів під якою культурою.

    `площі` — {ключ поля: га}. Поле без площі в структуру не входить і
    рахується окремо: приписати йому нуль гектарів означало б тихо
    применшити частку культури, а вигадати площу — збрехати.
    """
    по_культурах, без_площі, усього = {}, [], 0.0
    for поле, запис in (план.get("поля") or {}).items():
        культура = запис.get("культура")
        if not культура:
            continue
        га = площі.get(поле)
        if not га:
            без_площі.append(поле)
            continue
        по_культурах[культура] = по_культурах.get(культура, 0.0) + float(га)
        усього += float(га)
    рядки = [{"культура": к, "га": round(г, 1),
              "частка": round(100 * г / усього, 1) if усього else None}
             for к, г in sorted(по_культурах.items(), key=lambda п: -п[1])]
    return {"культур": len(рядки), "га": round(усього, 1),
            "рядки": рядки, "без_площі": без_площі}


def затвердити(план):
    """Чернетка стає затвердженим планом.

    Ворота: план без жодного поля з культурою затвердити не можна. Це не
    формальність — із затвердженого плану народжуються операції, і план,
    у якому нічого не стоїть, породив би порожній сезон.
    """
    з_культурою = [п for п, з in (план.get("поля") or {}).items() if з.get("культура")]
    if not з_культурою:
        raise ValueError("У плані немає жодного поля з культурою")
    план["стан"] = "затверджений"
    план["затверджено"] = datetime.now().strftime("%Y-%m-%d")
    return план
