# -*- coding: utf-8 -*-
"""Фази 4-5: приведення до спільного вигляду і відсів того, що не є врожаєм.

Головне правило цього модуля: низька врожайність — не привід викидати запис.
Викидається те, що фізично неможливе, і те, що є слідом машини, а не поля:
зупинки, розвороти, стрибки GPS, початок і кінець проходу.
"""

import numpy as np

from app.core import util

# Коди QC. Короткі, бо лізуть у DBF.
ЧИСТО = "OK"
КОДИ = {
    "DUP": "повтор координати",
    "NOXY": "координати неможливі",
    "OUT": "поза контуром поля",
    "NEG": "врожайність відʼємна",
    "HIGH": "вище фізичної межі",
    "ZERO": "нуль без підстав",
    "NOYLD": "врожайності немає",
    "MOIST": "вологість неможлива",
    "STOP": "комбайн стояв",
    "JUMP": "стрибок GPS",
    "TRANS": "початок або кінець проходу",
    "TURN": "розворот на кінцівці",
    "WIDTH": "ширина захвату неможлива",
    "ELEV": "викид висоти",
    "OUTL": "локальний викид",
}


def _числа(таблиця, колонка):
    if not колонка or колонка not in таблиця.columns:
        return None
    return np.asarray(таблиця[колонка], dtype="float64")


# ------------------------------------------------------------ стандартизація


def стандартизувати(таблиця, паспорт, колонки, журнал):
    """Створює робочі колонки з тих, що вказав користувач."""
    зауваження = []
    поле_врожаю = колонки.get("врожай")
    if not поле_врожаю or поле_врожаю not in таблиця.columns:
        raise ValueError("Не вказано колонку врожайності — рахувати нічого.")

    сирий = _числа(таблиця, поле_врожаю)
    таблиця["ВРОЖАЙ_СИР"] = сирий

    одиниця = паспорт.get("одиниця_врожаю") or ""
    if not одиниця:
        медіана = float(np.nanmedian(сирий[np.isfinite(сирий) & (сирий > 0)]))
        одиниця, чому = util.підказати_одиницю(медіана, паспорт.get("культура"))
        зауваження.append("Одиниця врожайності визначена самою програмою. " + чому)
    переведене = util.у_кг_на_га(сирий, одиниця, паспорт.get("культура"))
    if переведене is None:
        raise ValueError(
            "Не вдалось перевести одиницю «{}» у кг/га. Для бушелів потрібна "
            "відома культура.".format(одиниця)
        )
    таблиця["ВРОЖАЙ_КГГА"] = переведене
    таблиця["_ОДИНИЦЯ"] = одиниця
    журнал.сказати("Врожайність переведено з «{}» у кг/га.".format(одиниця))

    вологість = _числа(таблиця, колонки.get("вологість"))
    таблиця["ВОЛОГІСТЬ"] = вологість if вологість is not None else np.nan

    висота = _числа(таблиця, колонки.get("висота"))
    таблиця["ВИСОТА"] = висота if висота is not None else np.nan

    ширина = _числа(таблиця, колонки.get("ширина"))
    if ширина is not None:
        ширина, одиниця_ширини = util.у_метри_ширина(ширина)
        таблиця["ШИРИНА"] = ширина
        журнал.сказати("Ширина захвату прочитана як {}.".format(одиниця_ширини))
    else:
        таблиця["ШИРИНА"] = np.nan

    швидкість = _числа(таблиця, колонки.get("швидкість"))
    if швидкість is not None:
        медіана = float(np.nanmedian(швидкість))
        if медіана < 5:            # м/с
            швидкість = швидкість * 3.6
            зауваження.append("Швидкість прочитана як метри за секунду, переведена в км/год.")
        elif медіана > 25:         # милі за годину — навряд, але буває
            швидкість = швидкість * 1.60934
            зауваження.append("Швидкість прочитана як милі за годину, переведена в км/год.")
        таблиця["ШВИДКІСТЬ"] = швидкість
    else:
        таблиця["ШВИДКІСТЬ"] = np.nan

    поле_часу = колонки.get("час")
    if поле_часу and поле_часу in таблиця.columns:
        import pandas as pd

        час = pd.to_datetime(таблиця[поле_часу], errors="coerce", format="mixed")
        if час.notna().sum() < len(час) * 0.5:
            час = pd.to_datetime(таблиця[поле_часу], errors="coerce", unit="s")
        таблиця["ЧАС"] = час
        if час.notna().any():
            журнал.сказати(
                "Час запису прочитано: {} — {}.".format(
                    час.min().strftime("%d.%m.%Y %H:%M"),
                    час.max().strftime("%d.%m.%Y %H:%M"),
                )
            )
    else:
        таблиця["ЧАС"] = None

    таблиця["QC"] = ЧИСТО
    return таблиця, зауваження


def _позначити(таблиця, умова, код):
    """Помітка ставиться лише на ще чисті записи — перша причина головна."""
    маска = умова & (таблиця["QC"] == ЧИСТО)
    таблиця.loc[маска, "QC"] = код
    return int(маска.sum())


# ------------------------------------------------------------ вікна


def фізичні_вікна(таблиця, паспорт, журнал):
    """Те, чого не буває. Тут ніякої агрономії — тільки фізика й арифметика."""
    межа = float(паспорт.get("межа") or 20000)
    врожай = таблиця["ВРОЖАЙ_КГГА"].to_numpy()

    відкинуто = {}
    відкинуто["NOXY"] = _позначити(
        таблиця, ~np.isfinite(таблиця.geometry.x) | ~np.isfinite(таблиця.geometry.y), "NOXY"
    )
    відкинуто["NOYLD"] = _позначити(таблиця, ~np.isfinite(врожай), "NOYLD")
    відкинуто["NEG"] = _позначити(таблиця, врожай < 0, "NEG")
    відкинуто["HIGH"] = _позначити(таблиця, врожай > межа, "HIGH")

    вологість = таблиця["ВОЛОГІСТЬ"].to_numpy()
    if np.isfinite(вологість).any():
        відкинуто["MOIST"] = _позначити(
            таблиця, np.isfinite(вологість) & ((вологість <= 0) | (вологість >= 60)), "MOIST"
        )

    ширина = таблиця["ШИРИНА"].to_numpy()
    if np.isfinite(ширина).any():
        відкинуто["WIDTH"] = _позначити(
            таблиця, np.isfinite(ширина) & ((ширина <= 0.3) | (ширина > 25)), "WIDTH"
        )

    # повтори координат: той самий метр двічі — це подвійний запис
    ключ = (
        таблиця.geometry.x.round(1).astype(str) + "_" + таблиця.geometry.y.round(1).astype(str)
    )
    відкинуто["DUP"] = _позначити(таблиця, ключ.duplicated(keep="first"), "DUP")

    for код, скільки in відкинуто.items():
        if скільки:
            журнал.сказати("  {} — {} записів".format(КОДИ[код], скільки))
    return таблиця, відкинуто


# ------------------------------------------------------------ нуль


def нулі(таблиця, журнал):
    """Нуль підозрілий, але не завжди брехня.

    Лишаємо нуль там, де він тримається купи: сусіди теж близько до нуля.
    Поодинокий нуль серед нормальних сусідів — це затримка сенсора або
    зупинка, а не поле.
    """
    from scipy.spatial import cKDTree

    маска_нулів = (таблиця["ВРОЖАЙ_КГГА"] <= 0.001) & (таблиця["QC"] == ЧИСТО)
    if not маска_нулів.any():
        return таблиця, 0

    чисті = таблиця[таблиця["QC"] == ЧИСТО]
    коорд = np.c_[чисті.geometry.x, чисті.geometry.y]
    врожай = чисті["ВРОЖАЙ_КГГА"].to_numpy()
    дерево = cKDTree(коорд)

    нулі_ід = np.where(маска_нулів.loc[чисті.index].to_numpy())[0]
    _, сусіди = дерево.query(коорд[нулі_ід], k=min(9, len(коорд)))
    сусідні = врожай[сусіди[:, 1:]] if сусіди.ndim > 1 else врожай[сусіди]
    частка_нулів_поруч = np.mean(сусідні <= 0.001, axis=1)

    самотні = нулі_ід[частка_нулів_поруч < 0.4]
    індекси = чисті.index[самотні]
    таблиця.loc[індекси, "QC"] = "ZERO"

    лишили = int(маска_нулів.sum()) - len(індекси)
    if len(індекси):
        журнал.сказати(
            "  нулі: {} поодиноких відкинуто, {} лишено — вони тримаються "
            "суцільною плямою і схожі на справжню порожнечу".format(len(індекси), лишили)
        )
    return таблиця, int(len(індекси))


# ------------------------------------------------------------ контур і зсув


def перевірити_зсув(таблиця, контур, журнал):
    """Чи не зсунутий увесь масив відносно межі поля.

    Масове видалення прикрайових точок — найгірше, що можна зробити, якщо
    насправді зсунута антена. Тому спершу шукаємо жорсткий зсув.
    """
    import geopandas as gpd
    from shapely.prepared import prep

    межа = контур.geometry.iloc[0]
    підготовлена = prep(межа)

    чисті = таблиця[таблиця["QC"] == ЧИСТО]
    if len(чисті) < 100:
        return 0.0, 0.0, "точок замало для перевірки зсуву"

    зразок = чисті.sample(min(4000, len(чисті)), random_state=7)
    x = зразок.geometry.x.to_numpy()
    y = зразок.geometry.y.to_numpy()

    def всередині(зx, зy):
        точки = gpd.points_from_xy(x + зx, y + зy)
        return float(np.mean([підготовлена.contains(т) for т in точки]))

    базова = всередині(0, 0)
    if базова > 0.97:
        пояснення = "зсуву немає: {:.1f} % точок і так усередині контуру".format(базова * 100)
        журнал.сказати("  " + пояснення)
        return 0.0, 0.0, пояснення

    найкраще, кращий = базова, (0.0, 0.0)
    for зx in np.arange(-12, 12.1, 3.0):
        for зy in np.arange(-12, 12.1, 3.0):
            частка = всередині(зx, зy)
            if частка > найкраще + 0.0001:
                найкраще, кращий = частка, (зx, зy)

    if найкраще - базова < 0.03 or np.hypot(*кращий) < 2.0:
        пояснення = "жорсткого зсуву не виявлено ({:.1f} % точок усередині)".format(базова * 100)
        журнал.сказати("  " + пояснення)
        return 0.0, 0.0, пояснення

    # уточнення дрібнішим кроком
    for зx in np.arange(кращий[0] - 3, кращий[0] + 3.1, 1.0):
        for зy in np.arange(кращий[1] - 3, кращий[1] + 3.1, 1.0):
            частка = всередині(зx, зy)
            if частка > найкраще:
                найкраще, кращий = частка, (зx, зy)

    пояснення = (
        "виявлено зсув усього масиву на {:.1f} м — точок усередині стало "
        "{:.1f} % замість {:.1f} %. Зсув застосовано, точки не видалялись".format(
            float(np.hypot(*кращий)), найкраще * 100, базова * 100
        )
    )
    журнал.сказати("  " + пояснення)
    return float(кращий[0]), float(кращий[1]), пояснення


def обрізати_контуром(таблиця, контур, ширина, журнал):
    """Поза контуром — не поле. Розвороти й дорога лишаються там же."""
    import geopandas as gpd

    межа = контур.geometry.iloc[0]
    # антена стоїть не в центрі жатки, тож дозволяємо піввисоти захвату назовні
    допуск = max(1.0, float(ширина) / 2.0)
    із_допуском = межа.buffer(допуск)

    всередині = gpd.GeoSeries(таблиця.geometry, crs=контур.crs).within(із_допуском)
    скільки = _позначити(таблиця, ~всередині.to_numpy(), "OUT")
    if скільки:
        журнал.сказати(
            "  поза контуром — {} записів (з допуском {:.1f} м на виніс "
            "антени)".format(скільки, допуск)
        )
    return таблиця, скільки


# ------------------------------------------------------------ кінематика


def кінематика(таблиця, геометрія, журнал):
    """Зупинки, стрибки, початок і кінець проходу, розвороти."""
    відкинуто = {}
    крок = таблиця["КРОК"].to_numpy()
    швидкість = таблиця["ШВИДКІСТЬ"].to_numpy()
    якщо_немає = ~np.isfinite(швидкість)
    if якщо_немає.any():
        швидкість = np.where(якщо_немає, таблиця["ШВИДКІСТЬ_ГЕО"].to_numpy() * 3.6, швидкість)

    # стояв або повз: зерно ще йде через сенсор, площа вже не набирається
    стояв = np.isfinite(швидкість) & (швидкість < 1.0)
    стояв |= np.isfinite(крок) & (крок < 0.05)
    відкинуто["STOP"] = _позначити(таблиця, стояв, "STOP")

    # стрибок: за один запис пройдено більше, ніж реально можна
    стрибок = np.isfinite(крок) & (крок > max(30.0, геометрія["крок_уздовж_м"] * 12))
    відкинуто["JUMP"] = _позначити(таблиця, стрибок, "JUMP")

    # перехідні записи на початку й у кінці проходу
    межа_записів = max(2, int(round(15.0 / max(геометрія["крок_уздовж_м"], 0.5))))
    порядок = таблиця.groupby("ПРОХІД").cumcount().to_numpy()
    розмір = таблиця.groupby("ПРОХІД")["ПРОХІД"].transform("size").to_numpy()
    перехід = (порядок < межа_записів) | (порядок >= розмір - межа_записів)
    перехід &= розмір > межа_записів * 3
    відкинуто["TRANS"] = _позначити(таблиця, перехід, "TRANS")

    # зовсім куці проходи — це розвороти, а не робота
    куці = розмір < max(6, межа_записів * 2)
    відкинуто["TURN"] = _позначити(таблиця, куці, "TURN")

    # висота: різкий одиночний стрибок рельєфу
    висота = таблиця["ВИСОТА"].to_numpy()
    if np.isfinite(висота).sum() > 100:
        медіана = np.nanmedian(висота)
        розкид = np.nanmedian(np.abs(висота - медіана)) * 1.4826
        if розкид > 0:
            відкинуто["ELEV"] = _позначити(
                таблиця, np.isfinite(висота) & (np.abs(висота - медіана) > 8 * розкид), "ELEV"
            )

    for код, скільки in відкинуто.items():
        if скільки:
            журнал.сказати("  {} — {} записів".format(КОДИ[код], скільки))
    return таблиця, відкинуто


# ------------------------------------------------------------ локальні викиди


def локальні_викиди(таблиця, радіус, журнал, поріг=4.0):
    """Викид відносно СУСІДІВ, а не всього поля.

    Так низька врожайність на реально слабкій ділянці лишається: там низькі
    й сусіди. Відсікається запис, що стирчить серед своїх.
    """
    from scipy.spatial import cKDTree

    чисті = таблиця[таблиця["QC"] == ЧИСТО]
    if len(чисті) < 200:
        return таблиця, 0

    коорд = np.c_[чисті.geometry.x, чисті.geometry.y]
    врожай = чисті["ВРОЖАЙ_КГГА"].to_numpy()
    дерево = cKDTree(коорд)
    сусіди = дерево.query_ball_point(коорд, r=max(радіус, 8.0))

    відхилення = np.zeros(len(коорд))
    for і, група in enumerate(сусіди):
        якщо = [ј for ј in група if ј != і]
        if len(якщо) < 6:
            continue
        значення = врожай[якщо]
        медіана = np.median(значення)
        розкид = np.median(np.abs(значення - медіана)) * 1.4826
        if розкид <= 1e-6:
            continue
        відхилення[і] = abs(врожай[і] - медіана) / розкид

    індекси = чисті.index[відхилення > поріг]
    таблиця.loc[індекси, "QC"] = "OUTL"
    if len(індекси):
        журнал.сказати(
            "  локальні викиди — {} записів (стирчать серед власних сусідів "
            "більш ніж на {} медіанних розкиди)".format(len(індекси), поріг)
        )
    return таблиця, int(len(індекси))
