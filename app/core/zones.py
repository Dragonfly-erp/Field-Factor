def _поверхні(сеанс, контур, сітка, джерела, журнал):
    """Кожне джерело → поверхня на спільній сітці. Повертає (шари, звіт)."""
    зібрані, звіт = {}, []
    налаштування = сеанс.налаштування
    база = сеанс.база

    for джерело in джерела:
        вид = джерело.get("вид")
        вага = float(джерело.get("вага") or 1.0)

        if вид == "вегетація":
            роки = джерело.get("роки") or []
            журнал.сказати("Беру багаторічну вегетацію: {}…".format(
                ", ".join(str(р) for р in роки)))
            шари, опис = sources.вегетація_багаторічна(
                контур, роки, налаштування, база, журнал,
                джерело.get("індекс") or "NDVI")
            if not шари:
                raise ValueError("Вегетацію взяти не вдалось: " + опис.get("причина", ""))
            зібрані["вегетація"] = (шари["вегетація"], вага)
            if джерело.get("з_мінливістю"):
                зібрані["мінливість_вегетації"] = (шари["мінливість_вегетації"], вага * 0.5)
            звіт.append({"джерело": "багаторічна вегетація", "вага": вага,
                         "деталі": "{} · років {}".format(опис.get("індекс"),
                                                          опис.get("років"))})

        elif вид == "яскравість_ґрунту":
            роки = джерело.get("роки") or []
            журнал.сказати("Шукаю знімки з відкритим ґрунтом…")
            шари, опис = sources.яскравість_ґрунту(контур, роки, налаштування, база, журнал)
            if not шари:
                raise ValueError("Яскравість ґрунту взяти не вдалось: " + опис.get("причина", ""))
            зібрані["яскравість_ґрунту"] = (шари["яскравість_ґрунту"], вага)
            звіт.append({"джерело": "яскравість голого ґрунту", "вага": вага,
                         "деталі": "сцен {}".format(опис.get("сцен"))})

        elif вид == "рельєф":
            звідки = джерело.get("джерело_висоти") or "dem"
            if isinstance(звідки, dict):
                # висота з власного сканування: RTK точніший за будь-який DEM
                журнал.сказати("Беру рельєф із власного сканування…")
                точки = _точковий_шар(звідки, контур)
                атрибут = звідки.get("атрибут")
                висота = sources.з_точок(точки, атрибут, сітка, журнал, назва="RTK-висота")
                if висота is None:
                    raise ValueError("У шарі рельєфу немає придатних висот")
                опис = {"джерело": "RTK-сканування, колонка {}".format(атрибут)}
            else:
                журнал.сказати("Беру рельєф із DEM…")
                шари_dem, опис = sources.рельєф(контур, журнал)
                if not шари_dem:
                    raise ValueError("Рельєф взяти не вдалось: " + опис.get("причина", ""))
                висота = шари_dem["висота"]

            шари = water.шари_води(висота, сітка["крок"], журнал)
            показники = джерело.get("показники") or ["висота", "схил", "кривина",
                                                     "індекс_зволоження"]
            for показник in показники:
                if показник in шари:
                    зібрані[показник] = (шари[показник], вага)
            звіт.append({"джерело": "рельєф і вода", "вага": вага,
                         "деталі": "{} · {}".format(опис.get("джерело", "DEM"),
                                                    ", ".join(показники))})

        elif вид == "шар":
            ключ = джерело.get("ключ")
            атрибут = джерело.get("атрибут")
            точки = _точковий_шар(джерело, контур)
            if атрибут not in точки.columns:
                raise ValueError("У шарі «{}» немає колонки {}".format(ключ, атрибут))
            поверхня = sources.з_точок(точки, атрибут, сітка, журнал, назва=ключ)
            if поверхня is None:
                raise ValueError("Шар «{}» не дав жодного придатного значення".format(ключ))
            назва_шару = джерело.get("як_називати") or атрибут
            зібрані[назва_шару] = (поверхня, вага)
            звіт.append({"джерело": джерело.get("назва") or ключ, "вага": вага,
                         "деталі": "колонка {}".format(атрибут)})
        else:
            raise ValueError("Невідоме джерело зонування: {}".format(вид))

    if not зібрані:
        raise ValueError("Не вказано жодного джерела, за яким різати поле.")
    return зібрані, звіт


def _звести(зібрані, поле, журнал):
    """Приводить джерела до спільної шкали і змішує за вагами."""
    складові, ваги = [], []
    for назва, (поверхня, вага) in зібрані.items():
        значення = поверхня[поле]
        добрі = np.isfinite(значення)
        if добрі.sum() < 20:
            журнал.сказати("  {} — майже немає даних, у суміш не бере участі".format(назва))
            continue
        середнє = float(np.mean(значення[добрі]))
        розкид = float(np.std(значення[добрі]))
        if розкид <= 1e-9:
            журнал.сказати("  {} — однакове по всьому полю, різати за ним нічого".format(назва))
            continue
        приведене = np.where(np.isfinite(поверхня), (поверхня - середнє) / розкид, 0.0)
        складові.append(np.clip(приведене, -3, 3) * вага)
        ваги.append(вага)

    if not складові:
        raise ValueError("Жодне з джерел не має різниці по полю — зони будувати нема з чого.")
    суміш = np.sum(складові, axis=0) / max(sum(ваги), 1e-9)
    return суміш.astype("float32")



def _точковий_шар(джерело, контур):
    """Читає зареєстрований шар поля і кладе його в систему координат поля."""
    import geopandas as gpd

    шлях = джерело.get("_шлях")
    if not шлях or not os.path.isfile(шлях):
        raise ValueError("Шар «{}» не знайдено у полі".format(джерело.get("ключ")))
    назви = gpd.list_layers(шлях)
    точки = gpd.read_file(шлях, layer=назви["name"].iloc[0] if len(назви) else None)
    return точки.to_crs(контур.crs)


def ландшафтна_вісь(зібрані, поле):
    """Вісь «здута вершина → волога западина», уздовж якої нумеруються зони.

    Номер зони має щось означати. Якщо нумерувати за середнім значенням
    суміші, число залежить від того, що саме змішали, і на сусідньому полі
    означатиме інше. Тому нумеруємо вздовж фізичної осі ландшафту:

      вище за індексом зволоження  → нижче в рельєфі, вода стоїть;
      увігнуте (кривина мінус)     → сюди наносить;
      вища електропровідність      → важчий, вологіший, іноді засолений ґрунт;
      вища відносна висота         → навпаки, здуває.

    Так зона 1 завжди означає найсухіше й найбільш здуте місце поля, а
    остання — найвологіше, незалежно від того, чим саме різали.
    """
    внески = []
    for назва, знак in (("індекс_зволоження", +1.0), ("кривина", -1.0),
                        ("EC_мала", +1.0), ("EC_велика", +1.0),
                        ("висота", -1.0), ("положення_в_рельєфі", -1.0)):
        якщо = зібрані.get(назва)
        if not якщо:
            continue
        поверхня = якщо[0]
        значення = поверхня[поле]
        добрі = np.isfinite(значення)
        if добрі.sum() < 20:
            continue
        розкид = float(np.std(значення[добрі]))
        if розкид <= 1e-9:
            continue
        середнє = float(np.mean(значення[добрі]))
        внески.append(знак * np.where(np.isfinite(поверхня),
                                      (поверхня - середнє) / розкид, 0.0))
    if not внески:
        return None
    return np.sum(внески, axis=0).astype("float32")


def перевірити_зонами(мітки, поле, перевірки, журнал):
    """Скільки мінливості врожаю чи вегетації пояснюють ці зони.

    Це і є чесна відповідь на питання «а чи вони взагалі щось означають».
    Зони будувались не за врожайністю, тож збіг із нею — незалежний доказ,
    а не самоперевірка.
    """
    підсумок = []
    for назва, поверхня in перевірки.items():
        значення = поверхня[поле]
        мітки_поля = мітки[поле]
        добрі = np.isfinite(значення) & (мітки_поля > 0)
        if добрі.sum() < 100:
            continue
        загальна = float(np.var(значення[добрі]))
        if загальна <= 0:
            continue
        всередині = 0.0
        for зона in np.unique(мітки_поля[добрі]):
            свої = значення[добрі & (мітки_поля == зона)]
            if свої.size:
                всередині += свої.size * float(np.var(свої))
        частка = 1.0 - (всередині / добрі.sum()) / загальна
        підсумок.append({"шар": назва, "пояснено": round(частка * 100, 1)})
        журнал.сказати("  зони пояснюють {:.0f} % мінливості: {}".format(частка * 100, назва))
    return підсумок


def групи_відбору(мітки, поле, груп, крок, журнал):
    """Зони під карту — окремо, зразки — окремо.

    Десять зон дають розділення для карти внесення, але десять зразків із
    поля ніхто не возитиме. Тому сусідні зони збираються в групи, і на кожну
    групу береться одна точка — у серцевині найбільшого суцільного шматка,
    подалі від меж, де ґрунт уже перехідний.
    """
    from scipy.ndimage import distance_transform_edt, label

    номери = np.unique(мітки[мітки > 0])
    if not номери.size:
        return [], np.zeros_like(мітки)
    груп = int(max(1, min(груп, len(номери))))
    розбиття = np.array_split(номери, груп)

    карта_груп = np.zeros_like(мітки)
    точки = []
    for номер, зони_групи in enumerate(розбиття, start=1):
        своє = np.isin(мітки, зони_групи)
        карта_груп[своє] = номер
        шматки, скільки = label(своє)
        if not скільки:
            continue
        найбільший = max(range(1, скільки + 1), key=lambda і: int((шматки == і).sum()))
        це = шматки == найбільший
        глибина = distance_transform_edt(це)
        р, с = np.unravel_index(int(np.argmax(глибина)), глибина.shape)
        точки.append({
            "група": номер,
            "зони": ", ".join(str(int(з)) for з in зони_групи),
            "клітинка": (int(р), int(с)),
            "площа_га": round(float(своє.sum()) * (крок ** 2) / 10000.0, 2),
            "від_межі_м": round(float(глибина[р, с]) * крок, 1),
        })
    журнал.сказати("  план відбору: {} груп із {} зон, точка в серцевині кожної".format(
        len(точки), len(номери)))
    return точки, карта_груп


def точки_відбору_у_шар(точки, перетворення, crs):
    import geopandas as gpd

    рядки, геометрії = [], []
    for т in точки:
        р, с = т["клітинка"]
        x = перетворення.c + (с + 0.5) * перетворення.a
        y = перетворення.f + (р + 0.5) * перетворення.e
        геометрії.append((x, y))
        рядки.append({"SAMPLE_ID": т["група"], "ZONES": т["зони"],
                      "AREA_HA": т["площа_га"], "EDGE_M": т["від_межі_м"]})
    if not рядки:
        return None
    return gpd.GeoDataFrame(
        рядки, geometry=gpd.points_from_xy([г[0] for г in геометрії],
                                           [г[1] for г in геометрії]), crs=crs)



def _коректори(сеанс, контур, сітка, завдання, зібрані, журнал):
    """Шари-свідки: вони не малюють зони, вони не дають EC збрехати."""
    свідки = {}
    for назва in ("індекс_зволоження", "кривина", "висота"):
        якщо = зібрані.get(назва)
        if якщо:
            свідки["рельєф: " + назва] = якщо[0]

    for коректор in (завдання.get("коректори") or []):
        if коректор.get("вид") != "вегетація":
            continue
        роки = коректор.get("роки") or []
        індекс = коректор.get("індекс") or "NDVI"
        журнал.сказати("Беру вегетацію як свідка проти слідів техніки ({}, {})…".format(
            індекс, ", ".join(str(р) for р in роки)))
        шари, опис = sources.вегетація_багаторічна(
            контур, роки, сеанс.налаштування, сеанс.база, журнал, індекс)
        if шари:
            свідки["вегетація " + індекс] = шари["вегетація"]
        else:
            журнал.сказати("  вегетації немає ({}) — EC лишається без цього свідка".format(
                опис.get("причина", "")))
    return свідки


def _почистити_ec(зібрані, поле, сітка, свідки, журнал, правити=False):
    """Перевіряє кожен шар EC. Числа міняє тільки коли про це попросили."""
    звіти = []
    for назва in list(зібрані.keys()):
        if not назва.upper().startswith("EC"):
            continue
        поверхня, вага = зібрані[назва]
        очищена, звіт = ec_clean.почистити(поверхня, поле, сітка["крок"], свідки,
                                           журнал=журнал, назва=назва)
        звіт["застосовано"] = bool(правити)
        if правити:
            зібрані[назва] = (очищена, вага)
        звіти.append(звіт)
    return звіти


