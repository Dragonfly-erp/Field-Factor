# -*- coding: utf-8 -*-
"""Фаза 17: зони менеджменту з уже нормалізованої карти.

Зона має бути цілим шматком поля, яким можна керувати технікою, а не
розсипом пікселів. Тому після кластеризації йде згладжування, викидання
острівців і зшивання дрібноти з сусідом.
"""

import os
import traceback

import numpy as np

from app.core import export_points, reading

ВАГА_ДОВІРИ = {"HIGH": 1.0, "MED": 0.6, "LOW": 0.3}


def виконати(сеанс, межі):
    журнал = сеанс.журнал
    try:
        сеанс.підсумок_зон = _зони(сеанс, межі)
    except Exception as помилка:
        traceback.print_exc()
        журнал.збій(str(помилка))
        return
    журнал.кінець()


# ------------------------------------------------------------


def _зони(сеанс, межі):
    import geopandas as gpd

    журнал = сеанс.журнал
    підсумок = сеанс.підсумок
    тека = підсумок["_тека"]
    основа = підсумок["_основа"]

    журнал.сказати("Читаю нормалізовану карту…", 5, "Читання")
    точки = gpd.read_file(os.path.join(тека, "{}_yield_normalized_points.gpkg".format(основа)),
                          layer="yield_points")
    контур, _ = reading.прочитати_контур(сеанс)
    точки = точки.to_crs(контур.crs)

    мін = int(межі.get("мін") or 3)
    ціль = int(межі.get("ціль") or 4)
    макс = int(межі.get("макс") or 6)
    площа_поля = float(контур.area.iloc[0]) / 10000.0

    мін_площа = межі.get("мін_площа_га")
    if not мін_площа:
        мін_площа = max(0.5, площа_поля / (макс * 6))
        журнал.сказати(
            "Найменшу зону не задано — прийнято {:.2f} га (поле {:.1f} га, "
            "щоб зони лишались робочими для техніки).".format(мін_площа, площа_поля)
        )
    мін_площа = float(мін_площа)

    # ---- сітка --------------------------------------------------------
    журнал.сказати("Кладу карту на сітку…", 15, "Сітка")
    крок = max(5.0, min(20.0, np.sqrt(площа_поля * 10000 / 4000)))
    растр, перетворення, поле = _на_сітку(точки, контур, крок)

    # ---- скільки зон --------------------------------------------------
    журнал.сказати("Приміряю кількість зон…", 30, "Кількість зон")
    значення = растр[поле]
    придатні = np.isfinite(значення)
    if придатні.sum() < 50:
        raise ValueError("Точок замало, щоб різати поле на зони.")

    кількість, пояснення = _скільки_зон(значення[придатні], мін, ціль, макс, журнал)
    журнал.сказати("  " + пояснення)

    # ---- кластери -----------------------------------------------------
    журнал.сказати("Ріжу поле…", 50, "Кластери")
    мітки = _кластери(растр, поле, кількість)

    журнал.сказати("Зшиваю дрібноту і згладжую межі…", 65, "Згладжування")
    мітки = _згладити(мітки, поле)
    мітки = _прибрати_дрібне(мітки, поле, крок, мін_площа, журнал)

    # ---- полігони -----------------------------------------------------
    журнал.сказати("Роблю полігони…", 78, "Полігони")
    полігони = _полігонізувати(мітки, перетворення, контур)
    if not len(полігони):
        raise ValueError("Полігони не вийшли — карта надто однорідна.")

    полігони = _атрибути(полігони, точки, журнал)

    # ---- віддача ------------------------------------------------------
    журнал.сказати("Складаю файли…", 92, "Віддача")
    імʼя = "{}_management_zones".format(основа)
    файли = export_points.записати_шейп(полігони, os.path.join(тека, імʼя + ".shp"))
    файли.append(export_points.таблиця_csv(
        os.path.join(тека, "zones_field_dictionary.csv"),
        ["поле", "що означає"],
        [["ZONE_ID", "номер зони"],
         ["YLD_AVG", "середня нормалізована врожайність зони, кг/га"],
         ["VEG_AVG", "середній вегетаційний показник; порожньо, якщо супутник не використовувався"],
         ["ELEV_AVG", "середня висота, м"],
         ["MOIST_AVG", "середня виміряна вологість зерна, %"],
         ["AREA_HA", "площа зони, га"],
         ["N_PTS", "скільки точок нормалізованої карти лягло в зону"],
         ["CONF_AVG", "середня довіра до точок зони: 1 — усе виміряне, менше — є добудоване"]],
    ))
    архів = export_points.запакувати(os.path.join(тека, імʼя + ".zip"), файли)

    журнал.сказати("Готово: {} зон.".format(len(полігони)), 100, "Готово")
    return {
        "зон": int(len(полігони)),
        "найменша_га": round(float(полігони["AREA_HA"].min()), 2),
        "пояснення": пояснення,
        "файли": [{"імʼя": os.path.basename(архів),
                   "опис": "Полігони зон менеджменту під SMS",
                   "байтів": os.path.getsize(архів)}],
    }


# ------------------------------------------------------------ сітка


def _на_сітку(точки, контур, крок):
    from rasterio.features import rasterize
    from rasterio.transform import from_origin
    from scipy.ndimage import distance_transform_edt

    xmin, ymin, xmax, ymax = контур.total_bounds
    стовпців = int(np.ceil((xmax - xmin) / крок)) + 1
    рядків = int(np.ceil((ymax - ymin) / крок)) + 1
    перетворення = from_origin(xmin, ymax, крок, крок)

    поле = rasterize([(контур.geometry.iloc[0], 1)], out_shape=(рядків, стовпців),
                     transform=перетворення, fill=0, dtype="uint8").astype(bool)

    рядки = np.clip(((ymax - точки.geometry.y.to_numpy()) / крок).astype("int64"), 0, рядків - 1)
    стовпці = np.clip(((точки.geometry.x.to_numpy() - xmin) / крок).astype("int64"), 0, стовпців - 1)
    ключ = рядки * стовпців + стовпці
    значення = точки["YLD_KGHA"].to_numpy(dtype="float64")

    сума = np.bincount(ключ, weights=значення, minlength=рядків * стовпців)
    кількість = np.bincount(ключ, minlength=рядків * стовпців)
    середнє = np.full(рядків * стовпців, np.nan)
    заповнені = кількість > 0
    середнє[заповнені] = сума[заповнені] / кількість[заповнені]
    растр = середнє.reshape(рядків, стовпців)

    # порожні клітинки всередині поля беруть значення найближчої заповненої
    порожні = ~np.isfinite(растр) & поле
    if порожні.any():
        _, індекси = distance_transform_edt(~np.isfinite(растр), return_indices=True)
        растр[порожні] = растр[індекси[0][порожні], індекси[1][порожні]]

    return растр, перетворення, поле


# ------------------------------------------------------------ кількість зон


def _скільки_зон(значення, мін, ціль, макс, журнал):
    from sklearn.cluster import KMeans

    дані = значення.reshape(-1, 1)
    загальна = float(np.var(дані))
    if загальна <= 0:
        return мін, "поле однорідне — узято найменшу дозволену кількість"

    пояснена = {}
    for к in range(мін, макс + 1):
        модель = KMeans(n_clusters=к, n_init=6, random_state=13).fit(дані)
        всередині = модель.inertia_ / len(дані)
        пояснена[к] = 1.0 - всередині / загальна
        журнал.сказати("  {} зон — пояснює {:.0f} % розкиду".format(к, пояснена[к] * 100))

    обране = макс
    for к in range(мін, макс):
        приріст = пояснена[к + 1] - пояснена[к]
        if приріст < 0.03:
            обране = к
            break
    if abs(обране - ціль) <= 1:
        обране = ціль
    return обране, (
        "узято {} зон: {} пояснює {:.0f} % розкиду врожайності, а кожна наступна "
        "додає менше трьох відсотків".format(обране, обране, пояснена[обране] * 100)
    )


def _кластери(растр, поле, кількість):
    from sklearn.cluster import KMeans

    значення = растр[поле].reshape(-1, 1)
    добрі = np.isfinite(значення).ravel()
    модель = KMeans(n_clusters=кількість, n_init=8, random_state=13).fit(значення[добрі])

    # нумеруємо від найгіршої зони до найкращої — так читає агроном
    порядок = np.argsort(модель.cluster_centers_.ravel())
    перенумерація = np.zeros(кількість, dtype="int32")
    перенумерація[порядок] = np.arange(1, кількість + 1)

    плоскі = np.zeros(значення.shape[0], dtype="int32")
    плоскі[добрі] = перенумерація[модель.labels_]
    мітки = np.zeros(растр.shape, dtype="int32")
    мітки[поле] = плоскі
    return мітки


# ------------------------------------------------------------ згладжування


def _згладити(мітки, поле, разів=2):
    from scipy.ndimage import generic_filter

    def більшість(вікно):
        значення = вікно[вікно > 0]
        if not значення.size:
            return 0
        числа, кількість = np.unique(значення, return_counts=True)
        return числа[np.argmax(кількість)]

    результат = мітки
    for _ in range(разів):
        результат = generic_filter(результат, більшість, size=3, mode="nearest")
        результат[~поле] = 0
    return результат.astype("int32")


def _прибрати_дрібне(мітки, поле, крок, мін_площа_га, журнал):
    from scipy.ndimage import binary_dilation, label

    клітинок_треба = max(4, int(мін_площа_га * 10000 / (крок ** 2)))
    прибрано = 0
    for _ in range(6):
        зміни = 0
        for зона in np.unique(мітки[мітки > 0]):
            шматки, скільки = label(мітки == зона)
            for номер in range(1, скільки + 1):
                це = шматки == номер
                if це.sum() >= клітинок_треба:
                    continue
                сусіди = binary_dilation(це) & ~це & поле
                значення = мітки[сусіди]
                значення = значення[значення > 0]
                if not значення.size:
                    continue
                числа, кількість = np.unique(значення, return_counts=True)
                мітки[це] = числа[np.argmax(кількість)]
                прибрано += int(це.sum())
                зміни += 1
        if not зміни:
            break
    if прибрано:
        журнал.сказати("  острівців менших за {:.2f} га зшито з сусідами: {} клітинок".format(
            мін_площа_га, прибрано))
    return мітки


def _полігонізувати(мітки, перетворення, контур):
    import geopandas as gpd
    from rasterio.features import shapes
    from shapely.geometry import shape
    from shapely.ops import unary_union

    зібране = {}
    for геометрія, значення in shapes(мітки.astype("int32"), mask=мітки > 0,
                                      transform=перетворення):
        зібране.setdefault(int(значення), []).append(shape(геометрія))

    рядки = []
    межа = контур.geometry.iloc[0]
    for зона, шматки in sorted(зібране.items()):
        обʼєднане = unary_union(шматки).buffer(0).intersection(межа)
        if обʼєднане.is_empty:
            continue
        рядки.append({"ZONE_ID": зона, "geometry": обʼєднане})
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=контур.crs)


def _атрибути(полігони, точки, журнал):
    import geopandas as gpd
    import pandas as pd

    злиття = gpd.sjoin(точки, полігони[["ZONE_ID", "geometry"]], how="inner", predicate="within")
    злиття["_ДОВІРА"] = злиття["CONF"].map(ВАГА_ДОВІРИ).fillna(0.5)

    def середнє(назва):
        if назва not in злиття.columns:
            return None
        числа = pd.to_numeric(злиття[назва], errors="coerce")
        return числа.groupby(злиття["ZONE_ID"]).mean()

    зведення = pd.DataFrame({"YLD_AVG": середнє("YLD_KGHA")})
    for колонка, звідки in (("VEG_AVG", "VEG_IDX"), ("ELEV_AVG", "ELEV_M"),
                            ("MOIST_AVG", "MOIST_RAW")):
        значення = середнє(звідки)
        зведення[колонка] = значення if значення is not None else np.nan
    зведення["N_PTS"] = злиття.groupby("ZONE_ID").size()
    зведення["CONF_AVG"] = злиття.groupby("ZONE_ID")["_ДОВІРА"].mean()

    полігони = полігони.merge(зведення, left_on="ZONE_ID", right_index=True, how="left")
    полігони["AREA_HA"] = полігони.area / 10000.0

    for колонка in ("YLD_AVG", "VEG_AVG", "ELEV_AVG", "MOIST_AVG", "AREA_HA", "CONF_AVG"):
        полігони[колонка] = pd.to_numeric(полігони[колонка], errors="coerce").round(3)
    полігони["N_PTS"] = полігони["N_PTS"].fillna(0).astype("int64")

    порожні = [к for к in ("VEG_AVG", "MOIST_AVG", "ELEV_AVG") if полігони[к].isna().all()]
    if порожні:
        журнал.сказати("  без даних лишились поля: {} — вони порожні, "
                       "а не вигадані".format(", ".join(порожні)))

    порядок = ["ZONE_ID", "YLD_AVG", "VEG_AVG", "ELEV_AVG", "MOIST_AVG",
               "AREA_HA", "N_PTS", "CONF_AVG", "geometry"]
    return полігони[порядок]
