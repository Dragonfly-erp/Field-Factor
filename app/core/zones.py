# -*- coding: utf-8 -*-
"""Зонування поля за одним джерелом або за кількома з вагами.

Комбіноване зонування тут не окремий режим, а звичайний випадок: одне
джерело — це список із одного елемента. Тому будь-яка пара «вегетація +
рельєф» чи «врожайність + електропровідність» працює тим самим кодом, і
поводиться так само передбачувано.

Зона має бути шматком поля, яким можна керувати технікою, а не розсипом
пікселів. Тому після кластеризації йде згладжування, зшивання острівців і
обрізання строго по контуру.
"""

import os
import traceback

import numpy as np

from app.core import export_points, reading, satellite, sources

# Як називати колонку в шейпі: DBF довгих імен не тримає
КОРОТКО = {
    "вегетація": "VEG_AVG",
    "мінливість_вегетації": "VEG_STD",
    "яскравість_ґрунту": "SOIL_BRT",
    "висота": "ELEV_AVG",
    "схил": "SLOPE_AVG",
    "положення_в_рельєфі": "TPI_AVG",
}

ЛЮДСЬКІ_НАЗВИ = {
    "вегетація": "багаторічна вегетація",
    "мінливість_вегетації": "мінливість вегетації між роками",
    "яскравість_ґрунту": "яскравість голого ґрунту",
    "висота": "висота",
    "схил": "схил",
    "положення_в_рельєфі": "положення в рельєфі",
}


def виконати(сеанс, завдання):
    журнал = сеанс.журнал
    try:
        сеанс.підсумок_зон = _зони(сеанс, завдання or {})
    except Exception as помилка:
        traceback.print_exc()
        журнал.збій(str(помилка))
        return
    журнал.кінець()


# ------------------------------------------------------------ джерела


def _поверхні(сеанс, контур, сітка, джерела, журнал):
    """Кожне джерело → поверхня на спільній сітці. Повертає (шари, звіт)."""
    зібрані, звіт = {}, []
    налаштування = сеанс.налаштування
    база = сеанс.база

    for джерело in джерела:
        вид = джерело.get("вид")
        вага = float(джерело.get("вага") or 1.0)

        if вид == "вегетація":
            роки = джерело.get("роки") or []
            журнал.сказати("Беру багаторічну вегетацію: {}…".format(
                ", ".join(str(р) for р in роки)))
            шари, опис = sources.вегетація_багаторічна(контур, роки, налаштування, база, журнал)
            if not шари:
                raise ValueError("Вегетацію взяти не вдалось: " + опис.get("причина", ""))
            зібрані["вегетація"] = (шари["вегетація"], вага)
            if джерело.get("з_мінливістю"):
                зібрані["мінливість_вегетації"] = (шари["мінливість_вегетації"], вага * 0.5)
            звіт.append({"джерело": "багаторічна вегетація", "вага": вага,
                         "деталі": "років {}".format(опис.get("років"))})

        elif вид == "яскравість_ґрунту":
            роки = джерело.get("роки") or []
            журнал.сказати("Шукаю знімки з відкритим ґрунтом…")
            шари, опис = sources.яскравість_ґрунту(контур, роки, налаштування, база, журнал)
            if not шари:
                raise ValueError("Яскравість ґрунту взяти не вдалось: " + опис.get("причина", ""))
            зібрані["яскравість_ґрунту"] = (шари["яскравість_ґрунту"], вага)
            звіт.append({"джерело": "яскравість голого ґрунту", "вага": вага,
                         "деталі": "сцен {}".format(опис.get("сцен"))})

        elif вид == "рельєф":
            журнал.сказати("Беру рельєф…")
            шари, опис = sources.рельєф(контур, журнал)
            if not шари:
                raise ValueError("Рельєф взяти не вдалось: " + опис.get("причина", ""))
            показники = джерело.get("показники") or ["висота"]
            for показник in показники:
                if показник in шари:
                    зібрані[показник] = (шари[показник], вага)
            звіт.append({"джерело": "рельєф", "вага": вага,
                         "деталі": ", ".join(показники)})

        elif вид == "шар":
            ключ = джерело.get("ключ")
            атрибут = джерело.get("атрибут")
            шлях = джерело.get("_шлях")
            if not шлях or not os.path.isfile(шлях):
                raise ValueError("Шар «{}» не знайдено у полі".format(ключ))
            import geopandas as gpd

            назви = gpd.list_layers(шлях)
            точки = gpd.read_file(шлях, layer=назви["name"].iloc[0] if len(назви) else None)
            точки = точки.to_crs(контур.crs)
            if атрибут not in точки.columns:
                raise ValueError("У шарі «{}» немає колонки {}".format(ключ, атрибут))
            поверхня = sources.з_точок(точки, атрибут, сітка, журнал, назва=ключ)
            if поверхня is None:
                raise ValueError("Шар «{}» не дав жодного придатного значення".format(ключ))
            зібрані[атрибут] = (поверхня, вага)
            звіт.append({"джерело": джерело.get("назва") or ключ, "вага": вага,
                         "деталі": "колонка {}".format(атрибут)})
        else:
            raise ValueError("Невідоме джерело зонування: {}".format(вид))

    if not зібрані:
        raise ValueError("Не вказано жодного джерела, за яким різати поле.")
    return зібрані, звіт


def _звести(зібрані, поле, журнал):
    """Приводить джерела до спільної шкали і змішує за вагами."""
    складові, ваги = [], []
    for назва, (поверхня, вага) in зібрані.items():
        значення = поверхня[поле]
        добрі = np.isfinite(значення)
        if добрі.sum() < 20:
            журнал.сказати("  {} — майже немає даних, у суміш не бере участі".format(назва))
            continue
        середнє = float(np.mean(значення[добрі]))
        розкид = float(np.std(значення[добрі]))
        if розкид <= 1e-9:
            журнал.сказати("  {} — однакове по всьому полю, різати за ним нічого".format(назва))
            continue
        приведене = np.where(np.isfinite(поверхня), (поверхня - середнє) / розкид, 0.0)
        складові.append(np.clip(приведене, -3, 3) * вага)
        ваги.append(вага)

    if not складові:
        raise ValueError("Жодне з джерел не має різниці по полю — зони будувати нема з чого.")
    суміш = np.sum(складові, axis=0) / max(sum(ваги), 1e-9)
    return суміш.astype("float32")


# ------------------------------------------------------------ головне


def _зони(сеанс, завдання):
    import geopandas as gpd

    журнал = сеанс.журнал
    межі_зон = завдання.get("зони") or {}
    джерела = завдання.get("джерела") or []

    журнал.сказати("Читаю контур поля…", 4, "Контур")
    контур, _ = reading.прочитати_контур(сеанс)
    площа_поля = float(контур.area.iloc[0]) / 10000.0
    сітка = satellite.сітка_поля(контур)

    журнал.сказати("Готую джерела…", 12, "Джерела")
    зібрані, звіт_джерел = _поверхні(сеанс, контур, сітка, джерела, журнал)

    поле = _маска_поля(контур, сітка)
    журнал.сказати("Зводжу джерела до спільної шкали…", 42, "Зведення")
    суміш = _звести(зібрані, поле, журнал)

    мін = int(межі_зон.get("мін") or 3)
    ціль = int(межі_зон.get("ціль") or 4)
    макс = int(межі_зон.get("макс") or 6)
    мін_площа = межі_зон.get("мін_площа_га")
    if not мін_площа:
        мін_площа = max(0.5, площа_поля / (макс * 6))
        журнал.сказати("Найменшу зону не задано — прийнято {:.2f} га для поля "
                       "{:.1f} га.".format(мін_площа, площа_поля))
    мін_площа = float(мін_площа)

    журнал.сказати("Приміряю кількість зон…", 52, "Кількість зон")
    кількість, пояснення = _скільки_зон(суміш[поле], мін, ціль, макс, журнал)
    журнал.сказати("  " + пояснення)

    журнал.сказати("Ріжу поле…", 64, "Кластери")
    мітки = _кластери(суміш, поле, кількість)
    журнал.сказати("Зшиваю дрібноту і згладжую межі…", 72, "Згладжування")
    мітки = _згладити(мітки, поле)
    мітки = _прибрати_дрібне(мітки, поле, сітка["крок"], мін_площа, журнал)

    журнал.сказати("Роблю полігони…", 82, "Полігони")
    полігони = _полігонізувати(мітки, сітка["перетворення"], контур)
    if not len(полігони):
        raise ValueError("Полігони не вийшли — поле надто однорідне.")

    полігони = _атрибути(полігони, мітки, зібрані, сітка, журнал)

    журнал.сказати("Складаю файли…", 92, "Віддача")
    підсумок = _віддати(сеанс, полігони, звіт_джерел, пояснення, мін_площа)
    журнал.сказати("Готово: {} зон.".format(len(полігони)), 100, "Готово")
    return підсумок


def _маска_поля(контур, сітка):
    from rasterio.features import rasterize

    return rasterize([(контур.geometry.iloc[0], 1)],
                     out_shape=(сітка["висота"], сітка["ширина"]),
                     transform=сітка["перетворення"], fill=0, dtype="uint8").astype(bool)


# ------------------------------------------------------------ кластери


def _скільки_зон(значення, мін, ціль, макс, журнал):
    from sklearn.cluster import KMeans

    дані = значення[np.isfinite(значення)].reshape(-1, 1)
    загальна = float(np.var(дані))
    if загальна <= 0:
        return мін, "поле однорідне — узято найменшу дозволену кількість"

    зразок = дані if len(дані) <= 30000 else _зразок(дані)
    пояснена = {}
    for к in range(мін, макс + 1):
        модель = KMeans(n_clusters=к, n_init=6, random_state=13).fit(зразок)
        пояснена[к] = 1.0 - (модель.inertia_ / len(зразок)) / загальна
        журнал.сказати("  {} зон — пояснює {:.0f} % розкиду".format(к, пояснена[к] * 100))

    обране = макс
    for к in range(мін, макс):
        if пояснена[к + 1] - пояснена[к] < 0.03:
            обране = к
            break
    if abs(обране - ціль) <= 1:
        обране = ціль
    return обране, ("узято {} зон: вони пояснюють {:.0f} % розкиду, а кожна наступна "
                    "додає менше трьох відсотків".format(обране, пояснена[обране] * 100))


def _зразок(дані):
    вибір = np.random.RandomState(13).choice(len(дані), 30000, replace=False)
    return дані[вибір]


def _кластери(суміш, поле, кількість):
    from sklearn.cluster import KMeans

    значення = суміш[поле].reshape(-1, 1)
    добрі = np.isfinite(значення).ravel()
    модель = KMeans(n_clusters=кількість, n_init=8, random_state=13).fit(значення[добрі])

    # нумеруємо від найгіршої зони до найкращої — так читає агроном
    порядок = np.argsort(модель.cluster_centers_.ravel())
    перенумерація = np.zeros(кількість, dtype="int32")
    перенумерація[порядок] = np.arange(1, кількість + 1)

    плоскі = np.zeros(значення.shape[0], dtype="int32")
    плоскі[добрі] = перенумерація[модель.labels_]
    мітки = np.zeros(суміш.shape, dtype="int32")
    мітки[поле] = плоскі
    return мітки


def _згладити(мітки, поле, разів=2):
    from scipy.ndimage import generic_filter

    def більшість(вікно):
        значення = вікно[вікно > 0]
        if not значення.size:
            return 0
        числа, кількість = np.unique(значення, return_counts=True)
        return числа[np.argmax(кількість)]

    результат = мітки
    for _ in range(разів):
        результат = generic_filter(результат, більшість, size=3, mode="nearest")
        результат[~поле] = 0
    return результат.astype("int32")


def _прибрати_дрібне(мітки, поле, крок, мін_площа_га, журнал):
    from scipy.ndimage import binary_dilation, label

    треба = max(4, int(мін_площа_га * 10000 / (крок ** 2)))
    прибрано = 0
    for _ in range(6):
        зміни = 0
        for зона in np.unique(мітки[мітки > 0]):
            шматки, скільки = label(мітки == зона)
            for номер in range(1, скільки + 1):
                це = шматки == номер
                if це.sum() >= треба:
                    continue
                сусіди = binary_dilation(це) & ~це & поле
                значення = мітки[сусіди]
                значення = значення[значення > 0]
                if not значення.size:
                    continue
                числа, кількість = np.unique(значення, return_counts=True)
                мітки[це] = числа[np.argmax(кількість)]
                прибрано += int(це.sum())
                зміни += 1
        if not зміни:
            break
    if прибрано:
        журнал.сказати("  острівців менших за {:.2f} га зшито з сусідами: {} "
                       "клітинок".format(мін_площа_га, прибрано))
    return мітки


def _полігонізувати(мітки, перетворення, контур):
    import geopandas as gpd
    from rasterio.features import shapes
    from shapely.geometry import shape
    from shapely.ops import unary_union

    зібране = {}
    for геометрія, значення in shapes(мітки.astype("int32"), mask=мітки > 0,
                                      transform=перетворення):
        зібране.setdefault(int(значення), []).append(shape(геометрія))

    межа = контур.geometry.iloc[0]
    рядки = []
    for зона, шматки in sorted(зібране.items()):
        обʼєднане = unary_union(шматки).buffer(0).intersection(межа)
        if обʼєднане.is_empty:
            continue
        рядки.append({"ZONE_ID": зона, "geometry": обʼєднане})
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=контур.crs)


def _атрибути(полігони, мітки, зібрані, сітка, журнал):
    """Кожна зона отримує середнє по КОЖНОМУ джерелу — у його власних одиницях."""
    import pandas as pd

    рядки = {}
    for назва, (поверхня, _) in зібрані.items():
        колонка = КОРОТКО.get(назва, назва.upper()[:10])
        значення = {}
        for зона in np.unique(мітки[мітки > 0]):
            свої = поверхня[(мітки == зона) & np.isfinite(поверхня)]
            значення[int(зона)] = float(np.mean(свої)) if свої.size else np.nan
        рядки[колонка] = значення

    зведення = pd.DataFrame(рядки)
    полігони = полігони.merge(зведення, left_on="ZONE_ID", right_index=True, how="left")
    полігони["AREA_HA"] = полігони.area / 10000.0
    for колонка in полігони.columns:
        if колонка in ("geometry", "ZONE_ID"):
            continue
        полігони[колонка] = pd.to_numeric(полігони[колонка], errors="coerce").round(3)

    порядок = ["ZONE_ID", "AREA_HA"] + [к for к in полігони.columns
                                        if к not in ("ZONE_ID", "AREA_HA", "geometry")]
    журнал.сказати("  у кожній зоні: {}".format(", ".join(порядок[2:])))
    return полігони[порядок + ["geometry"]]


# ------------------------------------------------------------ віддача


def _віддати(сеанс, полігони, звіт_джерел, пояснення, мін_площа):
    основа = "{}_{}".format(
        (сеанс.паспорт.get("поле") or "поле").replace(" ", "_"),
        сеанс.паспорт.get("рік") or ""
    ).strip("_")
    тека = сеанс.шлях("3_віддача")
    os.makedirs(тека, exist_ok=True)
    імʼя = "{}_zones".format(основа)

    файли = export_points.записати_шейп(полігони, os.path.join(тека, імʼя + ".shp"))
    словник = [["ZONE_ID", "номер зони, від найгіршої до найкращої"],
               ["AREA_HA", "площа зони, гектарів"]]
    for колонка in полігони.columns:
        if колонка in ("ZONE_ID", "AREA_HA", "geometry"):
            continue
        людське = next((ЛЮДСЬКІ_НАЗВИ[н] for н, к in КОРОТКО.items() if к == колонка), колонка)
        словник.append([колонка, "середнє по зоні: {}".format(людське)])
    файли.append(export_points.таблиця_csv(
        os.path.join(тека, "zones_field_dictionary.csv"), ["поле", "що означає"], словник))

    рядки = ["FieldFactor · зонування", "=" * 60, ""]
    рядки.append("Поле: {}".format(сеанс.паспорт.get("поле")))
    рядки.append("Зон: {}".format(len(полігони)))
    рядки.append("Найменша зона: {:.2f} га (обмеження {:.2f} га)".format(
        float(полігони["AREA_HA"].min()), мін_площа))
    рядки.append("")
    рядки.append("ЗА ЧИМ РІЗАЛИ")
    рядки.append("-" * 60)
    for д in звіт_джерел:
        рядки.append("  {:<34} вага {:<5} {}".format(д["джерело"], д["вага"], д["деталі"]))
    рядки.append("")
    рядки.append("СКІЛЬКИ ЗОН")
    рядки.append("-" * 60)
    рядки.append("  " + пояснення)
    рядки.append("")
    рядки.append("ЗОНИ")
    рядки.append("-" * 60)
    колонки = [к for к in полігони.columns if к != "geometry"]
    рядки.append("  " + "  ".join("{:>10}".format(к) for к in колонки))
    for _, рядок in полігони.iterrows():
        рядки.append("  " + "  ".join("{:>10}".format(
            "{:.2f}".format(рядок[к]) if isinstance(рядок[к], float) else str(рядок[к]))
            for к in колонки))
    файли.append(export_points.звіт_qc(os.path.join(тека, "zones_summary.txt"),
                                       "\n".join(рядки)))

    архів = export_points.запакувати(os.path.join(тека, імʼя + ".zip"), файли)
