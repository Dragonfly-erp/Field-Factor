def _зони(сеанс, завдання):
    import geopandas as gpd

    журнал = сеанс.журнал
    межі_зон = завдання.get("зони") or {}
    джерела = завдання.get("джерела") or []

    журнал.сказати("Читаю контур поля…", 4, "Контур")
    контур, _ = reading.прочитати_контур(сеанс)
    площа_поля = float(контур.area.iloc[0]) / 10000.0
    сітка = satellite.сітка_поля(контур)

    журнал.сказати("Готую джерела…", 12, "Джерела")
    зібрані, звіт_джерел = _поверхні(сеанс, контур, сітка, джерела, журнал)

    поле = _маска_поля(контур, сітка)

    звіт_ec = []
    # Правити EC за замовчуванням НЕ будемо. Поточний фільтр ловить лише
    # частину слідів техніки і зачіпає чисте поле — на перевірці з відомою
    # правдою він зняв 29 % справжніх смуг і 13 % решти. Тому режим один:
    # порахувати, показати в звіті і НЕ чіпати числа, доки не буде зроблено
    # виправлення по проходах сканера, як це вже працює для комбайна.
    if any(н.upper().startswith("EC") for н in зібрані):
        журнал.сказати("Перевіряю електропровідність на сліди техніки…", 34, "Очистка EC")
        свідки = _коректори(сеанс, контур, сітка, завдання, зібрані, журнал)
        правити = bool(завдання.get("чистити_ec"))
        звіт_ec = _почистити_ec(зібрані, поле, сітка, свідки, журнал, правити)
        if not правити:
            журнал.сказати("  числа EC не змінювались: підозріле лише позначено у звіті")

    журнал.сказати("Зводжу джерела до спільної шкали…", 42, "Зведення")
    суміш = _звести(зібрані, поле, журнал)

    мін = int(межі_зон.get("мін") or 3)
    ціль = int(межі_зон.get("ціль") or 4)
    макс = int(межі_зон.get("макс") or 6)
    мін_площа = межі_зон.get("мін_площа_га")
