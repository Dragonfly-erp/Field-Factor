ЧИСЛОВІ = [п["ключ"] for п in ПОЛЯ if п["вид"] == "число"]
СКЛАДНИКИ = ("CaO", "MgO", "K2O", "S", "H2O")

ЗАМОВЧУВАННЯ = dict(тип="карбонат", статус="WORKING",
                    CaO=0.0, MgO=0.0, K2O=0.0, S=0.0, H2O=0.0,
                    максимум=5000, мінімум=500, крок=100)

# Різниця між надрукованою нейтралізуючою здатністю і порахованою зі складу,
# після якої треба питати, а не мовчки брати одну з них.
РОЗБІЖНІСТЬ_CCE = 5.0
ВОДИ_БАГАТО = 5.0     # понад це питання «суха чи волога маса» перестає бути дрібним


# ═══════════════════════════════════════════════════════════════════════
# АРИФМЕТИКА
# ═══════════════════════════════════════════════════════════════════════


def порахувати_CCE(продукт):
    """Нейтралізуюча здатність зі складу. Тільки карбонати: сіль кислотності
    не знімає, скільки б кальцію в ній не було."""
    if продукт.get("тип") != "карбонат":
        return 0.0
    return (float(продукт.get("CaO") or 0) * norms.CaO_CaCO3
            + float(продукт.get("MgO") or 0) * norms.MgO_CaCO3)


def чинна_CCE(продукт):
    """Та, якою рахуємо. Надрукована в протоколі головніша за пораховану:
    лабораторія міряла продукт, а ми виводимо число зі стехіометрії."""
    з_протоколу = продукт.get("CCE_протокол")
    if з_протоколу not in (None, ""):
        return float(з_протоколу), "з протоколу"
    return порахувати_CCE(продукт), "порахована зі складу"


def доповнити(продукт):
    """Похідні числа картки. Нічого не зберігає — рахує на льоту."""
    п = dict(продукт)
    п["CCE_порахована"] = порахувати_CCE(п)
    п["CCE"], п["CCE_звідки"] = чинна_CCE(п)
    п["Ca"] = float(п.get("CaO") or 0) * norms.CaO_Ca / 100.0
    п["Mg"] = float(п.get("MgO") or 0) * norms.MgO_Mg / 100.0
    п["K"] = float(п.get("K2O") or 0) * norms.K2O_K / 100.0
    п["зауваги"] = перевірити(п)
    п["годиться"] = not any(з["вага"] == "помилка" for з in п["зауваги"])
    return п


# ═══════════════════════════════════════════════════════════════════════
# ПЕРЕВІРКА КАРТКИ
# ═══════════════════════════════════════════════════════════════════════
# Помилка — картку не приймаємо. Увага — приймаємо, але кажемо вголос.


def перевірити(продукт):
    з = []

    def помилка(що, чому):
        з.append(dict(вага="помилка", що=що, чому=чому))

    def увага(що, чому):
        з.append(dict(вага="увага", що=що, чому=чому))

    if not (продукт.get("назва") or "").strip():
        помилка("Немає назви", "без назви продукт не покласти в довідник")

    for ключ in ЧИСЛОВІ:
        значення = продукт.get(ключ)
        if значення in (None, ""):
            continue
        try:
            if float(значення) < 0:
                помилка("Від'ємне значення: " + ключ,
                        "від'ємного складу не буває")
        except (TypeError, ValueError):
            помилка("Не число: " + ключ, "тут має бути число у відсотках")

    сума = 0.0
    for ключ in СКЛАДНИКИ:
        try:
            сума += float(продукт.get(ключ) or 0)
        except (TypeError, ValueError):
            pass
    if сума > 100.0:
        помилка("Складники дають %.1f %%" % сума,
                "більше ста відсотків речовини не буває — швидше за все "
                "переплутано колонку протоколу")

    тип = продукт.get("тип")
    cce_порахована = порахувати_CCE(продукт)
    cce, звідки = чинна_CCE(продукт)

    if тип == "карбонат" and cce <= 0:
        помилка("Карбонат без нейтралізуючої здатності",
                "ні кальцію, ні магнію — нейтралізувати кислоту нічим. "
                "Або це не карбонат, або склад не заповнений")

    if тип == "сіль" and (float(продукт.get("CaO") or 0) > 0
                          or float(продукт.get("MgO") or 0) > 0):
        увага("У солі є CaO або MgO, але CCE лишається нулем",
              "сіль кислотності не знімає: її магній заходить на комплекс "
              "за рахунок кальцію, а не замість водню")

    if звідки == "з протоколу" and cce_порахована > 0:
        різниця = abs(cce - cce_порахована)
        if різниця >= РОЗБІЖНІСТЬ_CCE:
            увага("Протокол каже %.1f %%, зі складу виходить %.1f %%"
                  % (cce, cce_порахована),
                  "розбіжність %.1f п.п. Беремо надруковане, але варто "
                  "перевірити, чи склад і здатність міряні на одній основі"
                  % різниця)

    вода = float(продукт.get("H2O") or 0)
    if вода >= ВОДИ_БАГАТО:
        увага("Води %.1f %%" % вода,
              "невідомо, чи склад наведений на суху речовину. Якщо на суху, "
              "то в тонні привезеного продукту кальцію менше, ніж рахує "
              "програма. Питання до лабораторії, у розрахунок вода поки "
              "не входить")

    if продукт.get("статус") in ("CANON", "VALIDATED") and not (
            продукт.get("джерело") or "").strip():
        помилка("Статус %s без джерела" % продукт.get("статус"),
                "CANON означає «провенанс задокументований». Немає номера "
                "протоколу — статус WORKING")

    мін = продукт.get("мінімум")
    макс = продукт.get("максимум")
    try:
        if мін not in (None, "") and макс not in (None, "") \
                and float(мін) > float(макс):
            помилка("Мінімум більший за максимум",
                    "нижня межа розкидача не може бути вищою за верхню")
    except (TypeError, ValueError):
        pass

    return з


