def _шлях(база):
    return os.path.join(база, ФАЙЛ)


def _ключ(назва):
    к = re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ]+", "_", (назва or "").strip().lower())
    return к.strip("_") or "продукт"


def _свої(база):
    шлях = _шлях(база)
    if not os.path.isfile(шлях):
        return {}
    try:
        with io.open(шлях, encoding="utf-8") as ф:
            дані = json.load(ф)
        return дані if isinstance(дані, dict) else {}
    except Exception:
        return {}


def довідник(база):
    """Заготовка з майстерні плюс свої партії. Своє перекриває заготовку."""
    зібране = {}
    for ключ, п in norms.ПРОДУКТИ.items():
        картка = {к: п.get(к) for к in
                  ("назва", "тип", "CaO", "MgO", "K2O", "S", "H2O",
                   "джерело", "статус", "максимум", "мінімум", "крок",
                   "примітка")}
        картка["звідки"] = "знімок методу з майстерні"
        картка["своє"] = False
        картка["у_обсязі"] = п.get("у_обсязі", True)
        зібране[ключ] = доповнити(картка)

    for ключ, п in _свої(база).items():
        картка = dict(п)
        картка["звідки"] = "заведено в господарстві"
        картка["своє"] = True
        картка.setdefault("у_обсязі", True)
        якщо_перекриває = ключ in зібране
        картка["перекриває_заготовку"] = якщо_перекриває
        зібране[ключ] = доповнити(картка)

    return зібране


def зберегти(база, продукт):
    """Записати картку. Помилки перевірки не пропускаються — картка з
    від'ємним складом або карбонат без кальцію в довіднику нікому не потрібні."""
    картка = dict(ЗАМОВЧУВАННЯ)
    картка.update({к: в for к, в in (продукт or {}).items()
                   if к in [п["ключ"] for п in ПОЛЯ]})
    for ключ in ЧИСЛОВІ:
        значення = картка.get(ключ)
        if значення in ("", None):
            картка[ключ] = None if ключ == "CCE_протокол" else 0.0
        else:
            try:
                картка[ключ] = float(str(значення).replace(",", "."))
            except (TypeError, ValueError):
                pass

    зауваги = перевірити(картка)
    погані = [з for з in зауваги if з["вага"] == "помилка"]
    if погані:
        return dict(гаразд=False, зауваги=зауваги)

    ключ = (продукт or {}).get("ключ") or _ключ(картка["назва"])
    свої = _свої(база)
    свої[ключ] = картка
    with io.open(_шлях(база), "w", encoding="utf-8") as ф:
        json.dump(свої, ф, ensure_ascii=False, indent=1, sort_keys=True)
    return dict(гаразд=True, ключ=ключ, зауваги=зауваги)


def видалити(база, ключ):
    """Прибрати свою картку. Заготовку з майстерні прибрати не можна —
    вона не тут живе, і без неї звірка знімка перестане сходитись."""
    свої = _свої(база)
    if ключ not in свої:
        return dict(гаразд=False,
                    чому="цієї картки в довіднику господарства немає. "
                         "Заготовку з майстерні видалити не можна — її можна "
                         "тільки перекрити своєю партією")
    свої.pop(ключ)
    with io.open(_шлях(база), "w", encoding="utf-8") as ф:
        json.dump(свої, ф, ensure_ascii=False, indent=1, sort_keys=True)
    return dict(гаразд=True)
