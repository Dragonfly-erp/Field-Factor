"""ДОВІДНИК ПРОДУКТІВ. Те, чим справді сиплють на цьому господарстві.

Чому окремо від `norms.py`. Там лежить **знімок методу з майстерні** — копія
з комітом і контрольною сумою, на якій тримається звірка. Якщо дозволити
правити її з екрана, звірка почне сваритись на кожну дію користувача й
перестане щось означати. Тому:

    norms.ПРОДУКТИ   заводська заготовка, тільки читання, звіряється з майстернею
    довідник_продуктів.json   робочий довідник господарства, правиться руками

Заготовка видно в довіднику як є. Своя партія заводиться поруч і **перекриває**
заготовку під тим самим ключем: склад дефекату з протоколу 2025 року і склад
дефекату, який привезли цього року, — це різні числа, і друге головніше.

Головне правило довідника: **склад береться з протоколу партії, а не з
довідника речовин.** «Дефекат» — це не формула, це те, що привезли з цукрового
заводу цього тижня.
"""

