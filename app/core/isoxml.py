# -*- coding: utf-8 -*-
"""ISO-XML. Тека TASKDATA, яку монітор бере з флешки.

Формат — ISO 11783-10. Але писався цей модуль не з тексту стандарту, а з
**живого файлу SMS**: `TASKDATA.XML` і `GRD00001.bin` поля Б-16 Половецьке
від 31.07.2025. Різниця принципова: стандарт каже, що можна, а живий файл
показує, що саме читає та техніка, яка вже їздить по цих полях.

Що з того файлу дістали й перевірили:

* сітка — тип 2, по чотири байти на комірку, ціле без знака;
* значення в комірці = **кг/га × 100**. У DDI 0006 одиниця мг/м², а
  1 кг/га = 100 мг/м², тож обидва прочитання сходяться на тому самому числі;
* рядки лежать **з півдня на північ**, колонки із заходу на схід. Перевірено
  не за стандартом: розшифрована сітка збіглася з картинкою на екрані —
  смуга норм лягла в північно-східний кут, як і на знімку;
* розмір комірки задається **в градусах** окремо на північ і на схід;
* `VPN` зі шкалою 0,01 і одиницею `kg/ha` — це для показу на моніторі.

**Чого в тому файлі не було.** SMS дав сітку, не полігони. Тому режим
полігонів («вектор») написаний за стандартом і живим файлом **не звірений**.
Так і позначено у звіті: цей режим треба перевірити на техніці, перш ніж
покладатись.
"""

import io
import math
import os
import xml.etree.ElementTree as ET

from app.core import rx

# ═══════════════════════════════════════════════════════════════════════
# ЩО ПИШЕМО В ЗАГОЛОВОК
# ═══════════════════════════════════════════════════════════════════════

ВЕРСІЯ_ГОЛОВНА = "1"
ВЕРСІЯ_МОЛОДША = "0"
ВИРОБНИК = "FieldFactor"

# DDI 0006 — Mass Per Area Application Rate, одиниця мг/м².
# 1 кг/га = 1000 г / 10 000 м² = 100 мг/м². Звідси множник.
DDI_МАСА_НА_ПЛОЩУ = "0006"
КГ_ГА_В_DDI = 100.0

# Показ на моніторі: значення × 0,01 з двома знаками, підпис kg/ha.
VPN_ЗСУВ = "0"
VPN_ШКАЛА = "0.01"
VPN_ЗНАКІВ = "2"
VPN_ОДИНИЦЯ = "kg/ha"

ТИП_СІТКИ = "2"          # у комірці лежить саме значення, а не код зони
ГРАДУС_ШИРОТИ_М = 111320.0

# Коди зон обробки. Такі самі, як у SMS: там TSK має H="1" I="3" J="2",
# тобто зона за замовчуванням 1, «втрачено позицію» 3, «поза полем» 2.
ЗОНА_СІТКИ = 0
ЗОНА_ЗАМОВЧУВАННЯ = 1
ЗОНА_ПОЗА_ПОЛЕМ = 2
ЗОНА_ВТРАЧЕНО_ПОЗИЦІЮ = 3

# Три DLT, які пише SMS. Що вони означають: DataLogDDI «DFFF» — усі змінні
# пристрою, «0043» — пройдена відстань; DataLogMethod — бітова маска, коли
# писати (31 = усе одразу, 8 = при зміні). Перенесені без змін: це те, що
# монітори вже приймають, і вигадувати тут своє немає жодної підстави.
ЖУРНАЛ = (("DFFF", "31"), ("DFFF", "8"), ("0043", "8"))

# Скільки комірок ще притомно. За цією межею файл сітки стає таким, що
# старий монітор його не подужає.
ЗАБАГАТО_КОМІРОК = 200_000


# ═══════════════════════════════════════════════════════════════════════
# СІТКА
# ═══════════════════════════════════════════════════════════════════════


def побудувати_сітку(зони, колонка_норми, крок_м):
    """Зони з нормами → прямокутна сітка значень DDI.

    Комірка дістає норму тієї зони, у якій лежить її ЦЕНТР. Правило просте
    й найменш упереджене: на полі Б-16 воно дало +1 % продукту проти
    полігонів, тоді як сітка SMS на тому самому полі дала +24 %."""
    import numpy as np
    from shapely.geometry import Point
    from shapely.strtree import STRtree

    у_градусах = зони.to_crs(4326) if зони.crs is not None else зони.set_crs(4326)
    lon0, lat0, lon1, lat1 = у_градусах.total_bounds
    середня_широта = math.radians((lat0 + lat1) / 2.0)

    крок_широти = крок_м / ГРАДУС_ШИРОТИ_М
    крок_довготи = крок_м / (ГРАДУС_ШИРОТИ_М * math.cos(середня_широта))

    колонок = max(1, int(math.ceil((lon1 - lon0) / крок_довготи)))
    рядків = max(1, int(math.ceil((lat1 - lat0) / крок_широти)))
    if колонок * рядків > ЗАБАГАТО_КОМІРОК:
        raise ValueError(
            "сітка з кроком %g м дала б %d комірок — це занадто для монітора"
            % (крок_м, колонок * рядків))

    геометрії = list(у_градусах.geometry.values)
    норми = у_градусах[колонка_норми].astype(float).values
    дерево = STRtree(геометрії)

    # Рядок 0 — найпівденніший: так лежить у файлі SMS, перевірено збігом
    # розшифрованої сітки з картинкою на екрані.
    значення = np.zeros((рядків, колонок), dtype="<u4")
    зайнято = 0
    for р in range(рядків):
        y = lat0 + (р + 0.5) * крок_широти
        for к in range(колонок):
            x = lon0 + (к + 0.5) * крок_довготи
            точка = Point(x, y)
            for і in дерево.query(точка):
                if геометрії[і].contains(точка):
                    ставка = норми[і]
                    if ставка > 0:
                        значення[р, к] = int(round(ставка * КГ_ГА_В_DDI))
                        зайнято += 1
                    break

    return dict(значення=значення, рядків=рядків, колонок=колонок,
                зайнято=зайнято,
                мін_широта=lat0, мін_довгота=lon0,
                крок_широти=крок_широти, крок_довготи=крок_довготи,
                крок_м=крок_м,
                байтів=рядків * колонок * 4)


# ═══════════════════════════════════════════════════════════════════════
# ГЕОМЕТРІЯ В ISO
# ═══════════════════════════════════════════════════════════════════════
# PNT: A — тип точки, C — широта, D — довгота. Саме в такому порядку, як
# у SMS: спершу північ, потім схід.

ТИП_ТОЧКИ_МЕЖА = "2"
КІЛЬЦЕ_ЗОВНІШНЄ = "1"
КІЛЬЦЕ_ВНУТРІШНЄ = "2"


def _кільце(батько, координати, тип_кільця):
    lsg = ET.SubElement(батько, "LSG", {"A": тип_кільця})
    for x, y in координати:
        ET.SubElement(lsg, "PNT", {"A": ТИП_ТОЧКИ_МЕЖА,
                                   "C": "%.9f" % y, "D": "%.9f" % x})
    return lsg


def _полігон(батько, геометрія, тип_полігона, площа_м2=None):
    атрибути = {"A": тип_полігона}
    if площа_м2 is not None:
        атрибути["C"] = "%d" % round(площа_м2)
    pln = ET.SubElement(батько, "PLN", атрибути)
    шматки = (list(геометрія.geoms)
              if геометрія.geom_type == "MultiPolygon" else [геометрія])
    for шматок in шматки:
        _кільце(pln, list(шматок.exterior.coords), КІЛЬЦЕ_ЗОВНІШНЄ)
        for дірка in шматок.interiors:
            _кільце(pln, list(дірка.coords), КІЛЬЦЕ_ВНУТРІШНЄ)
    return pln


# ═══════════════════════════════════════════════════════════════════════
# ЗБІРКА TASKDATA
# ═══════════════════════════════════════════════════════════════════════


def записати(тека_кореня, роботи, режим="сітка", крок_м=20.0):
    """Кілька полів → одна тека TASKDATA.

    роботи — список словників:
        господарство, ферма, поле  — назви (транслітеруються)
        зони      — GeoDataFrame з колонками ZONE_ID і RATE (кг/га)
        контур    — межа поля або None (тоді береться обʼєднання зон)
        продукт, дата, назва

    режим: «сітка» — перевірено на живому файлі SMS;
           «полігони» — за стандартом, живим файлом НЕ звірено."""
    import geopandas as gpd
    from shapely.ops import unary_union

    тека = os.path.join(тека_кореня, "TASKDATA")
    os.makedirs(тека, exist_ok=True)
    for старий in os.listdir(тека):
        if старий.upper().endswith((".XML", ".BIN")):
            os.remove(os.path.join(тека, старий))

    корінь = ET.Element("ISO11783_TaskData", {
        "VersionMajor": ВЕРСІЯ_ГОЛОВНА,
        "VersionMinor": ВЕРСІЯ_МОЛОДША,
        "ManagementSoftwareManufacturer": ВИРОБНИК,
        "ManagementSoftwareVersion": _версія_програми(),
        "DataTransferOrigin": "1",
    })

    господарства, ферми, продукти = {}, {}, {}
    поля_опис, завдання_опис, сітки = [], [], []
    застереження = []

    # --- довідники: замовник, ферма, продукт ---------------------------
    for робота in роботи:
        г = rx.підпис(робота.get("господарство") or "Customer", 32, "Customer")
        if г not in господарства:
            господарства[г] = "CTR%d" % (len(господарства) + 1)
        ф = rx.підпис(робота.get("ферма") or г, 32, "Farm")
        if ф not in ферми:
            ферми[ф] = ("FRM%d" % (len(ферми) + 1), господарства[г])
        п = rx.підпис(робота.get("продукт") or "Product", 32, "Product")
        if п not in продукти:
            продукти[п] = "PDT%d" % (len(продукти) + 1)

    for назва, ід in господарства.items():
        ET.SubElement(корінь, "CTR", {"A": ід, "B": назва})
    for назва, (ід, ктр) in ферми.items():
        ET.SubElement(корінь, "FRM", {"A": ід, "B": назва, "I": ктр})

    # --- поля ------------------------------------------------------------
    for номер, робота in enumerate(роботи, start=1):
        зони = робота["зони"]
        зони = зони.to_crs(4326) if зони.crs is not None else зони.set_crs(4326)
        контур = робота.get("контур")
        if контур is None:
            контур = unary_union(list(зони.geometry.values))
        метричні = rx._у_метри(gpd.GeoDataFrame(geometry=[контур], crs=4326))
        площа = float(метричні.geometry.area.iloc[0])

        г = rx.підпис(робота.get("господарство") or "Customer", 32, "Customer")
        ф = rx.підпис(робота.get("ферма") or г, 32, "Farm")
        назва_поля = rx.підпис(робота.get("поле") or "Field", 32, "Field")
        ід_поля = "PFD%d" % номер

        pfd = ET.SubElement(корінь, "PFD", {
            "A": ід_поля, "C": назва_поля, "D": "%d" % round(площа),
            "E": господарства[г], "F": ферми[ф][0]})
        _полігон(pfd, контур, КІЛЬЦЕ_ЗОВНІШНЄ, площа)

        поля_опис.append(dict(ід=ід_поля, назва=назва_поля,
                              площа_м2=round(площа), господарство=г, ферма=ф))
        робота["_ід_поля"] = ід_поля
        робота["_зони"] = зони

    # --- група продуктів, продукти, практика, показ ----------------------
    ET.SubElement(корінь, "PGP", {"A": "PGP1", "B": "Fertilizer"})
    for назва, ід in продукти.items():
        ET.SubElement(корінь, "PDT", {"A": ід, "B": назва, "C": "PGP1"})
    ET.SubElement(корінь, "CPC", {"A": "CPC1", "B": "Fertilizing Prescription"})
    ET.SubElement(корінь, "VPN", {"A": "VPN1", "B": VPN_ЗСУВ, "C": VPN_ШКАЛА,
                                  "D": VPN_ЗНАКІВ, "E": VPN_ОДИНИЦЯ})

    # --- завдання ---------------------------------------------------------
    for номер, робота in enumerate(роботи, start=1):
        зони = робота["_зони"]
        г = rx.підпис(робота.get("господарство") or "Customer", 32, "Customer")
        ф = rx.підпис(робота.get("ферма") or г, 32, "Farm")
        п = rx.підпис(робота.get("продукт") or "Product", 32, "Product")
        ід_завдання = "TSK%d" % номер
        назва_завдання = rx.підпис(
            робота.get("назва") or (робота.get("поле") or "Task"), 32, "Task")

        tsk = ET.SubElement(корінь, "TSK", {
            "A": ід_завдання, "B": назва_завдання,
            "C": господарства[г], "D": ферми[ф][0], "E": робота["_ід_поля"],
            "G": "1",                       # стан: заплановане
            "H": str(ЗОНА_ЗАМОВЧУВАННЯ),
            "I": str(ЗОНА_ВТРАЧЕНО_ПОЗИЦІЮ),
            "J": str(ЗОНА_ПОЗА_ПОЛЕМ)})
        for ддi, метод in ЖУРНАЛ:
            ET.SubElement(tsk, "DLT", {"A": ддi, "B": метод})

        if режим == "сітка":
            сітка = побудувати_сітку(зони, "RATE", крок_м)
            імʼя_bin = "GRD%05d" % номер
            with open(os.path.join(тека, імʼя_bin + ".bin"), "wb") as ф_:
                ф_.write(сітка["значення"].tobytes())

            # Зона, на яку посилається сітка: у ній описано, ЩО саме лежить
            # у чотирьох байтах комірки — яка величина і для якого продукту.
            _зона(tsk, ЗОНА_СІТКИ, 0.0, продукти[п])
            for код in (ЗОНА_ЗАМОВЧУВАННЯ, ЗОНА_ПОЗА_ПОЛЕМ,
                        ЗОНА_ВТРАЧЕНО_ПОЗИЦІЮ):
                _зона(tsk, код, 0.0, продукти[п])

            ET.SubElement(tsk, "GRD", {
                "A": "%.13f" % сітка["мін_широта"],
                "B": "%.13f" % сітка["мін_довгота"],
                "C": "%.16f" % сітка["крок_широти"],
                "D": "%.16f" % сітка["крок_довготи"],
                "E": str(сітка["колонок"]),
                "F": str(сітка["рядків"]),
                "G": імʼя_bin,
                "H": str(сітка["байтів"]),
                "I": ТИП_СІТКИ,
                "J": str(ЗОНА_СІТКИ)})
            сітки.append(dict(поле=робота["_ід_поля"], файл=імʼя_bin + ".bin",
                              комірок=сітка["рядків"] * сітка["колонок"],
                              під_нормою=сітка["зайнято"],
                              рядків=сітка["рядків"], колонок=сітка["колонок"],
                              крок_м=сітка["крок_м"], байтів=сітка["байтів"]))
        else:
            # Кожна зона — окрема зона обробки зі своєю геометрією.
            _зона(tsk, ЗОНА_ЗАМОВЧУВАННЯ, 0.0, продукти[п])
            _зона(tsk, ЗОНА_ПОЗА_ПОЛЕМ, 0.0, продукти[п])
            _зона(tsk, ЗОНА_ВТРАЧЕНО_ПОЗИЦІЮ, 0.0, продукти[п])
            код = 4
            for _, з in зони.iterrows():
                ставка = float(з["RATE"])
                зона = _зона(tsk, код, ставка, продукти[п])
                _полігон(зона, з.geometry, КІЛЬЦЕ_ЗОВНІШНЄ)
                код += 1
            застереження.append(dict(
                вага="увага",
                що="режим полігонів не звірений із живим файлом",
                чому="сітку ми переписали з робочого експорту SMS і знаємо, "
                     "що монітори її беруть. Полігонний ISO-XML написаний за "
                     "стандартом — перш ніж покладатись, треба спробувати "
                     "його на техніці"))

        завдання_опис.append(dict(ід=ід_завдання, назва=назва_завдання,
                                  поле=робота["_ід_поля"], продукт=п,
                                  зон=int(len(зони))))

    # ElementTree пише оголошення в одинарних лапках і ставить пробіл перед
    # «/>». Стандарту це не порушує, але живий файл SMS виглядає інакше, а
    # на старих моніторах трапляються прискіпливі розбирачі. Тримаємось
    # ближче до того, що вже точно читається.
    шлях_xml = os.path.join(тека, "TASKDATA.XML")
    тіло = ET.tostring(корінь, encoding="unicode").replace(" />", "/>")
    with io.open(шлях_xml, "w", encoding="utf-8", newline="") as ф_:
        ф_.write('<?xml version="1.0" encoding="UTF-8"?>' + тіло)

    return dict(тека=тека, режим=режим,
                файли=sorted(os.listdir(тека)),
                поля=поля_опис, завдання=завдання_опис, сітки=сітки,
                застереження=застереження,
                вага=sum(os.path.getsize(os.path.join(тека, ф))
                         for ф in os.listdir(тека)))


def _зона(tsk, код, кг_на_га, ід_продукту):
    """TZN із однією змінною: скільки маси на площу і чого саме."""
    зона = ET.SubElement(tsk, "TZN", {
        "A": str(код), "B": "%.2f %s" % (кг_на_га, VPN_ОДИНИЦЯ)})
    ET.SubElement(зона, "PDV", {
        "A": DDI_МАСА_НА_ПЛОЩУ,
        "B": str(int(round(кг_на_га * КГ_ГА_В_DDI))),
        "C": ід_продукту, "E": "VPN1"})
    return зона


def _версія_програми():
    """Версія самої програми, а не тієї теки, куди пишемо.

    Спершу я брав version.json із теки виводу — і в TASKDATA лягало 0.0.0.
    Монітор на це не дивиться, але той, хто потім розбиратиме, чому карта
    поїхала не так, дивитиметься саме сюди."""
    import json

    корінь = os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))
    try:
        with open(os.path.join(корінь, "version.json"), encoding="utf-8") as ф:
            return str(json.load(ф).get("version") or "0.0.0")
    except Exception:
        return "0.0.0"


