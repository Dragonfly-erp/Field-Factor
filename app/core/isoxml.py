# Те саме правило, що й із shapefile: у звіт іде прочитане з диска, а не
# те, що ми збирались записати.


def перечитати(тека):
    """Розібрати щойно записану теку так, ніби її дав хтось інший."""
    import struct

    шлях = os.path.join(тека, "TASKDATA.XML")
    дерево = ET.parse(шлях)
    корінь = дерево.getroot()

    сітки = []
    for tsk in корінь.findall("TSK"):
        for grd in tsk.findall("GRD"):
            імʼя = grd.get("G") + ".bin"
            повний = os.path.join(тека, імʼя)
            байтів = os.path.getsize(повний)
            колонок, рядків = int(grd.get("E")), int(grd.get("F"))
            очікувано = колонок * рядків * 4
            дані = open(повний, "rb").read()
            значення = struct.unpack("<%dI" % (len(дані) // 4), дані)
            ненульових = [з for з in значення if з]
            сітки.append(dict(
                завдання=tsk.get("A"), файл=імʼя,
                колонок=колонок, рядків=рядків,
                байтів=байтів, збігається=(байтів == очікувано
                                           and байтів == int(grd.get("H"))),
                ненульових=len(ненульових),
                норми_кг_га=sorted({round(з / КГ_ГА_В_DDI, 2)
                                    for з in ненульових}),
                тип=grd.get("I")))

    текст = open(шлях, encoding="utf-8").read()
    не_латиниця = sorted({з for з in текст if ord(з) > 127})

    return dict(
        версія="%s.%s" % (корінь.get("VersionMajor"), корінь.get("VersionMinor")),
        замовників=len(корінь.findall("CTR")),
        ферм=len(корінь.findall("FRM")),
        полів=len(корінь.findall("PFD")),
        продуктів=len(корінь.findall("PDT")),
        завдань=len(корінь.findall("TSK")),
        зон=sum(len(t.findall("TZN")) for t in корінь.findall("TSK")),
        сітки=сітки,
        уся_латиниця=not не_латиниця,
        не_латиниця="".join(не_латиниця),
        вага_xml=os.path.getsize(шлях),
        зразок=текст[:600],
    )
