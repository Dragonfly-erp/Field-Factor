# -*- coding: utf-8 -*-
"""ГЛАДКА ПОВЕРХНЯ: останній крок, без якого карта лишається кришивом.

Середні по комірках — це ще не карта. На Г-03 сусідні комірки розходяться на
19 % при середньому 12 050 кг/га, і на екрані це виглядає як шум, а не як
поле. У цьому ремеслі очищені точки завжди зводять у гладку поверхню — саме
її людина й називає картою врожайності.

**Радіус не вигадується.** Він обирається за незалежним свідком: беремо
кілька радіусів і дивимось, на якому згода з рослинністю найвища. Шум із
рослинністю не корелює, тому поки згладжування прибирає шум — згода росте.
Щойно воно починає стирати справжню структуру поля — згода падає. Вершина
цієї кривої і є правильний радіус.

На Г-03 вийшло так:

    як є    розкид 19 %   згода 0,669
    20 м    розкид 16 %   згода 0,729   <- вершина
    30 м    розкид 15 %   згода 0,717
    60 м    розкид 14 %   згода 0,680

Без свідка береться замовчування у два кроки сітки — і це чесно сказано
у звіті.
"""

import numpy as np

РАДІУСИ_М = (10.0, 20.0, 30.0, 40.0)
ЗАМОВЧУВАННЯ_КРОКІВ = 2.0


def _згладити(сітка, маска, вікно):
    from scipy.ndimage import uniform_filter

    сума = uniform_filter(np.nan_to_num(сітка), вікно, mode="nearest")
    вага = uniform_filter(маска.astype("float64"), вікно, mode="nearest")
    return np.where(вага > 1e-9, сума / np.maximum(вага, 1e-9), np.nan)


def поверхня(x, y, значення, крок, свідок=None, журнал=None):
    """Гладка поверхня з очищених комірок. Повертає (значення, звіт)."""
    x = np.asarray(x, float); y = np.asarray(y, float)
    з = np.asarray(значення, dtype="float64")

    с = np.clip(((x - x.min()) / крок).round().astype(int), 0, None)
    р = np.clip(((y.max() - y) / крок).round().astype(int), 0, None)
    рядків, стовпців = int(р.max()) + 1, int(с.max()) + 1
    сітка = np.full((рядків, стовпців), np.nan)
    сітка[р, с] = з
    маска = np.isfinite(сітка)
    if маска.sum() < 200:
        return з, {"зроблено": False, "чому": "замало комірок"}

    придатний = None
    if свідок is not None:
        в = np.asarray(свідок, dtype="float64")
        добрі = np.isfinite(в) & np.isfinite(з)
        if добрі.sum() > 500 and np.nanstd(в[добрі]) > 0:
            придатний = (в, добрі)

    найкраще, крива = None, []
    for радіус in РАДІУСИ_М:
        вікно = max(3, int(round(радіус / крок)) | 1)
        гладко = _згладити(сітка, маска, вікно)
        гладко = np.where(маска, гладко, np.nan)
        нове = гладко[р, с]
        якщо = np.nan
        if придатний is not None:
            в, добрі = придатний
            якщо = float(np.corrcoef(нове[добрі], в[добрі])[0, 1])
        крива.append({"радіус_м": радіус, "згода": якщо,
                      "розкид": float(np.nanstd(нове) / max(np.nanmean(нове), 1e-9))})
        if придатний is not None and (найкраще is None or якщо > найкраще["згода"]):
            найкраще = {"радіус_м": радіус, "згода": якщо, "значення": нове}

    if найкраще is None:
        радіус = ЗАМОВЧУВАННЯ_КРОКІВ * крок
        вікно = max(3, int(round(радіус / крок)) | 1)
        гладко = np.where(маска, _згладити(сітка, маска, вікно), np.nan)
        найкраще = {"радіус_м": радіус, "згода": np.nan, "значення": гладко[р, с]}
        чому = "свідка немає — узято {:.0f} кроків сітки".format(ЗАМОВЧУВАННЯ_КРОКІВ)
    else:
        чому = "обрано за найвищою згодою з рослинністю"

    звіт = {
        "зроблено": True,
        "радіус_м": найкраще["радіус_м"],
        "згода": найкраще["згода"],
        "чому": чому,
        "крива": крива,
        "розкид_до": float(np.nanstd(з) / max(np.nanmean(з), 1e-9)),
        "розкид_після": float(np.nanstd(найкраще["значення"])
                              / max(np.nanmean(найкраще["значення"]), 1e-9)),
    }
    if журнал is not None:
        журнал.сказати(
            "  гладка поверхня: радіус {:.0f} м ({}). Розкид між сусідніми "
            "комірками {:.0f} % -> {:.0f} %{}.".format(
                звіт["радіус_м"], чому, звіт["розкид_до"] * 100,
                звіт["розкид_після"] * 100,
                ", згода з рослинністю {:.3f}".format(звіт["згода"])
                if np.isfinite(звіт["згода"]) else "")
        )
    return найкраще["значення"], звіт
