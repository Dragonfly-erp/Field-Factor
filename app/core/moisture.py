# -*- coding: utf-8 -*-
"""Фаза 7: приведення до базисної вологості, обʼєм і звірка з вивезеною вагою."""

import numpy as np

# Ознаки того, що монітор уже сам привів врожайність до сухої основи
ОЗНАКИ_ПРИВЕДЕНОГО = ("dry", "_dr", "сух")


def схоже_на_приведене(назва_колонки):
    низ = str(назва_колонки).lower()
    return any(о in низ for о in ОЗНАКИ_ПРИВЕДЕНОГО)


def привести(таблиця, паспорт, журнал):
    """ВРОЖАЙ_ЗВЕД → ВРОЖАЙ_БАЗ при базисній вологості користувача."""
    базис = float(паспорт.get("базис"))
    вологість = таблиця["ВОЛОГІСТЬ"].to_numpy(dtype="float64")
    врожай = таблиця["ВРОЖАЙ_ЗВЕД"].to_numpy(dtype="float64")
    звіт = {"базис": базис, "застосовано": False, "застереження": []}

    if паспорт.get("вже_приведено"):
        таблиця["ВРОЖАЙ_БАЗ"] = врожай
        звіт["застереження"].append(
            "Монітор уже видавав приведену врожайність, тож формула вологості "
            "не застосовувалась удруге. До якої саме вологості приводив сам "
            "монітор — у файлі не записано; якщо це не {:.1f} %, числа зміщені "
            "на цю різницю.".format(базис)
        )
        журнал.сказати("Врожайність лишено як є: монітор уже приводив її сам.")
        return таблиця, звіт

    придатна = np.isfinite(вологість) & (вологість > 0) & (вологість < 60)
    if придатна.sum() < len(таблиця) * 0.2:
        таблиця["ВРОЖАЙ_БАЗ"] = врожай
        звіт["застереження"].append(
            "Вологості у файлі майже немає, тож приведення до {:.1f} % не "
            "виконувалось. Числа лишились такими, як їх записав монітор.".format(базис)
        )
        журнал.сказати("Вологості немає — приведення пропущено.")
        return таблиця, звіт

    медіана_вологості = float(np.nanmedian(вологість[придатна]))
    приведене = np.where(
        придатна,
        врожай * (100.0 - вологість) / (100.0 - базис),
        врожай * (100.0 - медіана_вологості) / (100.0 - базис),
    )
    таблиця["ВРОЖАЙ_БАЗ"] = приведене
    звіт["застосовано"] = True
    звіт["медіана_вологості"] = round(медіана_вологості, 2)
    звіт["частка_з_вологістю"] = round(float(придатна.mean()) * 100, 1)

    if придатна.mean() < 0.98:
        звіт["застереження"].append(
            "У {:.1f} % записів вологості не було — для них узято медіану по "
            "полю ({:.1f} %).".format((1 - придатна.mean()) * 100, медіана_вологості)
        )

    журнал.сказати(
        "Приведено до {:.1f} % вологості. Медіана виміряної — {:.1f} %.".format(
            базис, медіана_вологості
        )
    )
    return таблиця, звіт


def обʼєм(таблиця, паспорт):
    """л/га рахуємо тільки з відомої натури. Немає натури — поле порожнє."""
    натура = паспорт.get("натура")
    if not натура:
        таблиця["ВРОЖАЙ_Л"] = np.nan
        return таблиця, "не рахувалось — натуральна вага не вказана"
    таблиця["ВРОЖАЙ_Л"] = таблиця["ВРОЖАЙ_БАЗ"] / float(натура)
    return таблиця, "пораховано з натури {:.3f} кг/л".format(float(натура))


def факт_у_кг_га(паспорт):
    """Число господарства → кг/га."""
    значення = паспорт.get("факт")
    if not значення:
        return None
    одиниця = (паспорт.get("одиниця_факту") or "т/га").lower()
    множник = {"т/га": 1000.0, "кг/га": 1.0, "ц/га": 100.0}.get(одиниця, 1000.0)
    return float(значення) * множник


def звірити_з_вагою(таблиця, паспорт, журнал, середнє_по_площі=None, поле_врожаю="ВРОЖАЙ_БАЗ"):
    """Фаза 7, кінець: підганяємо середнє під вивезену вагу — але лише коли є за чим.

    Підгін іде по СЕРЕДНЬОМУ ПО ПЛОЩІ, а не по середньому точок: точки лежать
    нерівномірно, і просте середнє по них — не врожайність поля.
    """
    ціль = факт_у_кг_га(паспорт)
    джерело = паспорт.get("джерело_факту") or "немає"
    звіт = {"ціль_кг_га": ціль, "джерело": джерело, "коефіцієнт": 1.0, "застереження": []}

    if середнє_по_площі is not None:
        поточне = float(середнє_по_площі)
    else:
        чисті = таблиця[таблиця["QC"] == "OK"]
        if not len(чисті):
            raise ValueError("Після очистки не лишилось жодного придатного запису.")
        поточне = float(np.nanmean(чисті[поле_врожаю]))
    звіт["до_підгону_кг_га"] = round(поточне, 1)

    if ціль is None or джерело == "немає":
        звіт["застереження"].append(
            "Фактичної врожайності не надано. Карта показує, де краще й гірше, "
            "але абсолютні кілограми на ній — це те, що намалював монітор, "
            "без зовнішньої перевірки."
        )
        журнал.сказати("Зовнішнього числа немає — карта лишається відносною.")
        return таблиця, звіт

    if джерело == "оцінка":
        відхилення = abs(поточне - ціль) / ціль * 100
        звіт["відхилення_відсотків"] = round(відхилення, 1)
        if відхилення > 25:
            звіт["застереження"].append(
                "Монітор дає {:.0f} кг/га, а ваша оцінка — {:.0f} кг/га. Різниця "
                "{:.0f} %. Оцінка на око не є мірилом, тож карту не підганяли, "
                "але таку різницю варто перевірити.".format(поточне, ціль, відхилення)
            )
        журнал.сказати(
            "Оцінка господарства {:.0f} кг/га проти {:.0f} кг/га з монітора — "
            "як перевірка, не як мірило.".format(ціль, поточне)
        )
        return таблиця, звіт

    # вивірене число: підганяємо
    коефіцієнт = ціль / поточне if поточне > 0 else 1.0
    if not (0.5 <= коефіцієнт <= 2.0):
        звіт["застереження"].append(
            "Щоб звести карту з вагою, треба було б множити все на {:.2f}. Це "
            "занадто — швидше за все, не збігаються одиниці або площа. Підгін "
            "не застосовано.".format(коефіцієнт)
        )
        журнал.сказати("Підгін під вагу відхилено: коефіцієнт {:.2f}".format(коефіцієнт))
        return таблиця, звіт

    таблиця[поле_врожаю] = таблиця[поле_врожаю] * коефіцієнт
    звіт["коефіцієнт"] = round(коефіцієнт, 4)
    журнал.сказати(
        "Середнє зведено з вивезеною вагою: {:.0f} → {:.0f} кг/га "
        "(×{:.3f}).".format(поточне, ціль, коефіцієнт)
    )
    return таблиця, звіт
