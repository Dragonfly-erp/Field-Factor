ПОРОЖНІЙ = {"матеріали": [], "роботи": [], "витрати": [],
            "ціни_продукції": [], "пальне_грн_л": None}


def _прочитати(шлях, замовчування):
    if not os.path.isfile(шлях):
        return json.loads(json.dumps(замовчування))
    try:
        with io.open(шлях, encoding="utf-8") as ф:
            return json.load(ф)
    except Exception:                                  # noqa: BLE001
        return json.loads(json.dumps(замовчування))


def _записати(шлях, дані):
    os.makedirs(os.path.dirname(шлях) or ".", exist_ok=True)
    with io.open(шлях, "w", encoding="utf-8") as ф:
        json.dump(дані, ф, ensure_ascii=False, indent=2)
    return шлях


def ключ(назва):
    return re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ]+", "_", (назва or "").strip().lower()).strip("_")


def довідники(база, тека_господарства=None):
    """Спільна заготовка плюс своє господарства, яке перекриває під ключем.

    Та сама механіка, що в довіднику продуктів. Ринкова ціна селітри одна на
    всіх, а оренда паю в кожного своя — і своє завжди головніше.
    """
    зведене = _прочитати(os.path.join(база, ФАЙЛ_СПІЛЬНИЙ), ПОРОЖНІЙ)
    for розділ in ПОРОЖНІЙ:
        зведене.setdefault(розділ, ПОРОЖНІЙ[розділ])

    if тека_господарства:
        своє = _прочитати(os.path.join(тека_господарства, ФАЙЛ_ГОСПОДАРСТВА), ПОРОЖНІЙ)
        for розділ in ("матеріали", "роботи", "витрати", "ціни_продукції"):
            свої = своє.get(розділ) or []
            if не_список(свої):
                continue
            за_ключем = {ключ(_імʼя(р, розділ)): р for р in зведене.get(розділ) or []}
            for р in свої:
                р = dict(р)
                р["своє"] = True
                за_ключем[ключ(_імʼя(р, розділ))] = р
            зведене[розділ] = list(за_ключем.values())
        if своє.get("пальне_грн_л") is not None:
            зведене["пальне_грн_л"] = своє["пальне_грн_л"]
    return зведене


def не_список(х):
    return not isinstance(х, list)


def _імʼя(запис, розділ):
    return запис.get("культура") if розділ == "ціни_продукції" else запис.get("назва")


def зберегти_своє(тека_господарства, дані):
    """Пише тільки те, що належить цьому господарству."""
    return _записати(os.path.join(тека_господарства, ФАЙЛ_ГОСПОДАРСТВА), дані)


