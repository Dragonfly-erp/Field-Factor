def перевірити(запис, поля):
    """Що не так із карткою. Порожній перелік означає, що все гаразд.

    Найважливіше тут — **дата ціни**. Ціна без дати виглядає як число, а
    насправді це число невідомо якого місяця, і бюджет на ньому — вигадка.
    """
    зауваги = []
    за_ключем = {п["ключ"]: п for п in поля}
    for п in поля:
        значення = запис.get(п["ключ"])
        if п.get("обовʼязкове") and (значення is None or значення == ""):
            зауваги.append("{}: не заповнено".format(п["підпис"]))
        if п["вид"] == "число" and значення not in (None, ""):
            try:
                if float(значення) < 0:
                    зауваги.append("{}: відʼємне число".format(п["підпис"]))
            except (TypeError, ValueError):
                зауваги.append("{}: не число — «{}»".format(п["підпис"], значення))
        if п["вид"] == "вибір" and значення not in (None, ""):
            дозволені = [в[0] for в in п.get("варіанти", [])]
            if дозволені and значення not in дозволені:
                зауваги.append("{}: невідоме значення «{}»".format(п["підпис"], значення))

    # Норма мусить лежати в межах, якщо межі названі.
    н, від, до = (_число(запис.get(к)) for к in ("норма", "норма_від", "норма_до"))
    if н is not None and від is not None and н < від:
        зауваги.append("Норма {} нижча за нижню межу {}".format(н, від))
    if н is not None and до is not None and н > до:
        зауваги.append("Норма {} вища за верхню межу {}".format(н, до))

    # Стаття витрат: або річна сума, або ставка на гектар. Обидва разом —
    # це два різних числа про одне й те саме, і котресь із них застаріє.
    if "група" in за_ключем:
        сума, ставка = _число(запис.get("сума_рік")), _число(запис.get("ставка_га"))
        if сума is None and ставка is None:
            зауваги.append("Не названо ні річної суми, ні ставки на гектар")
        if сума is not None and ставка is not None:
            зауваги.append("Названо і річну суму, і ставку на гектар — "
                           "лишіть щось одне, інакше вони розійдуться")
    return зауваги


def _число(х, замовчування=None):
    try:
        return float(х)
    except (TypeError, ValueError):
        return замовчування


