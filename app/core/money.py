def вартість_матеріалу(матеріал, норма=None):
    """Скільки коштує цей матеріал на гектарі. Одиниця товару — його власна.

    Ціна вже стоїть за ту одиницю, у якій його купують, а норма — у тих
    самих одиницях на гектар. Тому множення пряме, і жодного переведення
    одиниць тут не відбувається — саме тому воно й не може зламатись.
    """
    ціна = _число(матеріал.get("ціна"))
    н = _число(норма if норма is not None else матеріал.get("норма"))
    if ціна is None or н is None:
        return None
    return ціна * н


def вартість_роботи(робота, пальне_грн_л):
    """Грн на гектар за один прохід: пальне плюс ставка."""
    пальне = _число(робота.get("пальне_л_га"), 0.0) * _число(пальне_грн_л, 0.0)
    return пальне + _число(робота.get("ставка_грн_га"), 0.0)


def постійні_на_гектар(витрати, площа_господарства_га, поле=None):
    """Постійні витрати, розкидані на гектар ЦЬОГО поля.

    Розкид робиться за статтею, а не однією ставкою на все — рішення
    Власника 21.08. Стаття «поле» бере ставку з самого поля: оренда паю в
    кожного поля своя, і ховати її в середньому по господарству означає
    зробити дороге поле схожим на дешеве.

    `поле` — словник із можливими ключами `оренда_грн_га`, `години_на_га`,
    `частка_годин`. Чого немає — те падає на розкид за площею.
    """
    поле = поле or {}
    площа = max(_число(площа_господарства_га, 0.0), 0.01)
    рядки = []
    for стаття in витрати or []:
        назва = стаття.get("назва") or "?"
        розкид = стаття.get("розкид") or "площа"
        ставка = _число(стаття.get("ставка_га"))
        сума = _число(стаття.get("сума_рік"))

        if розкид == "поле":
            # Пряма ставка поля, якщо вона названа; інакше та, що в статті.
            своя = _число(поле.get("оренда_грн_га")) if стаття.get("група") == "земля" else None
            на_га = своя if своя is not None else (ставка if ставка is not None
                                                   else (сума / площа if сума else 0.0))
            чому = "ставка поля" if своя is not None else "ставка статті"
        elif розкид == "години":
            частка = _число(поле.get("частка_годин"))
            if сума is not None and частка is not None:
                # Частка — це доля напрацювання техніки, що припала на це
                # поле. Ділимо на площу поля, щоб дістати грн/га.
                площа_поля = max(_число(поле.get("площа_га"), 0.0), 0.01)
                на_га = сума * частка / площа_поля
                чому = "за годинами роботи"
            else:
                на_га = ставка if ставка is not None else (сума / площа if сума else 0.0)
                чому = "годин не названо — за площею"
        elif розкид == "виручка":
            частка = _число(поле.get("частка_виручки"))
            площа_поля = max(_число(поле.get("площа_га"), 0.0), 0.01)
            if сума is not None and частка is not None:
                на_га = сума * частка / площа_поля
                чому = "за виручкою"
            else:
                на_га = ставка if ставка is not None else (сума / площа if сума else 0.0)
                чому = "виручки не названо — за площею"
        else:
            на_га = ставка if ставка is not None else (сума / площа if сума else 0.0)
            чому = "за площею"

        рядки.append({"назва": назва, "група": стаття.get("група"),
                      "грн_га": round(на_га, 2), "розкид": розкид, "чому": чому})
    return рядки


def бюджет(вхід):
    """Бюджет підприємства для одного поля під одну культуру за один рік.

    `вхід` — словник:
        площа_га, врожайність_т_га, ціна_т, дотація_грн_га
        змінні: {стаття: грн/га}
        постійні: [рядки з `постійні_на_гектар`]

    Повертає всі рівні канонічної форми плюс точку беззбитковості. Нічого
    не округлює до цілих: округлення робить показ, і робить його один раз.
    """
    площа = _число(вхід.get("площа_га"), 0.0)
    урожай = _число(вхід.get("врожайність_т_га"), 0.0)
    ціна = _число(вхід.get("ціна_т"), 0.0)

    зерно = урожай * ціна
    дотація = _число(вхід.get("дотація_грн_га"), 0.0)
    дохід = зерно + дотація

    змінні_рядки = []
    for стаття, підпис in СТАТТІ_ЗМІННИХ:
        значення = _число((вхід.get("змінні") or {}).get(стаття), 0.0)
        змінні_рядки.append({"ключ": стаття, "підпис": підпис, "грн_га": значення})
    змінні = sum(р["грн_га"] for р in змінні_рядки)

    постійні_рядки = list(вхід.get("постійні") or [])
    постійні = sum(_число(р.get("грн_га"), 0.0) for р in постійні_рядки)

    маржинальний = дохід - змінні
    чистий = маржинальний - постійні
    повні = змінні + постійні

    # Точка беззбитковості. Ділення на нуль тут не аварія, а нормальний
    # стан: поле, з якого нічого не взяли, беззбиткової ціни не має.
    беззбиткова_врожайність = повні / ціна if ціна > 0 else None
    беззбиткова_ціна = повні / урожай if урожай > 0 else None

    return {
        "площа_га": площа,
        "дохід": {"зерно": зерно, "дотація": дотація, "разом": дохід},
        "змінні": {"рядки": змінні_рядки, "разом": змінні},
        "маржинальний": маржинальний,
        "постійні": {"рядки": постійні_рядки, "разом": постійні},
        "чистий": чистий,
        "повні_витрати": повні,
        "собівартість_т": повні / урожай if урожай > 0 else None,
        "беззбитковість": {
            "врожайність_т_га": беззбиткова_врожайність,
            "ціна_т": беззбиткова_ціна,
            "запас_врожайності": ((урожай / беззбиткова_врожайність - 1.0) * 100.0
                                  if беззбиткова_врожайність else None),
            "запас_ціни": ((ціна / беззбиткова_ціна - 1.0) * 100.0
                           if беззбиткова_ціна else None),
        },
        "на_поле": {
            "дохід": дохід * площа,
            "змінні": змінні * площа,
            "маржинальний": маржинальний * площа,
            "постійні": постійні * площа,
            "чистий": чистий * площа,
        },
    }


def звести(бюджети, підпис="разом"):
    """Матрьошка: поле → культура → господарство.

    Складаємо ГРИВНІ, а не грн/га. Середнє з питомих чисел по полях різної
    площі — не середнє господарства: поле на 5 га важило б стільки ж,
    скільки поле на 200. Питоме число дістаємо назад діленням на суму площ.
    """
    площа = sum(_число(б.get("площа_га"), 0.0) for б in бюджети)
    сума = {к: 0.0 for к in ("дохід", "змінні", "маржинальний", "постійні", "чистий")}
    for б in бюджети:
        на_поле = б.get("на_поле") or {}
        for к in сума:
            сума[к] += _число(на_поле.get(к), 0.0)
    га = max(площа, 1e-9)
    return {
        "підпис": підпис,
        "площа_га": площа,
        "полів": len(бюджети),
        "грн": dict(сума),
        "грн_га": {к: (в / га) for к, в in сума.items()},
    }


