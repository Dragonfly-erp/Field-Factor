# ПЛАН ПОЛЯ: що саме на ньому робили й чим
# ═══════════════════════════════════════════════════════════════════════
#
# Бюджет не вводиться руками рядок за рядком. Він СКЛАДАЄТЬСЯ з двох речей:
# довідників (скільки коштує) і плану поля (що і скільки застосували). Тому
