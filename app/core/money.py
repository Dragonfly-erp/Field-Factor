# табличок, з яких двадцять забули.

ФАЙЛ_ПЛАНУ = "бюджет_{}.json"

ПОРОЖНІЙ_ПЛАН = {
    "культура": "", "врожайність_т_га": None, "ціна_т": None,
    "дотація_грн_га": 0.0,
    "матеріали": [],        # [{"ключ": ..., "норма": ...}]
    "роботи": [],           # ["дискування", "сівба", ...]
    "змінні_вручну": {},    # {"сушіння": 2645, ...} — те, чого немає в довідниках
    "поле": {},             # оренда_грн_га, частка_годин, частка_виручки
}


def план(тека_поля, рік):
    return _прочитати(os.path.join(тека_поля, ФАЙЛ_ПЛАНУ.format(рік)), ПОРОЖНІЙ_ПЛАН)


def зберегти_план(тека_поля, рік, дані):
    повний = json.loads(json.dumps(ПОРОЖНІЙ_ПЛАН))
    повний.update(дані or {})
    return _записати(os.path.join(тека_поля, ФАЙЛ_ПЛАНУ.format(рік)), повний)


def _за_ключем(перелік, поле="назва"):
    return {ключ(з.get(поле) or ""): з for з in перелік or []}


def скласти(довід, план_поля, площа_га, площа_господарства_га):
    """План поля × довідники → готовий бюджет підприємства.

    Тут не питається жодного числа: усе, що потрібно, лежить або в довіднику,
    або в плані. Рядок, для якого чогось бракує, **не мовчить** — він
    потрапляє в `бракує`, і екран показує його червоним. Мовчазний нуль у
    бюджеті — це найдорожчий вид брехні: він виглядає як «безкоштовно».
    """
    матеріали = _за_ключем(довід.get("матеріали"))
    роботи = _за_ключем(довід.get("роботи"))
    пальне_грн_л = _число(довід.get("пальне_грн_л"))
    бракує = []

    змінні = {к: 0.0 for к, _ in СТАТТІ_ЗМІННИХ}
    ужито = {"матеріали": [], "роботи": []}

    # ── матеріали: кожен лягає у свою статтю за видом
    куди = {"добриво": "добрива", "насіння": "насіння", "ЗЗР": "ЗЗР"}
    for рядок in план_поля.get("матеріали") or []:
        к = ключ(рядок.get("ключ") or "")
        картка = матеріали.get(к)
        if картка is None:
            бракує.append("матеріалу «{}» немає в довіднику".format(рядок.get("ключ")))
            continue
        норма = рядок.get("норма") if рядок.get("норма") is not None else картка.get("норма")
        грн = вартість_матеріалу(картка, норма)
        if грн is None:
            бракує.append("«{}»: не названо {}".format(
                картка.get("назва"),
                "ціни" if _число(картка.get("ціна")) is None else "норми"))
            continue
        стаття = куди.get(картка.get("вид"), "інші_змінні")
        змінні[стаття] += грн
        ужито["матеріали"].append({"назва": картка.get("назва"), "стаття": стаття,
                                   "норма": _число(норма), "одиниця": картка.get("одиниця"),
                                   "ціна": _число(картка.get("ціна")), "грн_га": грн,
                                   "дата_ціни": картка.get("дата_ціни")})

    # ── роботи: пальне окремою статтею, решта — «роботи й техніка»
    if план_поля.get("роботи") and пальне_грн_л is None:
        бракує.append("не названо ціни пального — роботи порахувати не можна")
    for імʼя in план_поля.get("роботи") or []:
        картка = роботи.get(ключ(імʼя))
        if картка is None:
            бракує.append("операції «{}» немає в довіднику".format(імʼя))
            continue
        л = _число(картка.get("пальне_л_га"), 0.0)
        пальне = л * (пальне_грн_л or 0.0)
        ставка = _число(картка.get("ставка_грн_га"), 0.0)
        змінні["пальне"] += пальне
        змінні["роботи"] += ставка
        ужито["роботи"].append({"назва": картка.get("назва"), "пальне_л_га": л,
                                "пальне_грн_га": пальне, "ставка_грн_га": ставка,
                                "грн_га": пальне + ставка})

    # ── те, чого в довідниках немає: сушіння, перевезення, страхування
    for стаття, значення in (план_поля.get("змінні_вручну") or {}).items():
        if стаття not in змінні:
            бракує.append("невідома стаття змінних: «{}»".format(стаття))
            continue
        змінні[стаття] += _число(значення, 0.0)

    поле = dict(план_поля.get("поле") or {})
    поле.setdefault("площа_га", площа_га)
    постійні = постійні_на_гектар(довід.get("витрати"), площа_господарства_га, поле)

    # ── ціна продукції: з плану, або з довідника за культурою
    ціна = _число(план_поля.get("ціна_т"))
    if ціна is None:
        культура = ключ(план_поля.get("культура") or "")
        картка = _за_ключем(довід.get("ціни_продукції"), "культура").get(культура)
        if картка is not None:
            ціна = _число(картка.get("ціна_т"))
        if ціна is None:
            бракує.append("не названо ціни на «{}»".format(план_поля.get("культура") or "культуру"))

    урожай = _число(план_поля.get("врожайність_т_га"))
    if урожай is None:
        бракує.append("не названо врожайності — дохід рахувати нема з чого")

    зібраний = бюджет({
        "площа_га": площа_га,
        "врожайність_т_га": урожай or 0.0,
        "ціна_т": ціна or 0.0,
        "дотація_грн_га": план_поля.get("дотація_грн_га") or 0.0,
        "змінні": змінні,
        "постійні": постійні,
    })
    зібраний["ужито"] = ужито
    зібраний["бракує"] = бракує
    зібраний["повний"] = not бракує
    return зібраний
