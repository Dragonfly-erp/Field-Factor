def без_ПДВ(ціна, з_ПДВ=True, ставка=СТАВКА_ПДВ):
    """Ціна без податку. Потрібна для порівняння з чужими бюджетами.

    У наших числах ПДВ сидить усередині — так вирішив Власник, і так стоїть
    у накладній. Але ПДВ відшкодовується, тож будь-яке порівняння з
    published-бюджетами треба робити на очищеній ціні, інакше ми на п'яту
    частину «дорожчі» без жодної причини.
    """
    ц = _число(ціна)
    if ц is None:
        return None
    return ц / (1.0 + ставка / 100.0) if з_ПДВ else ц


