# -*- coding: utf-8 -*-
"""Зведення нормалізованої карти на сітку: рівно стільки точок, скільки треба.

Монітор пише запис приблизно кожні півтори секунди. На полі 127 га з жаткою
6 м це 222 760 записів — по вісімнадцять на кожну комірку тієї сітки 10 м,
на якій потім будуються зони. Вісімнадцять чисел про один і той самий
клапоть землі — це не точність, це вага файлу.

**Але густина — не питання зручності, а питання чесності.** Карта не має
права стверджувати дрібніше, ніж вона здатна розрізнити, а розрізняє вона
грубо:

- **упоперек проходу** роздільність не може бути кращою за ширину жатки:
  все, що зайшло в молотарку з шести метрів, змішалось в одну масу;
- **уздовж проходу** зерно розмазане шляхом, який воно пройшло всередині
  комбайна. Затримку ми повертаємо назад, але розмазування лишається:
  на 6 км/год і десяти секундах шляху це десятки метрів.

Тому комірка дрібніша за жатку — це вигадана точність. Замовчування:
ширина жатки, але не дрібніше за десять метрів — саме на цій сітці працює
зонування, і давати йому дрібніше немає кому.

**Зводимо середнім, а не вибіркою.** Викинути сімнадцять записів із
вісімнадцяти означало б лишити один випадковий разом з усім його шумом.
Середнє по комірці — це і є врожайність цього клаптя; заразом воно гасить
трясіння датчика.

Повний хмар точок нікуди не дівається: він лишається окремим файлом. Але
далі — у зонування, у SMS, у звіт — іде зведене.
"""

import numpy as np

МІНІМАЛЬНА_КОМІРКА_М = 10.0     # сітка зонування; дрібніше нема кому споживати


def крок_за_замовчуванням(ширина_жатки_м=None):
    """Ширина жатки, але не дрібніше за сітку зонування."""
    if ширина_жатки_м and np.isfinite(ширина_жатки_м) and ширина_жатки_м > 0:
        return float(max(МІНІМАЛЬНА_КОМІРКА_М, round(float(ширина_жатки_м), 1)))
    return МІНІМАЛЬНА_КОМІРКА_М


# Скільки важить один запис у файлі. Число не з голови: у нашій схемі точок
# двадцять із гаком полів, і на диску це приблизно стільки байтів на точку
# в shapefile разом із геометрією та DBF.
БАЙТІВ_НА_ТОЧКУ = 320


def порадити(площа_га, ширина_жатки_м=None, затримка_м=None):
    """Від якого кроку до якого має сенс — і чому саме так.

    Порада не з міркувань зручності. Знизу її тримає фізика вимірювання:

    - **ширина жатки** — усе, що зайшло в молотарку з цієї смуги, змішалось
      в одну масу, і розрізняти всередині неї нема чого;
    - **шлях зерна всередині комбайна** — його ми міряємо затримкою сенсора.
      Затримку повертаємо назад, але розмазування лишається: комірка
      коротша за цей шлях описує зерно, якого в ній не росло.

    Зверху тримає споживач: зони будуються на сітці 10 м, і карта грубіша
    за 25 м уже не зона, а середнє по полю.

    Повертає межі, пораду й приблизну вагу файлу для кожного варіанта."""
    жатка = float(ширина_жатки_м) if (ширина_жатки_м and ширина_жатки_м > 0) else None
    шлях = float(затримка_м) if (затримка_м and затримка_м > 0) else None

    підстави = []
    низ = МІНІМАЛЬНА_КОМІРКА_М
    if жатка:
        підстави.append("ширина жатки {:.1f} м".format(жатка))
        низ = max(низ, жатка)
    if шлях:
        підстави.append("шлях зерна в комбайні {:.0f} м".format(шлях))
        низ = max(низ, шлях * 0.6)

    низ = float(max(МІНІМАЛЬНА_КОМІРКА_М, round(низ)))
    верх = float(max(низ + 5.0, 25.0))
    порада = float(max(МІНІМАЛЬНА_КОМІРКА_М, round(низ / 5.0) * 5.0))

    return {
        "мін_м": низ,
        "макс_м": верх,
        "порада_м": порада,
        "підстави": підстави,
        "чому_низ": ("Дрібніше не має сенсу: " + ", ".join(підстави) + "."
                     if підстави else
                     "Дрібніше за 10 м не має кому споживати — зони будуються "
                     "на сітці 10 м."),
        "чому_верх": "Грубіше за {:.0f} м це вже не карта поля, а середнє по "
                     "ньому.".format(верх),
        "варіанти": [оцінити(площа_га, к)
                     for к in _шкала(низ, верх)],
    }


def _шкала(низ, верх):
    кроки = [5, 6, 8, 10, 12, 15, 20, 25, 30]
    свої = [к for к in кроки if низ - 0.5 <= к <= верх + 0.5]
    return свої or [низ]


def оцінити(площа_га, крок_м):
    """Скільки точок і скільки байтів вийде при такому кроці."""
    крок = float(крок_м)
    комірок = (float(площа_га) * 10000.0) / (крок * крок)
    байтів = комірок * БАЙТІВ_НА_ТОЧКУ
    return {
        "крок_м": крок,
        "точок": int(round(комірок)),
        "мб": round(байтів / 1024.0 / 1024.0, 2),
    }


# Як зводити кожну колонку. Те, чого тут немає, береться від першого запису
# в комірці — це стосується підписів на кшталт назви методу.
# YLD_MODEL, LOSS_KGHA і LOSS_ZONE сюди НЕ входять: модель рахується вже
# після зведення на сітку, по готових комірках. Тут їх ще не існує.
СЕРЕДНІ = ("YLD_KGHA", "YLD_SM", "YLD_LHA", "YLD_RAW", "MOIST", "ELEV_M",
           "WORK_W_M", "SPD_KMH", "VEG_IDX", "VEG_YEARS", "BSI_IDX")

# Тривалість не усереднюється, а СУМУЄТЬСЯ: комірку набирали стільки, скільки
# сумарно тривали записи, що в неї лягли. Середнє тут дало б час одного
# запису й розсипало б арифметику, на якій тримається імпорт у SMS.
СУМИ = ("DUR_S",)
НАЙЧАСТІШІ = ("SRC_TYPE", "COMB_ID", "QC_FLAG", "METHOD", "CONF", "GAP_CLASS")


def звести_на_сітку(точки, крок_м, журнал=None):
    """Точки монітора → по одній точці на комірку сітки.

    Повертає (зведені_точки, звіт). Геометрія зведеної точки — центр комірки:
    так сітка виходить рівною, і сусідні поля лягають в одну систему.

    До кожної точки додається два числа, яких раніше не було ніде:
    `N_REC` — скільки записів монітора стоїть за цим числом, і `SD_KGHA` —
    наскільки вони між собою розходились. Комірка, зібрана з одного запису
    при розкиді сусідів у пів тонни, і комірка з двадцяти узгоджених — це
    дуже різні числа, і тепер видно, яке з них яке."""
    import geopandas as gpd
    import pandas as pd

    крок = float(крок_м)
    якщо_порожньо = {"було": int(len(точки)), "стало": int(len(точки)),
                     "крок_м": крок, "зведено": False}
    if крок <= 0 or not len(точки):
        return точки, якщо_порожньо

    x = точки.geometry.x.to_numpy()
    y = точки.geometry.y.to_numpy()

    # Початок сітки — не від хмари точок, а від круглого числа в метрах.
    # Тоді дві операції на одному полі (різні роки, різні комбайни) лягають
    # у ті самі комірки, і карти можна віднімати одну від одної.
    x0 = np.floor(x.min() / крок) * крок
    y0 = np.floor(y.min() / крок) * крок
    стовпець = np.floor((x - x0) / крок).astype("int64")
    рядок = np.floor((y - y0) / крок).astype("int64")

    таблиця = pd.DataFrame({"_р": рядок, "_с": стовпець})
    for колонка in точки.columns:
        if колонка == "geometry":
            continue
        таблиця[колонка] = точки[колонка].to_numpy()

    # Вага запису — скільки землі він накрив. Запис на повільному ході й
    # запис на повному не рівні між собою: перший описує метр, другий — три.
    вага = np.ones(len(точки))
    if "WORK_W_M" in таблиця.columns:
        ш = pd.to_numeric(таблиця["WORK_W_M"], errors="coerce").to_numpy()
        добрі = np.isfinite(ш) & (ш > 0)
        if добрі.any():
            вага = np.where(добрі, ш, np.nanmedian(ш[добрі]))
    таблиця["_вага"] = вага

    групи = таблиця.groupby(["_р", "_с"], sort=True)
    зібране = {}

    for колонка in СЕРЕДНІ:
        if колонка not in таблиця.columns:
            continue
        значення = pd.to_numeric(таблиця[колонка], errors="coerce")
        таблиця["_зн"] = значення * таблиця["_вага"]
        таблиця["_є"] = np.where(np.isfinite(значення), таблиця["_вага"], 0.0)
        сума = таблиця.groupby(["_р", "_с"])[["_зн", "_є"]].sum()
        зібране[колонка] = (сума["_зн"] / сума["_є"].replace(0, np.nan))

    for колонка in СУМИ:
        if колонка not in таблиця.columns:
            continue
        значення = pd.to_numeric(таблиця[колонка], errors="coerce")
        таблиця["_сум"] = значення
        зібране[колонка] = групи["_сум"].sum(min_count=1)

    for колонка in НАЙЧАСТІШІ:
        if колонка not in таблиця.columns:
            continue
        зібране[колонка] = групи[колонка].agg(_найчастіше)

    зведене = pd.DataFrame(зібране)
    зведене["N_REC"] = групи.size()
    if "YLD_KGHA" in таблиця.columns:
        зведене["SD_KGHA"] = групи["YLD_KGHA"].std().round(1)

    # PASS_ID і DATETIME у комірці можуть бути різні — беремо перший і
    # чесно не робимо вигляду, що комірка належить одному проходу.
    for колонка in ("PASS_ID", "DATETIME", "ORIG_ID"):
        if колонка in таблиця.columns:
            зведене[колонка] = групи[колонка].first()

    зведене = зведене.reset_index()
    центр_x = x0 + (зведене["_с"].to_numpy() + 0.5) * крок
    центр_y = y0 + (зведене["_р"].to_numpy() + 0.5) * крок
    зведене = зведене.drop(columns=["_р", "_с"])

    # Порядок колонок лишаємо той самий, що у вхідних точках, щоб словник
    # полів і всі читачі нижче по течії не помітили різниці.
    порядок = [к for к in точки.columns if к in зведене.columns]
    решта = [к for к in зведене.columns if к not in порядок]
    зведене = зведене[порядок + решта]
    зведене.insert(0, "PT_ID", np.arange(1, len(зведене) + 1))

    вихід = gpd.GeoDataFrame(
        зведене, geometry=gpd.points_from_xy(центр_x, центр_y), crs=точки.crs)

    звіт = {
        "було": int(len(точки)),
        "стало": int(len(вихід)),
        "крок_м": крок,
        "зведено": True,
        "записів_на_комірку": round(float(len(точки)) / max(len(вихід), 1), 1),
        "комірок_з_одного_запису": int((вихід["N_REC"] == 1).sum()),
    }
    if "SD_KGHA" in вихід.columns:
        розкид = вихід["SD_KGHA"].to_numpy(dtype="float64")
        розкид = розкид[np.isfinite(розкид)]
        звіт["медіанний_розкид_кггa"] = (round(float(np.median(розкид)), 1)
                                         if розкид.size else None)
    if журнал:
        журнал.сказати(
            "  зведено на сітку {:.0f} м: {} записів → {} точок "
            "(по {:.1f} на комірку)".format(
                крок, звіт["було"], звіт["стало"], звіт["записів_на_комірку"]))
    return вихід, звіт


def _найчастіше(ряд):
    ряд = ряд.dropna()
    if not len(ряд):
        return None
    значення = ряд.mode()
    return значення.iloc[0] if len(значення) else ряд.iloc[0]
