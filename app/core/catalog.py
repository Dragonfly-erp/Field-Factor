# -*- coding: utf-8 -*-
"""Картотека: господарство → поле → рік → шари.

Це те місце, якого бракувало. Поле перестає бути купою файлів у теці і стає
сутністю, до якої з роками липнуть шари: контур, врожайність, агрохімія,
знімки, зони. Контур завантажується один раз назавжди, а не щоразу.

На диску все лежить відкрито, без бази даних: тека — це господарство, тека
всередині — поле, а `шари.json` каже, що є що. Скопіювати теку на інший
компʼютер означає перенести господарство цілком.
"""

import json
import os
import shutil
from datetime import datetime

from app.core.state import безпечна_назва

РЕЄСТР = "шари.json"
ПАСПОРТ_ПОЛЯ = "поле.json"
ПАСПОРТ_ГОСПОДАРСТВА = "господарство.json"

# Типи шарів і як їх показувати за замовчуванням
ТИПИ = {
    "контур":       {"назва": "Контур поля",        "геометрія": "полігон", "колір": "#1e4d2b"},
    "врожайність":  {"назва": "Врожайність",        "геометрія": "точки",   "атрибут": "YLD_KGHA"},
    "зони":         {"назва": "Зони",               "геометрія": "полігон", "атрибут": "ZONE_ID"},
    "вегетація":    {"назва": "Вегетаційний індекс", "геометрія": "растр",  "атрибут": "NDVI"},
    "агрохімія":    {"назва": "Агрохімія",          "геометрія": "точки",   "атрибут": None},
    "ec":           {"назва": "Електропровідність", "геометрія": "точки",   "атрибут": None},
    "сканування":   {"назва": "Сканування RTK + EC", "геометрія": "точки",  "атрибут": None},
    "відбір":       {"назва": "Точки відбору зразків", "геометрія": "точки", "атрибут": "SAMPLE_ID"},
    "рельєф":       {"назва": "Рельєф",             "геометрія": "точки",   "атрибут": "ELEV_M"},
    "відкинуте":    {"назва": "Відкинуті записи",   "геометрія": "точки",   "атрибут": "QC_FLAG"},
}


def _прочитати(шлях, замовчування):
    try:
        with open(шлях, encoding="utf-8") as ф:
            return json.load(ф)
    except Exception:
        return замовчування


def _записати(шлях, дані):
    os.makedirs(os.path.dirname(шлях), exist_ok=True)
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(дані, ф, ensure_ascii=False, indent=2)


class Картотека:
    def __init__(self, корінь):
        self.корінь = корінь
        os.makedirs(корінь, exist_ok=True)

    # ---------------------------------------------------------- господарства

    def господарства(self):
        перелік = []
        for імʼя in sorted(os.listdir(self.корінь)):
            тека = os.path.join(self.корінь, імʼя)
            if not os.path.isdir(тека) or імʼя.startswith((".", "_")):
                continue
            паспорт = _прочитати(os.path.join(тека, ПАСПОРТ_ГОСПОДАРСТВА),
                                 {"назва": імʼя})
            паспорт["ключ"] = імʼя
            паспорт["поля"] = self.поля(імʼя)
            перелік.append(паспорт)
        return перелік

    def завести_господарство(self, назва):
        ключ = безпечна_назва(назва, "господарство")
        тека = os.path.join(self.корінь, ключ)
        os.makedirs(тека, exist_ok=True)
        шлях = os.path.join(тека, ПАСПОРТ_ГОСПОДАРСТВА)
        if not os.path.isfile(шлях):
            _записати(шлях, {"назва": назва.strip() or ключ,
                             "заведено": datetime.now().strftime("%Y-%m-%d")})
        return ключ

    # ---------------------------------------------------------------- поля

    def поля(self, господарство):
        тека = os.path.join(self.корінь, господарство)
        перелік = []
        if not os.path.isdir(тека):
            return перелік
        for імʼя in sorted(os.listdir(тека)):
            шлях = os.path.join(тека, імʼя)
            if not os.path.isdir(шлях):
                continue
            # Теки з підкресленням — службові (прийом меж, тимчасове). Поле
            # так назватись не може, а от імпорт свою теку кладе поруч.
            if імʼя.startswith("_"):
                continue
            паспорт = _прочитати(os.path.join(шлях, ПАСПОРТ_ПОЛЯ), {"назва": імʼя})
            паспорт["ключ"] = імʼя
            паспорт["господарство"] = господарство
            шари = self.шари(господарство, імʼя)
            паспорт["шарів"] = len(шари)
            паспорт["роки"] = sorted({ш["рік"] for ш in шари if ш.get("рік")}, reverse=True)
            # Дерево поля їде разом із полем: без нього екран мусив би
            # питати сервер по разу на кожне поле, а їх у господарстві
            # бувають сотні.
            паспорт["дерево"] = self.дерево_поля(господарство, імʼя)
            # Скільки проб прийнято й скільки бюджетів складено — два числа,
            # за якими рейка етапів каже, де робота стоїть. Читаються тут, бо
            # питати сервер по разу на поле означало б тридцять шість запитів
            # на один показ дерева.
            паспорт["проб"] = self._проб_у_полі(шлях)
            паспорт["бюджетів"] = len([ф for ф in os.listdir(шлях)
                                       if ф.startswith("бюджет_") and ф.endswith(".json")])
            перелік.append(паспорт)
        return перелік

    @staticmethod
    def _проб_у_полі(тека_поля):
        """Скільки проб у прийнятому протоколі. Немає протоколу — нуль, і це
        не «нуль проб», а «протоколу немає»; екран так це й називає."""
        розбір = _прочитати(
            os.path.join(тека_поля, "2_проміжне", "аналізи_розбір.json"), {})
        якщо = розбір.get("розбір") or {}
        return int(якщо.get("точок") or len(якщо.get("точки") or []))

    def тека_поля(self, господарство, поле):
        return os.path.join(self.корінь, господарство, поле)

    def завести_поле(self, господарство, назва):
        ключ = безпечна_назва(назва, "поле")
        тека = self.тека_поля(господарство, ключ)
        # назви підтек збігаються з тими, якими користується конвеєр
        for під in ("шари", "1_вхідні_дані", "2_проміжне", "3_віддача"):
            os.makedirs(os.path.join(тека, під), exist_ok=True)
        шлях = os.path.join(тека, ПАСПОРТ_ПОЛЯ)
        if not os.path.isfile(шлях):
            _записати(шлях, {"назва": назва.strip() or ключ,
                             "заведено": datetime.now().strftime("%Y-%m-%d")})
        return ключ

    def паспорт_поля(self, господарство, поле):
        паспорт = _прочитати(
            os.path.join(self.тека_поля(господарство, поле), ПАСПОРТ_ПОЛЯ), {}
        )
        паспорт.setdefault("назва", поле)
        паспорт["ключ"] = поле
        паспорт["господарство"] = господарство
        return паспорт

    def оновити_поле(self, господарство, поле, зміни):
        паспорт = self.паспорт_поля(господарство, поле)
        паспорт.update(зміни or {})
        паспорт.pop("ключ", None)
        паспорт.pop("господарство", None)
        _записати(os.path.join(self.тека_поля(господарство, поле), ПАСПОРТ_ПОЛЯ), паспорт)
        return паспорт

    def видалити_поле(self, господарство, поле):
        shutil.rmtree(self.тека_поля(господарство, поле), ignore_errors=True)

    # --------------------------------------------------------------- шари

    def _шлях_реєстру(self, господарство, поле):
        return os.path.join(self.тека_поля(господарство, поле), "шари", РЕЄСТР)

    # Види даних у дереві. Порядок і назви взяті з робочого дерева SMS —
    # того самого, за яким Власник працює щодня: під роком лежить межа,
    # потім те, що зробили, потім те, що зібрали. Свою мову тут вигадувати
    # не можна: людина шукає очима звичний рядок, а не наш синонім.
    ВИДИ_ДАНИХ = (
        ("контур", "Межа"),
        ("врожайність", "Збирання"),
        ("зони", "Зони керування"),
        ("норми", "Приписи внесення"),
        ("внесення", "Внесення"),
        ("сівба", "Сівба"),
        ("обприскування", "Обприскування"),
        ("аналізи", "Аналізи ґрунту"),
        ("відбір", "Відбір проб"),
        ("рельєф", "Рельєф"),
        ("сканування", "Сканування"),
        ("вегетація", "Вегетація"),
        ("інше", "Інше"),
    )
    ПІДПИС_ВИДУ = dict(ВИДИ_ДАНИХ)

    def дерево_поля(self, господарство, поле):
        """Шари поля, розкладені як у SMS: рік → вид даних → шари.

        Рік окремим рівнем, а не приміткою на шарі. У SMS так, і не з
        примхи: те саме поле живе десятиліттями, і питання агронома завжди
        звучить «що ми робили ТУТ У ТОМУ РОЦІ», а не «покажи всі шари».

        Шар без року не ховається — він лягає в окремий рік `null`, який
        екран показує як «без року». Сховати його означало б, що дані є,
        а їх ніби немає.
        """
        за_роком = {}
        for шар in self.шари(господарство, поле):
            рік = шар.get("рік")
            ключ_року = str(рік) if рік else ""
            вид = шар.get("тип") or "інше"
            if вид not in self.ПІДПИС_ВИДУ:
                вид = "інше"
            за_роком.setdefault(ключ_року, {}).setdefault(вид, []).append(шар)

        роки = []
        for ключ_року in sorted(за_роком, key=lambda р: (р == "", р), reverse=True):
            види = за_роком[ключ_року]
            роки.append({
                "рік": ключ_року or None,
                "шарів": sum(len(с) for с in види.values()),
                "види": [{"ключ": в, "підпис": self.ПІДПИС_ВИДУ[в],
                          "шари": види[в], "продукти": self._за_продуктом(види[в])}
                         for в, _ in self.ВИДИ_ДАНИХ if в in види],
            })
        return роки

    @staticmethod
    def _за_продуктом(шари):
        """Нижні рівні дерева: продукт → операція → прохід.

        Рівень з'являється тільки тоді, коли він є в даних. Порожній
        «Без продукту» над одним шаром — це сходинка, яку треба клацнути
        нізащо; а от коли продуктів кілька, без цього рівня їх не розрізнити.
        """
        за_продуктом = {}
        for шар in шари:
            за_продуктом.setdefault(шар.get("продукт") or "", {}) \
                        .setdefault(шар.get("операція") or "", []).append(шар)

        якщо_один = len(за_продуктом) == 1 and "" in за_продуктом
        якщо_один = якщо_один and all(о == "" for о in за_продуктом[""])
        якщо_один = якщо_один and not any(ш.get("проходи") for ш in шари)
        if якщо_один:
            return []          # рівнів під видом немає — показуємо самі шари

        перелік = []
        for продукт in sorted(за_продуктом):
            операції = за_продуктом[продукт]
            перелік.append({
                "продукт": продукт or "Без продукту",
                "операції": [{
                    "операція": операція or "Один захід",
                    "шари": шари_операції,
                    "проходи": [п for ш in шари_операції for п in (ш.get("проходи") or [])],
                } for операція, шари_операції in sorted(операції.items())],
            })
        return перелік

    def шари(self, господарство, поле):
        реєстр = _прочитати(self._шлях_реєстру(господарство, поле), [])
        живі = []
        тека = os.path.join(self.тека_поля(господарство, поле), "шари")
        for шар in реєстр:
            if os.path.isfile(os.path.join(тека, шар.get("файл", ""))):
                живі.append(шар)
        return живі

    def додати_шар(self, господарство, поле, ключ, назва, тип, файл,
                   рік=None, атрибут=None, походження=None, замінити=True,
                   колонки=None, культура=None,
                   продукт=None, операція=None, проходи=None):
        """Реєструє файл як шар поля. Файл уже має лежати в теці `шари`.

        `культура` пишеться поруч із роком: карта врожайності без культури —
        це число без сенсу. Дванадцять тонн — прекрасно для кукурудзи й
        неможливо для пшениці, і через рік ніхто не згадає, що там росло.

        `продукт`, `операція` і `проходи` — три нижні рівні дерева, як у
        SMS. Приписи внесення діляться по продукту (кожен свій KaliyMag чи
        вапно), операція — це один захід у поле, а прохід — окремий запис
        монітора з датою й назвою джерела. Різниця не косметична: два
        внесення одного продукту в різні дати — це дві дії, і зводити їх у
        рядок «внесли KaliyMag» означає втратити половину історії поля."""
        реєстр = _прочитати(self._шлях_реєстру(господарство, поле), [])
        if замінити:
            реєстр = [ш for ш in реєстр if ш.get("ключ") != ключ]
        зразок = ТИПИ.get(тип, {})
        реєстр.append({
            "ключ": ключ,
            "назва": назва or зразок.get("назва") or ключ,
            "тип": тип,
            "файл": файл,
            "рік": рік,
            "культура": культура,
            "атрибут": атрибут or зразок.get("атрибут"),
            "геометрія": зразок.get("геометрія", "точки"),
            "походження": походження or "",
            "колонки": колонки or [],
            "продукт": продукт or None,
            "операція": операція or None,
            # Прохід: {"дата": "15.10.2022", "джерело": "Climate FieldView",
            #          "назва": "L1", "записів": 12345}
            "проходи": list(проходи or []),
            "додано": datetime.now().strftime("%Y-%m-%d %H:%M"),
        })
        реєстр.sort(key=lambda ш: (ш.get("тип") != "контур", -(ш.get("рік") or 0),
                                   ш.get("назва", "")))
        _записати(self._шлях_реєстру(господарство, поле), реєстр)
        return реєстр

    def шар(self, господарство, поле, ключ):
        for ш in self.шари(господарство, поле):
            if ш["ключ"] == ключ:
                ш["_шлях"] = os.path.join(
                    self.тека_поля(господарство, поле), "шари", ш["файл"])
                return ш
        return None

    def видалити_шар(self, господарство, поле, ключ):
        реєстр = _прочитати(self._шлях_реєстру(господарство, поле), [])
        тека = os.path.join(self.тека_поля(господарство, поле), "шари")
        for ш in реєстр:
            if ш.get("ключ") == ключ:
                try:
                    os.remove(os.path.join(тека, ш.get("файл", "")))
                except OSError:
                    pass
        _записати(self._шлях_реєстру(господарство, поле),
                  [ш for ш in реєстр if ш.get("ключ") != ключ])

    # ------------------------------------------------------------- контур

    def покласти_контур(self, господарство, поле, gdf):
        """Контур — головний шар поля. Кладеться раз і далі береться звідси.

        Кладеться **в метрах**. Межа від клієнта частіше за все приходить у
        градусах — це будь-який KML, — а площа в градусах не площа: квадратний
        градус на нашій широті це вісім тисяч квадратних кілометрів. Доки цього
        не було, поле з такою межею показувало в дереві «0,00 га»."""
        from app.core import util

        тека = os.path.join(self.тека_поля(господарство, поле), "шари")
        os.makedirs(тека, exist_ok=True)
        файл = "контур.gpkg"
        if gdf.crs is None:
            gdf = gdf.set_crs(4326)
        if gdf.crs.is_geographic:
            gdf = gdf.to_crs(util.метрична_crs(gdf))
        gdf.to_file(os.path.join(тека, файл), driver="GPKG", layer="контур")
        площа = float(gdf.area.sum()) / 10000.0
        self.додати_шар(господарство, поле, "контур", "Контур поля", "контур", файл,
                        походження="завантажений файл межі")
        self.оновити_поле(господарство, поле, {
            "площа_га": round(площа, 2),
            "crs": int(gdf.crs.to_epsg()),
        })
        return площа

    def контур(self, господарство, поле):
        import geopandas as gpd

        шар = self.шар(господарство, поле, "контур")
        if not шар:
            return None
        return gpd.read_file(шар["_шлях"], layer="контур")
