#
# Усе вище перевіряє таблицю в ПАМʼЯТІ, і робить це до запису. Але
# господарству їде файл, а між таблицею й файлом стоять округлення, опис
# поля, його довжина й кодування. 21.08 округлення при стисканні DBF
# обнулило 789 значень потоку: таблиця лишалась бездоганною, ворота казали
# «чисто», а сім чисел SMS у файлі між собою не сходились.
#
# Тому перед видачею файл ПЕРЕЧИТУЄТЬСЯ з диска й звіряється з тим, що ми
# збиралися віддати.


def _опис_полів_dbf(шлях):
    """Тип, довжина й кількість знаків кожного поля — з ОПИСУ у файлі.

    Дивитись треба саме сюди, а не на значення: драйвер шейпфайла оголошує
    числове поле 24 байтами з пʼятнадцятьма знаками незалежно від того, що
    ми округлили в памʼяті. Точність зашита в опис.
    """
    import struct

    with open(шлях, "rb") as ф:
        дані = ф.read(4096)
    скільки = (struct.unpack("<H", дані[8:10])[0] - 33) // 32
    поля = {}
    for і in range(скільки):
        п = 32 + і * 32
        імʼя = дані[п:п + 11].split(b"\x00")[0].decode("ascii", "replace")
        поля[імʼя] = {"тип": chr(дані[п + 11]),
                      "довжина": дані[п + 16],
                      "знаків": дані[п + 17]}
    return поля


def звірити_віддане(шлях_шейпа, очікувано, журнал):
    """Ті самі числа, але прочитані з файлу, який поїде господарству.

    `очікувано` — таблиця, яку ми записували. Порівнюємо не «схоже», а
    покомірково: розбіжність не має перевищувати того кроку округлення,
    який ми самі оголосили в `export_points.ЗНАКІВ`.

    Кидає ValueError. Це ворота, а не рядок у довідці: 21.08 арифметика
    семи чисел SMS теж «перевірялась» — і мовчки пропускала биті файли,
    бо її результат ішов у текст.
    """
    import geopandas as gpd
    import numpy as np

    from app.core import export_points

    файл = gpd.read_file(шлях_шейпа)
    біди = []

    if len(файл) != len(очікувано):
        # Далі йти нема сенсу: порівняння покомірково на різній довжині дало б
        # помилку numpy замість зрозумілого вироку. Ворота мусять КАЗАТИ, що
        # не так, а не падати з чужим текстом.
        raise ValueError(
            "Записаний файл розійшовся з тим, що ми віддавали: у файлі {} "
            "рядків, а віддавали {}. Віддавати його не можна.".format(
                len(файл), len(очікувано)))

    # Колонка, що не доїхала, — це той самий мовчазний пропуск, який уже раз
    # викинув вісім полів із віддачі.
    зникли = [к for к in очікувано.columns
              if к != "geometry" and к not in файл.columns]
    if зникли:
        біди.append("до файлу не доїхали колонки: " + ", ".join(зникли))

    опис = _опис_полів_dbf(шлях_шейпа.replace(".shp", ".dbf"))
    знаків = export_points.ЗНАКІВ

    for колонка in файл.columns:
        if колонка == "geometry" or колонка not in очікувано.columns:
            continue
        було = np.asarray(очікувано[колонка].to_numpy(), dtype="object")
        стало = np.asarray(файл[колонка].to_numpy(), dtype="object")
        if файл[колонка].dtype.kind not in "if":
            continue

        # Ціле лишається цілим: номер проходу чи запису не має знаків після
        # коми, і в `ЗНАКІВ` йому робити нічого. Але якщо у файлі в нього
        # раптом зʼявились знаки — це вже не той номер, який ми віддавали.
        якщо_ціле = очікувано[колонка].dtype.kind in "iu"
        if якщо_ціле:
            є = опис.get(колонка, {}).get("знаків")
            if є:
                біди.append("{}: ціле число записано з {} знаками після коми"
                            .format(колонка, є))
            треба = 0
        else:
            # Кожне ДРОБОВЕ поле мусить мати оголошену точність. «Немає в
            # таблиці — пишемо як вийде» означає пʼятнадцять знаків після
            # коми там, де значущих чотири, і ніхто про це не дізнається:
            # саме так VEG_IDX, VEG_YEARS і BSI_IDX проїхали клієнту
            # сімнадцятибайтовими полями.
            if колонка not in знаків:
                біди.append("{}: дробова колонка без оголошеної точності в ЗНАКІВ"
                            .format(колонка))
                continue
            треба = знаків[колонка]
        if not якщо_ціле:
            є = опис.get(колонка, {}).get("знаків")
            if є is not None and є != треба:
                біди.append("{}: у файлі {} знаків після коми, оголошено {}"
                            .format(колонка, є, треба))

        а = np.asarray(очікувано[колонка], dtype="float64")
        б = np.asarray(файл[колонка], dtype="float64")
        якщо_обидва = np.isfinite(а) & np.isfinite(б)
        втрачені = int((np.isfinite(а) & ~np.isfinite(б)).sum())
        if втрачені:
            біди.append("{}: {} значень стали порожніми при записі"
                        .format(колонка, втрачені))
        if якщо_обидва.any():
            крок = 0.5 * 10.0 ** (-треба)
            розбіжність = np.abs(а[якщо_обидва] - б[якщо_обидва])
            найгірше = float(розбіжність.max())
            if найгірше > крок * 1.001:
                де = int(np.argmax(розбіжність))
                біди.append(
                    "{}: значення змінилось при записі на {:.6g} при дозволених "
                    "{:.6g} (було {:.6g}, стало {:.6g})".format(
                        колонка, найгірше, крок,
                        float(а[якщо_обидва][де]), float(б[якщо_обидва][де])))

    # І ті самі критичні числа, але вже з файлу.
    if "YLD_KGHA" in файл.columns:
        y = np.asarray(файл["YLD_KGHA"], dtype="float64")
        if (y < 0).any():
            біди.append("у файлі відʼємна врожайність, мінімум {:.1f}".format(np.nanmin(y)))
        if not np.isfinite(y).all():
            біди.append("у файлі {} порожніх значень врожайності".format(
                int((~np.isfinite(y)).sum())))
    коорд = np.c_[файл.geometry.x, файл.geometry.y]
    if not np.isfinite(коорд).all():
        біди.append("у файлі неможливі координати")

    if біди:
        raise ValueError(
            "Записаний файл розійшовся з тим, що ми віддавали: "
            + "; ".join(біди) + ". Віддавати його не можна.")
    журнал.сказати("  віддане звірено з записаним файлом: {} рядків, {} колонок — "
                   "збігається.".format(len(файл), len(файл.columns) - 1))

