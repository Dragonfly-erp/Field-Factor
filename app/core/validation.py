# -*- coding: utf-8 -*-
"""Фаза 13: ворота перед видачею.

Якщо тут щось не сходиться, файл не віддається мовчки «як вийшло» —
про це пишеться просто в підсумку, а критичні речі зупиняють прогін.
"""

import numpy as np


def перевірити(точки, контур, паспорт, геометрія, журнал, крок_виходу_м=None):
    """Повертає (список перевірок, чи є критичні збої).

    `крок_виходу_м` — крок сітки, на яку зведено карту. Без нього ворота
    густини міряли б вихід кроком монітора й лаялись би на кожну зведену
    карту: 98 точок на гектар проти очікуваних 2556."""
    from shapely.prepared import prep

    межа = float(паспорт.get("межа") or 20000)
    перевірки = []

    def записати(назва, гаразд, деталь, критично=False):
        перевірки.append({"перевірка": назва, "гаразд": bool(гаразд),
                          "деталь": деталь, "критично": критично})

    врожай = точки["YLD_KGHA"].to_numpy(dtype="float64")

    записати("Немає відʼємної врожайності", not (врожай < 0).any(),
             "мінімум {:.0f} кг/га".format(np.nanmin(врожай)), критично=True)

    записати("Ніщо не перевищує фізичну межу", not (врожай > межа).any(),
             "максимум {:.0f} кг/га при межі {:.0f}".format(np.nanmax(врожай), межа),
             критично=True)

    записати("Немає порожніх значень врожайності", np.isfinite(врожай).all(),
             "порожніх {}".format(int((~np.isfinite(врожай)).sum())), критично=True)

    підготовлена = prep(контур.geometry.iloc[0].buffer(0.5))
    поза = sum(0 if підготовлена.contains(т) else 1 for т in точки.geometry)
    записати("Жодна точка не вийшла за контур", поза == 0,
             "поза контуром {} точок".format(поза), критично=True)

    координати = np.c_[точки.geometry.x, точки.geometry.y]
    записати("Координати скінченні", np.isfinite(координати).all(),
             "неможливих {}".format(int((~np.isfinite(координати)).sum())), критично=True)

    ключі = np.round(координати, 1)
    унікальних = len(np.unique(ключі, axis=0))
    записати("Немає купи накладених точок", унікальних >= len(точки) * 0.98,
             "унікальних координат {} з {}".format(унікальних, len(точки)))

    щільність = len(точки) / max(контур.area.iloc[0] / 10000.0, 0.01)
    if крок_виходу_м:
        # Карта зведена на сітку — на гектарі рівно стільки комірок, скільки
        # їх туди влазить, і жодного стосунку до кроку монітора це вже не має.
        очікувано = 10000.0 / (float(крок_виходу_м) ** 2)
    else:
        очікувано = 10000.0 / (геометрія["крок_уздовж_м"] * геометрія["крок_упоперек_м"])
    записати("Щільність точок правдоподібна", 0.25 * очікувано <= щільність <= 2.5 * очікувано,
             "{:.0f} точок на гектар, очікувалось близько {:.0f}".format(щільність, очікувано))

    добудовані = точки["SRC_TYPE"] == "INTERP"
    if добудовані.any():
        з_мітками = точки.loc[добудовані, "CONF"].notna().all()
        записати("Кожна добудована точка має мітку довіри", з_мітками,
                 "добудованих {}".format(int(добудовані.sum())))

    оригінали = точки["SRC_TYPE"].isin(("ORIG", "CORR"))
    записати("Добудоване не затерло справжнє", оригінали.sum() > 0,
             "справжніх записів у файлі {}".format(int(оригінали.sum())), критично=True)

    критичні = [п for п in перевірки if п["критично"] and not п["гаразд"]]
    for п in перевірки:
        if not п["гаразд"]:
            журнал.сказати("  {} {} — {}".format(
                "СТОП:" if п["критично"] else "увага:", п["перевірка"], п["деталь"]))
    if not критичні:
        журнал.сказати("Ворота видачі пройдено чисто.")
    return перевірки, bool(критичні)
