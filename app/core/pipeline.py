def _радіус_великих_дір(перелік, ширина):
    """Наскільки великі дірки треба вміти закривати — з реальних пропусків поля."""
    великі = [д["площа_га"] for д in перелік if д["клас"] in ("C", "D")]
    if not великі:
        return max(30.0, ширина * 4)
    площа = float(np.median(великі)) * 10000.0
    радіус = float(np.sqrt(площа / np.pi))
    return float(np.clip(радіус, 20.0, 120.0))


def _середнє_по_площі(точки, растр):
    """Середнє по клітинках поля, а не по точках: точки лежать нерівномірно."""
    xmin, ymin, xmax, ymax = растр["межі"]
    рядків, стовпців = растр["форма"]
    крок = растр["крок"]
    рядки = np.clip(((ymax - точки.geometry.y.to_numpy()) / крок).astype("int64"), 0, рядків - 1)
    стовпці = np.clip(((точки.geometry.x.to_numpy() - xmin) / крок).astype("int64"), 0, стовпців - 1)
    ключ = рядки * стовпців + стовпці
    значення = точки["YLD_KGHA"].to_numpy(dtype="float64")

    сума = np.bincount(ключ, weights=значення)
    кількість = np.bincount(ключ)
    заповнені = кількість > 0
    if not заповнені.any():
        return float(np.nanmean(значення))
    return float(np.mean(сума[заповнені] / кількість[заповнені]))


def _домалювати_модель(точки):
    """Три колонки моделі: YLD_MODEL, LOSS_KGHA, LOSS_ZONE.

    Порожні ділянки — не біда: якщо модель не побудувалась або жодної ділянки
    недобору немає, колонки все одно зʼявляться. Клієнт має отримати той самий
    набір полів незалежно від того, знайшли ми на його полі втрати чи ні:
    шаблон імпорту SMS складається один раз і має підходити до всіх полів.
    """
    from app.core import report_norm

    модель = точки["YLD_KGHA"].to_numpy(dtype="float64").copy()
    підйом = np.zeros(len(точки), dtype="float64")
    зона = np.zeros(len(точки), dtype="int16")
    try:
        залишок, _пояснено, ок = report_norm.пояснити_полем(точки)
        if залишок is not None:
            ділянки = report_norm.ділянки_уваги(точки, залишок, ок, мін_га=1.5)
            if ділянки:
                модель, підйом, зона = report_norm.змодельована(точки, ділянки)
    except Exception:                                   # noqa: BLE001
        pass                                            # колонки лишаються порожніми

    точки = точки.copy()
    точки["YLD_MODEL"] = модель
    точки["LOSS_KGHA"] = підйом
    точки["LOSS_ZONE"] = зона
    return точки


