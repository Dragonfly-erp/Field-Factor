    # записів, відкинуті записи, той самий шар у GPKG, той самий шар у ZIP,
    # словник полів, протокол QC і дві зведені таблиці. Жодного з них ніхто
    # жодного разу не відкрив.
    #
    # **Нових файлів сюди не додавати без прямого прохання Власника.**
    # ═══════════════════════════════════════════════════════════════════


    добудованих = int((точки["SRC_TYPE"] == "INTERP").sum())
