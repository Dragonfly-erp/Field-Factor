# -*- coding: utf-8 -*-
"""Повний прогін: від сирих файлів монітора до готового ZIP під SMS.

Порядок кроків тут не випадковий. Затримка сенсора виправляється до того, як
рахуються викиди, бо інакше зсунуте зерно саме виглядає викидом. Калібрування
комбайнів іде до вологості, бо порівнювати треба однакове. А підгін під
вивезену вагу — найостанніший, уже по всій площі разом із добудованим.
"""

import os
import traceback
from datetime import datetime

import numpy as np

from app.core import (export_points, gaps, machines, modeling, moisture, passes,
                      qc, reading, satellite, validation)


def виконати(сеанс):
    журнал = сеанс.журнал
    try:
        сеанс.підсумок = _прогін(сеанс)
    except Exception as помилка:
        traceback.print_exc()
        журнал.збій(str(помилка))
        return
    журнал.кінець()


# ------------------------------------------------------------ головне


def _прогін(сеанс):
    журнал = сеанс.журнал
    паспорт = сеанс.паспорт
    колонки = паспорт.get("колонки") or {}
    застереження = []

    # ---- контур -------------------------------------------------------
    журнал.сказати("Читаю контур поля…", 3, "Контур поля")
    контур, опис_контуру = reading.прочитати_контур(сеанс)
    площа = float(контур.area.iloc[0]) / 10000.0
    журнал.сказати("Поле {:.2f} га, система координат {}.".format(площа, опис_контуру["crs"]))
    застереження += опис_контуру.get("зауваження", [])

    # ---- монітор ------------------------------------------------------
    журнал.сказати("Читаю файли монітора…", 8, "Записи монітора")
    таблиця, описи, зауваження = reading.прочитати_монітор(сеанс, контур.crs.to_epsg())
    таблиця, _ = reading.призначити_машини(таблиця, колонки.get("машина"), описи)
    таблиця["_ВХІДНИЙ_НОМЕР"] = np.arange(1, len(таблиця) + 1)
    застереження += зауваження
    сирих = int(len(таблиця))
    журнал.сказати("Записів: {}. Комбайнів: {}.".format(сирих, таблиця["МАШИНА"].nunique()))

    # ---- спільний вигляд ----------------------------------------------
    журнал.сказати("Зводжу до спільного вигляду…", 14, "Стандартизація")
    таблиця, нотатки = qc.стандартизувати(таблиця, паспорт, колонки, журнал)
    застереження += нотатки

    # ---- фізика -------------------------------------------------------
    журнал.сказати("Відсіваю фізично неможливе…", 20, "Очистка")
    таблиця, відсів = qc.фізичні_вікна(таблиця, паспорт, журнал)

    # ---- проходи ------------------------------------------------------
    журнал.сказати("Відновлюю проходи комбайна…", 26, "Геометрія проходів")
    таблиця = passes.визначити_проходи(таблиця)
    таблиця = таблиця.sort_values(["МАШИНА", "_ПОРЯДОК"], kind="stable").reset_index(drop=True)

    ширина_з_файлу = None
    if np.isfinite(таблиця["ШИРИНА"]).any():
        ширина_з_файлу = float(np.nanmedian(таблиця["ШИРИНА"]))
    геометрія = passes.оцінити_геометрію(таблиця, ширина_з_файлу)
    журнал.сказати(
        "Проходів {}, напрямок {:.0f}°, крок уздовж {:.1f} м, між смугами {:.1f} м, "
        "ширина захвату {:.1f} м ({}).".format(
            геометрія["проходів"], геометрія["напрямок_град"], геометрія["крок_уздовж_м"],
            геометрія["крок_упоперек_м"], геометрія["ширина_м"], геометрія["джерело_ширини"])
    )

    # ---- контур: зсув і обрізка ---------------------------------------
    журнал.сказати("Звіряю масив із межею поля…", 32, "Межа поля")
    зсув_x, зсув_y, пояснення_зсуву = qc.перевірити_зсув(таблиця, контур, журнал)
    if зсув_x or зсув_y:
        таблиця["geometry"] = таблиця.geometry.translate(зсув_x, зсув_y)
        застереження.append("Позиції зсунуто: " + пояснення_зсуву)
    таблиця, поза_контуром = qc.обрізати_контуром(таблиця, контур, геометрія["ширина_м"], журнал)

    # ---- кінематика ---------------------------------------------------
    журнал.сказати("Прибираю сліди машини, а не поля…", 38, "Зупинки й розвороти")
    таблиця, _ = qc.кінематика(таблиця, геометрія, журнал)

    # ---- затримка сенсора ---------------------------------------------
    журнал.сказати("Оцінюю затримку сенсора…", 43, "Затримка сенсора")
    затримка, пояснення_затримки = passes.оцінити_затримку(
        таблиця[таблиця["QC"] == "OK"], "ВРОЖАЙ_КГГА"
    )
    таблиця["_ЗМІНЕНО"] = False
    if затримка:
        зсунуте = passes.зсунути_уздовж(
            таблиця["ВРОЖАЙ_КГГА"].to_numpy(dtype="float64"),
            таблиця["ПРОХІД"].to_numpy(), затримка,
        )
        змінилось = np.isfinite(зсунуте)
        таблиця.loc[змінилось, "ВРОЖАЙ_КГГА"] = зсунуте[змінилось]
        таблиця.loc[змінилось, "_ЗМІНЕНО"] = True
        таблиця.loc[~змінилось & (таблиця["QC"] == "OK"), "QC"] = "TRANS"
    журнал.сказати("  " + пояснення_затримки)

    # ---- нулі й локальні викиди ---------------------------------------
    журнал.сказати("Розбираюсь із нулями…", 46, "Нулі")
    таблиця, _ = qc.нулі(таблиця, журнал)
    журнал.сказати("Шукаю локальні викиди…", 49, "Викиди")
    таблиця, _ = qc.локальні_викиди(таблиця, геометрія["крок_упоперек_м"] * 1.5, журнал)

    чистих = int((таблиця["QC"] == "OK").sum())
    частка = чистих / max(сирих, 1) * 100
    журнал.сказати("Після очистки лишилось {} записів із {} ({:.1f} %).".format(
        чистих, сирих, частка))
    if частка < 50:
        застереження.append(
            "Після очистки лишилось менше половини записів ({:.1f} %). Це багато — "
            "перегляньте, чи не помилка в налаштуваннях монітора.".format(частка)
        )
    if чистих < 100:
        raise ValueError(
            "Придатних записів лишилось {} — цього замало для будь-якої карти.".format(чистих)
        )

    # ---- комбайни -----------------------------------------------------
    журнал.сказати("Зводжу комбайни…", 53, "Комбайни")
    таблиця, звіт_машин = machines.звести(таблиця, журнал)

    # ---- вологість ----------------------------------------------------
    журнал.сказати("Приводжу до базисної вологості…", 57, "Вологість")
    таблиця, звіт_вологості = moisture.привести(таблиця, паспорт, журнал)
    застереження += звіт_вологості.get("застереження", [])
    таблиця, пояснення_обʼєму = moisture.обʼєм(таблиця, паспорт)

    чисті = таблиця[таблиця["QC"] == "OK"].copy()

    # ---- супутник -----------------------------------------------------
    шари, звіт_супутника = {}, {"використано": False, "причина": "не запитували"}
    ознаки_чистих, ознаки_назви = None, []
    if (паспорт.get("супутник") or "так") != "ні":
        журнал.сказати("Шукаю знімки Sentinel-2 за сезон…", 62, "Супутник")
        шари, звіт_супутника = satellite.зібрати(
            контур, паспорт, сеанс.налаштування, сеанс.база, журнал
        )
    if шари:
        таблиця_ознак = satellite.взяти_у_точках(
            шари, звіт_супутника["_сітка"],
            чисті.geometry.x.to_numpy(), чисті.geometry.y.to_numpy(),
        )
        if np.isfinite(чисті["ВИСОТА"]).sum() > len(чисті) * 0.5:
            таблиця_ознак["ВИСОТА"] = чисті["ВИСОТА"].to_numpy()
        ознаки_назви = list(таблиця_ознак.columns)
        ознаки_чистих = таблиця_ознак.to_numpy(dtype="float64")

    # ---- вибір методу -------------------------------------------------
    журнал.сказати("Перевіряю, чим краще закривати пропуски…", 70, "Вибір методу")
    x = чисті.geometry.x.to_numpy()
    y = чисті.geometry.y.to_numpy()
    z = чисті["ВРОЖАЙ_БАЗ"].to_numpy(dtype="float64")
    найкращий, усі_методи, висновок_супутника = modeling.обрати_метод(
        x, y, z, ознаки_чистих, чисті["ПРОХІД"].to_numpy(),
        геометрія["напрямок_рад"], геометрія["ширина_м"], журнал
    )
    супутник_у_ділі = найкращий["_ознаки"] is not None
    if висновок_супутника:
        застереження.append(висновок_супутника)

    # ---- пропуски -----------------------------------------------------
    журнал.сказати("Розмічаю пропуски…", 78, "Пропуски")
    растр = gaps.карта_покриття(чисті, контур, геометрія["ширина_м"])
    класи, зведення_пропусків, _ = gaps.класифікувати_пропуски(растр, геометрія["ширина_м"])
    покрито = float(растр["покрито"].sum()) / max(float(растр["поле"].sum()), 1) * 100
    журнал.сказати("Комбайн покрив {:.1f} % площі. Пропуски: A {} га, B {} га, "
                   "C {} га, D {} га.".format(покрито, зведення_пропусків["A"],
                                              зведення_пропусків["B"], зведення_пропусків["C"],
                                              зведення_пропусків["D"]))

    журнал.сказати("Добудовую точки на продовженні смуг…", 84, "Добудова")
    кандидати = gaps.добудувати_точки(чисті, контур, растр, класи, геометрія, журнал)

    добудовані = None
    if кандидати is not None and not паспорт.get("закривати_без_опори"):
        без_опори = кандидати["клас"] == "D"
        if без_опори.any():
            пропуски_без_опори = зведення_пропусків["D"]
            застереження.append(
                "Ділянки без жодної опори поруч ({} га) лишились незаповненими — "
                "там нічим підтвердити число. Це свідоме рішення, а не збій: "
                "щоб їх усе-таки закрити, увімкніть це на кроці «Супутник»."
                .format(пропуски_без_опори)
            )
            журнал.сказати(
                "  ділянки без опори ({} га) не заповнюються — так наказано "
                "налаштуванням".format(пропуски_без_опори)
            )
            залишити = ~без_опори
            кандидати = {к: (в[залишити] if hasattr(в, "__len__") else в)
                         for к, в in кандидати.items()}
            if not len(кандидати["x"]):
                кандидати = None

    if кандидати is not None:
        модель = найкращий["_фабрика"]()
        модель.навчити(x, y, z, найкращий["_ознаки"])

        # висота потрібна і в моделі, і в атрибутах точки, тож рахуємо завжди
        висота_нових = None
        є_висота = np.isfinite(чисті["ВИСОТА"]).sum() > len(чисті) * 0.5
        if є_висота:
            висота_модель = modeling.ЛокальнаМодель(геометрія["напрямок_рад"], 2.0)
            висота_чистих = чисті["ВИСОТА"].to_numpy(dtype="float64")
            висота_модель.навчити(x, y, np.nan_to_num(
                висота_чистих, nan=float(np.nanmean(висота_чистих))))
            висота_нових = висота_модель.передбачити(кандидати["x"], кандидати["y"])

        ознаки_нових = None
        if супутник_у_ділі:
            нові_ознаки = satellite.взяти_у_точках(
                шари, звіт_супутника["_сітка"], кандидати["x"], кандидати["y"]
            )
            if "ВИСОТА" in ознаки_назви and висота_нових is not None:
                нові_ознаки["ВИСОТА"] = висота_нових
            ознаки_нових = нові_ознаки[ознаки_назви].to_numpy(dtype="float64")

        значення = модель.передбачити(кандидати["x"], кандидати["y"], ознаки_нових)
        межа = float(паспорт.get("межа") or 20000)
        значення = np.clip(значення, 0.0, межа)

        довіра = modeling.довіра(кандидати["відстань_до_опори"], геометрія["ширина_м"])
        довіра = np.where(np.isin(кандидати["клас"], ("C", "D")) & (довіра == "HIGH"),
                          "MED", довіра)
        довіра = np.where(кандидати["клас"] == "D", "LOW", довіра)

        import geopandas as gpd

        добудовані = {
            "geometry": gpd.points_from_xy(кандидати["x"], кандидати["y"]),
            "врожай": значення,
            "смуга": кандидати["смуга"],
            "клас": кандидати["клас"],
            "довіра": довіра,
            "ширина": np.full(len(значення), геометрія["ширина_м"]),
        }
        if висота_нових is not None:
            добудовані["висота"] = висота_нових
        if паспорт.get("натура"):
            добудовані["врожай_л"] = значення / float(паспорт["натура"])
        if ознаки_нових is not None and "NDVI_макс" in ознаки_назви:
            добудовані["вег"] = ознаки_нових[:, ознаки_назви.index("NDVI_макс")]

    # ---- звірка з вагою -----------------------------------------------
    журнал.сказати("Звіряю середнє з вивезеною вагою…", 89, "Звірка з вагою")
    вег_колонка = None
    if супутник_у_ділі and "NDVI_макс" in ознаки_назви:
        чисті["_ВЕГ"] = ознаки_чистих[:, ознаки_назви.index("NDVI_макс")]
        вег_колонка = "_ВЕГ"

    точки = export_points.зібрати_таблицю(
        чисті, добудовані, паспорт, найкращий["метод"], вег_колонка
    )
    середнє_по_площі = _середнє_по_площі(точки, растр)
    точки, звіт_ваги = moisture.звірити_з_вагою(
        точки, паспорт, журнал, середнє_по_площі, поле_врожаю="YLD_KGHA"
    )
    if звіт_ваги["коефіцієнт"] != 1.0 and "YLD_LHA" in точки.columns:
        точки["YLD_LHA"] = точки["YLD_LHA"] * звіт_ваги["коефіцієнт"]
    застереження += звіт_ваги.get("застереження", [])
    точки["YLD_KGHA"] = np.clip(точки["YLD_KGHA"], 0.0, float(паспорт.get("межа") or 20000))

    # У віддачу не йде нічого поза точною межею. Допуск на виніс антени потрібен
    # був, щоб не викинути справжні прикрайові записи з розрахунку — але у файл
    # господарства має лягти рівно поле, і ні сантиметра більше.
    строго_всередині = точки.within(контур.geometry.iloc[0])
    якщо_поза = int((~строго_всередині).sum())
    if якщо_поза:
        точки = точки[строго_всередині].reset_index(drop=True)
        точки["PT_ID"] = np.arange(1, len(точки) + 1)
        журнал.сказати(
            "  {} прикрайових точок лишились за межею контуру — у розрахунку вони "
            "працювали, у файл не пішли.".format(якщо_поза)
        )

    # ---- ворота -------------------------------------------------------
    журнал.сказати("Проходжу ворота видачі…", 93, "Перевірка")
    перевірки, є_критичні = validation.перевірити(точки, контур, паспорт, геометрія, журнал)
    if є_критичні:
        raise ValueError(
            "Перевірка перед видачею не пройдена. Файл не створено — дивіться "
            "рядки зі словом СТОП вище."
        )

    # ---- віддача ------------------------------------------------------
    журнал.сказати("Складаю файли…", 96, "Віддача")
    підсумок = _віддати(
        сеанс, точки, таблиця, контур, геометрія, растр, зведення_пропусків,
        звіт_машин, звіт_вологості, звіт_ваги, звіт_супутника, найкращий, усі_методи,
        перевірки, застереження, сирих, чистих, пояснення_обʼєму, покрито,
    )
    журнал.сказати("Готово.", 100, "Готово")
    return підсумок


# ------------------------------------------------------------ допоміжне


def _середнє_по_площі(точки, растр):
    """Середнє по клітинках поля, а не по точках: точки лежать нерівномірно."""
    xmin, ymin, xmax, ymax = растр["межі"]
    рядків, стовпців = растр["форма"]
    крок = растр["крок"]
    рядки = np.clip(((ymax - точки.geometry.y.to_numpy()) / крок).astype("int64"), 0, рядків - 1)
    стовпці = np.clip(((точки.geometry.x.to_numpy() - xmin) / крок).astype("int64"), 0, стовпців - 1)
    ключ = рядки * стовпців + стовпці
    значення = точки["YLD_KGHA"].to_numpy(dtype="float64")

    сума = np.bincount(ключ, weights=значення)
    кількість = np.bincount(ключ)
    заповнені = кількість > 0
    if not заповнені.any():
        return float(np.nanmean(значення))
    return float(np.mean(сума[заповнені] / кількість[заповнені]))


def _віддати(сеанс, точки, повна, контур, геометрія, растр, пропуски, звіт_машин,
             звіт_вологості, звіт_ваги, звіт_супутника, найкращий, усі_методи,
             перевірки, застереження, сирих, чистих, пояснення_обʼєму, покрито):
    import geopandas as gpd

    основа = "{}_{}".format(
        сеанс.паспорт.get("поле") or "поле", сеанс.паспорт.get("рік") or ""
    ).strip("_").replace(" ", "_")
    тека = сеанс.шлях("3_віддача")
    os.makedirs(тека, exist_ok=True)
    файли = []

    імʼя_точок = "{}_yield_normalized_points".format(основа)
    файли += export_points.записати_шейп(точки, os.path.join(тека, імʼя_точок + ".shp"))
    файли.append(export_points.словник_полів(os.path.join(тека, "field_dictionary.csv")))

    відкинуті = повна[повна["QC"] != "OK"]
    if len(відкинуті):
        колонки = ["QC", "МАШИНА", "ПРОХІД", "ВРОЖАЙ_КГГА", "ВОЛОГІСТЬ", "geometry"]
        колонки = [к for к in колонки if к in відкинуті.columns]
        шар = gpd.GeoDataFrame(відкинуті[колонки], geometry="geometry", crs=повна.crs)
        шар = шар.rename(columns={"МАШИНА": "COMB_ID", "ПРОХІД": "PASS_ID",
                                  "ВРОЖАЙ_КГГА": "YLD_KGHA", "ВОЛОГІСТЬ": "MOIST_RAW",
                                  "QC": "QC_FLAG"})
        файли += export_points.записати_шейп(
            шар, os.path.join(тека, "removed_or_flagged_points.shp")
        )

    оригінали = точки[точки["SRC_TYPE"] != "INTERP"]
    файли += export_points.записати_шейп(
        оригінали, os.path.join(тека, "original_clean_points.shp")
    )

    gpkg = os.path.join(тека, імʼя_точок + ".gpkg")
    точки.to_file(gpkg, driver="GPKG", layer="yield_points")
    файли.append(gpkg)

    if звіт_машин.get("рядки"):
        файли.append(export_points.таблиця_csv(
            os.path.join(тека, "machine_normalization_summary.csv"),
            ["комбайн", "поправка", "спільних клітинок", "рішення"],
            [[р["машина"], р["поправка"], р["спільних_клітинок"], р["рішення"]]
             for р in звіт_машин["рядки"]],
        ))

    if звіт_супутника.get("рядки"):
        файли.append(export_points.таблиця_csv(
            os.path.join(тека, "satellite_sources_summary.csv"),
            ["вікно сезону", "дата сцени", "хмарність сцени, %", "стан"],
            [[р["вікно"], р["сцена"], р.get("хмарність", ""), р["стан"]]
             for р in звіт_супутника["рядки"]],
        ))

    зміст = _текст_qc(сеанс, точки, повна, геометрія, пропуски, звіт_машин, звіт_вологості,
                      звіт_ваги, звіт_супутника, найкращий, усі_методи, перевірки,
                      застереження, сирих, чистих, пояснення_обʼєму, покрито)
    файли.append(export_points.звіт_qc(os.path.join(тека, "qc_summary.txt"), зміст))

    архів = os.path.join(тека, імʼя_точок + ".zip")
    export_points.запакувати(архів, файли)

    добудованих = int((точки["SRC_TYPE"] == "INTERP").sum())
    похибка = найкращий.get("проходами") or найкращий.get("блоками")

    перелік = [{"імʼя": os.path.basename(архів),
                "опис": "Нормалізована точкова карта під SMS — усе разом",
                "байтів": os.path.getsize(архів)}]
    for додатковий in ("qc_summary.txt", "field_dictionary.csv"):
        шлях = os.path.join(тека, додатковий)
        if os.path.isfile(шлях):
            перелік.append({
                "імʼя": додатковий,
                "опис": ("Звіт: що зроблено з даними і чому" if "qc" in додатковий
                         else "Словник полів шейпфайла"),
                "байтів": os.path.getsize(шлях),
            })

    return {
        "записів_сирих": сирих,
        "записів_чистих": чистих,
        "частка_чистих": round(чистих / max(сирих, 1) * 100, 1),
        "записів_відкинутих": сирих - чистих,
        "точок_добудованих": добудованих,
        "частка_добудованих": round(добудованих / max(len(точки), 1) * 100, 1),
        "точок_усього": int(len(точки)),
        "середня_кг_га": round(float(точки["YLD_KGHA"].mean()), 1),
        "базис": сеанс.паспорт.get("базис"),
        "похибка": ("{:.0f} кг/га на схованих ділянках ({:.0f} % від середнього)".format(
            похибка["MAE"], похибка["MAE"] / max(float(точки["YLD_KGHA"].mean()), 1) * 100)
            if похибка else "не рахувалась"),
        "комбайни": "{} · {}".format(звіт_машин.get("машин"), звіт_машин.get("підстава")),
        "супутник": (("узято {} сцен, {}".format(звіт_супутника.get("сцен"),
                      "використано в моделі" if найкращий["_ознаки"] is not None
                      else "у модель не пішов — не покращив перевірку"))
                     if звіт_супутника.get("використано") else
                     "не використано ({})".format(звіт_супутника.get("причина", "—"))),
        "застереження": застереження,
        "файли": перелік,
        "_тека": тека,
        "_основа": основа,
    }


def _текст_qc(сеанс, точки, повна, геометрія, пропуски, звіт_машин, звіт_вологості,
              звіт_ваги, звіт_супутника, найкращий, усі_методи, перевірки,
              застереження, сирих, чистих, пояснення_обʼєму, покрито):
    п = сеанс.паспорт
    рядки = []
    д = рядки.append

    д("FieldFactor · звіт про обробку")
    д("=" * 70)
    д("Поле: {}".format(п.get("поле")))
    д("Культура і рік: {}, {}".format(п.get("культура"), п.get("рік")))
    д("Збирання: {}".format(п.get("дати") or "не вказано"))
    д("Зроблено: {}".format(datetime.now().strftime("%d.%m.%Y %H:%M")))
    д("")

    д("ЩО БУЛО НА ВХОДІ")
    д("-" * 70)
    д("Записів монітора: {}".format(сирих))
    д("Комбайнів: {}".format(звіт_машин.get("машин")))
    д("Ширина захвату: {:.2f} м ({})".format(геометрія["ширина_м"], геометрія["джерело_ширини"]))
    д("Крок уздовж проходу: {:.2f} м; між смугами: {:.2f} м".format(
        геометрія["крок_уздовж_м"], геометрія["крок_упоперек_м"]))
    д("Напрямок проходів: {:.0f}°".format(геометрія["напрямок_град"]))
    д("")

    д("ОЧИСТКА")
    д("-" * 70)
    зведення = повна["QC"].value_counts()
    for код, кількість in зведення.items():
        назва = "чистий запис" if код == "OK" else qc.КОДИ.get(код, код)
        д("  {:<6} {:>8}   {}".format(код, int(кількість), назва))
    д("")
    д("Лишилось {} записів із {} ({:.1f} %).".format(
        чистих, сирих, чистих / max(сирих, 1) * 100))
    д("Комбайн покрив {:.1f} % площі поля.".format(покрито))
    д("")

    д("КОМБАЙНИ")
    д("-" * 70)
    д("Підстава: {}".format(звіт_машин.get("підстава")))
    for р in звіт_машин.get("рядки", []):
        д("  {:<20} ×{:<8} {}".format(str(р["машина"])[:20], р["поправка"], р["рішення"]))
    д("")

    д("ВОЛОГІСТЬ І ОДИНИЦІ")
    д("-" * 70)
    д("Базис: {} %".format(п.get("базис")))
    if звіт_вологості.get("застосовано"):
        д("Формула Y_баз = Y_вим × (100 − M_вим) / (100 − M_баз) застосована.")
        д("Медіана виміряної вологості: {} %".format(звіт_вологості.get("медіана_вологості")))
    else:
        д("Приведення не виконувалось.")
    д("л/га: {}".format(пояснення_обʼєму))
    д("")

    д("ЗВІРКА З ФАКТИЧНОЮ ВРОЖАЙНІСТЮ")
    д("-" * 70)
    д("Джерело числа господарства: {}".format(звіт_ваги.get("джерело")))
    д("Середнє по площі до підгону: {} кг/га".format(звіт_ваги.get("до_підгону_кг_га")))
    if звіт_ваги.get("ціль_кг_га"):
        д("Ціль: {:.0f} кг/га".format(звіт_ваги["ціль_кг_га"]))
    д("Застосований коефіцієнт: ×{}".format(звіт_ваги.get("коефіцієнт")))
    д("")

    д("СУПУТНИК")
    д("-" * 70)
    д("Джерело: {}".format(звіт_супутника.get("джерело", "—")))
    if звіт_супутника.get("рядки"):
        for р in звіт_супутника["рядки"]:
            д("  {:<24} {:<12} {}".format(р["вікно"], р["сцена"], р["стан"]))
    else:
        д("  не використовувався: {}".format(звіт_супутника.get("причина")))
    д("")

    д("ВИБІР МЕТОДУ ВІДНОВЛЕННЯ")
    д("-" * 70)
    д("Перевірка: приховані блоки поля і приховані цілі проходи.")
    for р in усі_методи:
        if р["MAE"] is None:
            д("  {:<22} перевірка не вийшла".format(р["метод"]))
            continue
        д("  {:<22} MAE {:>7.0f} кг/га{}".format(
            р["метод"], р["MAE"],
            "   на схованих проходах {:.0f}".format(р["проходами"]["MAE"]) if р["проходами"] else ""))
    д("")
    д("Обрано: {}".format(найкращий["метод"]))
    д("")

    д("ПРОПУСКИ Й ДОБУДОВА")
    д("-" * 70)
    д("A — короткі розриви всередині проходу: {} га".format(пропуски["A"]))
    д("B — пропущені смуги між проходами: {} га".format(пропуски["B"]))
    д("C — великі ділянки з опорою поруч: {} га".format(пропуски["C"]))
    д("D — великі ділянки без опори: {} га".format(пропуски["D"]))
    д("")
    за_довірою = точки[точки["SRC_TYPE"] == "INTERP"]["CONF"].value_counts()
    if len(за_довірою):
        д("Добудовані точки за довірою:")
        for мітка, кількість in за_довірою.items():
            д("  {:<6} {}".format(мітка, int(кількість)))
    else:
        д("Добудова не знадобилась.")
    д("")

    д("ВОРОТА ВИДАЧІ")
    д("-" * 70)
    for пер in перевірки:
        д("  [{}] {:<44} {}".format("так" if пер["гаразд"] else "НІ",
                                    пер["перевірка"], пер["деталь"]))
    д("")

    if застереження:
        д("ЩО ТРЕБА ЗНАТИ ПРО ЦЕЙ ФАЙЛ")
        д("-" * 70)
        for з in застереження:
            д("  · " + з)
        д("")

    д("ПІДСУМОК")
    д("-" * 70)
    д("Точок у файлі: {} (справжніх {}, добудованих {})".format(
        len(точки), int((точки["SRC_TYPE"] != "INTERP").sum()),
        int((точки["SRC_TYPE"] == "INTERP").sum())))
    д("Середня врожайність: {:.0f} кг/га при {} % вологості".format(
        float(точки["YLD_KGHA"].mean()), п.get("базис")))
    д("")
    д("Добудовані точки позначені SRC_TYPE = INTERP і мають мітку довіри CONF.")
    д("Справжні записи монітора нічим не замінені й не затерті.")
    return "\n".join(рядки)
