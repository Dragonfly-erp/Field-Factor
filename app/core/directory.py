ЗА_КЛЮЧЕМ = {р["ключ"]: р for р in РОЗДІЛИ}


def _шлях(база):
    return os.path.join(база, ФАЙЛ)


def _прочитати(база):
    try:
        with open(_шлях(база), encoding="utf-8") as ф:
            return json.load(ф)
    except Exception:
        return {}


def _записати(база, дані):
    with open(_шлях(база), "w", encoding="utf-8") as ф:
        json.dump(дані, ф, ensure_ascii=False, indent=2)


def ключ_назви(назва):
    """Ключ із назви. Потрібен, щоб два записи з тим самим іменем не
    розʼїхались у два різні елементи через зайвий пробіл."""
    низ = re.sub(r"\s+", " ", str(назва or "").strip().lower())
    return re.sub(r"[^\w\- ]", "", низ, flags=re.UNICODE)


def перевірити(розділ, елемент):
    """Що не так із карткою. Помилка — не приймаємо; увага — приймаємо,
    але кажемо вголос."""
    опис = ЗА_КЛЮЧЕМ.get(розділ)
    зауваги = []
    if опис is None:
        return [{"вага": "помилка", "що": "розділ", "чому": "невідомий розділ довідника"}]
    for поле in опис.get("поля") or []:
        значення = (елемент or {}).get(поле["ключ"])
        порожнє = значення in (None, "", [])
        if поле.get("обовʼязкове") and порожнє:
            зауваги.append({"вага": "помилка", "що": поле["підпис"],
                            "чому": "без цього картка ні про що"})
        if поле.get("вид") == "число" and not порожнє:
            try:
                float(str(значення).replace(",", "."))
            except ValueError:
                зауваги.append({"вага": "помилка", "що": поле["підпис"],
                                "чому": "це не число: «{}»".format(значення)})
        if поле.get("вид") == "вибір" and not порожнє:
            дозволені = [к for к, _ in поле.get("варіанти") or []]
            if дозволені and значення not in дозволені:
                зауваги.append({"вага": "увага", "що": поле["підпис"],
                                "чому": "значення поза переліком: «{}»".format(значення)})
    return зауваги


def перелік(база, розділ):
    """Елементи розділу. Розділи з чужою домівкою тут порожні: їх збирає
    той, хто ними володіє."""
    if ЗА_КЛЮЧЕМ.get(розділ, {}).get("де") != "тут":
        return []
    return _прочитати(база).get(розділ) or []


def зберегти(база, розділ, елемент):
    опис = ЗА_КЛЮЧЕМ.get(розділ)
    if опис is None or опис.get("де") != "тут":
        return {"гаразд": False, "повідомлення": "Цей розділ редагується не тут"}
    зауваги = перевірити(розділ, елемент)
    if any(з["вага"] == "помилка" for з in зауваги):
        return {"гаразд": False, "зауваги": зауваги}

    дані = _прочитати(база)
    свої = list(дані.get(розділ) or [])
    елемент = dict(елемент or {})
    ключ = елемент.get("ключ") or ключ_назви(елемент.get("назва"))
    елемент["ключ"] = ключ
    елемент["змінено"] = datetime.now().strftime("%Y-%m-%d %H:%M")
    за_ключем = {з.get("ключ"): і for і, з in enumerate(свої)}
    if ключ in за_ключем:
        свої[за_ключем[ключ]] = елемент
    else:
        елемент.setdefault("заведено", елемент["змінено"])
        свої.append(елемент)
    свої.sort(key=lambda з: str(з.get("назва") or ""))
    дані[розділ] = свої
    _записати(база, дані)
    return {"гаразд": True, "ключ": ключ, "зауваги": зауваги}


def видалити(база, розділ, ключ):
    дані = _прочитати(база)
    свої = list(дані.get(розділ) or [])
    лишилось = [з for з in свої if з.get("ключ") != ключ]
    if len(лишилось) == len(свої):
        return {"гаразд": False, "повідомлення": "Такого запису немає"}
    дані[розділ] = лишилось
    _записати(база, дані)
    return {"гаразд": True}


def улюблене(база, розділ, ключ, стан=True):
    """Зірочка, як у SMS: часто вживане спливає нагору переліку."""
    дані = _прочитати(база)
    for з in дані.get(розділ) or []:
        if з.get("ключ") == ключ:
            з["улюблене"] = bool(стан)
            _записати(база, дані)
            return {"гаразд": True}
    return {"гаразд": False, "повідомлення": "Такого запису немає"}
