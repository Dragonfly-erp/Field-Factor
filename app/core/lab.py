# Найдешевша й найдорожча помилка одночасно: зразок ліг не на ту точку.
# Числа при цьому виглядають нормально, карта виходить гарна, а норма
# їде не на той гектар. Тому звіряння — окремий крок до розрахунку.

РАДІУС_ЗБІГУ_М = 60.0     # далі цього збіг за координатою вже не збіг


def наші_точки_з_шару(шлях):
    """Точки відбору з нашого шейпфайла: номер і координата в WGS-84.

    Номер шукаємо серед звичних назв колонок; якщо його немає — беремо
    порядковий. Порядковий гірший: він залежить від порядку записів у файлі,
    тому такий випадок позначаємо."""
    import geopandas as gpd

    шар = gpd.read_file(шлях)
    if шар.crs is not None:
        шар = шар.to_crs(4326)
    імена = {к.lower(): к for к in шар.columns}
    колонка = None
    for варіант in ("sample_id", "номер", "група", "group", "pt_id", "id", "zone"):
        if варіант in імена:
            колонка = імена[варіант]
            break
    точки = []
    for порядок, (_, рядок) in enumerate(шар.iterrows(), start=1):
        г = рядок.geometry
        точки.append(dict(
            номер=рядок[колонка] if колонка else порядок,
            номер_порядковий=колонка is None,
            широта=float(г.y) if г is not None else None,
            довгота=float(г.x) if г is not None else None))
    return точки


def _відстань_м(ш1, д1, ш2, д2):
    """Груба відстань між двома точками в метрах. Для десятків метрів годиться."""
    import math
    if None in (ш1, д1, ш2, д2):
        return None
    сер = math.radians((ш1 + ш2) / 2.0)
    dx = (д2 - д1) * 111320.0 * math.cos(сер)
    dy = (ш2 - ш1) * 110540.0
    return math.hypot(dx, dy)


def _ключ_номера(значення):
    """«1,000», «01», « 1 » — це той самий номер 1."""
    т = str(значення if значення is not None else "").strip()
    if not т:
        return None
    try:
        ч = float(т.replace(",", "."))
        if ч == int(ч):
            return str(int(ч))
    except ValueError:
        pass
    return т.lower()


def звірити_нумерацію(розбір, наші_точки):
    """Рядки лабораторії ↔ наші точки відбору.

    наші_точки — список словників із «номер» і, якщо є, «широта»/«довгота».
    Повертає пари, сиріт з обох боків і дублікати."""
    наші = []
    for т in наші_точки or []:
        наші.append(dict(
            номер=т.get("номер") if т.get("номер") is not None else т.get("група"),
            широта=т.get("широта"), довгота=т.get("довгота"),
            зони=т.get("зони"), зайнята=False))

    лабораторні = розбір["точки"]
    пари, лаб_без_пари, дублікати = [], [], []
    вжиті_номери = {}

    for л in лабораторні:
        ключ = _ключ_номера(л.get("номер_лабораторії"))
        if ключ is not None:
            вжиті_номери.setdefault(ключ, []).append(л["рядок_у_файлі"])

        збіг, як, відстань = None, None, None
        for н in наші:
            if н["зайнята"]:
                continue
            if ключ is not None and _ключ_номера(н["номер"]) == ключ:
                збіг, як = н, "за номером"
                відстань = _відстань_м(л.get("широта"), л.get("довгота"),
                                       н.get("широта"), н.get("довгота"))
                break
        if збіг is None:
            найкраща = None
            for н in наші:
                if н["зайнята"]:
                    continue
                д = _відстань_м(л.get("широта"), л.get("довгота"),
                                н.get("широта"), н.get("довгота"))
                if д is not None and (найкраща is None or д < найкраща[1]):
                    найкраща = (н, д)
            if найкраща and найкраща[1] <= РАДІУС_ЗБІГУ_М:
                збіг, як, відстань = найкраща[0], "за координатою", найкраща[1]

        if збіг is None:
            лаб_без_пари.append(dict(
                рядок=л["рядок_у_файлі"], номер=л.get("номер_лабораторії"),
                широта=л.get("широта"), довгота=л.get("довгота")))
            continue

        збіг["зайнята"] = True
        попередження = []
        if як == "за номером" and відстань is not None and відстань > РАДІУС_ЗБІГУ_М:
            попередження.append(
                "номер збігся, а точка стоїть за %.0f м від нашої — "
                "перевірити, чи не переплутано зразки" % відстань)
        if як == "за координатою":
            попередження.append(
                "номери не збіглись, звели за координатою (%.0f м). "
                "Так робити можна тільки після перегляду очима" % відстань)
        пари.append(dict(рядок=л["рядок_у_файлі"], лабораторія=л.get("номер_лабораторії"),
                         наша=збіг["номер"], зони=збіг.get("зони"),
                         як=як, відстань_м=None if відстань is None else round(відстань, 1),
                         попередження=попередження))

    for ключ, рядки in вжиті_номери.items():
        if len(рядки) > 1:
            дублікати.append(dict(номер=ключ, рядки=рядки))

    наші_без_пари = [dict(номер=н["номер"], зони=н.get("зони"))
                     for н in наші if not н["зайнята"]]

    із_попередженням = [п for п in пари if п["попередження"]]
    чисто = not (лаб_без_пари or наші_без_пари or дублікати or із_попередженням)

    if чисто:
        підсумок = "Нумерація зійшлась: %d із %d" % (len(пари), len(лабораторні))
    else:
        шматки = ["зійшлось %d із %d" % (len(пари), len(лабораторні))]
        if із_попередженням:
            шматки.append("%d пар під питанням" % len(із_попередженням))
        if лаб_без_пари:
            шматки.append("%d рядків лабораторії без нашої точки" % len(лаб_без_пари))
        if наші_без_пари:
            шматки.append("%d наших точок без результату" % len(наші_без_пари))
        if дублікати:
            шматки.append("%d номерів двічі" % len(дублікати))
        підсумок = ("Нумерація не зійшлась начисто: " + "; ".join(шматки)
                    + ". Дивитись рядки нижче, перш ніж рахувати")

    return dict(
        чисто=чисто,
        пари=пари,
        лаб_без_пари=лаб_без_пари,
        наші_без_пари=наші_без_пари,
        дублікати=дублікати,
        підсумок=підсумок,
    )
