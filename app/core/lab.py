def розібрати_значення(сирець, ключ):
    """Клітинка протоколу → комірка з типом. Ніколи не повертає голе число."""
    п = ПОКАЗНИКИ.get(ключ, {})
    т = (сирець or "").strip()
    низ = т.lower()
    комірка = dict(сирець=сирець, значення=None, вид=None, напрям=None,
                   межа=None, примітки=[])

    if низ in СЛОВА_ПОРОЖНЕЧІ:
        комірка["вид"] = "немає_виміру"
        return комірка
    if низ in СЛОВА_СЛІДІВ:
        комірка.update(вид="цензуровано", напрям="<")
        комірка["примітки"].append("«сліди» — межу лабораторія не назвала")
        return комірка

    збіг = re.match(r"^\s*([<>≤≥])\s*([0-9]+(?:[.,][0-9]+)?)", т)
    if збіг:
        знак = {"≤": "<", "≥": ">"}.get(збіг.group(1), збіг.group(1))
        комірка.update(вид="цензуровано", напрям=знак,
                       межа=float(збіг.group(2).replace(",", ".")))
        комірка["примітки"].append(
            "нижче межі визначення" if знак == "<" else "вище верхньої межі")
        return комірка

    try:
        значення = float(т.replace("\xa0", "").replace(" ", "").replace(",", "."))
    except ValueError:
        комірка["вид"] = "нечитане"
        комірка["примітки"].append("не число і не відома позначка")
        return комірка

    if значення == 0.0:
        нуль = п.get("нуль_це", "справжній")
        if нуль == "немає_виміру":
            комірка["вид"] = "немає_виміру"
            комірка["примітки"].append(
                "нуль тут неможливий — лабораторія так позначає невиміряне")
            return комірка
        if нуль == "округлення":
            комірка.update(вид="цензуровано", напрям="<", межа=0.5, значення=0.0)
            комірка["примітки"].append(
                "колонка друкується цілими відсотками: нуль означає «менше 0,5 %»")
            return комірка
        if нуль == "підозра":
            комірка.update(вид="число", значення=0.0)
            комірка["примітки"].append(
                "нуль на живому ґрунті не буває — швидше за все не виміряно")
            return комірка

    комірка.update(вид="число", значення=значення)
    return комірка


def майже_нуль(комірка):
    """Чи означає клітинка «майже нічого».

    Водень 0 % ЄКО в цьому протоколі — це не «не виміряно», а «менше
    піввідсотка»: колонка друкується цілими. Для питання «чи карбонатний
    ґрунт» це найсильніший знак, який тут узагалі є, і втратити його через
    те, що ми акуратно назвали нуль цензурованим, було б безглуздо."""
    if not комірка:
        return False
    if комірка.get("вид") == "число":
        return комірка.get("значення") == 0.0
    if комірка.get("вид") == "цензуровано" and комірка.get("напрям") == "<":
        return True
    return False


def число(комірка):
    """Значення, з яким можна рахувати, або None. Цензуроване — не можна."""
    if комірка and комірка.get("вид") == "число":
        return комірка.get("значення")
    return None


# ═══════════════════════════════════════════════════════════════════════
# ФОСФОР: BRAY ЧИ OLSEN
# ═══════════════════════════════════════════════════════════════════════
# Витяжка Bray кисла. На ґрунті з вільним карбонатом карбонат її нейтралізує,
# і фосфор просто не виходить у розчин — цифра виходить заниженою, і заниження
# тим більше, чим більше карбонату. Це не похибка виміру: метод там не працює.
# Olsen робиться лужною витяжкою і на карбонаті працює.
#
# Пороги по pH водної витяжки. Це угода, не стандарт: у літературі межу
# кладуть по вільному карбонату, а не по pH, але карбонат у протоколі не
# міряють. Тому статус WORKING, і сіра смуга між порогами лишається сірою.
pH_BRAY_ЩЕ_МОЖНА = 7.2
pH_ТІЛЬКИ_OLSEN = 7.4
pH_ФОСФОР_СТАТУС = "WORKING"

# Другий підозріливий знак: водень на комплексі зник, а кальцій сидить високо.
# Такий ґрунт буває карбонатним і при pH нижче порога.
КАРБОНАТ_Ca_НАС = 85.0


# Порядок переваги на кислому й нейтральному ґрунті та на карбонатному.
# Береться перший метод зі списку, який у протоколі справді є.
ПЕРЕВАГА_КИСЛИЙ = ("P_Bray", "P_M3", "P_Bray2", "P_Olsen")
ПЕРЕВАГА_СІРА = ("P_Olsen", "P_Bray", "P_M3", "P_Bray2")
ПЕРЕВАГА_КАРБОНАТ = ("P_Olsen", "P_Bray", "P_M3", "P_Bray2")

# Кислі витяжки. На вільному карбонаті вони гаснуть і занижують.
КИСЛІ_ВИТЯЖКИ = ("P_Bray", "P_Bray2", "P_M3")

МЕТОДИ_ФОСФОРУ = ("P_Bray", "P_Bray2", "P_Olsen", "P_M3")


def фосфор(точка):
    """Який фосфор заносимо в цій точці і чи можна ним рахувати.

    Рішення Власника: **заносимо те, що лабораторія зробила.** Є Bray — Bray,
    є Olsen — Olsen, є Mehlich-3 — Mehlich-3. Число не викидається ніколи.

    Окремо від цього стоїть придатність. Кислі витяжки (Bray і Mehlich-3) на
    ґрунті з вільним карбонатом гаснуть і занижують — там їхнє число лишається
    у звіті як вимір, але в розрахунок не заходить. Рішення про придатність
    приймає pH, а не наявність цифри."""
    ph = число(точка.get("pH_H2O"))
    по_воді = ph is not None
    if ph is None:
        ph = число(точка.get("pH_KCl"))
    ca_нас = число(точка.get("Ca_нас"))
    водню_нема = майже_нуль(точка.get("H_нас"))

    наявні = {к: число(точка.get(к)) for к in МЕТОДИ_ФОСФОРУ
              if число(точка.get(к)) is not None}

    вихід = dict(метод=None, ключ=None, значення=None, вирок="немає",
                 брати_в_розрахунок=False, чому="", прапорці=[],
                 усі=[dict(метод=ПОКАЗНИКИ[к]["метод"], значення=в)
                      for к, в in наявні.items()])

    if not наявні:
        вихід["чому"] = "фосфору в протоколі немає"
        return вихід

    if ph is None:
        # Число заносимо все одно — просто не знаємо, чи ним можна рахувати.
        к = next(к for к in ПЕРЕВАГА_КИСЛИЙ if к in наявні)
        вихід.update(метод=ПОКАЗНИКИ[к]["метод"], ключ=к, значення=наявні[к],
                     вирок="під питанням", брати_в_розрахунок=False,
                     чому="pH ґрунту не виміряний — сказати, чи придатна ця "
                          "витяжка, нема на чому")
        return вихід

    if not по_воді:
        вихід["прапорці"].append(
            "pH водної витяжки немає, вирішуємо за сольовим — а він нижчий "
            "за водний приблизно на 0,5 од., тобто карбонат можна проґавити")

    карбонатний = ph >= pH_ТІЛЬКИ_OLSEN
    сіра_смуга = pH_BRAY_ЩЕ_МОЖНА < ph < pH_ТІЛЬКИ_OLSEN
    порядок = (ПЕРЕВАГА_КАРБОНАТ if карбонатний
               else ПЕРЕВАГА_СІРА if сіра_смуга else ПЕРЕВАГА_КИСЛИЙ)
    к = next(кл for кл in порядок if кл in наявні)
    метод = ПОКАЗНИКИ[к]["метод"]
    вихід.update(метод=метод, ключ=к, значення=наявні[к])

    кисла = к in КИСЛІ_ВИТЯЖКИ
    if карбонатний and кисла:
        вихід.update(вирок="непридатний метод", брати_в_розрахунок=False,
                     чому="pH %.1f — ґрунт карбонатний, а %s робиться кислою "
                          "витяжкою: карбонат її гасить і число виходить "
                          "заниженим. Заносимо як вимір, у розрахунок не беремо"
                          % (ph, метод))
        вихід["прапорці"].append(
            "щоб мати придатний фосфор на цій точці, треба замовити Olsen")
    elif сіра_смуга and кисла:
        вихід.update(вирок="під питанням", брати_в_розрахунок=False,
                     чому="pH %.1f — сіра смуга між %.1f і %.1f. %s ще "
                          "читається, але вже може занижувати"
                          % (ph, pH_BRAY_ЩЕ_МОЖНА, pH_ТІЛЬКИ_OLSEN, метод))
    else:
        вихід.update(вирок="чинний", брати_в_розрахунок=True,
                     чому="pH %.1f — %s тут працює" % (ph, метод))
        if кисла and водню_нема and ca_нас is not None and ca_нас >= КАРБОНАТ_Ca_НАС:
            вихід.update(
                вирок="під питанням", брати_в_розрахунок=False,
                чому="pH %.1f нижче порога, і сам по собі %s тут працював би. "
                     "Але водню на комплексі нема, а кальцію %.0f %% — так "
                     "виглядає карбонатний ґрунт, і тоді кисла витяжка занижує"
                     % (ph, метод, ca_нас))
            вихід["прапорці"].append(
                "варто замовити Olsen на цю точку — по pH вона в нормі, "
                "а по комплексу схожа на карбонатну")

    решта = [ПОКАЗНИКИ[кл]["метод"] for кл in наявні if кл != к]
    if решта:
        вихід["прапорці"].append(
            "у протоколі є ще " + ", ".join(решта) +
            ". Не зводимо й не порівнюємо: це інші шкали, а не інші виміри "
            "тієї самої величини")
    return вихід


