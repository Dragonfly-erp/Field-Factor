КОДУВАННЯ = ("utf-8-sig", "cp1251", "utf-8")


def _прочитати_текст(шлях):
    останнє = None
    for код in КОДУВАННЯ:
        try:
            with io.open(шлях, encoding=код) as ф:
                return ф.read(), код
        except UnicodeDecodeError as помилка:
            останнє = помилка
    raise ValueError("Не вдалось прочитати файл у жодному з кодувань: %s" % останнє)


def _роздільник(перший_рядок):
    return max((";", ",", "\t"), key=перший_рядок.count)


# ═══════════════════════════════════════════════════════════════════════
# РОЗКЛАДКА КОЛОНОК: що з чим звели
# ═══════════════════════════════════════════════════════════════════════
# Автовпізнавання добре працює на знайомій лабораторії й безпорадне на новій.
# Тому розкладка — не внутрішня дрібниця, а окрема річ: її видно на екрані,
# її можна поправити руками й зберегти шаблоном на наступний раз.
#
# Роль колонки:
#   "показник"  — вимір, іде в розрахунок під своїм ключем
#   "номер" / "широта" / "довгота" / "поле" / "глибина" — службова
#   "не брати"  — свідомо пропущена (чужі рекомендації, співвідношення)
#   "невідома"  — програма не знає, що це. Не читається, доки не скажуть

СЛУЖБОВІ_РОЛІ = ("номер", "широта", "довгота", "поле", "глибина")
РОЛІ = ("показник",) + СЛУЖБОВІ_РОЛІ + ("не брати", "невідома")


def розкласти_колонки(заголовки, шаблон=None):
    """Заголовки файлу → роль кожної колонки.

    Шаблон головніший за автовпізнавання: людина вже сказала, що це за
    колонка, і переучувати її програмі не належить."""
    ручні = (шаблон or {}).get("колонки") or {}
    розкладка = []
    for і, сирий in enumerate(заголовки):
        простий = _спростити(сирий)
        запис = dict(індекс=і, заголовок=сирий, простий=простий,
                     роль="невідома", ключ=None, звідки="автоматично")

        вибір = ручні.get(сирий, ручні.get(простий))
        if вибір is not None:
            запис["звідки"] = "шаблон"
            if вибір in СЛУЖБОВІ_РОЛІ:
                запис.update(роль=вибір)
            elif вибір in ПОКАЗНИКИ:
                запис.update(роль="показник", ключ=вибір)
            else:
                запис.update(роль="не брати")
            розкладка.append(запис)
            continue

        if not простий:
            запис.update(роль="не брати")
            розкладка.append(запис)
            continue

        службова = None
        for роль, варіанти in (("номер", КОЛОНКИ_НОМЕРА),
                               ("широта", КОЛОНКА_ШИРОТИ),
                               ("довгота", КОЛОНКА_ДОВГОТИ),
                               ("поле", КОЛОНКА_ПОЛЯ),
                               ("глибина", КОЛОНКА_ГЛИБИНИ)):
            if any(_службова(простий, в) for в in варіанти):
                службова = роль
                break
        if службова:
            запис.update(роль=службова)
            розкладка.append(запис)
            continue

        if СПІВВІДНОШЕННЯ.match(сирий) or any(х in сирий.lower() for х in ПРОПУСКАЄМО):
            запис.update(роль="не брати")
            розкладка.append(запис)
            continue

        ключ = показник_колонки(простий)
        if ключ:
            запис.update(роль="показник", ключ=ключ)
        розкладка.append(запис)
    return розкладка


def _перша(розкладка, роль):
    """Індекс першої колонки цієї службової ролі."""
    for з in розкладка:
        if з["роль"] == роль:
            return з["індекс"]
    return None


def _зразки(таблиця, розкладка, скільки=3):
    """Перші кілька значень кожної колонки. Без них людина не може вирішити,
    що це за колонка: назва буває нечитабельна, а числа говорять самі."""
    зразки = {}
    for з in розкладка:
        і = з["індекс"]
        значення = [(р[і].strip() if і < len(р) else "")
                    for р in таблиця[1:1 + скільки]]
        зразки[str(і)] = [в for в in значення if в]
    return зразки


def заголовки_файлу(шлях, роздільник=None):
    """Тільки перший рядок. Потрібен, щоб підібрати шаблон або зберегти його,
    не розбираючи весь файл заново."""
    текст, _ = _прочитати_текст(шлях)
    рядки = текст.splitlines()
    if not рядки:
        return []
    роздільник = роздільник or _роздільник(рядки[0])
    for р in csv.reader(рядки[:1], delimiter=роздільник):
        return [(к or "").strip() for к in р]
    return []


def прочитати_протокол(шлях, глибина_см=None, шаблон=None):
    """Файл лабораторії → точки з комірками, методами й застереженнями.

    глибина_см — з НАШОГО завдання на відбір. Якщо у файлі є своя глибина
    і вона інша, це не привід її взяти: це привід сказати про розбіжність.
    шаблон — збережена розкладка колонок для цієї лабораторії."""
    глибина_см = norms.ГЛИБИНА_СМ if глибина_см is None else глибина_см
    текст, кодування = _прочитати_текст(шлях)
    рядки = текст.splitlines()
    if not рядки:
        raise ValueError("Файл порожній")
    роздільник = (шаблон or {}).get("роздільник") or _роздільник(рядки[0])
    читач = csv.reader(рядки, delimiter=роздільник)
    таблиця = [р for р in читач if any((к or "").strip() for к in р)]
    if len(таблиця) < 2:
        raise ValueError("У файлі немає жодного рядка з даними")

    заголовки = [(к or "").strip() for к in таблиця[0]]
    розкладка = розкласти_колонки(заголовки, шаблон)

    показник_у_колонці = {з["індекс"]: з["ключ"] for з in розкладка
                          if з["роль"] == "показник"}
    невпізнані = [з["заголовок"] for з in розкладка if з["роль"] == "невідома"]
    пропущені = [з["заголовок"] for з in розкладка if з["роль"] == "не брати"]

    і_номер = _перша(розкладка, "номер")
    і_широта = _перша(розкладка, "широта")
    і_довгота = _перша(розкладка, "довгота")
    і_поле = _перша(розкладка, "поле")
    і_глибина = _перша(розкладка, "глибина")

    # Один показник у двох колонках — не дрібниця: друга мовчки перекриє першу,
    # і ніхто не дізнається, яка саме цифра пішла в норму.
    подвійні = {}
    for з in розкладка:
        if з["роль"] == "показник":
            подвійні.setdefault(з["ключ"], []).append(з["заголовок"])
    подвійні = {к: в for к, в in подвійні.items() if len(в) > 1}

    точки = []
    for номер_рядка, рядок in enumerate(таблиця[1:], start=2):
        def бр(і):
            return рядок[і].strip() if і is not None and і < len(рядок) else ""

        точка = dict(
            рядок_у_файлі=номер_рядка,
            номер_лабораторії=бр(і_номер) or None,
            поле=бр(і_поле) or None,
            широта=None, довгота=None,
            глибина_см=глибина_см,
            глибина_джерело="наше завдання на відбір",
            примітки=[],
        )
        for назва, і in (("широта", і_широта), ("довгота", і_довгота)):
            точка[назва] = число(розібрати_значення(бр(і), назва))
        for і, ключ in показник_у_колонці.items():
            точка[ключ] = розібрати_значення(бр(і), ключ)

        своя_глибина = бр(і_глибина)
        if своя_глибина:
            к = число(розібрати_значення(своя_глибина, "глибина"))
            if к is not None and abs(к - глибина_см) > 0.5:
                точка["примітки"].append(
                    "у протоколі стоїть глибина %g см, у нашому завданні %g см. "
                    "Беремо наше: лабораторія знає глибину тільки з наших слів"
                    % (к, глибина_см))
        точки.append(точка)

    for т in точки:
        т["фосфор"] = фосфор(т)
        т["перерахунки"] = _перерахувати(т)

    застереження = _застереження_поля(точки, показник_у_колонці)
    if подвійні:
        застереження.insert(0, dict(
            вага="стоп",
            що="один показник узято з двох колонок: " + "; ".join(
                "%s ← %s" % (ПОКАЗНИКИ[к]["назва"], " і ".join(в))
                for к, в in sorted(подвійні.items())),
            чому="друга колонка мовчки перекриває першу — незрозуміло, яке "
                 "число піде в норму. Одну з них треба зняти в розкладці"))
    if невпізнані:
        застереження.append(dict(
            вага="увага",
            що="колонок, яких програма не знає: %d" % len(невпізнані),
            чому="вони не прочитані. Якщо серед них є вимір — вкажіть його "
                 "в розкладці й збережіть шаблон, щоб наступного разу від цієї "
                 "лабораторії все читалось само"))

    return dict(
        файл=os.path.basename(шлях),
        шлях=шлях,
        кодування=кодування,
        роздільник=роздільник,
        профіль=ПРОФІЛЬ,
        шаблон=(шаблон or {}).get("назва"),
        точок=len(точки),
        точки=точки,
        колонок_у_файлі=len(заголовки),
        розкладка=розкладка,
        зразки=_зразки(таблиця, розкладка),
        впізнано=sorted(set(показник_у_колонці.values())),
        невпізнані=невпізнані,
        пропущені=пропущені,
        глибина_см=глибина_см,
        застереження=застереження,
    )


