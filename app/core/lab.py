def _спростити(текст):
    """Заголовок → форма для порівняння. Вміст дужок ЛИШАЄТЬСЯ: саме там
    лабораторія пише метод — «Фосфор (Bray 1)». Викинути дужки означало б
    втратити єдине місце, де метод названий."""
    т = (текст or "").lower().replace("ʼ", "").replace("'", "").replace("’", "")
    т = re.sub(r"[^0-9a-zа-яіїєґ]+", " ", т)
    return " ".join(т.split())


