КОДУВАННЯ = ("utf-8-sig", "cp1251", "utf-8")


def _прочитати_текст(шлях):
    останнє = None
    for код in КОДУВАННЯ:
        try:
            with io.open(шлях, encoding=код) as ф:
                return ф.read(), код
        except UnicodeDecodeError as помилка:
            останнє = помилка
    raise ValueError("Не вдалось прочитати файл у жодному з кодувань: %s" % останнє)


def _роздільник(перший_рядок):
    return max((";", ",", "\t"), key=перший_рядок.count)


def прочитати_протокол(шлях, глибина_см=None):
    """Файл лабораторії → точки з комірками, методами й застереженнями.

    глибина_см — з НАШОГО завдання на відбір. Якщо у файлі є своя глибина
    і вона інша, це не привід її взяти: це привід сказати про розбіжність."""
    глибина_см = norms.ГЛИБИНА_СМ if глибина_см is None else глибина_см
    текст, кодування = _прочитати_текст(шлях)
    рядки = текст.splitlines()
    if not рядки:
        raise ValueError("Файл порожній")
    читач = csv.reader(рядки, delimiter=_роздільник(рядки[0]))
    таблиця = [р for р in читач if any((к or "").strip() for к in р)]
    if len(таблиця) < 2:
        raise ValueError("У файлі немає жодного рядка з даними")

    заголовки = [(к or "").strip() for к in таблиця[0]]
    прості = [_спростити(к) for к in заголовки]

    # --- розкладка колонок
    показник_у_колонці, невпізнані, пропущені = {}, [], []
    for і, (сирий, простий) in enumerate(zip(заголовки, прості)):
        if not простий:
            continue
        службові = (КОЛОНКИ_НОМЕРА + КОЛОНКА_ШИРОТИ + КОЛОНКА_ДОВГОТИ
                    + КОЛОНКА_ПОЛЯ + КОЛОНКА_ГЛИБИНИ)
        if any(_службова(простий, в) for в in службові):
            continue
        низ = сирий.lower()
        if СПІВВІДНОШЕННЯ.match(сирий) or any(х in низ for х in ПРОПУСКАЄМО):
            пропущені.append(сирий)
            continue
        ключ = показник_колонки(простий)
        if ключ:
            показник_у_колонці[і] = ключ
            continue
        невпізнані.append(сирий)

    def індекс(варіанти):
        """Перша колонка, чий заголовок ПОЧИНАЄТЬСЯ з одного з варіантів.
        Порядок варіантів — це порядок довіри.

        Саме початок, а не входження: «y» як позначка широти знайшлось би
        всередині слова «bray» і забрало б колонку фосфору."""
        for в in варіанти:
            for і, простий in enumerate(прості):
                if _службова(простий, в):
                    return і
        return None

    і_номер = індекс(КОЛОНКИ_НОМЕРА)
    і_широта, і_довгота = індекс(КОЛОНКА_ШИРОТИ), індекс(КОЛОНКА_ДОВГОТИ)
    і_поле, і_глибина = індекс(КОЛОНКА_ПОЛЯ), індекс(КОЛОНКА_ГЛИБИНИ)

    # --- точки
    точки = []
    for номер_рядка, рядок in enumerate(таблиця[1:], start=2):
        бр = lambda і: (рядок[і].strip() if і is not None and і < len(рядок) else "")  # noqa: E731
        точка = dict(
            рядок_у_файлі=номер_рядка,
            номер_лабораторії=бр(і_номер) or None,
            поле=бр(і_поле) or None,
            широта=None, довгота=None,
            глибина_см=глибина_см,
            глибина_джерело="наше завдання на відбір",
            примітки=[],
        )
        for назва, і in (("широта", і_широта), ("довгота", і_довгота)):
            к = розібрати_значення(бр(і), назва)
            точка[назва] = число(к)
        for і, ключ in показник_у_колонці.items():
            точка[ключ] = розібрати_значення(бр(і), ключ)

        своя_глибина = бр(і_глибина)
        if своя_глибина:
            к = число(розібрати_значення(своя_глибина, "глибина"))
            if к is not None and abs(к - глибина_см) > 0.5:
                точка["примітки"].append(
                    "у протоколі стоїть глибина %g см, у нашому завданні %g см. "
                    "Беремо наше: лабораторія знає глибину тільки з наших слів"
                    % (к, глибина_см))
        точки.append(точка)

    # --- фосфор і насиченості по кожній точці
    for т in точки:
        т["фосфор"] = чинний_фосфор(т)
        т["перерахунки"] = _перерахувати(т)

    return dict(
        файл=os.path.basename(шлях),
        кодування=кодування,
        профіль=ПРОФІЛЬ,
        точок=len(точки),
        точки=точки,
        колонок_у_файлі=len(заголовки),
        впізнано=sorted({к for к in показник_у_колонці.values()}),
        невпізнані=невпізнані,
        пропущені=пропущені,
        глибина_см=глибина_см,
        застереження=_застереження_поля(точки, показник_у_колонці),
    )


