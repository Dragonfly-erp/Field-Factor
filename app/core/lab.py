# ЗАСТЕРЕЖЕННЯ НА ВСЕ ПОЛЕ
# ═══════════════════════════════════════════════════════════════════════


def _застереження_поля(точки, показник_у_колонці):
    """Те, що видно тільки коли дивишся на всі точки разом."""
    з = []
    ключі = set(показник_у_колонці.values())

    методи = {т["фосфор"]["метод"] for т in точки if т["фосфор"]["метод"]}
    якщо_немає = [т for т in точки if т["фосфор"]["вирок"] == "немає"]
    if len(методи) > 1:
        з.append(dict(
            вага="стоп",
            що="поле розрізане на дві шкали фосфору: " + " і ".join(sorted(методи)),
            чому="Bray і Olsen — різні шкали, а не два виміри однієї величини. "
                 "Зводити їх в одну карту, інтерполювати між ними або "
                 "порівнювати числа заборонено"))
    if якщо_немає:
        з.append(dict(
            вага="стоп",
            що="фосфор не визначений придатним методом у %d точках із %d"
               % (len(якщо_немає), len(точки)),
            чому="на карбонатному ґрунті Bray занижує, а Olsen лабораторія не "
                 "робила. Ці точки йдуть у звіт як «потрібне дообстеження», "
                 "не як нуль"))

    без_методу = [к for к in ключі
                  if ПОКАЗНИКИ.get(к, {}).get("метод_статус") == "НЕВІДОМО"]
    if без_методу:
        з.append(dict(
            вага="увага",
            що="метод невідомий: " + ", ".join(
                sorted(ПОКАЗНИКИ[к]["назва"] for к in без_методу)),
            чому="число без методу не інтерпретується. Ці показники зняті з "
                 "розрахунку й лишаються у звіті тільки як довідка"))

    цензурованих = sum(
        1 for т in точки for к in ключі
        if isinstance(т.get(к), dict) and т[к].get("вид") == "цензуровано")
    if цензурованих:
        з.append(dict(
            вага="увага",
            що="цензурованих значень: %d" % цензурованих,
            чому="«<5», «сліди» і нулі округлення — це не числа. У розрахунок "
                 "не заходять, у звіті показуються як є"))

    підозра = [(т["номер_лабораторії"] or т["рядок_у_файлі"], ПОКАЗНИКИ[к]["назва"])
               for т in точки for к in ключі
               if isinstance(т.get(к), dict) and т[к].get("вид") == "число"
               and т[к].get("значення") == 0.0
               and ПОКАЗНИКИ.get(к, {}).get("нуль_це") == "підозра"]
    if підозра:
        з.append(dict(
            вага="увага",
            що="нулі там, де нуля не буває: " + ", ".join(
                "%s · %s" % (н, п) for н, п in підозра[:6]),
            чому="швидше за все показник не вимірювався, а не дорівнює нулю"))

    великі = [т for т in точки
              if т["перерахунки"].get("розбіжність_V") is not None
              and abs(т["перерахунки"]["розбіжність_V"]) >= 1.0]
    if великі:
        з.append(dict(
            вага="увага",
            що="насиченість основами розходиться з надрукованою в %d точках "
               "(до %.1f п.п.)" % (
                   len(великі),
                   max(abs(т["перерахунки"]["розбіжність_V"]) for т in великі)),
            чому="протокол друкує водень цілими відсотками. Один відсоток "
                 "тут — це сотні кілограмів вапна на гектар, тому в розрахунок "
                 "іде наше число з буферного pH, а не округлене"))

    # Дублікат номера — властивість самого файлу. Її видно без наших точок,
    # тому вона не має чекати на план відбору.
    номери = {}
    for т in точки:
        к = _ключ_номера(т.get("номер_лабораторії"))
        if к is not None:
            номери.setdefault(к, []).append(т["рядок_у_файлі"])
    подвійні = {к: р for к, р in номери.items() if len(р) > 1}
    if подвійні:
        з.append(dict(
            вага="стоп",
            що="один номер зразка стоїть двічі: " + ", ".join(
                "%s (рядки %s)" % (к, ", ".join(map(str, р)))
                for к, р in sorted(подвійні.items())),
            чому="поки не ясно, який рядок якій точці належить, прив'язати "
                 "результати до карти не можна"))

    без_буферного = [т for т in точки if число(т.get("pH_буф")) is None]
    if без_буферного:
        з.append(dict(
            вага="стоп",
            що="буферного pH немає в %d точках із %d" % (len(без_буферного), len(точки)),
            чому="без буферного pH немає ні водню на комплексі, ні насиченості "
                 "основами. Норма вапна по цих точках не виводиться — "
                 "їх треба дозамовити, а не добудувати"))

    немає_щільності = [т for т in точки if число(т.get("щільність")) is None]
    if немає_щільності:
        з.append(dict(
            вага="увага",
            що="щільності ґрунту немає в %d точках" % len(немає_щільності),
            чому="без щільності маса шару не рахується, а без неї немає ні "
                 "кілограмів на гектар, ні норми вапна"))
    return з


