# методи. Автовпізнавання знає ХАНЗЕ, бо ми тримали в руках її протокол.
# Для будь-якої іншої лабораторії людина один раз показує, де що лежить, —
# і це запам'ятовується шаблоном. Далі той самий файл читається сам.
#
# Шаблон прив'язується не до назви файлу (вона щоразу інша), а до НАБОРУ
# ЗАГОЛОВКІВ: саме він у лабораторії сталий.

ТЕКА_ШАБЛОНІВ = "шаблони_лабораторій"


def _тека_шаблонів(база):
    тека = os.path.join(база, ТЕКА_ШАБЛОНІВ)
    os.makedirs(тека, exist_ok=True)
    return тека


def _відбиток(заголовки):
    """Підпис набору колонок. Порядок і регістр не рахуються: лабораторія
    може переставити колонки місцями, а файл лишиться тим самим."""
    прості = sorted({_спростити(з) for з in заголовки if _спростити(з)})
    return hashlib.sha256("\n".join(прості).encode("utf-8")).hexdigest()[:16]


def _імʼя_файлу(назва):
    чисте = re.sub(r"[^0-9A-Za-zА-Яа-яІіЇїЄєҐґ _-]+", "", назва or "").strip()
    return (чисте or "шаблон") + ".json"


def шаблони(база):
    """Усі збережені шаблони. Биті файли не валять список — вони в ньому
    видно як биті."""
    тека = _тека_шаблонів(база)
    зібрані = []
    for імʼя in sorted(os.listdir(тека)):
        if not імʼя.lower().endswith(".json"):
            continue
        шлях = os.path.join(тека, імʼя)
        try:
            with io.open(шлях, encoding="utf-8") as ф:
                ш = json.load(ф)
            ш["файл"] = імʼя
            зібрані.append(ш)
        except Exception as помилка:
            зібрані.append(dict(назва=імʼя, файл=імʼя, битий=str(помилка),
                                колонки={}, відбиток=None))
    return зібрані


def підібрати_шаблон(база, заголовки):
    """Шаблон із таким самим набором колонок, якщо він уже є."""
    відбиток = _відбиток(заголовки)
    for ш in шаблони(база):
        if ш.get("відбиток") == відбиток:
            return ш
    return None


def зберегти_шаблон(база, назва, заголовки, колонки, роздільник=None,
                    лабораторія=None):
    """Записати розкладку як шаблон.

    колонки — {заголовок: роль або ключ показника}. Зберігаємо і сирий
    заголовок, і спрощений: сирий читабельний для людини, спрощений витримує
    зміну регістру й розділових знаків."""
    назва = (назва or "").strip()
    if not назва:
        raise ValueError("Шаблон без назви не зберігається")
    очищені = {}
    for заголовок, роль in (колонки or {}).items():
        if роль in ("невідома", None, ""):
            continue
        очищені[заголовок] = роль
        простий = _спростити(заголовок)
        if простий:
            очищені[простий] = роль
    ш = dict(назва=назва,
             лабораторія=лабораторія or "",
             роздільник=роздільник,
             відбиток=_відбиток(заголовки),
             заголовки=list(заголовки),
             колонки=очищені)
    шлях = os.path.join(_тека_шаблонів(база), _імʼя_файлу(назва))
    with io.open(шлях, "w", encoding="utf-8") as ф:
        json.dump(ш, ф, ensure_ascii=False, indent=1)
    ш["файл"] = os.path.basename(шлях)
    return ш


def видалити_шаблон(база, файл):
    шлях = os.path.join(_тека_шаблонів(база), os.path.basename(файл or ""))
    if os.path.isfile(шлях):
        os.remove(шлях)
        return True
    return False


def довідник_ролей():
    """Те, з чого людина обирає в розкладці. Разом із методом: у розкладці
    видно не тільки «калій», а й яким саме способом його виймали."""
    показники = [dict(ключ=к, назва=п["назва"], одиниця=п["одиниця"],
                      метод=п.get("метод"), група=п["група"])
                 for к, п in ПОКАЗНИКИ.items()]
    показники.sort(key=lambda п: (п["група"], п["назва"]))
    return dict(
        показники=показники,
        службові=[dict(ключ="номер", назва="Номер зразка в лабораторії"),
                  dict(ключ="широта", назва="Широта"),
                  dict(ключ="довгота", назва="Довгота"),
                  dict(ключ="поле", назва="Назва або номер поля"),
                  dict(ключ="глибина", назва="Глибина відбору (тільки звірка)")],
        не_брати=dict(ключ="не брати", назва="Не брати"),
    )
