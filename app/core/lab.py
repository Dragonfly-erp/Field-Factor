# «<5» — це не 5 і не нуль. Це «менше за поріг, яким лабораторія бачить».
# Підставити нуль означає збрехати вниз, підставити 5 — збрехати вгору.
# Тому воно лишається окремим типом і в арифметику не заходить без рішення.

СЛОВА_ПОРОЖНЕЧІ = {"", "-", "—", "–", "н/в", "нв", "не виявлено", "нд", "n/d",
                   "na", "n/a", "немає", "не визначено"}
СЛОВА_СЛІДІВ = {"сліди", "слiди", "traces", "trace", "сл"}


def розібрати_значення(сирець, ключ):
    """Клітинка протоколу → комірка з типом. Ніколи не повертає голе число."""
    п = ПОКАЗНИКИ.get(ключ, {})
    т = (сирець or "").strip()
    низ = т.lower()
    комірка = dict(сирець=сирець, значення=None, вид=None, напрям=None,
                   межа=None, примітки=[])

    if низ in СЛОВА_ПОРОЖНЕЧІ:
        комірка["вид"] = "немає_виміру"
        return комірка
    if низ in СЛОВА_СЛІДІВ:
        комірка.update(вид="цензуровано", напрям="<")
        комірка["примітки"].append("«сліди» — межу лабораторія не назвала")
        return комірка

    збіг = re.match(r"^\s*([<>≤≥])\s*([0-9]+(?:[.,][0-9]+)?)", т)
    if збіг:
        знак = {"≤": "<", "≥": ">"}.get(збіг.group(1), збіг.group(1))
        комірка.update(вид="цензуровано", напрям=знак,
                       межа=float(збіг.group(2).replace(",", ".")))
        комірка["примітки"].append(
            "нижче межі визначення" if знак == "<" else "вище верхньої межі")
        return комірка

    try:
        значення = float(т.replace("\xa0", "").replace(" ", "").replace(",", "."))
    except ValueError:
        комірка["вид"] = "нечитане"
        комірка["примітки"].append("не число і не відома позначка")
        return комірка

    if значення == 0.0:
        нуль = п.get("нуль_це", "справжній")
        if нуль == "немає_виміру":
            комірка["вид"] = "немає_виміру"
            комірка["примітки"].append(
                "нуль тут неможливий — лабораторія так позначає невиміряне")
            return комірка
        if нуль == "округлення":
            комірка.update(вид="цензуровано", напрям="<", межа=0.5, значення=0.0)
            комірка["примітки"].append(
                "колонка друкується цілими відсотками: нуль означає «менше 0,5 %»")
            return комірка
        if нуль == "підозра":
            комірка.update(вид="число", значення=0.0)
            комірка["примітки"].append(
                "нуль на живому ґрунті не буває — швидше за все не виміряно")
            return комірка

    комірка.update(вид="число", значення=значення)
    return комірка


def майже_нуль(комірка):
    """Чи означає клітинка «майже нічого».

    Водень 0 % ЄКО в цьому протоколі — це не «не виміряно», а «менше
    піввідсотка»: колонка друкується цілими. Для питання «чи карбонатний
    ґрунт» це найсильніший знак, який тут узагалі є, і втратити його через
    те, що ми акуратно назвали нуль цензурованим, було б безглуздо."""
    if not комірка:
        return False
    if комірка.get("вид") == "число":
        return комірка.get("значення") == 0.0
    if комірка.get("вид") == "цензуровано" and комірка.get("напрям") == "<":
        return True
    return False


def число(комірка):
    """Значення, з яким можна рахувати, або None. Цензуроване — не можна."""
    if комірка and комірка.get("вид") == "число":
        return комірка.get("значення")
    return None


# ═══════════════════════════════════════════════════════════════════════
# ФОСФОР: BRAY ЧИ OLSEN
# ═══════════════════════════════════════════════════════════════════════
# Витяжка Bray кисла. На ґрунті з вільним карбонатом карбонат її нейтралізує,
# і фосфор просто не виходить у розчин — цифра виходить заниженою, і заниження
# тим більше, чим більше карбонату. Це не похибка виміру: метод там не працює.
# Olsen робиться лужною витяжкою і на карбонаті працює.
#
# Пороги по pH водної витяжки. Це угода, не стандарт: у літературі межу
# кладуть по вільному карбонату, а не по pH, але карбонат у протоколі не
# міряють. Тому статус WORKING, і сіра смуга між порогами лишається сірою.
pH_BRAY_ЩЕ_МОЖНА = 7.2
pH_ТІЛЬКИ_OLSEN = 7.4
pH_ФОСФОР_СТАТУС = "WORKING"

# Другий підозріливий знак: водень на комплексі зник, а кальцій сидить високо.
# Такий ґрунт буває карбонатним і при pH нижче порога.
КАРБОНАТ_Ca_НАС = 85.0


def чинний_фосфор(точка):
    """Який фосфор беремо в цій точці і чи беремо взагалі.

    Повертає: метод, значення, вирок, чому. Вирок «немає» означає, що фосфор
    у цій точці не визначений придатним методом — і це чесніше, ніж узяти
    цифру, яку зробила непридатна витяжка."""
    ph = число(точка.get("pH_H2O")) or число(точка.get("pH_KCl"))
    по_воді = число(точка.get("pH_H2O")) is not None
    bray = число(точка.get("P_Bray"))
    olsen = число(точка.get("P_Olsen"))
    ca_нас = число(точка.get("Ca_нас"))
    водню_нема = майже_нуль(точка.get("H_нас"))

    вихід = dict(метод=None, значення=None, вирок="немає", чому="", прапорці=[])

    if ph is None:
        вихід["чому"] = ("pH ґрунту не виміряний — обрати між Bray і Olsen "
                         "нема на чому. Фосфор не інтерпретується")
        return вихід
    if not по_воді:
        вихід["прапорці"].append(
            "pH водної витяжки немає, вирішуємо за сольовим — а він нижчий "
            "за водний приблизно на 0,5 од., тобто карбонат можна проґавити")

    карбонат_на_око = (водню_нема and ca_нас is not None
                       and ca_нас >= КАРБОНАТ_Ca_НАС)

    if ph >= pH_ТІЛЬКИ_OLSEN:
        if olsen is not None:
            вихід.update(метод="Olsen", значення=olsen, вирок="чинний",
                         чому="pH %.1f — ґрунт карбонатний, чинний тільки Olsen" % ph)
        else:
            вихід["чому"] = ("pH %.1f — ґрунт карбонатний. Bray тут занижує, "
                             "а Olsen лабораторія не робила. Фосфору по цій "
                             "точці у нас немає" % ph)
            if bray is not None:
                вихід["прапорці"].append(
                    "у протоколі стоїть Bray %.0f мг/кг — це число не беремо" % bray)
        return вихід

    if ph > pH_BRAY_ЩЕ_МОЖНА:
        if olsen is not None:
            вихід.update(метод="Olsen", значення=olsen, вирок="чинний",
                         чому="pH %.1f — сіра смуга, є Olsen, беремо його" % ph)
        elif bray is not None:
            вихід.update(метод="Bray-1", значення=bray, вирок="під питанням",
                         чому="pH %.1f — сіра смуга між %.1f і %.1f. Bray ще "
                              "читається, але вже може занижувати"
                              % (ph, pH_BRAY_ЩЕ_МОЖНА, pH_ТІЛЬКИ_OLSEN))
        else:
            вихід["чому"] = "pH %.1f, а фосфору в протоколі немає взагалі" % ph
        return вихід

    if bray is not None:
        вихід.update(метод="Bray-1", значення=bray, вирок="чинний",
                     чому="pH %.1f — ґрунт кислий або нейтральний, Bray чинний" % ph)
        if olsen is not None:
            вихід["прапорці"].append(
                "є ще Olsen %.0f мг/кг. Не порівнюємо: це друга шкала, "
                "а не другий вимір тієї самої величини" % olsen)
        if карбонат_на_око:
            вихід["вирок"] = "під питанням"
            вихід["прапорці"].append(
                "pH нижче порога, але водню на комплексі нема, а кальцію "
                "%.0f %% — так виглядає карбонатний ґрунт. Варто замовити Olsen"
                % ca_нас)
    elif olsen is not None:
        вихід.update(метод="Olsen", значення=olsen, вирок="чинний",
                     чому="pH %.1f, Bray не робили, є Olsen" % ph)
    else:
        вихід["чому"] = "фосфору в протоколі немає"
    return вихід


