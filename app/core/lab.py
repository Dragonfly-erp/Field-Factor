# ПЕРЕРАХУНКИ, ЯКІ РОБИМО САМІ
# ═══════════════════════════════════════════════════════════════════════
# Лабораторія друкує насиченості цілими відсотками. Ми маємо сирі мг/кг і
# буферний pH — з них те саме рахується без округлення. Надруковане не
# викидаємо: тримаємо поруч і показуємо розбіжність.


def _перерахувати(точка):
    """Насиченість основами й водень із сирих чисел, а не з цілих відсотків."""
    з = {е: число(точка.get(е)) for е in ("Ca", "Mg", "K", "Na")}
    ph_буф = число(точка.get("pH_буф"))
    єко_друк = число(точка.get("ЄКО"))
    вихід = dict(H_мекв=None, ЄКО_наша=None, V_наша=None,
                 V_друкована=None, розбіжність_V=None, чому=[])

    if ph_буф is None:
        вихід["чому"].append("буферного pH немає — водень порахувати нема з чого")
    elif ph_буф >= 7.0:
        вихід["H_мекв"] = 0.0
    else:
        вихід["H_мекв"] = norms.H_НА_ОДИНИЦЮ_pH * (7.0 - ph_буф)
        вихід["чому"].append(
            "водень із буферного pH за коефіцієнтом %.2f мекв на одиницю "
            "(WORKING: відновлено з чисел цієї ж лабораторії)"
            % norms.H_НА_ОДИНИЦЮ_pH)

    if all(в is not None for в in з.values()):
        основи = sum(з[е] / norms.ЕКВ[е] for е in з)
        if вихід["H_мекв"] is not None:
            вихід["ЄКО_наша"] = основи + вихід["H_мекв"]
            if вихід["ЄКО_наша"] > 0:
                вихід["V_наша"] = 100.0 * основи / вихід["ЄКО_наша"]
    else:
        вихід["чому"].append("не всі обмінні основи виміряні — ЄКО не рахуємо")

    h_друк = число(точка.get("H_нас"))
    if h_друк is not None:
        вихід["V_друкована"] = 100.0 - h_друк
    v_прямо = число(точка.get("V"))
    if v_прямо is not None:
        вихід["V_друкована"] = v_прямо

    if вихід["V_наша"] is not None and вихід["V_друкована"] is not None:
        вихід["розбіжність_V"] = вихід["V_наша"] - вихід["V_друкована"]

    if єко_друк is not None and вихід["ЄКО_наша"] is not None:
        вихід["ЄКО_розбіжність"] = вихід["ЄКО_наша"] - єко_друк
    return вихід


