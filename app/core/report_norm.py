def _крок_сітки(x):
    одні = np.unique(np.round(x, 2))
    if len(одні) > 2:
        кроки = np.diff(одні)
        крок = float(np.median(кроки[кроки > 0.5]))
        if np.isfinite(крок) and крок > 0.5:
            return крок
    return 10.0


def _індекси(точки):
    x = точки.geometry.x.to_numpy()
    y = точки.geometry.y.to_numpy()
    крок = _крок_сітки(x)
    с = np.clip(((x - x.min()) / крок).round().astype(int), 0, None)
    р = np.clip(((y.max() - y) / крок).round().astype(int), 0, None)
    return с, р, int(с.max()) + 1, int(р.max()) + 1


def _палітра_чисел(кольори):
    return np.array([render._у_числа(к) for к in кольори], dtype="uint8")


def _класи(значення, межі, кількість):
    return np.clip(np.digitize(значення, межі[1:-1]), 0, кількість - 1)


def _png(полотно):
    висота, ширина, _ = полотно.shape
    рядки = bytearray()
    for р in range(висота):
        рядки.append(0)
        рядки.extend(полотно[р].tobytes())

    def шматок(тип, дані):
        return (struct.pack(">I", len(дані)) + тип + дані
                + struct.pack(">I", zlib.crc32(тип + дані) & 0xFFFFFFFF))

    буфер = io.BytesIO()
    буфер.write(b"\x89PNG\r\n\x1a\n")
    буфер.write(шматок(b"IHDR", struct.pack(">IIBBBBB", ширина, висота, 8, 2, 0, 0, 0)))
    буфер.write(шматок(b"IDAT", zlib.compress(bytes(рядки), 9)))
    буфер.write(шматок(b"IEND", b""))
    буфер.seek(0)
    return буфер


def карта_плоска(точки, колонка, палітра="врожай", класів=КЛАСІВ, тло=(255, 255, 255)):
    """Звичайна карта згори. Повертає (буфер PNG, межі класів, кольори).

    Для врожайності беремо ЗГЛАДЖЕНУ поверхню, якщо вона є: середні по
    комірках — це сировина, і на екрані вони кришиво, а не поле.
    """
    if колонка == "YLD_KGHA" and "YLD_SM" in точки and точки["YLD_SM"].notna().any():
        колонка = "YLD_SM"
    значення = np.asarray(точки[колонка], dtype="float64")
    межі = np.array(render.класифікувати(значення, класів, "квантилі"))
    кольори = render.палітра(палітра, max(len(межі) - 1, 2))
    с, р, стовпців, рядків = _індекси(точки)

    полотно = np.zeros((рядків, стовпців, 3), dtype="uint8")
    полотно[:, :] = тло
    добрі = np.isfinite(значення)
    полотно[р[добрі], с[добрі]] = _палітра_чисел(кольори)[
        _класи(значення, межі, len(кольори))[добрі]]

    збільшення = max(1, int(round(ШИРИНА_КАРТИ / max(стовпців, 1))))
    if збільшення > 1:
        полотно = np.repeat(np.repeat(полотно, збільшення, axis=0), збільшення, axis=1)
    return _png(полотно), межі, кольори


def карта_до(сирі, як_у, колонка, множник=1.0):
    """Карта з файлу монітора, якою вона є до нашої роботи.

    Кладеться на ту саму сітку, що й нормалізована, — інакше поруч їх не
    порівняти. Жодної очистки: ні зупинок, ні розворотів, ні викидів. Саме
    в цьому й суть сторінки — видно, що прибрано і що добудовано.

    Класи рахуються по цій же карті, а не позичаються в нормалізованої:
    рівні в них різні, і порівнювати треба **малюнок**, а не колір.
    """
    крок = _крок_сітки(як_у.geometry.x.to_numpy())
    x0 = як_у.geometry.x.min()
    y1 = як_у.geometry.y.max()
    _, _, стовпців, рядків = _індекси(як_у)

    x = сирі.geometry.x.to_numpy()
    y = сирі.geometry.y.to_numpy()
    з = np.asarray(сирі[колонка], dtype="float64") * множник

    с = np.round((x - x0) / крок).astype(int)
    р = np.round((y1 - y) / крок).astype(int)
    у_межах = (с >= 0) & (с < стовпців) & (р >= 0) & (р < рядків) & np.isfinite(з)
    с, р, з = с[у_межах], р[у_межах], з[у_межах]

    сума = np.zeros((рядків, стовпців), dtype="float64")
    лік = np.zeros((рядків, стовпців), dtype="float64")
    np.add.at(сума, (р, с), з)
    np.add.at(лік, (р, с), 1.0)
    поле = np.where(лік > 0, сума / np.maximum(лік, 1), np.nan)

    значення = поле[np.isfinite(поле)]
    межі = np.array(render.класифікувати(значення, КЛАСІВ, "квантилі"))
    кольори = render.палітра("врожай", max(len(межі) - 1, 2))
    палітра = _палітра_чисел(кольори)

    полотно = np.full((рядків, стовпців, 3), 255, dtype="uint8")
    рр, сс = np.nonzero(np.isfinite(поле))
    полотно[рр, сс] = палітра[_класи(поле[рр, сс], межі, len(кольори))]

    збільшення = max(1, int(round(ШИРИНА_КАРТИ / max(стовпців, 1))))
    if збільшення > 1:
        полотно = np.repeat(np.repeat(полотно, збільшення, axis=0), збільшення, axis=1)

    середнє = float(np.nanmean(поле))
    комірок = int(np.isfinite(поле).sum())
    return _png(полотно), межі, кольори, середнє, комірок


ПАЛІТРА_ЗАЛИШКУ = ["#8c3a22", "#c9743a", "#e6d9c0", "#e6d9c0", "#a8c95c", "#2f6b30"]
ПАЛІТРА_ЗАЛИШКУ_ЗОН = ["#8c3a22", "#d09a6a", "#ece5d4", "#a8c95c", "#2f6b30"]


def пояснити_полем(точки):
    """Що на карті пояснює саме поле, а що лишається на технологію.

    Вегетація й рельєф — незалежні від монітора свідки. Якщо врожайність у
    комірці лягає на те, що кажуть вони, — це поле. Якщо різко не лягає,
    причина не в ґрунті: обробіток, сівба, внесення, ущільнення.

    Модель навмисно найпростіша — пряма по двох шарах. Складніша підібрала б
    і техногенне теж, і показувати тоді було б нічого.

    Повертає (залишок, частка_поясненого, маска_придатних).
    """
    y = np.asarray(точки["YLD_KGHA"], dtype="float64")
    шари = []
    for к in ("VEG_YEARS", "VEG_IDX", "BSI_IDX", "ELEV_M"):
        if к in точки:
            шари.append(np.asarray(точки[к], dtype="float64"))
    if not шари:
        return None, None, None
    X = np.column_stack(шари)
    ок = np.isfinite(y) & np.all(np.isfinite(X), axis=1)
    if ок.sum() < 200:
        return None, None, None

    A = np.column_stack([X[ок], np.ones(ок.sum())])
    коеф, *_ = np.linalg.lstsq(A, y[ок], rcond=None)
    прогноз = np.full(len(y), np.nan)
    прогноз[ок] = A @ коеф
    залишок = y - прогноз
    пояснено = 1.0 - np.nanvar(залишок[ок]) / max(np.var(y[ок]), 1e-9)
    return залишок, float(пояснено), ок


def карта_залишку(точки, залишок, ок, зон=5, мін_га=0.5):
    """Причини — зонами, а не пікселями.

    Піксельна карта залишку рябіє: у кожній комірці сидить шум монітора, і
    за ним не видно того, заради чого карта робиться. Тому:

    1. залишок згладжується вікном у три комірки — шум комірки прибирається,
       а смуги й плями лишаються;
    2. ділиться на зони по квантилях;
    3. модальний фільтр прибирає поодинокі комірки чужої зони;
    4. клапті дрібніші за {мін} га віддаються сусідові — з ними нічого не
       робиться в полі, і показувати їх нема сенсу.

    Червоне — поле дає менше, ніж обіцяють ґрунт і рельєф. Зелене — більше.
    """
    from scipy.ndimage import uniform_filter

    з = np.asarray(залишок, dtype="float64").copy()
    з[~ок] = np.nan
    с, р, стовпців, рядків = _індекси(точки)

    сітка = np.full((рядків, стовпців), np.nan)
    сітка[р, с] = з
    маска = np.isfinite(сітка)

    сума = uniform_filter(np.nan_to_num(сітка), 3, mode="nearest")
    вага = uniform_filter(маска.astype("float64"), 3, mode="nearest")
    гладко = np.where(вага > 1e-9, сума / np.maximum(вага, 1e-9), np.nan)
    гладко = np.where(маска, гладко, np.nan)

    значення = гладко[маска]
    межі = np.array(np.quantile(значення, np.linspace(0, 1, зон + 1)))
    межі = np.unique(межі)
    if len(межі) < 3:
        return None, 0.0
    мітки = np.full((рядків, стовпців), -1, dtype=int)
    мітки[маска] = np.clip(np.digitize(гладко[маска], межі[1:-1]), 0, len(межі) - 2)

    мітки = _модальний(мітки, маска, 3)
    мітки = _прибрати_клапті(мітки, маска, мін_га, крок=_крок_сітки(точки.geometry.x.to_numpy()))

    кольори = ПАЛІТРА_ЗАЛИШКУ_ЗОН[:len(межі) - 1]
    палітра = _палітра_чисел(кольори)
    полотно = np.full((рядків, стовпців, 3), 255, dtype="uint8")
    добрі = маска & (мітки >= 0)
    полотно[добрі] = палітра[np.clip(мітки[добрі], 0, len(кольори) - 1)]

    збільшення = max(1, int(round(ШИРИНА_КАРТИ / max(стовпців, 1))))
    if збільшення > 1:
        полотно = np.repeat(np.repeat(полотно, збільшення, axis=0), збільшення, axis=1)
    return _png(полотно), кольори


def _модальний(мітки, маска, радіус):
    """Поодинока комірка чужої зони — це шум, а не зона."""
    вихід = мітки.copy()
    рядків, стовпців = мітки.shape
    скільки = int(мітки[маска].max()) + 1 if маска.any() else 0
    if скільки < 2:
        return вихід
    from scipy.ndimage import uniform_filter
    голоси = []
    for к in range(скільки):
        свій = ((мітки == к) & маска).astype("float64")
        голоси.append(uniform_filter(свій, 2 * радіус + 1, mode="nearest"))
    голоси = np.stack(голоси)
    переможець = np.argmax(голоси, axis=0)
    вихід[маска] = переможець[маска]
    return вихід


def _прибрати_клапті(мітки, маска, мін_га, крок):
    """Клапоть, менший за поріг, віддається найбільшому сусідові."""
    from scipy.ndimage import label, binary_dilation

    мін_комірок = max(1, int(round(мін_га * 10000.0 / (крок * крок))))
    вихід = мітки.copy()
    скільки = int(мітки[маска].max()) + 1 if маска.any() else 0
    for _ in range(3):
        змінилось = False
        for к in range(скільки):
            свій = (вихід == к) & маска
            якщо, кількість = label(свій)
            if кількість == 0:
                continue
            розміри = np.bincount(якщо.ravel())
            for шматок in range(1, кількість + 1):
                if розміри[шматок] >= мін_комірок:
                    continue
                де = якщо == шматок
                довкола = binary_dilation(де, np.ones((3, 3), bool)) & маска & ~де
                сусіди = вихід[довкола]
                сусіди = сусіди[сусіди >= 0]
                if len(сусіди):
                    вихід[де] = np.bincount(сусіди).argmax()
                    змінилось = True
        if not змінилось:
            break
    return вихід


def ділянки_уваги(точки, залишок, ок, мін_га=1.0, поріг=0.80):
    """Суцільні ділянки, де врожайність не відповідає можливостям поля.

    Питання, на яке це відповідає: **червона пляма на карті — це справді
    поле чи огріх комбайна?**

    Якщо врожайність там низька, а рослинність увесь сезон теж низька — це
    поле. Якщо врожайність низька, а рослинність нормальна — поле там росло,
    а в бункер не потрапило.

    Тому по кожній ділянці рахується не лише наскільки вона нижча, а й що
    в тому самому місці кажуть незалежні свідки.

    Повертає перелік, найгірші перші.
    """
    from scipy.ndimage import label, binary_opening

    y = np.asarray(точки["YLD_KGHA"], dtype="float64")
    с, р, стовпців, рядків = _індекси(точки)
    крок = _крок_сітки(точки.geometry.x.to_numpy())
    комірка_га = крок * крок / 10000.0

    from scipy.ndimage import uniform_filter

    сира = np.full((рядків, стовпців), np.nan)
    сира[р, с] = np.where(ок, залишок, np.nan)
    маска = np.isfinite(сира)
    if маска.sum() < 200:
        return []

    # Шукаємо ділянки на ЗГЛАДЖЕНОМУ залишку. На сирому кожна комірка сама
    # собі пляма: шум монітора рве плями на друзки, і жодна не набирає
    # гектара. Вікно в пʼять комірок (50 м) прибирає шум комірки й лишає те,
    # що справді суцільне.
    сума = uniform_filter(np.nan_to_num(сира), 5, mode="nearest")
    вага = uniform_filter(маска.astype("float64"), 5, mode="nearest")
    сітка = np.where((вага > 1e-9) & маска, сума / np.maximum(вага, 1e-9), np.nan)
    маска = np.isfinite(сітка)

    межа_низу = float(np.nanquantile(сітка[маска], 0.18))
    межа_верху = float(np.nanquantile(сітка[маска], 0.82))

    вихід = []
    for назва, умова in (("нижче", сітка <= межа_низу), ("вище", сітка >= межа_верху)):
        грубо = binary_opening(умова & маска, np.ones((3, 3), bool))
        мітки, скільки = label(грубо)
        for і in range(1, скільки + 1):
            де = мітки == і
            га = float(де.sum()) * комірка_га
            if га < мін_га:
                continue
            рр, сс = np.nonzero(де)
            індекси = np.zeros(len(y), dtype=bool)
            ключ = {(a, b) for a, b in zip(рр, сс)}
            для = np.array([(a, b) in ключ for a, b in zip(р, с)])
            якщо_порожньо = для.sum() < 5
            if якщо_порожньо:
                continue
            запис = {
                "бік": назва,
                "га": га,
                "врожайність": float(np.nanmedian(y[для])),
                "відхил_кг": float(np.nanmedian(np.where(для, np.where(ок, залишок, np.nan), np.nan))),
                "центр_x": float(точки.geometry.x.to_numpy()[для].mean()),
                "центр_y": float(точки.geometry.y.to_numpy()[для].mean()),
                # справжні комірки ділянки: малювати її кружком означало б
                # намалювати форму, якої немає
                "комірки": для.copy(),
            }
            поле_медіана = float(np.nanmedian(y))
            запис["проти_поля"] = 100.0 * (запис["врожайність"] / поле_медіана - 1.0)
            if abs(запис["проти_поля"]) < 5.0:
                continue
            # що кажуть свідки в тому самому місці — у z-оцінці по полю
            for колонка, ім in (("VEG_IDX", "вегетація"), ("BSI_IDX", "ґрунт"),
                                ("ELEV_M", "рельєф")):
                if колонка not in точки:
                    continue
                v = np.asarray(точки[колонка], dtype="float64")
                добрі = np.isfinite(v)
                if добрі.sum() < 100 or np.nanstd(v[добрі]) <= 0:
                    continue
                z = (v - np.nanmean(v[добрі])) / np.nanstd(v[добрі])
                запис[ім] = float(np.nanmedian(z[для & добрі]))
            вихід.append(запис)

    вихід.sort(key=lambda з_: abs(з_["проти_поля"]), reverse=True)
    return вихід


def втрачені_можливості(точки, ділянки):
    """Скільки зерна ймовірно недобрано на ділянках, що не відповідають полю.

    Рахується тільки по ділянках, які пройшли відбір: суцільних, не менших за
    поріг і з відхилом понад п'ять відсотків. По окремих шумних комірках не
    рахується ніколи — там половина числа була б шумом монітора.

    Число **ймовірне, а не виміряне**: це різниця між тим, що дало поле, і
    тим, що обіцяли рослинність із рельєфом у тому самому місці. Причину воно
    не називає й назвати не може.
    """
    втрати = [д for д in ділянки if д["бік"] == "нижче"]
    разом_т = 0.0
    for д in втрати:
        недобір = abs(д["відхил_кг"])
        д["втрачено_т"] = недобір * д["га"] / 1000.0
        д["недобір_кг_га"] = недобір
        разом_т += д["втрачено_т"]
    return {
        "ділянок": len(втрати),
        "га": sum(д["га"] for д in втрати),
        "тонн": разом_т,
        "перелік": sorted(втрати, key=lambda д: д["втрачено_т"], reverse=True),
    }


