def _растр(точки, значення, межі, кольори, тло=(255, 255, 255)):
    x = точки.geometry.x.to_numpy()
    y = точки.geometry.y.to_numpy()
    крок = _крок_сітки(x, y)

    стовпців = int(np.ceil((x.max() - x.min()) / крок)) + 1
    рядків = int(np.ceil((y.max() - y.min()) / крок)) + 1
    збільшення = max(1, int(round(ШИРИНА_КАРТИ / max(стовпців, 1))))

    полотно = np.zeros((рядків, стовпців, 3), dtype="uint8")
    полотно[:, :] = тло

    сі = np.clip(((x - x.min()) / крок).round().astype(int), 0, стовпців - 1)
    рі = np.clip(((y.max() - y) / крок).round().astype(int), 0, рядків - 1)

    клас = np.clip(np.digitize(значення, межі[1:-1]), 0, len(кольори) - 1)
    палітра = np.array([render._у_числа(к) for к in кольори], dtype="uint8")
    добрі = np.isfinite(значення)
    полотно[рі[добрі], сі[добрі]] = палітра[клас[добрі]]

    if збільшення > 1:
        полотно = np.repeat(np.repeat(полотно, збільшення, axis=0), збільшення, axis=1)
    return полотно


def _крок_сітки(x, y):
    """Крок сітки з самих даних — щоб не питати того, що можна виміряти."""
    одні = np.unique(np.round(x, 2))
    if len(одні) > 2:
        кроки = np.diff(одні)
        крок = float(np.median(кроки[кроки > 0.5]))
        if np.isfinite(крок) and крок > 0.5:
            return крок
    return 10.0


def _png_у_рядок(полотно):
    import struct
    import zlib

    висота, ширина, _ = полотно.shape
    рядки = bytearray()
    for р in range(висота):
        рядки.append(0)
        рядки.extend(полотно[р].tobytes())

    def шматок(тип, дані):
        return (struct.pack(">I", len(дані)) + тип + дані
                + struct.pack(">I", zlib.crc32(тип + дані) & 0xFFFFFFFF))

    буфер = io.BytesIO()
    буфер.write(b"\x89PNG\r\n\x1a\n")
    буфер.write(шматок(b"IHDR", struct.pack(">IIBBBBB", ширина, висота, 8, 2, 0, 0, 0)))
    буфер.write(шматок(b"IDAT", zlib.compress(bytes(рядки), 9)))
    буфер.write(шматок(b"IEND", b""))
    return "data:image/png;base64," + base64.b64encode(буфер.getvalue()).decode("ascii")


def карта_врожайності(точки):
    значення = np.asarray(точки["YLD_KGHA"], dtype="float64")
    межі = render.класифікувати(значення, КЛАСІВ, "квантилі")
    кольори = render.палітра("врожай", len(межі) - 1)
    return _png_у_рядок(_растр(точки, значення, np.array(межі), кольори)), межі, кольори


def карта_походження(точки):
    """Де число виміряне, а де добудоване. Головна картинка чесності."""
    вимір = (точки["SRC_TYPE"] != "INTERP").to_numpy().astype(float)
    кольори = ["#c9743a", "#5d9f42"]        # добудовано · виміряно
    межі = np.array([0.0, 0.5, 1.0])
    return _png_у_рядок(_растр(точки, вимір, межі, кольори))


