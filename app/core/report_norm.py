def _крок_сітки(x):
    одні = np.unique(np.round(x, 2))
    if len(одні) > 2:
        кроки = np.diff(одні)
        крок = float(np.median(кроки[кроки > 0.5]))
        if np.isfinite(крок) and крок > 0.5:
            return крок
    return 10.0


def _індекси(точки):
    x = точки.geometry.x.to_numpy()
    y = точки.geometry.y.to_numpy()
    крок = _крок_сітки(x)
    с = np.clip(((x - x.min()) / крок).round().astype(int), 0, None)
    р = np.clip(((y.max() - y) / крок).round().astype(int), 0, None)
    return с, р, int(с.max()) + 1, int(р.max()) + 1


def _палітра_чисел(кольори):
    return np.array([render._у_числа(к) for к in кольори], dtype="uint8")


def _класи(значення, межі, кількість):
    return np.clip(np.digitize(значення, межі[1:-1]), 0, кількість - 1)


def _png(полотно):
    висота, ширина, _ = полотно.shape
    рядки = bytearray()
    for р in range(висота):
        рядки.append(0)
        рядки.extend(полотно[р].tobytes())

    def шматок(тип, дані):
        return (struct.pack(">I", len(дані)) + тип + дані
                + struct.pack(">I", zlib.crc32(тип + дані) & 0xFFFFFFFF))

    буфер = io.BytesIO()
    буфер.write(b"\x89PNG\r\n\x1a\n")
    буфер.write(шматок(b"IHDR", struct.pack(">IIBBBBB", ширина, висота, 8, 2, 0, 0, 0)))
    буфер.write(шматок(b"IDAT", zlib.compress(bytes(рядки), 9)))
    буфер.write(шматок(b"IEND", b""))
    буфер.seek(0)
    return буфер


def карта_плоска(точки, колонка, палітра="врожай", класів=КЛАСІВ, тло=(255, 255, 255)):
    """Звичайна карта згори. Повертає (буфер PNG, межі класів, кольори)."""
    значення = np.asarray(точки[колонка], dtype="float64")
    межі = np.array(render.класифікувати(значення, класів, "квантилі"))
    кольори = render.палітра(палітра, max(len(межі) - 1, 2))
    с, р, стовпців, рядків = _індекси(точки)

    полотно = np.zeros((рядків, стовпців, 3), dtype="uint8")
    полотно[:, :] = тло
    добрі = np.isfinite(значення)
    полотно[р[добрі], с[добрі]] = _палітра_чисел(кольори)[
        _класи(значення, межі, len(кольори))[добрі]]

    збільшення = max(1, int(round(ШИРИНА_КАРТИ / max(стовпців, 1))))
    if збільшення > 1:
        полотно = np.repeat(np.repeat(полотно, збільшення, axis=0), збільшення, axis=1)
    return _png(полотно), межі, кольори


def карта_походження(точки):
    вимір = (точки["SRC_TYPE"] != "INTERP").to_numpy().astype(float)
    кольори = ["#c9743a", "#5d9f42"]
    с, р, стовпців, рядків = _індекси(точки)
    полотно = np.zeros((рядків, стовпців, 3), dtype="uint8")
    полотно[:, :] = (255, 255, 255)
    полотно[р, с] = _палітра_чисел(кольори)[вимір.astype(int)]
    збільшення = max(1, int(round(ШИРИНА_КАРТИ / max(стовпців, 1))))
    if збільшення > 1:
        полотно = np.repeat(np.repeat(полотно, збільшення, axis=0), збільшення, axis=1)
    return _png(полотно)


def _згладити_рельєф(z, с, р, рядків, стовпців, вікно=7):
    """Прибирає шум приймача з висоти — але тільки для малюнка.

    Приймач комбайна тримає висоту з точністю близько чверті метра. При
    перебільшенні, потрібному щоб рельєф було видно, ця чверть метра стає
    десятком пікселів, і поверхня заростає голками. Тому для КАРТИНКИ
    висота згладжується вікном у кілька комірок.

    У розрахунок згладжена висота не йде ніколи: там працює виміряна.
    """
    from scipy.ndimage import uniform_filter

    сітка = np.zeros((рядків, стовпців), dtype="float64")
    маска = np.zeros((рядків, стовпців), dtype="float64")
    сітка[р, с] = z
    маска[р, с] = 1.0
    сума = uniform_filter(сітка, вікно, mode="nearest")
    вага = uniform_filter(маска, вікно, mode="nearest")
    з_вагою = np.where(вага > 1e-6, сума / np.maximum(вага, 1e-6), np.nan)
    згладжене = з_вагою[р, с]
    return np.where(np.isfinite(згладжене), згладжене, z)


def вид_3d(точки, колонка_кольору="YLD_KGHA", колонка_висоти="ELEV_M",
           перебільшення=9.0, ширина=1400):
    """Рельєф поля, розфарбований урожайністю. Ізометрія.

    Навіщо саме так. Плоска карта не показує, що низи й вершини працюють
    по-різному — а на Г-03 перепад 15 метрів на три з половиною кілометри,
    і саме він тягне за собою воду. Висота перебільшена навмисно: у
    справжньому масштабі поле було б плоским аркушем, і дивитись не було б
    на що. Це ілюстрація рельєфу, а не вимір висоти.
    """
    if колонка_висоти not in точки:
        return None
    z = np.asarray(точки[колонка_висоти], dtype="float64")
    c = np.asarray(точки[колонка_кольору], dtype="float64")
    добрі = np.isfinite(z) & np.isfinite(c)
    if добрі.sum() < 100:
        return None

    с, р, стовпців, рядків = _індекси(точки)
    с, р, z, c = с[добрі], р[добрі], z[добрі], c[добрі]
    z = _згладити_рельєф(z, с, р, рядків, стовпців)

    межі = np.array(render.класифікувати(c, КЛАСІВ, "квантилі"))
    кольори = _палітра_чисел(render.палітра("врожай", max(len(межі) - 1, 2)))
    клас = _класи(c, межі, len(кольори))

    # ---- проєкція
    u = (с - р).astype("float64")
    v = (с + р).astype("float64")
    кв = ширина / max(u.max() - u.min(), 1)
    кг = кв * 0.5
    кz = перебільшення * кв

    sx = (u - u.min()) * кв
    sy = (v - v.min()) * кг - (z - z.min()) * кz

    # ---- «спідниця»: без неї поверхня розсипається на кришиво.
    # Сусідні комірки різняться висотою, і при перебільшенні кожні 10 см
    # розводять їх на кілька пікселів. Якщо малювати саму лише верхню
    # грань, між ними світиться тло. Тому кожна комірка малюється як
    # стовпчик: верхня грань у своєму кольорі і бік під нею, притемнений.
    # Малюємо ззаду наперед, і ближчі стовпчики закривають боки дальших.
    спідниця = max(3, int(round(кz * 0.55)) + int(round(кг * 2)))

    поля = int(6 + кв * 2)
    W = int(sx.max()) + поля * 2 + 1
    H = int(sy.max() - sy.min()) + поля * 2 + спідниця + 1
    px = (sx + поля).astype(int)
    py = (sy - sy.min() + поля).astype(int)

    # ---- тінь: схил проти світла робить рельєф читабельним
    сітка = np.full((рядків, стовпців), np.nan)
    сітка[р, с] = z
    заповнена = np.nan_to_num(сітка, nan=float(np.nanmean(z)))
    gy, gx = np.gradient(заповнена)
    ухил = (gx * 0.8 - gy * 0.6)[р, с]
    яскравість = np.clip(1.0 + ухил * 0.55, 0.6, 1.3)

    полотно = np.zeros((H, W, 3), dtype="uint8")
    полотно[:, :] = (255, 255, 255)

    порядок = np.argsort(v, kind="stable")
    товщина = max(2, int(round(кв)) + 1)
    верх = max(2, int(round(кг)) + 2)
    for і in порядок:
        основа = кольори[клас[і]].astype("float64")
        x0, y0 = px[і], py[і]
        бік = np.clip(основа * 0.62, 0, 255).astype("uint8")
        полотно[y0 + верх:y0 + верх + спідниця, x0:x0 + товщина] = бік
        верхня = np.clip(основа * яскравість[і], 0, 255).astype("uint8")
        полотно[y0:y0 + верх, x0:x0 + товщина] = верхня

    return _png(полотно)


