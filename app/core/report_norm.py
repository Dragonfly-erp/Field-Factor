def зібрати_числа(точки, площа_га, факт=None):
    y = np.asarray(точки["YLD_KGHA"], dtype="float64")
    y = y[np.isfinite(y)]
    комірок = len(точки)
    вимір = int((точки["SRC_TYPE"] != "INTERP").sum()) if "SRC_TYPE" in точки else комірок
    p10, p50, p90 = np.percentile(y, [10, 50, 90])
    середнє = float(y.mean())

    числа = {
        "комірок": комірок,
        "вимір_відсотків": 100.0 * вимір / max(комірок, 1),
        "модель_відсотків": 100.0 * (комірок - вимір) / max(комірок, 1),
        "площа_га": площа_га,
        "середнє": середнє,
        "медіана": float(p50),
        "гірша_десятина": float(p10),
        "краща_десятина": float(p90),
        "розмах": float(p90 / p10) if p10 > 0 else float("nan"),
        "валовий_т": середнє * площа_га / 1000.0,
        "площа_нижче_середнього_га": float((y < середнє).sum()) * 0.01,
        "факт": факт,
    }
    числа.update(звірка_з_джерелами(точки))
    return числа


def звірка_з_джерелами(точки):
    """Чи згодні з картою джерела, які її НЕ будували.

    Рахується **тільки по виміряних комірках**. Добудовані рахувати не можна:
    вегетація брала участь у їх заповненні, і згода там була б колом.
    """
    вихід = {}
    if "SRC_TYPE" not in точки:
        return вихід
    свої = (точки["SRC_TYPE"] != "INTERP").to_numpy()
    y = np.asarray(точки["YLD_KGHA"], dtype="float64")
    for колонка, ключ in (("VEG_IDX", "r_вегетація"), ("ELEV_M", "r_рельєф")):
        if колонка not in точки:
            continue
        v = np.asarray(точки[колонка], dtype="float64")
        ок = свої & np.isfinite(v) & np.isfinite(y)
        if ок.sum() > 100 and np.nanstd(v[ок]) > 0:
            вихід[ключ] = float(np.corrcoef(v[ок], y[ок])[0, 1])
            вихід[ключ + "_n"] = int(ок.sum())
    return вихід


