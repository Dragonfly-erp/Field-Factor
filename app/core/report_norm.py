def _сітка(значення, с, р, рядків, стовпців):
    поле = np.full((рядків, стовпців), np.nan)
    поле[р, с] = значення
    return поле


def _межа_поля(поле):
    """Де поле є. Дірки всередині — теж поле, за краєм — уже не поле."""
    from scipy.ndimage import binary_closing, binary_fill_holes

    є = np.isfinite(поле)
    зімкнене = binary_closing(є, structure=np.ones((5, 5), dtype=bool))
    return binary_fill_holes(зімкнене)


def _заповнити(поле, вікно=5, проходів=6):
    """Затягує дірки в сітці сусідами. Тільки для малюнка.

    Поверхня з дірками розсипається на клапті, і рельєфу на ній не видно.
    Тому для картинки порожні комірки затягуються середнім по сусідах —
    кілька разів, доки дірки не заростуть. У числа це не потрапляє ніде.
    """
    from scipy.ndimage import uniform_filter

    всередині = _межа_поля(поле)
    вихід = поле.copy()
    for _ in range(проходів):
        порожні = ~np.isfinite(вихід) & всередині
        if not порожні.any():
            break
        значення = np.nan_to_num(вихід, nan=0.0)
        маска = np.isfinite(вихід).astype("float64")
        сума = uniform_filter(значення, вікно, mode="nearest")
        вага = uniform_filter(маска, вікно, mode="nearest")
        сусіди = np.where(вага > 1e-6, сума / np.maximum(вага, 1e-6), np.nan)
        вихід = np.where(порожні & np.isfinite(сусіди), сусіди, вихід)
    return np.where(всередині, вихід, np.nan)


def _згладити_рельєф(z, с, р, рядків, стовпців, вікно=7):
    """Прибирає шум приймача з висоти — але тільки для малюнка.

    Приймач комбайна тримає висоту з точністю близько чверті метра. При
    перебільшенні, потрібному щоб рельєф було видно, ця чверть метра стає
    десятком пікселів, і поверхня заростає голками. Тому для КАРТИНКИ
    висота згладжується вікном у кілька комірок.

    У розрахунок згладжена висота не йде ніколи: там працює виміряна.
    """
    from scipy.ndimage import uniform_filter

    сітка = np.zeros((рядків, стовпців), dtype="float64")
    маска = np.zeros((рядків, стовпців), dtype="float64")
    сітка[р, с] = z
    маска[р, с] = 1.0
    сума = uniform_filter(сітка, вікно, mode="nearest")
    вага = uniform_filter(маска, вікно, mode="nearest")
    з_вагою = np.where(вага > 1e-6, сума / np.maximum(вага, 1e-6), np.nan)
    згладжене = з_вагою[р, с]
    return np.where(np.isfinite(згладжене), згладжене, z)


def вид_3d(точки, колонка_кольору="YLD_KGHA", колонка_висоти="ELEV_M",
           перебільшення=4.5, ширина=1500, нахил=0.40):
    """Рельєф поля, розфарбований урожайністю. Погляд збоку й згори.

    Три речі, без яких воно не читається, і кожну довелось спіймати очима:

    1. **поверхня має бути суцільною.** Сітка з дірками розсипається на
       клапті — дірки затягуються сусідами, тільки для малюнка;
    2. **під кожною плиткою потрібна «спідниця».** Сусідні комірки різняться
       висотою, і при перебільшенні між ними світиться тло;
    3. **висоту треба згладити.** Приймач тримає чверть метра, і при
       перебільшенні ця чверть стає голками.

    `нахил` — це і є ракурс. Одиниця дала б погляд згори, нуль — точно
    збоку. Третина ставить око над полем і збоку, як у SMS.
    """
    if колонка_висоти not in точки:
        return None
    z0 = np.asarray(точки[колонка_висоти], dtype="float64")
    c0 = np.asarray(точки[колонка_кольору], dtype="float64")
    if np.isfinite(z0).sum() < 100:
        return None

    с, р, стовпців, рядків = _індекси(точки)
    межі = np.array(render.класифікувати(c0[np.isfinite(c0)], КЛАСІВ, "квантилі"))
    палітра = _палітра_чисел(render.палітра("врожай", max(len(межі) - 1, 2)))

    # ---- суцільна поверхня
    from scipy.ndimage import uniform_filter

    Z = _заповнити(_сітка(z0, с, р, рядків, стовпців))
    C = _заповнити(_сітка(c0, с, р, рядків, стовпців))
    є = np.isfinite(Z) & np.isfinite(C)
    if не_вистачає(є):
        return None
    вага = uniform_filter(є.astype("float64"), 9, mode="nearest")
    сума = uniform_filter(np.nan_to_num(Z), 9, mode="nearest")
    Zг = np.where(вага > 1e-6, сума / np.maximum(вага, 1e-6), np.nan)
    Z = np.where(є, Zг, np.nan)

    сумаC = uniform_filter(np.nan_to_num(C), 5, mode="nearest")
    вагаC = uniform_filter(є.astype("float64"), 5, mode="nearest")
    Cг = np.where(вагаC > 1e-6, сумаC / np.maximum(вагаC, 1e-6), np.nan)

    рр, сс = np.nonzero(є)
    z = Z[рр, сс]
    клас = _класи(Cг[рр, сс], межі, len(палітра))

    # ---- проєкція: око збоку й згори
    u = (сс - рр).astype("float64")
    v = (сс + рр).astype("float64")
    кв = ширина / max(u.max() - u.min(), 1)
    кг = кв * нахил
    кz = перебільшення * кв

    sx = (u - u.min()) * кв
    sy = (v - v.min()) * кг - (z - z.min()) * кz

    підошва = int(кz * 0.45) + 14
    спідниця = max(4, int(round(кz * 0.6)) + int(round(кг * 2)))
    поля = int(8 + кв * 2)
    W = int(sx.max()) + поля * 2 + 1
    H = int(sy.max() - sy.min()) + поля * 2 + підошва + 1
    px = (sx + поля).astype(int)
    py = (sy - sy.min() + поля).astype(int)

    # ---- тінь від схилу
    gy, gx = np.gradient(np.nan_to_num(Z, nan=float(np.nanmean(z))))
    ухил = (gx * 0.85 - gy * 0.55)[рр, сс]
    яскравість = np.clip(1.0 + ухил * 0.6, 0.6, 1.32)

    полотно = np.full((H, W, 3), 255, dtype="uint8")
    порядок = np.argsort(v, kind="stable")
    товщина = max(2, int(round(кв)) + 1)
    верх = max(2, int(round(кг)) + 2)
    сірий = np.array([214, 214, 210], dtype="uint8")
    сірий_бік = np.array([188, 188, 184], dtype="uint8")

    for і in порядок:
        x0, y0 = px[і], py[і]
        # підошва — сірий постамент, як у SMS: дає око, від чого рахувати висоту
        полотно[y0 + верх:y0 + верх + спідниця + підошва, x0:x0 + товщина] = сірий
        основа = палітра[клас[і]].astype("float64")
        полотно[y0 + верх:y0 + верх + спідниця, x0:x0 + товщина] = (
            np.clip(основа * 0.6, 0, 255).astype("uint8"))
        полотно[y0:y0 + верх, x0:x0 + товщина] = (
            np.clip(основа * яскравість[і], 0, 255).astype("uint8"))

    # бічна грань постаменту темніша — інакше він зливається з тлом
    сіре = np.all(полотно == сірий, axis=2)
    край = сіре & ~np.roll(сіре, -1, axis=0)
    полотно[край] = сірий_бік

    return _png(полотно)


def не_вистачає(маска):
    return int(маска.sum()) < 100


