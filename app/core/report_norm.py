    a = д.append
    a("<!doctype html><html lang='uk'><head><meta charset='utf-8'>")
    a("<title>Звіт про нормалізацію · {} · {}</title>".format(_е(поле), _е(рік)))
    a("<style>{}</style></head><body>".format(_стилі()))

    # ---------------------------------------------------------- сторінка 1
    a("<section class='аркуш'>")
    a("<header class='шапка'>")
    a("<div><div class='над'>Карта врожайності · нормалізовано</div>")
    a("<h1>{}{}</h1>".format(_е(поле),
                             " · " + _е(господарство) if господарство else ""))
    a("<div class='під'>{}{}{} · {:.2f} га</div></div>".format(
        _е(культура), " · " if культура and рік else "", _е(рік), числа["площа_га"]))
    a("<div class='марка'>FieldFactor</div>")
    a("</header>")

    a("<div class='головне'>")
    for підпис, значення, одиниця in [
            ("Середня врожайність", _ч(числа["середнє"]), "кг/га"),
            ("Валовий збір", _ч(числа["валовий_т"], 0), "тонн"),
            ("Різниця по полю", _ч(числа["розмах"], 1).replace(",0", ""), "разів")]:
        a("<div class='чістка'><div class='цифра'>{}</div>"
          "<div class='одиниця'>{}</div><div class='підпис'>{}</div></div>"
          .format(значення, одиниця, підпис))
    a("</div>")
    a("<p class='базис'>Числа наведені на заліковій вологості {} %.</p>"
      .format(_ч(базис, 0)))

    a("<figure class='карта'><img src='{}' alt='Карта врожайності'>".format(карта))
    a("<figcaption>")
    a("<span class='легенда'>")
    for і, колір in enumerate(кольори):
        a("<span class='клітинка'><i style='background:{}'></i>{}–{}</span>"
          .format(колір, _ч(межі[і]), _ч(межі[і + 1])))
    a("</span><span class='одиниця-легенди'>кг/га</span>")
    a("</figcaption></figure>")

    a("<div class='висновок'>")
    a("<h2>Що це означає</h2>")
    a("<p>Найкраща десятина поля дає <b>{} кг/га</b>, найгірша — <b>{} кг/га</b>. "
      "Це різниця в <b>{}</b> рази на одному полі, під однією культурою, "
      "з однаковим внесенням.</p>".format(
          _ч(числа["краща_десятина"]), _ч(числа["гірша_десятина"]),
          _ч(числа["розмах"], 1)))
    a("<p><b>{} га</b> працюють нижче середнього по цьому ж полю. Різниця між "
      "ними й середнім — <b>{} тонн</b> зерна за сезон.</p>".format(
          _ч(числа["площа_нижче_середнього_га"], 1), _ч(числа["недобір_т"], 0)))
    a("<p class='осторога'>Це опис поля, а не обіцянка врожаю. Слабка ділянка "
      "не означає, що туди треба сипати більше: причина буває в кислотності, "
      "ущільненні, воді чи рельєфі, і добривом вона не лікується. Що саме "
      "стримує кожну ділянку — показує наступний крок, зонування й аналізи.</p>")
    a("</div>")
    a("<footer class='низ'>Сторінка 1 з 2 · FieldFactor · {}</footer>"
      .format(datetime.date.today().strftime("%d.%m.%Y")))
    a("</section>")

    # ---------------------------------------------------------- сторінка 2
    a("<section class='аркуш'>")
    a("<h2 class='розділ'>Чому цій карті можна вірити</h2>")

    a("<div class='дві'>")
    a("<figure class='карта мала'><img src='{}' alt='Звідки взяте число'>"
      "<figcaption><span class='легенда'>"
      "<span class='клітинка'><i style='background:#5d9f42'></i>виміряно комбайном</span>"
      "<span class='клітинка'><i style='background:#c9743a'></i>добудовано</span>"
      "</span></figcaption></figure>".format(походження))
    a("<div class='пояснення'>")
    a("<p><b>{:.0f} % карти — це вимір</b> із монітора комбайна. Решта {:.0f} % — "
      "проміжки між сусідніми проходами, які добудовані за оточенням.</p>".format(
          числа["вимір_відсотків"], числа["модель_відсотків"]))
    a("<p>Добудоване позначене в самому файлі окремою колонкою. Ви завжди "
      "можете відрізнити виміряне від порахованого — ми цього не ховаємо.</p>")
    a("</div></div>")

    if очистка:
        a("<h3>Що не пішло в карту</h3>")
        a("<p>З {} записів монітора у карту пішли <b>{}</b>. Решту прибрано: "
          "{}.</p>".format(_ч(очистка.get("сирих")), _ч(очистка.get("чистих")),
                           _е(очистка.get("чому") or "повтори координат, "
                              "розвороти й початки проходів")))

    if звірка and звірка.get("ціль_кг_га"):
        a("<h3>Звірка з вагою господарства</h3>")
        a("<table class='звірка'>")
        a("<tr><td>Монітор комбайна дав</td><td>{} кг/га</td></tr>".format(
            _ч(звірка.get("до_підгону_кг_га"))))
        a("<tr><td>Вагова господарства</td><td>{} кг/га</td></tr>".format(
            _ч(звірка.get("ціль_кг_га"))))
        a("<tr><td>Карту зведено з вагою</td><td>×{}</td></tr>".format(
            _ч(звірка.get("коефіцієнт"), 3)))
        a("</table>")
        a("<p>Абсолютні кілограми на карті спираються на вашу вагову, а не на "
          "монітор. Монітор показує, <b>де</b> більше й менше; скільки саме — "
          "каже вага.</p>")
    else:
        a("<h3>Звірка з вагою господарства</h3>")
        a("<p class='осторога'>Фактичної врожайності не надано. Карта показує, "
          "де краще й гірше, але абсолютні кілограми на ній — це те, що "
          "намалював монітор, без зовнішньої перевірки.</p>")

    if застереження:
        a("<h3>Що варто знати</h3><ul class='застереження'>")
        for з in застереження:
            a("<li>{}</li>".format(_е(з)))
        a("</ul>")

    a("<h3>Що далі</h3>")
    a("<ol class='далі'>")
    a("<li><b>Зонування.</b> Поле ділиться на ділянки, які поводяться однаково "
      "рік у рік — за рельєфом, електропровідністю й урожайністю.</li>")
    a("<li><b>План відбору.</b> Карта каже, <i>де</i> брати зразок, щоб проба "
      "не змішала маківку горба з улоговиною.</li>")
    a("<li><b>Аналізи й норми.</b> Аж тоді стає видно, що саме стримує слабкі "
      "ділянки і чи лікується це внесенням.</li>")
    a("</ol>")

    a("<footer class='низ'>Сторінка 2 з 2 · Повний технічний протокол "
      "обробки — у файлі qc_summary.txt поруч із картою.</footer>")
    a("</section>")

    a("</body></html>")

    os.makedirs(os.path.dirname(шлях) or ".", exist_ok=True)
    with io.open(шлях, "w", encoding="utf-8") as ф:
        ф.write("\n".join(д))
    return шлях


