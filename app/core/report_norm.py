def _ч(значення, знаків=0):
    if значення is None or not np.isfinite(значення):
        return "—"
    текст = "{:,.{}f}".format(float(значення), знаків).replace(",", " ")
    return текст.replace(".", ",")


class _Аркуш:
    """Тонка обгортка над fpdf2: шапка, підвал, дрібні цеглинки."""

    ПОЛЕ = 14

    def __init__(self, підзаголовок):
        from fpdf import FPDF

        self.pdf = FPDF(orientation="P", unit="mm", format="A4")
        # Автоперенос вимкнено свідомо. Звіт має рівно стільки сторінок,
        # скільки ми намалювали: як тільки він доливає сторінку сам, підвал
        # «сторінка 2 з 3» починає брехати, а порожня сторінка з двома
        # рядками їде господарству. Переповнення тут — помилка розкладки,
        # і воно має бути видно, а не залатане.
        self.pdf.set_auto_page_break(False)
        self.pdf.set_margins(self.ПОЛЕ, self.ПОЛЕ, self.ПОЛЕ)
        self._шрифт()
        self.підзаголовок = підзаголовок
        self.сторінок = 0
        self.переповнення = []

    def _шрифт(self):
        for звичайний, жирний in ШРИФТИ:
            if os.path.isfile(звичайний) and os.path.isfile(жирний):
                self.pdf.add_font("ф", "", звичайний)
                self.pdf.add_font("ф", "B", жирний)
                return
        raise RuntimeError(
            "Не знайдено системного шрифту з кирилицею — PDF без нього не зробити.")

    @property
    def ш(self):
        return self.pdf.w - 2 * self.ПОЛЕ

    def аркуш(self):
        self.pdf.add_page()
        self.сторінок += 1

    ДНО = 275.0        # мм: нижче цього починається підвал

    def підвал(self, текст):
        якщо_вилізло = self.pdf.get_y() - self.ДНО
        if якщо_вилізло > 0:
            self.переповнення.append(
                "сторінка {}: вміст виліз за підвал на {:.0f} мм".format(
                    self.сторінок, якщо_вилізло))
        self.pdf.set_y(-15)
        self.pdf.set_draw_color(*ЛІНІЯ)
        self.pdf.line(self.ПОЛЕ, self.pdf.get_y(), self.pdf.w - self.ПОЛЕ, self.pdf.get_y())
        self.pdf.ln(1.5)
        self.pdf.set_font("ф", "", 7.5)
        self.pdf.set_text_color(*СІРИЙ)
        self.pdf.cell(0, 4, текст)
        self.pdf.set_text_color(*ТЕМНИЙ)

    def заголовок(self, великий, малий, праворуч=""):
        self.pdf.set_font("ф", "", 7.5)
        self.pdf.set_text_color(*СІРИЙ)
        self.pdf.cell(0, 4, малий.upper(), new_x="LMARGIN", new_y="NEXT")
        self.pdf.set_text_color(*ТЕМНИЙ)
        self.pdf.set_font("ф", "B", 17)
        y = self.pdf.get_y()
        self.pdf.cell(self.ш * 0.75, 8, великий)
        if праворуч:
            self.pdf.set_xy(self.ПОЛЕ + self.ш * 0.75, y)
            self.pdf.set_font("ф", "B", 11)
            self.pdf.set_text_color(*ЗЕЛЕНИЙ)
            self.pdf.cell(self.ш * 0.25, 8, праворуч, align="R")
            self.pdf.set_text_color(*ТЕМНИЙ)
        self.pdf.ln(9)
        self.pdf.set_draw_color(*ЗЕЛЕНИЙ)
        self.pdf.set_line_width(0.5)
        self.pdf.line(self.ПОЛЕ, self.pdf.get_y(), self.pdf.w - self.ПОЛЕ, self.pdf.get_y())
        self.pdf.set_line_width(0.2)
        self.pdf.ln(3)

    def розділ(self, текст):
        self.pdf.ln(2)
        self.pdf.set_font("ф", "B", 10.5)
        self.pdf.set_text_color(*ЗЕЛЕНИЙ)
        self.pdf.cell(0, 5.5, текст, new_x="LMARGIN", new_y="NEXT")
        self.pdf.set_text_color(*ТЕМНИЙ)

    def абзац(self, текст, розмір=9.5, відступ=1.5):
        self.pdf.set_font("ф", "", розмір)
        self.pdf.multi_cell(self.ш, 4.6, текст)
        self.pdf.ln(відступ)

    def рамка(self, текст):
        self.pdf.set_fill_color(251, 246, 233)
        self.pdf.set_draw_color(230, 191, 85)
        y = self.pdf.get_y()
        self.pdf.set_font("ф", "", 8.8)
        self.pdf.multi_cell(self.ш, 4.2, текст, fill=True, border=0)
        self.pdf.set_line_width(0.9)
        self.pdf.line(self.ПОЛЕ, y, self.ПОЛЕ, self.pdf.get_y())
        self.pdf.set_line_width(0.2)
        self.pdf.ln(2)

    def плитки(self, набір):
        ширина = self.ш / len(набір)
        y = self.pdf.get_y()
        for і, (цифра, одиниця, підпис) in enumerate(набір):
            x = self.ПОЛЕ + і * ширина
            self.pdf.set_fill_color(244, 246, 241)
            self.pdf.rect(x, y, ширина - 2, 21, style="F")
            self.pdf.set_fill_color(*(93, 159, 66))
            self.pdf.rect(x, y, 1.2, 21, style="F")
            self.pdf.set_xy(x + 4, y + 2.5)
            self.pdf.set_font("ф", "B", 17)
            self.pdf.set_text_color(30, 77, 43)
            self.pdf.cell(ширина - 6, 8, цифра)
            self.pdf.set_xy(x + 4, y + 10.5)
            self.pdf.set_font("ф", "", 7.5)
            self.pdf.set_text_color(*СІРИЙ)
            self.pdf.cell(ширина - 6, 4, одиниця)
            self.pdf.set_xy(x + 4, y + 14.5)
            self.pdf.set_font("ф", "", 8.5)
            self.pdf.set_text_color(*ТЕМНИЙ)
            self.pdf.cell(ширина - 6, 4, підпис)
        self.pdf.set_y(y + 24)

    def пари(self, набір):
        """Плитка «було → стало». Ліворуч монітор, праворуч наш результат."""
        ширина = self.ш / len(набір)
        y = self.pdf.get_y()
        for і, (було, стало, одиниця, підпис) in enumerate(набір):
            x = self.ПОЛЕ + і * ширина
            self.pdf.set_fill_color(244, 246, 241)
            self.pdf.rect(x, y, ширина - 2, 21, style="F")
            self.pdf.set_fill_color(93, 159, 66)
            self.pdf.rect(x, y, 1.2, 21, style="F")

            self.pdf.set_xy(x + 4, y + 2.5)
            self.pdf.set_font("ф", "", 13)
            self.pdf.set_text_color(*СІРИЙ)
            ш_було = self.pdf.get_string_width(було)
            self.pdf.cell(ш_було + 1, 8, було)
            self.pdf.set_font("ф", "", 11)
            self.pdf.cell(5, 8, "→")
            self.pdf.set_font("ф", "B", 15)
            self.pdf.set_text_color(30, 77, 43)
            self.pdf.cell(ширина - 12 - ш_було, 8, стало)

            self.pdf.set_xy(x + 4, y + 11)
            self.pdf.set_font("ф", "", 7.5)
            self.pdf.set_text_color(*СІРИЙ)
            self.pdf.cell(ширина - 6, 4, одиниця)
            self.pdf.set_xy(x + 4, y + 15)
            self.pdf.set_font("ф", "", 8.5)
            self.pdf.set_text_color(*ТЕМНИЙ)
            self.pdf.cell(ширина - 6, 4, підпис)
        self.pdf.set_y(y + 23)

    def малюнок(self, буфер, висота=None, ширина=None):
        if буфер is None:
            return
        буфер.seek(0)
        ш = ширина or self.ш
        self.pdf.image(буфер, x=self.pdf.get_x(), y=self.pdf.get_y(),
                       w=ш, h=висота or 0)

    def легенда(self, кольори, межі, одиниця="кг/га", підписи=None):
        self.pdf.set_font("ф", "", 7.2)
        x = self.ПОЛЕ
        y = self.pdf.get_y()
        for і, колір in enumerate(кольори):
            self.pdf.set_fill_color(*render._у_числа(колір))
            self.pdf.rect(x, y + 1, 4, 2.6, style="F")
            текст = (підписи[і] if підписи
                     else "{}–{}".format(_ч(межі[і]), _ч(межі[і + 1])))
            self.pdf.set_xy(x + 5, y)
            ш = self.pdf.get_string_width(текст) + 4
            self.pdf.cell(ш, 4.5, текст)
            x += 5 + ш
        if підписи is None:
            self.pdf.set_xy(self.pdf.w - self.ПОЛЕ - 20, y)
            self.pdf.set_text_color(*СІРИЙ)
            self.pdf.cell(20, 4.5, одиниця, align="R")
            self.pdf.set_text_color(*ТЕМНИЙ)
        self.pdf.set_y(y + 6)


def скласти(шлях, паспорт, точки, числа, до=None, очистка=None, звірка=None):
    """Пише PDF. Повертає шлях.

    `до` — те, що було у файлі монітора: `(буфер, межі, кольори, середнє,
    комірок)` з `карта_до`. Без нього перша сторінка показує лише результат.

    Тексту тут навмисно мало. Рішення Власника 21.08: звіт має показувати,
    а не переказувати. Пояснення, що слабка зона не лікується нормою, і
    перелік дальших кроків прибрані — вони йдуть голосом, а не папером.
    """
    поле = паспорт.get("поле") or "поле"
    господарство = паспорт.get("господарство") or ""
    культура = паспорт.get("культура") or ""
    рік = паспорт.get("рік") or ""
    базис = паспорт.get("базис") or 14.0
    сьогодні = datetime.date.today().strftime("%d.%m.%Y")

    а = _Аркуш(поле)
    p = а.pdf

    # ══════════════════════════════════════════ 1. ДО І ПІСЛЯ
    а.аркуш()
    а.заголовок("{}{}".format(поле, " · " + господарство if господарство else ""),
                "Карта врожайності · нормалізовано", "FieldFactor")
    p.set_font("ф", "", 9.5)
    p.set_text_color(*СІРИЙ)
    p.cell(0, 4.5, "{}{}{} · {:.2f} га · залікова вологість {} %".format(
        культура, " · " if культура and рік else "", рік,
        числа["площа_га"], _ч(базис, 0)), new_x="LMARGIN", new_y="NEXT")
    p.set_text_color(*ТЕМНИЙ)
    p.ln(2)

    карта, межі, кольори = карта_плоска(точки, "YLD_KGHA")
    пів = (а.ш - 4) / 2

    if до is not None:
        буфер_до, межі_до, кольори_до, середнє_до, комірок_до = до
        валовий_до = середнє_до * числа["площа_га"] / 1000.0
        y = p.get_y()
        for х, підпис in ((а.ПОЛЕ, "З файлу монітора"),
                          (а.ПОЛЕ + пів + 4, "Після нормалізації")):
            p.set_xy(х, y)
            p.set_font("ф", "B", 9)
            p.cell(пів, 5, підпис)
        p.set_y(y + 5.5)
        y = p.get_y()
        буфер_до.seek(0)
        p.image(буфер_до, x=а.ПОЛЕ, y=y, w=пів)
        карта.seek(0)
        p.image(карта, x=а.ПОЛЕ + пів + 4, y=y, w=пів)
        p.set_y(y + 45)
        p.set_font("ф", "", 7.2)
        p.set_text_color(*СІРИЙ)
        p.multi_cell(а.ш, 3.6,
                     "Кожна карта у своїх межах кольору — порівнюйте малюнок, "
                     "не відтінок. Ліворуч видно сліди машини, розвороти й "
                     "порожнечі; праворуч їх немає.")
        p.set_text_color(*ТЕМНИЙ)
        p.ln(1)

        а.пари([
            (_ч(середнє_до), _ч(числа["середнє"]), "кг/га", "Середня врожайність"),
            (_ч(валовий_до), _ч(числа["валовий_т"]), "тонн", "Валовий збір"),
        ])
        а.плитки([(_ч(числа["розмах"], 1), "рази", "Різниця по полю")])
    else:
        а.плитки([
            (_ч(числа["середнє"]), "кг/га", "Середня врожайність"),
            (_ч(числа["валовий_т"]), "тонн", "Валовий збір"),
            (_ч(числа["розмах"], 1), "рази", "Різниця по полю"),
        ])
        а.малюнок(карта, висота=68)
        p.ln(69)
        а.легенда(кольори, межі)

    а.підвал("Сторінка 1 з 3 · FieldFactor · {}".format(сьогодні))

    # ══════════════════════════════════════════ 2. РЕЛЬЄФ І РОСЛИННІСТЬ
    вид = вид_3d(точки)
    а.аркуш()
    а.заголовок("Рельєф і рослинність", "Те, з чим карта збігається", поле)
    if вид:
        а.малюнок(вид, висота=88)
        p.ln(89)
        а.легенда(кольори, межі)

    if "VEG_IDX" in точки:
        p.ln(1)
        p.set_font("ф", "B", 9)
        p.cell(0, 5, "Рослинність зі супутника за сезон", new_x="LMARGIN", new_y="NEXT")
        веге, межі_в, кольори_в = карта_плоска(точки, "VEG_IDX", "вегетація", 5)
        а.малюнок(веге, висота=40)
        p.ln(41)
        а.легенда(кольори_в, межі_в, "індекс")

    рядки = [(н, числа[к], з) for н, к, з in (
        ("Рослинність зі супутника", "r_вегетація", "Sentinel-2, 4 дати сезону"),
        ("Рельєф поля", "r_рельєф", "приймач комбайна")) if к in числа]
    if рядки:
        p.ln(1)
        p.set_font("ф", "B", 9)
        p.cell(0, 5, "Збіг із картою врожайності", new_x="LMARGIN", new_y="NEXT")
        for назва, r, звідки in рядки:
            p.set_font("ф", "", 9)
            p.cell(а.ш * 0.42, 5.6, назва)
            p.set_font("ф", "B", 9)
            p.cell(а.ш * 0.13, 5.6, "{:.2f}".format(r).replace(".", ","))
            p.set_font("ф", "", 8.5)
            p.set_text_color(*СІРИЙ)
            p.cell(а.ш * 0.45, 5.6, звідки, new_x="LMARGIN", new_y="NEXT")
            p.set_text_color(*ТЕМНИЙ)
            p.set_draw_color(*ЛІНІЯ)
            p.line(а.ПОЛЕ, p.get_y(), p.w - а.ПОЛЕ, p.get_y())
        p.set_font("ф", "", 7.2)
        p.set_text_color(*СІРИЙ)
        p.ln(1)
        p.multi_cell(а.ш, 3.6,
                     "Рахувалось тільки по комірках із живим записом монітора. "
                     "Ні рельєф, ні супутник у їх обчисленні не брали участі.")
        p.set_text_color(*ТЕМНИЙ)

    а.підвал("Сторінка 2 з 3 · FieldFactor · {}".format(сьогодні))

    # ══════════════════════════════════════════ 3. ПОХОДЖЕННЯ ЧИСЕЛ
    а.аркуш()
    а.заголовок("Походження чисел", "Вимір, добудова, звірка з вагою", поле)

    а.абзац(
        "{:.0f} % карти — вимір із монітора комбайна, {:.0f} % — проміжки між "
        "проходами, добудовані за оточенням. У файлі це позначено окремою "
        "колонкою.".format(числа["вимір_відсотків"], числа["модель_відсотків"]))
    а.малюнок(карта_походження(точки), висота=52)
    p.ln(53)
    а.легенда(["#5d9f42", "#c9743a"], None,
              підписи=["виміряно комбайном", "добудовано"])

    if очистка:
        p.ln(1)
        а.абзац("З {} записів монітора в карту пішли {}.".format(
            _ч(очистка.get("сирих")), _ч(очистка.get("чистих"))))

    if звірка and звірка.get("ціль_кг_га"):
        а.розділ("Звірка з вагою господарства")
        for назва, значення in (
                ("Монітор комбайна дав", _ч(звірка.get("до_підгону_кг_га")) + " кг/га"),
                ("Вагова господарства", _ч(звірка.get("ціль_кг_га")) + " кг/га"),
                ("Карту зведено з вагою", "×" + _ч(звірка.get("коефіцієнт"), 3))):
            p.set_font("ф", "", 9)
            p.cell(а.ш * 0.6, 6, назва)
            p.set_font("ф", "B", 9)
            p.cell(а.ш * 0.4, 6, значення, align="R", new_x="LMARGIN", new_y="NEXT")
            p.set_draw_color(*ЛІНІЯ)
            p.line(а.ПОЛЕ, p.get_y(), p.w - а.ПОЛЕ, p.get_y())
        p.ln(1)
        а.абзац("Кілограми на карті спираються на вашу вагову. Монітор "
                "показує, де більше й менше.", розмір=8.8)

    а.підвал("Сторінка 3 з 3 · Технічний протокол — у файлі qc_summary.txt "
             "поруч із картою.")

    if а.переповнення:
        raise ValueError(
            "Звіт не вміщується в намальовані сторінки: "
            + "; ".join(а.переповнення)
            + ". Це помилка розкладки, а не привід долити сторінку.")

    os.makedirs(os.path.dirname(шлях) or ".", exist_ok=True)
    p.output(шлях)
    return шлях
