def чи_свідки_згодні(ділянка):
    """Одне слово: поле там справді таке, чи ні.

    Порівнюється знак. Ділянка нижча за поле, і вегетація там теж нижча —
    свідки згодні, це поле. Ділянка нижча, а вегетація нормальна або вища —
    свідки не згодні, і тоді число в бункері не пояснюється полем.
    """
    веге = ділянка.get("вегетація")
    if веге is None:
        return "свідка немає"
    нижче = ділянка["бік"] == "нижче"
    if нижче and веге <= -0.3:
        return "згодна"
    if (not нижче) and веге >= 0.3:
        return "згодна"
    if abs(веге) < 0.3:
        return "мовчить"
    return "НЕ згодна"


def край_поля(точки, контур, смуга_м=20.0):
    """Скільки поля лежить у розворотній смузі й наскільки вона бідніша."""
    if контур is None:
        return None
    межа = контур.geometry.iloc[0].boundary
    d = точки.geometry.distance(межа).to_numpy()
    y = np.asarray(точки["YLD_KGHA"], dtype="float64")
    край = d < смуга_м
    якщо = np.isfinite(y)
    if край.sum() < 50 or (~край & якщо).sum() < 50:
        return None
    усередині = float(np.median(y[~край & якщо]))
    на_краю = float(np.median(y[край & якщо]))
    return {"га": float(край.sum()) * 0.01,
            "частка": 100.0 * край.mean(),
            "усередині": усередині,
            "на_краю": на_краю,
            "нижче_на": 100.0 * (1.0 - на_краю / усередині) if усередині else 0.0,
            "смуга_м": смуга_м}


