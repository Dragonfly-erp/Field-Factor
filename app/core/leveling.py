def смугастість(x, y, значення, проходи, крок=None, ширина_захвату=None):
    """Наскільки перехід через шов проходу додає різниці між сусідами.

    Тест не спирається на жодне припущення про поле: беруться пари сусідніх
    комірок **в одному напрямку** і на однаковій відстані, і питається, чи
    більша різниця, коли вони в різних проходах. Поле не знає, де межа
    проходу; машина знає.

    **Крок сітки тут не дрібниця, а суть.** Якщо комірка точно збігається з
    проходом, то всі пари вздовж лежать в одному проході, а всі впоперек — у
    різних, і мірило порівнює не шов, а напрямок. Якщо комірка ширша за два
    проходи — шва не видно взагалі. Тому крок не задається наосліп: пробуємо
    кілька і беремо той, де в ОДНОМУ напрямку набирається досить пар обох
    видів. Тільки тоді порівняння чесне.

    Повертає `{надлишок, усередині, через_шов, крок}` або None, якщо чесного
    порівняння не склалось.
    """
    x = np.asarray(x, float); y = np.asarray(y, float)
    з = np.asarray(значення, float); п = np.asarray(проходи)

    ширина = float(ширина_захвату) if ширина_захвату else None
    кроки = [крок] if крок else (
        [ширина * к for к in (1.5, 1.0, 2.0, 0.75, 3.0)] if ширина
        else [10.0, 15.0, 7.0, 20.0])

    найкраще = None
    for пробний in кроки:
        if not (пробний and np.isfinite(пробний) and пробний > 0.2):
            continue
        с = np.round((x - x.min()) / пробний).astype(int)
        р = np.round((y.max() - y) / пробний).astype(int)
        сітка = np.full((р.max() + 1, с.max() + 1), np.nan)
        прох = np.full(сітка.shape, -1, dtype="int64")
        сітка[р, с] = з
        прох[р, с] = п.astype("int64")

        for зр, зс in ((0, 1), (1, 0)):
            a = сітка[:сітка.shape[0] - зр, :сітка.shape[1] - зс]
            b = сітка[зр:, зс:]
            pa = прох[:прох.shape[0] - зр, :прох.shape[1] - зс]
            pb = прох[зр:, зс:]
            ок = np.isfinite(a) & np.isfinite(b) & (pa >= 0) & (pb >= 0)
            якщо_мало = ок.sum() < 400
            if якщо_мало:
                continue
            різ = np.abs(a - b)[ок]
            свій = (pa == pb)[ок]
            # обидва види пар мусять бути, і жоден не може бути крихтою:
            # десяток пар «усередині» дав би медіану з повітря
            if свій.sum() < 200 or (~свій).sum() < 200:
                continue
            всередині = float(np.median(різ[свій]))
            через = float(np.median(різ[~свій]))
            if всередині <= 0:
                continue
            надлишок = 100.0 * (через / всередині - 1.0)
            пар = min(int(свій.sum()), int((~свій).sum()))
            if найкраще is None or пар > найкраще["пар"]:
                найкраще = {"надлишок": надлишок, "усередині": всередині,
                            "через_шов": через, "крок": пробний, "пар": пар,
                            "пар_усередині": int(свій.sum()),
                            "пар_через": int((~свій).sum())}
        if найкраще is not None:
            break
    return найкраще
