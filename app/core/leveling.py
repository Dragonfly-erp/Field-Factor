# -*- coding: utf-8 -*-
"""ВИРІВНЮВАННЯ ПРОХОДІВ. Прибирає з карти те, що намалювала машина.

Навіщо. Поле не знає, де межа проходу комбайна. Якщо два сусідні записи за
десять метрів один від одного розходяться сильніше через шов проходу, ніж
усередині проходу, — ця надлишкова різниця не з поля. Вона з машини: сенсор
потоку пливе, ширина захвату на кожному проході трохи інша, комбайнер веде
з різним нахлистом.

На Г-03 перехід через шов додавав **69 %** до різниці між сусідами: 724 кг/га
всередині проходу проти 1 225 через шов. Це і є смугастість.

**Що цей модуль робить і чого не робить.**

Робить: знаходить власний множник кожного проходу відносно того, що показують
сусідні проходи на тому самому місці, і ділить прохід на нього.

Не робить: не рухає рівень поля. Множники нормуються так, щоб середнє по
масиву лишилось те саме — рівень задають поправка на перекриття та вагова
господарства, і вирівнювання не має права їх чіпати.

Не робить: не згладжує поле. Опора для кожного запису береться з **сусідніх**
проходів у тому ж місці, а не з середнього по полю. Тому низина лишається
низиною, а горб горбом — рівняються між собою проходи, а не ділянки.

**Чому ітераціями.** Опора рахується по всіх записах довкола, зокрема й по
самому проході. Через це перша оцінка множника занижена — прохід частково
рівняється сам на себе. Кожна наступна ітерація бере опору вже з вирівняних
сусідів, і оцінка сходиться. Трьох вистачає; збіжність перевіряється числом,
а не вірою.
"""

import numpy as np

# Опора береться з кола такого радіуса. Має бути помітно ширшою за прохід,
# інакше в опору потрапить майже сам прохід і рівняти буде нема з чим; і не
# надто широкою, щоб у неї не заліз інший край поля. Три-чотири проходи —
# те, що треба.
РАДІУС_ОПОРИ = 4.0        # у ширинах захвату

# Скільки записів проходу мусять мати опору, щоб множник узагалі рахувати.
# Прохід із десятка записів — це недогін або кутик, і його «множник» був би
# випадковим числом.
ЗАПИСІВ_НА_ПРОХІД = 40

# Межі, поза якими це вже не зміщення сенсора. Прохід, що дає вдвічі більше
# за сусідів, не калібрується — з ним щось інше, і мовчки ділити його на два
# означало б заховати поламане.
МНОЖНИК_ВІД = 0.6
МНОЖНИК_ДО = 1.7

# Кожна ітерація бере опору з уже вирівняних сусідів. На перевірці зсув
# сходився 18 % → 3,6 % → 1,1 %; п'ятої вистачає з запасом, а коштує вона
# секунди.
ІТЕРАЦІЙ = 8

# Наскільки повно застосовувати поправку кожної ітерації. Одиниця означає
# «увесь крок одразу» — і саме так воно й закрутилось на Г-03: 56 % → 23 %
# → 23 % → 39 % → 8 %, тобто коливання, а не збіжність. Причина: проходи
# входять і виходять із опори (дикі з неї викидаються), і опора стрибає.
# Півкроку гасить це коливання, ціною зайвих ітерацій.
ДЕМПФЕР = 0.55


def _опора(x, y, з, крок, вікно_комірок):
    """Місцевий рівень довкола кожного запису — растром, бо швидко."""
    from scipy.ndimage import uniform_filter

    с = np.clip(((x - x.min()) / крок).astype(int), 0, None)
    р = np.clip(((y.max() - y) / крок).astype(int), 0, None)
    сітка_сум = np.zeros((р.max() + 1, с.max() + 1), dtype="float64")
    сітка_лік = np.zeros_like(сітка_сум)
    беремо = np.isfinite(з)
    np.add.at(сітка_сум, (р[беремо], с[беремо]), з[беремо])
    np.add.at(сітка_лік, (р[беремо], с[беремо]), 1.0)

    сума = uniform_filter(сітка_сум, вікно_комірок, mode="nearest")
    лік = uniform_filter(сітка_лік, вікно_комірок, mode="nearest")
    рівень = np.where(лік > 1e-9, сума / np.maximum(лік, 1e-9), np.nan)
    return рівень[р, с]


def множники(x, y, значення, проходи, ширина_захвату):
    """Скільки кожен прохід приписує собі проти сусідів. Ітераціями."""
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    з = np.asarray(значення, float)
    п = np.asarray(проходи)

    крок = max(1.0, float(ширина_захвату) / 2.0)
    вікно = max(3, int(round(РАДІУС_ОПОРИ * ширина_захвату / крок)) | 1)

    поточні = {}
    хід = []
    робоче = з.copy()
    for ітерація in range(ІТЕРАЦІЙ):
        # Прохід, який дає вдвічі більше за сусідів, не калібрується — і
        # опорою нікому теж бути не може. Інакше він тягне за собою сусідні
        # проходи: на перевірці один прохід ×2,4 зсував чотирьох сусідів на
        # 16 %. Тому з опори такі проходи прибираються.
        дикий = np.zeros(len(з), dtype=bool)
        for прохід, м in поточні.items():
            if not (МНОЖНИК_ВІД <= м <= МНОЖНИК_ДО):
                дикий |= (п == прохід)
        для_опори = np.where(дикий, np.nan, робоче)
        рівень = _опора(x, y, для_опори, крок, вікно)
        придатні = np.isfinite(рівень) & (рівень > 0) & np.isfinite(з) & (з > 0)
        відношення = np.full(len(з), np.nan)
        відношення[придатні] = робоче[придатні] / рівень[придатні]

        зміна = 0.0
        for прохід in np.unique(п):
            маска = (п == прохід) & придатні
            if маска.sum() < ЗАПИСІВ_НА_ПРОХІД:
                continue
            крок_множника = float(np.median(відношення[маска]))
            if not np.isfinite(крок_множника) or крок_множника <= 0:
                continue
            пригальмований = крок_множника ** ДЕМПФЕР
            новий = поточні.get(прохід, 1.0) * пригальмований
            зміна = max(зміна, abs(пригальмований - 1.0))
            поточні[прохід] = новий
            робоче[п == прохід] = з[п == прохід] / новий
        хід.append(зміна)

    return поточні, хід


def вирівняти(таблиця, ширина_захвату, поле_значень="ВРОЖАЙ_КГГА",
              поле_проходу="ПРОХІД", журнал=None):
    """Ділить кожен прохід на його власний множник. Змінює таблицю на місці.

    Повертає звіт: скільки проходів вирівняно, скільки відхилено, який був
    розкид множників і чи зійшлись ітерації.
    """
    маска_чистих = (таблиця["QC"] == "OK").to_numpy() if "QC" in таблиця.columns \
        else np.ones(len(таблиця), dtype=bool)
    if маска_чистих.sum() < 500:
        return таблиця, {"зроблено": False, "чому": "замало чистих записів"}

    чисті = таблиця.loc[маска_чистих]
    x = чисті.geometry.x.to_numpy()
    y = чисті.geometry.y.to_numpy()
    з = чисті[поле_значень].to_numpy(dtype="float64")
    п = чисті[поле_проходу].to_numpy()

    сирі_множники, хід = множники(x, y, з, п, ширина_захвату)
    if not сирі_множники:
        return таблиця, {"зроблено": False, "чому": "жоден прохід не набрав опори"}

    # Рівень поля лишається чужою справою. Нормуємо множники так, щоб
    # середнє по масиву не зрушилось ані на кілограм.
    ваги = {к: int((п == к).sum()) for к in сирі_множники}
    здорові = [в for в in сирі_множники.values()
               if МНОЖНИК_ВІД <= в <= МНОЖНИК_ДО] or list(сирі_множники.values())
    опорний = float(np.median(здорові))
    нормовані = {к: в / опорний for к, в in сирі_множники.items()}

    відхилені = {к: в for к, в in нормовані.items()
                 if not (МНОЖНИК_ВІД <= в <= МНОЖНИК_ДО)}
    прийняті = {к: в for к, в in нормовані.items() if к not in відхилені}

    множник_запису = np.ones(len(таблиця), dtype="float64")
    усі_проходи = таблиця[поле_проходу].to_numpy()
    for прохід, м in прийняті.items():
        множник_запису[усі_проходи == прохід] = м

    було = таблиця[поле_значень].to_numpy(dtype="float64")
    стало = було / множник_запису

    # Рівень поля задають поправка на перекриття та вагова господарства.
    # Вирівнювання не має права його чіпати — а нормування по медіані
    # множників цього не гарантує: на Г-03 воно зсунуло середнє на 2,3 %.
    # Тому рівень відновлюємо точно, по тих самих записах, які рахували.
    для_рівня = маска_чистих & np.isfinite(було) & np.isfinite(стало) & (стало > 0)
    if для_рівня.sum() > 100:
        поправка_рівня = було[для_рівня].mean() / стало[для_рівня].mean()
        стало = стало * поправка_рівня
    else:
        поправка_рівня = 1.0
    таблиця[поле_значень] = стало

    значення_множників = np.array(list(прийняті.values()))
    звіт = {
        "зроблено": True,
        "проходів_усього": int(len(np.unique(п))),
        "вирівняно": len(прийняті),
        "без_опори": int(len(np.unique(п)) - len(нормовані)),
        "відхилено": len(відхилені),
        "множник_від": float(значення_множників.min()) if len(значення_множників) else 1.0,
        "множник_до": float(значення_множників.max()) if len(значення_множників) else 1.0,
        "розкид_множників": float(значення_множників.std()) if len(значення_множників) else 0.0,
        "збіжність": [round(з_, 4) for з_ in хід],
        "поправка_рівня": float(поправка_рівня),
    }
    if журнал is not None:
        журнал.сказати(
            "  вирівняно {} проходів із {}: множники {:.3f}…{:.3f}, розкид {:.3f}. "
            "Без опори {}, відхилено як неправдоподібні {}.".format(
                звіт["вирівняно"], звіт["проходів_усього"], звіт["множник_від"],
                звіт["множник_до"], звіт["розкид_множників"],
                звіт["без_опори"], звіт["відхилено"])
        )
        журнал.сказати(
            "  збіжність по ітераціях: {}.".format(
                " → ".join("{:.1%}".format(з_) for з_ in хід))
        )
    return таблиця, звіт


