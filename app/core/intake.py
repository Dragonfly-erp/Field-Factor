# -*- coding: utf-8 -*-
"""ІМПОРТ ПОЛІВ У ДЕРЕВО. Один файл межі — багато полів одразу.

Досі контур клався в поле по одному: заведи поле руками, завантаж межу,
повтори двадцять один раз. Господарство приходить не так. Воно приходить
одним `.kml` з Google Earth або одним shapefile з обліковця, де всередині
лежать усі поля, а колонка `FARM` чи `Відділок` каже, чиє яке.

Що робить модуль:

* читає будь-що з того, що вміє `reading` — shp, kml, kmz, gpkg, geojson,
  zip з усім цим усередині;
* бере **тільки полігони**. Точки й лінії в такому файлі — це підписи,
  дороги й свердловини, а не поля;
* **вгадує**, де назва поля і де ферма, за переліком імен колонок, які
  справді трапляються в українських і закордонних вивантаженнях;
* **зшиває однойменні шматки в одне поле.** Поле, розрізане дорогою навпіл,
  у файлі лежить двома полігонами з тією самою назвою. Це одне поле з двома
  контурами, а не два поля;
* нічого не кладе, доки не спитали. Спершу `розвідати()` показує, що знайшло,
  і тільки потім `закласти()` пише в картотеку.

**Ферма — це властивість поля, не тека.** У картотеці рівно два рівні:
господарство і поле. Ферма (відділок, бригада) лягає в паспорт поля й
збирає дерево в групи на екрані. Так відділок можна перейменувати або
розформувати, не переносячи теки з даними.
"""

import os
import re

# Імена колонок, у яких різні програми тримають назву поля й назву ферми.
# Перелік не вигаданий: це те, що трапляється у вивантаженнях Google Earth,
# QGIS, SMS, Agworld і в обліковців, які підписують колонки українською.
КОЛОНКИ_НАЗВИ = (
    "назва", "назва_поля", "поле", "імʼя", "им'я", "ім'я",
    "name", "field", "field_name", "fieldname", "fld_name", "title",
    "label", "layer", "id_field", "field_id", "код", "номер",
)
КОЛОНКИ_ФЕРМИ = (
    "ферма", "відділок", "виддилок", "бригада", "дільниця", "ділянка_госп",
    "підрозділ", "кластер", "farm", "farm_name", "unit", "division",
    "subunit", "block", "team", "cluster", "region", "zone_name",
)
КОЛОНКИ_ПЛОЩІ = (
    "площа", "площа_га", "га", "area", "area_ha", "ha", "hectares", "acres",
)


def _низ(текст):
    return re.sub(r"[\s_\-.]+", "", str(текст or "").strip().lower())


def _вгадати_колонку(колонки, перелік):
    """Спершу точний збіг, потім входження. Порядок важливий: колонка
    `field_name` має вигравати в колонки `name_old`, а не навпаки."""
    норма = {_низ(к): к for к in колонки}
    for бажане in перелік:
        якщо = норма.get(_низ(бажане))
        if якщо is not None:
            return якщо
    for бажане in перелік:
        for ключ, справжня in норма.items():
            if _низ(бажане) in ключ:
                return справжня
    return None


# Слова, за якими ферму видно **у вмісті** колонки, а не в її назві.
# Потрібні тому, що GDAL, читаючи KML, стирає кириличні імена колонок:
# `<Data name="Відділок">` приїжджає колонкою `________________`, і назви,
# за якою вгадувати, просто не існує. Значення при цьому ціле.
СЛОВА_ФЕРМИ = ("відділок", "ферма", "бригада", "дільниц", "підрозділ",
               "кластер", "farm", "unit", "division", "block", "team")


def _зіпсована_назва(колонка):
    """GDAL віддає стерте імʼя суцільними підкресленнями."""
    return bool(re.fullmatch(r"_+", str(колонка or "")))


def _вгадати_ферму_вмістом(шари):
    """Колонка, у значеннях якої стоїть «Відділок 3» чи «Ферма Північна».

    Дивимось тільки туди, куди більше нема куди: імені немає, отже або так,
    або людина вибирає руками. Тому вимога сувора — слово має траплятись
    у більшості непорожніх значень, а не в одному з двадцяти.
    """
    найкраща, найкраща_частка = None, 0.0
    for шар in шари:
        for колонка in шар.columns:
            if колонка == шар.geometry.name:
                continue
            значення = [str(з).strip() for з in шар[колонка].tolist()
                        if з is not None and str(з).strip() and str(з).strip().lower() != "nan"]
            if len(значення) < 2:
                continue
            влучань = sum(1 for з in значення
                          if any(с in з.lower() for с in СЛОВА_ФЕРМИ))
            частка = влучань / len(значення)
            # Колонка з унікальним значенням у кожному рядку — це назва поля,
            # а не ферма: ферма на те й ферма, що повторюється.
            повторюваність = 1 - len(set(з.lower() for з in значення)) / len(значення)
            if частка >= 0.6 and повторюваність > 0 and частка > найкраща_частка:
                найкраща, найкраща_частка = колонка, частка
    return найкраща


def _значення(рядок, колонка):
    if not колонка:
        return ""
    значення = рядок.get(колонка)
    if значення is None:
        return ""
    текст = str(значення).strip()
    return "" if текст.lower() in ("nan", "none", "null", "<na>") else текст


def _площа_га(геометрія, crs):
    """Площа рахується в метрах, а не в градусах. Квадратний градус на нашій
    широті — це вісім тисяч квадратних кілометрів, і поле з такою «площею»
    показувало б у дереві сміття."""
    import geopandas as gpd
    from app.core import util

    один = gpd.GeoDataFrame(geometry=[геометрія], crs=crs or 4326)
    if один.crs.is_geographic:
        один = один.to_crs(util.метрична_crs(один))
    return float(один.area.sum()) / 10000.0


# ═══════════════════════════════════════════════════════════════════════
# РОЗВІДКА: що лежить у файлі
# ═══════════════════════════════════════════════════════════════════════


def розвідати(тека, колонка_назви=None, колонка_ферми=None):
    """Читає теку прийому й повертає перелік полів, які з неї вийдуть.

    Нічого не пише. Це передпоказ: агроном має побачити, що саме зайде
    в дерево, до того як воно туди зайде.
    """
    from app.core import reading

    reading.розгорнути_архіви(тека)
    шляхи = reading.знайти_шари(тека)
    if not шляхи:
        return {"гаразд": False, "повідомлення": "У файлах немає жодного просторового шару",
                "ділянки": [], "колонки": []}

    прочитані, пропущені = [], []
    for шлях in шляхи:
        try:
            шар = reading.прочитати_шар(шлях)
        except Exception as збій:
            пропущені.append("{}: {}".format(os.path.basename(шлях), збій))
            continue
        if шар is None or not len(шар):
            continue
        полігони = шар[шар.geometry.geom_type.isin(("Polygon", "MultiPolygon"))]
        якщо_втрачено = len(шар) - len(полігони)
        if якщо_втрачено:
            пропущені.append("{}: {} не-полігонів пропущено (точки й лінії — це не поля)"
                             .format(os.path.basename(шлях), якщо_втрачено))
        if len(полігони):
            прочитані.append((os.path.basename(шлях), полігони))

    if not прочитані:
        return {"гаразд": False, "повідомлення": "Полігонів не знайдено — у файлі немає меж полів",
                "ділянки": [], "колонки": [], "попередження": пропущені}

    колонки = []
    for _, шар in прочитані:
        for к in шар.columns:
            if к != шар.geometry.name and к not in колонки:
                колонки.append(к)

    назва_к = колонка_назви or _вгадати_колонку(колонки, КОЛОНКИ_НАЗВИ)
    ферма_к = колонка_ферми or _вгадати_колонку(колонки, КОЛОНКИ_ФЕРМИ)
    площа_к = _вгадати_колонку(колонки, КОЛОНКИ_ПЛОЩІ)

    за_вмістом = ""
    if not ферма_к:
        ферма_к = _вгадати_ферму_вмістом([ш for _, ш in прочитані])
        if ферма_к:
            за_вмістом = ("ферму взято з колонки «{}» за вмістом, а не за назвою"
                          .format("без назви" if _зіпсована_назва(ферма_к) else ферма_к)
                          + " — GDAL стирає кириличні імена колонок у KML")

    ділянки = []
    for файл, шар in прочитані:
        for порядок, (_, рядок) in enumerate(шар.iterrows(), start=1):
            назва = _значення(рядок, назва_к) or "Поле {}".format(len(ділянки) + 1)
            ділянки.append({
                "назва": назва,
                "ферма": _значення(рядок, ферма_к),
                "площа_га": round(_площа_га(рядок.geometry, шар.crs), 2),
                "площа_заявлена": _значення(рядок, площа_к),
                "файл": файл,
                "порядок": порядок,
            })

    # ── однойменні шматки — це одне поле. Поле, розрізане дорогою або
    # лісосмугою, лежить у файлі двома полігонами під тією самою назвою.
    зведені, злиття = [], []
    за_назвою = {}
    for д in ділянки:
        ключ = (_низ(д["ферма"]), _низ(д["назва"]))
        якщо = за_назвою.get(ключ)
        if якщо is None:
            д = dict(д, шматків=1)
            за_назвою[ключ] = д
            зведені.append(д)
        else:
            якщо["шматків"] += 1
            якщо["площа_га"] = round(якщо["площа_га"] + д["площа_га"], 2)
    for д in зведені:
        if д["шматків"] > 1:
            злиття.append("«{}»: {} шматки зшито в одне поле".format(д["назва"], д["шматків"]))

    ферми = sorted({д["ферма"] for д in зведені if д["ферма"]})
    return {
        "гаразд": True,
        "ділянки": зведені,
        "колонки": колонки,
        "вгадано": {"назва": назва_к, "ферма": ферма_к, "площа": площа_к},
        "ферми": ферми,
        "площа_га": round(sum(д["площа_га"] for д in зведені), 2),
        "попередження": пропущені + злиття + ([за_вмістом] if за_вмістом else []),
    }


# ═══════════════════════════════════════════════════════════════════════
# ЗАКЛАДЕННЯ: поля лягають у дерево
# ═══════════════════════════════════════════════════════════════════════


def закласти(картотека, господарство, тека, колонка_назви=None, колонка_ферми=None,
             ферма_якщо_немає="", пропустити=(), перезаписувати=False):
    """Створює поля в картотеці й кладе кожному його контур.

    Поле, яке вже є, за замовчуванням **не чіпається**: контур поточного
    року — істина, і мовчки затирати його чужим файлом не можна. Щоб
    замінити межу свідомо, треба сказати `перезаписувати=True`.
    """
    import geopandas as gpd
    from shapely.ops import unary_union
    from app.core import reading

    reading.розгорнути_архіви(тека)
    шляхи = reading.знайти_шари(тека)
    зібране, колонки = {}, []
    for шлях in шляхи:
        try:
            шар = reading.прочитати_шар(шлях)
        except Exception:
            continue
        if шар is None or not len(шар):
            continue
        полігони = шар[шар.geometry.geom_type.isin(("Polygon", "MultiPolygon"))]
        if not len(полігони):
            continue
        for к in полігони.columns:
            if к != полігони.geometry.name and к not in колонки:
                колонки.append(к)
        зібране[шлях] = полігони

    if not зібране:
        return {"гаразд": False, "повідомлення": "Полігонів не знайдено", "закладено": []}

    назва_к = колонка_назви or _вгадати_колонку(колонки, КОЛОНКИ_НАЗВИ)
    ферма_к = колонка_ферми or _вгадати_колонку(колонки, КОЛОНКИ_ФЕРМИ)
    # Те саме вгадування вмістом, що й у розвідці. Інакше передпоказ показав би
    # ферми, а в дерево лягли б поля без них — і ніхто б не крикнув.
    if not ферма_к:
        ферма_к = _вгадати_ферму_вмістом(list(зібране.values()))
    пропустити = {_низ(п) for п in пропустити or ()}

    # ── зібрати геометрії під однією назвою докупи
    поля = {}
    лічильник = 0
    for _, шар in зібране.items():
        for _, рядок in шар.iterrows():
            лічильник += 1
            назва = _значення(рядок, назва_к) or "Поле {}".format(лічильник)
            ферма = _значення(рядок, ферма_к) or ферма_якщо_немає
            ключ = (_низ(ферма), _низ(назва))
            запис = поля.setdefault(ключ, {"назва": назва, "ферма": ферма,
                                           "геометрії": [], "crs": шар.crs})
            запис["геометрії"].append(рядок.geometry)

    закладено, пропущено, збої = [], [], []
    for запис in поля.values():
        if _низ(запис["назва"]) in пропустити:
            пропущено.append(запис["назва"])
            continue
        ключ_поля = картотека.завести_поле(господарство, запис["назва"])
        уже = картотека.шар(господарство, ключ_поля, "контур")
        if уже and not перезаписувати:
            пропущено.append("{} — контур уже є, не чіпаю".format(запис["назва"]))
            continue
        try:
            межа = gpd.GeoDataFrame(geometry=[unary_union(запис["геометрії"])],
                                    crs=запис["crs"] or 4326)
            площа = картотека.покласти_контур(господарство, ключ_поля, межа)
        except Exception as збій:
            збої.append("{}: {}".format(запис["назва"], збій))
            continue
        зміни = {"джерело_контуру": "імпорт межі"}
        if запис["ферма"]:
            зміни["ферма"] = запис["ферма"]
        картотека.оновити_поле(господарство, ключ_поля, зміни)
        закладено.append({"поле": ключ_поля, "назва": запис["назва"],
                          "ферма": запис["ферма"], "площа_га": round(площа, 2),
                          "шматків": len(запис["геометрії"])})

    return {
        "гаразд": bool(закладено),
        "закладено": закладено,
        "пропущено": пропущено,
        "збої": збої,
        "полів": len(закладено),
        "площа_га": round(sum(з["площа_га"] for з in закладено), 2),
        "ферм": len(sorted({з["ферма"] for з in закладено if з["ферма"]})),
    }
