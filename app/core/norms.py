def вирок(відстань, сігма_hi):
    """СТІЙКЕ / НА МЕЖІ / ВИПАДКОВЕ — за відстанню до порога у σ методу."""
    if not сігма_hi or сігма_hi <= 0:
        return "НЕВІДОМО", float("nan")
    n = abs(відстань) / сігма_hi
    if n <= ВИРОК_ВИПАДКОВЕ:
        return "ВИПАДКОВЕ", n
    if n <= ВИРОК_НА_МЕЖІ:
        return "НА МЕЖІ", n
    return "СТІЙКЕ", n


