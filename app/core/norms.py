def _sha256(шлях):
    х = hashlib.sha256()
    with open(шлях, "rb") as ф:
        for шматок in iter(lambda: ф.read(1 << 20), b""):
            х.update(шматок)
    return х.hexdigest()


def звірити_джерела(корінь=None):
    """Чи змінилась майстерня з дня знімка. Дешева перевірка — тільки sha256.

    Повертає список: файл, стан ('збіг' / 'ЗМІНЕНО' / 'недоступне'), хеші."""
    корінь = корінь or КОРІНЬ_МАЙСТЕРНІ
    підсумок = []
    for дж in ПРОВЕНАНС["джерела"]:
        шлях = os.path.join(корінь, дж["файл"].replace("/", os.sep))
        рядок = dict(ключ=дж["ключ"], файл=дж["файл"], шлях=шлях,
                     коміт=дж["коміт_короткий"], очікуваний=дж["sha256"],
                     фактичний=None)
        if not os.path.isfile(шлях):
            рядок["стан"] = "недоступне"
            рядок["що_це_означає"] = ("майстерні на цій машині немає — "
                                      "це норма для господарства")
        else:
            рядок["фактичний"] = _sha256(шлях)
            збіг = рядок["фактичний"] == дж["sha256"]
            рядок["стан"] = "збіг" if збіг else "ЗМІНЕНО"
            рядок["що_це_означає"] = (
                "джерело не рухалось із дня знімка" if збіг else
                "джерело в майстерні змінилось — знімок треба переглянути")
        підсумок.append(рядок)
    return підсумок


class НеЛітерал(Exception):
    """Вираз, який статично не читається — наприклад `1 / CaO_Ca`."""


def _значення(вузол):
    """Значення вузла без виконання коду. Розуміє те, чим писані джерела:
    числа, рядки, від'ємні числа, списки, кортежі, словники і `dict(...)`."""
    import ast
    if isinstance(вузол, ast.Constant):
        return вузол.value
    if isinstance(вузол, ast.UnaryOp) and isinstance(вузол.op, ast.USub):
        return -_значення(вузол.operand)
    if isinstance(вузол, ast.Dict):
        return {_значення(к): _значення(в)
                for к, в in zip(вузол.keys, вузол.values)}
    if isinstance(вузол, (ast.List, ast.Tuple)):
        зібране = [_значення(е) for е in вузол.elts]
        return зібране if isinstance(вузол, ast.List) else tuple(зібране)
    if (isinstance(вузол, ast.Call) and isinstance(вузол.func, ast.Name)
            and вузол.func.id == "dict" and not вузол.args):
        return {к.arg: _значення(к.value) for к in вузол.keywords}
    raise НеЛітерал(type(вузол).__name__)


def _літерали(шлях):
    """Верхньорівневі присвоєння файлу як словник. Нічого не виконує."""
    import ast
    with open(шлях, encoding="utf-8") as ф:
        дерево = ast.parse(ф.read(), filename=шлях)
    зібране = {}
    for вузол in дерево.body:
        if not isinstance(вузол, ast.Assign):
            continue
        for ціль in вузол.targets:
            if isinstance(ціль, ast.Name):
                пари = [(ціль.id, вузол.value)]
            elif (isinstance(ціль, ast.Tuple)
                  and isinstance(вузол.value, (ast.Tuple, ast.List))
                  and len(ціль.elts) == len(вузол.value.elts)):
                пари = [(е.id, з) for е, з in zip(ціль.elts, вузол.value.elts)
                        if isinstance(е, ast.Name)]
            else:
                continue
            for імʼя, вираз in пари:
                try:
                    зібране[імʼя] = _значення(вираз)
                except НеЛітерал:
                    pass          # похідні на кшталт `1 / CaO_Ca` не звіряємо
    return зібране


def звірити_значення(корінь=None):
    """Звірити числа знімка з джерелами в майстерні. Джерела розбираються
    деревом, не виконуються — див. коментар до розділу.

    Працює тільки там, де майстерня є (машина Власника). На машині
    господарства чесно каже «джерело недоступне» і нічого не вигадує."""
    корінь = корінь or КОРІНЬ_МАЙСТЕРНІ
    розбіжності, звірено, читане = [], 0, {}

    for дж in ПРОВЕНАНС["джерела"]:
        if дж["ключ"] not in ЗВІРЯНІ_ЗНАЧЕННЯ:
            continue
        шлях = os.path.join(корінь, дж["файл"].replace("/", os.sep))
        if not os.path.isfile(шлях):
            return dict(доступно=False, причина="немає " + дж["файл"],
                        звірено=0, розбіжності=[])
        try:
            читане[дж["ключ"]] = _літерали(шлях)
        except SyntaxError as помилка:
            return dict(доступно=False,
                        причина="%s не розбирається: %s" % (дж["файл"], помилка),
                        звірено=0, розбіжності=[])

    def розбіжність(джерело, імʼя, там, тут):
        розбіжності.append(dict(джерело=джерело, імʼя=імʼя,
                                майстерня=там, продукт=тут))

    for ключ, пари in ЗВІРЯНІ_ЗНАЧЕННЯ.items():
        файл = читане.get(ключ)
        if файл is None:
            continue
        for імʼя, наше in пари.items():
            if імʼя == "ERR":
                continue          # похибки звіряються нижче, по перетину імен
            звірено += 1
            там = файл.get(імʼя, "<немає>")
            тут = наше()
            if там != тут:
                розбіжність(ключ, імʼя, там, тут)

    # похибки — тільки те, що є в обох
    файл = читане.get("y9_flip")
    if файл is not None:
        їхні = файл.get("ERR", {})
        for наше, їхнє in ІМЕНА_ПОХИБОК.items():
            запис = їхні.get(їхнє)
            if запис is None:
                розбіжність("y9_flip", "ERR[%s]" % їхнє, "<немає>", наше)
                continue
            for поле in ("вид", "lo", "hi", "джерело"):
                звірено += 1
                if запис.get(поле) != ПОХИБКИ[наше].get(поле):
                    розбіжність("y9_flip", "ERR[%s].%s" % (їхнє, поле),
                                запис.get(поле), ПОХИБКИ[наше].get(поле))

    файл = читане.get("y8_norms")
    if файл is not None:
        їхні = файл.get("PRODUCTS", {})
        for ключ, наш in ПРОДУКТИ.items():
            їхній = їхні.get(ключ)
            if їхній is None:
                розбіжність("y8_norms", "PRODUCTS[%s]" % ключ,
                            "<немає>", наш["назва"])
                continue
            for поле in ЗВІРЯНІ_ПОЛЯ_ПРОДУКТУ:
                звірено += 1
                if їхній.get(поле) != наш.get(поле):
                    розбіжність("y8_norms", "PRODUCTS[%s].%s" % (ключ, поле),
                                їхній.get(поле), наш.get(поле))
            # CCE в майстерні дораховується циклом, у літералах його немає.
            # Тому звіряємо не число, а результат нашої формули на ЇХНЬОМУ
            # складі: якщо склад зійшовся, зійдеться й CCE.
            звірено += 1
            їхнє_CCE = ((їхній.get("CaO", 0.0) * CaO_CaCO3
                         + їхній.get("MgO", 0.0) * MgO_CaCO3)
                        if їхній.get("тип") == "карбонат" else 0.0)
            if abs(їхнє_CCE - наш["CCE"]) > 1e-9:
                розбіжність("y8_norms", "PRODUCTS[%s].CCE" % ключ,
                            їхнє_CCE, наш["CCE"])
        for ключ in їхні:
            if ключ not in ПРОДУКТИ:
                розбіжність("y8_norms", "PRODUCTS[%s]" % ключ,
                            "зʼявився в майстерні", "<немає у знімку>")

    return dict(доступно=True, причина=None, звірено=звірено,
                розбіжності=розбіжності)


