def _напрямок_поля(межа):
    """Найдовша сторона найменшого повернутого прямокутника поля.

    Полем їздять уздовж, а не впоперек: розворотів менше. Це здогад, і він
    так і підписаний — агроном міняє число одним полем на екрані."""
    from shapely import affinity  # noqa: F401  (лишаємо поруч, читається разом)

    прямокутник = межа.minimum_rotated_rectangle
    точки = list(прямокутник.exterior.coords)[:4]
    найдовша, кут = -1.0, 0.0
    for і in range(4):
        x0, y0 = точки[і]
        x1, y1 = точки[(і + 1) % 4]
        довжина = float(np.hypot(x1 - x0, y1 - y0))
        if довжина > найдовша:
            найдовша = довжина
            кут = float(np.degrees(np.arctan2(y1 - y0, x1 - x0)))
    return кут % 180.0


def _крок_уздовж_руху(шматки, опції, контур, метричні):
    """Відрізок, коротший за поріг уздовж руху, зшивається з довшим сусідом."""
    from rasterio.features import rasterize, shapes
    from rasterio.transform import from_origin
    from shapely import affinity
    from shapely.geometry import shape

    крок = {"крок": "уздовж", "назва": "Мінімальний розмір уздовж руху",
            "зроблено": False}

    мін_м = _число(опції.get("мін_м"), ЗАМОВЧУВАННЯ["уздовж"]["мін_м"])
    if not (МІН_УЗДОВЖ[0] <= мін_м <= МІН_УЗДОВЖ[1]):
        крок["чому_ні"] = ("поріг {:.0f} м поза межами {:.0f}–{:.0f} м — це вже "
                           "не про перекладання заслінки".format(мін_м, *МІН_УЗДОВЖ))
        return шматки, крок

    межа, звідки_межа = _межа(контур, метричні)
    заданий = опції.get("напрямок_град")
    if заданий is None or заданий == "":
        напрямок = _напрямок_поля(межа)
        звідки = "здогад: найдовша сторона поля"
    else:
        напрямок = _число(заданий, 0.0) % 180.0
        звідки = "задано на екрані"

    крок["мін_м"] = round(мін_м, 1)
    крок["напрямок_град"] = round(напрямок, 1)
    крок["звідки_напрямок"] = звідки

    центр = межа.centroid
    повернуті = [affinity.rotate(г, -напрямок, origin=центр)
                 for г in шматки.geometry]

    розмір = max(МІН_КРОК_РАСТРА, мін_м / 20.0)
    x0 = min(г.bounds[0] for г in повернуті) - розмір
    y0 = min(г.bounds[1] for г in повернуті) - розмір
    x1 = max(г.bounds[2] for г in повернуті) + розмір
    y1 = max(г.bounds[3] for г in повернуті) + розмір
    ширина = int(np.ceil((x1 - x0) / розмір))
    висота = int(np.ceil((y1 - y0) / розмір))
    if ширина * висота > КОМІРОК_СТЕЛЯ:
        крок["чому_ні"] = ("поле завелике для такого кроку растра "
                           "({} × {} комірок)".format(ширина, висота))
        return шматки, крок

    перетворення = from_origin(x0, y1, розмір, розмір)
    номери = list(range(1, len(повернуті) + 1))
    растр = rasterize(
        [(г, н) for г, н in zip(повернуті, номери)],
        out_shape=(висота, ширина), transform=перетворення,
        fill=0, dtype="int32", all_touched=False)

    # номер шматка → номер зони; зшиваємо ЗОНАМИ, бо машині байдуже,
    # з якого шматка зона складається
    у_зону = {н: int(з) for н, з in zip(номери, шматки["ЗОНА"])}
    зонний = np.zeros_like(растр)
    for н, з in у_зону.items():
        зонний[растр == н] = з

    # Растр має представляти ПОЛЕ, а не тільки ті комірки, у центр яких
    # влучив полігон. Інакше вузька смуга провалюється між центрами, і на
    # її місці лишається дірка — тобто «сюди нічого не сипати». Тому кожна
    # комірка поля, що лишилась порожньою, дістається найближчій зоні; і
    # робиться це ДО зшивання, щоб відрізки в рядку були суцільні.
    маска_поля = rasterize(
        [(affinity.rotate(межа, -напрямок, origin=центр), 1)],
        out_shape=(висота, ширина), transform=перетворення,
        fill=0, dtype="uint8", all_touched=True)
    пусто = (зонний == 0) & (маска_поля > 0)
    залатано = int(пусто.sum())
    if залатано and (зонний > 0).any():
        from scipy.ndimage import distance_transform_edt

        індекси = distance_transform_edt(зонний == 0, return_distances=False,
                                         return_indices=True)
        зонний = np.where(пусто, зонний[tuple(індекси)], зонний).astype("int32")

    мін_клітинок = max(2, int(round(мін_м / розмір)))
    змінено = 0
    незшитих = 0
    for ряд in range(зонний.shape[0]):
        новий, скільки, лишилось = _зшити_ряд(зонний[ряд], мін_клітинок)
        if скільки:
            зонний[ряд] = новий
            змінено += скільки
        незшитих += лишилось

    зібране = {}
    for геометрія, значення in shapes(зонний, mask=зонний > 0,
                                      transform=перетворення):
        зібране.setdefault(int(значення), []).append(shape(геометрія))

    нові = []
    for зона, частини in зібране.items():
        for частина in частини:
            назад = affinity.rotate(частина, напрямок, origin=центр)
            назад = назад.buffer(0).intersection(межа)
            for шматок in _частини(назад):
                if шматок.area > 0:
                    нові.append({"ЗОНА": зона, "geometry": шматок})

    import geopandas as gpd

    крок["зроблено"] = True
    крок["крок_растра_м"] = round(розмір, 2)
    крок["клітинок_залатано"] = залатано
    крок["клітинок_перезшито"] = int(змінено)
    крок["площа_перезшита_га"] = round(змінено * розмір * розмір / 10000.0, 3)
    крок["коротких_лишилось"] = int(незшитих)
    крок["межа_звідки"] = звідки_межа
    крок["що"] = (
        "Поле розкладено на рядки під {:.0f}° ({}). Відрізок, коротший за "
        "{:.0f} м уздовж руху, віддано довшому сусідові: {:.2f} га. "
        "Міряно комірками по {:.0f} м, тож поріг витриманий з точністю до "
        "одного кроку."
        .format(напрямок, звідки, мін_м, крок["площа_перезшита_га"], розмір))
    if незшитих:
        крок["застереження"] = (
            "{} коротких відрізків лишились як були: з обох боків від них край "
            "поля, і зшивати їх нема з ким.".format(незшитих))
    return gpd.GeoDataFrame(нові, geometry="geometry", crs=шматки.crs), крок


def _зшити_ряд(ряд, мін_клітинок):
    """Один рядок растра вздовж руху: короткі відрізки йдуть довшим сусідам.

    Нуль — це не зона, а «поза полем». Він не зшивається і не поглинає:
    відрізок, у якого з обох боків нуль, лишається як є. Це чесніше, ніж
    дірка в полі, і про це пишеться у звіті."""
    значення, довжини = _відрізками(ряд)
    if len(значення) < 2:
        return ряд, 0, 0

    перезшито = 0
    while True:
        кандидати = [
            і for і in range(len(значення))
            if значення[і] != 0 and довжини[і] < мін_клітинок
            and ((і > 0 and значення[і - 1] != 0)
                 or (і < len(значення) - 1 and значення[і + 1] != 0))
        ]
        if not кандидати:
            break
        і = min(кандидати, key=lambda к: довжини[к])
        ліворуч = і - 1 if і > 0 and значення[і - 1] != 0 else None
        праворуч = і + 1 if і < len(значення) - 1 and значення[і + 1] != 0 else None
        if ліворуч is None:
            сусід = праворуч
        elif праворуч is None:
            сусід = ліворуч
        else:
            сусід = ліворуч if довжини[ліворуч] >= довжини[праворуч] else праворуч
        перезшито += довжини[і]
        значення[і] = значення[сусід]
        значення, довжини = _склеїти(значення, довжини)

    лишилось = sum(1 for і, д in enumerate(довжини)
                   if значення[і] != 0 and д < мін_клітинок)
    if not перезшито:
        return ряд, 0, лишилось
    return np.repeat(значення, довжини).astype(ряд.dtype), перезшито, лишилось


def _відрізками(ряд):
    ряд = np.asarray(ряд)
    if not ряд.size:
        return [], []
    межі = np.flatnonzero(np.diff(ряд)) + 1
    початки = np.concatenate(([0], межі))
    кінці = np.concatenate((межі, [ряд.size]))
    return [int(ряд[п]) for п in початки], [int(к - п) for п, к in zip(початки, кінці)]


def _склеїти(значення, довжини):
    нові_з, нові_д = [], []
    for з, д in zip(значення, довжини):
        if нові_з and нові_з[-1] == з:
            нові_д[-1] += д
        else:
            нові_з.append(з)
            нові_д.append(д)
    return нові_з, нові_д


