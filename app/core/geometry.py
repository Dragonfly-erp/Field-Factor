def _розкласти(метричні, колонка):
    """Кожен полігон окремим рядком, номер зони — у колонці ЗОНА.

    Мультиполігон із двох клаптів у різних кінцях поля — це два різні шматки
    з погляду машини, і зшивати дрібне треба поклаптево, а не оптом."""
    import geopandas as gpd

    рядки = []
    for порядок, (_, р) in enumerate(метричні.iterrows(), start=1):
        зона = int(р[колонка]) if колонка else порядок
        геометрія = р.geometry
        if геометрія is None or геометрія.is_empty:
            continue
        for частина in _частини(геометрія):
            if частина.area > 0:
                рядки.append({"ЗОНА": зона, "geometry": частина})
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=метричні.crs)


def _частини(геометрія):
    if геометрія.geom_type == "Polygon":
        return [геометрія]
    if геометрія.geom_type in ("MultiPolygon", "GeometryCollection"):
        return [г for г in геометрія.geoms if г.geom_type == "Polygon"]
    return []


def _звести(шматки, crs):
    """Шматки → по одному рядку на зону."""
    import geopandas as gpd
    from shapely.ops import unary_union

    рядки = []
    for зона in sorted(set(int(з) for з in шматки["ЗОНА"])):
        свої = [г for г in шматки.loc[шматки["ЗОНА"] == зона, "geometry"]
                if г is not None and not г.is_empty]
        if not свої:
            continue
        обʼєднане = unary_union(свої).buffer(0)
        if обʼєднане.is_empty or обʼєднане.area <= 0:
            continue
        рядки.append({"ЗОНА": зона, "geometry": обʼєднане})
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=crs)


ПИЛ_М2 = 0.01     # квадрат десять на десять сантиметрів


def _прибрати_пил(шматки):
    """Кільця й клапті нульової площі, що лишаються після полігонізації.

    Растр, повернутий назад на кут і обрізаний по контуру, лишає по собі
    сміття завтовшки в останній знак — кільця площею 10⁻¹² м². У файлі це
    зайві вершини, у перевірках — «дірки в покритті», яких насправді немає.
    Поріг у сотку квадратного метра прибирає їх і не може зачепити нічого,
    що має агрономічний сенс."""
    import geopandas as gpd
    from shapely.geometry import Polygon

    рядки, прибрано = [], 0
    for _, р in шматки.iterrows():
        if р.geometry is None or р.geometry.is_empty:
            continue
        for частина in _частини(р.geometry):
            if частина.area <= ПИЛ_М2:
                прибрано += 1
                continue
            кільця = []
            for дірка in частина.interiors:
                if Polygon(дірка).area <= ПИЛ_М2:
                    прибрано += 1
                else:
                    кільця.append(дірка)
            якщо = (Polygon(частина.exterior, кільця)
                    if len(кільця) != len(частина.interiors) else частина)
            рядки.append({"ЗОНА": int(р["ЗОНА"]), "geometry": якщо})
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=шматки.crs), прибрано


def _шви(зведені):
    """Скільки в покритті накладань і скільки дірок — числом, а не на віру.

    Дві зони не мають накладатись, і між ними не має бути щілини: накладання
    монітор прочитає як подвійну норму, щілина — як нуль. Міряємо це щоразу,
    а не сподіваємось. Залишок на рівні квадратних сантиметрів — це слід
    міліметрової сітки, на яку ми свідомо зводимо вершини; усе, що більше, —
    це вже привід зупинитись.

    Чого цей вимір НЕ бачить: щілину, відкриту назовні. Дірка рахується тільки
    тоді, коли вона з усіх боків обведена зонами. Прогнано на трьох підкладених
    покриттях: накладання 5 м дало 500 м², дірка 20 × 20 м — 400 м², рівний
    стик — нуль; щілина, відкрита з торця, лишилась непоміченою."""
    from shapely.geometry import Polygon
    from shapely.ops import unary_union

    геометрії = [г for г in зведені.geometry if г is not None and not г.is_empty]
    if not геометрії:
        return {"накладань_м2": 0.0, "дірок_м2": 0.0, "дірок": 0}
    сума = sum(г.area for г in геометрії)
    обʼєднання = unary_union(геометрії)
    дірки = [Polygon(і).area for ч in _частини(обʼєднання) for і in ч.interiors]
    return {
        "накладань_м2": round(max(0.0, сума - обʼєднання.area), 4),
        "дірок_м2": round(sum(дірки), 4),
        "дірок": len(дірки),
    }


def _битих(шар):
    return int(sum(0 if (г is not None and г.is_valid) else 1
                   for г in шар.geometry))


def _на_міліметрову_сітку(шматки):
    """Звести вершини на сітку в міліметр — інакше файл ламається на виході.

    Рахуємо в метрах, а на техніку віддаємо в градусах. Дві вершини за
    міліметр одна від одної в метрах живуть спокійно, а після переведення в
    градуси зливаються — і рівний кут стає самоперетином. Монітор читає
    самоперетин як завгодно.

    Ловилось це вже на воротах видачі: «битих полігонів 3». Тому зводимо тут,
    у метрах, де ще видно, що робиш. Міліметр — найдрібніша сітка, яка це
    лікує: на демо-полі вона зрушила площу на чверть квадратного метра з
    сорока трьох гектарів."""
    import geopandas as gpd
    import numpy as np
    import shapely

    геометрії = np.array(list(шматки.geometry.values), dtype=object)
    if not геометрії.size:
        return шматки
    try:
        зведені = shapely.set_precision(геометрії, 0.001)
    except Exception:
        return шматки
    вихід = []
    for нова, стара in zip(зведені, геометрії):
        якщо = нова if (нова is not None and not нова.is_empty
                        and нова.area > 0 and нова.is_valid) else стара
        вихід.append(якщо)
    return gpd.GeoDataFrame({"ЗОНА": list(шматки["ЗОНА"])}, geometry=вихід,
                            crs=шматки.crs)


def _площі_по_зонах(шар):
    разом = {}
    for _, р in шар.iterrows():
        if р.geometry is None or р.geometry.is_empty:
            continue
        зона = int(р["ЗОНА"])
        разом[зона] = разом.get(зона, 0.0) + р.geometry.area / 10000.0
    return разом


def _межа(контур, метричні):
    """Край поля в метрах: або справжній контур, або обвід самих зон."""
    from shapely.ops import unary_union

    if контур is not None:
        try:
            свій = контур.to_crs(метричні.crs) if hasattr(контур, "to_crs") else None
            if свій is not None and len(свій):
                return unary_union(list(свій.geometry.values)).buffer(0), "контур поля"
        except Exception:
            pass
    return unary_union(list(метричні.geometry.values)).buffer(0), "обвід зон"


