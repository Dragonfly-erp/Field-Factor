def _зламаних_ребер(геометрії):
    """Скільки ребер не мають пари в сусіда. Нуль — покриття ціле."""
    import numpy as np
    import shapely

    try:
        погані = shapely.coverage_invalid_edges(
            np.array(list(геометрії), dtype=object))
    except Exception:
        return 0
    return int(sum(1 for г in погані if г is not None and not г.is_empty))


def _звузлувати(геометрії, зони):
    """Розставити вузли наново: усі межі в одну мережу і назад у полігони.

    Межі всіх зон зливаються в одну лінійну мережу — на кожному перетині
    зʼявляється вузол. З мережі складаються клітинки, і кожна дістається тій
    зоні, усередині якої лежить. Геометрія поля від цього не змінюється: та
    сама межа, просто описана однаковими відрізками з обох боків.

    Повертає (нові_геометрії, нові_зони) або None, якщо не склалось."""
    from shapely.ops import polygonize, unary_union
    from shapely.strtree import STRtree

    try:
        мережа = unary_union([г.boundary for г in геометрії])
        клітинки = list(polygonize(мережа))
        if not клітинки:
            return None
        дерево = STRtree(list(геометрії))
        нові_г, нові_з = [], []
        загублено = 0.0
        for клітинка in клітинки:
            якщо = клітинка.representative_point()
            свій = None
            for і in дерево.query(якщо):
                if геометрії[і].contains(якщо):
                    свій = і
                    break
            if свій is None:
                загублено += клітинка.area
                continue
            нові_г.append(клітинка)
            нові_з.append(зони[свій])
        if not нові_г:
            return None
        було = sum(г.area for г in геометрії)
        стало = sum(г.area for г in нові_г)
        # Розстановка вузлів не має права зʼїсти площу. Сотка квадратного
        # метра на все поле — це той самий пил, більше — це вже не вузли.
        if abs(було - стало) > max(ПИЛ_М2, було * 1e-9):
            return None
        return нові_г, нові_з
    except Exception:
        return None


