def налаштування(сире=None):
    """Злити те, що прийшло з екрана, із замовчуваннями. Чужого не пускаємо."""
    сире = сире or {}
    вихід = {}
    for розділ, типове in ЗАМОВЧУВАННЯ.items():
        своє = dict(типове)
        своє.update({к: в for к, в in (сире.get(розділ) or {}).items()
                     if к in типове})
        вихід[розділ] = своє
    return вихід


def _число(значення, замовчування):
    try:
        ч = float(значення)
    except (TypeError, ValueError):
        return замовчування
    return ч if np.isfinite(ч) else замовчування


