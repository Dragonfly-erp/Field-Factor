def підготувати(зони, сирі_налаштування=None, контур=None):
    """Шар зон → шар зон, готовий до монітора, плюс звіт про кожну дію.

    Повертає (нові_зони, звіт). Зони віддаються в тій самій системі
    координат, у якій прийшли: рахуємо в метрах, віддаємо як узяли."""
    import geopandas as gpd

    н = налаштування(сирі_налаштування)
    вхідна_crs = зони.crs
    метричні = _у_метри(зони)
    колонка = _колонка_зони(метричні)

    шматки = _розкласти(метричні, колонка)
    площі_до = _площі_по_зонах(шматки)
    полігонів_до = int(len(шматки))

    звіт = {"кроки": [], "напрямок": None}

    if н["уздовж"]["увімкнено"]:
        шматки, крок = _крок_уздовж_руху(шматки, н["уздовж"], контур, метричні)
        # Пил прибираємо одразу, а не наприкінці: кільця нульової площі
        # ламають покриття, а наступний крок на зламаному покритті вже
        # не може спростити межі.
        шматки, пилу = _прибрати_пил(шматки)
        крок["пилу_прибрано"] = пилу
        звіт["кроки"].append(крок)
        звіт["напрямок"] = крок.get("напрямок_град")

    if н["дрібні"]["увімкнено"]:
        шматки, крок = _крок_дрібні(шматки, н["дрібні"])
        звіт["кроки"].append(крок)

    if н["спрощення"]["увімкнено"]:
        шматки, крок = _крок_спрощення(шматки, н["спрощення"])
        звіт["кроки"].append(крок)

    if н["буфер"]["увімкнено"]:
        шматки, крок = _крок_буфер(шматки, н["буфер"], контур, метричні)
        звіт["кроки"].append(крок)

    # Спершу сітка, потім пил: зведення на сітку саме лишає по собі кільця
    # в кілька квадратних сантиметрів, і прибирати пил до нього — значить
    # прибирати не той пил.
    шматки = _на_міліметрову_сітку(шматки)
    шматки, пилу = _прибрати_пил(шматки)
    зведені = _звести(шматки, метричні.crs)
    площі_після = _площі_по_зонах(зведені)
    звіт["пилу_прибрано"] = пилу

    # Рахуємо шматки, а не рядки: монітор бачить окремі полігони, і саме їх
    # кількість вирішує, чи він задумається на хвилину.
    звіт["полігонів_до"] = полігонів_до
    звіт["полігонів_після"] = int(sum(len(_частини(г))
                                      for г in зведені.geometry))
    звіт["рядків_після"] = int(len(зведені))
    звіт["площа_до_га"] = round(sum(площі_до.values()), 3)
    звіт["площа_після_га"] = round(sum(площі_після.values()), 3)
    звіт["зони"] = [
        {"зона": з,
         "площа_до_га": round(площі_до.get(з, 0.0), 3),
         "площа_після_га": round(площі_після.get(з, 0.0), 3)}
        for з in sorted(set(площі_до) | set(площі_після))
    ]
    звіт["зон_зникло"] = sorted(з for з in площі_до
                                if площі_після.get(з, 0.0) <= 0.0)
    звіт["налаштування"] = н

    # Остання перевірка — у тих самих градусах, у яких файл поїде на техніку.
    # Перевіряти цілість тільки в метрах виявилось замало: у метрах було
    # чисто, а ворота видачі знайшли три биті полігони вже після переведення.
    звіт["битих_у_градусах"] = _битих(зведені.to_crs(4326))
    звіт.update(_шви(зведені))

    # Віддаємо ту саму колонку зони, з якою прийшли, — щоб решта програми
    # читала шар так само, як читала до нас.
    імʼя = колонка or "ZONE_ID"
    зведені = зведені.rename(columns={"ЗОНА": імʼя})
    вихід = gpd.GeoDataFrame(зведені, geometry="geometry", crs=метричні.crs)
    if вхідна_crs is not None and вхідна_crs != метричні.crs:
        вихід = вихід.to_crs(вхідна_crs)
    return вихід, звіт


