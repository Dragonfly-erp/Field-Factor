def _крок_буфер(шматки, опції, контур, метричні):
    крок = {"крок": "буфер", "назва": "Буфер за межу поля", "зроблено": False}
    ширина = _число(опції.get("ширина_м"), ЗАМОВЧУВАННЯ["буфер"]["ширина_м"])
    бік = опції.get("бік") or "зовнішній"
    крок["ширина_м"] = round(ширина, 2)
    крок["бік"] = бік
    if ширина <= 0:
        крок["чому_ні"] = "ширина нуль"
        return шматки, крок

    межа, звідки = _межа(контур, метричні)
    крок["межа_звідки"] = звідки

    if бік == "внутрішній":
        return _буфер_усередину(шматки, межа, ширина, крок)
    return _буфер_назовні(шматки, межа, ширина, крок)


def _буфер_усередину(шматки, межа, ширина, крок):
    import geopandas as gpd

    вужче = межа.buffer(-ширина)
    if вужче.is_empty:
        крок["чому_ні"] = ("поле вужче за подвійний буфер — {:.1f} м усередину "
                           "не лишає нічого".format(ширина))
        return шматки, крок

    рядки, було, стало = [], 0.0, 0.0
    for _, р in шматки.iterrows():
        було += р.geometry.area
        обрізане = р.geometry.intersection(вужче)
        for частина in _частини(обрізане.buffer(0)):
            if частина.area > 0:
                стало += частина.area
                рядки.append({"ЗОНА": int(р["ЗОНА"]), "geometry": частина})

    крок["зроблено"] = True
    крок["площа_знято_га"] = round((було - стало) / 10000.0, 3)
    крок["що"] = ("Смуга {:.1f} м уздовж межі поля знята з карти: {:.2f} га. "
                  "За цю смугу розкидач не кине.".format(
                      ширина, крок["площа_знято_га"]))
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=шматки.crs), крок


def _буфер_назовні(шматки, межа, ширина, крок):
    """Кільце за межею поля розбирається між зонами за близькістю.

    Кожна комірка кільця дістається тій зоні, до якої вона ближча — це
    рівно те, що зробив би розкидач, продовжуючи свою норму за край. Кільце
    міряється растром у метр, тому шов між зонами всередині кільця точний до
    метра; зовнішній край кільця — рівно межа поля плюс ширина, бо наприкінці
    все обрізається по ній."""
    import geopandas as gpd
    from rasterio.features import rasterize, shapes
    from rasterio.transform import from_origin
    from scipy.ndimage import distance_transform_edt
    from shapely.geometry import shape
    from shapely.ops import unary_union

    ширше = межа.buffer(ширина)
    кільце = ширше.difference(межа)
    if кільце.is_empty:
        крок["чому_ні"] = "кільце порожнє"
        return шматки, крок

    розмір = 1.0
    x0, y0, x1, y1 = ширше.bounds
    x0, y0 = x0 - розмір, y0 - розмір
    x1, y1 = x1 + розмір, y1 + розмір
    ширина_р = int(np.ceil((x1 - x0) / розмір))
    висота_р = int(np.ceil((y1 - y0) / розмір))
    if ширина_р * висота_р > КОМІРОК_СТЕЛЯ:
        крок["чому_ні"] = "поле завелике, щоб розібрати кільце комірками в метр"
        return шматки, крок
    перетворення = from_origin(x0, y1, розмір, розмір)

    номери = list(range(1, len(шматки) + 1))
    растр = rasterize(
        [(г, н) for г, н in zip(шматки.geometry, номери)],
        out_shape=(висота_р, ширина_р), transform=перетворення,
        fill=0, dtype="int32", all_touched=False)
    у_зону = {н: int(з) for н, з in zip(номери, шматки["ЗОНА"])}
    зонний = np.zeros_like(растр)
    for н, з in у_зону.items():
        зонний[растр == н] = з

    if not (зонний > 0).any():
        крок["чому_ні"] = "зони не потрапили в растр"
        return шматки, крок

    індекси = distance_transform_edt(зонний == 0, return_distances=False,
                                     return_indices=True)
    заповнений = зонний[tuple(індекси)]

    маска_кільця = rasterize(
        [(кільце, 1)], out_shape=(висота_р, ширина_р), transform=перетворення,
        fill=0, dtype="uint8", all_touched=True)
    заповнений = np.where(маска_кільця > 0, заповнений, 0).astype("int32")

    свій_кільцевий = {}
    for геометрія, значення in shapes(заповнений, mask=заповнений > 0,
                                      transform=перетворення):
        свій_кільцевий.setdefault(int(значення), []).append(shape(геометрія))

    старе = unary_union(list(шматки.geometry.values)).buffer(0)
    рядки, додано = [], 0.0
    for _, р in шматки.iterrows():
        рядки.append({"ЗОНА": int(р["ЗОНА"]), "geometry": р.geometry})
    for зона, частини in свій_кільцевий.items():
        шматок = unary_union(частини).buffer(0).difference(старе).intersection(ширше)
        for частина in _частини(шматок):
            if частина.area > 0:
                додано += частина.area
                рядки.append({"ЗОНА": зона, "geometry": частина})

    крок["зроблено"] = True
    крок["площа_додано_га"] = round(додано / 10000.0, 3)
    крок["що"] = ("За межу поля додано смугу {:.1f} м: {:.2f} га. Кожна ділянка "
                  "смуги дісталась найближчій зоні — так, як розкидач продовжив "
                  "би свою норму за край.".format(ширина, крок["площа_додано_га"]))
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=шматки.crs), крок
