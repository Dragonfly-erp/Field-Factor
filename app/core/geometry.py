def _крок_дрібні(шматки, опції):
    """Клапоть менший за поріг іде сусідові з найдовшою спільною межею."""
    import geopandas as gpd
    from shapely.ops import unary_union

    крок = {"крок": "дрібні", "назва": "Дрібні шматки", "зроблено": True}
    поріг_га = _число(опції.get("мін_площа_га"),
                      ЗАМОВЧУВАННЯ["дрібні"]["мін_площа_га"])
    поріг = max(0.0, поріг_га) * 10000.0
    крок["мін_площа_га"] = round(поріг_га, 3)

    рядки = [{"ЗОНА": int(р["ЗОНА"]), "geometry": р.geometry}
             for _, р in шматки.iterrows()
             if р.geometry is not None and not р.geometry.is_empty]

    # Щоразу беремо найдрібніший клапоть із тих, що не дотягують до порога.
    # Після зшивання сусід стає більшим, тож коло треба починати спочатку —
    # інакше клапоть, який щойно доріс до порога, зшився б удруге.
    зшито, віддано_м2 = 0, 0.0
    самотні, самотні_м2 = 0, 0.0
    for р in рядки:
        р["_самотній"] = False
    стеля = len(рядки) * 2 + 10
    while стеля > 0:
        стеля -= 1
        дрібні = [і for і, р in enumerate(рядки)
                  if not р["_самотній"] and р["geometry"].area < поріг]
        if not дрібні or len(рядки) < 2:
            break
        і = min(дрібні, key=lambda к: рядки[к]["geometry"].area)
        це = рядки[і]["geometry"]
        сусід = _найдовша_межа(це, рядки, і)
        if сусід is None:
            # Сусіда немає — це окремий клапоть поля. Викинути його означало б
            # лишити шматок поля без норми, тому він лишається як є.
            рядки[і]["_самотній"] = True
            самотні += 1
            самотні_м2 += це.area
            continue
        віддано_м2 += це.area
        зшито += 1
        # Без жодних подушок: шматки прийшли з одного покриття, спільні межі
        # в них збігаються вузол у вузол. Розширення клаптя «щоб напевно
        # склеїлось» на міліметр залазить на сусідів — і покриття перестає
        # бути покриттям, а `coverage_simplify` після цього мовчки нічого
        # не робить.
        рядки[сусід]["geometry"] = unary_union(
            [рядки[сусід]["geometry"], це]).buffer(0)
        рядки.pop(і)
    for р in рядки:
        р.pop("_самотній", None)

    # дірки всередині зон, менші за поріг, заростають своєю ж зоною
    затягнуто, затягнуто_м2 = 0, 0.0
    for р in рядки:
        нова, скільки, площа = _затягнути_дірки(р["geometry"], поріг)
        if скільки:
            р["geometry"] = нова
            затягнуто += скільки
            затягнуто_м2 += площа

    крок["шматків_зшито"] = зшито
    крок["площа_зшита_га"] = round(віддано_м2 / 10000.0, 3)
    крок["дірок_затягнуто"] = затягнуто
    крок["площа_дірок_га"] = round(затягнуто_м2 / 10000.0, 3)
    крок["самотніх"] = самотні
    крок["площа_самотніх_га"] = round(самотні_м2 / 10000.0, 3)
    крок["що"] = (
        "Клаптів дрібніших за {:.2f} га віддано сусідам: {} ({:.2f} га). "
        "Дірок затягнуто: {} ({:.2f} га)."
        .format(поріг_га, зшито, крок["площа_зшита_га"],
                затягнуто, крок["площа_дірок_га"]))
    if самотні:
        крок["застереження"] = (
            "{} клаптів ({:.2f} га) стоять окремо від решти поля — зшивати їх "
            "нема з ким, і вони лишились на карті як були. Викинути їх означало "
            "б лишити шматок поля без норми.".format(самотні, крок["площа_самотніх_га"]))
    return gpd.GeoDataFrame(рядки, geometry="geometry", crs=шматки.crs), крок


def _найдовша_межа(це, рядки, свій):
    """Сусід, з яким у цього клаптя найдовша спільна межа. Іншої зони — теж.

    Спільна межа міряється перетином із трохи розширеним клаптем: після
    полігонізації межі збігаються з точністю до останнього знака, і чистий
    `intersection` дає то лінію, то порожнечу."""
    подушка = це.buffer(0.05)
    найкращий, найдовша = None, 0.0
    for і, р in enumerate(рядки):
        if і == свій:
            continue
        сусід = р["geometry"]
        if сусід is None or сусід.is_empty:
            continue
        if not подушка.intersects(сусід):
            continue
        спільне = подушка.intersection(сусід)
        довжина = спільне.area / 0.05 if спільне.area else 0.0
        if довжина > найдовша:
            найдовша, найкращий = довжина, і
    return найкращий


def _затягнути_дірки(геометрія, поріг):
    from shapely.geometry import Polygon

    if геометрія.geom_type != "Polygon" or not геометрія.interiors:
        return геометрія, 0, 0.0
    лишити, скільки, площа = [], 0, 0.0
    for дірка in геометрія.interiors:
        своя = Polygon(дірка)
        if своя.area < поріг:
            скільки += 1
            площа += своя.area
        else:
            лишити.append(дірка)
    if not скільки:
        return геометрія, 0, 0.0
    return Polygon(геометрія.exterior, лишити), скільки, площа


