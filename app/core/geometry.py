# -*- coding: utf-8 -*-
"""Підготовка геометрії зон до монітора.

Зони будуються за ґрунтом. Розкидач їде по полю. Це різні логіки, і між
ними стоїть цей модуль: він не змінює, ДЕ проходить межа за агрономією, він
прибирає з неї те, чого машина фізично не відпрацює.

Чотири дії, кожна вмикається окремо і кожна звітує, що саме зробила:

1. **Дрібні шматки.** Клапоть на десять сотих гектара монітор покаже, а
   розкидач по ньому не встигне перемкнутись. Такий шматок віддається
   сусідові, з яким у нього найдовша спільна межа, а не викидається:
   викинутий шматок — це дірка в полі, а дірка означає «нічого не сипати».
   Дірки всередині зон, менші за той самий поріг, заростають.

2. **Спрощення меж.** Межа, полігонізована з растра, має сходинку на кожну
   комірку. Монітор із неї нічого не виграє, а файл важчає. Спрощується
   **покриттям цілком** (`shapely.coverage_simplify`), тому спільна межа двох
   зон лишається спільною: жодних щілин і жодних накладань. Зовнішній край
   поля не рухається взагалі.

3. **Мінімальний розмір уздовж руху.** Головне обмеження машини: доки
   заслінка перекладеться і потік дійде до диска, агрегат проїде десятки
   метрів. Смуга, коротша за цю відстань УЗДОВЖ НАПРЯМКУ РУХУ, — це не зона,
   це поштовх. Поле розкладається на рядки вздовж напрямку руху, і в кожному
   рядку відрізок, коротший за поріг, зшивається з довшим сусідом.
   Упоперек руху нічого не зшивається: там машина перемикається миттєво,
   бо це вже наступний прохід.

4. **Буфер за межу поля.** Зовнішній — щоб розкидач накрив край і не лишив
   недосів; внутрішній — щоб не кинути через межу до сусіда. Тільки за
   прямою галочкою, ширина руками, замовчування 5 м.

Порядок саме такий: спершу найгрубіша дія, потім тонші. Буфер останній, щоб
зовнішній край був рівно там, де його попросили.

**Площа після роботи інша, ніж до неї.** Тому модуль повертає площу кожної
зони до і після — щоб на екрані було видно, скільки продукту додала або
забрала геометрія, а не тільки красиву картинку.
"""

