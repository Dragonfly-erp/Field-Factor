def _крок_спрощення(шматки, опції):
    """Покриття спрощується цілком, інакше між зонами зʼявиться щілина.

    `simplify_boundary=False` тримає зовнішній край покриття нерухомим:
    межа поля лишається рівно там, де була, рухаються тільки межі між
    зонами. Це важливо — по зовнішньому краю рахується площа поля."""
    import geopandas as gpd
    import shapely

    крок = {"крок": "спрощення", "назва": "Спрощення меж", "зроблено": True}
    допуск = _число(опції.get("допуск_м"), ЗАМОВЧУВАННЯ["спрощення"]["допуск_м"])
    крок["допуск_м"] = round(допуск, 2)
    if допуск <= 0:
        крок["зроблено"] = False
        крок["чому_ні"] = "допуск нуль — нічого спрощувати"
        return шматки, крок

    геометрії = list(шматки.geometry.values)
    точок_спочатку = sum(shapely.get_num_coordinates(г) for г in геометрії)

    # `coverage_simplify` на зламаному покритті не лається — він мовчки
    # віддає те саме, що взяв. Тому спершу питаємо, чи покриття ціле.
    #
    # Ламає його не щілина і не накладання, а різна розстановка вузлів:
    # у одної зони спільна межа йде однією прямою на 360 м, а в сусідів
    # та сама пряма розбита на три відрізки — там, де до неї підходять інші
    # зони. Дірки між ними немає ані на міліметр, але для `coverage_*` це
    # різні ребра. Лікується розстановкою вузлів наново.
    зламаних = _зламаних_ребер(геометрії)
    крок["ребер_зламано"] = зламаних
    if зламаних:
        звузловані = _звузлувати(геометрії, list(шматки["ЗОНА"]))
        if звузловані is not None:
            стало = _зламаних_ребер(звузловані[0])
            крок["ребер_після_вузлів"] = стало
            if стало < зламаних:
                геометрії = звузловані[0]
                шматки = _з_геометрій(звузловані[0], звузловані[1], шматки.crs)

    # Рахуємо точки після розстановки вузлів, а не до неї: вузли самі по собі
    # додають вершин, і змішувати їх зі спрощенням у одному числі — брехати
    # на два боки. Скільки додали вузли, видно окремим числом.
    точок_до = sum(shapely.get_num_coordinates(г) for г in геометрії)
    крок["точок_спочатку"] = int(точок_спочатку)

    # Спрощувати полігони поодинці ми НЕ будемо. Кожен зсунув би свою межу
    # у свій бік, і між двома зонами лишилась би щілина завширшки з допуск —
    # смуга, у якій монітор не має норми взагалі. Краще віддати межі як є
    # і сказати про це вголос, ніж віддати карту з прогалинами.
    спосіб = "покриттям"
    лишилось_зламаних = _зламаних_ребер(геометрії)
    if лишилось_зламаних:
        крок["зроблено"] = False
        крок["чому_ні"] = (
            "покриття зламане ({} ребер не мають пари в сусіда), а спрощувати "
            "кожен полігон окремо не можна: між зонами відкрились би щілини до "
            "{:.1f} м. Межі лишились як були.".format(лишилось_зламаних, допуск))
        return шматки, крок
    try:
        спрощені = list(shapely.coverage_simplify(
            geometry=np.array(геометрії, dtype=object), tolerance=допуск,
            simplify_boundary=False))
    except Exception as помилка:
        крок["зроблено"] = False
        крок["чому_ні"] = "спростити покриттям не вийшло: {}".format(помилка)
        return шматки, крок

    очищені = []
    for стара, нова in zip(геометрії, спрощені):
        якщо = нова.buffer(0) if нова is not None else None
        if якщо is None or якщо.is_empty or якщо.area <= 0:
            якщо = стара
        очищені.append(якщо)

    точок_після = sum(shapely.get_num_coordinates(г) for г in очищені)
    новий = gpd.GeoDataFrame(
        {"ЗОНА": list(шматки["ЗОНА"])}, geometry=очищені, crs=шматки.crs)

    крок["спосіб"] = спосіб
    крок["точок_до"] = int(точок_до)
    крок["точок_після"] = int(точок_після)
    крок["що"] = (
        "Допуск {:.1f} м, спрощено {}: точок у межах {} → {} ({:.0f} % геть)."
        .format(допуск, спосіб, точок_до, точок_після,
                100.0 * (точок_до - точок_після) / точок_до if точок_до else 0.0))
    return новий, крок


