"""Фаза 8: знімки Sentinel-2 як допоміжний свідок.

Знімки тут не прикраса і не доказ самі по собі. Вони або допомагають
відновити пропуск краще, ніж сусідні проходи, — і тоді використовуються, —
або не допомагають, і тоді програма про це прямо каже (фаза 9).

Джерело — Microsoft Planetary Computer: відкритий каталог, без реєстрації.
Качається лише вікно розміром із поле, не вся сцена.
"""

import hashlib
import os
from datetime import date

import numpy as np

КАТАЛОГ = "https://planetarycomputer.microsoft.com/api/stac/v1"
КОЛЕКЦІЯ = "sentinel-2-l2a"

# Класи маски SCL, які лишаємо: рослинність, голий ґрунт, вода, неcласифіковане
ПРИДАТНІ_КЛАСИ = (4, 5, 6, 7)

СМУГИ = {"B03": "green", "B04": "red", "B05": "rededge1", "B08": "nir", "B11": "swir16"}


# ------------------------------------------------------------ вікна сезону


def вікна_сезону(культура, рік, дата_збирання=None):
    """Коли дивитись. Прив'язка до реального календаря культури, не «раз на місяць»."""
    культура = (культура or "").lower()
    озима = "озим" in культура or культура in ("жито", "ріпак")
    пізня = any(с in культура for с in ("кукурудза", "соняшник", "соя", "сорго"))

    if озима:
        вікна = [("відновлення вегетації", (3, 1), (4, 10)),
                 ("вихід у трубку", (4, 10), (5, 10)),
                 ("колосіння", (5, 10), (6, 5)),
                 ("налив зерна", (6, 5), (6, 30)),
                 ("достигання", (6, 30), (7, 25))]
    elif пізня:
        вікна = [("сходи", (5, 1), (6, 1)),
                 ("інтенсивний ріст", (6, 1), (7, 1)),
                 ("максимум покриву", (7, 1), (8, 1)),
                 ("налив", (8, 1), (9, 1)),
                 ("достигання", (9, 1), (10, 5))]
    else:
        вікна = [("сходи", (4, 1), (5, 1)),
                 ("кущіння", (5, 1), (6, 1)),
                 ("максимум покриву", (6, 1), (7, 1)),
                 ("налив", (7, 1), (8, 1)),
                 ("достигання", (8, 1), (9, 10))]

    результат = []
    for назва, (мп, дп), (мк, дк) in вікна:
        результат.append((назва, date(рік, мп, дп), date(рік, мк, дк)))
    return результат


# ------------------------------------------------------------ сітка


def сітка_поля(контур, крок=10.0):
    """Растрова сітка над полем у метричній CRS поля."""
    from rasterio.transform import from_origin

    xmin, ymin, xmax, ymax = контур.total_bounds
    xmin, ymin = xmin - крок * 3, ymin - крок * 3
    xmax, ymax = xmax + крок * 3, ymax + крок * 3
    ширина = int(np.ceil((xmax - xmin) / крок))
    висота = int(np.ceil((ymax - ymin) / крок))
    перетворення = from_origin(xmin, ymax, крок, крок)
    return {
        "перетворення": перетворення,
        "ширина": ширина,
        "висота": висота,
        "crs": контур.crs,
        "крок": крок,
        "межі": (xmin, ymin, xmax, ymax),
    }


def _ключ_кешу(сітка, ідентифікатор):
    основа = "{}|{}|{}|{}".format(
        ідентифікатор, сітка["ширина"], сітка["висота"], сітка["межі"]
    )
    return hashlib.md5(основа.encode("utf-8")).hexdigest()[:16]


# ------------------------------------------------------------ читання сцени


def _прочитати_смугу(адреса, сітка):
    """Читає потрібне вікно COG і перекладає на сітку поля."""
    import rasterio
    from rasterio.warp import Resampling, reproject

    ціль = np.full((сітка["висота"], сітка["ширина"]), np.nan, dtype="float32")
    with rasterio.Env(GDAL_DISABLE_READDIR_ON_OPEN="EMPTY_DIR",
                      GDAL_HTTP_MAX_RETRY="3", GDAL_HTTP_RETRY_DELAY="1"):
        with rasterio.open(адреса) as джерело:
            reproject(
                source=rasterio.band(джерело, 1),
                destination=ціль,
                src_transform=джерело.transform,
                src_crs=джерело.crs,
                dst_transform=сітка["перетворення"],
                dst_crs=сітка["crs"],
                resampling=Resampling.bilinear,
                dst_nodata=np.nan,
            )
    return ціль


def _прочитати_сцену(запис, сітка, кеш):
    """Одна сцена → словник індексів або None, якщо над полем хмара."""
    файл_кешу = os.path.join(кеш, _ключ_кешу(сітка, запис.id) + ".npz")
    if os.path.isfile(файл_кешу):
        збережене = np.load(файл_кешу)
        if збережене["придатна"].item() is False:
            return None
        return {к: збережене[к] for к in збережене.files if к != "придатна"}

    смуги = {}
    for код, назва in СМУГИ.items():
        актив = запис.assets.get(назва) or запис.assets.get(код)
        if актив is None:
            return None
        смуги[код] = _прочитати_смугу(актив.href, сітка)

    актив_scl = запис.assets.get("SCL") or запис.assets.get("scl")
    if актив_scl is not None:
        from rasterio.warp import Resampling, reproject
        import rasterio

        класи = np.full((сітка["висота"], сітка["ширина"]), 0, dtype="uint8")
        with rasterio.Env(GDAL_DISABLE_READDIR_ON_OPEN="EMPTY_DIR"):
            with rasterio.open(актив_scl.href) as джерело:
                reproject(
                    source=rasterio.band(джерело, 1),
                    destination=класи,
                    src_transform=джерело.transform,
                    src_crs=джерело.crs,
                    dst_transform=сітка["перетворення"],
                    dst_crs=сітка["crs"],
                    resampling=Resampling.nearest,
                )
        придатно = np.isin(класи, ПРИДАТНІ_КЛАСИ)
    else:
        придатно = np.ones((сітка["висота"], сітка["ширина"]), dtype=bool)

    частка = float(придатно.mean())
    if частка < 0.6:
        np.savez_compressed(файл_кешу, придатна=np.array(False))
        return None

    def смуга(код):
        значення = смуги[код].astype("float32")
        значення = np.where(придатно & (значення > 0), значення, np.nan)
        return значення / 10000.0

    зелений, червоний, край, бік, свір = (смуга(к) for к in ("B03", "B04", "B05", "B08", "B11"))

    with np.errstate(invalid="ignore", divide="ignore"):
        індекси = {
            "NDVI": (бік - червоний) / (бік + червоний),
            "NDRE": (бік - край) / (бік + край),
            "GNDVI": (бік - зелений) / (бік + зелений),
            "NDMI": (бік - свір) / (бік + свір),
            "ЯСКРАВІСТЬ": (зелений + червоний + свір) / 3.0,
        }
    for назва in індекси:
        індекси[назва] = np.where(np.isfinite(індекси[назва]), індекси[назва], np.nan).astype("float32")

    np.savez_compressed(файл_кешу, придатна=np.array(True), **індекси)
    return індекси


# ------------------------------------------------------------ головне


def зібрати(контур, паспорт, налаштування, база, журнал):
    """Повертає (словник шарів-предикторів, звіт про джерела). Збій — не аварія."""
    звіт = {"використано": False, "сцен": 0, "джерело": "Sentinel-2 L2A · Planetary Computer",
            "рядки": [], "причина": ""}
    try:
        import planetary_computer
        from pystac_client import Client
    except Exception as помилка:
        звіт["причина"] = "бібліотеки для супутника не стали: {}".format(помилка)
        журнал.сказати("Супутник пропущено — " + звіт["причина"])
        return {}, звіт

    рік = int(паспорт.get("рік"))
    культура = паспорт.get("культура")
    вікна = вікна_сезону(культура, рік)

    кеш = (налаштування.get("супутник") or {}).get("кеш") or "кеш_знімків"
    if not os.path.isabs(кеш):
        кеш = os.path.join(база, кеш)
    os.makedirs(кеш, exist_ok=True)

    сітка = сітка_поля(контур)
    у_градусах = контур.to_crs(4326)
    межі = tuple(у_градусах.total_bounds)

    максимум_хмар = (налаштування.get("супутник") or {}).get("максимум_хмарності_сцени", 60)

    try:
        клієнт = Client.open(КАТАЛОГ, modifier=planetary_computer.sign_inplace)
    except Exception as помилка:
        звіт["причина"] = "каталог недоступний: {}".format(помилка)
        журнал.сказати("Супутник пропущено — " + звіт["причина"])
        return {}, звіт

    шари = {}
    усі_ndvi = []
    for назва_вікна, початок, кінець in вікна:
        період = "{}/{}".format(початок.isoformat(), кінець.isoformat())
        try:
            пошук = клієнт.search(
                collections=[КОЛЕКЦІЯ], bbox=межі, datetime=період,
                query={"eo:cloud_cover": {"lt": максимум_хмар}},
            )
            записи = sorted(пошук.items(), key=lambda з: з.properties.get("eo:cloud_cover", 100))
        except Exception as помилка:
            журнал.сказати("  {}: пошук не вдався ({})".format(назва_вікна, помилка))
            continue

        взято = None
        for запис in записи[:4]:
            try:
                індекси = _прочитати_сцену(запис, сітка, кеш)
            except Exception as помилка:
                журнал.сказати("  {}: сцену не прочитали ({})".format(назва_вікна, помилка))
                continue
            if індекси is not None:
                взято = (запис, індекси)
                break

        if взято is None:
            журнал.сказати("  {}: придатної сцени немає".format(назва_вікна))
            звіт["рядки"].append({"вікно": назва_вікна, "сцена": "—",
                                  "стан": "чистого знімка не знайшлось"})
            continue

        запис, індекси = взято
        дата_сцени = str(запис.datetime.date())
        for ключ, шар in індекси.items():
            шари["{}_{}".format(ключ, назва_вікна.split()[0])] = шар
        усі_ndvi.append(індекси["NDVI"])
        звіт["сцен"] += 1
        звіт["рядки"].append({
            "вікно": назва_вікна, "сцена": дата_сцени,
            "хмарність": запис.properties.get("eo:cloud_cover"),
            "стан": "узято",
        })
        журнал.сказати("  {}: знімок {}".format(назва_вікна, дата_сцени))

    if усі_ndvi:
        стос = np.stack(усі_ndvi)
        with np.errstate(invalid="ignore"):
            шари["NDVI_макс"] = np.nanmax(стос, axis=0).astype("float32")
            шари["NDVI_сер"] = np.nanmean(стос, axis=0).astype("float32")
            шари["NDVI_розмах"] = (шари["NDVI_макс"] - np.nanmin(стос, axis=0)).astype("float32")

    звіт["використано"] = bool(шари)
    if not шари:
        звіт["причина"] = "жодного придатного знімка за сезон не знайшлось"
    звіт["_сітка"] = сітка
    журнал.сказати("Знімків узято: {}.".format(звіт["сцен"]))
    return шари, звіт


def взяти_у_точках(шари, сітка, x, y):
    """Значення шарів у координатах точок. Поза сіткою — NaN."""
    import pandas as pd

    if not шари:
        return pd.DataFrame(index=range(len(x)))
    перетворення = сітка["перетворення"]
    стовпці = ((x - перетворення.c) / перетворення.a).astype("int64")
    рядки = ((y - перетворення.f) / перетворення.e).astype("int64")
    добрі = ((рядки >= 0) & (рядки < сітка["висота"])
             & (стовпці >= 0) & (стовпці < сітка["ширина"]))
    рядки = np.clip(рядки, 0, сітка["висота"] - 1)
    стовпці = np.clip(стовпці, 0, сітка["ширина"] - 1)

    зібране = {}
    for назва, шар in шари.items():
        значення = шар[рядки, стовпці].astype("float64")
        зібране[назва] = np.where(добрі, значення, np.nan)
    return pd.DataFrame(зібране)
