"""Читання і перевірка даних електромагнітного сканера.

Сканер віддає за один прохід і рельєф, і електропровідність. Але віддає він
і те, чого в ґрунті немає:

* **мертві колонки.** У справжньому файлі з поля EC малої глибини стояла
  константою −12,8 по всіх 6854 записах. Це не низька провідність, це
  заглушка вимкненого каналу. Зонування по ній дало б рівний шум, і ніхто
  б не помітив;

* **зсунуті проходи.** Машина проїхала по ущільненому, по свіжому обробітку,
  по мокрому — і весь прохід читається вище або нижче сусідів. У полі такої
  смуги немає, вона є тільки в маршруті.

Друге лікується так само, як зсув калібрування між комбайнами: прохід
порівнюється з тим, що поруч намиряли ІНШІ проходи, і якщо він зсунутий
цілком — зсув знімається. Різниця між сусідніми смугами, яку підтверджують
обидві сторони, лишається недоторканою.
"""

import numpy as np

# EC у ґрунті не буває відʼємною і не буває однаковою до третього знака.
МЕЖІ_EC = {"dS/m": (0.01, 5.0), "mS/m": (1.0, 500.0)}

ОЗНАКИ = {
    "висота": ("elevation", "elev", "rtk", "висот", "altitude", "height"),
    "ec_мала": ("ec_shallow", "ecshallow", "ec_sh", "ecs", "ec1", "shallow"),
    "ec_велика": ("ec_deep", "ecdeep", "ec_dp", "ecd", "ec2", "deep"),
    "курс": ("track_deg", "trackdeg", "heading", "course", "azimuth", "курс"),
    "порядок": ("obj__id", "objid", "obj_id", "record", "id"),
    "швидкість": ("speed", "швидк"),
    "крок": ("distance_m", "distance", "dist"),
    "ширина": ("swth_wdth", "swath", "width", "ширина"),
}


def _спростити(назва):
    return "".join(с for с in str(назва).lower() if с.isalnum() or с == "_")


def вгадати_колонки(колонки):
    знайдене = {}
    спрощені = {к: _спростити(к) for к in колонки}
    for роль, ознаки in ОЗНАКИ.items():
        for ознака in ознаки:
            for справжня, спрощена in спрощені.items():
                if справжня in знайдене.values():
                    continue
                if ознака in спрощена:
                    знайдене[роль] = справжня
                    break
            if роль in знайдене:
                break
    return знайдене


def перевірити_висоту(значення, назва, журнал=None):
    """Висота міряється в метрах і має перепад. Одиниці EC до неї не липнуть."""
    числа = np.asarray(значення, dtype="float64")
    добрі = числа[np.isfinite(числа)]
    if добрі.size < 10:
        return False, "порожня колонка"
    перепад = float(добрі.max() - добрі.min())
    if перепад < 0.3:
        пояснення = "перепад {:.2f} м — це рівна поверхня або мертвий канал".format(перепад)
        if журнал:
            журнал.сказати("  {}: НЕ ВИКОРИСТОВУЄМО — {}".format(назва, пояснення))
        return False, пояснення
    пояснення = "{:.1f}–{:.1f} м, перепад {:.1f} м".format(
        float(добрі.min()), float(добрі.max()), перепад)
    if журнал:
        журнал.сказати("  {}: {}".format(назва, пояснення))
    return True, пояснення


def перевірити_канал(значення, назва, журнал=None):
    """Чи це взагалі дані. Повертає (придатне, пояснення, одиниця)."""
    числа = np.asarray(значення, dtype="float64")
    добрі = числа[np.isfinite(числа)]
    if добрі.size < 10:
        return False, "порожня колонка", None

    розкид = float(np.std(добрі))
    середнє = float(np.mean(добрі))
    унікальних = int(np.unique(np.round(добрі, 4)).size)

    if унікальних <= 2 or розкид < 1e-6:
        пояснення = ("канал стоїть константою {:.4g} по всіх записах — це заглушка "
                     "вимкненого приладу, а не низька провідність".format(середнє))
        if журнал:
            журнал.сказати("  {}: НЕ ВИКОРИСТОВУЄМО — {}".format(назва, пояснення))
        return False, пояснення, None

    if середнє < 0:
        пояснення = "середнє {:.3g} відʼємне — електропровідність такою не буває".format(середнє)
        if журнал:
            журнал.сказати("  {}: НЕ ВИКОРИСТОВУЄМО — {}".format(назва, пояснення))
        return False, пояснення, None

    одиниця = "dS/m" if середнє < 5 else "mS/m"
    низ, верх = МЕЖІ_EC[одиниця]
    поза = float(np.mean((добрі < низ) | (добрі > верх))) * 100
    пояснення = "{:.3g}–{:.3g} {} (медіана {:.3g})".format(
        float(добрі.min()), float(добрі.max()), одиниця, float(np.median(добрі)))
    if поза > 20:
        if журнал:
            журнал.сказати("  {}: {} — але {:.0f} % поза фізичними межами, "
                           "перевірте одиниці".format(назва, пояснення, поза))
    elif журнал:
        журнал.сказати("  {}: {}".format(назва, пояснення))
    return True, пояснення, одиниця


# ------------------------------------------------------------ проходи


def проходи_сканера(таблиця, колонки, поворот=60.0, розрив=40.0):
    """Розбиває запис на проходи за курсом і розривами.

    Курс сканер пише сам, тож здогадуватись не треба: різка зміна напрямку
    або стрибок відстані — це кінець проходу.
    """
    порядок = колонки.get("порядок")
    якщо = таблиця.sort_values(порядок, kind="stable") if порядок else таблиця

    x = якщо.geometry.x.to_numpy()
    y = якщо.geometry.y.to_numpy()
    крок = np.hypot(np.diff(x, prepend=x[0]), np.diff(y, prepend=y[0]))

    поле_курсу = колонки.get("курс")
    if поле_курсу and поле_курсу in якщо.columns:
        курс = np.asarray(якщо[поле_курсу], dtype="float64")
    else:
        курс = np.degrees(np.arctan2(np.diff(y, prepend=y[0]),
                                     np.diff(x, prepend=x[0]))) % 360

    # курс сканера смикається на малій швидкості — згладжуємо, інакше прохід
    # розсиплеться на десятки уламків там, де машина просто йшла нерівно
    радіани = np.radians(курс)
    вікно = 7
    if len(курс) > вікно:
        синус = np.convolve(np.sin(радіани), np.ones(вікно) / вікно, mode="same")
        косинус = np.convolve(np.cos(радіани), np.ones(вікно) / вікно, mode="same")
        курс = np.degrees(np.arctan2(синус, косинус)) % 360

    різниця = np.abs(np.diff(курс, prepend=курс[0]))
    різниця = np.minimum(різниця, 360 - різниця)

    зміна = np.zeros(len(x), dtype=bool)
    зміна[1:] |= різниця[1:] > поворот
    зміна[1:] |= крок[1:] > розрив
    номери = np.cumsum(зміна)
    номери = _зшити_куці(номери, найменший=25)

    результат = якщо.copy()
    результат["ПРОХІД"] = номери
    результат["КРОК"] = крок
    return результат


def _зшити_куці(номери, найменший=25):
    """Уламок у кілька записів — це не прохід, а смикання. Клеїмо до сусіда."""
    результат = номери.copy()
    межі = np.flatnonzero(np.diff(результат)) + 1
    початки = np.concatenate([[0], межі])
    кінці = np.concatenate([межі, [len(результат)]])
    for початок, кінець in zip(початки, кінці):
        if кінець - початок >= найменший:
            continue
        сусід = результат[початок - 1] if початок > 0 else (
            результат[кінець] if кінець < len(результат) else результат[початок])
        результат[початок:кінець] = сусід
    # перенумеровуємо підряд
    _, нові = np.unique(результат, return_inverse=True)
    return нові


def вирівняти_проходи(таблиця, поле_ec, радіус=None, поріг=0.12, журнал=None):
    """Знімає зсув цілого проходу відносно сусідів.

    Для кожної точки шукається найближчий запис з ІНШОГО проходу. Медіана
    різниць по всьому проходу і є його зсув. Прибирається лише те, що
    стосується проходу цілком; справжня межа між смугами ґрунту так не
    виглядає — вона видно з обох сторін однаково.
    """
    from scipy.spatial import cKDTree

    x = таблиця.geometry.x.to_numpy()
    y = таблиця.geometry.y.to_numpy()
    проходи = таблиця["ПРОХІД"].to_numpy()
    значення = np.asarray(таблиця[поле_ec], dtype="float64")
    придатні = np.isfinite(значення)

    if радіус is None:
        крок = таблиця["КРОК"].to_numpy()
        крок = крок[np.isfinite(крок) & (крок > 0)]
        радіус = float(np.median(крок)) * 12 if крок.size else 40.0
        радіус = float(np.clip(радіус, 15.0, 60.0))

    дерево = cKDTree(np.c_[x, y])
    сусіди = дерево.query_ball_point(np.c_[x, y], r=радіус)

    різниці = np.full(len(x), np.nan)
    for і, група in enumerate(сусіди):
        if not придатні[і]:
            continue
        чужі = [ј for ј in група if проходи[ј] != проходи[і] and придатні[ј]]
        if len(чужі) < 5:
            continue
        різниці[і] = значення[і] - float(np.median(значення[чужі]))

    масштаб = float(np.median(np.abs(значення[придатні] - np.median(значення[придатні]))))
    масштаб = масштаб * 1.4826 or 1.0

    виправлене = значення.copy()
    звіт = []
    for прохід in np.unique(проходи):
        свої = проходи == прохід
        власні = різниці[свої]
        власні = власні[np.isfinite(власні)]
        if власні.size < 20:
            continue
        зсув = float(np.median(власні))
        # згода: чи зсунутий прохід послідовно, а не в різні боки
        згода = float(np.mean(np.sign(власні) == np.sign(зсув)))
        якщо_знімати = abs(зсув) > поріг * масштаб and згода > 0.7
        if якщо_знімати:
            виправлене[свої] -= зсув
        звіт.append({
            "прохід": int(прохід), "точок": int(свої.sum()),
            "зсув": round(зсув, 4), "згода": round(згода, 2),
            "знято": bool(якщо_знімати),
        })

    знятих = [з for з in звіт if з["знято"]]
    if журнал:
        якщо_є = len(знятих)
        журнал.сказати(
            "  проходів {}, зсунутих цілком {} ({:.0f} % записів). "
            "Найбільший зсув {:+.3g}".format(
                len(звіт), якщо_є,
                sum(з["точок"] for з in знятих) / max(len(x), 1) * 100,
                max((з["зсув"] for з in знятих), key=abs) if знятих else 0.0))
        for з in sorted(знятих, key=lambda з: -abs(з["зсув"]))[:5]:
            журнал.сказати("    прохід {:>3}: {:+.3g} на {} записах, згода {:.0%}".format(
                з["прохід"], з["зсув"], з["точок"], з["згода"]))
    return виправлене, звіт
