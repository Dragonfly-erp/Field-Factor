КОЛОНКИ = [
    dict(імʼя="ZONE_ID", вид="ціле", ширина=6, знаків=0, підпис="номер зони"),
    dict(імʼя="RATE", вид="дробове", ширина=10, знаків=2, підпис="норма, кг/га"),
    dict(імʼя="UNIT", вид="текст", ширина=8, підпис="одиниця"),
    dict(імʼя="PRODUCT", вид="текст", ширина=24, підпис="продукт, латиницею"),
    dict(імʼя="FIELD", вид="текст", ширина=24, підпис="поле, латиницею"),
    dict(імʼя="RX_DATE", вид="текст", ширина=10, підпис="дата карти"),
    dict(імʼя="AREA_HA", вид="дробове", ширина=10, знаків=3,
         підпис="площа зони, га"),
]
ШИРИНИ = {к["імʼя"]: к.get("ширина") for к in КОЛОНКИ if к["вид"] == "текст"}
ЧИСЛА = {к["імʼя"]: (к["ширина"], к["знаків"])
         for к in КОЛОНКИ if к["вид"] != "текст"}
ОДИНИЦЯ = "kg/ha"

# Скільки байтів важить один запис DBF — щоб сказати вагу файлу ще до того,
# як його зроблено. Тепер, коли ми самі задаємо ширину і текстовим, і числовим
# полям, це рахується зі схеми й збігається з тим, що лягає на диск.
БАЙТІВ_НА_ЗАПИС = 1 + sum(к["ширина"] for к in КОЛОНКИ)

