# Офіційна українська транслітерація, постанова КМУ № 55 від 27.01.2010.
# Частина літер читається по-різному на початку слова і всередині — саме
# тому тут таблиця, а не проста заміна символ у символ.

_ПОЧАТОК = {"є": "ye", "ї": "yi", "й": "y", "ю": "yu", "я": "ya"}
_ВСЕРЕДИНІ = {"є": "ie", "ї": "i", "й": "i", "ю": "iu", "я": "ia"}
_ПРОСТІ = {
    "а": "a", "б": "b", "в": "v", "г": "h", "ґ": "g", "д": "d", "е": "e",
    "ж": "zh", "з": "z", "и": "y", "і": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ь": "", "'": "", "ʼ": "", "’": "",
    # Трапляється в старих файлах, привезених з інших програм.
    "ы": "y", "э": "e", "ё": "e", "ъ": "", "№": "N",
}


def латиницею(текст):
    """Кирилиця → латиниця за КМУ 55-2010. Усе інше, що не ASCII, знімається."""
    текст = (текст or "").strip()
    якщо_велике = []
    вихід = []
    попередній_буквений = False
    for і, знак in enumerate(текст):
        низ = знак.lower()
        велике = знак != низ
        if низ == "г" and попередній_буквений and вихід and вихід[-1].endswith("z"):
            # «зг» читається як zgh, інакше воно злилось би з «ж»
            перекладене = "gh"
        elif низ in _ПОЧАТОК and not попередній_буквений:
            перекладене = _ПОЧАТОК[низ]
        elif низ in _ВСЕРЕДИНІ:
            перекладене = _ВСЕРЕДИНІ[низ]
        elif низ in _ПРОСТІ:
            перекладене = _ПРОСТІ[низ]
        else:
            перекладене = знак
        if велике and перекладене:
            перекладене = перекладене[0].upper() + перекладене[1:]
        вихід.append(перекладене)
        попередній_буквений = низ.isalpha()
        якщо_велике.append(велике)

    зібране = "".join(вихід)
    # Усе, що лишилось не-ASCII (наголоси, тире, лапки) — розкладаємо й ріжемо.
    зібране = unicodedata.normalize("NFKD", зібране)
    return лише_ascii(зібране)


def лише_ascii(текст):
    return "".join(з for з in текст if ord(з) < 128)


def імʼя_файлу(текст, замовчування="map"):
    """Ім'я, яке піде на флешку. Без кирилиці, без пробілів, без розділових.

    Пробіл у назві — не косметика: SMS назвав свій експорт `1 grid_poly.shp`,
    і частина моніторів на пробілі спотикається."""
    т = латиницею(текст)
    т = re.sub(r"[^0-9A-Za-z._-]+", "_", т).strip("._-")
    т = re.sub(r"_+", "_", т)
    return т[:40] or замовчування


def підпис(текст, довжина=24, замовчування=""):
    """Значення текстового поля для DBF: латиниця, обрізане до довжини."""
    т = латиницею(текст).strip()
    т = re.sub(r"\s+", " ", т)
    return (т or замовчування)[:довжина]


