def перевірити(таблиця, назва_файлу):
    з = []

    def стоп(що, чому):
        з.append(dict(вага="стоп", що=що, чому=чому))

    def увага(що, чому):
        з.append(dict(вага="увага", що=що, чому=чому))

    if not len(таблиця):
        стоп("У карті немає жодної зони", "нема чого віддавати")
        return з

    # --- латиниця
    негаразди = []
    for колонка in ШИРИНИ:
        if колонка not in таблиця.columns:
            continue
        for значення in таблиця[колонка].astype(str).unique():
            if any(ord(з_) > 127 for з_ in значення):
                негаразди.append("%s: %s" % (колонка, значення))
    if негаразди:
        стоп("У файл потрапила не латиниця: " + "; ".join(негаразди[:4]),
             "монітор угадуватиме кодування й покаже кашу. Саме так робить "
             "SMS: у його DBF лежить «Б-16 Половецьке», а кодова сторінка "
             "не вказана")

    if any(ord(з_) > 127 for з_ in назва_файлу) or " " in назва_файлу:
        стоп("Ім'я файлу не годиться для флешки: " + назва_файлу,
             "тільки латиниця й без пробілів — частина моніторів на пробілі "
             "спотикається")

    # --- імена колонок
    імена = [к["імʼя"] for к in КОЛОНКИ]
    задовгі = [і for і in імена if len(і) > 10]
    if задовгі:
        стоп("Імена колонок довші за десять символів: " + ", ".join(задовгі),
             "DBF обріже їх, і різні колонки можуть злитись в одну")
    if len(set(і[:10] for і in імена)) != len(імена):
        стоп("Після обрізання до десяти символів імена колонок збігаються",
             "саме це сталось у SMS: три колонки з іменем Target_Rat")

    # --- геометрія
    невалідні = int((~таблиця.geometry.is_valid).sum())
    if невалідні:
        стоп("Битих полігонів: %d" % невалідні,
             "самоперетини монітор читає непередбачувано — треба полагодити "
             "геометрію перед видачею")
    порожні = int(таблиця.geometry.is_empty.sum())
    if порожні:
        стоп("Порожніх полігонів: %d" % порожні, "у файлі їм нема чого робити")

    типи = set(таблиця.geometry.geom_type.unique())
    if типи - {"Polygon", "MultiPolygon"}:
        стоп("У карті не тільки полігони: " + ", ".join(sorted(типи)),
             "карта внесення — це полігони; лінії й точки монітор не візьме")

    # --- вага
    полігонів = len(таблиця)
    вага_мб = полігонів * БАЙТІВ_НА_ЗАПИС / 1024.0 / 1024.0
    if полігонів > ЗАБАГАТО_ПОЛІГОНІВ:
        стоп("Полігонів %d" % полігонів,
             "старі монітори Müller і Raven такого не тягнуть. Для порівняння: "
             "у SMS полігонний експорт того самого поля дав 4 записи")
    elif полігонів > БАГАТО_ПОЛІГОНІВ:
        увага("Полігонів %d" % полігонів,
              "для старого монітора це вже багато — варто спростити межі зон")
    if вага_мб > ЗАВАЖКИЙ_ФАЙЛ_МБ:
        увага("Таблиця важитиме близько %.1f МБ" % вага_мб,
              "перевірте, чи монітор читає такі файли")

    # --- норми
    норми = таблиця["RATE"].astype(float)
    if (норми < 0).any():
        стоп("Є від'ємні норми", "монітор такого не зрозуміє")
    if (норми == 0).all():
        стоп("Усі норми нульові", "такій карті нема чого їхати в поле")
    нульових = int((норми == 0).sum())
    if нульових:
        увага("Зон із нульовою нормою: %d" % нульових,
              "це нормально — «сюди не сипати». Головне, щоб так і задумано")

    return з


