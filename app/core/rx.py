"""КАРТА ВНЕСЕННЯ. Зони з нормою → файл, який проковтне монітор.

Це остання ланка ланцюга «від техніки до техніки», і вона найменш прощає
недбалості. Монітор не скаже «у вас тут кирилиця» — він або покаже кашу,
або просто не побачить файл, і агроном стоятиме серед поля з флешкою.

Три речі, які тут вирішуються, і всі три взяті з живого експорту SMS
(`1_poly` і `1 grid_poly`, поле Б-16 Половецьке, 31.07.2025):

**Латиниця скрізь.** SMS пише в DBF `Б-16 Половецьке` у кожному з двадцяти
однієї тисячі записів, а байт кодової сторінки лишає нулем. Монітор угадує.
Ми не вгадуємо: усе, що йде на техніку, транслітерується, і поруч кладеться
`.cpg`.

**Імена колонок унікальні.** У DBF ім'я поля — щонайбільше десять символів.
У SMS «Target Rate (Mass) (N)», «(P)» і «(Water)» після обрізання стають
трьома полями з однаковим іменем `Target_Rat`. Читач за іменем візьме одне
з трьох і не скаже, яке.

**Полігони, а не сітка.** На тому самому полі полігонів вийшло 4 записи й
1,1 КБ, а сітки за замовчуванням — 21 913 записів і 18,3 МБ.

І окремо про перевитрату, бо тут легко сказати зайве. Сітка SMS на цьому
полі дала 409 кг проти 330 кг полігонами — на 24 % більше. Я перевірив, чи
це властивість сіток узагалі, і виявилось, що ні: якщо комірку зараховувати
зоні за її центром, виходить 334 кг, тобто +1 %. Правило, за яким рахує SMS,
з одного файлу не відновлюється — воно щедріше за центр і скупіше за «будь-який
перетин» (той дав би 447 кг).

Тому: **наша сітка рахується за центром комірки**, і на кроці 10 м вона
близька до полігонів. Але на кроках 25–30 м її кидає на ±6…9 % в обидва
боки — то в плюс, то в мінус, залежно від того, як лягли межі зон. Це й
лишається головною причиною надавати перевагу полігонам.
"""

