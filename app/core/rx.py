def записати(таблиця, тека, назва):
    """Shapefile з усіма частинами. Повертає перелік файлів."""
    from app.core import export_points

    os.makedirs(тека, exist_ok=True)
    назва = імʼя_файлу(назва, "rx")
    шлях = os.path.join(тека, назва + ".shp")
    for хвіст in (".shp", ".shx", ".dbf", ".prj", ".cpg"):
        старий = os.path.join(тека, назва + хвіст)
        if os.path.isfile(старий):
            os.remove(старий)

    таблиця.to_file(шлях, driver="ESRI Shapefile", engine="pyogrio",
                    encoding="UTF-8")
    основа = os.path.splitext(шлях)[0]
    with open(основа + ".cpg", "w", encoding="ascii") as ф:
        ф.write("UTF-8")
    export_points.стиснути_dbf(основа + ".dbf", ШИРИНИ)
    звузити_числа(основа + ".dbf", ЧИСЛА)

    файли = [основа + х for х in (".shp", ".shx", ".dbf", ".prj", ".cpg")]
    return [ф for ф in файли if os.path.isfile(ф)]


def звузити_числа(шлях, формати):
    """Переписати числові поля DBF із розумною шириною й кількістю знаків.

    Драйвер віддає кожному дробовому полю по 24 символи й п'ятнадцять знаків
    після коми, і площа 10,008 га лягає у файл як `10.007999999999999`. Це не
    лише зайва вага: монітор читає ці поля як рядок і показує агроному те, що
    там написано. Норма має виглядати як норма."""
    if not os.path.isfile(шлях):
        return шлях
    with open(шлях, "rb") as ф:
        дані = ф.read()

    шапка = bytearray(дані[:32])
    записів = int.from_bytes(дані[4:8], "little")
    довжина_шапки = int.from_bytes(дані[8:10], "little")
    довжина_запису = int.from_bytes(дані[10:12], "little")

    описи, зсув = [], 32
    while зсув < довжина_шапки - 1 and дані[зсув] != 0x0D:
        описи.append(bytearray(дані[зсув:зсув + 32]))
        зсув += 32
    if not описи:
        return шлях

    старі = [(о[:11].split(b"\x00")[0].decode("ascii", "replace"),
              chr(о[11]), о[16], о[17]) for о in описи]
    нові = []
    змінилось = False
    for (імʼя, тип, ширина, знаків), опис in zip(старі, описи):
        if тип == "N" and імʼя in формати:
            нова_ширина, нові_знаки = формати[імʼя]
            if (нова_ширина, нові_знаки) != (ширина, знаків):
                змінилось = True
            опис[16], опис[17] = нова_ширина, нові_знаки
            нові.append((нова_ширина, нові_знаки))
        else:
            нові.append((ширина, знаків))
    if not змінилось:
        return шлях

    нова_довжина = 1 + sum(ш for ш, _ in нові)
    шапка[10:12] = нова_довжина.to_bytes(2, "little")

    вихід = bytearray(шапка)
    for опис in описи:
        вихід += опис
    вихід += b"\x0D"

    початок = довжина_шапки
    for номер in range(записів):
        запис = дані[початок + номер * довжина_запису:
                     початок + (номер + 1) * довжина_запису]
        вихід += запис[:1] or b" "
        зсув = 1
        for (імʼя, тип, стара_ширина, старі_знаки), (ширина, знаків) in zip(
                старі, нові):
            сире = запис[зсув:зсув + стара_ширина]
            зсув += стара_ширина
            if тип == "N" and (ширина, знаків) != (стара_ширина, старі_знаки):
                текст = сире.decode("ascii", "replace").strip()
                try:
                    значення = float(текст) if текст else 0.0
                except ValueError:
                    значення = 0.0
                нове = ("%*.*f" % (ширина, знаків, значення)).encode("ascii")
                if len(нове) > ширина:      # число не влізло — краще зірочки,
                    нове = b"*" * ширина    # ніж мовчки обрізане число
                вихід += нове
            else:
                вихід += сире.ljust(ширина)[:ширина]

    вихід += b"\x1A"
    with open(шлях, "wb") as ф:
        ф.write(bytes(вихід))
    return шлях


def перечитати(шлях):
    """Прочитати щойно записане й показати, що там насправді.

    Не для краси: між тим, що ми передали драйверу, і тим, що лягло у файл,
    стоїть драйвер. Імена колонок він може обрізати, кодування підмінити.
    Тому у звіт іде прочитане з диска, а не те, що ми збирались записати."""
    import geopandas as gpd

    шар = gpd.read_file(шлях)
    основа = os.path.splitext(шлях)[0]
    вага = {х: os.path.getsize(основа + х)
            for х in (".shp", ".shx", ".dbf", ".prj", ".cpg")
            if os.path.isfile(основа + х)}
    зразок = шар.drop(columns="geometry").head(5).to_dict("records")
    return dict(
        записів=len(шар),
        колонки=[к for к in шар.columns if к != "geometry"],
        зразок=[{к: (float(в) if hasattr(в, "item") else в)
                 for к, в in р.items()} for р in зразок],
        вага=вага,
        вага_разом=sum(вага.values()),
        crs=str(шар.crs),
        уся_латиниця=all(
            all(ord(з) < 128 for з in str(в))
            for р in зразок for в in р.values()),
    )
