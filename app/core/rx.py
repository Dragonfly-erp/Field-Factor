def порівняти_із_сіткою(зони, колонка_норми, крок_м):
    """Скільки продукту вийде полігонами і скільки тією самою картою в сітці.

    Комірка зараховується зоні, якщо в зоні лежить ЦЕНТР комірки. Це найменш
    упереджене з простих правил: на полі Б-16 при кроці 10 м воно дало +1 %
    проти полігонів, тоді як сітка SMS на тому самому полі дала +24 %.

    Але на грубому кроці навіть чесне правило кидає в обидва боки: 25 м дало
    −9 %, 30 м +6 %. Агроном має бачити це число до того, як обере сітку, а не
    після того, як недорахується добрива на складі."""
    import numpy as np
    from shapely.geometry import Point
    from shapely.strtree import STRtree

    метричні = _у_метри(зони)
    норми = метричні[колонка_норми].astype(float).values
    площі_га = площі_гектарами(метричні)

    полігонами_кг = float((норми * площі_га).sum())

    межі = метричні.total_bounds
    x0, y0, x1, y1 = межі
    кол = max(1, int(np.ceil((x1 - x0) / крок_м)))
    ряд = max(1, int(np.ceil((y1 - y0) / крок_м)))
    if кол * ряд > 4_000_000:
        return dict(можливо=False,
                    чому="сітка з таким кроком дала б понад чотири мільйони "
                         "комірок — крок явно замалий")

    геометрії = list(метричні.geometry.values)
    дерево = STRtree(геометрії)

    центри_x = x0 + (np.arange(кол) + 0.5) * крок_м
    центри_y = y0 + (np.arange(ряд) + 0.5) * крок_м
    комірок_у_зоні = np.zeros(len(геометрії), dtype=np.int64)
    зайнято = 0
    for y in центри_y:
        for x in центри_x:
            точка = Point(x, y)
            for і in дерево.query(точка):
                if геометрії[і].contains(точка):
                    комірок_у_зоні[і] += 1
                    зайнято += 1
                    break

    площа_комірки_га = крок_м * крок_м / 10000.0
    сіткою_га = комірок_у_зоні * площа_комірки_га
    сіткою_кг = float((норми * сіткою_га).sum())

    різниця = сіткою_кг - полігонами_кг
    return dict(
        можливо=True,
        крок_м=крок_м,
        комірок=int(зайнято),
        комірок_усього=int(кол * ряд),
        полігонами_кг=полігонами_кг,
        сіткою_кг=сіткою_кг,
        різниця_кг=різниця,
        різниця_відсотків=(100.0 * різниця / полігонами_кг) if полігонами_кг else 0.0,
        вага_dbf_мб=зайнято * БАЙТІВ_НА_ЗАПИС / 1024.0 / 1024.0,
    )


def площі_гектарами(метричні):
    return (метричні.geometry.area / 10000.0).values


def _у_метри(зони):
    """Площі й кроки міряються в метрах, тому для арифметики беремо проєкцію.

    Файл потім віддається в WGS-84, як робить SMS, — але рахувати площу
    в градусах не можна: градус довготи на нашій широті це 64 % градуса
    широти, і гектари вийдуть кривими."""
    if зони.crs is None:
        return зони.set_crs(4326).to_crs(зони.estimate_utm_crs())
    if зони.crs.is_geographic:
        return зони.to_crs(зони.estimate_utm_crs())
    return зони


