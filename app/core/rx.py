def зібрати(зони, норми, продукт, поле, дата, колонка_зони=None):
    """Шар зон + норма на кожну зону → таблиця під shapefile.

    норми — {номер зони: кг/га}. Зона, якої немає в нормах, отримує нуль:
    це і є «сюди не сипати», і воно має бути в файлі явно, а не пропуском."""
    import geopandas as gpd

    метричні = _у_метри(зони)
    площі = площі_гектарами(метричні)

    колонка_зони = колонка_зони or _знайти_колонку_зони(зони)
    рядки = []
    for порядок, (_, з) in enumerate(зони.iterrows(), start=1):
        номер = int(з[колонка_зони]) if колонка_зони else порядок
        ставка = float(норми.get(номер, норми.get(str(номер), 0.0)) or 0.0)
        рядки.append({
            "ZONE_ID": номер,
            "RATE": round(ставка, 2),
            "UNIT": ОДИНИЦЯ,
            "PRODUCT": підпис(продукт, ШИРИНИ["PRODUCT"], "PRODUCT"),
            "FIELD": підпис(поле, ШИРИНИ["FIELD"], "FIELD"),
            "RX_DATE": підпис(дата, ШИРИНИ["RX_DATE"]),
            "AREA_HA": round(float(площі[порядок - 1]), 3),
        })

    таблиця = gpd.GeoDataFrame(рядки, geometry=list(зони.geometry.values),
                               crs=зони.crs)
    # На техніку віддаємо в тих самих координатах, що й SMS: WGS-84 у градусах.
    if таблиця.crs is None:
        таблиця = таблиця.set_crs(4326)
    return таблиця.to_crs(4326)


def _знайти_колонку_зони(зони):
    for варіант in ("зона", "ZONE_ID", "zone", "зони", "GRIDCODE", "gridcode",
                    "DN", "value", "клас"):
        if варіант in зони.columns:
            return варіант
    return None


