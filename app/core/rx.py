ЗАБАГАТО_ПОЛІГОНІВ = 2000     # далі старий монітор починає думати хвилинами
БАГАТО_ПОЛІГОНІВ = 500
ЗАВАЖКИЙ_ФАЙЛ_МБ = 4.0
