def перевірити():
    """Чи не розійшлась мапа з тим, що програма справді пише у файл."""
    from app.core import export_points

    наші = set(export_points.ПОРЯДОК)
    у_мапі = {р[0] for р in ВІДПОВІДНІСТЬ}
    зауваги = []
    for імʼя in sorted(наші - у_мапі):
        зауваги.append("колонка {} є у файлі, але її немає в мапі SMS".format(імʼя))
    for імʼя in sorted(у_мапі - наші):
        зауваги.append("мапа SMS згадує {}, а такої колонки у файлі немає".format(імʼя))
    for наша, група, атрибут, *_ in ВІДПОВІДНІСТЬ:
        if група == "Grain Harvest" and атрибут not in GRAIN_HARVEST:
            зауваги.append(
                "{} веде на «{}» у групі Grain Harvest, а такого атрибута в "
                "переліку немає".format(наша, атрибут))
    return зауваги


