def звірити_арифметику(точки, допуск=0.01):
    """Чи справді сходяться сім чисел. Без цього мапа — обіцянка, не факт."""
    import numpy as np

    треба = ("FLOW_TH", "DUR_S", "YLD_WET", "CELL_HA")
    якщо_немає = [к for к in треба if к not in точки]
    if якщо_немає:
        return {"можна": False, "чому": "немає колонок: " + ", ".join(якщо_немає)}

    з_потоку = (точки["FLOW_TH"].to_numpy(dtype="float64") / 3.6 * 1000.0
                * точки["DUR_S"].to_numpy(dtype="float64"))
    з_врожаю = (точки["YLD_WET"].to_numpy(dtype="float64")
                * точки["CELL_HA"].to_numpy(dtype="float64"))
    ок = np.isfinite(з_потоку) & np.isfinite(з_врожаю) & (з_врожаю > 0)
    if ок.sum() < 100:
        return {"можна": False, "чому": "замало придатних комірок"}
    відхил = np.abs(з_потоку[ок] / з_врожаю[ок] - 1.0)
    return {
        "можна": True,
        "комірок": int(ок.sum()),
        "медіана_відхилу": float(np.median(відхил)),
        "найгірше": float(np.max(відхил)),
        "сходиться": bool(np.max(відхил) < допуск),
    }


