def за_групами(словник_атрибутів):
    """Для екрана: перелік, розкладений по групах у сталому порядку."""
    вихід = []
    for ключ, назва in ГРУПИ.items():
        картки = [к for к in словник_атрибутів.values() if к.get("група") == ключ]
