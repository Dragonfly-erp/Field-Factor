def словник(база=None):
    """Перелік величин, з якими працює програма. Ключ — імʼя у файлі."""
    зібране = {}
    for к in ЗАГОТОВКА:
        картка = dict(к)
        картка["звідки"] = "заготовка FieldFactor"
        картка["своє"] = False
        зібране[картка["імʼя"]] = доповнити(картка)

    if база:
        for імʼя, к in _свої(база).items():
            картка = dict(к)
            картка["імʼя"] = імʼя
            картка["звідки"] = "заведено в господарстві"
            картка["своє"] = True
            картка["перекриває_заготовку"] = імʼя in зібране
            # Роль зашита в картку заготовки й правці з екрана не підлягає:
            # інакше клієнт зняв би канонічність із врожайності й пішов далі.
            if імʼя in зібране:
                картка["роль"] = зібране[імʼя]["роль"]
                картка["без_нього"] = зібране[імʼя]["без_нього"]
            else:
                картка["роль"] = "додатковий"
                картка.setdefault("без_нього", "")
            картка.setdefault("тип", "дробове")
            картка.setdefault("група", "службові")
            картка.setdefault("синонім_до", None)
            картка.setdefault("двигун", "")
            зібране[імʼя] = доповнити(картка)

    return зібране


