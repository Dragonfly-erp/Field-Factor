def одиниці_розмірності(розмірність):
    """Які одиниці допустимі для цієї величини. Звідси перелік на екрані."""
    return [і for і, о in ОДИНИЦІ.items() if о["розмірність"] == розмірність]


def перевести(значення, з_одиниці, в_одиницю):
    """Одне число з однієї одиниці в іншу.

    Повертає `(число, пояснення)`. Число `None` означає, що перевести не
    можемо, і пояснення каже чому — мовчки підставляти одиницю не будемо
    ніколи, бо помилка в одиниці не видно на карті, вона видно на полі.
    """
    a, b = ОДИНИЦІ.get(з_одиниці), ОДИНИЦІ.get(в_одиницю)
    if a is None:
        return None, "невідома одиниця: %s" % з_одиниці
    if b is None:
        return None, "невідома одиниця: %s" % в_одиницю
    if a["розмірність"] != b["розмірність"]:
        return None, ("%s — це %s, а %s — це %s. Різні величини"
                      % (з_одиниці, a["розмірність"], в_одиницю, b["розмірність"]))
    if a["множник"] is None or b["множник"] is None:
        нема = з_одиниці if a["множник"] is None else в_одиницю
        return None, ОДИНИЦІ[нема].get("пояснення", "переводити нічим")
    try:
        return float(значення) * a["множник"] / b["множник"], ""
    except (TypeError, ValueError):
        return None, "не число"


