НЕМАЄ_У_ФАЙЛІ = "немає у файлі"


def перевірити_розкладку(призначено, картки=None):
    """`призначено` — що клієнт склав у модулі співставлення:

        {"YLD_KGHA": "Yld Mass Dry", "MOIST": "Moisture", "COMB_ID": None}

    Значення `None` або `НЕМАЄ_У_ФАЙЛІ` — це **явна** відповідь «цього у
    файлі немає». Ключа немає взагалі — відповіді не було, і далі не пускаємо.
    Різниця між «не знайшлось» і «не питали» тут головна: перше клієнт бачив
    і підтвердив, друге проскочило повз очі.
    """
    картки = картки if картки is not None else ЗАГОТОВКА
    за_іменем = {к["імʼя"]: к for к in картки}
    з = []
    for імʼя in [к["імʼя"] for к in картки if к["роль"] == "канонічний"]:
        картка = за_іменем[імʼя]
        if імʼя not in призначено:
            з.append(dict(вага="помилка", атрибут=імʼя,
                          що="%s не заповнено" % картка["назва"],
                          чому="канонічний атрибут. Треба або вказати "
                               "колонку файлу, або сказати прямо, що цього "
                               "у файлі немає. %s" % картка["без_нього"]))
            continue
        джерело = призначено[імʼя]
        if джерело in (None, "", НЕМАЄ_У_ФАЙЛІ):
            з.append(dict(вага="увага", атрибут=імʼя,
                          що="%s: у файлі немає" % картка["назва"],
                          чому=картка["без_нього"]))
    return з


