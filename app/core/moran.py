# -*- coding: utf-8 -*-
"""ПРОСТОРОВІ ВИКИДИ: точка, яка сперечається зі своїми сусідами.

Це не наш винахід. Це третій крок стандартного протоколу очистки карт
врожайності (Vega та ін., 2019), перевіреного на 595 справжніх полях і
реалізованого в R-пакеті `paar`. Протокол складається з трьох кроків:

    1. край поля            ~13 % точок
    2. глобальні викиди     ~1,3 %
    3. ПРОСТОРОВІ ВИКИДИ    ~4,5 %      <- цей модуль

Перші два в нас були. Третього не було, і саме він прибирає огріхи комбайна.

**Чим просторовий викид відрізняється від глобального.** Глобальний — це
число, неможливе саме по собі: сорок тонн з гектара. Просторовий — число,
цілком нормальне для поля, але неможливе **в цьому місці**: шість тонн там,
де довкола дванадцять. Саме так виглядає огріх: зерно не потрапило в бункер,
а сусідні комірки показують, скільки там мало бути.

**Як це міряють.** Локальний індекс Морана. Для кожної точки беруть її
власне відхилення від середнього по полю (z) і середнє відхилення її сусідів
(просторовий лаг). Якщо знаки протилежні — точка сперечається з оточенням:

    z < 0, сусіди > 0     низька серед високих   <- огріх, недомолот, втрати
    z > 0, сусіди < 0     висока серед низьких   <- подвійний облік, зсув

Обидва випадки прибираються: обидва однаково не є полем.

**Межа методу, яку треба знати.** Фільтр бачить те, що **вужче за
оточення**. Якщо аномалія ширша за радіус, її власні комірки стають одна
одній сусідами, і сперечатися нема з ким. Тому радіус береться в ширинах
захвату: огріх — це один-два проходи, а оточення — три-чотири.

**Чого цей фільтр НЕ робить.** Він не чіпає плавних змін: низина серед
низини не суперечить нікому. Він не потребує ні супутника, ні вегетації —
працює на самих даних монітора. І він не знає слова «техногенний»: він
знає тільки, що ця точка не тримається купи зі своїми сусідами.
"""

import numpy as np

# Скільки сусідів навколо. Радіус береться в ширинах захвату: три-чотири
# проходи — це вже оточення, а не той самий прохід.
РАДІУС_ЖАТОК = 3.0

# Наскільки різко точка має сперечатись із сусідами, щоб її прибрати.
# У протоколі значущість беруть перестановками; тут — у стандартних
# відхиленнях самої різниці, що дає той самий поріг і рахується миттєво
# на двохстах тисячах записів.
ПОРІГ_СИГМ = 2.5

# Нижче цієї кількості сусідів судити нема кому: одна-дві точки поруч
# зроблять «оточення» з випадкового числа.
СУСІДІВ_МІНІМУМ = 8

КОД = "SPAT"


def знайти(x, y, значення, ширина_захвату=6.0, поріг=ПОРІГ_СИГМ):
    """Точки, що сперечаються з оточенням. Повертає (маска, звіт)."""
    from scipy.spatial import cKDTree

    x = np.asarray(x, float)
    y = np.asarray(y, float)
    з = np.asarray(значення, dtype="float64")
    придатні = np.isfinite(з)
    if придатні.sum() < 200:
        return np.zeros(len(з), dtype=bool), {"чому": "замало точок"}

    радіус = max(10.0, float(ширина_захвату) * РАДІУС_ЖАТОК)
    дерево = cKDTree(np.c_[x[придатні], y[придатні]])
    свої = з[придатні]

    # Сума й кількість сусідів у колі — разом із собою, тому себе віднімаємо.
    сума = дерево.sparse_distance_matrix(дерево, радіус, output_type="coo_matrix")
    ваги = сума.copy()
    ваги.data = np.ones_like(ваги.data)
    кількість = np.asarray(ваги.sum(axis=1)).ravel() - 1.0
    сума_сусідів = np.asarray(
        ваги.multiply(свої[np.newaxis, :]).sum(axis=1)).ravel() - свої

    досить = кількість >= СУСІДІВ_МІНІМУМ
    оточення = np.full(len(свої), np.nan)
    оточення[досить] = сума_сусідів[досить] / кількість[досить]

    середнє = float(np.nanmean(свої))
    розкид = float(np.nanstd(свої))
    if розкид <= 0:
        return np.zeros(len(з), dtype=bool), {"чому": "розкиду немає"}

    z = (свої - середнє) / розкид
    лаг = (оточення - середнє) / розкид
    різниця = z - лаг
    сигма = float(np.nanstd(різниця[np.isfinite(різниця)]))
    if not np.isfinite(сигма) or сигма <= 0:
        return np.zeros(len(з), dtype=bool), {"чому": "різниці немає"}

    # Сперечається = точка різко відходить ВІД СВОЇХ СУСІДІВ.
    #
    # Класичні квадранти Морана вимагають протилежних знаків відносно
    # середнього ПО ПОЛЮ: низька серед високих. Перша версія так і робила —
    # і мовчала на огріху, що лежав у низькій частині поля: там і сама точка
    # нижча за середнє, і сусіди нижчі, знаки однакові, ворота не спрацювали.
    #
    # Але огріх у низині — такий самий огріх. Питання не «чи вона нижча за
    # поле», а «чи вона нижча за тих, хто поруч». Тому міряємо різницю з
    # сусідами, а квадрант лишаємо тільки для підпису, у який бік.
    різко = np.isfinite(лаг) & (np.abs(різниця) > поріг * сигма)
    викид = різко

    низька_серед_високих = викид & (різниця < 0)
    висока_серед_низьких = викид & (різниця > 0)

    повна = np.zeros(len(з), dtype=bool)
    повна[np.where(придатні)[0]] = викид
    # Напрям по кожній точці: -1 нижча за сусідів, +1 вища, 0 не викид.
    напрям = np.zeros(len(з), dtype="int8")
    напрям[np.where(придатні)[0]] = np.where(
        викид, np.where(різниця < 0, -1, 1), 0)

    звіт = {
        "радіус_м": радіус,
        "усього": int(придатні.sum()),
        "прибрано": int(викид.sum()),
        "частка": 100.0 * викид.sum() / max(придатні.sum(), 1),
        "низька_серед_високих": int(низька_серед_високих.sum()),
        "висока_серед_низьких": int(висока_серед_низьких.sum()),
        "без_сусідів": int((~досить).sum()),
        "напрям": напрям,
    }
    return повна, звіт


def прибрати(таблиця, ширина_захвату=6.0, поле_значень="ВРОЖАЙ_БАЗ", журнал=None):
    """Позначає просторові викиди кодом SPAT. Змінює таблицю на місці."""
    чисті = (таблиця["QC"] == "OK").to_numpy()
    if чисті.sum() < 500:
        return таблиця, {"чому": "замало чистих записів"}

    маска, звіт = знайти(
        таблиця.geometry.x.to_numpy()[чисті],
        таблиця.geometry.y.to_numpy()[чисті],
        таблиця.loc[чисті, поле_значень].to_numpy(),
        ширина_захвату)
    якщо = звіт.get("прибрано", 0)
    if якщо:
        індекси = таблиця.index[чисті][маска]
        таблиця.loc[індекси, "QC"] = КОД

    if журнал is not None:
        if якщо:
            журнал.сказати(
                "  просторових викидів: {} ({:.1f} %) — {} низьких серед "
                "високих, {} високих серед низьких. Оточення береться в колі "
                "{:.0f} м.".format(
                    звіт["прибрано"], звіт["частка"],
                    звіт["низька_серед_високих"], звіт["висока_серед_низьких"],
                    звіт["радіус_м"])
            )
        else:
            журнал.сказати("  просторових викидів не знайдено: {}".format(
                звіт.get("чому", "усе тримається купи")))
    return таблиця, звіт
