# -*- coding: utf-8 -*-
"""МАШИННІ АНОМАЛІЇ: там, де поле росло, а в бункер не потрапило.

Питання, на яке цей модуль відповідає: **червона пляма на карті — це бідне
поле чи огріх комбайна?**

Свідок один і незалежний: рослинність зі супутника. Якщо врожайність у
плямі провалилась, а рослинність там **не провалилась разом із нею** — поле
там росло. Отже число в бункері описує не поле, а те, що сталося з машиною:
сенсор загубив потік, зерно пішло у втрати, потік приписався не туди.

**Чому не «виправляємо індексом».** У методі записано: індексами виміряні
числа не правимо ніколи. Тут ми його й не порушуємо. Аномальні записи
**знімаються з обліку так само, як зупинки й розвороти**, і далі відновлюються
тим самим механізмом, що й будь-який інший пропуск. Різниця між «домалювати
індексом» і «визнати вимір недійсним і перебудувати як діру» — принципова:
у другому випадку у файлі стоїть чесне INTERP, і клієнт бачить, що це не вимір.

**Чому валовий не зростає.** Якщо зерно виросло й поїхало на вагову, воно
вже в підсумку — монітор приписав його не туди. Тому після відновлення
рівень повертається на місце: зерно перерозподіляється, а не додається.
Інакше ми б намалювали врожай, якого не було.

Ворота навмисно вузькі. Аномалією стає тільки те, що:

    · лежить суцільною ділянкою не менше МІН_ГА;
    · нижче за оточення більше ніж на ПОРІГ_ВІДХИЛУ;
    · рослинність там **не впала** разом із урожайністю;
    · витягнуте вздовж проходів — форма машини, не форма ґрунту.

Кожна з чотирьох умов сама по собі трапляється на будь-якому полі. Разом —
майже ніколи, і саме тому їхній збіг щось означає.
"""

import numpy as np

МІН_ГА = 1.5
ПОРІГ_ВІДХИЛУ = 0.08       # наскільки нижче за оточення, частка
# Наскільки рослинність має «не провалитись» разом із урожайністю.
# Спершу тут стояла вимога, щоб рослинність була вищою за середню ПО ПОЛЮ.
# Вона хибна: огріх посеред звичайної ділянки має рослинність просто
# нормальну, і такий огріх ворота пропускали. Правильне питання не «чи
# висока рослинність», а «чи впала вона там разом із урожайністю».
ЗГОДА_СВІДКА = -0.15
ВИТЯГНУТІСТЬ = 1.8         # у скільки разів довша вздовж проходів, ніж упоперек
КОД = "ANOM"


def _z(значення):
    з = np.asarray(значення, dtype="float64")
    ок = np.isfinite(з)
    if ок.sum() < 50 or np.nanstd(з[ок]) <= 0:
        return None
    return (з - np.nanmean(з[ок])) / np.nanstd(з[ок])


def знайти(x, y, врожай, вегетація, напрямок_рад, крок=10.0, журнал=None):
    """Суцільні ділянки, де поле росло, а врожайність провалилась.

    Повертає (маска_аномалій, перелік_ділянок).
    """
    from scipy.ndimage import uniform_filter, label, binary_closing

    x = np.asarray(x, float); y = np.asarray(y, float)
    врожай = np.asarray(врожай, dtype="float64")
    зв = _z(вегетація)
    if зв is None:
        return np.zeros(len(врожай), dtype=bool), []

    с = np.clip(((x - x.min()) / крок).round().astype(int), 0, None)
    р = np.clip(((y.max() - y) / крок).round().astype(int), 0, None)
    рядків, стовпців = int(р.max()) + 1, int(с.max()) + 1

    сітка = np.full((рядків, стовпців), np.nan)
    сітка[р, с] = врожай
    маска = np.isfinite(сітка)
    if маска.sum() < 200:
        return np.zeros(len(врожай), dtype=bool), []

    # оточення: широке вікно, щоб пляма сама себе не піднімала
    вікно = max(9, int(round(120.0 / крок)) | 1)
    сума = uniform_filter(np.nan_to_num(сітка), вікно, mode="nearest")
    вага = uniform_filter(маска.astype("float64"), вікно, mode="nearest")
    оточення = np.where(вага > 1e-9, сума / np.maximum(вага, 1e-9), np.nan)

    відносно = np.where(маска, сітка / np.maximum(оточення, 1e-9) - 1.0, np.nan)
    провал = маска & (відносно <= -ПОРІГ_ВІДХИЛУ)

    сітка_веге = np.full((рядків, стовпців), np.nan)
    сітка_веге[р, с] = зв
    маска_веге = np.isfinite(сітка_веге)
    сума_в = uniform_filter(np.nan_to_num(сітка_веге), вікно, mode="nearest")
    вага_в = uniform_filter(маска_веге.astype("float64"), вікно, mode="nearest")
    оточення_веге = np.where(вага_в > 1e-9, сума_в / np.maximum(вага_в, 1e-9), np.nan)
    відхил_веге = сітка_веге - оточення_веге
    росло = маска_веге & (відхил_веге >= ЗГОДА_СВІДКА)

    # Дірки в підозрі ЗАКРИВАЄМО, а не роз'їдаємо. Спершу тут стояло
    # binary_opening — і воно нищило рівно те, що шукаємо: огріх це смуга
    # завширшки з жатку, тобто чотири-пʼять комірок, і відкриття 3×3 з'їдало
    # по комірці з кожного боку. На перевірці обидві умови спрацьовували на
    # 70 % смуги, а після відкриття лишалось 16 %, розсипаних на друзки.
    # Від шуму захищають площа й витягнутість, а не ерозія.
    підозра = binary_closing(провал & росло, np.ones((3, 3), bool))
    мітки, скільки = label(підозра)
    комірка_га = крок * крок / 10000.0

    маска_записів = np.zeros(len(врожай), dtype=bool)
    перелік = []
    ключі = {}
    for і in range(1, скільки + 1):
        де = мітки == і
        га = float(де.sum()) * комірка_га
        if га < МІН_ГА:
            continue
        рр, сс = np.nonzero(де)
        # форма: скільки тягнеться вздовж проходів проти впоперек
        уздовж = (сс * np.sin(напрямок_рад) + рр * np.cos(напрямок_рад))
        упоперек = (сс * np.cos(напрямок_рад) - рр * np.sin(напрямок_рад))
        довжина = уздовж.max() - уздовж.min() + 1
        ширина = упоперек.max() - упоперек.min() + 1
        витягнутість = довжина / max(ширина, 1.0)
        if витягнутість < ВИТЯГНУТІСТЬ:
            continue
        ключі[і] = True
        свої = np.isin(р * 100000 + с, рр * 100000 + сс)
        маска_записів |= свої
        перелік.append({
            "га": га,
            "витягнутість": float(витягнутість),
            "нижче_на": float(-np.nanmedian(відносно[де]) * 100.0),
            "рослинність": float(np.nanmedian(сітка_веге[де])),
            "рослинність_проти_оточення": float(np.nanmedian(відхил_веге[де])),
            "врожайність": float(np.nanmedian(сітка[де])),
            "мало_б_бути": float(np.nanmedian(оточення[де])),
        })

    if журнал is not None:
        if перелік:
            журнал.сказати(
                "  машинних аномалій: {} ділянок, {:.1f} га. Там рослинність "
                "вища за середню, а врожайність нижча за оточення на "
                "{:.0f}–{:.0f} %.".format(
                    len(перелік), sum(д["га"] for д in перелік),
                    min(д["нижче_на"] for д in перелік),
                    max(д["нижче_на"] for д in перелік))
            )
        else:
            журнал.сказати("  машинних аномалій не знайдено.")
    return маска_записів, перелік


def зняти_з_обліку(таблиця, вегетація, напрямок_рад, крок=10.0, журнал=None):
    """Позначає аномалії кодом ANOM. Далі їх відновить механізм пропусків."""
    чисті = (таблиця["QC"] == "OK").to_numpy()
    if чисті.sum() < 500:
        return таблиця, []

    маска, перелік = знайти(
        таблиця.geometry.x.to_numpy()[чисті],
        таблиця.geometry.y.to_numpy()[чисті],
        таблиця.loc[чисті, "ВРОЖАЙ_БАЗ"].to_numpy(),
        np.asarray(вегетація, dtype="float64"),
        напрямок_рад, крок, журнал)
    if not перелік:
        return таблиця, []

    індекси = np.where(чисті)[0][маска]
    таблиця.iloc[індекси, таблиця.columns.get_loc("QC")] = КОД
    return таблиця, перелік
