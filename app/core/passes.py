"""Геометрія проходів комбайна.

Проходи — це кістяк усього. По них рахується затримка сенсора, по них
відсікаються розвороти, і саме на них, а не на квадратну сітку, лягають
добудовані точки.
"""

import numpy as np


# ------------------------------------------------------------ розбиття


def _курси(x, y):
    """Курс руху між сусідніми точками, у радіанах. Перша точка = друга."""
    dx = np.diff(x, prepend=x[0])
    dy = np.diff(y, prepend=y[0])
    курс = np.arctan2(dy, dx)
    if len(курс) > 1:
        курс[0] = курс[1]
    return курс


def _різниця_кутів(а, б):
    """Найменший кут між напрямками, без урахування «вперед-назад»."""
    р = np.abs(а - б) % np.pi
    return np.minimum(р, np.pi - р)


def визначити_проходи(таблиця, розрив_часу=8.0, розрив_відстані=25.0,
                      поворот=np.deg2rad(50)):
    """Додає колонки ПРОХІД, КУРС, КРОК, ШВИДКІСТЬ_ГЕО. Працює по кожній машині."""
    таблиця = таблиця.copy()
    таблиця["ПРОХІД"] = -1
    таблиця["КУРС"] = np.nan
    таблиця["КРОК"] = np.nan
    таблиця["ШВИДКІСТЬ_ГЕО"] = np.nan

    номер = 0
    for машина, індекси in таблиця.groupby("МАШИНА", sort=False).groups.items():
        шматок = таблиця.loc[індекси]
        if "ЧАС" in шматок.columns and шматок["ЧАС"].notna().any():
            шматок = шматок.sort_values("ЧАС", kind="stable")
        x = шматок.geometry.x.to_numpy()
        y = шматок.geometry.y.to_numpy()
        if len(x) < 3:
            continue

        крок = np.hypot(np.diff(x, prepend=x[0]), np.diff(y, prepend=y[0]))
        курс = _курси(x, y)

        if "ЧАС" in шматок.columns and шматок["ЧАС"].notna().all():
            секунди = шматок["ЧАС"].astype("int64").to_numpy() / 1e9
            пауза = np.diff(секунди, prepend=секунди[0])
            with np.errstate(divide="ignore", invalid="ignore"):
                швидкість = np.where(пауза > 0, крок / пауза, np.nan)
        else:
            пауза = np.zeros_like(крок)
            швидкість = np.full_like(крок, np.nan)

        # згладжений курс, щоб один кривий запис не рвав прохід
        згладжений = курс.copy()
        if len(курс) > 5:
            вікно = 5
            синус = np.convolve(np.sin(2 * курс), np.ones(вікно) / вікно, mode="same")
            косинус = np.convolve(np.cos(2 * курс), np.ones(вікно) / вікно, mode="same")
            згладжений = np.arctan2(синус, косинус) / 2.0

        зміна = np.zeros(len(x), dtype=bool)
        зміна[1:] |= крок[1:] > розрив_відстані
        зміна[1:] |= _різниця_кутів(згладжений[1:], згладжений[:-1]) > поворот
        if пауза.any():
            зміна[1:] |= пауза[1:] > розрив_часу

        проходи = номер + np.cumsum(зміна)
        номер = int(проходи.max()) + 1 if len(проходи) else номер

        таблиця.loc[шматок.index, "ПРОХІД"] = проходи
        таблиця.loc[шматок.index, "КУРС"] = курс
        таблиця.loc[шматок.index, "КРОК"] = крок
        таблиця.loc[шматок.index, "ШВИДКІСТЬ_ГЕО"] = швидкість
        таблиця.loc[шматок.index, "_ПОРЯДОК"] = np.arange(len(шматок))

    return таблиця


# ------------------------------------------------------------ геометрія поля


def головний_напрямок(курси, ваги=None):
    """Круговий середній напрямок без розрізнення «туди-сюди», у радіанах."""
    добрі = np.isfinite(курси)
    if not добрі.any():
        return 0.0
    к = курси[добрі]
    в = np.ones_like(к) if ваги is None else np.asarray(ваги)[добрі]
    return float(np.arctan2(np.sum(в * np.sin(2 * к)), np.sum(в * np.cos(2 * к))) / 2.0)


# Найдрібніша клітинка, якою міряємо накриту землю. Півметра — це вчетверо
# дрібніше за найвужчий слід, який нас цікавить, і на полі 3,5 x 1,5 км дає
# растр на двадцять мільйонів клітинок: пам'яті небагато, а похибка країв
# нижча за відсоток.
КЛІТИНКА_М = 0.5


def виміряти_ширину(таблиця, ширина_запису, журнал=None):
    """Скільки землі комбайн накрив насправді, поділити на пройдений шлях.

    **Навіщо це окремим виміром.** Монітор пише ширину жатки, і ділить на неї
    масу. Але за прохід реально береться менше: комбайнер іде з нахлистом,
    друга половина жатки місцями йде по вже зібраному, і зерна звідти немає.
    Площа виходить завищена, а врожайність — занижена рівно настільки ж.

    На Г-03 монітор писав 6,00 м, а земля під смугами дала 5,26 м. Це 12 %
    різниці, і саме вони робили карту біднішою за вагову господарства.

    Рахуємо растром, а не об'єднанням полігонів: на двохстах тисячах записів
    друге займає хвилини, перше — секунди, а відповідь та сама.

    Повертає `{ширина_м, накрито_га, шлях_м, перекриття_відсотків}` або None,
    якщо міряти нема на чому.
    """
    import numpy as np
    from scipy.ndimage import binary_dilation

    if not (np.isfinite(ширина_запису) and ширина_запису > 0):
        return None

    x = таблиця.geometry.x.to_numpy()
    y = таблиця.geometry.y.to_numpy()
    кроки = таблиця["КРОК"].to_numpy() if "КРОК" in таблиця.columns else None
    if кроки is None:
        return None
    придатні = np.isfinite(кроки) & (кроки > 0.01) & (кроки < 60.0)
    шлях = float(кроки[придатні].sum())
    if шлях < 100:
        return None

    радіус = int(round((ширина_запису / 2.0) / КЛІТИНКА_М))
    if радіус < 1:
        return None

    стовпців = int((x.max() - x.min()) / КЛІТИНКА_М) + 2 * радіус + 2
    рядків = int((y.max() - y.min()) / КЛІТИНКА_М) + 2 * радіус + 2
    if стовпців * рядків > 120_000_000:      # більше — рахуємо грубіше
        return None

    полотно = np.zeros((рядків, стовпців), dtype=bool)
    с = ((x - x.min()) / КЛІТИНКА_М).astype(int) + радіус
    р = ((y.max() - y) / КЛІТИНКА_М).astype(int) + радіус
    полотно[р, с] = True

    # круг радіусом у пів-жатки: слід запису це смуга завширшки з жатку
    d = np.arange(-радіус, радіус + 1)
    круг = (d[:, None] ** 2 + d[None, :] ** 2) <= радіус ** 2
    накрито = binary_dilation(полотно, structure=круг)

    площа = float(накрито.sum()) * КЛІТИНКА_М * КЛІТИНКА_М
    ширина = площа / шлях
    звіт = {
        "ширина_м": ширина,
        "накрито_га": площа / 10000.0,
        "шлях_м": шлях,
        "перекриття_відсотків": max(0.0, 100.0 * (1.0 - ширина / ширина_запису)),
    }
    if журнал is not None:
        журнал.сказати(
            "  земля під смугами: {:.2f} га на {:.0f} м шляху — це {:.2f} м "
            "робочої ширини проти {:.2f} м записаної монітором "
            "(перекриття {:.0f} %).".format(
                звіт["накрито_га"], шлях, ширина, ширина_запису,
                звіт["перекриття_відсотків"])
        )
    return звіт


def оцінити_геометрію(таблиця, ширина_з_файлу=None):
    """Крок уздовж проходу, відстань між проходами, робоча ширина захвату."""
    x = таблиця.geometry.x.to_numpy()
    y = таблиця.geometry.y.to_numpy()
    курси = таблиця["КУРС"].to_numpy()
    проходи = таблиця["ПРОХІД"].to_numpy()

    довжини = таблиця.groupby("ПРОХІД")["КРОК"].transform("size").to_numpy()
    напрямок = головний_напрямок(курси, ваги=довжини)

    кроки = таблиця["КРОК"].to_numpy()
    кроки = кроки[np.isfinite(кроки) & (кроки > 0.05) & (кроки < 25)]
    крок_уздовж = float(np.median(кроки)) if кроки.size else 2.0

    # поперечна координата: проєкція на нормаль до головного напрямку
    нормаль = np.array([-np.sin(напрямок), np.cos(напрямок)])
    поперек = x * нормаль[0] + y * нормаль[1]

    центри = []
    for прохід in np.unique(проходи):
        якщо = проходи == прохід
        if якщо.sum() < 5:
            continue
        центри.append(float(np.median(поперек[якщо])))
    центри = np.sort(np.array(центри))
    крок_упоперек = np.nan
    if центри.size > 3:
        різниці = np.diff(центри)
        різниці = різниці[(різниці > 1.0) & (різниці < 60.0)]
        if різниці.size:
            крок_упоперек = float(np.median(різниці))

    if ширина_з_файлу is not None and np.isfinite(ширина_з_файлу) and ширина_з_файлу > 0:
        ширина = float(ширина_з_файлу)
        джерело_ширини = "записана монітором"
    elif np.isfinite(крок_упоперек):
        ширина = крок_упоперек
        джерело_ширини = "оцінена за відстанню між проходами"
    else:
        ширина = 7.0
        джерело_ширини = "невідома, прийнято 7 м"

    if not np.isfinite(крок_упоперек):
        крок_упоперек = ширина

    return {
        "напрямок_рад": напрямок,
        "напрямок_град": round(float(np.rad2deg(напрямок)) % 180, 1),
        "крок_уздовж_м": round(крок_уздовж, 2),
        "крок_упоперек_м": round(float(крок_упоперек), 2),
        "ширина_м": round(float(ширина), 2),
        "джерело_ширини": джерело_ширини,
        "проходів": int(len(np.unique(проходи[проходи >= 0]))),
    }


