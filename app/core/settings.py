def _дістати(дані, шлях, замовчування=None):
    вузол = дані
    for частина in шлях.split("."):
        if not isinstance(вузол, dict) or частина not in вузол:
            return замовчування
        вузол = вузол[частина]
    return вузол


def _покласти(дані, шлях, значення):
    частини = шлях.split(".")
    вузол = дані
    for частина in частини[:-1]:
        if not isinstance(вузол.get(частина), dict):
            вузол[частина] = {}
        вузол = вузол[частина]
    вузол[частини[-1]] = значення


def прочитати(база):
    шлях = os.path.join(база, ФАЙЛ)
    try:
        with io.open(шлях, encoding="utf-8") as ф:
            return json.load(ф)
    except Exception:                                  # noqa: BLE001
        return {}


def показати(база):
    """Значення для екрана: що лежить у файлі, а чого немає — замовчування."""
    сире = прочитати(база)
    значення = {}
    for п in ПОЛЯ:
        з = _дістати(сире, п["шлях"], None)
        значення[п["ключ"]] = п.get("замовчування") if з is None else з
    return значення


def перевірити(введене):
    """Що не так. Порожній перелік означає, що можна писати."""
    зауваги = []
    за_ключем = {п["ключ"]: п for п in ПОЛЯ}
    for ключ, значення in (введене or {}).items():
        п = за_ключем.get(ключ)
        if п is None:
            зауваги.append("невідоме налаштування: {}".format(ключ))
            continue
        if п["вид"] == "число" and значення not in (None, ""):
            try:
                число = float(значення)
            except (TypeError, ValueError):
                зауваги.append("{}: не число — «{}»".format(п["підпис"], значення))
                continue
            if число < 0:
                зауваги.append("{}: відʼємне число".format(п["підпис"]))
        if п["вид"] == "вибір" and значення not in (None, ""):
            дозволені = [в[0] for в in п.get("варіанти", [])]
            if значення not in дозволені:
                зауваги.append("{}: невідоме значення «{}»".format(п["підпис"], значення))

    # Окремо — те, що зламало б програму мовчки.
    порт = (введене or {}).get("порт")
    if порт not in (None, ""):
        try:
            п = int(порт)
            if not (1024 <= п <= 65535):
                зауваги.append("Порт {} поза межами 1024…65535".format(п))
        except (TypeError, ValueError):
            зауваги.append("Порт має бути числом")
    межа = (введене or {}).get("верхня_межа")
    if межа not in (None, "") and float(межа) < 5000:
        зауваги.append("Фізична стеля {:.0f} кг/га зріже справжні записи. "
                       "Нижче 5 000 не буває".format(float(межа)))
    return зауваги


def записати(база, введене):
    """Пише лише те, що прийшло, решту файлу не чіпає.

    Переписати файл цілком означало б стерти те, чого немає в нашій формі,
    — а туди люди дописують своє. Правило те саме, що з чужими файлами:
    міняємо своє, чуже лишаємо.
    """
    зауваги = перевірити(введене)
    if зауваги:
        return {"гаразд": False, "зауваги": зауваги}

    дані = прочитати(база)
    за_ключем = {п["ключ"]: п for п in ПОЛЯ}
    треба_перезапуск = []
    for ключ, значення in (введене or {}).items():
        п = за_ключем[ключ]
        if п["вид"] == "число":
            значення = None if значення in (None, "") else float(значення)
            if значення is not None and float(значення).is_integer():
                значення = int(значення)
        elif п["вид"] == "прапорець":
            значення = bool(значення)
        старе = _дістати(дані, п["шлях"], None)
        if старе != значення:
            _покласти(дані, п["шлях"], значення)
            if п.get("перезапуск"):
                треба_перезапуск.append(п["підпис"])

    with io.open(os.path.join(база, ФАЙЛ), "w", encoding="utf-8") as ф:
        json.dump(дані, ф, ensure_ascii=False, indent=2)
    return {"гаразд": True, "перезапуск": треба_перезапуск,
            "значення": показати(база)}


def ціна_пального(база, довідники_господарства=None):
    """Скільки коштує літр. Господарство головніше за програму.

    Порядок той самий, що в решті довідників: спільне замовчування, і поверх
    нього своє. Солярку кожен купує сам.
    """
    своя = (довідники_господарства or {}).get("пальне_грн_л")
    if своя not in (None, ""):
        return float(своя)
    з_файлу = _дістати(прочитати(база), "гроші.ціна_пального_грн_л", None)
    return float(з_файлу) if з_файлу not in (None, "") else ЦІНА_ПАЛЬНОГО
