# -*- coding: utf-8 -*-
"""МАЙСТЕР-ТАБЛИЦЯ ГОСПОДАРСТВА. Історія полів так, як її веде агроном.

Господарства віддають історію не базою, а таблицею: рядок — поле, далі
роки блоками. Форма в кожного своя, і це не безлад, а різні звички обліку:

    Комагро   рік · культура · т/га, і план на наступний рік у трьох варіантах
    АТП       рік · культура · гібрид · дата посіву · норма висіву · т/га
    Альянс    те саме плюс колонки добрив по продуктах
    Тріом     сівозміна з площами план/факт ПЛЮС операції поточного року:
              внесення 1–3, обприскування 1–4, з нормами, цінами й вартістю робіт

Читач не намагається звести їх до одного шаблону. Він знаходить у шапці
**блоки років** і забирає з кожного те, що там є. Чого немає — того немає:
порожня клітинка лишається порожньою, а не стає нулем.

**Нічого не пише сам.** `розібрати()` повертає передпоказ: які поля, які
роки, що знайшлось. Запис у теку поля робить `закласти()` — і лише після
того, як людина подивилась на передпоказ.
"""

import os
import re

# Слова, за якими в шапці впізнається зміст колонки. Перелік не вигаданий —
# зібраний із чотирьох живих таблиць господарств.
# Порядок тут — це порядок перевірки, і він має значення. «т/га» містить
# «га», і якщо площу шукати першою, урожай назавжди стане площею. Спершу
# найвужчі підписи, потім широкі.
СЛОВА = (
    ("рік", ("рік", "год", "year")),
    ("урожай", ("т/га", "урож", "yield")),
    ("площа_план", ("площа, план", "площа план")),
    ("площа_факт", ("площа, факт", "площа факт")),
    ("дата_посіву", ("дата посіву",)),
    ("норма_висіву", ("норма висіву", "норма")),
    ("гібрид", ("гібрид", "сорт")),
    ("культура", ("культура",)),
    ("рейтинг", ("рейтинг",)),
    ("підрозділ", ("підрозділ", "бригада", "відділок", "ферма")),
    ("поле", ("поле", "назва групи", "геозона", "field")),
    ("площа", ("площа", "area", "га")),
)


def _низ(з):
    return re.sub(r"\s+", " ", str(з if з is not None else "").strip().lower())


def _рік(значення):
    """Рік із клітинки шапки. Приймає 2024, «2024», «2024 результати»."""
    текст = str(значення if значення is not None else "").strip()
    знайдено = re.search(r"(19|20)\d{2}", текст)
    if not знайдено:
        return None
    рік = int(знайдено.group(0))
    return рік if 1990 <= рік <= 2100 else None


def _число(значення):
    if значення is None or значення == "":
        return None
    if isinstance(значення, (int, float)):
        return float(значення)
    текст = str(значення).strip().replace("\xa0", "").replace(" ", "").replace(",", ".")
    try:
        return float(текст)
    except ValueError:
        return None


def _вид_колонки(підпис):
    н = _низ(підпис)
    if not н:
        return None
    for вид, слова in СЛОВА:
        for с in слова:
            if с in н:
                return вид
    return None


def _роки_з_рядка(види, рядок):
    """Роки колонок, узяті з КЛІТИНОК цього рядка, а не з шапки.

    АТП, Альянс і Маяк ведуть історію інакше за Комагро: у шапці стоїть
    підпис «рік», а сам рік лежить у кожному рядку окремо — бо в різних
    полів у тій самій колонці різні роки. Колонка «рік» відкриває блок,
    і все праворуч належить їй, доки не почнеться наступний блок.

    Шапкові роки тут навмисно НЕ беруться. У Альянса й Маяка в шапці
    стоять окремі колонки «2020 результати … 2025 результати»; остання з
    них інакше ставила б рік усім колонкам праворуч, і вся історія поля
    злипалась би в 2025 — саме так воно й було.
    """
    роки, поточний = [], None
    for і, вид in enumerate(види):
        if вид == "рік":
            поточний = _рік(рядок[і]) if і < len(рядок) else None
        роки.append(поточний)
    return роки


def прочитати_аркуш(шлях, аркуш=None):
    """Аркуш як список рядків. Значення беруться такими, як лежать."""
    from openpyxl import load_workbook

    книга = load_workbook(шлях, data_only=True, read_only=True)
    лист = книга[аркуш] if аркуш else книга[книга.sheetnames[0]]
    рядки = [[к for к in рядок] for рядок in лист.iter_rows(values_only=True)]
    книга.close()
    return рядки


def знайти_шапку(рядки, глибина=6):
    """Де починається шапка й де починаються дані.

    Шапка буває на одному рядку й на двох: у живих таблицях рік стоїть
    згори над групою, а «культура · гібрид · т/га» — під ним. Тому шукається
    ПАРА рядків, а не один: інакше вибір нижнього рядка зсуває початок даних
    на рядок уперед і перше поле мовчки зникає.

    Повертає (рядок_року, рядок_підписів, перший_рядок_даних).
    """
    найкраще, вибір = -1, (0, 1, 2)
    for і in range(min(глибина, len(рядки))):
        верх = рядки[і]
        низ = рядки[і + 1] if і + 1 < len(рядки) else []
        роки_вгорі = sum(1 for к in верх if _рік(к))
        підписи_внизу = sum(1 for к in низ if _вид_колонки(к))
        підписи_вгорі = sum(1 for к in верх if _вид_колонки(к))

        # двохрядкова шапка: роки згори, підписи знизу
        оцінка_пари = роки_вгорі * 2 + підписи_внизу
        if підписи_внизу >= 2 and роки_вгорі >= 1 and оцінка_пари > найкраще:
            найкраще, вибір = оцінка_пари, (і, і + 1, і + 2)

        # однорядкова: і роки, і підписи в одному рядку
        оцінка_одного = роки_вгорі * 2 + підписи_вгорі
        if оцінка_одного > найкраще:
            найкраще, вибір = оцінка_одного, (і, і, і + 1)
    return вибір


def _зібрати_шапку(рядки, і_року, і_підписів):
    """Підписи колонок із урахуванням двох рівнів шапки: у живих таблицях
    рік стоїть над групою, а підписи «культура · гібрид · т/га» — під ним."""
    верх = рядки[і_року] if і_року < len(рядки) else []
    низ = рядки[і_підписів] if і_підписів < len(рядки) else []
    ширина = max(len(верх), len(низ))
    підписи, роки = [], []
    поточний_рік = None
    for і in range(ширина):
        в = верх[і] if і < len(верх) else None
        н = низ[і] if і < len(низ) else None
        рік_у_клітинці = _рік(в)
        if рік_у_клітинці:
            поточний_рік = рік_у_клітинці
        підписи.append(_низ(н) or _низ(в))
        роки.append(поточний_рік)
    return підписи, роки


def розібрати(шлях, аркуш=None):
    """Передпоказ: що ця таблиця дасть у історію полів. Нічого не пише."""
    рядки = прочитати_аркуш(шлях, аркуш)
    if not рядки:
        return {"гаразд": False, "повідомлення": "Аркуш порожній"}

    і_року, і_підписів, і_даних = знайти_шапку(рядки)
    підписи, роки_колонок = _зібрати_шапку(рядки, і_року, і_підписів)
    види = [_вид_колонки(п) for п in підписи]

    # Колонка поля — перша, у якій підпис схожий на «поле», інакше просто перша
    і_поля = next((і for і, в in enumerate(види) if в == "поле"), 0)
    і_площі = next((і for і, в in enumerate(види) if в == "площа"), None)
    і_підрозділу = next((і for і, в in enumerate(види) if в == "підрозділ"), None)
    і_рейтингу = next((і for і, в in enumerate(види) if в == "рейтинг"), None)
    # Є в шапці колонки «рік» — значить рік живе в рядках, не в шапці
    рік_у_рядку = any(в == "рік" for в in види)

    поля, роки_знайдені, попередження = [], set(), []
    for рядок in рядки[і_даних:]:
        якщо_назва = str(рядок[і_поля] if і_поля < len(рядок) else "" or "").strip()
        if not якщо_назва or якщо_назва.lower() in ("nan", "none"):
            continue
        запис = {
            "поле": якщо_назва,
            "площа_га": _число(рядок[і_площі]) if і_площі is not None and і_площі < len(рядок) else None,
            "підрозділ": (str(рядок[і_підрозділу]).strip()
                          if і_підрозділу is not None and і_підрозділу < len(рядок)
                          and рядок[і_підрозділу] else None),
            "рейтинг": _число(рядок[і_рейтингу]) if і_рейтингу is not None and і_рейтингу < len(рядок) else None,
            "роки": {},
        }
        роки_рядка = роки_колонок
        if рік_у_рядку:
            роки_рядка = _роки_з_рядка(види, рядок)
        for і, (вид, рік) in enumerate(zip(види, роки_рядка)):
            if not рік or і >= len(рядок):
                continue
            значення = рядок[і]
            if значення in (None, ""):
                continue
            сезон = запис["роки"].setdefault(str(рік), {})
            if вид in ("культура", "гібрид", "дата_посіву"):
                сезон[вид] = str(значення).strip()
            elif вид in ("урожай", "норма_висіву", "площа_план", "площа_факт"):
                число = _число(значення)
                сезон[вид] = число if число is not None else str(значення).strip()
            elif вид is None and isinstance(значення, str) and значення.strip():
                # Колонка без підпису всередині блоку року — найчастіше це
                # культура або гібрид. Не вгадуємо: кладемо як «інше», щоб
                # людина побачила й сказала, що це.
                сезон.setdefault("інше", []).append(значення.strip())
            роки_знайдені.add(str(рік))
        if запис["роки"] or запис["площа_га"]:
            поля.append(запис)

    if not поля:
        попередження.append("рядків з полями не знайдено — можливо, шапка на іншому аркуші")

    return {
        "гаразд": bool(поля),
        "файл": os.path.basename(шлях),
        "рядок_шапки": і_підписів + 1,
        "перший_рядок_даних": і_даних + 1,
        "колонок": len(підписи),
        "поля": поля,
        "роки": sorted(роки_знайдені),
        "попередження": попередження,
    }


def закласти(картотека, господарство, розбір, звірка_назв=None, тільки=None):
    """Кладе розібране в історію полів. Пише лише те, що є в таблиці.

    `звірка_назв` — відповідність «назва в таблиці → ключ поля в дереві».
    Без неї беруться поля, назви яких збігаються з наявними; решта
    потрапляє в «не знайшлось», а не заводиться наосліп: поле з чужою
    назвою — це нове поле без межі, і воно засмітить дерево.
    """
    from app.core import history

    звірка_назв = звірка_назв or {}
    наявні = {п["назва"]: п["ключ"] for п in картотека.поля(господарство)}
    наявні_низ = {_низ(н): к for н, к in наявні.items()}

    закладено, не_знайшлось = [], []
    for запис in розбір.get("поля") or []:
        назва = запис["поле"]
        if тільки and назва not in тільки:
            continue
        ключ = звірка_назв.get(назва) or наявні.get(назва) or наявні_низ.get(_низ(назва))
        if not ключ:
            не_знайшлось.append(назва)
            continue
        тека = картотека.тека_поля(господарство, ключ)
        роки_записані = 0
        for рік, сезон in (запис.get("роки") or {}).items():
            загальне = {}
            if сезон.get("культура"):
                загальне["культура"] = сезон["культура"]
            if сезон.get("гібрид"):
                загальне["гібрид"] = сезон["гібрид"]
            if сезон.get("дата_посіву"):
                загальне["посів"] = сезон["дата_посіву"]
            if сезон.get("норма_висіву") is not None:
                загальне["норма_висіву"] = сезон["норма_висіву"]
            if isinstance(сезон.get("урожай"), (int, float)):
                загальне["урожай_т_га"] = сезон["урожай"]
            if сезон.get("площа_план") is not None:
                загальне["площа_план_га"] = сезон["площа_план"]
            if сезон.get("площа_факт") is not None:
                загальне["площа_факт_га"] = сезон["площа_факт"]
            if не_порожнє(загальне):
                history.записати(тека, "загальне", рік, загальне,
                                 джерело="майстер-таблиця господарства · "
                                         + розбір.get("файл", ""),
                                 статус="WORKING")
                роки_записані += 1
        if запис.get("рейтинг") is not None:
            картотека.оновити_поле(господарство, ключ, {"рейтинг": запис["рейтинг"]})
        if запис.get("підрозділ"):
            картотека.оновити_поле(господарство, ключ, {"ферма": запис["підрозділ"]})
        закладено.append({"поле": назва, "ключ": ключ, "років": роки_записані})

    return {"гаразд": bool(закладено), "закладено": закладено,
            "не_знайшлось": не_знайшлось,
            "полів": len(закладено), "не_знайдено": len(не_знайшлось)}


def не_порожнє(словник):
    return any(з not in (None, "", []) for з in (словник or {}).values())
