"""Фази 2-3: читання контуру поля і всіх файлів монітора врожайності.

Правило тут одне: нічого не домислювати мовчки. Кожен здогад — здогад
про одиниці, про комбайн, про систему координат — повертається нагору,
щоб користувач побачив його і міг перебити.
"""

import os
import zipfile

from app.core import util

ПРОСТОРОВІ = (".shp", ".gpkg", ".geojson", ".json", ".kml", ".gml", ".gpx")
ТАБЛИЧНІ = (".csv", ".txt", ".dat")
АРХІВИ = (".zip", ".kmz")

ІМОВІРНІ_X = ("longitude", "long", "lon", "lng", "x", "easting", "gpslongitude", "довгота")
ІМОВІРНІ_Y = ("latitude", "lat", "y", "northing", "gpslatitude", "широта")


# ------------------------------------------------------------ пошук файлів


def розгорнути_архіви(тека):
    """ZIP і KMZ розпаковуються поруч, у теку з тим самим імʼям."""
    розгорнуті = []
    for корінь, _, файли in os.walk(тека):
        for імʼя in list(файли):
            if not імʼя.lower().endswith(АРХІВИ):
                continue
            джерело = os.path.join(корінь, імʼя)
            ціль = os.path.join(корінь, "_" + os.path.splitext(імʼя)[0])
            if os.path.isdir(ціль):
                continue
            try:
                with zipfile.ZipFile(джерело) as архів:
                    архів.extractall(ціль)
                розгорнуті.append(імʼя)
            except Exception:
                pass
    return розгорнуті


def знайти_шари(тека):
    """Усі читабельні файли в теці, включно з розпакованим."""
    розгорнути_архіви(тека)
    знайдені = []
    for корінь, теки, файли in os.walk(тека):
        теки[:] = [т for т in теки if not т.startswith("__")]
        for імʼя in файли:
            низ = імʼя.lower()
            if низ.endswith(ПРОСТОРОВІ) or низ.endswith(ТАБЛИЧНІ):
                знайдені.append(os.path.join(корінь, імʼя))
    return sorted(знайдені)


# ------------------------------------------------------------ читання шару


def _читати_таблицю(шлях):
    import geopandas as gpd
    import pandas as pd

    for роздільник in (None, ";", ",", "\t"):
        try:
            таблиця = pd.read_csv(шлях, sep=роздільник, engine="python",
                                  encoding="utf-8-sig", on_bad_lines="skip")
            if таблиця.shape[1] > 1:
                break
        except Exception:
            таблиця = None
    if таблиця is None or таблиця.empty:
        raise ValueError("Файл {} не читається як таблиця".format(os.path.basename(шлях)))

    низи = {к.strip().lower(): к for к in таблиця.columns}
    колонка_x = next((низи[і] for і in ІМОВІРНІ_X if і in низи), None)
    колонка_y = next((низи[і] for і in ІМОВІРНІ_Y if і in низи), None)
    if not колонка_x or not колонка_y:
        raise ValueError(
            "У файлі {} не видно колонок із координатами".format(os.path.basename(шлях))
        )

    таблиця = таблиця.dropna(subset=[колонка_x, колонка_y])
    геометрія = gpd.points_from_xy(таблиця[колонка_x], таблиця[колонка_y])
    у_градусах = (таблиця[колонка_x].abs().max() <= 180
                  and таблиця[колонка_y].abs().max() <= 90)
    return gpd.GeoDataFrame(таблиця, geometry=геометрія, crs=4326 if у_градусах else None)


def прочитати_шар(шлях):
    """Один файл → GeoDataFrame. Кидає виняток із людською причиною."""
    import geopandas as gpd

    низ = шлях.lower()
    if низ.endswith(ТАБЛИЧНІ):
        return _читати_таблицю(шлях)

    if низ.endswith((".kml", ".gml", ".gpx")):
        # у KML буває кілька шарів; беремо перший непорожній
        try:
            шари = gpd.list_layers(шлях)
            for назва in шари["name"]:
                шар = gpd.read_file(шлях, layer=назва)
                if len(шар):
                    return шар
        except Exception:
            pass
    if низ.endswith(".gpkg"):
        шари = gpd.list_layers(шлях)
        if len(шари):
            return gpd.read_file(шлях, layer=шари["name"].iloc[0])
    return gpd.read_file(шлях)


# ------------------------------------------------------------ контур


def прочитати_контур(сеанс):
    """Повертає (GeoDataFrame з одним полігоном, опис). CRS — метрична."""
    import geopandas as gpd
    from shapely.ops import unary_union

    тека = сеанс.шлях("1_вхідні_дані", "контур")
    файли = [ф for ф in знайти_шари(тека)]
    if not файли:
        raise ValueError("Файл контуру не знайдено.")

    зауваження = []
    полігони = None
    вибраний = None
    for шлях in файли:
        try:
            шар = прочитати_шар(шлях)
        except Exception as помилка:
            зауваження.append("{}: {}".format(os.path.basename(шлях), помилка))
            continue
        якщо_полігони = шар[шар.geometry.geom_type.isin(("Polygon", "MultiPolygon"))]
        if len(якщо_полігони):
            полігони = якщо_полігони
            вибраний = шлях
            break
    if полігони is None:
        raise ValueError("У наданих файлах немає жодного полігона — контуру немає.")

    if полігони.crs is None:
        полігони = полігони.set_crs(4326)
        зауваження.append(
            "У файлі контуру не записана система координат. Прийнято WGS-84 "
            "(звичайні широта й довгота). Якщо це не так — контур ляже не туди."
        )

    метрична = util.метрична_crs(полігони)
    полігони = полігони.to_crs(метрична)

    погані = ~полігони.geometry.is_valid
    if погані.any():
        полігони.loc[погані, "geometry"] = полігони.loc[погані, "geometry"].buffer(0)
        зауваження.append(
            "Геометрія контуру мала самоперетини — виправлено найобережнішим "
            "способом, межа не рухалась."
        )

    частин = int(len(полігони))
    зʼєднаний = unary_union(полігони.geometry.values)
    if зʼєднаний.geom_type == "MultiPolygon" and len(зʼєднаний.geoms) > 1:
        зауваження.append(
            "Контур складається з {} окремих шматків. Це нормально для поля з "
            "вирізами, але перевірте, чи не потрапив сюди сусід.".format(len(зʼєднаний.geoms))
        )

    контур = gpd.GeoDataFrame(geometry=[зʼєднаний], crs=метрична)
    опис = {
        "файл": os.path.basename(вибраний),
        "crs": "EPSG:{}".format(метрична),
        "площа_га": round(float(контур.area.iloc[0]) / 10000.0, 2),
        "частин": частин,
        "зауваження": зауваження,
    }
    return контур, опис


# ------------------------------------------------------------ монітор


def прочитати_монітор(сеанс, метрична):
    """Усі файли монітора → один GeoDataFrame точок у метричній CRS."""
    import geopandas as gpd
    import pandas as pd

    тека = сеанс.шлях("1_вхідні_дані", "монітор")
    файли = знайти_шари(тека)
    if not файли:
        raise ValueError("Файлів монітора не знайдено.")

    шматки, описи, зауваження = [], [], []
    for шлях in файли:
        імʼя = os.path.basename(шлях)
        try:
            шар = прочитати_шар(шлях)
        except Exception as помилка:
            зауваження.append("{} пропущено: {}".format(імʼя, помилка))
            continue

        точки = шар[шар.geometry.geom_type == "Point"]
        if not len(точки):
            зауваження.append("{}: точок немає, файл пропущено.".format(імʼя))
            continue

        if точки.crs is None:
            точки = точки.set_crs(4326)
            зауваження.append(
                "{}: система координат не записана, прийнято WGS-84.".format(імʼя)
            )
        точки = точки.to_crs(метрична)
        точки = точки.copy()
        точки["ФАЙЛ"] = імʼя
        шматки.append(точки)
        описи.append({
            "файл": імʼя,
            "записів": int(len(точки)),
            "crs": "EPSG:{}".format(метрична),
            "колонки": [к for к in точки.columns if к != "geometry"],
        })

    if not шматки:
        raise ValueError("Жоден файл монітора не дав придатних точок.")

    зведене = gpd.GeoDataFrame(
        pd.concat(шматки, ignore_index=True, sort=False), crs=метрична
    )
    return зведене, описи, зауваження


МАКСИМУМ_КОМБАЙНІВ = 24


def схоже_на_лічильник(значення, записів):
    """Чи це справді номер машини, а не порядковий номер запису.

    На справжньому експорті SMS колонка `Obj__Id` мала 54 665 різних значень
    на 222 760 записів — це лічильник, а не комбайн. Взяти його за машину
    означало б «звести» 54 тисячі комбайнів, кожен зі своїм калібруванням.
    Господарство з двома десятками комбайнів на одному полі — вже рідкість;
    усе, що більше, — точно не машини."""
    різних = int(значення.nunique())
    if різних <= 1:
        return False, різних
    if різних > МАКСИМУМ_КОМБАЙНІВ:
        return True, різних
    return False, різних


def призначити_машини(зведене, колонка_машини, описи):
    """Комбайн беремо з колонки; немає колонки — з імені файлу."""
    if колонка_машини and колонка_машини in зведене.columns:
        лічильник, різних = схоже_на_лічильник(зведене[колонка_машини], len(зведене))
        if лічильник:
            зведене["МАШИНА"] = зведене["ФАЙЛ"].map(
                lambda і: os.path.splitext(і)[0][:20])
            джерело = ("імена файлів — у колонці «{}» {} різних значень, це "
                       "лічильник записів, а не номер комбайна".format(
                           колонка_машини, різних))
            for опис in описи:
                свої = зведене.loc[зведене["ФАЙЛ"] == опис["файл"], "МАШИНА"].unique()
                опис["машина"] = ", ".join(str(с) for с in свої[:3])
            return зведене, джерело
    if колонка_машини and колонка_машини in зведене.columns:
        зведене["МАШИНА"] = зведене[колонка_машини].astype(str).str.strip()
        зведене.loc[зведене["МАШИНА"].isin(("", "nan", "None")), "МАШИНА"] = "невідомий"
        джерело = "колонка «{}»".format(колонка_машини)
    else:
        зведене["МАШИНА"] = зведене["ФАЙЛ"].map(
            lambda і: os.path.splitext(і)[0][:20]
        )
        джерело = "імена файлів"
    for опис in описи:
        свої = зведене.loc[зведене["ФАЙЛ"] == опис["файл"], "МАШИНА"].unique()
        опис["машина"] = ", ".join(str(с) for с in свої[:3])
    return зведене, джерело


# ------------------------------------------------------------ розвідка


def розвідати(сеанс):
    """Фаза 3: подивитись у файли й розповісти, що там. Нічого не міняючи."""
    import numpy as np

    звіт = {"контур": {}, "монітор": {}}

    try:
        контур, опис_контуру = прочитати_контур(сеанс)
        звіт["контур"] = опис_контуру
        метрична = контур.crs.to_epsg()
    except Exception as помилка:
        звіт["контур"] = {"помилка": str(помилка)}
        метрична = None

    try:
        if метрична is None:
            raise ValueError("Без контуру файли монітора не можна прив'язати до поля.")
        зведене, описи, зауваження = прочитати_монітор(сеанс, метрична)
    except Exception as помилка:
        звіт["монітор"] = {"помилка": str(помилка)}
        return звіт

    колонки = [к for к in зведене.columns if к not in ("geometry", "ФАЙЛ")]
    вгадано = util.вгадати_колонки(колонки)
    зведене, джерело_машин = призначити_машини(зведене, вгадано.get("машина"), описи)

    одиниця, обґрунтування = "", ""
    вже_приведено = False
    базис_монітора = None
    if вгадано.get("врожай"):
        from app.core import moisture

        вже_приведено = moisture.схоже_на_приведене(вгадано["врожай"])
        if вже_приведено:
            базис_монітора = _відновити_базис_монітора(зведене, вгадано)
            if базис_монітора:
                зауваження.append(
                    "Монітор писав приведену врожайність у колонці «{}», і до "
                    "якої вологості — видно з його ж чисел: **{:.2f} %** "
                    "(сходиться на {:.1f} % записів). Ми переведемо це на той "
                    "базис, який ви вкажете.".format(
                        вгадано["врожай"], базис_монітора["базис"],
                        базис_монітора["згода_відсотків"])
                )
            else:
                зауваження.append(
                    "Назва колонки «{}» натякає, що монітор уже сам приводив "
                    "врожайність до сухої основи. Тоді формулу вологості вдруге "
                    "застосовувати не можна — звірте позначку нижче.".format(
                        вгадано["врожай"])
                )
    if вгадано.get("врожай"):
        значення = зведене[вгадано["врожай"]]
        числа = np.asarray(значення, dtype="float64")
        числа = числа[np.isfinite(числа) & (числа > 0)]
        if числа.size:
            медіана = float(np.median(числа))
            одиниця, обґрунтування = util.підказати_одиницю(
                медіана, сеанс.паспорт.get("культура")
            )
    else:
        зауваження.append(
            "Колонку врожайності не впізнано. Вкажіть її самі — без неї рахувати нічого."
        )

    if not вгадано.get("вологість"):
        зауваження.append(
            "Колонки вологості немає. Приведення до базису тоді неможливе: "
            "числа лишаться такими, як їх записав монітор."
        )
    if not вгадано.get("час"):
        зауваження.append(
            "Часу запису немає. Проходи будуть відновлені за геометрією, "
            "а затримку сенсора оцінити не вийде — фільтрація буде обережнішою."
        )
    if not вгадано.get("ширина"):
        зауваження.append(
            "Ширини захвату немає у файлі. Її буде оцінено з відстані між "
            "сусідніми проходами."
        )

    машин = int(зведене["МАШИНА"].nunique())
    звіт["монітор"] = {
        "файли": описи,
        "усього_записів": int(len(зведене)),
        "машин": машин,
        "джерело_машин": джерело_машин,
        "колонки": колонки,
        "вгадано": вгадано,
        "одиниця_врожаю": одиниця,
        "одиниця_обґрунтування": обґрунтування,
        "вже_приведено_здогад": вже_приведено,
        "базис_монітора": базис_монітора,
        "густина": _порада_густини(зведене, вгадано, звіт.get("контур") or {}),
        "зауваження": зауваження,
    }
    return звіт


def _порада_густини(зведене, вгадано, опис_контуру):
    """Від якого кроку до якого має сенс зводити карту на цьому полі.

    Питаємо це ще на розвідці, а не після прогону: людина має бачити, скільки
    важитиме файл, ДО того як чекатиме хвилину на розрахунок."""
    import numpy as np

    from app.core import thinning

    площа = опис_контуру.get("площа_га")
    if not площа:
        return None
    жатка = None
    назва = вгадано.get("ширина")
    if назва and назва in зведене.columns:
        значення = np.asarray(зведене[назва], dtype="float64")
        значення = значення[np.isfinite(значення) & (значення > 0.5) & (значення < 60)]
        if значення.size:
            жатка = float(np.median(значення))
    return thinning.порадити(площа, жатка)


def _відновити_базис_монітора(зведене, вгадано):
    """Пара «волога маса + приведена маса» видає базис монітора однозначно.

    Шукаємо вологу пару до тієї колонки, яку взяли за врожай: якщо взяли
    `Yld_Mass_D`, вологою парою буде `Yld_Mass_W`. Порівнюємо не назви цілком,
    а їхній спільний початок — назви в DBF обрізані."""
    from app.core import moisture, util

    сухий = вгадано.get("врожай")
    вологість = вгадано.get("вологість")
    if not сухий or not вологість:
        return None

    основа = util._спростити(сухий).rstrip("d") .replace("dry", "")
    кандидати = []
    for назва in зведене.columns:
        if назва == сухий or назва == вологість:
            continue
        спрощена = util._спростити(назва)
        if moisture.схоже_на_приведене(назва):
            continue
        if спрощена.startswith(основа[: max(6, len(основа) - 2)]):
            кандидати.append(назва)
    for назва in кандидати:
        знайдене = moisture.відновити_базис(
            зведене[назва], зведене[сухий], зведене[вологість])
        if знайдене and знайдене["згода_відсотків"] >= 90.0:
            знайдене["вологу_взято_з"] = назва
            return знайдене
    return None
