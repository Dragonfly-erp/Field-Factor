# -*- coding: utf-8 -*-
"""Операції над полем.

Задача запускається НАД полем із картотеки, а не замість нього: контур
береться з поля, результат повертається туди ж окремим шаром. Так поле
з роками обростає шарами, і жоден файл не треба шукати вдруге.
"""

import os
import shutil


def _перенести_у_шари(картотека, господарство, поле, джерело, назва_файлу):
    тека = os.path.join(картотека.тека_поля(господарство, поле), "шари")
    os.makedirs(тека, exist_ok=True)
    ціль = os.path.join(тека, назва_файлу)
    shutil.copy2(джерело, ціль)
    return назва_файлу


def нормалізація(сеанс, картотека, господарство, поле):
    """Нормалізація карти врожайності з реєстрацією результату як шару поля."""
    from app.core import pipeline

    pipeline.виконати(сеанс)
    if not сеанс.підсумок:
        return

    рік = сеанс.паспорт.get("рік")
    культура = (сеанс.паспорт.get("культура") or "").strip()
    тека_віддачі = сеанс.підсумок["_тека"]
    основа = сеанс.підсумок["_основа"]

    # Шар поля береться з ТОГО САМОГО shapefile, який поїхав господарству.
    # Доти тут шукався .gpkg і .shp відкинутих записів — обидва зникли з
    # віддачі 21.08, коли з неї прибрали двадцять зайвих файлів. Помилки не
    # було: `if os.path.isfile(...)` мовчки не спрацьовував, поле лишалось
    # без шару врожайності, і зонуванню не було з чого будувати зони.
    # Тому тут не «якщо файл є», а «файлу нема — це збій»: віддача без
    # головного файлу означає, що зламався прогін, а не що шар не потрібен.
    основний = os.path.join(тека_віддачі,
                            "{}_yield_normalized_points.shp".format(основа))
    if not os.path.isfile(основний):
        біда = ("Прогін завершився, але {} у віддачі немає — реєструвати як шар "
                "поля нічого.".format(os.path.basename(основний)))
        # Через журнал, а не тільки вгору: виняток із потоку задачі йде в
        # консоль, а людина дивиться в смужку прогресу й побачила б там
        # спокійне «готово».
        сеанс.журнал.збій(біда)
        raise FileNotFoundError(біда)

    for розширення in (".shp", ".shx", ".dbf", ".prj", ".cpg"):
        шматок = основний.replace(".shp", розширення)
        if os.path.isfile(шматок):
            _перенести_у_шари(картотека, господарство, поле, шматок,
                              "врожайність_{}{}".format(рік, розширення))
    густина = сеанс.підсумок.get("густина") or {}
    крок = густина.get("крок_м")
    картотека.додати_шар(
        господарство, поле, "врожайність_{}".format(рік),
        "Врожайність {} · {}".format(рік, культура) if культура
        else "Врожайність {}, кг/га".format(рік),
        "врожайність", "врожайність_{}.shp".format(рік),
        рік=рік, культура=культура or None, атрибут="YLD_KGHA",
        походження="нормалізовано з монітора комбайна · {} точок{}".format(
            сеанс.підсумок["точок_усього"],
            " · сітка {:.0f} м".format(крок) if крок else ""),
    )

    сеанс.підсумок["поле"] = поле
    сеанс.підсумок["господарство"] = господарство


def зонування(сеанс, картотека, господарство, поле, завдання):
    """Зони за обраними джерелами. Результат лягає шаром цього ж поля."""
    from app.core import zones

    zones.виконати(сеанс, завдання)
    if not сеанс.підсумок_зон:
        return

    рік = сеанс.паспорт.get("рік")
    тека_віддачі = сеанс.шлях("3_віддача")
    імʼя_файлів = сеанс.підсумок_зон["_імʼя"]
    ключ = завдання.get("ключ") or "зони"
    назва = завдання.get("назва") or "Зони"

    for розширення in (".shp", ".shx", ".dbf", ".prj", ".cpg"):
        шматок = os.path.join(тека_віддачі, імʼя_файлів + розширення)
        if os.path.isfile(шматок):
            _перенести_у_шари(картотека, господарство, поле, шматок,
                              "{}{}".format(ключ, розширення))

    # точки відбору — окремий шар: із ним їде відбірник
    if os.path.isfile(os.path.join(тека_віддачі, імʼя_файлів + "_sampling.shp")):
        for розширення in (".shp", ".shx", ".dbf", ".prj", ".cpg"):
            шматок = os.path.join(тека_віддачі, імʼя_файлів + "_sampling" + розширення)
            if os.path.isfile(шматок):
                _перенести_у_шари(картотека, господарство, поле, шматок,
                                  "{}_відбір{}".format(ключ, розширення))
        картотека.додати_шар(
            господарство, поле, ключ + "_відбір",
            "Точки відбору · {}".format(назва), "відбір",
            "{}_відбір.shp".format(ключ), рік=рік, атрибут="SAMPLE_ID",
            походження="по одній точці в серцевині кожної групи зон",
        )

    картотека.додати_шар(
        господарство, поле, ключ, назва, "зони", "{}.shp".format(ключ),
        рік=рік, атрибут=завдання.get("атрибут_показу"),
        походження="{} зон · {}".format(
            сеанс.підсумок_зон["зон"],
            ", ".join(д["джерело"] for д in (сеанс.підсумок_зон.get("джерела") or []))),
    )
