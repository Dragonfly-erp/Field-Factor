# ПРОПОЗИЦІЯ: СКІЛЬКИ ЗРАЗКІВ І ЯКОЮ КОМІРКОЮ
# ═══════════════════════════════════════════════════════════════════════
# Сенс оптимізованого відбору — не в тому, щоб нарізати красивіше, а в тому,
# щоб зразків стало менше при тій самій якості. Тому програма має сказати
# число до того, як людина погодиться: стільки зразків замість стількох,
# і ось чому саме стільки.


def запропонувати(контур, контраст, атрибут=None,
                  класична_га=КОМІРКА_ЗАМОВЧУВАННЯ_ГА,
                  мін_га=КОМІРКА_МІН_ГА, макс_га=КОМІРКА_МАКС_ГА):
    """Що програма радить для цього поля — і скільки це заощаджує.

    Логіка проста й пояснювана: чим строкатіше поле, тим дрібніша комірка
    потрібна, щоб зразок лишався репрезентативним. Строкатість міряємо
    кількістю різних ділянок і тим, наскільки вони дрібні."""
    from shapely.ops import unary_union

    метричний = _у_метри(контур)
    поле_га = float(unary_union(list(метричний.geometry.values)).area / 10000.0)

    ділянки = _у_метри(контраст)
    атрибут = атрибут or _знайти_атрибут(ділянки)
    площі = {}
    for _, д in ділянки.iterrows():
        к = _клас(д, атрибут)
        площі[к] = площі.get(к, 0.0) + д.geometry.area / 10000.0
    класів = len([к for к in площі if к is not None])
    найменша_ділянка = min([п for к, п in площі.items() if к is not None],
                           default=поле_га)

    # Комірка не має бути більшою за найменшу ділянку: інакше ця ділянка
    # ніколи не отримає власного зразка й розчиниться в сусідній.
    порада = min(макс_га, max(мін_га, найменша_ділянка))
    порада = round(порада * 2) / 2.0          # до півгектара, щоб було кругло

    класичних = max(1, int(round(поле_га / класична_га)))

    # Не вгадуємо, скільки вийде комірок, а будуємо сітку й рахуємо.
    # Оцінка «площа поділити на комірку» давала 21 там, де насправді
    # виходить 14: після підтягування до меж контрасту комірки зростають.
    сітка, _ = динамічна(контур, контраст, атрибут, гектарів=порада,
                         мін_га=мін_га, макс_га=макс_га)
    оптимальних = max(1, len(сітка))

    return dict(
        поле_га=round(поле_га, 2),
        ділянок=класів,
        найменша_ділянка_га=round(найменша_ділянка, 2),
        порада_га=порада,
        класична_га=класична_га,
        зразків_класично=класичних,
        зразків_оптимально=оптимальних,
        заощадження=класичних - оптимальних,
        заощадження_відсотків=(round(100.0 * (класичних - оптимальних)
                                     / класичних, 1) if класичних else 0.0),
        межі=dict(мін_га=мін_га, макс_га=макс_га),
        чому=("найменша ділянка на полі — %.2f га, тому комірка більша за неї "
              "не має сенсу: така ділянка не дістала б власного зразка"
              % найменша_ділянка),
    )


