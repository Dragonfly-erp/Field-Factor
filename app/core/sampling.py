# ПРАВКА НАВПАКИ: «ХОЧУ СТІЛЬКИ ЗРАЗКІВ»
# ═══════════════════════════════════════════════════════════════════════
# Замовник рідко думає гектарами комірки. Він думає грошима, а гроші тут —
# це кількість аналізів. Тому має бути й зворотний хід: сказав «двадцять»
# — програма підібрала комірку.


def підібрати_комірку(контур, скільки_зразків, контраст=None, атрибут=None,
                      мін_га=None, макс_га=None, кут=0.0, кроків=14):
    """Що змінити, щоб зразків стало стільки, скільки просять.

    **Для класичної сітки** відповідь пряма: розмір комірки. Ділити площу на
    кількість не можна — край поля ріже квадрати навскіс, — тому шукаємо
    навпомацки, будуючи сітку.

    **Для оптимізованої розмір комірки майже нічого не вирішує.** Перша версія
    цієї функції шукала саме його й видавала дурницю: на прохання «вісім
    зразків» радила комірку 27,58 га — більшу за дві третини поля — і все
    одно отримувала пʼятнадцять. Причина в тому, що після підтягування до
    меж ділянок кожна комірка все одно затискається між мінімумом і
    максимумом. Скільки не проси — вийде те, що дозволяє ця пара чисел.

    Тому для оптимізованої підбираємо **саму пару меж**, розсуваючи або
    стискаючи її цілком. І чесно кажемо, куди довелось зайти: якщо заради
    тридцяти зразків мінімум опустився до 1,2 га, замовник має це побачити
    до того, як платити."""
    from shapely.ops import unary_union

    метричний = _у_метри(контур)
    поле_га = float(unary_union(list(метричний.geometry.values)).area / 10000.0)
    скільки_зразків = max(1, int(скільки_зразків))
    базовий_мін = мін_га or КОМІРКА_МІН_ГА
    базовий_макс = макс_га or КОМІРКА_МАКС_ГА

    спроби = []

    # ── класична: шукаємо розмір комірки ────────────────────────────────
    if контраст is None:
        низ, верх = 0.001, max(поле_га, 1.0)
        найкраще = None
        for _ in range(кроків + 6):
            середина = (низ + верх) / 2.0
            сітка_спроби = класична(контур, середина, кут)
            вийшло = len(сітка_спроби)
            спроби.append((round(середина, 4), вийшло))
            if найкраще is None or abs(вийшло - скільки_зразків) < abs(
                    найкраще[1] - скільки_зразків):
                найкраще = (середина, вийшло, сітка_спроби)
            if вийшло == скільки_зразків:
                break
            if вийшло > скільки_зразків:
                низ = середина
            else:
                верх = середина
        га, вийшло, знайдена_сітка = найкраще
        return dict(варіант="класична", га=round(га, 3), зразків=вийшло,
                    _комірки=знайдена_сітка,
                    просили=скільки_зразків, точно=(вийшло == скільки_зразків),
                    мін_га=None, макс_га=None, спроби=спроби,
                    чому=("Комірка %.2f га дає %d зразків." % (га, вийшло))
                    + ("" if вийшло == скільки_зразків else
                       " Рівно %d не виходить: край поля ріже квадрати "
                       "навскіс." % скільки_зразків))

    # ── оптимізована: шукаємо пару меж ──────────────────────────────────
    ділянок = len(контраст)
    низ, верх = 0.05, 6.0          # у скільки разів розсунути базові межі
    найкраще = None
    for _ in range(кроків):
        масштаб = (низ + верх) / 2.0
        м, М = базовий_мін * масштаб, базовий_макс * масштаб
        комірки, _ = динамічна(контур, контраст, атрибут,
                               гектарів=м * 1.5, мін_га=м, макс_га=М, кут=кут)
        вийшло = len(комірки)
        спроби.append((round(м, 2), round(М, 2), вийшло))
        if найкраще is None or abs(вийшло - скільки_зразків) < abs(
                найкраще[2] - скільки_зразків):
            # Запамʼятовуємо САМУ сітку, а не числа, якими її зробили.
            # Переграти ті самі числа й отримати ту саму сітку не виходить:
            # злиття уламків чутливе до тисячних гектара, і повторна побудова
            # давала на два зразки більше. Обіцянка має бути тим самим
            # обʼєктом, що й результат, а не його копією за описом.
            найкраще = (м, М, вийшло, комірки)
        if вийшло == скільки_зразків:
            break
        if вийшло > скільки_зразків:
            низ = масштаб
        else:
            верх = масштаб

    м, М, вийшло, знайдена_сітка = найкраще
    примітки = []
    if вийшло != скільки_зразків:
        примітки.append(
            "Рівно %d зразків не виходить: комірки підтягуються до меж "
            "ділянок і не діляться довільно." % скільки_зразків)
    if вийшло <= ділянок and скільки_зразків < ділянок:
        примітки.append(
            "Менше ніж %d зразків тут не буде взагалі: стільки на полі "
            "різних ділянок, і кожна має отримати свій." % ділянок)
    if м < КОМІРКА_МІН_ГА:
        примітки.append(
            "Щоб дійти до %d, довелось опустити найменшу комірку до %.2f га "
            "— нижче за робочі %g га. Такі зразки коштують стільки ж, "
            "скільки повні." % (скільки_зразків, м, КОМІРКА_МІН_ГА))
    if М > КОМІРКА_МАКС_ГА:
        примітки.append(
            "Найбільша комірка вийшла %.2f га — вище за робочі %g га. "
            "Усередині такої поле вже могло змінитись."
            % (М, КОМІРКА_МАКС_ГА))

    # Ціль повертаємо з чотирма знаками, а не з двома: сітка чутлива до
    # довжини сторони, і округлення 2,3850 до 2,38 зсувало результат на
    # два зразки. Обіцянка й побудова мають збігатись.
    return dict(
        варіант="оптимізована", га=round(м * 1.5, 4),
        # Межі теж повними: округлення мінімуму з 1,5866 до 1,59 га — це
        # сорок квадратних метрів, і саме вони вирішують, чи зіллється
        # уламок із сусідом. Дві такі розбіжності — і замість обіцяних
        # девʼятнадцяти зразків виходить двадцять один.
        мін_га=round(м, 4), макс_га=round(М, 4),
        мін_показати=round(м, 2), макс_показати=round(М, 2),
        зразків=вийшло, просили=скільки_зразків,
        точно=(вийшло == скільки_зразків), ділянок=ділянок, спроби=спроби,
        _комірки=знайдена_сітка,
        чому=("Межі комірки %.2f–%.2f га дають %d зразків. " % (м, М, вийшло))
        + " ".join(примітки),
        застереження=примітки,
    )


# ═══════════════════════════════════════════════════════════════════════
# ВЕГЕТАЦІЯ ЗА ІСТОРІЄЮ КУЛЬТУР
# ═══════════════════════════════════════════════════════════════════════
# У наявному коді зонування написано прямо: «культура щороку інша, тож
# прив'язуватись до її календаря не можна, беремо максимум за квітень-серпень».
# Власник каже інакше: питати, яка культура була і коли, щоб брати доречні
# знімки. Обидва праві, але про різне, і різницю варто назвати.
#
# **Вікно справді майже нічого не дає.** Максимум NDVI за квітень-вересень
# спіймає пік хоч у пшениці в травні, хоч у кукурудзи в серпні. Тут старий
# коментар має рацію.
#
# **Культура дає інше, і воно важливіше.**
#
# 1. Роки, які не можна брати взагалі. Пар, багаторічні трави, поле під
#    покривною культурою — там малюнок не про ґрунт.
# 2. Різні культури показують ґрунт по-різному. Соняшник на посушливому
#    горбі згорає й дає величезний контраст; озима пшениця на тому самому
#    горбі майже не відрізняється від решти поля. Якщо усереднити піки
#    просто так, рік під соняшником перекричить три роки під пшеницею —
#    і зонування вийде за один посушливий рік, а не за поле.
# 3. Тому кожен рік перед усередненням зводиться до **власної z-оцінки**:
#    у середнє йде малюнок року, а не його гучність.
#
# Вікно все одно ставимо за культурою: воно нічого не псує, зменшує
# кількість зайвих сцен і робить звіт зрозумілим — видно, за який період
# брали кожен рік.

КУЛЬТУРИ = {
    "пшениця озима":   dict(вікно=("04-20", "06-05"), показує="добре"),
    "ячмінь озимий":   dict(вікно=("04-20", "06-01"), показує="добре"),
    "жито":            dict(вікно=("04-25", "06-05"), показує="добре"),
    "ріпак озимий":    dict(вікно=("04-15", "05-25"), показує="середньо"),
    "пшениця яра":     dict(вікно=("05-15", "06-25"), показує="добре"),
    "ячмінь ярий":     dict(вікно=("05-10", "06-20"), показує="добре"),
    "горох":           dict(вікно=("05-10", "06-15"), показує="середньо"),
    "соя":             dict(вікно=("06-25", "08-15"), показує="дуже добре"),
    "соняшник":        dict(вікно=("06-20", "08-10"), показує="дуже добре"),
    "кукурудза":       dict(вікно=("07-01", "08-20"), показує="дуже добре"),
    "гречка":          dict(вікно=("06-20", "08-01"), показує="середньо"),
    "буряк цукровий":  dict(вікно=("07-01", "09-01"), показує="дуже добре"),
    "ріпак ярий":      dict(вікно=("06-01", "07-10"), показує="середньо"),
    "не знаю":         dict(вікно=("04-01", "09-01"), показує="невідомо"),
    "пар":             dict(вікно=None, показує="не показує"),
    "багаторічні трави": dict(вікно=None, показує="не показує"),
}

# Культури, під якими малюнок поля читається найкраще: глибококореневі ярі
# на них першими вигорають там, де мало вологи.
ПОКАЗУЄ_НАЙКРАЩЕ = "дуже добре"


def довідник_культур():
    """Список для екрана: назва, вікно, наскільки під нею видно ґрунт."""
    вихід = []
    for назва, опис in КУЛЬТУРИ.items():
        вікно = опис["вікно"]
        вихід.append(dict(
            назва=назва,
            вікно=("%s … %s" % вікно) if вікно else "не береться",
            показує=опис["показує"],
            береться=вікно is not None))
    return вихід


def вегетація_за_історією(контур, історія, налаштування, база, журнал,
                          індекс="NDVI"):
    """Багаторічний малюнок вегетації з урахуванням того, що на полі росло.

    історія — [{"рік": 2024, "культура": "соняшник"}, …].

    Кожен рік береться у вікно своєї культури, зводиться до z-оцінки в межах
    поля і аж тоді йде в середнє. Рік без культури або під паром не береться
    зовсім — і про це сказано, а не мовчки пропущено."""
    import numpy as np

    from app.core import satellite, sources

    сітка = satellite.сітка_поля(контур)
    кеш = sources.тека_кешу(налаштування, база)
    межі = tuple(контур.to_crs(4326).total_bounds)

    try:
        клієнт = sources._клієнт()
    except Exception as помилка:
        return None, {"причина": "каталог знімків недоступний: %s" % помилка,
                      "рядки": []}

    малюнки, рядки = [], []
    for запис_року in історія:
        рік = int(запис_року.get("рік") or 0)
        культура = (запис_року.get("культура") or "не знаю").strip()
        опис = КУЛЬТУРИ.get(культура, КУЛЬТУРИ["не знаю"])
        вікно = опис["вікно"]
        if not рік:
            continue
        if вікно is None:
            рядки.append(dict(рік=рік, культура=культура, сцен=0,
                              стан="не беремо",
                              чому="під цією культурою малюнок не про ґрунт"))
            журнал.сказати("  %d · %s — не беремо: малюнок не про ґрунт"
                           % (рік, культура))
            continue

        період = "%d-%s/%d-%s" % (рік, вікно[0], рік, вікно[1])
        try:
            записи = sources._сцени(клієнт, межі, період)
        except Exception as помилка:
            рядки.append(dict(рік=рік, культура=культура, сцен=0,
                              стан="пошук не вдався", чому=str(помилка)[:120]))
            continue

        шари = []
        for запис in записи:
            try:
                індекси = satellite._прочитати_сцену(запис, сітка, кеш)
            except Exception:
                continue
            if індекси is not None:
                шари.append(індекси.get(індекс, індекси["NDVI"]))
            if len(шари) >= 5:
                break

        if not шари:
            рядки.append(dict(рік=рік, культура=культура, сцен=0,
                              стан="чистих знімків немає",
                              чому="у вікні %s хмарно" % період))
            журнал.сказати("  %d · %s — чистих знімків немає" % (рік, культура))
            continue

        with np.errstate(invalid="ignore"):
            пік = np.nanmax(np.stack(шари), axis=0).astype("float32")
            # Кожен рік — до власної z-оцінки. Інакше рік під соняшником
            # перекричить три роки під пшеницею, і зони вийдуть за один
            # посушливий сезон, а не за поле.
            середнє = float(np.nanmean(пік))
            розкид = float(np.nanstd(пік)) or 1.0
        малюнки.append((пік - середнє) / розкид)
        рядки.append(dict(рік=рік, культура=культура, сцен=len(шари),
                          стан="узято", вікно=період,
                          показує=опис["показує"]))
        журнал.сказати("  %d · %s — %d чистих знімків, вікно %s"
                       % (рік, культура, len(шари), період))

    if not малюнки:
        return None, {"причина": "жодного року з придатними знімками",
                      "рядки": рядки}

    стос = np.stack(малюнки)
    with np.errstate(invalid="ignore"):
        малюнок = np.nanmean(стос, axis=0).astype("float32")
        мінливість = (np.nanstd(стос, axis=0).astype("float32")
                      if len(малюнки) > 1 else np.zeros_like(малюнок))

    добрих = [р for р in рядки if р["стан"] == "узято"]
    сильних = [р for р in добрих if р.get("показує") == ПОКАЗУЄ_НАЙКРАЩЕ]
    застереження = []
    if len(добрих) < 3:
        застереження.append(
            "Років із придатними знімками лише %d. Малюнок за один-два роки "
            "— це радше погода тих років, ніж стала різниця ґрунту"
            % len(добрих))
    if not сильних:
        застереження.append(
            "Жодного року під культурою, яка добре показує ґрунт (соняшник, "
            "кукурудза, соя, буряк). Під зерновими різниця видно слабше")

    return ({"вегетація": малюнок, "мінливість_вегетації": мінливість,
             "_сітка": сітка},
            {"років": len(малюнки), "індекс": індекс, "рядки": рядки,
             "застереження": застереження})
