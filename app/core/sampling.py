def _колонки_шару(шлях):
    import geopandas as gpd

    try:
        зразок = gpd.read_file(шлях, rows=1)
        return [str(к) for к in зразок.columns if к != "geometry"]
    except Exception:
        return []


def наявні_джерела(картотека, господарство, поле):
    """Що на цьому полі є для пошуку однорідних ділянок.

    Не «які шари завантажені», а **що з них можна зробити**: у файлі
    сканування лежать і висота, і електропровідність, і це два різні
    джерела, хоч файл один."""
    import os

    шари = картотека.шари(господарство, поле)
    знайдено = {}

    for шар in шари:
        тип = шар.get("тип")
        шлях = os.path.join(картотека.тека_поля(господарство, поле),
                            "шари", шар.get("файл", ""))
        if not os.path.isfile(шлях):
            continue
        колонки = _колонки_шару(шлях) if тип in (
            "сканування", "ec", "рельєф", "врожайність") else []
        великі = [к.upper() for к in колонки]

        for ключ in ("рельєф", "EC", "врожайність"):
            підходить = [к for к, вел in zip(колонки, великі)
                         if any(вел.startswith(з) for з in ОПИС_ДЖЕРЕЛ[ключ]["колонки"])]
            if підходить:
                запис = знайдено.setdefault(ключ, dict(колонки=[], шари=[]))
                запис["колонки"].extend(підходить)
                if шар["ключ"] not in [ш["ключ"] for ш in запис["шари"]]:
                    запис["шари"].append(dict(ключ=шар["ключ"],
                                              назва=шар.get("назва"),
                                              тип=тип))

    вихід = []
    for ключ, опис in ОПИС_ДЖЕРЕЛ.items():
        є = знайдено.get(ключ)
        if ключ == "вегетація":
            вихід.append(dict(ключ=ключ, назва=опис["назва"], чому=опис["чому"],
                              є=True, потребує="роки й культуру",
                              колонки=[], шари=[],
                              примітка="береться з супутника, потрібен "
                                       "інтернет і питання про культуру"))
            continue
        вихід.append(dict(
            ключ=ключ, назва=опис["назва"], чому=опис["чому"],
            є=bool(є),
            колонки=sorted(set(є["колонки"])) if є else [],
            шари=є["шари"] if є else [],
            примітка="" if є else "на цьому полі такого шару немає"))
    return вихід


# ═══════════════════════════════════════════════════════════════════════
# ОДНОРІДНІ ДІЛЯНКИ З ВЛАСНИХ ШАРІВ
# ═══════════════════════════════════════════════════════════════════════
# Це не нове зонування — це той самий механізм, що будує зони в програмі,
# тільки покликаний під відбір і без запису шарів на диск. Писати другий
# кластеризатор поруч із наявним означало б завести два джерела істини,
# які потім розійдуться.

КРОК_СІТКИ_М = 10.0
ДІЛЯНОК_ЗАМОВЧУВАННЯ = 4
МІН_ДІЛЯНКА_ГА = 0.5


def ділянки_з_джерел(контур, шари, ділянок=ДІЛЯНОК_ЗАМОВЧУВАННЯ,
                     крок_м=КРОК_СІТКИ_М, мін_ділянка_га=МІН_ДІЛЯНКА_ГА,
                     журнал=None, поверхні_готові=None):
    """Точкові шари поля → однорідні ділянки.

    шари — список (назва, GeoDataFrame точок, атрибут). Кожен стає поверхнею
    на спільній сітці, поверхні зводяться в суміш, суміш ріжеться на
    ділянки. Ділянка = шматок поля, усередині якого джерела кажуть те саме."""
    import numpy as np

    from app.core import sources, zones

    метричний = _у_метри(контур)
    # Вегетація приходить уже поверхнею, і на СВОЇЙ сітці. Тоді спільною
    # сіткою стає її: перекладати растр на іншу сітку заради однаковості
    # означало б розмити його двічі.
    готові = poверхні_список(поверхні_готові)
    сітка = (готові[0][2] if готові else _сітка_поля(метричний, крок_м))
    маска = zones._маска_поля(метричний, сітка)

    поверхні, ужиті = [], []
    for назва, поверхня, _ in готові:
        значення = поверхня[маска]
        добрі = np.isfinite(значення)
        if добрі.sum() < 10 or float(np.nanstd(значення[добрі])) == 0:
            continue
        середнє = float(np.nanmean(значення[добрі]))
        розкид = float(np.nanstd(значення[добрі])) or 1.0
        поверхні.append((поверхня - середнє) / розкид)
        ужиті.append(назва)
    for назва, точки, атрибут in шари:
        точки_м = точки.to_crs(метричний.crs)
        поверхня = sources.з_точок(точки_м, атрибут, сітка, журнал, назва=назва)
        if поверхня is None:
            continue
        значення = поверхня[маска]
        добрі = np.isfinite(значення)
        if добрі.sum() < 10 or float(np.nanstd(значення[добрі])) == 0:
            continue
        # Кожне джерело зводимо до z-оцінки: інакше електропровідність
        # у мСм/м і висота в метрах не порівнюються між собою, і те,
        # у якого числа більший розмах, і визначить зони.
        середнє = float(np.nanmean(значення[добрі]))
        розкид = float(np.nanstd(значення[добрі])) or 1.0
        поверхні.append((поверхня - середнє) / розкид)
        ужиті.append(назва)

    if not поверхні:
        raise ValueError("З наявних шарів не вийшло жодної поверхні: "
                         "у них немає придатних значень")

    суміш = np.nanmean(np.dstack(поверхні), axis=2)
    суміш[~маска] = np.nan

    мітки = zones._кластери(суміш, маска, int(ділянок))
    мітки = zones._згладити(мітки, маска)
    zones._прибрати_дрібне(мітки, маска, крок_м, мін_ділянка_га,
                           журнал or _мовчазний())
    полігони = zones._полігонізувати(мітки, сітка["перетворення"], метричний)
    полігони = полігони.rename(columns={"зона": "ZONE_ID"}) \
        if "зона" in полігони.columns else полігони
    return полігони, dict(ужиті=ужиті, ділянок=int(ділянок), крок_м=крок_м)


def _сітка_поля(метричний, крок_м):
    from rasterio.transform import from_origin

    x0, y0, x1, y1 = метричний.total_bounds
    ширина = max(2, int(math.ceil((x1 - x0) / крок_м)))
    висота = max(2, int(math.ceil((y1 - y0) / крок_м)))
    return dict(перетворення=from_origin(x0, y1, крок_м, крок_м),
                ширина=ширина, висота=висота, крок=крок_м)


