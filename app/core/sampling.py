# -*- coding: utf-8 -*-
"""СІТКОВИЙ ВІДБІР. Де брати зразки, коли зон ще немає.

Зонування каже «ось п'ять різних шматків поля». Але поки зон немає — або
господарство їм не довіряє — відбирають по сітці. І тут є одна річ, яку
роблять неправильно частіше, ніж будь-що інше в агрохімії.

**Комірка не має накривати дві протилежні ділянки.** Якщо квадрат ліг так,
що половина його на маківці горба, а половина в улоговині, то зсипані разом
проби дадуть середнє, якого немає ніде: ні на горбі, ні в улоговині. Це
число потім поїде в норму, і норма буде неправильною в обох місцях одразу.

Тому тут дві сітки:

**Класична** — рівні квадрати заданої площі. Проста, передбачувана, і саме
її псує строкате поле.

**Динамічна** — та сама сітка, але її межі **підтягуються до меж контрасту**.
Комірка ріжеться там, де проходить межа між різними ділянками, дрібні уламки
приростають до сусіда свого ж класу, завеликі шматки діляться. На виході
кожна комірка лежить усередині одного класу — і зразок із неї щось означає.

**Про розмір.** В Україні дрібніше за гектар не відбирають: це дорого і
ніхто за це не платить. Робочий діапазон — від двох до п'яти гектарів на
комірку. Тому мінімум тут не 0,1 га, як у західних посібниках, а два.
"""

import io
import math

# ═══════════════════════════════════════════════════════════════════════
# РОЗМІРИ
# ═══════════════════════════════════════════════════════════════════════
# Ці межі стосуються ТІЛЬКИ оптимізованого відбору, де розмір комірки
# пропонує програма. У класичній сітці розмір каже замовник — хоч 0,01 га,
# хоч менше, і програма не має права його виправляти. Замовник платить за
# аналізи, він і вирішує, скільки їх буде.
#
# Числа з того, за що платять: в Україні дрібніше за гектар масово не
# відбирають, робочий діапазон — два-п'ять гектарів на комірку.

КОМІРКА_МІН_ГА = 2.0
КОМІРКА_МАКС_ГА = 5.0
КОМІРКА_ЗАМОВЧУВАННЯ_ГА = 3.0

# Клапоть, менший за це і без жодного сусіда, — залишок обрізання контуру,
# а не шматок поля. Такі викидаємо, але рахуємо й кажемо скільки.
СПЕК_ГА = 0.05

# Наскільки один клас має переважати в комірці, щоб вважати її однорідною.
ОДНОРІДНІСТЬ = 0.80

# Точка відбору не ставиться ближче за це до межі: там ґрунт уже перехідний,
# і проба збере суміш.
ВІД_МЕЖІ_М = 20.0


# ═══════════════════════════════════════════════════════════════════════
# ДОПОМІЖНЕ
# ═══════════════════════════════════════════════════════════════════════


def _у_метри(шар):
    """Площі й відстані рахуються в метрах. У градусах гектар не гектар."""
    if шар.crs is None:
        return шар.set_crs(4326).to_crs(шар.estimate_utm_crs())
    if шар.crs.is_geographic:
        return шар.to_crs(шар.estimate_utm_crs())
    return шар


def сторона_м(гектарів):
    return math.sqrt(гектарів * 10000.0)


def серцевина(полігон):
    """Найглибша точка полігона — та, що найдалі від будь-якої межі.

    Не центр ваги: у підкови центр ваги лежить поза фігурою, а відбірник
    поїде саме туди, куди показала програма."""
    from shapely.algorithms.polylabel import polylabel

    try:
        return polylabel(полігон, tolerance=1.0)
    except Exception:
        return полігон.representative_point()


def _відстань_до_межі(точка, полігон):
    return точка.distance(полігон.exterior) if полігон.exterior else 0.0


# ═══════════════════════════════════════════════════════════════════════
# КЛАСИЧНА СІТКА
# ═══════════════════════════════════════════════════════════════════════


def класична(контур, гектарів=КОМІРКА_ЗАМОВЧУВАННЯ_ГА, кут=0.0,
             зливати_край=False, мін_га=КОМІРКА_МІН_ГА,
             макс_га=КОМІРКА_МАКС_ГА):
    """Рівні квадрати заданої площі, обрізані контуром поля.

    **Розмір каже замовник.** Хоч 0,01 га, хоч менше — програма його не
    виправляє й нічого не зливає, поки не попросять: замовник платить за
    аналізи і сам вирішує, скільки їх буде.

    зливати_край=True — прибрати крайові уламки, злив їх із сусідами.
    За замовчуванням вимкнено: у класичній сітці рівні квадрати і є те,
    що замовляли, а обрізані краї — чесний наслідок форми поля.

    кут — поворот сітки в градусах. Придається, коли поле витягнуте по
    діагоналі: неповернена сітка нарізає його на самі трикутники."""
    import geopandas as gpd
    from shapely import affinity
    from shapely.geometry import box
    from shapely.ops import unary_union

    метричний = _у_метри(контур)
    поле = unary_union(list(метричний.geometry.values))
    сторона = сторона_м(гектарів)

    осередок = поле.centroid
    робоче = (affinity.rotate(поле, -кут, origin=осередок) if кут else поле)
    x0, y0, x1, y1 = робоче.bounds
    # З запасом на пів комірки з кожного боку, щоб поворот не з'їв край.
    x0 -= сторона
    y0 -= сторона

    комірки = []
    y = y0
    while y < y1 + сторона:
        x = x0
        while x < x1 + сторона:
            квадрат = box(x, y, x + сторона, y + сторона)
            if кут:
                квадрат = affinity.rotate(квадрат, кут, origin=осередок)
            шматок = квадрат.intersection(поле)
            if not шматок.is_empty and шматок.area > 0:
                комірки.extend(_розібрати(шматок))
            x += сторона
        y += сторона

    сітка = gpd.GeoDataFrame({"клас": [0] * len(комірки)},
                             geometry=комірки, crs=метричний.crs)
    if зливати_край:
        # Край поля ріже квадрати навскіс, і по периметру лишаються уламки
        # по сотій гектара. Зразок із такого уламка коштує стільки ж, скільки
        # з повної комірки. Класична сітка класів не знає, тому зливаємо
        # з будь-яким сусідом.
        сітка, _ = злити_дрібні(сітка, мін_га * 10000.0, макс_га * 10000.0,
                                за_класом=False)
    return сітка


def _розібрати(геометрія):
    """MultiPolygon → окремі полігони. Дірка в полі ріже комірку надвоє,
    і два шматки по різні боки яру — це два різні зразки, а не один."""
    if геометрія.geom_type == "Polygon":
        return [геометрія]
    return [г for г in геометрія.geoms if г.geom_type == "Polygon" and г.area > 0]


# ═══════════════════════════════════════════════════════════════════════
# ДИНАМІЧНА СІТКА
# ═══════════════════════════════════════════════════════════════════════


def динамічна(контур, контраст, атрибут=None,
              гектарів=КОМІРКА_ЗАМОВЧУВАННЯ_ГА,
              мін_га=КОМІРКА_МІН_ГА, макс_га=КОМІРКА_МАКС_ГА, кут=0.0):
    """Сітка, межі якої підтягнуті до меж контрасту.

    контраст — шар, що ділить поле на різні ділянки: зони, класи врожайності,
    класи вегетації. Комірка ріжеться його межами, дрібні уламки приростають
    до сусіда СВОГО класу, завеликі шматки діляться навпіл."""
    import geopandas as gpd

    # Для динамічної край не зливаємо: його все одно поріже контраст, і
    # злиття тут тільки сплутало б класи.
    сітка = класична(контур, гектарів, кут, зливати_край=False)
    ділянки = _у_метри(контраст).to_crs(сітка.crs)
    атрибут = атрибут or _знайти_атрибут(ділянки)

    # --- 1 · ріжемо сітку межами контрасту
    шматки = []
    for номер, комірка in enumerate(сітка.geometry.values):
        накрито = 0.0
        for _, д in ділянки.iterrows():
            перетин = комірка.intersection(д.geometry)
            if перетин.is_empty or перетин.area <= 0:
                continue
            накрито += перетин.area
            for частина in _розібрати(перетин):
                шматки.append(dict(комірка=номер, клас=_клас(д, атрибут),
                                   geometry=частина))
        # Те, що не накрив жоден клас, — теж шматок, але без класу.
        решта = комірка.area - накрито
        if решта > комірка.area * 0.02:
            без_класу = комірка
            for _, д in ділянки.iterrows():
                без_класу = без_класу.difference(д.geometry)
            for частина in _розібрати(без_класу):
                if частина.area > 0:
                    шматки.append(dict(комірка=номер, клас=None,
                                       geometry=частина))

    if not шматки:
        сітка["клас"] = None
        return сітка, dict(зрізано=0, приросло=0, поділено=0)

    поділ = gpd.GeoDataFrame(шматки, crs=сітка.crs)

    # --- 2 · дрібні уламки приростають до сусіда свого класу
    поділ, приросло = злити_дрібні(поділ, мін_га * 10000.0,
                                   макс_га * 10000.0, за_класом=True)
    # Другий прохід для тих, кому нема куди рости під стелею. Комірка
    # у пʼять із половиною гектарів замість сотої гектара — це очевидний
    # обмін, і робити його треба, а не лишати уламок «за правилами».
    поділ, ще = злити_дрібні(поділ, мін_га * 10000.0, float("inf"),
                             за_класом=True)
    приросло += ще

    # --- 3 · завеликі шматки ділимо
    поділ, поділено = _поділити(поділ, макс_га * 10000.0, мін_га * 10000.0)

    поділ, спеків, спеків_га = _викинути_спеки(поділ)
    поділ = поділ.reset_index(drop=True)
    return поділ, dict(зрізано=len(шматки), приросло=приросло,
                       поділено=поділено, спеків=спеків,
                       спеків_га=round(спеків_га, 4))


def _викинути_спеки(шар, поріг_га=СПЕК_ГА):
    """Клапті, менші за поріг і без жодного сусіда, — сміття обрізання.

    Це не поле. Ставити туди точку відбору означає послати людину в кут
    між лісосмугою і дорогою заради шести сотих гектара."""
    геом = list(шар.geometry.values)
    поріг = поріг_га * 10000.0
    лишити = []
    викинуто, викинуто_га = 0, 0.0
    for і, г in enumerate(геом):
        якщо_малий = г.area < поріг
        має_сусіда = any(і != j and (г.touches(геом[j]) or г.intersects(геом[j]))
                         for j in range(len(геом)))
        if якщо_малий and not має_сусіда:
            викинуто += 1
            викинуто_га += г.area / 10000.0
            continue
        лишити.append(і)
    return шар.iloc[лишити], викинуто, викинуто_га


def _знайти_атрибут(шар):
    for варіант in ("ZONE_ID", "зона", "клас", "CLASS", "GRIDCODE", "DN", "value"):
        if варіант in шар.columns:
            return варіант
    return None


def _без_nan(значення):
    """NaN → None. Порівняння NaN із будь-чим, включно з собою, хибне."""
    if значення is None:
        return None
    try:
        if значення != значення:
            return None
    except (TypeError, ValueError):
        pass
    return значення


def _клас(рядок, атрибут):
    """Значення класу або None.

    Окремо ловимо NaN. У шарі з числовою колонкою порожня клітинка приїжджає
    як NaN, а NaN **не дорівнює сам собі** — і два уламки без класу ніколи
    не впізнають одне одного як пару. Через це пʼять клаптів по сотій гектара
    лишались на карті й ніяк не зливались: не тому, що нема сусіда, а тому
    що порівняння завжди хибне."""
    if not атрибут:
        return None
    значення = рядок.get(атрибут)
    if значення is None:
        return None
    try:
        if значення != значення:      # NaN
            return None
    except (TypeError, ValueError):
        pass
    try:
        return int(значення)
    except (TypeError, ValueError):
        return str(значення)


def злити_дрібні(шар, мін_площа, макс_площа, за_класом=True):
    """Дрібні комірки приростають до сусідів, доки не доростуть до мінімуму.

    Ціль злиття — саме **мінімальна площа в гектарах**, а не якась частка
    від цільової комірки. Перша версія зливала все, що менше третини цілі,
    і лишала купу комірок по гектару: формально не уламки, а платити за них
    однаково як за повний зразок.

    За_класом=True — зливати тільки зі своїм класом. Прирости уламок до
    чужого класу означало б зробити рівно те, чого ми уникаємо: змішати
    дві протилежні ділянки в одному зразку. Якщо свого сусіда немає, уламок
    лишається малим і про це сказано у звіті."""
    import geopandas as gpd
    from shapely.ops import unary_union

    шар = шар.reset_index(drop=True)
    живі = {і: г for і, г in enumerate(шар.geometry.values)}
    # pandas перетворює None у числовій колонці на NaN, а NaN не дорівнює
    # сам собі — два клапті без класу ніколи не впізнали б одне одного.
    класи = {і: _без_nan(к)
             for і, к in enumerate(шар.get("клас", [None] * len(шар)))}
    приросло = 0

    while True:
        дрібні = [(живі[і].area, і) for і in живі if живі[і].area < мін_площа]
        if not дрібні:
            break
        дрібні.sort()
        зрушилось = False
        for _, і in дрібні:
            якщо = живі.get(і)
            if якщо is None:
                continue
            найкращий, найменша_сума = None, None
            без_класу = класи[і] is None
            for j, сусід in живі.items():
                if j == і:
                    continue
                # Клапоть, якого не накрив контраст, не несе інформації про
                # ділянку — його можна прирости до будь-кого. Захищаємо тільки
                # ті уламки, у яких клас є.
                if за_класом and not без_класу and класи[j] != класи[і]:
                    continue
                if not якщо.touches(сусід) and not якщо.intersects(сусід):
                    continue
                сума = сусід.area + якщо.area
                if сума > макс_площа:
                    continue
                # Ростемо до найменшого придатного сусіда: так дві дрібні
                # комірки стають однією нормальною, а не липнуть до великої,
                # яку потім доведеться ділити назад.
                if найменша_сума is None or сума < найменша_сума:
                    найкращий, найменша_сума = j, сума
            if найкращий is None:
                continue
            зʼєднане = unary_union([живі[найкращий], якщо])
            if зʼєднане.geom_type != "Polygon":
                continue
            живі[найкращий] = зʼєднане
            if класи[найкращий] is None:
                класи[найкращий] = класи[і]
            живі.pop(і)
            приросло += 1
            зрушилось = True
        if not зрушилось:
            break

    лишок = sorted(живі.items())
    return gpd.GeoDataFrame(
        {"клас": [класи[і] for і, _ in лишок]},
        geometry=[г for _, г in лишок], crs=шар.crs), приросло


def _поділити(поділ, макс_площа, мін_площа):
    """Шматок, більший за стелю, ріжеться навпіл по довшій стороні.

    Ділимо доти, доки половинки не стануть меншими за мінімум: краще одна
    завелика комірка, ніж дві, за які ніхто не заплатить."""
    import geopandas as gpd
    from shapely.geometry import box

    геометрії = list(поділ.geometry.values)
    класи = list(поділ["клас"].values)
    вихід_г, вихід_к, поділено = [], [], 0

    черга = list(zip(геометрії, класи))
    while черга:
        г, к = черга.pop()
        if г.area <= макс_площа or г.area / 2.0 < мін_площа:
            вихід_г.append(г)
            вихід_к.append(к)
            continue
        x0, y0, x1, y1 = г.bounds
        if (x1 - x0) >= (y1 - y0):
            середина = (x0 + x1) / 2.0
            ліва, права = box(x0, y0, середина, y1), box(середина, y0, x1, y1)
        else:
            середина = (y0 + y1) / 2.0
            ліва, права = box(x0, y0, x1, середина), box(x0, середина, x1, y1)
        частини = []
        for половина in (ліва, права):
            частини.extend(_розібрати(г.intersection(половина)))
        частини = [ч for ч in частини if ч.area > 0]
        if len(частини) < 2:
            вихід_г.append(г)
            вихід_к.append(к)
            continue
        поділено += 1
        черга.extend((ч, к) for ч in частини)

    return gpd.GeoDataFrame({"клас": вихід_к}, geometry=вихід_г,
                            crs=поділ.crs), поділено


# ═══════════════════════════════════════════════════════════════════════
# ТОЧКИ ВІДБОРУ
# ═══════════════════════════════════════════════════════════════════════


def точки(комірки, від_межі_м=ВІД_МЕЖІ_М):
    """По одній точці в серцевині кожної комірки.

    Точка ставиться найдалі від меж, які в цієї комірки є. Якщо комірка
    вузька й від межі нікуди не подітись — так і кажемо, а не мовчки ставимо
    на краю."""
    import geopandas as gpd

    метричні = _у_метри(комірки)
    рядки, геометрії = [], []
    for номер, (_, к) in enumerate(метричні.iterrows(), start=1):
        точка = серцевина(к.geometry)
        відстань = _відстань_до_межі(точка, к.geometry)
        рядки.append({
            "SAMPLE_ID": номер,
            "клас": к.get("клас"),
            "площа_га": round(к.geometry.area / 10000.0, 3),
            "від_межі_м": round(float(відстань), 1),
            "тісно": bool(відстань < від_межі_м),
        })
        геометрії.append(точка)
    return gpd.GeoDataFrame(рядки, geometry=геометрії, crs=метричні.crs)


