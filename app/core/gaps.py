"""Фази 10-11: де саме пропуск і як покласти туди точки.

Ключова заборона: не перетворювати поле на квадратну сітку. Добудовані точки
лягають на продовження реальних проходів — з тим самим напрямком, тим самим
кроком уздовж і тією самою відстанню між смугами.
"""

import numpy as np


# ------------------------------------------------------------ покриття


def карта_покриття(таблиця, контур, ширина, крок=None):
    """Растр: де комбайн записував, а де ні. Клітинка ≈ ширина захвату."""
    from rasterio.features import rasterize
    from rasterio.transform import from_origin

    крок = крок or max(5.0, ширина / 2.0)
    xmin, ymin, xmax, ymax = контур.total_bounds
    xmin, ymin, xmax, ymax = xmin - крок, ymin - крок, xmax + крок, ymax + крок
    стовпців = int(np.ceil((xmax - xmin) / крок))
    рядків = int(np.ceil((ymax - ymin) / крок))
    перетворення = from_origin(xmin, ymax, крок, крок)

    поле = rasterize(
        [(контур.geometry.iloc[0], 1)], out_shape=(рядків, стовпців),
        transform=перетворення, fill=0, dtype="uint8",
    ).astype(bool)

    x = таблиця.geometry.x.to_numpy()
    y = таблиця.geometry.y.to_numpy()
    стовпці = np.clip(((x - xmin) / крок).astype("int64"), 0, стовпців - 1)
    рядки = np.clip(((ymax - y) / крок).astype("int64"), 0, рядків - 1)
    покрито = np.zeros((рядків, стовпців), dtype=bool)
    покрито[рядки, стовпці] = True

    # запис накриває смугу завширшки з жатку, а не одну клітинку
    радіус = max(1, int(round((ширина / 2.0) / крок)))
    if радіус >= 1:
        from scipy.ndimage import binary_dilation

        ядро = np.ones((2 * радіус + 1, 2 * радіус + 1), dtype=bool)
        покрито = binary_dilation(покрито, structure=ядро)

    return {
        "поле": поле, "покрито": покрито & поле, "пропуск": поле & ~покрито,
        "перетворення": перетворення, "крок": крок,
        "форма": (рядків, стовпців), "межі": (xmin, ymin, xmax, ymax),
    }


def класифікувати_пропуски(растр, ширина):
    """Кожна діра дістає літеру A/B/C/D за розміром і формою."""
    from scipy.ndimage import label

    мітки, скільки = label(растр["пропуск"])
    площа_клітинки = растр["крок"] ** 2
    смуга = ширина * растр["крок"]

    опис = []
    для_класу = {"A": 0, "B": 0, "C": 0, "D": 0}
    класи = np.zeros_like(мітки, dtype="uint8")

    for номер in range(1, скільки + 1):
        якщо = мітки == номер
        клітинок = int(якщо.sum())
        площа = клітинок * площа_клітинки
        рядки, стовпці = np.where(якщо)
        висота = (рядки.max() - рядки.min() + 1) * растр["крок"]
        довжина = (стовпці.max() - стовпці.min() + 1) * растр["крок"]
        товщина = min(висота, довжина)

        if площа <= смуга * 2:
            клас = "A"
        elif товщина <= ширина * 3.5:
            клас = "B"
        elif площа <= 10000 * 1.5:
            клас = "C"
        else:
            клас = "D"

        класи[якщо] = ord(клас) - ord("A") + 1
        для_класу[клас] += клітинок
        опис.append({"клас": клас, "площа_га": round(площа / 10000, 3),
                     "товщина_м": round(товщина, 1)})

    зведення = {
        клас: round(кількість * площа_клітинки / 10000, 3)
        for клас, кількість in для_класу.items()
    }
    return класи, зведення, опис


# ------------------------------------------------------------ лінії проходів


def лінії_проходів(таблиця, контур, геометрія):
    """Продовження реальних смуг на все поле: координати майбутніх точок."""
    напрямок = геометрія["напрямок_рад"]
    крок_уздовж = max(1.0, геометрія["крок_уздовж_м"])
    крок_упоперек = max(2.0, геометрія["крок_упоперек_м"])

    к, с = np.cos(-напрямок), np.sin(-напрямок)

    def у_систему(x, y):
        return x * к - y * с, x * с + y * к

    def назад(уздовж, впоперек):
        кп, сп = np.cos(напрямок), np.sin(напрямок)
        return уздовж * кп - впоперек * сп, уздовж * сп + впоперек * кп

    xmin, ymin, xmax, ymax = контур.total_bounds
    кути_x = np.array([xmin, xmin, xmax, xmax])
    кути_y = np.array([ymin, ymax, ymin, ymax])
    уздовж_кути, впоперек_кути = у_систему(кути_x, кути_y)

    # фаза смуг береться з реальних проходів, щоб добудоване лягло між ними
    _, впоперек_точок = у_систему(таблиця.geometry.x.to_numpy(), таблиця.geometry.y.to_numpy())
    зсув = float(np.median(впоперек_точок % крок_упоперек)) if len(впоперек_точок) else 0.0

    смуги = np.arange(
        np.floor((впоперек_кути.min() - крок_упоперек) / крок_упоперек) * крок_упоперек + зсув,
        впоперек_кути.max() + крок_упоперек,
        крок_упоперек,
    )
    уздовж = np.arange(уздовж_кути.min() - крок_уздовж,
                       уздовж_кути.max() + крок_уздовж, крок_уздовж)

    сітка_уздовж, сітка_впоперек = np.meshgrid(уздовж, смуги)
    номери = np.repeat(np.arange(len(смуги)), len(уздовж)).reshape(сітка_уздовж.shape)
    x, y = назад(сітка_уздовж.ravel(), сітка_впоперек.ravel())
    return x, y, номери.ravel()


def добудувати_точки(таблиця, контур, растр, класи, геометрія, журнал):
    """Точки-кандидати у пропусках. Уже всередині поля і не поверх наявних."""
    import geopandas as gpd
    from scipy.spatial import cKDTree
    from shapely.prepared import prep

    x, y, смуга = лінії_проходів(таблиця, контур, геометрія)

    # 1. лише там, де є пропуск
    xmin, ymin, xmax, ymax = растр["межі"]
    рядків, стовпців = растр["форма"]
    стовпці = ((x - xmin) / растр["крок"]).astype("int64")
    рядки = ((ymax - y) / растр["крок"]).astype("int64")
    у_межах = (рядки >= 0) & (рядки < рядків) & (стовпці >= 0) & (стовпці < стовпців)
    x, y, смуга = x[у_межах], y[у_межах], смуга[у_межах]
    рядки, стовпці = рядки[у_межах], стовпці[у_межах]

    у_пропуску = растр["пропуск"][рядки, стовпці]
    клас_точки = класи[рядки, стовпці]
    x, y, смуга, клас_точки = (x[у_пропуску], y[у_пропуску],
                               смуга[у_пропуску], клас_точки[у_пропуску])
    if not len(x):
        журнал.сказати("Пропусків, які варто добудовувати, немає.")
        return None

    # 2. строго всередині контуру
    межа = prep(контур.geometry.iloc[0])
    точки = gpd.points_from_xy(x, y)
    всередині = np.array([межа.contains(т) for т in точки])
    x, y, смуга, клас_точки = x[всередині], y[всередині], смуга[всередині], клас_точки[всередині]
    if not len(x):
        return None

    # 3. не дублювати наявні записи
    дерево = cKDTree(np.c_[таблиця.geometry.x, таблиця.geometry.y])
    відстань, _ = дерево.query(np.c_[x, y], k=1)
    досить_далеко = відстань > max(геометрія["крок_уздовж_м"] * 0.7, 1.5)
    x, y, смуга, клас_точки = (x[досить_далеко], y[досить_далеко],
                               смуга[досить_далеко], клас_точки[досить_далеко])
    відстань = відстань[досить_далеко]

    if not len(x):
        журнал.сказати("Усі пропуски вже перекриті наявними записами.")
        return None

    літери = np.array(["", "A", "B", "C", "D"])[np.clip(клас_точки, 0, 4)]
    журнал.сказати(
        "Добудовано {} точок на продовженні смуг (крок уздовж {:.1f} м, "
        "між смугами {:.1f} м).".format(len(x), геометрія["крок_уздовж_м"],
                                        геометрія["крок_упоперек_м"])
    )
    return {"x": x, "y": y, "смуга": смуга, "клас": літери, "відстань_до_опори": відстань}
