ПОРЯДОК = [і[0] for і in СЛОВНИК]


# Скільки знаків реально треба текстовим полям. Без цього кожне з них займає
# у DBF по 80 байтів на запис, і файл роздувається вчетверо.
# Рахується в БАЙТАХ, а не в знаках: кирилиця в UTF-8 займає по два, і поле
# на 22 байти вміщає лише одинадцять українських літер.
ШИРИНИ = {
    "SRC_TYPE": 8, "COMB_ID": 48, "DATETIME": 19, "QC_FLAG": 8,
    "METHOD": 48, "CONF": 4, "GAP_CLASS": 1,
}


def _обрізати(значення, довжина=254):
    if значення is None:
        return None
    текст = str(значення)
    return текст[:довжина]


def зібрати_таблицю(чисті, добудовані, паспорт, метод, вег_колонка=None):
    """Один GeoDataFrame зі схемою під SMS."""
    import geopandas as gpd
    import pandas as pd

    базис = float(паспорт.get("базис") or 0)

    def з_колонки(таблиця, назва, замовчування=np.nan):
        if назва in таблиця.columns:
            return таблиця[назва].to_numpy()
        return np.full(len(таблиця), замовчування)

    частини = []

    if len(чисті):
        час = чисті["ЧАС"] if "ЧАС" in чисті.columns else None
        частини.append(pd.DataFrame({
            "ORIG_ID": з_колонки(чисті, "_ВХІДНИЙ_НОМЕР"),
            "SRC_TYPE": чисті["_ЗМІНЕНО"].map({True: "CORR", False: "ORIG"}).to_numpy()
                        if "_ЗМІНЕНО" in чисті.columns else "ORIG",
            "COMB_ID": чисті["МАШИНА"].to_numpy(),
            "PASS_ID": чисті["ПРОХІД"].to_numpy(),
            "DATETIME": (час.dt.strftime("%Y-%m-%d %H:%M:%S") if час is not None
                         and hasattr(час, "dt") else None),
            "YLD_RAW": з_колонки(чисті, "ВРОЖАЙ_СИР"),
            "YLD_KGHA": чисті["ВРОЖАЙ_БАЗ"].to_numpy(),
            "YLD_SM": np.nan,
            "YLD_LHA": з_колонки(чисті, "ВРОЖАЙ_Л"),
            "MOIST": з_колонки(чисті, "ВОЛОГІСТЬ"),
            "YLD_WET": np.nan,
            "FLOW_TH": np.nan,
            "DUR_S": з_колонки(чисті, "ТРИВАЛІСТЬ") if "ТРИВАЛІСТЬ" in чисті.columns else np.nan,
            "MOIST_BAS": базис,
            "ELEV_M": з_колонки(чисті, "ВИСОТА"),
            "WORK_W_M": з_колонки(чисті, "ШИРИНА"),
            "SWTH_W_M": np.nan,
            "DIST_M": np.nan,
            "CELL_HA": np.nan,
            "SPD_KMH": з_колонки(чисті, "ШВИДКІСТЬ"),
            "QC_FLAG": "OK",
            "METHOD": "MONITOR",
            "CONF": "HIGH",
            "GAP_CLASS": None,
            "VEG_IDX": з_колонки(чисті, вег_колонка) if вег_колонка else np.nan,
            "VEG_YEARS": з_колонки(чисті, "_ВЕГ_РОКИ"),
            "BSI_IDX": з_колонки(чисті, "_ҐРУНТ"),
            "geometry": чисті.geometry.values,
        }))

    if добудовані is not None and len(добудовані):
        частини.append(pd.DataFrame({
            "ORIG_ID": np.nan,
            "SRC_TYPE": "INTERP",
            "COMB_ID": None,
            "PASS_ID": добудовані["смуга"],
            "DATETIME": None,
            "YLD_RAW": np.nan,
            "YLD_KGHA": добудовані["врожай"],
            "YLD_SM": np.nan,
            "YLD_LHA": добудовані.get("врожай_л", np.nan),
            "MOIST": np.nan,
            "YLD_WET": np.nan,
            "FLOW_TH": np.nan,
            "DUR_S": np.nan,
            "MOIST_BAS": базис,
            "ELEV_M": добудовані.get("висота", np.nan),
            "WORK_W_M": добудовані.get("ширина", np.nan),
            "SWTH_W_M": np.nan,
            "DIST_M": np.nan,
            "CELL_HA": np.nan,
            "SPD_KMH": np.nan,
            "QC_FLAG": "FILL",
            # у кожної точки свій метод: близькі розриви й великі ділянки
            # закриваються по-різному, і це має бути видно у файлі
            "METHOD": добудовані.get("метод", метод),
            "CONF": добудовані["довіра"],
            "GAP_CLASS": добудовані["клас"],
            "VEG_IDX": добудовані.get("вег", np.nan),
            "VEG_YEARS": добудовані.get("вег_роки", np.nan),
            "BSI_IDX": добудовані.get("ґрунт", np.nan),
            "geometry": добудовані["geometry"],
        }))

    зведене = pd.concat(частини, ignore_index=True)
    зведене.insert(0, "PT_ID", np.arange(1, len(зведене) + 1))
    зведене["ORIG_ID"] = pd.to_numeric(зведене["ORIG_ID"], errors="coerce")
    for колонка, довжина in ШИРИНИ.items():
        if колонка in зведене.columns:
            зведене[колонка] = зведене[колонка].map(lambda з, д=довжина: _обрізати(з, д))
    зведене = зведене[ПОРЯДОК + ["geometry"]]
    return gpd.GeoDataFrame(зведене, geometry="geometry", crs=чисті.crs)


