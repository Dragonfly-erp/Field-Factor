# Скільки знаків після коми має сенс у кожній величині. Драйвер шейпфайла
# пише float як є, тобто «12045.700000000001» — вісімнадцять байтів там, де
# значуще число має сім. На Г-03 це роздувало DBF із двох мегабайтів до
# одинадцяти. Зайві знаки — не точність, а сміття: врожайність не буває
# відома до мільйонної частки кілограма.
ЗНАКІВ = {
    "YLD_KGHA": 1, "YLD_SM": 1, "YLD_MODEL": 1, "LOSS_KGHA": 1, "LOSS_ZONE": 0, "YLD_WET": 1, "YLD_LHA": 1, "YLD_RAW": 3,
    "SD_KGHA": 1, "MOIST": 2, "MOIST_BAS": 1, "ELEV_M": 2, "SPD_KMH": 2,
    "WORK_W_M": 2, "SWTH_W_M": 2, "DIST_M": 2, "CELL_HA": 4, "DUR_S": 4,   # бувають комірки по 0,2 с: два знаки лишили б
    #              один значущий розряд і зламали б арифметику SMS
    # медіана потоку 0,07 т/год: три знаки лишили б два значущих розряди,
    # а 789 комірок перетворили б на нуль
    "FLOW_TH": 6,
    # індекси лежать у межах 0…1, і четвертий знак — це вже шум сцени
    "VEG_IDX": 4, "VEG_YEARS": 4, "BSI_IDX": 4, "CONF_N": 3,
    # ціле з дірками: у добудованих точок вихідного номера немає, і саме
    # порожнеча робить колонку дробовою. Знаків після коми в номера запису
    # не буває — інакше він перестає бути номером.
    "ORIG_ID": 0,
}


def записати_шейп(таблиця, шлях, стиснути=True):
    таблиця = таблиця.copy()
    for колонка, знаків in ЗНАКІВ.items():
        if колонка in таблиця.columns:
            таблиця[колонка] = таблиця[колонка].astype("float64").round(знаків)
    таблиця.to_file(шлях, driver="ESRI Shapefile", engine="pyogrio", encoding="UTF-8")
    основа = os.path.splitext(шлях)[0]
    with open(основа + ".cpg", "w", encoding="ascii") as ф:
        ф.write("UTF-8")
    if стиснути:
        стиснути_dbf(основа + ".dbf", ШИРИНИ)
    return [основа + р for р in (".shp", ".shx", ".dbf", ".prj", ".cpg")]


def стиснути_dbf(шлях, ширини, знаків=None):
    """Перезаписує DBF так, щоб кожне поле займало стільки, скільки потребує.

    **Чому це не дрібниця.** Драйвер шейпфайла оголошує числове поле як
    24 байти з пʼятнадцятьма знаками після коми і пише «12045.700000000000»
    незалежно від того, що ми округлили в памʼяті: розмір і точність зашиті
    в ОПИС поля, а не в значення. Текстовому полю він так само дає 80 байтів
    на слово «MONITOR».

    На Г-03 це давало рядок у 647 байтів і DBF на 11 МБ. Після переписування —
    близько 150 байтів і два мегабайти. Дані ті самі: врожайність не буває
    відома до мільйонної частки кілограма.

    Тому тут робиться три речі:

    1. для числових полів беремо потрібну кількість знаків після коми з
       `ЗНАКІВ`, а довжину цілої частини — з фактичного вмісту файлу;
    2. кожне число переформатовується під нову точність і вирівнюється
       ПРАВОРУЧ: обрізати число зліва означало б відрубати старші розряди;
    3. текстове поле звужується або до заданої стелі, або до найдовшого
       значення, яке в ньому справді лежить.
    """
    if not os.path.isfile(шлях):
        return шлях
    знаків = ЗНАКІВ if знаків is None else знаків
    with open(шлях, "rb") as ф:
        дані = ф.read()

    шапка = bytearray(дані[:32])
    записів = int.from_bytes(дані[4:8], "little")
    довжина_шапки = int.from_bytes(дані[8:10], "little")
    довжина_запису = int.from_bytes(дані[10:12], "little")

    описи, зсув = [], 32
    while зсув < довжина_шапки - 1 and дані[зсув] != 0x0D:
        описи.append(bytearray(дані[зсув:зсув + 32]))
        зсув += 32
    if not описи:
        return шлях

    старі_ширини = [о[16] for о in описи]
    імена = [о[:11].split(b"\x00")[0].decode("ascii", "replace") for о in описи]
    типи = [chr(о[11]) for о in описи]

    # Що реально лежить у кожній колонці: найдовший текст і найдовша ціла
    # частина. Береться з самого файлу, а не зі стелі.
    найдовший, ціла_частина = _зміряти(дані, старі_ширини, типи,
                                       довжина_шапки, довжина_запису, записів)

    нові_ширини, нові_знаки = [], []
    for і, (імʼя, тип, стара) in enumerate(zip(імена, типи, старі_ширини)):
        if тип in ("N", "F"):
            д = знаків.get(імʼя)
            if д is None:
                д = описи[і][17]
            ширина = ціла_частина[і] + (1 + д if д > 0 else 0)
            нова = max(1, min(стара, ширина))
            нові_знаки.append(д)
        else:
            стеля = ширини.get(імʼя, стара)
            нова = max(1, min(стара, стеля, max(найдовший[і], 1)))
            нові_знаки.append(описи[і][17])
        нові_ширини.append(нова)

    if нові_ширини == старі_ширини:
        return шлях

    for опис, нова, д in zip(описи, нові_ширини, нові_знаки):
        опис[16] = нова
        опис[17] = д if chr(опис[11]) in ("N", "F") else 0

    нова_довжина_запису = 1 + sum(нові_ширини)
    нова_довжина_шапки = 32 + 32 * len(описи) + 1
    шапка[8:10] = нова_довжина_шапки.to_bytes(2, "little")
    шапка[10:12] = нова_довжина_запису.to_bytes(2, "little")

    вихід = bytearray(шапка)
    for опис in описи:
        вихід += опис
    вихід += b"\x0D"

    for номер in range(записів):
        початок = довжина_шапки + номер * довжина_запису
        запис = дані[початок:початок + довжина_запису]
        if len(запис) < довжина_запису:
            break
        вихід += запис[:1]
        місце = 1
        for тип, стара, нова, д in zip(типи, старі_ширини, нові_ширини, нові_знаки):
            значення = запис[місце:місце + стара]
            місце += стара
            if нова == стара:
                вихід += значення
                continue
            текст = значення.decode("utf-8", "ignore").strip()
            if тип in ("N", "F"):
                вихід += _число(текст, нова, д)
            else:
                обрізане = текст.encode("utf-8")[:нова]
                обрізане = обрізане.decode("utf-8", "ignore").encode("utf-8")
                вихід += обрізане.ljust(нова, b" ")
    вихід += b"\x1A"

    with open(шлях, "wb") as ф:
        ф.write(вихід)
    return шлях


def _зміряти(дані, ширини, типи, довжина_шапки, довжина_запису, записів):
    """Найдовший текст і найдовша ціла частина в кожній колонці."""
    найдовший = [0] * len(ширини)
    ціла = [1] * len(ширини)
    крок = max(1, записів // 20000)
    for номер in range(0, записів, крок):
        початок = довжина_шапки + номер * довжина_запису
        запис = дані[початок:початок + довжина_запису]
        if len(запис) < довжина_запису:
            break
        місце = 1
        for і, (тип, ш) in enumerate(zip(типи, ширини)):
            текст = запис[місце:місце + ш].strip()
            місце += ш
            if len(текст) > найдовший[і]:
                найдовший[і] = len(текст)
            if тип in ("N", "F") and текст:
                # Порожнє число драйвер пише не пробілами, а зірочками:
                # «************************». Двадцять чотири зірочки без
                # крапки виглядають як двадцятичотиризначне ціле, і колонка
                # через це не звужується взагалі. Це не значення, це NULL.
                if b"*" in текст:
                    continue
                голова = текст.split(b".")[0]
                if len(голова) > ціла[і]:
                    ціла[і] = len(голова)
    return найдовший, ціла


def _число(текст, ширина, знаків):
    """Число під нову точність, вирівняне праворуч. Порожнє лишається порожнім."""
    if not текст or "*" in текст:
        # порожнє лишається порожнім: пробіли, а не зірочки
        return b" " * ширина
    try:
        значення = float(текст)
    except ValueError:
        return b" " * ширина
    рядок = "{:.{}f}".format(значення, знаків)
    if len(рядок) > ширина:
        рядок = рядок[:ширина]
    return рядок.encode("ascii", "replace").rjust(ширина, b" ")


def таблиця_csv(шлях, заголовки, рядки):
    with open(шлях, "w", encoding="utf-8-sig", newline="") as ф:
        писар = csv.writer(ф, delimiter=";")
        писар.writerow(заголовки)
        писар.writerows(рядки)
    return шлях


def запакувати(архів, файли):
    with zipfile.ZipFile(архів, "w", zipfile.ZIP_DEFLATED) as зіп:
        for шлях in файли:
            if шлях and os.path.isfile(шлях):
                зіп.write(шлях, os.path.basename(шлях))
    return архів
