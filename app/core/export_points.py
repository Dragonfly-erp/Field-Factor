def записати_шейп(таблиця, шлях, стиснути=True):
    таблиця.to_file(шлях, driver="ESRI Shapefile", engine="pyogrio", encoding="UTF-8")
    основа = os.path.splitext(шлях)[0]
    with open(основа + ".cpg", "w", encoding="ascii") as ф:
        ф.write("UTF-8")
    if стиснути:
        стиснути_dbf(основа + ".dbf", ШИРИНИ)
    return [основа + р for р in (".shp", ".shx", ".dbf", ".prj", ".cpg")]


def стиснути_dbf(шлях, ширини):
    """Перезаписує DBF, звузивши текстові поля до реально потрібних розмірів.

    Драйвер шейпфайла віддає кожному текстовому полю по 80 знаків незалежно
    від вмісту. На сотні тисяч точок це десятки зайвих мегабайтів, які потім
    їде господарству поштою.
    """
    if not os.path.isfile(шлях):
        return шлях
    with open(шлях, "rb") as ф:
        дані = ф.read()

    шапка = bytearray(дані[:32])
    записів = int.from_bytes(дані[4:8], "little")
    довжина_шапки = int.from_bytes(дані[8:10], "little")
    довжина_запису = int.from_bytes(дані[10:12], "little")

    описи, зсув = [], 32
    while зсув < довжина_шапки - 1 and дані[зсув] != 0x0D:
        описи.append(bytearray(дані[зсув:зсув + 32]))
        зсув += 32
    if not описи:
        return шлях

    старі_ширини = [о[16] for о in описи]
    нові_ширини = []
    змінилось = False
    for опис, стара in zip(описи, старі_ширини):
        імʼя = опис[:11].split(b"\x00")[0].decode("ascii", "replace")
        нова = стара
        if chr(опис[11]) == "C" and імʼя in ширини:
            нова = max(1, min(стара, int(ширини[імʼя])))
        нові_ширини.append(нова)
        змінилось = змінилось or нова != стара
    if not змінилось:
        return шлях

    for опис, нова in zip(описи, нові_ширини):
        опис[16] = нова

    нова_довжина_запису = 1 + sum(нові_ширини)
    нова_довжина_шапки = 32 + 32 * len(описи) + 1
    шапка[8:10] = нова_довжина_шапки.to_bytes(2, "little")
    шапка[10:12] = нова_довжина_запису.to_bytes(2, "little")

    вихід = bytearray(шапка)
    for опис in описи:
        вихід += опис
    вихід += b"\x0D"

    початок = довжина_шапки
    for номер in range(записів):
        запис = дані[початок + номер * довжина_запису:
                     початок + (номер + 1) * довжина_запису]
        if len(запис) < довжина_запису:
            break
        вихід += запис[:1]
        місце = 1
        for стара, нова in zip(старі_ширини, нові_ширини):
            значення = запис[місце:місце + стара]
            місце += стара
            if нова == стара:
                вихід += значення
            else:
                текст = значення.decode("utf-8", "ignore").strip()
                обрізане = текст.encode("utf-8")[:нова]
                # не лишати обрубок багатобайтового знака
                обрізане = обрізане.decode("utf-8", "ignore").encode("utf-8")
                вихід += обрізане.ljust(нова, b" ")
    вихід += b"\x1A"

    with open(шлях, "wb") as ф:
        ф.write(вихід)
    return шлях


def словник_полів(шлях):
    with open(шлях, "w", encoding="utf-8-sig", newline="") as ф:
        писар = csv.writer(ф, delimiter=";")
        писар.writerow(["поле", "що означає"])
        писар.writerows(СЛОВНИК)
    return шлях


def звіт_qc(шлях, зміст):
    with open(шлях, "w", encoding="utf-8") as ф:
        ф.write(зміст)
    return шлях


def таблиця_csv(шлях, заголовки, рядки):
    with open(шлях, "w", encoding="utf-8-sig", newline="") as ф:
        писар = csv.writer(ф, delimiter=";")
        писар.writerow(заголовки)
        писар.writerows(рядки)
    return шлях


def запакувати(архів, файли):
    with zipfile.ZipFile(архів, "w", zipfile.ZIP_DEFLATED) as зіп:
        for шлях in файли:
            if шлях and os.path.isfile(шлях):
                зіп.write(шлях, os.path.basename(шлях))
    return архів
