    # «чого немає, те пропустимо» — саме той механізм, який уже одного разу
    # тихо викинув колонки з віддачі.
    for пізня, порожньо in (("YLD_SM", np.nan), ("YLD_MODEL", np.nan),
                            ("LOSS_KGHA", 0.0), ("LOSS_ZONE", 0)):
        if пізня not in зведене.columns:
            зведене[пізня] = порожньо

    бракує = [к for к in ПОРЯДОК if к not in зведене.columns]
    if бракує:
        raise KeyError("у зібраній таблиці немає колонок зі списку віддачі: "
                       + ", ".join(бракує))
    зведене = зведене[ПОРЯДОК + ["geometry"]]
    return gpd.GeoDataFrame(зведене, geometry="geometry", crs=чисті.crs)


