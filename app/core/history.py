# -*- coding: utf-8 -*-
"""ІСТОРІЯ ПОЛЯ. Те, що накопичується на полі рік за роком.

**Де вона лежить.** У теці самого поля, поруч із паспортом, шарами й
бюджетом — рішення Власника 21.08.2026. Не окремим сховищем на господарство:
поле перейменували або прибрали — історія поїхала б разом із ним або
лишилась сиротою.

**Чим вона поділена.** Не роками, а **логічними блоками**. Кожен блок —
свій файл, усередині якого роки:

    <поле>/історія/загальне.json     культура, гібрид, попередник, дати, урожай
    <поле>/історія/живлення.json     N P K Mg S за сезон
    <поле>/історія/меліорація.json   вапнування, гіпсування, інше
    <поле>/історія/захист.json       гербіциди, фунгіциди, інсектициди
    <поле>/історія/загрози.json      бурʼяни, хвороби, шкідники з оцінкою
    <поле>/історія/обробіток.json    основний, передпосівний
    <поле>/історія/економіка.json    витрати, carryover

Чому саме так, а не файл на рік. Агроном править історію блоками, а не
роками: сьогодні заводить захист за три сезони, завтра — живлення. Файл на
рік означав би, що обидві правки б'ються за той самий файл. А ще блок —
це те, що приходить із одного джерела: живлення з накладних, захист із
журналу обприскувача, економіка з бухгалтерії. Одне джерело — один файл.

**Провенанс на кожному році кожного блоку.** Не на файлі: живлення 2018-го
може приїхати з таблиці господарства, а живлення 2025-го — з наших власних
карт внесення. Хто це переплутає, той порахує на вигаданому.

**Порожній рік лишається порожнім.** Якщо блоку за рік немає, він і не
з'являється; місце в таблиці показується прочерком, а не нулем. Нуль у
живленні означає «не вносили», і сплутати це з «не знаємо» — найдорожча
помилка в усій історії поля.
"""

import json
import os
from datetime import datetime

ТЕКА = "історія"

# Порядок тут — це порядок у картці поля й у звіті. Спершу що сіяли й що
# зібрали, потім чим годували, потім чим лікували, потім чим це коштувало.
БЛОКИ = (
    ("загальне", "Загальне"),
    ("живлення", "Живлення"),
    ("меліорація", "Меліорація"),
    ("захист", "Захист"),
    ("загрози", "Загрози"),
    ("обробіток", "Обробіток"),
    ("економіка", "Економіка"),
)
КЛЮЧІ_БЛОКІВ = tuple(к for к, _ in БЛОКИ)

# Поля, які показуються в зведеній таблиці «усі роки». Решта живе всередині
# блоку й видно її в картці року.
ЗВЕДЕНІ = (
    ("культура", "Культура", "загальне"),
    ("гібрид", "Гібрид / сорт", "загальне"),
    ("попередник", "Попередник", "загальне"),
    ("урожай_т_га", "Урожай, т/га", "загальне"),
    ("N", "N", "живлення"),
    ("P", "P₂O₅", "живлення"),
    ("K", "K₂O", "живлення"),
    ("Mg", "MgO", "живлення"),
    ("S", "S", "живлення"),
    ("вапнування_т_га", "Вапно, т/га", "меліорація"),
    ("основний", "Основний обробіток", "обробіток"),
    ("витрати_на_га", "Витрати, $/га", "економіка"),
    ("carryover", "Carryover", "економіка"),
)


def _тека(тека_поля):
    return os.path.join(тека_поля, ТЕКА)


def _шлях(тека_поля, блок):
    return os.path.join(_тека(тека_поля), "{}.json".format(блок))


def _прочитати(шлях, замовчування):
    try:
        with open(шлях, encoding="utf-8") as ф:
            return json.load(ф)
    except Exception:
        return json.loads(json.dumps(замовчування))


def _записати(шлях, дані):
    os.makedirs(os.path.dirname(шлях), exist_ok=True)
    with open(шлях, "w", encoding="utf-8") as ф:
        json.dump(дані, ф, ensure_ascii=False, indent=2)


def _рік_ключем(рік):
    """Рік завжди рядок: у JSON ключі й так рядки, і 2025 проти "2025"
    згодом дає два записи про той самий сезон."""
    return str(int(рік))


# ═══════════════════════════════════════════════════════════════════════
# ЧИТАННЯ
# ═══════════════════════════════════════════════════════════════════════


def блок(тека_поля, ключ):
    """Один блок цілком: {"роки": {"2025": {...}}}."""
    return _прочитати(_шлях(тека_поля, ключ), {"блок": ключ, "роки": {}})


def роки(тека_поля):
    """Усі роки, про які хоч щось відомо, свіжий перший."""
    знайдені = set()
    for ключ in КЛЮЧІ_БЛОКІВ:
        знайдені.update((блок(тека_поля, ключ).get("роки") or {}).keys())
    return sorted(знайдені, reverse=True)


def рік(тека_поля, який):
    """Усі блоки за один сезон. Блоку немає — його немає й у відповіді."""
    який = _рік_ключем(який)
    зібране = {}
    for ключ in КЛЮЧІ_БЛОКІВ:
        значення = (блок(тека_поля, ключ).get("роки") or {}).get(який)
        if значення:
            зібране[ключ] = значення
    return зібране


def усе(тека_поля):
    """Уся історія поля: {рік: {блок: дані}}."""
    зібране = {}
    for ключ in КЛЮЧІ_БЛОКІВ:
        for р, значення in (блок(тека_поля, ключ).get("роки") or {}).items():
            зібране.setdefault(р, {})[ключ] = значення
    return зібране


def зведення(тека_поля):
    """Таблиця «усі роки»: по рядку на сезон, колонки з різних блоків.

    Порожнє лишається порожнім (`None`), і екран показує його прочерком.
    Підставляти нуль тут не можна: «не вносили» і «не знаємо» — це різні
    речі, і в нормах вони розходяться на цілу норму.
    """
    зібране = усе(тека_поля)
    рядки = []
    for р in sorted(зібране, reverse=True):
        блоки = зібране[р]
        рядок = {"рік": р}
        for поле, _, звідки in ЗВЕДЕНІ:
            рядок[поле] = (блоки.get(звідки) or {}).get(поле)
        рядок["блоків"] = len([б for б in блоки.values() if б])
        рядки.append(рядок)
    return рядки


def підсумок(тека_поля):
    """Кілька чисел про історію цілком — для шапки картки поля."""
    рядки = зведення(тека_поля)
    урожаї = [_число(р.get("урожай_т_га")) for р in рядки]
    урожаї = [у for у in урожаї if у is not None]
    культури = [р.get("культура") for р in рядки if р.get("культура")]
    return {
        "років": len(рядки),
        "від": рядки[-1]["рік"] if рядки else None,
        "до": рядки[0]["рік"] if рядки else None,
        "середній_урожай": round(sum(урожаї) / len(урожаї), 2) if урожаї else None,
        "культур": len(set(культури)),
    }


def _число(значення):
    try:
        if значення is None or значення == "":
            return None
        return float(значення)
    except (TypeError, ValueError):
        return None


