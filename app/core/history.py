def записати(тека_поля, ключ_блоку, який_рік, значення, джерело="", статус="WORKING"):
    """Кладе один блок за один рік. Решта років і решта блоків не чіпаються.

    Саме заради цього історія й поділена блоками: правка захисту за 2019-й
    не має жодної нагоди зіпсувати живлення за 2025-й.
    """
    if ключ_блоку not in КЛЮЧІ_БЛОКІВ:
        raise ValueError("невідомий блок історії: {}".format(ключ_блоку))
    вміст = блок(тека_поля, ключ_блоку)
    вміст.setdefault("блок", ключ_блоку)
    вміст.setdefault("роки", {})
    запис = dict(значення or {})
    # Провенанс лягає на РІК, а не на файл: різні роки приходять із різних
    # джерел, і спільний підпис на файлі був би підписом ні під чим.
    запис["джерело"] = джерело or запис.get("джерело") or ""
    запис["статус"] = статус or запис.get("статус") or "WORKING"
    запис["записано"] = datetime.now().strftime("%Y-%m-%d")
    вміст["роки"][_рік_ключем(який_рік)] = запис
    _записати(_шлях(тека_поля, ключ_блоку), вміст)
    return запис


def записати_рік(тека_поля, який_рік, блоки, джерело="", статус="WORKING"):
    """Кілька блоків одного сезону одним заходом."""
    записано = {}
    for ключ, значення in (блоки or {}).items():
        if not значення:
            continue
        записано[ключ] = записати(тека_поля, ключ, який_рік, значення, джерело, статус)
    return записано


def видалити_рік(тека_поля, який_рік):
    """Прибирає сезон з усіх блоків. Використовується, коли рік завели
    помилково — виправляти його порожніми значеннями не можна, бо порожнє
    значення означає «не вносили», а не «цього року в нас немає»."""
    який = _рік_ключем(який_рік)
    прибрано = []
    for ключ in КЛЮЧІ_БЛОКІВ:
        вміст = блок(тека_поля, ключ)
        якщо = (вміст.get("роки") or {}).pop(який, None)
        if якщо is not None:
            _записати(_шлях(тека_поля, ключ), вміст)
            прибрано.append(ключ)
    return прибрано
