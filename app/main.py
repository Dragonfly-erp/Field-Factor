            тека_г = self._гроші_тека_господарства(г)
            if not тека_г:
                return self._збій("Не вказано господарство")
            своє = money._прочитати(
                os.path.join(тека_г, money.ФАЙЛ_ГОСПОДАРСТВА), money.ПОРОЖНІЙ)
