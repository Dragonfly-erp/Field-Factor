    def _відбір(self, дані):
        """Сітковий відбір: класична сітка або оптимізоване дослідження."""
        from app.core import sampling

        дані = дані or {}
        г, п = дані.get("господарство"), дані.get("поле")
        якщо_контур = КАРТОТЕКА.шар(г, п, "контур") if г and п else None
        if not якщо_контур:
            return self._збій("У цього поля немає контуру")

        варіант = дані.get("варіант") or "класична"
        га = float(дані.get("га") or sampling.КОМІРКА_ЗАМОВЧУВАННЯ_ГА)
        if га <= 0:
            return self._збій("Розмір комірки має бути більшим за нуль")
        кут = float(дані.get("кут") or 0)
        мін_га = float(дані.get("мін_га") or sampling.КОМІРКА_МІН_ГА)
        макс_га = float(дані.get("макс_га") or sampling.КОМІРКА_МАКС_ГА)

        with ЗАМОК_ПРОСТОРУ:
            import geopandas as gpd

            контур = gpd.read_file(якщо_контур["_шлях"])

            контраст, порівняння, порада = None, None, None
            звідки_ділянки = None
            if варіант == "оптимізована":
                if дані.get("_готовий_контраст") is not None:
                    контраст = дані["_готовий_контраст"]
                    звідки_ділянки = dict(спосіб="побудовано з джерел поля",
                                          ділянок=len(контраст), узято=[])
                    чому_ні = None
                else:
                    контраст, звідки_ділянки, чому_ні = self._ділянки(
                        г, п, контур, дані)
                if контраст is None:
                    return self._збій(чому_ні)
                порада = sampling.запропонувати(
                    контур, контраст, класична_га=float(
                        дані.get("порівняти_з") or 1.0),
                    мін_га=мін_га, макс_га=макс_га)
                комірки, як = sampling.динамічна(
                    контур, контраст, гектарів=га, мін_га=мін_га,
                    макс_га=макс_га, кут=кут)
                # Рахуємо змішані і в класичній, і в нашій: без другого
                # числа перше читається як вирок нашій сітці, тобто рівно
                # навпаки до того, що сталось.
                порівняння = sampling.порівняти(
                    sampling.класична(контур, га, кут), комірки, контраст)
                наше = sampling.порівняти(комірки, комірки, контраст)
                порівняння["змішаних_у_нашій"] = наше["змішаних"]
                порівняння["найгірша_у_нашій"] = наше["найгірша_домішка"]
            else:
                як = {}
                комірки = sampling.класична(
                    контур, га, кут,
                    зливати_край=bool(дані.get("зливати_край")),
                    мін_га=мін_га, макс_га=макс_га)

            # Якщо сітку вже побудував підбір — беремо її, а не робимо ще раз.
            if дані.get("_готові_комірки") is not None:
                комірки = дані["_готові_комірки"]

            точки = sampling.точки(комірки)
            оцінка = sampling.оцінити(комірки, точки, мін_га, макс_га)
            карта = sampling.для_карти(контур, комірки, точки)

            файли = []
            if дані.get("писати"):
                тека = os.path.join(КАРТОТЕКА.тека_поля(г, п), "3_віддача",
                                    "завдання_на_відбір")
                назва_поля = дані.get("назва_поля") or п
                підпис = ("%s · %s · комірка %g га · зразків %d"
                          % (назва_поля, варіант, га, len(точки)))
                файли = sampling.записати_заявку(
                    тека, комірки, точки,
                    дані.get("назва") or (назва_поля + " vidbir"),
                    назва_поля, підпис)

        відповідь = {
            "варіант": варіант, "га": га, "кут": кут,
            "звідки_ділянки": звідки_ділянки,
            "як": як, "оцінка": оцінка, "карта": карта,
            "порівняння": порівняння, "порада": порада,
            "тека": os.path.dirname(файли[0]) if файли else None,
            "файли": [os.path.basename(ф) for ф in файли],
        }
        # Підбір під кількість кличе цей самий метод і бере словник, а не
        # відповідь: так обіцянка й побудова — це один прогін, а не два.
        if (дані or {}).get("_тільки_дані"):
            return відповідь
        return self._віддати(відповідь)

    def _ділянки(self, г, п, контур, дані):
        """Однорідні ділянки: або з готового шару зон, або з власних шарів поля.

        Повертає (ділянки, звідки, чому_ні)."""
        import geopandas as gpd

        from app.core import sampling

        ключ = дані.get("контраст")
        if ключ and ключ != "самому":
            шар = КАРТОТЕКА.шар(г, п, ключ)
            if not шар:
                return None, None, "такого шару зон немає"
            return (gpd.read_file(шар["_шлях"]),
                    dict(спосіб="готовий шар", назва=шар.get("назва")), None)

        обрані = дані.get("джерела") or []
        if not обрані:
            return None, None, ("Немає з чого шукати однорідні ділянки. "
                                "Оберіть хоча б одне джерело або готовий "
                                "шар зон")

        доступні = {д["ключ"]: д for д in sampling.наявні_джерела(КАРТОТЕКА, г, п)}
        шари, узято = [], []
        for ключ_дж in обрані:
            опис = доступні.get(ключ_дж)
            if not опис or not опис.get("є") or not опис.get("шари"):
                continue
            for шар_опис in опис["шари"]:
                шар = КАРТОТЕКА.шар(г, п, шар_опис["ключ"])
                if not шар:
                    continue
                точки = gpd.read_file(шар["_шлях"])
                for колонка in опис["колонки"]:
                    if колонка in точки.columns:
                        шари.append((ключ_дж + " · " + колонка, точки, колонка))
                        узято.append(ключ_дж + " · " + колонка)
                break

        # Вегетація приходить не шаром із теки, а з супутника — і тільки
        # тоді, коли сказано, яка культура була в якому році.
        готові, вегетація_звіт = [], None
        if "вегетація" in обрані:
            історія = [з for з in (дані.get("історія") or [])
                       if з.get("рік")]
            if not історія:
                return None, None, ("Для вегетації треба сказати, яка "
                                    "культура була на полі і в якому році")
            шари_вег, опис = sampling.вегетація_за_історією(
                контур, історія, СЕАНС.налаштування, БАЗА, Журнал())
            if not шари_вег:
                return None, None, ("Вегетацію взяти не вдалось: "
                                    + str(опис.get("причина", "")))
            готові.append(("вегетація", шари_вег["вегетація"],
                           шари_вег["_сітка"]))
            узято.append("вегетація · %d років" % опис.get("років", 0))
            вегетація_звіт = опис

        if not шари and not готові:
            return None, None, ("З обраних джерел не вийшло жодної поверхні")

        ділянок = int(дані.get("ділянок") or sampling.ДІЛЯНОК_ЗАМОВЧУВАННЯ)
        try:
            ділянки, як = sampling.ділянки_з_джерел(
                контур, шари, ділянок=ділянок, поверхні_готові=готові)
        except Exception as помилка:
            return None, None, str(помилка)
        return ділянки, dict(спосіб="побудовано з джерел поля", узято=узято,
                             ділянок=len(ділянки),
                             вегетація=вегетація_звіт), None

    def _відбір_кількість(self, дані):
        """«Хочу стільки зразків» — що для цього змінити."""
        import geopandas as gpd

        from app.core import sampling

        дані = дані or {}
        г, п = дані.get("господарство"), дані.get("поле")
        якщо_контур = КАРТОТЕКА.шар(г, п, "контур") if г and п else None
        if not якщо_контур:
            return self._збій("У цього поля немає контуру")
        скільки = int(дані.get("зразків") or 0)
        if скільки < 1:
            return self._збій("Скільки зразків потрібно?")

        with ЗАМОК_ПРОСТОРУ:
            контур = gpd.read_file(якщо_контур["_шлях"])
            контраст = None
            if (дані.get("варіант") or "класична") == "оптимізована":
                контраст, _, чому = self._ділянки(г, п, контур, дані)
                if контраст is None:
                    return self._збій(чому)
            підбір = sampling.підібрати_комірку(
                контур, скільки, контраст=контраст,
                кут=float(дані.get("кут") or 0))

        # Підбір і побудова більше не два окремі прогони. Раніше підбір
        # обіцяв девʼятнадцять зразків, а кнопка «побудувати» давала
        # двадцять один: ті самі числа, але дві різні побудови, і сотих
        # гектара вистачало, щоб уламок злився або ні. Я двічі підкручував
        # точність, поки не побачив, що ганяюсь за цифрами замість причини.
        # Тепер підбір одразу віддає ту сітку, яку знайшов: обіцянка і є
        # результатом, бо це той самий обʼєкт.
        повне = self._відбір(dict(
            дані, га=підбір["га"], мін_га=підбір.get("мін_га"),
            макс_га=підбір.get("макс_га"), писати=False, _тільки_дані=True,
            _готові_комірки=підбір.pop("_комірки", None),
            _готовий_контраст=контраст))
        if not isinstance(повне, dict):
            return повне
        повне["підбір"] = підбір
        return self._віддати(повне)

