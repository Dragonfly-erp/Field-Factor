    def _гроші_врожайність(self, господарство, поле, рік):
        """Врожайність для бюджету — з НАШОЇ нормалізованої карти.

        Це те, чого немає в жодної бухгалтерської системи: там врожайність
        вводять руками з відомості, і вона одна на все поле. У нас вона вже
        порахована по комірках, зведена з ваговою і має провенанс. Тому
        бюджет не питає її в людини, а бере — і каже, звідки взяв.

        Комірки сітки рівні між собою, тож середнє по комірках і є середнє
        по площі. Порожньо повертаємо чесно: карти немає — числа немає.
        """
        картка = КАРТОТЕКА.шар(господарство, поле, "врожайність_{}".format(рік))
        if not картка or not os.path.isfile(картка.get("_шлях") or ""):
            return None, None
        import geopandas as gpd
        import numpy as np

        try:
            таблиця = gpd.read_file(картка["_шлях"], columns=["YLD_KGHA"])
        except Exception:                              # noqa: BLE001
            return None, None
        if "YLD_KGHA" not in таблиця.columns:
            return None, None
        y = np.asarray(таблиця["YLD_KGHA"], dtype="float64")
        y = y[np.isfinite(y)]
        if not len(y):
            return None, None
        return float(y.mean()) / 1000.0, "нормалізована карта {}, {} комірок".format(
            рік, len(y))

