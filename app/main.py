    def _геометрія_зон(self, дані):
        """Шар зон, підготовлений до монітора. Спільне для переліку і видачі.

        Готується ОДИН раз і тими самими налаштуваннями і для показу площ,
        і для запису файлів. Інакше на екрані були б одні гектари, а на
        флешці інші."""
        from app.core import geometry, rx

        зони, колонка, чому = self._шар_зон(дані)
        if зони is None:
            return None, None, None, чому
        сирі = (дані or {}).get("геометрія")
