    def _гроші_площа_господарства(self, господарство):
        """Уся площа в обробітку — знаменник для розкиду постійних витрат."""
        якщо = 0.0
        for п in (КАРТОТЕКА.поля(господарство) if господарство else []):
            якщо += float(п.get("площа_га") or 0.0)
