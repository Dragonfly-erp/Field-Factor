function намалювати_розвідку(р) {
  const частини = [];
  const к = р['контур'] || {};

  частини.push('<h3>Контур поля</h3>');
  if (к.помилка) {
    частини.push(`<p><span class="мітка стоп">не прочитався</span> ${екран(к.помилка)}</p>`);
  } else {
    частини.push('<dl>' +
      `<dt>Файл</dt><dd>${екран(к['файл'])}</dd>` +
      `<dt>Площа</dt><dd>${к['площа_га']} га</dd>` +
      `<dt>Система координат</dt><dd>${екран(к['crs'])}</dd>` +
      `<dt>Частин</dt><dd>${к['частин']}</dd>` +
      '</dl>');
    (к['зауваження'] || []).forEach(з =>
      частини.push(`<p><span class="мітка увага">увага</span> ${екран(з)}</p>`));
  }

  const м = р['монітор'] || {};
  частини.push('<h3>Записи монітора</h3>');
  if (м.помилка) {
    частини.push(`<p><span class="мітка стоп">не прочиталось</span> ${екран(м.помилка)}</p>`);
  } else {
    частини.push('<div class="обгортка"><table><tr><th>Файл</th><th>Записів</th>' +
      '<th>Система координат</th><th>Позначено як комбайн</th></tr>' +
      (м['файли'] || []).map(ф => `<tr><td>${екран(ф['файл'])}</td><td>${ф['записів']}</td>` +
        `<td>${екран(ф['crs'])}</td><td>${екран(ф['машина'])}</td></tr>`).join('') +
      '</table></div>');
    частини.push(`<p>Усього записів: <strong>${м['усього_записів']}</strong>, ` +
      `комбайнів: <strong>${м['машин']}</strong></p>`);
  }

  // мапінг колонок
  const колонки = (м['колонки'] || []);
  const вгадано = (м['вгадано'] || {});
  if (колонки.length) {
    частини.push('<h3>Колонки</h3>');
    частини.push('<div class="обгортка"><table><tr><th>Що це</th><th>Колонка у файлі</th><th></th></tr>' +
      РОЛІ.map(([ключ, назва, пояснення]) => {
        const обране = вгадано[ключ] || '';
        const опції = ['<option value="">— немає —</option>'].concat(
          колонки.map(к => `<option value="${екран(к)}"${к === обране ? ' selected' : ''}>${екран(к)}</option>`)
        ).join('');
        return `<tr><td><strong>${екран(назва)}</strong></td>` +
               `<td><select data-роль="${ключ}">${опції}</select></td>` +
               `<td style="color:var(--тихий)">${екран(пояснення)}</td></tr>`;
      }).join('') + '</table></div>');

    частини.push('<h3>Одиниця врожайності у файлі</h3>');
    const од = м['одиниця_врожаю'] || '';
    const варіанти = [['', 'визначити самій'], ['кг/га', 'кг/га'], ['т/га', 'т/га'],
                      ['ц/га', 'ц/га'], ['bu/ac', 'бушелів/акр'], ['lb/ac', 'фунтів/акр'],
                      ['л/га', 'л/га']];
    частини.push('<select id="одиниця-врожаю">' + варіанти.map(([з, п]) =>
      `<option value="${з}"${з === од ? ' selected' : ''}>${екран(п)}</option>`).join('') + '</select>');
    if (м['одиниця_обґрунтування'])
      частини.push(`<p class="підказка">${екран(м['одиниця_обґрунтування'])}</p>`);

    частини.push('<h3>Чи приводив монітор сам</h3>');
    частини.push('<label class="радіо"><input type="checkbox" id="вже-приведено"' +
      (м['вже_приведено_здогад'] ? ' checked' : '') + '>' +
      '<span>Монітор уже видає врожайність, приведену до сухої основи. ' +
      'Тоді програма <strong>не</strong> застосовує формулу вологості вдруге — ' +
      'інакше поправка ляже двічі й числа поїдуть.</span></label>');
  }

  (м['зауваження'] || []).forEach(з =>
    частини.push(`<p><span class="мітка увага">увага</span> ${екран(з)}</p>`));

  $('#звіт-розвідки').innerHTML = частини.join('');
}

function зібрати_колонки() {
  const мапа = {};
  $$('#звіт-розвідки select[data-роль]').forEach(с => {
    if (с.value) мапа[с.dataset.роль] = с.value;
  });
  const од = $('#одиниця-врожаю');
  const приведено = $('#вже-приведено');
  return {
    колонки: мапа,
    одиниця_врожаю: од ? од.value : '',
    вже_приведено: приведено ? приведено.checked : false
  };
}

