function підключити_прийом(зона, поле, список, вид) {
  const блок = $(зона), вхід = $(поле), перелік = $(список);

  блок.addEventListener('click', () => вхід.click());
  блок.addEventListener('dragover', п => { п.preventDefault(); блок.classList.add('наведено'); });
  блок.addEventListener('dragleave', () => блок.classList.remove('наведено'));
  блок.addEventListener('drop', п => {
    п.preventDefault();
    блок.classList.remove('наведено');
    відправити(п.dataTransfer.files);
  });
  вхід.addEventListener('change', () => відправити(вхід.files));

  async function відправити(файли) {
    if (!файли || !файли.length) return;
    const форма = new FormData();
    форма.append('вид', вид);
    for (const ф of файли) форма.append('файл', ф);
    перелік.innerHTML = '<li>Переношу файли…</li>';
    try {
      const відп = await fetch('/api/файли', { method: 'POST', body: форма });
      const дані = await відп.json();
      if (дані.помилка) throw new Error(дані.помилка);
      перелік.dataset.є = '1';
      перелік.innerHTML = дані.збережено.map(ф =>
        `<li><span class="імʼя">${екран(ф['імʼя'])}</span><span>${байти(ф.байтів)}</span></li>`
      ).join('');
    } catch (п) {
      перелік.innerHTML = '';
      поскаржитись(п);
    }
  }
}

