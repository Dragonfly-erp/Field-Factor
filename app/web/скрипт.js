let таймер = null;

function стежити(після) {
  стан.прочитано = 0;
  $('#журнал').textContent = '';
  $('#смужка').style.width = '0%';
  clearInterval(таймер);
  таймер = setInterval(async () => {
    try {
      const п = await взяти('/api/прогрес?від=' + стан.прочитано);
      стан.прочитано = п['усього_рядків'];
      if (п['рядки'].length) {
        const журнал = $('#журнал');
        журнал.textContent += п['рядки'].map(р => `${р['час']}  ${р['текст']}`).join('\n') + '\n';
        журнал.scrollTop = журнал.scrollHeight;
      }
      $('#смужка').style.width = п['відсоток'] + '%';
      $('#фаза').textContent = п['фаза'] || '';
      if (п['завершено']) {
        clearInterval(таймер);
        таймер = null;
        після(п);
      }
    } catch (е) { /* сервер перезавантажується — просто чекаємо */ }
  }, 700);
}

