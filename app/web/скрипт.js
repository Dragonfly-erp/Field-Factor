const $ = (сел) => document.querySelector(сел);
const $$ = (сел) => Array.from(document.querySelectorAll(сел));

function екран(текст) {
  const д = document.createElement('div');
  д.textContent = текст == null ? '' : String(текст);
  return д.innerHTML;
}

async function послати(адреса, тіло) {
  const опції = { method: 'POST', headers: { 'Content-Type': 'application/json' },
                  body: JSON.stringify(тіло || {}) };
  const відп = await fetch(адреса, опції);
  const дані = await відп.json();
  if (дані.помилка) throw new Error(дані.помилка);
  return дані;
}

async function взяти(адреса) {
  const відп = await fetch(адреса);
  const дані = await відп.json();
  if (дані.помилка) throw new Error(дані.помилка);
  return дані;
}

function поскаржитись(помилка) {
  alert('Не вийшло:\n\n' + (помилка && помилка.message ? помилка.message : помилка));
}

function байти(н) {
  if (н < 1024) return н + ' Б';
  if (н < 1048576) return (н / 1024).toFixed(0) + ' КБ';
  return (н / 1048576).toFixed(1) + ' МБ';
}

