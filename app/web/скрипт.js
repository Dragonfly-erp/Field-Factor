async function перевірити_оновлення() {
  try {
    const о = await взяти('/api/оновлення');
    if (!о['доступно']) return;
    const плашка = $('#плашка-оновлення');
    плашка.hidden = false;
    плашка.innerHTML = `Є нова версія <strong>${екран(о['нова'])}</strong> ` +
      `(у вас ${екран(о['поточна'])}). <button id="кнопка-оновити">Поставити</button>`;
    $('#кнопка-оновити').addEventListener('click', async (п) => {
      п.target.disabled = true;
      п.target.textContent = 'Ставлю…';
      try {
        const р = await послати('/api/оновити', {});
        плашка.innerHTML = екран(р['повідомлення']);
      } catch (е) { поскаржитись(е); п.target.disabled = false; }
    });
  } catch (е) { /* немає інтернету — мовчимо */ }
}

