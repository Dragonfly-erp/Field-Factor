// Верхнє робоче меню — один перелік на всю програму.
//
// Порядок пунктів — це порядок роботи, а не абетка: спершу привести сире до
// придатного, потім поділити поле, потім поїхати по зразки, потім прочитати
// лабораторію, потім віддати карту на техніку. Хто відкрив програму вперше,
// має бачити зі шапки, чим його робота закінчиться.
//
// Довідники стоять окремо: вони не крок, до них заходять посеред будь-якого
// кроку й повертаються назад.

const МЕНЮ_КРОКИ = [
  { адреса: "/нормалізація", підпис: "Нормалізація",
    пояснення: "карта врожайності з монітора комбайна" },
  { адреса: "/", підпис: "Зонування",
    пояснення: "поле ділиться на зони за тим, що про нього відомо" },
  { адреса: "/відбір", підпис: "Відбір",
    пояснення: "завдання на відбір зразків: куди їхати й скільки брати" },
  { адреса: "/аналізи", підпис: "Аналізи",
    пояснення: "приймання протоколу лабораторії" },
  { адреса: "/карта", підпис: "Карта внесення",
    пояснення: "зони з нормою у файл для монітора" },
  { адреса: "/звіти", підпис: "Звіти",
    пояснення: "документи по виконаних роботах — у розробці" },
];

const МЕНЮ_ДОВІДНИКИ = [
  { адреса: "/продукти", підпис: "Продукти",
    пояснення: "склад партії, нейтралізуюча здатність, статус" },
  { адреса: "/метод", підпис: "Метод",
    пояснення: "числа, якими рахуємо, і звірка з майстернею" },
];

function намалювати_меню(куди) {
  const тут = decodeURIComponent(location.pathname).replace(/\/$/, "") || "/";
  const обгортка = typeof куди === "string" ? document.querySelector(куди) : куди;
  if (!обгортка) return;

  const ряд = document.createElement("nav");
  ряд.className = "меню";

  МЕНЮ_КРОКИ.forEach((п, і) => {
    if (і) ряд.appendChild(стрілка());
    ряд.appendChild(пункт(п, тут));
  });

  const розрив = document.createElement("span");
  розрив.className = "меню-розрив";
  ряд.appendChild(розрив);

  МЕНЮ_ДОВІДНИКИ.forEach(п => ряд.appendChild(пункт(п, тут, true)));

  обгортка.innerHTML = "";
  обгортка.appendChild(ряд);

  function стрілка() {
    const с = document.createElement("span");
    с.className = "меню-стрілка";
    с.textContent = "→";
    return с;
  }

  function пункт(п, тут, довідник) {
    const а = document.createElement("a");
    а.className = "меню-пункт" + (довідник ? " довідник" : "");
    а.href = п.адреса;
    а.textContent = п.підпис;
    а.title = п.пояснення;
    if (п.адреса === тут) {
      а.className += " тут";
      а.setAttribute("aria-current", "page");
    }
    return а;
  }
}

document.addEventListener("DOMContentLoaded", () => намалювати_меню("#меню"));
