//
// Довідники (метод, налаштування) стоять окремо праворуч: вони не крок, до
// них заходять посеред будь-якого кроку й повертаються назад.
//
// Перелік етапів мусить збігатися з `ЕТАПИ` в `робоче.js`. Там він живий —
