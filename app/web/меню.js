function _тут() {
  return decodeURIComponent(location.pathname).replace(/\/$/, "") || "/";
}

function намалювати_меню(куди) {
  const тут = _тут();
  const обгортка = typeof куди === "string" ? document.querySelector(куди) : куди;
  if (!обгортка) return;

  const ряд = document.createElement("nav");
  ряд.className = "пайплайн";

  ЕТАПИ_МЕНЮ.forEach((е, і) => {
    if (і) {
      const с = document.createElement("span");
      с.className = "пайплайн-стрілка";
      с.textContent = "→";
      ряд.appendChild(с);
    }
    const а = document.createElement("a");
    а.className = "етап" + (_належить(е, тут) ? " тут" : "");
    а.href = е.адреса;
    а.title = е.пояснення;
    а.innerHTML = "<i>" + е.номер + "</i>";
    а.appendChild(document.createTextNode(е.підпис));
    if (_належить(е, тут)) а.setAttribute("aria-current", "page");
    ряд.appendChild(а);
  });

  обгортка.innerHTML = "";
  обгортка.appendChild(ряд);

  ПОЗА_ПАЙПЛАЙНОМ.forEach(п => {
    const а = document.createElement("a");
    а.className = "до-методу" + (п.адреса === тут ? " тут" : "");
    а.href = п.адреса;
    а.textContent = п.підпис;
    а.title = п.пояснення;
    обгортка.appendChild(а);
  });

  намалювати_функції_меню();
}

// Етап «свій», якщо поточна сторінка — це він сам або будь-яка з його функцій.
// Інакше на екрані «Продукти» жоден етап не світився б, і людина не бачила б,
// де вона в роботі.
function _належить(етап, тут) {
  if (етап.адреса === тут) return true;
  return (етап.функції || []).some(ф => ф.адреса === тут && ф.адреса !== "/");
}

// Ряд функцій під шапкою. Малюється лише там, де для нього є місце:
// сторінка мусить мати `<nav class="функції" id="функції">` одразу під шапкою.
function намалювати_функції_меню() {
  const місце = document.querySelector("#функції");
  if (!місце) return;
  const тут = _тут();
  const етап = ЕТАПИ_МЕНЮ.find(е => _належить(е, тут));
  if (!етап) { місце.innerHTML = ""; return; }

  місце.innerHTML = "";
  // Підсвічується РІВНО ОДНА функція. Кілька функцій одного етапу можуть
  // вести на ту саму сторінку (на «Грошах» бюджет і довідники — це вкладки
  // всередині екрана), і тоді підсвітити обидві означає збрехати, що ми
  // одночасно у двох місцях.
  let вже = false;
  (етап.функції || []).forEach(ф => {
    const а = document.createElement("a");
    const своя = !вже && ф.адреса === тут;
    if (своя) вже = true;
    а.className = "функція" + (своя ? " тут" : "");
    а.href = ф.адреса;
    а.textContent = ф.підпис;
    місце.appendChild(а);
  });
}

document.addEventListener("DOMContentLoaded", () => намалювати_меню("#меню"));
