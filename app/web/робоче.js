function намалювати_дерево() {
  const частини = [];
  if (!стан.господарства.length) {
    частини.push('<p class="дрібно порожньо">Ще жодного господарства.<br>Натисніть «+» угорі.</p>');
  }
  for (const г of стан.господарства) {
    const га = г['поля'].reduce((с, п) => с + (Number(п['площа_га']) || 0), 0);
    частини.push(`<div class="гілка">
      <div class="гілка-шапка">
        <span class="гілка-назва">${екран(г['назва'])}</span>
        <span class="лист-дрібно">${г['поля'].length ? г['поля'].length + ' · ' + га.toFixed(0) + ' га' : ''}</span>
        <button class="дрібна" data-імпорт="${екран(г['ключ'])}"
                title="Імпорт меж: shapefile або KML з багатьма полями">↧</button>
        <button class="дрібна" data-нове-поле="${екран(г['ключ'])}" title="Додати поле">+</button>
      </div>`);
    if (!г['поля'].length) частини.push('<p class="дрібно відступ">полів немає</p>');

    // Поля групуються по фермах. Ферма — властивість поля, а не тека: відділок
    // можна розформувати, не переносячи даних. Поля без ферми йдуть окремою
    // групою «без ферми», а не мовчки домішуються до першої-ліпшої.
    const групи = new Map();
    for (const п of г['поля']) {
      const ферма = (п['ферма'] || '').trim();
      if (!групи.has(ферма)) групи.set(ферма, []);
      групи.get(ферма).push(п);
    }
    const назви_ферм = [...групи.keys()].sort((а, б) => (а === '' ? 1 : б === '' ? -1 : а.localeCompare(б, 'uk')));
    const показувати_групи = групи.size > 1 || (групи.size === 1 && назви_ферм[0] !== '');

    for (const ферма of назви_ферм) {
      const поля = групи.get(ферма);
      if (показувати_групи) {
        const га_ферми = поля.reduce((с, п) => с + (Number(п['площа_га']) || 0), 0);
        частини.push(`<div class="ферма-шапка">
          <span>${екран(ферма || 'без ферми')}</span>
          <span class="лист-дрібно">${поля.length} · ${га_ферми.toFixed(0)} га</span>
        </div>`);
      }
      for (const п of поля) {
        const обране = стан.господарство === г['ключ'] && стан.поле === п['ключ'];
        const шлях_поля = г['ключ'] + '/' + п['ключ'];
        const розкрите = стан.розкриті.has(шлях_поля);
        const дерево = п['дерево'] || [];
        частини.push(`<div class="лист${обране ? ' обраний' : ''}${показувати_групи ? ' у-фермі' : ''}"
             data-господарство="${екран(г['ключ'])}" data-поле="${екран(п['ключ'])}">
          <span class="гілочка${дерево.length ? '' : ' порожня'}"
                data-розкрити="${екран(шлях_поля)}">${дерево.length ? (розкрите ? '▾' : '▸') : '·'}</span>
          <span class="лист-назва">${екран(п['назва'])}</span>
          <span class="лист-дрібно">${п['площа_га'] ? п['площа_га'] + ' га' : 'без контуру'}</span>
        </div>`);
        // Роки й види даних під полем — та сама розкладка, що в робочому
        // дереві SMS: рік → вид → шар. Людина шукає очима звичний рядок.
        if (розкрите) {
          for (const рік of дерево) {
            const шлях_року = шлях_поля + '/' + (рік['рік'] || '—');
            const рік_розкритий = стан.розкриті.has(шлях_року);
            частини.push(`<div class="рік-вузол" data-розкрити="${екран(шлях_року)}">
              <span class="гілочка">${рік_розкритий ? '▾' : '▸'}</span>
              <span class="рік-підпис">${екран(рік['рік'] || 'без року')}</span>
              <span class="лист-дрібно">${екран(рік['шарів'])}</span>
            </div>`);
            if (!рік_розкритий) continue;
            for (const вид of рік['види']) {
              const шлях_виду = шлях_року + '/' + вид['ключ'];
              const продукти = вид['продукти'] || [];
              const вид_розкритий = стан.розкриті.has(шлях_виду) || !продукти.length;
              частини.push(`<div class="вид-вузол"${продукти.length
                  ? ` data-розкрити="${екран(шлях_виду)}"` : ''}>
                ${продукти.length ? `<span class="гілочка">${вид_розкритий ? '▾' : '▸'}</span>` : ''}
                <span class="вид-підпис">${екран(вид['підпис'])}</span>
                <span class="лист-дрібно">${екран(вид['шари'].length)}</span></div>`);
              if (!вид_розкритий) continue;

              // Без продуктів — самі шари, як було. З продуктами — три
              // нижні рівні SMS: продукт → операція → прохід.
              if (!продукти.length) {
                for (const ш of вид['шари']) частини.push(рядок_шару(г, п, ш));
                continue;
              }
              for (const пр of продукти) {
                частини.push(`<div class="продукт-вузол">
                  <span class="продукт-підпис">${екран(пр['продукт'])}</span></div>`);
                for (const оп of пр['операції']) {
                  частини.push(`<div class="операція-вузол">
                    <span>${екран(оп['операція'])}</span>
                    <span class="лист-дрібно">${оп['проходи'].length || оп['шари'].length}</span></div>`);
                  for (const ш of оп['шари']) частини.push(рядок_шару(г, п, ш, true));
                  for (const пх of оп['проходи']) {
                    частини.push(`<div class="прохід-вузол">
                      <span class="прохід-дата">${екран(пх['дата'] || '')}</span>
                      <span class="прохід-назва">${екран(пх['назва'] || '')}</span>
                      ${пх['джерело'] ? `<span class="лист-дрібно">${екран(пх['джерело'])}</span>` : ''}
                    </div>`);
                  }
                }
              }
            }
          }
        }
      }
    }
    частини.push('</div>');
  }
  $('#дерево').innerHTML = частини.join('');

  $$('#дерево .лист').forEach(е => е.addEventListener('click',
    () => обрати_поле(е.dataset['господарство'], е.dataset['поле'])));

  // Розкриття вузлів. Клік по трикутнику розкриває, клік по самому полю
  // його обирає — це різні дії, і плутати їх не можна.
  $$('#дерево [data-розкрити]').forEach(е => е.addEventListener('click', п => {
    п.stopPropagation();
    const шлях = е.dataset['розкрити'];
    if (стан.розкриті.has(шлях)) стан.розкриті.delete(шлях);
    else стан.розкриті.add(шлях);
    намалювати_дерево();
  }));

  // Клік по шару в дереві показує саме цей шар на карті.
  $$('#дерево .шар-вузол').forEach(е => е.addEventListener('click', async п => {
    п.stopPropagation();
    const г = е.dataset['господарство'], пл = е.dataset['поле'];
    if (стан.господарство !== г || стан.поле !== пл) await обрати_поле(г, пл);
    стан.вигляд = 'карта';
    перемкнути_вигляд();
    await показати_шар(е.dataset['шар'], true);
    стан.активний = е.dataset['шар'];
    намалювати_список_шарів();
    намалювати_показ();
  }));
  $$('#дерево [data-нове-поле]').forEach(е => е.addEventListener('click', п => {
    п.stopPropagation();
    завести_поле(е.dataset['новеПоле']);
  }));
  $$('#дерево [data-імпорт]').forEach(е => е.addEventListener('click', п => {
    п.stopPropagation();
    імпорт_меж(е.dataset['імпорт']);
  }));
}

/* ─────────────────────────────────────────── імпорт багатьох полів одразу
   Господарство приходить одним файлом на всі поля, а не двадцятьма
   окремими межами. Два кроки навмисне: спершу показуємо, що вийде,
   і лише після згоди кладемо в дерево. */

function імпорт_меж(господарство) {
  const вибір = document.createElement('input');
  вибір.type = 'file';
  вибір.multiple = true;
  вибір.accept = '.kml,.kmz,.zip,.shp,.dbf,.shx,.prj,.cpg,.geojson,.json,.gpkg';
  вибір.addEventListener('change', async () => {
    if (!вибір.files.length) return;
    const форма = new FormData();
    форма.append('господарство', господарство);
    for (const ф of вибір.files) форма.append('файл', ф);
    try {
      const в = await fetch('/api/імпорт-полів', { method: 'POST', body: форма });
      const д = await в.json();
      if (!д['гаразд']) { поскаржитись(д['повідомлення'] || 'Не вдалося прочитати межі'); return; }
      await показати_передпоказ(господарство, д);
    } catch (е) { поскаржитись(е); }
  });
  вибір.click();
}

async function показати_передпоказ(господарство, д) {
  const ферм = (д['ферми'] || []).length;
  const рядки = д['ділянки'].map(о =>
    `${о['назва']}${о['ферма'] ? '  ·  ' + о['ферма'] : ''}  ·  ${о['площа_га']} га`
      + (о['шматків'] > 1 ? `  (${о['шматків']} шматки)` : ''));
  const попередження = (д['попередження'] || []).length
    ? '\n\nУвага:\n' + д['попередження'].join('\n') : '';
  const питання =
    `Знайдено ${д['ділянки'].length} полів на ${д['площа_га']} га`
    + (ферм ? `, ферм: ${ферм}` : ', без поділу на ферми')
    + `.\nНазва береться з колонки «${д['вгадано']['назва'] || '—'}»`
    + `, ферма — з «${д['вгадано']['ферма'] || '—'}».\n\n`
    + рядки.slice(0, 25).join('\n')
    + (рядки.length > 25 ? `\n… і ще ${рядки.length - 25}` : '')
    + попередження
    + '\n\nЗакласти в дерево?';
  if (!confirm(питання)) return;

  const наслідок = await послати('/api/імпорт-закласти', {
    господарство,
    колонка_назви: д['вгадано']['назва'] || '',
    колонка_ферми: д['вгадано']['ферма'] || '',
  });
  await оновити_дерево();
  const пропущено = (наслідок['пропущено'] || []).length;
  сказати_коротко(
    `Закладено ${наслідок['полів']} полів · ${наслідок['площа_га']} га`
    + (наслідок['ферм'] ? ` · ферм: ${наслідок['ферм']}` : '')
    + (пропущено ? ` · пропущено ${пропущено} (контур уже був)` : '')
    + ((наслідок['збої'] || []).length ? `\nЗбої:\n${наслідок['збої'].join('\n')}` : ''));
}

