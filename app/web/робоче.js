async function взяти(адреса) {
  const в = await fetch(адреса);
  const д = await в.json();
  if (д.помилка) throw new Error(д.помилка);
  return д;
}

async function послати(адреса, тіло) {
  const в = await fetch(адреса, { method: 'POST', headers: { 'Content-Type': 'application/json' },
                                  body: JSON.stringify(тіло || {}) });
  const д = await в.json();
  if (д.помилка) throw new Error(д.помилка);
  return д;
}

