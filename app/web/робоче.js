function підключити_прийом() {
  const блок = $('#прийом-монітор'), вхід = $('#файл-монітор'), перелік = $('#список-монітор');
  const відправити = async файли => {
    if (!файли || !файли.length) return;
    const форма = new FormData();
    форма.append('вид', 'монітор');
    for (const ф of файли) форма.append('файл', ф);
    перелік.innerHTML = '<li>Переношу файли…</li>';
    try {
      const в = await fetch('/api/файли', { method: 'POST', body: форма });
      const д = await в.json();
      if (д.помилка) throw new Error(д.помилка);
      перелік.dataset['є'] = '1';
      перелік.innerHTML = д.збережено.map(ф =>
        `<li><span>${екран(ф['імʼя'])}</span><span>${байти(ф.байтів)}</span></li>`).join('');
    } catch (п) { перелік.innerHTML = ''; поскаржитись(п); }
  };
  блок.addEventListener('click', () => вхід.click());
  блок.addEventListener('dragover', п => { п.preventDefault(); блок.classList.add('наведено'); });
  блок.addEventListener('dragleave', () => блок.classList.remove('наведено'));
  блок.addEventListener('drop', п => { п.preventDefault(); блок.classList.remove('наведено'); відправити(п.dataTransfer.files); });
  вхід.addEventListener('change', () => відправити(вхід.files));
}

