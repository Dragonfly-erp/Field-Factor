  $('#пуск-зон').addEventListener('click', async () => {
    const джерела = зібрати_джерела();
    if (!джерела.length) { поскаржитись('Оберіть хоча б одне джерело.'); return; }
    const межі = {
      мін: Number($('#зон-мін').value) || 3, ціль: Number($('#зон-ціль').value) || 4,
      макс: Number($('#зон-макс').value) || 6,
      мін_площа_га: Number($('#зон-площа').value) || null
    };
    if (межі.мін > межі.ціль || межі.ціль > межі.макс) {
      поскаржитись('Найменше ≤ бажано ≤ найбільше.'); return;
    }
    const назва = $('#назва-зонування').textContent;
    const рік = new Date().getFullYear();
    try {
      // шари, які в побудові НЕ брали участі, стають незалежною перевіркою
      const задіяні = new Set(джерела.filter(д => д.вид === 'шар').map(д => д.ключ));
      const перевірки = стан.шари
        .filter(ш => ш.тип === 'врожайність' && !задіяні.has(ш.ключ))
        .map(ш => ({ ключ: ш.ключ, атрибут: ш.атрибут, назва: ш.назва }));

      await послати('/api/задача', {
        режим: 'зони', господарство: стан.господарство, поле: стан.поле,
        джерела: джерела, зони: межі, перевірки: перевірки,
        груп_відбору: Number($('#груп-відбору').value) || 5,
        ключ: 'зони_' + (стан.пресет || 'своє') + '_' + рік,
        назва: назва
      });
      $('#накладка-зон').hidden = true;
      $('#накладка').hidden = false;
      $('#назва-операції').textContent = назва;
      $('#заголовок-роботи').textContent = 'Будую зони';
      на_крок(7);
      стежити(async п => {
        if (п['помилка']) { alert('Зони не побудувались:' + String.fromCharCode(10) + п['помилка']); return; }
        $('#накладка').hidden = true;
        await обрати_поле(стан.господарство, стан.поле);
      });
    } catch (е) { поскаржитись(е); }
  });
