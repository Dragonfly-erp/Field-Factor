// Тандем дає в одному файлі і висоту, і електропровідність. Колонки
// вгадуються за назвою, але останнє слово лишається за людиною.
function _вгадати_колонку(колонки, ознаки) {
  for (const ознака of ознаки) {
    const знайдене = колонки.find(к => к.toLowerCase().includes(ознака));
    if (знайдене) return знайдене;
  }
  return '';
}

function _вибір(підпис, клас, колонки, обране) {
  const опції = ['<option value="">— немає —</option>'].concat(
    колонки.map(к => '<option value="' + екран(к) + '"'
      + (к === обране ? ' selected' : '') + '>' + екран(к) + '</option>')).join('');
  return '<label class="дрібна-мітка">' + підпис + '</label>'
    + '<select class="' + клас + '">' + опції + '</select>';
}

function _картка_сканування(д) {
  const к = д.колонки || [];
  return _вибір('Висота RTK', 'кол-висота', к,
                _вгадати_колонку(к, ['elev', 'rtk', 'height', 'висот', 'alt']))
    + _вибір('EC мала глибина', 'кол-ec-мала', к,
             _вгадати_колонку(к, ['sh', 'мала', '_h', 'ec1', 'shallow']))
    + _вибір('EC велика глибина', 'кол-ec-велика', к,
             _вгадати_колонку(к, ['dp', 'deep', 'велик', 'ec2', '_v']));
}

