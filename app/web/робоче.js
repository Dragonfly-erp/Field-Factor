function зібрати_джерела() {
  const перелік = доступні_джерела();
  const джерела = [];
  $$('#джерела-зонування .джерело').forEach(е => {
    if (!е.querySelector('.джерело-шапка input').checked) return;
    const ключ = е.dataset['ключ'];
    const опис = перелік.find(д => д.ключ === ключ);
    const вага = Number(е.querySelector('.вага').value) || 1;
    if (ключ.startsWith('шар:')) {
      джерела.push({ вид: 'шар', ключ: опис.шар, атрибут: опис.атрибут,
                     назва: опис.назва, вага });
      return;
    }
    if (ключ.startsWith('сканування:')) {
      const бери = с => { const е2 = е.querySelector(с); return е2 ? е2.value : ''; };
      const висота = бери('.кол-висота');
      const мала = бери('.кол-ec-мала'), велика = бери('.кол-ec-велика');
      if (висота) {
        джерела.push({ вид: 'рельєф', вага,
          джерело_висоти: { ключ: опис.шар, атрибут: висота },
          показники: ['кривина', 'індекс_зволоження', 'схил'] });
      }
      if (мала) джерела.push({ вид: 'шар', ключ: опис.шар, атрибут: мала,
        як_називати: 'EC_мала', назва: 'EC мала глибина', вага });
      if (велика) джерела.push({ вид: 'шар', ключ: опис.шар, атрибут: велика,
        як_називати: 'EC_велика', назва: 'EC велика глибина', вага });
      return;
    }
    const джерело = { вид: ключ, вага };
    const від = е.querySelector('.рік-від'), до = е.querySelector('.рік-до');
    if (від && до) {
      const а = Number(від.value), б = Number(до.value);
      джерело.роки = [];
      for (let р = Math.min(а, б); р <= Math.max(а, б); р++) джерело.роки.push(р);
    }
    const показники = [...е.querySelectorAll('.показник:checked')].map(п => п.value);
    if (показники.length) джерело.показники = показники;
    джерела.push(джерело);
  });
  return джерела;
}

