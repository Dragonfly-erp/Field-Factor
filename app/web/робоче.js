// ---------------------------------------------------------------- поле

async function обрати_поле(господарство, поле) {
  стан.господарство = господарство;
  стан.поле = поле;
  стан.активний = null;
  карта.шари = [];
  карта.підкладка = null;
  // Підпис іде разом із тлом: тло змінилось — старий підпис бреше.
  $('#підпис-джерела').hidden = true;

  await послати('/api/обрати', { господарство, поле });
  const д = await взяти(`/api/поле?господарство=${encodeURIComponent(господарство)}&поле=${encodeURIComponent(поле)}`);
  стан.шари = д['шари'];
  стан.поле_дані = д;
  const п = д['паспорт'];
  // Паспорт ПОЛЯ лежить окремо від паспорта ПРОГОНУ: перший належить полю
  // назавжди, другий — одному запуску нормалізації. Змішати їх означало б,
  // що культура з майстра запису затирає культуру поля.
  стан.паспорт_поля = п;
  // Історія прочитана для ІНШОГО поля — тримати її означало б показати чужі
  // сезони під новою назвою. Скидаємо разом із полем.
  стан.історія = null;
  стан.історія_рік = null;
  $('#де-я').textContent = `${екран(п['назва'])}${п['площа_га'] ? ' · ' + п['площа_га'] + ' га' : ''}`;
  намалювати_дерево();
  намалювати_операції();
  намалювати_контекст();
  if (стан.контекст === 'історія') підтягнути_історію();

  $('#порожня-карта').hidden = стан.шари.length > 0;
  намалювати_список_шарів();

  if (стан.вигляд === 'картка') намалювати_картку();

  // контур і найсвіжіший змістовний шар показуємо одразу
  const контур = стан.шари.find(ш => ш.ключ === 'контур');
  if (контур) {
    await показати_шар(контур.ключ, true);
    // Тло під контуром вантажиться саме: многокутник у порожнечі не
    // відповідає на питання «чи це те поле». Плитки кешуються, тож удруге
    // це нічого не коштує; не вийшло — поле просто лишається без тла.
    підкласти_тло_світу();
  }
  const головний = стан.шари.find(ш => ш.тип === 'зони') || стан.шари.find(ш => ш.тип === 'врожайність');
  if (головний) {
    await показати_шар(головний.ключ, true);
    // активним робимо змістовний шар, а не контур: саме його легенду хочуть бачити
    стан.активний = головний.ключ;
    намалювати_список_шарів();
    намалювати_показ();
  }
  карта.вписати(карта.спільні_межі());
}

// ---------------------------------------------------------------- шари

function намалювати_список_шарів() {
  if (!стан.шари.length) {
    $('#список-шарів').innerHTML = '<p class="дрібно">Шарів ще немає.</p>';
    return;
  }
  $('#список-шарів').innerHTML = стан.шари.map(ш => {
    const на_карті = карта.знайти(ш.ключ);
    const видимий = на_карті && на_карті.видимий;
    return `<label class="рядок-шару${стан.активний === ш.ключ ? ' активний' : ''}" data-шар="${екран(ш.ключ)}">
      <input type="checkbox" ${видимий ? 'checked' : ''}>
      <span class="шар-назва">${екран(ш.назва)}</span>
      <span class="шар-тип">${екран(ш.тип)}</span>
    </label>`;
  }).join('');

  $$('#список-шарів .рядок-шару').forEach(е => {
    const ключ = е.dataset['шар'];
    е.querySelector('input').addEventListener('change', п => показати_шар(ключ, п.target.checked));
    е.querySelector('.шар-назва').addEventListener('click', п => {
      п.preventDefault();
      стан.активний = ключ;
      намалювати_список_шарів();
      намалювати_показ();
    });
  });
}

async function показати_шар(ключ, увімкнути, налаштування) {
  if (!увімкнути) { карта.прибрати(ключ); намалювати_список_шарів(); return; }
  const опис = стан.шари.find(ш => ш.ключ === ключ);
  const н = налаштування || {};
  const адреса = `/api/шар?господарство=${encodeURIComponent(стан.господарство)}`
    + `&поле=${encodeURIComponent(стан.поле)}&ключ=${encodeURIComponent(ключ)}`
    + (н.атрибут ? `&атрибут=${encodeURIComponent(н.атрибут)}` : '')
    + `&класів=${н.класів || 6}&метод=${encodeURIComponent(н.метод || 'квантилі')}`;
  try {
    const дані = await взяти(адреса);
    карта.покласти({
      ключ, назва: опис ? опис.назва : ключ, видимий: true, дані,
      заливка: ключ !== 'контур',
      товщина: ключ === 'контур' ? 2.5 : 1,
      // Обвід контуру береться з теми, а не вписаний числом: на графіті
      // темно-зелений рядок 'rgba(30,77,43,.95)' зливався з тлом карти й
      // межа поля просто зникала.
      обвід: ключ === 'контур' ? колір_теми('--акцент') : колір_теми('--тихий'),
      прозорість: опис && опис.тип === 'зони' ? 0.8 : 1
    });
    if (!стан.активний || стан.активний === ключ) { стан.активний = ключ; намалювати_показ(); }
    намалювати_список_шарів();
    $('#порожня-карта').hidden = true;
  } catch (п) { поскаржитись(п); }
}

// Колір із теми. Потрібен там, де малює полотно: CSS туди не дістає, а
// вписані числом кольори переживають зміну вигляду й ламаються на ній.
function колір_теми(токен, запасний) {
  const в = getComputedStyle(document.documentElement).getPropertyValue(токен).trim();
  return в || запасний || '#8b97a3';
}

