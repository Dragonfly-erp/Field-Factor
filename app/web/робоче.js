function бюджет_картки(б) {
  if (!б['є']) {
    return '<p class="порожньо-блок">Бюджету ще немає. Він складається з плану поля '
      + 'і довідників цін на екрані «Гроші».'
      + (б['збій'] ? ` <span class="тиха">(${екран(б['збій'])})</span>` : '') + '</p>';
  }
  const рядки = пари([
    ['Рік', б['рік']],
    ['Дохід', ч_або_прочерк(Math.round(б['дохід'])) + ' грн/га'],
    ['Змінні витрати', ч_або_прочерк(Math.round(б['змінні'])) + ' грн/га'],
    ['Маржинальний дохід', ч_або_прочерк(Math.round(б['маржинальний'])) + ' грн/га'],
    ['Чистий результат', ч_або_прочерк(Math.round(б['чистий'])) + ' грн/га']
  ]);
  // Неповний бюджет мусить сказати про себе сам. Мовчазний нуль у грошах
  // виглядає як «безкоштовно» — це найдорожча брехня в цьому екрані.
  const бракує = (б['бракує'] || []).length
    ? `<p class="бракує-рядок">Неповний: ${б['бракує'].map(екран).join(' · ')}</p>` : '';
  return рядки + бракує;
}

/* Історія на екрані. Ліворуч усі роки рядками, праворуч обраний рік
   блоками. Прочерк означає «не вносили» і виглядає прочерком: нуль у
   колонці живлення читається як «внесли нічого», і це найдорожча брехня
   в усій картці. */

const ПРОЧЕРК = '<span class="нема">—</span>';

function ч_або_прочерк(значення, знаків) {
  if (значення === null || значення === undefined || значення === '') return ПРОЧЕРК;
  if (typeof значення === 'number') {
    // Роздільник — кома, як в усій програмі. Крапка тут виглядає як чужий
    // формат і збиває читання колонки, де решта чисел із комою.
    const текст = знаків === undefined ? String(значення) : значення.toFixed(знаків);
    return текст.replace('.', ',');
  }
  return екран(значення);
}

function вміст_історії() {
  const і = стан.історія;
  if (!і) return '<p class="порожньо">Читаю історію…</p>';
  if (і.помилка) return `<p class="порожньо">Не вийшло прочитати історію: ${екран(і.помилка)}</p>`;
  if (!(і.зведення || []).length) {
    return '<p class="порожньо">Історії по цьому полю ще немає. '
      + 'Вона накопичується блоками: загальне, живлення, меліорація, захист, '
      + 'загрози, обробіток, економіка — кожен блок окремо й зі своїм джерелом.</p>';
  }

  const колонки = і.колонки || [];
  const шапка = '<tr><th>Рік</th>' + колонки.map(к => `<th>${екран(к.підпис)}</th>`).join('') + '</tr>';
  const рядки = і.зведення.map(р => {
    const свій = String(р.рік) === String(стан.історія_рік);
    return `<tr class="рік-рядок${свій ? ' обраний' : ''}" data-рік="${екран(р.рік)}">`
      + `<td class="ч рік-клітинка">${екран(р.рік)}</td>`
      + колонки.map(к => {
        const в = р[к.ключ];
        const число = typeof в === 'number';
        return `<td class="${число ? 'ч' : ''}">${ч_або_прочерк(в, к.ключ === 'урожай_т_га' ? 2 : undefined)}</td>`;
      }).join('') + '</tr>';
  }).join('');

  const п = і.підсумок || {};
  const шапка_підсумку = `<div class="історія-підсумок">`
    + `<span>${екран(п.років || 0)} сезонів</span>`
    + (п.від ? `<span class="ч">${екран(п.від)} — ${екран(п.до)}</span>` : '')
    + (п.середній_урожай !== null && п.середній_урожай !== undefined
        ? `<span>середній урожай <b class="ч">${ч_або_прочерк(п.середній_урожай, 2)}</b> т/га</span>` : '')
    + (п.культур ? `<span>культур: <b class="ч">${екран(п.культур)}</b></span>` : '')
    + `</div>`;

  return '<div class="історія">'
    + `<div class="історія-роки">${шапка_підсумку}`
    + `<table class="контекст-таблиця"><thead>${шапка}</thead><tbody>${рядки}</tbody></table></div>`
    + `<div class="історія-рік">${блоки_року(і)}</div>`
    + '</div>';
}

function блоки_року(і) {
  const рік = і.рік || {};
  if (!Object.keys(рік).length) {
    return '<p class="порожньо">Оберіть рік у таблиці зліва.</p>';
  }
  const назви = {};
  (і.блоки || []).forEach(б => { назви[б.ключ] = б.підпис; });
  const частини = [`<div class="рік-шапка">${екран(стан.історія_рік)} · `
    + `${екран((рік['загальне'] || {}).культура || 'культура не названа')}</div>`];

  (і.блоки || []).forEach(б => {
    const дані = рік[б.ключ];
    if (!дані) return;
    частини.push(`<div class="блок-історії"><h4>${екран(б.підпис)}`
      + (дані.джерело ? `<small title="${екран(дані.джерело)}">${екран(дані.статус || '')}</small>` : '')
      + '</h4>' + тіло_блоку(б.ключ, дані) + '</div>');
  });
  return частини.join('');
}

function тіло_блоку(ключ, дані) {
  if (ключ === 'захист') {
    const групи = [['гербіциди', 'Гербіциди'], ['фунгіциди', 'Фунгіциди'], ['інсектициди', 'Інсектициди']];
    const частини = [];
    групи.forEach(([к, підпис]) => {
      const перелік = дані[к] || [];
      if (!перелік.length) return;
      частини.push(`<div class="підблок">${екран(підпис)}</div>`);
      перелік.forEach(з => частини.push(
        `<div class="препарат"><b>${екран(з.назва)}</b>`
        + `<span>${екран((з.діючі || []).join(' + '))}</span>`
        + `<i>${екран(з.механізм || '')}</i></div>`));
    });
    return частини.join('') || '<div class="підблок">не застосовували</div>';
  }
  if (ключ === 'загрози') {
    const перелік = дані.перелік || [];
    if (!перелік.length) return '<div class="підблок">не відмічено</div>';
    return перелік.map(з => {
      const о = Number(з.оцінка);
      const кульки = isFinite(о) ? '●'.repeat(о) + '○'.repeat(Math.max(0, 5 - о)) : '—';
      return `<div class="загроза"><span class="вид">${екран(з.вид)}</span>`
        + `<span class="назва">${екран(з.назва)}</span>`
        + `<span class="оцінка о${isFinite(о) ? о : 0}">${кульки}</span></div>`;
    }).join('');
  }
  const службові = new Set(['джерело', 'статус', 'записано', 'одиниця', 'валюта']);
  const рядки = Object.keys(дані).filter(к => !службові.has(к))
    .map(к => `<dt>${екран(підпис_поля_історії(к))}</dt>`
      + `<dd>${ч_або_прочерк(дані[к], к === 'урожай_т_га' ? 2 : undefined)}</dd>`);
  return `<dl class="влас-блоку">${рядки.join('')}</dl>`;
}

