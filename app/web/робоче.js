async function оновити_дерево() {
  const д = await взяти('/api/картотека');
  стан.господарства = д['господарства'];
  намалювати_дерево();
}

function намалювати_дерево() {
  const частини = [];
  if (!стан.господарства.length) {
    частини.push('<p class="дрібно порожньо">Ще жодного господарства.<br>Натисніть «+» угорі.</p>');
  }
  for (const г of стан.господарства) {
    частини.push(`<div class="гілка">
      <div class="гілка-шапка">
        <span class="гілка-назва">${екран(г['назва'])}</span>
        <button class="дрібна" data-нове-поле="${екран(г['ключ'])}" title="Додати поле">+</button>
      </div>`);
    if (!г['поля'].length) частини.push('<p class="дрібно відступ">полів немає</p>');
    for (const п of г['поля']) {
      const обране = стан.господарство === г['ключ'] && стан.поле === п['ключ'];
      частини.push(`<div class="лист${обране ? ' обраний' : ''}"
           data-господарство="${екран(г['ключ'])}" data-поле="${екран(п['ключ'])}">
        <span class="лист-назва">${екран(п['назва'])}</span>
        <span class="лист-дрібно">${п['площа_га'] ? п['площа_га'] + ' га' : 'без контуру'}${
          п['роки'] && п['роки'].length ? ' · ' + п['роки'].join(', ') : ''}</span>
      </div>`);
    }
    частини.push('</div>');
  }
  $('#дерево').innerHTML = частини.join('');

  $$('#дерево .лист').forEach(е => е.addEventListener('click',
    () => обрати_поле(е.dataset['господарство'], е.dataset['поле'])));
  $$('#дерево [data-нове-поле]').forEach(е => е.addEventListener('click', п => {
    п.stopPropagation();
    завести_поле(е.dataset['новеПоле']);
  }));
}

async function завести_господарство() {
  const назва = prompt('Назва господарства');
  if (!назва) return;
  await послати('/api/господарство', { назва });
  await оновити_дерево();
}

async function завести_поле(господарство) {
  const назва = prompt('Назва поля');
  if (!назва) return;
  const в = await послати('/api/нове-поле', { господарство, назва });
  await оновити_дерево();
  await обрати_поле(господарство, в['ключ']);
  завантажити_контур();
}

function завантажити_контур() {
  const вхід = document.createElement('input');
  вхід.type = 'file';
  вхід.multiple = true;
  вхід.addEventListener('change', async () => {
    if (!вхід.files.length) return;
    const форма = new FormData();
    форма.append('господарство', стан.господарство);
    форма.append('поле', стан.поле);
    for (const ф of вхід.files) форма.append('файл', ф);
    try {
      const в = await fetch('/api/контур', { method: 'POST', body: форма });
      const д = await в.json();
      if (д.помилка) throw new Error(д.помилка);
      await оновити_дерево();
      await обрати_поле(стан.господарство, стан.поле);
    } catch (п) { поскаржитись(п); }
  });
  вхід.click();
}


function додати_шар_файлом() {
  if (!стан.поле) { поскаржитись('Спершу оберіть поле.'); return; }
  const назва = prompt('Як назвати шар?\nНаприклад: Сканування 2026 · RTK + EC');
  if (!назва) return;
  const вхід = document.createElement('input');
  вхід.type = 'file';
  вхід.multiple = true;
  вхід.addEventListener('change', async () => {
    if (!вхід.files.length) return;
    const форма = new FormData();
    форма.append('господарство', стан.господарство);
    форма.append('поле', стан.поле);
    форма.append('тип', 'сканування');
    форма.append('назва', назва);
    форма.append('ключ', 'скан_' + Date.now());
    for (const ф of вхід.files) форма.append('файл', ф);
    try {
      const в = await fetch('/api/шар-файл', { method: 'POST', body: форма });
      const д = await в.json();
      if (д.помилка) throw new Error(д.помилка);
      alert('Прочитано ' + д['точок'] + ' точок.\nЧислові колонки: '
            + (д['колонки'] || []).join(', '));
      await обрати_поле(стан.господарство, стан.поле);
    } catch (п) { поскаржитись(п); }
  });
  вхід.click();
}

// ---------------------------------------------------------------- поле

async function обрати_поле(господарство, поле) {
  стан.господарство = господарство;
  стан.поле = поле;
  стан.активний = null;
  карта.шари = [];
  карта.підкладка = null;

  await послати('/api/обрати', { господарство, поле });
  const д = await взяти(`/api/поле?господарство=${encodeURIComponent(господарство)}&поле=${encodeURIComponent(поле)}`);
  стан.шари = д['шари'];
  const п = д['паспорт'];
  $('#де-я').textContent = `${екран(п['назва'])}${п['площа_га'] ? ' · ' + п['площа_га'] + ' га' : ''}`;
  намалювати_дерево();
  намалювати_операції();

  $('#порожня-карта').hidden = стан.шари.length > 0;
  намалювати_список_шарів();

  // контур і найсвіжіший змістовний шар показуємо одразу
  const контур = стан.шари.find(ш => ш.ключ === 'контур');
  if (контур) await показати_шар(контур.ключ, true);
  const головний = стан.шари.find(ш => ш.тип === 'зони') || стан.шари.find(ш => ш.тип === 'врожайність');
  if (головний) {
    await показати_шар(головний.ключ, true);
    // активним робимо змістовний шар, а не контур: саме його легенду хочуть бачити
    стан.активний = головний.ключ;
    намалювати_список_шарів();
    намалювати_показ();
  }
  карта.вписати(карта.спільні_межі());
}

// ---------------------------------------------------------------- шари

function намалювати_список_шарів() {
  if (!стан.шари.length) {
    $('#список-шарів').innerHTML = '<p class="дрібно">Шарів ще немає.</p>';
    return;
  }
  $('#список-шарів').innerHTML = стан.шари.map(ш => {
    const на_карті = карта.знайти(ш.ключ);
    const видимий = на_карті && на_карті.видимий;
    return `<label class="рядок-шару${стан.активний === ш.ключ ? ' активний' : ''}" data-шар="${екран(ш.ключ)}">
      <input type="checkbox" ${видимий ? 'checked' : ''}>
      <span class="шар-назва">${екран(ш.назва)}</span>
      <span class="шар-тип">${екран(ш.тип)}</span>
    </label>`;
  }).join('');

  $$('#список-шарів .рядок-шару').forEach(е => {
    const ключ = е.dataset['шар'];
    е.querySelector('input').addEventListener('change', п => показати_шар(ключ, п.target.checked));
    е.querySelector('.шар-назва').addEventListener('click', п => {
      п.preventDefault();
      стан.активний = ключ;
      намалювати_список_шарів();
      намалювати_показ();
    });
  });
}

async function показати_шар(ключ, увімкнути, налаштування) {
  if (!увімкнути) { карта.прибрати(ключ); намалювати_список_шарів(); return; }
  const опис = стан.шари.find(ш => ш.ключ === ключ);
  const н = налаштування || {};
  const адреса = `/api/шар?господарство=${encodeURIComponent(стан.господарство)}`
    + `&поле=${encodeURIComponent(стан.поле)}&ключ=${encodeURIComponent(ключ)}`
    + (н.атрибут ? `&атрибут=${encodeURIComponent(н.атрибут)}` : '')
    + `&класів=${н.класів || 6}&метод=${encodeURIComponent(н.метод || 'квантилі')}`;
  try {
    const дані = await взяти(адреса);
    карта.покласти({
      ключ, назва: опис ? опис.назва : ключ, видимий: true, дані,
      заливка: ключ !== 'контур',
      товщина: ключ === 'контур' ? 2.5 : 1,
      обвід: ключ === 'контур' ? 'rgba(30,77,43,.95)' : 'rgba(255,255,255,.55)',
      прозорість: опис && опис.тип === 'зони' ? 0.8 : 1
    });
    if (!стан.активний || стан.активний === ключ) { стан.активний = ключ; намалювати_показ(); }
    намалювати_список_шарів();
    $('#порожня-карта').hidden = true;
  } catch (п) { поскаржитись(п); }
}

// ---------------------------------------------------------------- показ

function намалювати_показ() {
  const шар = карта.знайти(стан.активний);
  if (!шар) { $('#панель-показу').innerHTML = '<p class="дрібно">Оберіть шар.</p>'; return; }
  const д = шар.дані;
  const частини = [`<div class="показ-назва">${екран(шар.назва)}</div>`];

  частини.push(`<p class="дрібно">${д['вид'] === 'точки'
    ? `${д['усього'].toLocaleString('uk')} точок${д['проріджено'] ? `, показано ${д['показано'].toLocaleString('uk')}` : ''}`
    : `${д['усього']} полігонів`}</p>`);

  if (д['числові'] && д['числові'].length) {
    частини.push('<label class="дрібна-мітка">Показувати за</label><select id="вибір-атрибута">'
      + д['числові'].map(а => `<option${а === д['атрибут'] ? ' selected' : ''}>${екран(а)}</option>`).join('')
      + '</select>');
    частини.push('<div class="пара">'
      + '<div><label class="дрібна-мітка">Класів</label><input id="кількість-класів" type="number" min="2" max="12" value="'
      + ((д['межі_класів'] || []).length - 1 || 6) + '"></div>'
      + '<div><label class="дрібна-мітка">Розбиття</label><select id="метод-класів">'
      + ['квантилі', 'рівні', 'розриви'].map(м => `<option value="${м}"${
          м === стан.показ.метод ? ' selected' : ''}>${
          м === 'квантилі' ? 'по квантилях' : м === 'рівні' ? 'рівні інтервали' : 'природні розриви'
        }</option>`).join('') + '</select></div></div>');
  }

  if (д['межі_класів'] && д['кольори']) {
    частини.push('<div class="шкала">');
    for (let і = 0; і < д['кольори'].length; і++) {
      частини.push(`<div class="щабель">
        <span class="зразок" style="background:${д['кольори'][і]}"></span>
        <span>${число(д['межі_класів'][і])} — ${число(д['межі_класів'][і + 1])}</span>
      </div>`);
    }
    частини.push('</div>');
  }

  частини.push('<label class="дрібна-мітка">Прозорість</label>'
    + `<input id="прозорість" type="range" min="20" max="100" value="${Math.round((шар.прозорість == null ? 1 : шар.прозорість) * 100)}">`);

  $('#панель-показу').innerHTML = частини.join('');

  const перемалювати = () => {
    стан.показ = {
      атрибут: $('#вибір-атрибута') ? $('#вибір-атрибута').value : null,
      класів: $('#кількість-класів') ? Number($('#кількість-класів').value) : 6,
      метод: $('#метод-класів') ? $('#метод-класів').value : 'квантилі'
    };
    показати_шар(стан.активний, true, стан.показ);
  };
  ['#вибір-атрибута', '#кількість-класів', '#метод-класів'].forEach(с => {
    const е = $(с); if (е) е.addEventListener('change', перемалювати);
  });
  const п = $('#прозорість');
  if (п) п.addEventListener('input', () => { шар.прозорість = Number(п.value) / 100; карта.малювати(); });
}

// ---------------------------------------------------------------- інспектор

function показати_точку(знахідка) {
  if (!знахідка) { $('#панель-точки').innerHTML = '<p class="дрібно">Клацніть по точці або зоні.</p>'; return; }
  const рядки = Object.entries(знахідка.підпис)
    .filter(([, з]) => з !== null && з !== undefined && з !== '')
    .map(([к, з]) => `<dt>${екран(к)}</dt><dd>${екран(typeof з === 'number' ? число(з) : з)}</dd>`);
  $('#панель-точки').innerHTML = `<div class="показ-назва">${екран(знахідка.шар.назва)}</div>`
    + (рядки.length ? `<dl class="властивості">${рядки.join('')}</dl>`
                    : '<p class="дрібно">Без атрибутів.</p>');
}

